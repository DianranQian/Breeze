//! BSN 适配层的错误类型。
//!
//! # 为什么错误要分成这些变体
//!
//! 适配层的每一种失败都对应一个**用户或开发者必须做出不同反应**的场景：
//!
//! * 世界缺少 BSN 依赖的资源 → 调用方用错了 API，属于编程错误；
//! * 官方实例化 API 返回错误 → 通常是资源依赖未加载，可以重试或排队；
//! * 组件未在注册表中登记 → 编辑器缺少该组件的编辑能力，需要补注册；
//! * 存在无法转换的组件 → **拒绝转换**，而不是丢掉它在文档里装作成功。
//!
//! 最后一条是本层最重要的语义约束：任何"转换成功"的返回都意味着
//! 世界里的数据已经完整落入文档；只要有一个组件说不清楚，就返回错误。

use scene_doc::document::实体标识;

/// BSN 适配层错误。
#[derive(Debug, thiserror::Error)]
pub enum BSN错误 {
    /// 传入的 `World` 缺少 BSN 官方实例化所需的资源。
    ///
    /// 官方 `World::spawn_scene` 直接 `world.resource::<AssetServer>()`，
    /// 缺少资源时会 panic。适配层先检查再调用，把 panic 变成可处理的错误。
    #[error("世界缺少 BSN 所需资源 `{缺少}`；请用 `BSN宿主` 构造世界")]
    世界缺少资源 {
        /// 缺失的资源类型名。
        缺少: &'static str,
    },

    /// 官方实例化 API 返回错误（例如资源依赖尚未加载完成）。
    #[error("BSN 场景实例化失败：{来源}")]
    实例化失败 {
        /// 官方错误的文本形式。官方类型只保证 `Debug`/`Display`，
        /// 这里保存文本以免把 `bevy_scene` 的类型泄漏到上层。
        来源: String,
    },

    /// 官方 API 成功返回了根实体，但随后在世界里查不到它。
    ///
    /// 这属于"官方 API 与适配层假设不一致"，必须显式报错而不是静默返回空文档。
    #[error("BSN 场景根实体 {根:?} 在世界中不存在")]
    根实体缺失 {
        /// 官方 API 返回的实体调试表示。
        根: String,
    },

    /// 某个组件在当前组件注册表里没有条目，因此无法导出为文档字段。
    #[error("实体 {实体}（{名称}）的组件 `{组件}` 未在组件注册表中登记，无法导出")]
    组件未注册 {
        /// 文档实体标识。
        实体: 实体标识,
        /// 实体名称，方便定位。
        名称: String,
        /// 组件类型名。
        组件: String,
    },

    /// 组件在注册表里，但它的属性导出失败（类型擦除后无法还原）。
    #[error("实体 {实体}（{名称}）的组件 `{组件}` 导出属性失败")]
    组件导出失败 {
        /// 文档实体标识。
        实体: 实体标识,
        /// 实体名称，方便定位。
        名称: String,
        /// 组件类型名。
        组件: String,
    },

    /// 场景中存在适配层无法表达的组件。
    ///
    /// **这是刻意的拒绝**：丢掉这些组件后仍然返回"成功"，
    /// 会让用户以为场景已完整转换，而实际上数据已经丢失。
    #[error(
        "场景中有 {数量} 个组件无法转换为 scene_doc 数据（{示例}），已拒绝转换以避免静默丢数据"
    )]
    存在未转换组件 {
        /// 未转换组件的个数。
        数量: usize,
        /// 一段人类可读的示例描述。
        示例: String,
    },
}
