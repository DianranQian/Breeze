//! 转换边界测试：`BSN 实例化后的 ECS` → `scene_doc 文档` 到底能转换到什么程度。
//!
//! 本文件按"损失程度"分层组织，这是任务要求的核心区分：
//!
//! | 层级 | 含义 | 对应测试 |
//! | --- | --- | --- |
//! | 完全无损 | 数值与结构逐一对应，落盘再读回不变 | `完整转换_`、`写入磁盘读回后` |
//! | 允许的规范化 | 表示方式变了但信息没丢 | `规范化项被如实记录` |
//! | 不支持的组件 | 适配层无法表达，必须报告 | `未登记组件导致严格转换失败` |
//! | 转换失败 | 注册表缺条目等硬错误 | `注册表缺组件时报错而不是跳过` |
//!
//! 关键约束：**只比较实体数量不算完整往返测试**。
//! 下面每个用例都核对名称、变换的每个分量、层级、次序与组件字段值。

