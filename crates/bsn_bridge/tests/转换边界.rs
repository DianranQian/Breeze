#[test]
fn 完整转换_名称变换层级与次序逐项核对() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 三层嵌套模板.实例化(宿主.世界可变()).expect("实例化");
    let 产物 = 严格提取(&宿主, 根, "三层嵌套");
    let 文档 = &产物.文档;

    // ---- 实体数量（不是唯一断言，但先确认规模）----
    assert_eq!(文档.实体数量(), 5, "世界根 + 2 区域 + 灯 + 箱子");

    // ---- 顶层只有一个根，且次序为 0 ----
    assert_eq!(文档.顶层顺序.len(), 1, "应当只有一个顶层实体");
    let 世界根 = 文档.顶层顺序[0];
    let 根实体 = 文档.取(世界根).unwrap();
    assert_eq!(根实体.名称, "世界根");
    assert_eq!(根实体.父实体, None);
    assert_eq!(根实体.次序, 0);

    // ---- 第一层：顺序与 BSN 写法一致 ----
    let 区域列表 = 文档.子实体列表(Some(世界根));
    let 区域名称: Vec<&str> = 区域列表
        .iter()
        .map(|标识| 文档.取(*标识).unwrap().名称.as_str())
        .collect();
    assert_eq!(区域名称, vec!["区域甲", "区域乙"], "子级次序必须保留");
    assert_eq!(文档.取(区域列表[0]).unwrap().次序, 0);
    assert_eq!(文档.取(区域列表[1]).unwrap().次序, 1);

    // ---- 第二层：区域甲下是 灯、箱子 ----
    let 甲 = 区域列表[0];
    let 甲的子级 = 文档.子实体列表(Some(甲));
    let 甲子名: Vec<&str> = 甲的子级
        .iter()
        .map(|标识| 文档.取(*标识).unwrap().名称.as_str())
        .collect();
    assert_eq!(甲子名, vec!["灯", "箱子"]);
    assert_eq!(文档.取(甲的子级[0]).unwrap().父实体, Some(甲));

    // ---- 变换：每个分量逐一核对 ----
    let 区域甲变换 = 文档.取(甲).unwrap().变换.expect("区域甲应有变换");
    assert_eq!(区域甲变换.平移, (100.0, 0.0, 0.0));
    assert_eq!(区域甲变换.缩放, (1.0, 1.0, 1.0), "未写 scale 时取默认 1");
    assert_eq!(
        区域甲变换.旋转,
        (0.0, 0.0, 0.0, 1.0),
        "未写 rotation 时取单位四元数"
    );

    let 灯变换 = 文档.取(甲的子级[0]).unwrap().变换.expect("灯应有变换");
    assert_eq!(灯变换.平移, (0.0, 40.0, 0.0));

    let 箱子变换 = 文档.取(甲的子级[1]).unwrap().变换.expect("箱子应有变换");
    assert_eq!(箱子变换.平移, (20.0, 0.0, 0.0));

    // ---- 世界根没有 Transform，文档里也应当没有变换 ----
    assert!(
        文档.取(世界根).unwrap().变换.is_none(),
        "BSN 里没写 Transform 的实体，文档里不应凭空有变换"
    );

    // ---- 报告与文档互相印证 ----
    assert_eq!(产物.报告.实体数, 5);
    assert_eq!(产物.报告.最大深度, 2);
    assert!(!产物.报告.有数据损失());
    assert!(产物.报告.文档校验.无问题(), "{}", 产物.报告.文档校验.摘要());
}

#[test]
fn 组件字段值逐项核对() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 宿主
        .实例化(bsn! {
            #据点
            HealthBar { 当前: 30, 最大: 120 }
            Armor { 值: 99 }
        })
        .expect("实例化");
    let 产物 = 严格提取(&宿主, 根, "据点");
    let 文档 = &产物.文档;

    let 标识 = 按名称取(文档, "据点");
    let 实体 = 文档.取(标识).unwrap();

    let 血条 = 实体.取组件("HealthBar").expect("应有 HealthBar 组件");
    assert_eq!(血条.属性.get("当前"), Some(&属性值::整数(30)));
    assert_eq!(血条.属性.get("最大"), Some(&属性值::整数(120)));

    let 护甲 = 实体.取组件("Armor").expect("应有 Armor 组件");
    assert_eq!(护甲.属性.get("值"), Some(&属性值::整数(99)));
    assert_eq!(
        护甲.属性.get("等级"),
        Some(&属性值::整数(3)),
        "未提到的字段必须取组件默认值"
    );

    // 报告里两个组件的计数必须各为 1。
    assert_eq!(产物.报告.已转换组件.get("HealthBar"), Some(&1));
    assert_eq!(产物.报告.已转换组件.get("Armor"), Some(&1));
}

#[test]
fn 写入磁盘读回后文档完全一致() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 宿主
        .实例化(bsn! {
            #存档根
            Transform { translation: { Vec3::new(3.5, -1.25, 0.0) } }
            Children [
                #存档子 HealthBar { 当前: 5 }
            ]
        })
        .expect("实例化");
    let 产物 = 严格提取(&宿主, 根, "存档测试");

    let 目录 = tempfile::tempdir().expect("创建临时目录");
    let 路径 = 目录.path().join("存档测试.scene.ron");
    let 存储 = 文件系统场景存储::新建();

    let 写入结果 = 存储.写入(&路径, &产物.文档).expect("写入应成功");
    assert_eq!(写入结果, scene_doc::storage::保存结果::新建);

    let 读取 = 存储.读取(&路径).expect("读取应成功");
    assert!(!读取.从备份恢复, "正常写入后读取不应走备份路径");
    assert_eq!(
        读取.文档, 产物.文档,
        "经过磁盘往返后，文档必须与提取结果逐字段相等"
    );

    // 文件确实是 RON 文本，带格式版本，扩展名为 .scene.ron。
    let 文本 = std::fs::read_to_string(&路径).expect("读回文本");
    assert!(文本.contains("格式版本"), "场景文件应含格式版本字段");
    assert!(路径.to_string_lossy().ends_with(".scene.ron"));
}

#[test]
fn 实体身份是新的唯一标识且不复用运行时实体() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 三层嵌套模板.实例化(宿主.世界可变()).expect("实例化");
    let 产物 = 严格提取(&宿主, 根, "身份测试");

    let 标识集合: std::collections::BTreeSet<实体标识> = 产物.文档.实体表.keys().copied().collect();
    assert_eq!(标识集合.len(), 产物.文档.实体数量(), "文档实体标识必须唯一");
    assert_eq!(
        产物.实体映射.len(),
        产物.文档.实体数量(),
        "映射必须覆盖每个实体"
    );

    // 映射里的每个运行时实体都必须是真实存在的、且都在提取子树内。
    for (运行时, 文档) in &产物.实体映射 {
        assert!(宿主.存在(*运行时), "映射里出现了已失效的运行时实体");
        assert!(产物.文档.存在(*文档), "映射指向不存在的文档实体");
    }
    // 根在映射里对应顶层实体。
    assert_eq!(产物.文档标识(根), Some(产物.文档.顶层顺序[0]));
}

