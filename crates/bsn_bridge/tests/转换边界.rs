/// 在给定宿主上提取一个 BSN 场景（严格模式）。
fn 严格提取(宿主: &BSN宿主, 根: Entity, 场景名: &str) -> bsn_bridge::提取产物 {
    let 注册表 = 测试注册表();
    let 配置 = 测试提取配置(&注册表);
    提取并校验(宿主.世界(), 根, 场景名, &配置).expect("应无损失地提取")
}

/// 从文档里按名称唯一取一个实体标识。
fn 按名称取(文档: &scene_doc::document::场景文档, 目标: &str) -> 实体标识 {
    文档
        .实体表
        .values()
        .find(|实体| 实体.名称 == 目标)
        .unwrap_or_else(|| panic!("文档里找不到名为 `{目标}` 的实体"))
        .标识
}

