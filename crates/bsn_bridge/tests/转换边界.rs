#[test]
fn 规范化项被如实记录() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 基础关卡模板.实例化(宿主.世界可变()).expect("实例化");
    let 产物 = 严格提取(&宿主, 根, "规范化");

    let 说明 = &产物.报告.规范化;
    assert!(
        说明
            .iter()
            .any(|行| 行.contains("Transform") && 行.contains("变换")),
        "`Transform → 变换` 这条规范化必须被记录，实际：{说明:#?}"
    );
    assert!(
        说明
            .iter()
            .any(|行| 行.contains("Children") && 行.contains("父实体")),
        "`Children → 父实体 + 次序` 必须被记录，实际：{说明:#?}"
    );

    // 引擎派生组件被有意忽略，且必须出现在报告里而不是无声消失。
    assert!(
        产物.报告.忽略组件.contains_key("GlobalTransform"),
        "GlobalTransform 应被显式列入忽略清单，实际：{:?}",
        产物.报告.忽略组件
    );
    // 忽略 ≠ 丢失：报告必须明确说无数据损失。
    assert!(!产物.报告.有数据损失());
}

