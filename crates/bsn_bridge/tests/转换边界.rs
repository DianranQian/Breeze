#[test]
fn 未登记组件导致严格转换失败而不是静默丢弃() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 宿主
        .实例化(bsn! {
            #带未知组件
            HealthBar { 当前: 1 }
            Unregistered { 载荷: 42 }
        })
        .expect("BSN 本身能实例化：官方不关心我们的提取器");

    // 宽松路径：返回文档，但报告必须列出未转换组件。
    let 注册表 = 测试注册表();
    let 配置 = 测试提取配置(&注册表);
    let 产物 = 提取文档(宿主.世界(), 根, "未知组件", &配置).expect("宽松提取应返回文档");
    assert!(产物.报告.有数据损失());
    assert_eq!(产物.报告.未转换组件.len(), 1);
    assert_eq!(
        产物.报告.未转换组件[0].类型标识,
        Some(std::any::TypeId::of::<Unregistered>())
    );
    assert_eq!(产物.报告.未转换组件[0].实体名称, "带未知组件");

    // 严格路径：必须拒绝，避免用户以为转换成功。
    match 提取并校验(宿主.世界(), 根, "未知组件", &配置) {
        Err(BSN错误::存在未转换组件 { 数量, 示例 }) => {
            assert_eq!(数量, 1);
            assert!(示例.contains("带未知组件"), "错误应能定位实体：{示例}");
        }
        其他 => panic!("期望存在未转换组件的错误，实际：{其他:?}"),
    }

    // 即便是宽松路径，那个组件也**没有**被写进文档 —— 不能假装转换过。
    let 标识 = 按名称取(&产物.文档, "带未知组件");
    assert!(!产物.文档.取(标识).unwrap().有组件("Unregistered"));
}

