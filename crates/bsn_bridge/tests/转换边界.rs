/// 世界类型与文档类型不同的组件，经 `组件提取器::带转换` 接入。
///
/// `Visibility` 是这一情形的真实例子：世界里是 Bevy 的三态枚举，
/// 文档适配器（`editor_app::scene_bridge::可见性属性`）只存一个布尔。
/// 这条测试同时守住"这个扩展点真的能用"与"映射方向正确"。
#[test]
fn 世界类型与文档类型不同的组件经转换器接入() {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 宿主
        .实例化(bsn! {
            #隐藏物
            Visibility::Hidden
        })
        .expect("实例化");

    // 先确认世界里确实是 Bevy 的 Visibility::Hidden。
    assert_eq!(宿主.取组件::<Visibility>(根), Some(&Visibility::Hidden));

    let 产物 = 严格提取(&宿主, 根, "可见性");
    let 标识 = 按名称取(&产物.文档, "隐藏物");
    let 可见性组件 = 产物
        .文档
        .取(标识)
        .unwrap()
        .取组件("Visibility")
        .expect("Visibility 应被转换成文档组件");

    assert_eq!(
        可见性组件.属性.get("可见"),
        Some(&属性值::布尔(false)),
        "Hidden 必须映射成不可见"
    );
    // 文档里存的类型名是适配器声明的文档名，而不是 Bevy 的类型路径。
    assert_eq!(可见性组件.类型名, "Visibility");
    // 这条组件被正确消费，所以不算未转换。
    assert!(!产物.报告.有数据损失());
    assert_eq!(产物.报告.已转换组件.get("Visibility"), Some(&1));
}
