//! 中文名：构建物理演示项目
//! 生成一个"带碰撞体"的 2D 演示项目，供 GUI 验收与手工试用。
//!
//! 运行：
//!
//! ```powershell
//! cargo run -p editor_app --example build_physics_demo
//! ```
//!
//! 打开后勾选视口工具栏的「碰撞」即可看到碰撞轮廓。
//! 演示里刻意放了三种情况：地面（静态矩形）、箱子（动态矩形）、
//! 危险区（圆形触发器）——对应物理排错时最常见的三类形状。
//!
//! # 为什么尺寸这么大
//!
//! 2D 视口在 100% 缩放下 **1 世界单位 = 1 像素**，所以碰撞体要几十到几百
//! 单位才看得见。这与编辑器里 64 单位精灵的约定一致；写成 1x1 的
//! "教科书尺寸"在视口里只会是一个点。

use editor_core::project::项目描述;
use scene_doc::document::{变换数据, 场景文档, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::property::{属性值, 枚举值, 颜色值};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let 目标 = std::env::args()
        .nth(1)
        .unwrap_or_else(|| ".verify/runs/physics_demo".to_string());
    let 根 = std::path::PathBuf::from(&目标);
    if 根.exists() {
        std::fs::remove_dir_all(&根)?;
    }
    if let Some(父) = 根.parent() {
        std::fs::create_dir_all(父)?;
    }
    let mut 项目 = 项目描述::创建(&根, "物理演示")?;

    let mut 文档 = 场景文档::新建("physics");
    // 地面：静态矩形。
    let 地面 = 文档.生成实体("地面", None);
    if let Some(实体) = 文档.取可变(地面) {
        实体.变换 = Some(变换数据 {
            平移: (0.0, -220.0, 0.0),
            ..变换数据::单位()
        });
        实体.加组件(碰撞体(
            枚举值::新建("Rectangle", 0),
            640.0,
            40.0,
            0.0,
            false,
        ));
        实体.加组件(刚体(枚举值::新建("Static", 0), 0.0));
    }
    // 箱子：动态矩形。
    let 箱子 = 文档.生成实体("箱子", None);
    if let Some(实体) = 文档.取可变(箱子) {
        实体.变换 = Some(变换数据 {
            平移: (-80.0, 0.0, 0.0),
            ..变换数据::单位()
        });
        实体.加组件(碰撞体(
            枚举值::新建("Rectangle", 0),
            80.0,
            80.0,
            0.0,
            false,
        ));
        实体.加组件(刚体(枚举值::新建("Dynamic", 1), 1.0));
    }
    // 危险区：圆形触发器。
    let 危险区 = 文档.生成实体("危险区", None);
    if let Some(实体) = 文档.取可变(危险区) {
        实体.变换 = Some(变换数据 {
            平移: (160.0, -80.0, 0.0),
            ..变换数据::单位()
        });
        实体.加组件(碰撞体(枚举值::新建("Circle", 1), 0.0, 0.0, 70.0, true));
    }
    // 一个可见的精灵做参照：碰撞体应当正好盖住它。
    加精灵实体(&mut 文档, "墙", (-260.0, -40.0), 60.0, 200.0);

    let 场景路径 = 项目相对路径::解析("scenes/physics.scene.ron")?;
    项目.保存场景(&场景路径, &文档)?;
    项目.清单可变().启动场景 = Some(场景路径);
    项目.保存清单()?;
    println!("已生成物理演示项目：{}", 根.display());
    println!(
        "打开方式：$env:BEVY_STUDIO_OPEN_PROJECT=\"{}\"; $env:BEVY_STUDIO_MODE=\"2d\"; $env:BEVY_STUDIO_SHOW_COLLISIONS=\"1\"",
        根.display()
    );
    Ok(())
}

/// 造一个 `碰撞体2d` 组件。
fn 碰撞体(形状: 枚举值, 宽: f32, 高: f32, 半径: f32, 触发器: bool) -> 组件数据 {
    组件数据::新建(
        "碰撞体2d",
        [
            ("形状".to_string(), 属性值::枚举(形状)),
            ("宽度".to_string(), 属性值::浮点(宽.max(0.001))),
            ("高度".to_string(), 属性值::浮点(高.max(0.001))),
            ("半径".to_string(), 属性值::浮点(半径.max(0.001))),
            ("触发器".to_string(), 属性值::布尔(触发器)),
        ]
        .into_iter()
        .collect(),
    )
}

/// 造一个 `刚体2d` 组件。
fn 刚体(类型: 枚举值, 质量: f32) -> 组件数据 {
    组件数据::新建(
        "刚体2d",
        [
            ("类型".to_string(), 属性值::枚举(类型)),
            ("质量".to_string(), 属性值::浮点(质量.max(0.001))),
            (
                "重力缩放".to_string(),
                属性值::浮点(if 质量 > 0.0 { 1.0 } else { 0.0 }),
            ),
        ]
        .into_iter()
        .collect(),
    )
}

/// 加一个带色的精灵实体（用编辑器内置的四边形贴图之外的简单方式：
/// 只写 `精灵` 组件的尺寸与颜色，预览会画成纯色块）。
fn 加精灵实体(
    文档: &mut 场景文档, 名称: &str, 位置: (f32, f32), 宽: f32, 高: f32
) {
    let 标识 = 文档.生成实体(名称, None);
    let Some(实体) = 文档.取可变(标识) else {
        return;
    };
    实体.变换 = Some(变换数据 {
        平移: (位置.0, 位置.1, 0.0),
        ..变换数据::单位()
    });
    实体.加组件(组件数据::新建(
        "精灵",
        [
            ("尺寸".to_string(), 属性值::二维(宽, 高)),
            (
                "颜色".to_string(),
                属性值::颜色(颜色值::srgb(0.55, 0.62, 0.72, 1.0)),
            ),
            ("受光".to_string(), 属性值::布尔(false)),
        ]
        .into_iter()
        .collect(),
    ));
}
