//! 中文名：构建界面演示项目
//! 生成一个"带游戏界面"的演示项目，供 GUI 验收与手工试用。
//!
//! 运行：
//!
//! ```powershell
//! cargo run -p editor_app --example build_ui_demo
//! ```
//!
//! 生成的场景包含：一个半透明面板、一个标题文字、一个按钮。
//! 打开项目后切到 2D 模式即可在视口里看到它们；选中任一实体，
//! 检查器里就能改文字、字号、颜色、尺寸与位置 —— 全部走注册表驱动的
//! 字段编辑器，没有一行界面代码是为这三个组件专门写的。

use editor_core::project::项目描述;
use scene_doc::document::{变换数据, 场景文档, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::property::{属性值, 颜色值};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let 目标 = std::env::args()
        .nth(1)
        .unwrap_or_else(|| ".verify/runs/ui_demo".to_string());
    let 根 = std::path::PathBuf::from(&目标);
    if 根.exists() {
        std::fs::remove_dir_all(&根)?;
    }
    if let Some(父) = 根.parent() {
        std::fs::create_dir_all(父)?;
    }
    let mut 项目 = 项目描述::创建(&根, "界面演示")?;

    let mut 文档 = 场景文档::新建("ui");
    // 铺满设计帧的底色面板：它把"预览画面实际占据的区域"整块染成
    // 一个容易识别的颜色，供自动验收从截图里量出 letterbox 矩形
    // （比例不对 = 画面被拉伸）。这本身也是一个真实用法：
    // 全屏背景板。
    加界面实体(
        &mut 文档,
        "画布底",
        "Stretch",
        (0.0, 0.0, 0.0, 0.0),
        颜色值::srgb(0.10, 0.22, 0.42, 1.0),
    );
    // 一块深色背景面板：让白色的文字与按钮有对比。
    // 主面板锚在左上：与里面文字的 72/118/160 偏移对齐，
    // 这样截图里能直接看出"面板与内容是一体的"。
    加界面实体(
        &mut 文档,
        "主面板",
        "TopLeft",
        (32.0, 32.0, 448.0, 200.0),
        颜色值::srgb(0.08, 0.10, 0.14, 0.92),
    );
    // 右下角的小标签：锚点用 BottomRight，偏移是"距右边/下边"的距离。
    加界面实体(
        &mut 文档,
        "版本标签",
        "BottomRight",
        (24.0, 24.0, 180.0, 44.0),
        颜色值::srgb(0.12, 0.16, 0.22, 0.92),
    );
    // 标题文字。
    加文字实体(&mut 文档, "标题", "微风 · 界面演示", (72.0, 72.0), 30.0);
    // 一行说明文字。
    // 说明文字：给定宽度 320 并居中，用来演示「对齐」字段的效果
    // （没有宽度时对齐看不出来，与 Godot 的 Label 一致）。
    加文字实体宽度(
        &mut 文档,
        "说明",
        "这条文字来自场景文件，改了字号会立刻变。",
        (72.0, 118.0),
        320.0,
        18.0,
    );
    // 按钮。
    加按钮实体(
        &mut 文档,
        "开始按钮",
        "开始游戏",
        (72.0, 160.0, 200.0, 56.0),
    );

    let 场景路径 = 项目相对路径::解析("scenes/ui.scene.ron")?;
    项目.保存场景(&场景路径, &文档)?;
    项目.清单可变().启动场景 = Some(场景路径);
    // 设计分辨率 1920×1080：预览里界面会等比缩小并居中（letterbox），
    // 这正是"设计稿尺寸"与"预览纹理尺寸"分离后的效果。
    项目.清单可变().设计分辨率 = (1920, 1080);
    项目.保存清单()?;
    println!("已生成界面演示项目：{}", 根.display());
    println!(
        "打开方式：$env:BEVY_STUDIO_OPEN_PROJECT=\"{}\"; $env:BEVY_STUDIO_MODE=\"2d\"",
        根.display()
    );
    Ok(())
}

/// 加一个 `UiNode` 面板实体。
fn 加界面实体(
    文档: &mut 场景文档,
    名称: &str,
    锚点: &str,
    位置尺寸: (f32, f32, f32, f32),
    背景: 颜色值,
) {
    let 标识 = 文档.生成实体(名称, None);
    let Some(实体) = 文档.取可变(标识) else {
        return;
    };
    实体.变换 = Some(变换数据::单位());
    实体.加组件(组件数据::新建(
        "UiNode",
        [
            (
                "锚点".to_string(),
                属性值::枚举(scene_doc::property::枚举值::新建(锚点, 锚点序号(锚点))),
            ),
            ("宽度".to_string(), 属性值::浮点(位置尺寸.2)),
            ("高度".to_string(), 属性值::浮点(位置尺寸.3)),
            ("偏移X".to_string(), 属性值::浮点(位置尺寸.0)),
            ("偏移Y".to_string(), 属性值::浮点(位置尺寸.1)),
            ("背景色".to_string(), 属性值::颜色(背景)),
        ]
        .into_iter()
        .collect(),
    ));
}

/// 锚点变体名对应的下拉序号（与 `editor_core::ui_layout::界面锚点` 一致）。
fn 锚点序号(变体名: &str) -> u32 {
    match 变体名 {
        "TopCenter" => 1,
        "Center" => 2,
        "BottomRight" => 3,
        "Stretch" => 4,
        _ => 0,
    }
}

/// 加一个带固定宽度且居中的 `UiText` 实体（用来演示「对齐」字段）。
fn 加文字实体宽度(
    文档: &mut 场景文档,
    名称: &str,
    文本: &str,
    位置: (f32, f32),
    宽度: f32,
    字号: f32,
) {
    加文字实体(文档, 名称, 文本, 位置, 字号);
    let 标识 = 文档
        .实体表
        .iter()
        .find(|(_, 实体)| 实体.名称 == 名称)
        .map(|(标识, _)| *标识);
    let Some(标识) = 标识 else {
        return;
    };
    let Some(实体) = 文档.取可变(标识) else {
        return;
    };
    if let Some(组件) = 实体.取组件可变("UiText") {
        组件.属性.insert(
            "对齐".to_string(),
            属性值::枚举(scene_doc::property::枚举值::新建("Center", 1)),
        );
    }
    if let Some(组件) = 实体.取组件可变("UiNode") {
        组件.属性.insert("宽度".to_string(), 属性值::浮点(宽度));
    }
}

/// 加一个 `UiText` 实体。
fn 加文字实体(
    文档: &mut 场景文档, 名称: &str, 文本: &str, 位置: (f32, f32), 字号: f32
) {
    let 标识 = 文档.生成实体(名称, None);
    let Some(实体) = 文档.取可变(标识) else {
        return;
    };
    实体.加组件(组件数据::新建(
        "UiText",
        [
            ("文本".to_string(), 属性值::文本(文本.to_string())),
            ("字号".to_string(), 属性值::浮点(字号)),
            (
                "颜色".to_string(),
                属性值::颜色(颜色值::srgb(0.92, 0.94, 0.98, 1.0)),
            ),
        ]
        .into_iter()
        .collect(),
    ));
    // 文本自己不带面板组件，位置由 `UiNode` 决定；这里补一个透明面板，
    // 让"文字放在哪"也是可编辑的数据（而不是写死在渲染代码里）。
    实体.加组件(组件数据::新建(
        "UiNode",
        [
            ("宽度".to_string(), 属性值::浮点(0.0)),
            ("高度".to_string(), 属性值::浮点(0.0)),
            ("偏移X".to_string(), 属性值::浮点(位置.0)),
            ("偏移Y".to_string(), 属性值::浮点(位置.1)),
            (
                "背景色".to_string(),
                属性值::颜色(颜色值::srgb(0.0, 0.0, 0.0, 0.0)),
            ),
        ]
        .into_iter()
        .collect(),
    ));
}

/// 加一个 `UiButton` 实体（带面板尺寸）。
fn 加按钮实体(
    文档: &mut 场景文档, 名称: &str, 文本: &str, 位置尺寸: (f32, f32, f32, f32)
) {
    let 标识 = 文档.生成实体(名称, None);
    let Some(实体) = 文档.取可变(标识) else {
        return;
    };
    实体.加组件(组件数据::新建(
        "UiButton",
        [
            ("文本".to_string(), 属性值::文本(文本.to_string())),
            ("字号".to_string(), 属性值::浮点(22.0)),
            (
                "背景色".to_string(),
                属性值::颜色(颜色值::srgb(0.22, 0.49, 0.86, 1.0)),
            ),
            (
                "文字颜色".to_string(),
                属性值::颜色(颜色值::srgb(1.0, 1.0, 1.0, 1.0)),
            ),
        ]
        .into_iter()
        .collect(),
    ));
    实体.加组件(组件数据::新建(
        "UiNode",
        [
            (
                "锚点".to_string(),
                属性值::枚举(scene_doc::property::枚举值::新建("TopLeft", 0)),
            ),
            ("宽度".to_string(), 属性值::浮点(位置尺寸.2)),
            ("高度".to_string(), 属性值::浮点(位置尺寸.3)),
            ("偏移X".to_string(), 属性值::浮点(位置尺寸.0)),
            ("偏移Y".to_string(), 属性值::浮点(位置尺寸.1)),
            (
                "背景色".to_string(),
                属性值::颜色(颜色值::srgb(0.22, 0.49, 0.86, 1.0)),
            ),
        ]
        .into_iter()
        .collect(),
    ));
}
