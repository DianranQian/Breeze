//! 动作执行：把界面产生的 [`UiAction`] 变成对编辑器状态的实际修改。
//!
//! # 为什么所有动作都集中在这里
//!
//! 如果让每个面板各自去改编辑器状态，那么"保存前先同步资源表"
//! "删除资源前先检查引用"这类**横切规则**就必须在每个面板里重复一遍，
//! 迟早会漏。集中在一个执行器里，这些规则只需要写一次，
//! 而且可以针对它单独写测试（见本文件底部的测试）。
//!
//! 这里也是唯一允许把 [`场景错误`] 转成控制台日志的地方：
//! 界面层不应该看到 `Result`，它只需要知道"这个操作没能完成"。

