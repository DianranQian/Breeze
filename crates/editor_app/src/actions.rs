/// 请求弹出文件对话框。
fn 请求对话框(
    对话框: &mut 文件对话框通道, 编辑器: &mut 编辑器状态, 请求: 文件对话框请求
) {
    if 对话框.处理中 {
        编辑器.警告("已有文件对话框在处理中，请先完成上一个");
        return;
    }
    match 对话框.请求发送端.send(请求) {
        Ok(()) => 对话框.处理中 = true,
        Err(错误) => {
            编辑器.错误(format!("无法打开文件对话框：{错误}"));
        }
    }
}

/// 按注册表构造一个组件的默认实例数据。
///
/// 属性取注册表里声明的默认值，因此"添加组件"得到的永远是一份合法数据，
/// 而不是空属性表 —— 后者在 Inspector 里会显示成一堆空字段。
fn 构造默认组件(
    编辑器: &编辑器状态,
    类型名: &str,
) -> Option<scene_doc::document::组件数据> {
    let 类型 = 编辑器.注册表.查询(类型名)?;
    let mut 属性 = std::collections::BTreeMap::new();
    for 描述 in 类型.字段描述() {
        属性.insert(描述.字段名.clone(), 描述.默认值.clone());
    }
    Some(scene_doc::document::组件数据::新建(类型名, 属性))
}

/// 从资源创建一个实体。
///
/// 按资源类别决定挂什么组件：
/// * 图片 → `Sprite`，并自动取图片尺寸填进 `自定义尺寸`；
/// * 其余类别 → 只建一个空实体并在日志里说明尚未支持，
///   而不是悄悄建个空实体让用户以为成功了。
fn 从资源创建实体(
    编辑器: &mut 编辑器状态,
    资源: &scene_doc::path::项目相对路径,
    父实体: Option<scene_doc::document::实体标识>,
) {
    use scene_doc::property::资源类别;

    let 类别 = 资源
        .扩展名()
        .map(|扩展| 资源类别::由扩展名推断(&扩展))
        .unwrap_or(资源类别::其他);

    let 名称 = 资源
        .文件名()
        .rsplit_once('.')
        .map(|(基名, _)| 基名.to_string())
        .unwrap_or_else(|| 资源.文件名().to_string());

    let Some(标识) = 编辑器.新建实体(名称.clone(), 父实体) else {
        编辑器.错误("创建实体失败");
        return;
    };

    match 类别 {
        资源类别::图片 => {
            let Some(mut 组件) = 构造默认组件(编辑器, "Sprite") else {
                return;
            };
            组件.属性.insert(
                "贴图".to_string(),
                属性值::资源(资源引用值::按路径(资源.clone())),
            );
            // 读图片真实尺寸，让视口与运行时都用正确的包围盒。
            // 读不到就地说明，而不是猜一个尺寸。
            match 读取图片尺寸(编辑器, 资源) {
                Some((宽, 高)) => {
                    组件
                        .属性
                        .insert("自定义尺寸".to_string(), 属性值::二维(宽, 高));
                    编辑器.添加组件(标识, 组件);
                    编辑器.信息(format!("已从 {} 创建精灵（{}×{}）", 资源.文本(), 宽, 高));
                }
                None => {
                    编辑器.添加组件(标识, 组件);
                    编辑器.警告(format!(
                        "已从 {} 创建精灵，但无法读取图片尺寸，\
                         视口将按默认尺寸显示。请确认文件是有效的图片。",
                        资源.文本()
                    ));
                }
            }
        }
        // 刻意不写 `其他 =>`：`资源类别` 里正好有一个同名变体 `其他`，
        // 那样写会被解析成"绑定任意值到叫 `其他` 的变量"，
        // 而不是"匹配 `其他` 这个变体"（`bindings_with_variant_name` 会拒绝）。
        非图片类别 => {
            编辑器.信息(format!(
                "已创建实体 `{名称}`，但尚未为 {} 类资源实现自动组件（{}）。\
                 请手工添加需要的组件。",
                // 这条消息整体仍是中文，等日志结构化那一批再一起本地化；
                // 这里显式用中文渲染，行为与改造前完全一致。
                editor_core::i18n::语言::中文.取(非图片类别.词条键()),
                资源.文本()
            ));
        }
    }
}

/// 读取图片资源的像素尺寸。
fn 读取图片尺寸(
    编辑器: &编辑器状态,
    资源: &scene_doc::path::项目相对路径,
) -> Option<(f32, f32)> {
    let 项目 = 编辑器.项目.as_ref()?;
    let 绝对 = 项目.绝对路径(资源);
    let 图片 = image::ImageReader::open(&绝对).ok()?.decode().ok()?;
    Some((图片.width() as f32, 图片.height() as f32))
}

/// 推进运行时世界。
///
/// 当前运行时世界只承载"场景被正确构建"这一事实与统计数据；
/// 它还没有自己的系统与渲染（那属于里程碑 C/E 的后续工作）。
/// 这里诚实地统计帧数与耗时，不假装在跑一个完整游戏循环。
pub fn 推进运行时(mut 运行时: ResMut<运行时宿主>, 时间: Res<Time>) {
    if !运行时.状态.在运行() {
        return;
    }

    运行时.上一帧毫秒 = 时间.delta_secs() * 1000.0;
    if 运行时.状态 == 运行状态::运行中 {
        运行时.已推进帧数 += 1;
    }
}

/// 收集运行时诊断信息，供界面显示。
pub fn 收集运行时诊断(
    运行时: Res<运行时宿主>,
    mut 诊断: ResMut<诊断资源>,
    编辑器: Res<EditorStateHolder>,
) {
    let 帧耗时 = 运行时.上一帧毫秒;
    诊断.0 = editor_ui::运行时诊断 {
        帧率: if 帧耗时 > 0.0 {
            1000.0 / 帧耗时
        } else {
            0.0
        },
        帧耗时毫秒: 帧耗时,
        实体总数: 运行时.运行时实体数(),
        组件类型数: 运行时.运行时组件类型数(),
        资源数: 编辑器
            .状态
            .项目
            .as_ref()
            .map(|项目| 项目.资源列表().len())
            .unwrap_or(0),
        已运行秒数: 运行时.已运行秒数(),
    };
}

