/// 绘制编辑器界面。
pub fn 绘制编辑器界面(
    mut 上下文: EguiContexts,
    mut 界面: ResMut<UiStateHolder>,
    编辑器: Res<EditorStateHolder>,
    运行时: Res<运行时宿主>,
    配色: Res<配色资源>,
    缩略图: Res<缩略图缓存>,
    诊断: Res<诊断资源>,
) {
    let Ok(上下文) = 上下文.ctx_mut() else {
        return;
    };

    // 先做一次"只改界面状态"的预处理。这些动作不需要碰编辑器数据，
    // 放在这里能让窗口的打开与布局重置在同一帧内立即生效。
    let 待处理 = 界面.动作.列表().to_vec();

    // 把 `界面.状态` 与 `界面.动作` 分开借用：
    // 二者都是 `UiStateHolder` 的字段，直接写 `&mut 界面.状态` 与
    // `&mut 界面.动作` 会同时可变借用 `界面`。先取出引用即可。
    let UiStateHolder { 状态, 动作 } = &mut *界面;

    for 动作项 in &待处理 {
        match 动作项 {
            UiAction::恢复默认布局 => 状态.恢复默认布局(),
            UiAction::显示关于 => 状态.显示关于 = true,
            UiAction::聚焦面板(面板) => 状态.聚焦面板(*面板),
            _ => {}
        }
    }

    绘制一帧(
        上下文,
        绘制环境 {
            编辑器: &编辑器.状态,
            配色: 配色.0,
            缩略图: &缩略图.纹理,
            运行时: &运行时,
            诊断: &诊断.0,
        },
        状态,
        动作,
    );
}
