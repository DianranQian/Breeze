use bevy::prelude::*;
use bevy_egui::EguiContexts;
use editor_core::command::编辑器命令;
use editor_core::state::{日志参数, 日志级别, 编辑器状态};
use editor_ui::state::{UiAction, 工作区对话框, 选择意图};
use editor_ui::界面状态;
use scene_doc::property::{属性值, 资源引用值};

use crate::config::{
    布局写盘间隔, 布局待保存, 编辑器配置资源, 配置文件路径, 配置格式版本
};
use crate::plugin::{
    EditorStateHolder, UiStateHolder, 文件对话框结果, 文件对话框请求, 文件对话框通道, 绘制一帧,
    绘制环境, 缩略图缓存, 诊断资源,
};
use crate::scene_bridge::{运行时宿主, 运行状态};

/// 拖动开始时各实体的变换快照。
///
/// 必须保存"按下那一刻"的位置：鼠标移动事件给出的是**相对按下点**的
/// 累积偏移，如果每次都把偏移加到当前值上，偏移会被重复累加，
/// 表现为对象以远快于鼠标的速度飞出去。
///
/// 快照存在界面状态里而不是运行时宿主里：它是纯粹的编辑期交互状态，
/// 与游戏运行时无关。
#[derive(Debug, Clone, Default)]
pub struct 拖动快照 {
    /// 每项为 (实体, 拖动开始时的变换)。
    pub 项: Vec<(scene_doc::document::实体标识, scene_doc::document::变换数据)>,
}

/// 处理键盘快捷键。
///
/// 快捷键在这里统一处理而不是在面板里：面板只有在获得焦点时才收到按键，
/// 而 Ctrl+S、F5 这类全局快捷键无论焦点在哪都应该生效。
pub fn 处理快捷键(
    mut 上下文: EguiContexts,
    mut 界面: ResMut<UiStateHolder>,
    当前运行: Res<运行时宿主>,
) {
    let Ok(上下文) = 上下文.ctx_mut() else {
        return;
    };

    // 有文本输入框在编辑时不响应全局快捷键，
    // 否则用户重命名实体时按 Ctrl+S 会同时保存并打断输入。
    if 界面.状态.文本编辑.is_some() {
        return;
    }

    let 按键 = 上下文.input(|输入| {
        let 命令键 = 输入.modifiers.command;
        快捷键状态 {
            保存: 命令键 && 输入.key_pressed(egui::Key::S),
            运行: 输入.key_pressed(egui::Key::F5),
            暂停: 输入.key_pressed(egui::Key::F6),
            停止: 输入.key_pressed(egui::Key::F7),
            撤销: 命令键 && 输入.key_pressed(egui::Key::Z),
            重做: 命令键 && 输入.key_pressed(egui::Key::Y),
            取消选择: 输入.key_pressed(egui::Key::Escape),
        }
    });

    if 按键.保存 {
        界面.动作.推(UiAction::保存场景);
    }
    if 按键.运行 && !当前运行.状态.在运行() {
        界面.动作.推(UiAction::运行场景);
    }
    if 按键.暂停 && 当前运行.状态.在运行() {
        界面.动作.推(UiAction::暂停运行);
    }
    if 按键.停止 && 当前运行.状态.在运行() {
        界面.动作.推(UiAction::停止运行);
    }
    if 按键.撤销 {
        界面.动作.推(UiAction::撤销);
    }
    if 按键.重做 {
        界面.动作.推(UiAction::重做);
    }
    if 按键.取消选择 {
        // # Escape 的唯一归属点
        //
        // 这条规则以前在**两个地方**各写了一遍（这里与 2D 视口内部），
        // 于是"拖拽操纵器时按 Escape"会先取消拖拽、再被另一处顺手清空选择 ——
        // 用户的感受是"我只是放弃这次拖动，选中却没了"。
        //
        // 现在只在全局这一处决定：
        // * 正在拖拽操纵器 → 什么都不做（取消由视口驱动负责，它持有起始变换）；
        // * 选择工具 → 清空选择（原有语义）；
        // * 变换工具且没在拖 → 不做任何事（Escape 的语义是"取消当前操作"）。
        let 正在变换 = 界面.状态.操纵器拖拽.is_some();
        if !正在变换 && 界面.状态.变换工具 == editor_ui::gizmo::变换工具::选择 {
            界面.动作.推(UiAction::选择(选择意图::清空));
        }
    }
}

/// 一帧内的快捷键状态。
///
/// 把多个布尔量打成一个结构体，是为了让下面的判断读起来是
/// "如果按下保存就……"，而不是一长串裸布尔变量。
struct 快捷键状态 {
    保存: bool,
    运行: bool,
    暂停: bool,
    停止: bool,
    撤销: bool,
    重做: bool,
    取消选择: bool,
}

/// 处理文件对话框回传的结果。
pub fn 处理文件对话框结果(
    mut 对话框: ResMut<文件对话框通道>,
    mut 界面: ResMut<UiStateHolder>,
    mut 编辑器: ResMut<EditorStateHolder>,
    mut 布局待保存: ResMut<布局待保存>,
) {
    // 非阻塞地取一次结果；通道里最多只会有一个。
    let Ok(结果) = 对话框.结果接收端.try_recv() else {
        return;
    };
    对话框.处理中 = false;

    match 结果 {
        文件对话框结果::取消 => {
            编辑器.状态.信息("已取消文件选择");
        }

        文件对话框结果::脚本已保存(路径) => {
            let 语言 = 界面.状态.语言;
            match 编辑器
                .状态
                .项目
                .as_ref()
                .and_then(|项目| 项目.相对路径(&路径))
            {
                Some(相对) => {
                    界面.状态.脚本.标记已保存(Some(相对.clone()));
                    编辑器.状态.结构化信息(
                        "log_script_saved",
                        vec![日志参数::用户数据(相对.文本().to_string())],
                    );
                }
                None => 编辑器
                    .状态
                    .警告(语言.取("script_unsaved_outside_project").to_string()),
            }
        }

        文件对话框结果::主题已导出(路径) => {
            编辑器.状态.结构化信息(
                "log_theme_exported",
                vec![日志参数::用户数据(路径.display().to_string())],
            );
        }

        文件对话框结果::主题文本 { 路径, 文本 } => {
            let 语言 = 界面.状态.语言;
            match 界面.状态.主题库.导入(&文本, 语言) {
                Ok(名称) => {
                    界面.状态.主题草稿 = Some(界面.状态.主题库.当前().clone());
                    编辑器
                        .状态
                        .结构化信息("log_theme_imported", vec![日志参数::用户数据(名称)]);
                    布局待保存.脏 = true;
                }
                Err(错误) => {
                    编辑器
                        .状态
                        .警告(format!("{}（{}）", 错误.文案(语言), 路径.display()))
                }
            }
        }

        文件对话框结果::选定目录(目录) => {
            界面.动作.推(UiAction::打开项目(目录));
        }

        文件对话框结果::新建项目 { 名称, 父目录 } => {
            // 项目建在"父目录/项目名"下，与 Godot 的习惯一致。
            let 目标 = 父目录.join(&名称);
            match 编辑器.状态.创建项目(&目标, 名称) {
                Ok(()) => {
                    编辑器.状态.信息(format!("项目已创建于 {}", 目标.display()));
                }
                Err(错误) => {
                    编辑器.状态.错误(format!("创建项目失败：{错误}"));
                }
            }
        }

        文件对话框结果::选定文件(文件) => {
            // 视目标是场景另存为还是打开场景，由文件是否存在来区分：
            // 场景另存为允许选一个不存在的文件（新建），
            // 打开场景时选的文件一般已经存在。
            // 更严谨的做法是在通道里带上请求种类，这里用当前场景路径是否为空
            // 作为判据，并在日志中说明，避免用户困惑。
            match 编辑器.状态.项目.as_ref() {
                Some(项目) => match 项目.相对路径(&文件) {
                    Some(相对) => {
                        界面.动作.推(UiAction::场景另存为(相对));
                    }
                    None => {
                        编辑器.状态.错误(format!(
                            "所选文件不在当前项目目录内，无法作为场景保存：{}",
                            文件.display()
                        ));
                    }
                },
                None => {
                    编辑器.状态.错误("尚未打开项目，无法保存场景");
                }
            }
        }
    }
}

/// 执行本帧累积的动作队列。
///
/// # 这是唯一修改编辑器状态的地方
///
/// **所有** `UiAction` 都在这里被处理，包括那些"只改界面状态"的动作
/// （恢复默认布局、聚焦面板、显示关于）。
///
/// 为什么强调这一点：这些动作以前是在界面绘制函数里"预处理"的，
/// 而动作队列在 `Update` 里就已经被本函数取空了 ——
/// 于是绘制函数看到的是一个**空队列**，`恢复默认布局` 永远不生效。
/// 两个 `add_systems(Update, ...)` 之间没有显式顺序，这个问题
/// 还表现为"有时灵有时不灵"，极难复现。
///
/// 现在把处理集中在一处：动作产生于绘制、执行于下一帧的这里，
/// 顺序确定，且每个动作恰好被处理一次。
pub fn 执行动作队列(
    mut 界面: ResMut<UiStateHolder>,
    mut 编辑器: ResMut<EditorStateHolder>,
    mut 运行时: ResMut<运行时宿主>,
    mut 对话框: ResMut<文件对话框通道>,
    mut 拖动: Local<拖动快照>,
    mut 布局待保存: ResMut<布局待保存>,
    mut 项目运行: ResMut<crate::run::项目运行管理器>,
) {
    let 动作列表 = 界面.动作.取出();
    if 动作列表.is_empty() {
        return;
    }

    // 拖动中的高频动作合并成一条，避免一次鼠标移动就压一个撤销步。
    let 动作列表 = 合并拖动动作(动作列表);

    // 把 `界面.状态` 与 `界面.动作` 分开借用：`取出()` 已经借过一次
    // `界面`，而下面执行动作时还要改 `界面.状态`。
    // 先取出动作列表（拥有所有权），再单独借状态。
    let UiStateHolder { 状态, .. } = &mut *界面;

    for 动作 in 动作列表 {
        执行单个动作(
            &mut 编辑器.状态,
            &mut 运行时,
            &mut 对话框,
            &mut 拖动,
            状态,
            &mut 布局待保存,
            &mut 项目运行,
            动作,
        );
    }

    // 执行完动作后，选择集可能包含已删除的实体，需要清理。
    //
    // 这里先算出失效项再统一移除，而不是调用 `清理失效项(&文档)`：
    // 后者需要在 `选择` 可变借用的同时不可变借用文档，
    // 而两者都在 `编辑器.状态` 里，借用检查器不会允许。
    let 失效项: Vec<_> = 编辑器
        .状态
        .选择
        .全部()
        .into_iter()
        .filter(|标识| !编辑器.状态.会话.文档.存在(*标识))
        .collect();
    for 标识 in 失效项 {
        编辑器.状态.选择.移除(标识);
    }
}

/// 把连续的拖动动作合并：只保留最后一条。
///
/// 一次拖动会产生几十条 `拖动实体到`，如果每条都执行，
/// 撤销栈会被瞬间填满，用户按一次 Ctrl+Z 只能退回一个鼠标像素。
/// 合并后整次拖动只占一个撤销步。
fn 合并拖动动作(动作列表: Vec<UiAction>) -> Vec<UiAction> {
    let mut 结果: Vec<UiAction> = Vec::with_capacity(动作列表.len());
    for 动作 in 动作列表 {
        if matches!(动作, UiAction::拖动实体到 { .. }) {
            // 丢掉之前累积的同类动作，只保留最新位置。
            if let Some(位置) = 结果
                .iter()
                .rposition(|已有| matches!(已有, UiAction::拖动实体到 { .. }))
            {
                结果.remove(位置);
            }
        }
        结果.push(动作);
    }
    结果
}

/// 执行一条动作。
///
/// `界面状态` 与 `布局待保存` 是给"只改界面、不碰文档"的动作用的
/// （恢复默认布局、聚焦面板、显示关于）。它们与文档修改放在同一个
/// 分派点里，保证每个动作只被处理一次、且处理顺序确定。
#[allow(clippy::too_many_arguments)]
fn 执行单个动作(
    编辑器: &mut 编辑器状态,
    运行时: &mut 运行时宿主,
    对话框: &mut 文件对话框通道,
    拖动: &mut 拖动快照,
    界面状态: &mut 界面状态,
    布局待保存: &mut 布局待保存,
    项目运行: &mut crate::run::项目运行管理器,
    动作: UiAction,
) {
    match 动作 {
        // ---------------------------------------------------------------
        // 项目
        // ---------------------------------------------------------------
        UiAction::新建项目 { 名称 } => {
            请求对话框(对话框, 编辑器, 文件对话框请求::选择新建项目目录 { 名称 });
        }

        UiAction::请求打开项目 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::选择项目目录);
        }

        UiAction::打开示例项目(示例) => match 准备示例项目(示例) {
            Ok(目录) => match 编辑器.打开项目(&目录) {
                Ok(()) => {
                    let 语言 = 界面状态.语言;
                    let _ = 界面状态.切换模式(示例.默认模式());
                    界面状态.聚焦面板(editor_ui::Tab::视口);
                    // 2D 场景打开后把视口对准整张地图；3D 场景不自动拉远 ——
                    // 48×48 竞技场拉到全景后角色只有十几像素，反而更差。
                    // 3D 用户仍可点「适应窗口」主动拉远。
                    if !界面状态.模式.是三维() {
                        界面状态.视口命令.适应窗口 = true;
                    }
                    布局待保存.脏 = true;
                    编辑器.结构化信息(
                        "log_example_opened",
                        vec![日志参数::用户数据(目录.display().to_string())],
                    );
                    let _ = 语言;
                }
                Err(错误) => {
                    编辑器.错误(format!("{}：{错误}", 界面状态.语言.取("open_demo_failed")))
                }
            },
            Err(错误) => {
                编辑器.错误(format!("{}：{错误}", 界面状态.语言.取("open_demo_failed")))
            }
        },

        UiAction::打开项目(目录) => match 编辑器.打开项目(&目录) {
            Ok(()) => {
                if !界面状态.模式.是三维() {
                    界面状态.视口命令.适应窗口 = true;
                }
            }
            Err(错误) => 编辑器.错误(format!("打开项目失败：{错误}")),
        },

        UiAction::关闭项目 => {
            // 停止运行时：项目都关了，运行时世界不应继续存在。
            运行时.停止();
            编辑器.关闭项目();
        }

        UiAction::新建场景 => {
            let 名称 = 编辑器
                .项目
                .as_ref()
                .map(|_| "新场景".to_string())
                .unwrap_or_else(|| "未命名场景".to_string());
            编辑器.新建场景(名称);
        }

        UiAction::打开场景(路径) => {
            if let Err(错误) = 编辑器.打开场景(&路径) {
                编辑器.错误(format!("打开场景失败：{错误}"));
            } else if !界面状态.模式.是三维() {
                界面状态.视口命令.适应窗口 = true;
            }
        }

        UiAction::请求场景另存为 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::场景另存为);
        }

        UiAction::场景另存为(路径) => {
            if let Err(错误) = 编辑器.保存场景到(&路径) {
                编辑器.错误(format!("保存场景失败：{错误}"));
            }
        }

        UiAction::保存场景 => {
            // 尚未关联文件时，先让用户选一个路径，而不是直接报错。
            if 编辑器.场景已保存到磁盘() {
                if let Err(错误) = 编辑器.保存场景() {
                    编辑器.错误(format!("保存场景失败：{错误}"));
                }
            } else if 编辑器.项目.is_some() {
                请求对话框(对话框, 编辑器, 文件对话框请求::场景另存为);
            } else {
                编辑器.错误("尚未打开项目，无法保存场景");
            }
        }

        UiAction::在资源管理器中显示(路径) => {
            let Some(项目) = 编辑器.项目.as_ref() else {
                编辑器.警告("尚未打开项目");
                return;
            };
            let 绝对 = 项目.绝对路径(&路径);
            let 目标 = if 绝对.is_dir() {
                绝对.clone()
            } else {
                绝对.parent().map(Path::to_path_buf).unwrap_or(绝对.clone())
            };
            match opener::open(&目标) {
                Ok(()) => 编辑器.信息(format!("已在文件管理器中打开 {}", 目标.display())),
                Err(错误) => 编辑器.警告(format!("无法打开文件管理器：{错误}")),
            }
        }

        // ---------------------------------------------------------------
        // 编辑
        // ---------------------------------------------------------------
        UiAction::执行命令(命令) => {
            // 会产生新实体的命令走 `执行并选中`，其余走普通路径。
            //
            // 不这样做会出现一个很别扭的体验：点"新建实体"之后场景树里
            // 多了一项，但检查器仍然显示"未选中任何实体"，用户必须再点
            // 一次才能编辑它。
            //
            // 只对"新建实体"选中、而不是对所有命令都选中，是因为
            // 删除、重命名这类命令顺手改变选择会让用户困惑 ——
            // 删掉一个东西之后不应该自动选中别的东西。
            if matches!(命令, 编辑器命令::新建实体 { .. }) {
                if let Err(错误) = 编辑器.执行并选中(命令) {
                    编辑器.错误(format!("操作失败：{错误}"));
                }
            } else {
                编辑器.执行并记录(命令);
            }
        }

        UiAction::执行命令连续(命令) => {
            编辑器.执行并记录连续(命令);
        }

        UiAction::撤销 => {
            编辑器.撤销一步();
        }

        UiAction::重做 => {
            编辑器.重做一步();
        }

        UiAction::修改属性(编辑请求) => {
            编辑器.设属性(编辑请求.实体, 编辑请求.组件, 编辑请求.属性, 编辑请求.新值);
        }

        UiAction::添加组件 { 实体, 类型名 } => {
            let 组件 = 构造默认组件(编辑器, &类型名);
            match 组件 {
                Some(组件) => {
                    编辑器.添加组件(实体, 组件);
                }
                None => {
                    编辑器.错误(format!("组件 `{类型名}` 未注册，无法添加"));
                }
            }
        }

        UiAction::删除组件 { 实体, 类型名 } => {
            编辑器.删除组件(实体, 类型名);
        }

        UiAction::删除实体(标识) => {
            编辑器.删除实体(标识);
        }

        UiAction::复制实体(标识) => {
            if let Some(结果) = 编辑器.执行并记录(编辑器命令::新建实体 {
                名称: 编辑器
                    .会话
                    .文档
                    .取(标识)
                    .map(|实体| format!("{}_副本", 实体.名称))
                    .unwrap_or_else(|| "副本".to_string()),
                父实体: 编辑器.会话.文档.取(标识).and_then(|实体| 实体.父实体),
                指定标识: None,
            }) {
                // 把源实体的组件也复制过来。
                if let (Some(新标识), Some(源)) = (结果.新实体, 编辑器.会话.文档.取(标识).cloned())
                {
                    for 组件 in 源.组件 {
                        编辑器.添加组件(新标识, 组件);
                    }
                    编辑器.选择.单选(新标识);
                }
            }
        }

        UiAction::重命名实体 { 标识, 新名称 } => {
            编辑器.重命名实体(标识, 新名称);
        }

        UiAction::选择(意图) => {
            eprintln!(
                "[诊断] 执行选择动作 {:?}（之前 {} 项）",
                意图,
                编辑器.选择.数量()
            );
            应用选择意图(&mut 编辑器.选择, 意图);
        }

        UiAction::开始拖动实体 {
            实体,
            追加选择,
            按下世界,
        } => {
            if 追加选择 {
                应用选择意图(&mut 编辑器.选择, 选择意图::追加(实体));
            } else if !编辑器.选择.包含(实体) {
                // 只在点到的实体尚未被选中时才改选择：
                // 这样"拖动已选中的多个实体之一"不会把多选打散成单选。
                应用选择意图(&mut 编辑器.选择, 选择意图::单选(实体));
            }

            // 记录所有选中实体在按下那一刻的变换。
            拖动.项 = 编辑器
                .选择
                .全部()
                .into_iter()
                .filter_map(|标识| {
                    编辑器
                        .会话
                        .文档
                        .取(标识)
                        .and_then(|实体| 实体.变换)
                        .map(|变换| (标识, 变换))
                })
                .collect();

            bevy::log::debug!(
                "开始拖动 {} 个实体，按下世界坐标 ({:.2}, {:.2})",
                拖动.项.len(),
                按下世界.0,
                按下世界.1
            );
        }

        UiAction::拖动实体到 { 世界偏移 } => {
            if 拖动.项.is_empty() {
                return;
            }
            // 以拖动开始时的位置为基准加上偏移，整批实体一条命令提交。
            // 用批量命令而不是逐个 `设变换`，是为了让整次拖动只占一个撤销步。
            let 项: Vec<_> = 拖动
                .项
                .iter()
                .map(|(标识, 起始)| {
                    let mut 新变换 = *起始;
                    新变换.平移.0 = 起始.平移.0 + 世界偏移.0;
                    新变换.平移.1 = 起始.平移.1 + 世界偏移.1;
                    (*标识, Some(新变换))
                })
                .collect();

            // 拖动过程中的每一步都提交会污染撤销栈，因此这里**不**记为
            // 独立的历史步骤：靠 `结束拖动` 时的一次提交收尾。
            // 由于命令是幂等的（位置由起始值 + 偏移决定），
            // 反复执行同一条命令不会累积漂移。
            编辑器.执行并记录(编辑器命令::批量设变换 { 项 });
        }

        UiAction::结束拖动 => {
            拖动.项.clear();
        }

        // ---------------------------------------------------------------
        // 操纵器拖拽事务
        //
        // 三条动作对应一次拖拽的三个时刻：预览（每帧）、提交（松手）、
        // 取消（Escape / 失焦 / 目标失效 / 换工具）。文档侧的三条通道在
        // `editor_core::state` 里，2D 与 3D 共用同一套，因此不会出现
        // "2D 能撤销、3D 不能"这种两套历史的问题。
        // ---------------------------------------------------------------
        UiAction::预览变换 { 项 } => {
            // 预览只改文档内容，不产生撤销记录。
            if 编辑器.预览变换(&项) {
                bevy::log::debug!(
                    "预览变换：{} 个实体，撤销步数={}",
                    项.len(),
                    编辑器.可撤销步数()
                );
            }
        }

        UiAction::提交变换 { 起始, 最终 } => {
            let 起点数 = 编辑器.可撤销步数();
            let 提交了 = 编辑器.提交变换(&起始, &最终);
            let 步数差 = 编辑器.可撤销步数().saturating_sub(起点数);
            // 一次拖拽必须**恰好**一条撤销记录；多出或没有都说明事务出了问题。
            debug_assert!(
                !提交了 || 步数差 <= 1,
                "一次拖拽提交了 {步数差} 条撤销记录，事务被拆碎了"
            );
            if 提交了 {
                bevy::log::debug!("变换提交：{} 个实体，撤销记录 +{步数差}", 最终.len());
            }
        }

        UiAction::取消变换 { 起始 } => {
            编辑器.取消变换(&起始);
        }

        UiAction::从资源创建实体 { 资源, 父实体 } => {
            从资源创建实体(编辑器, &资源, 父实体);
        }

        UiAction::请求重命名资源(_) | UiAction::请求删除资源(_) => {
            // 这两个功能需要"文本输入对话框"与"删除确认对话框"，
            // 本版本未实现。如实记录到控制台，而不是假装成功。
            编辑器.信息(
                "资源重命名/删除对话框尚未实现。\
                 本版本请直接在系统的文件管理器中操作资源文件。",
            );
        }

        // ---------------------------------------------------------------
        // 运行
        // ---------------------------------------------------------------
        UiAction::运行场景 => {
            运行时.启动(&编辑器.会话.文档, &编辑器.注册表);
            let 统计 = 运行时.上次统计.clone();
            编辑器.信息(format!(
                "开始运行：已构建 {} 个实体、{} 个组件、{} 条父子关系",
                统计.实体数, 统计.组件数, 统计.父子关系数
            ));
            if 统计.跳过组件数 > 0 {
                编辑器.警告(format!(
                    "有 {} 个组件未注册被跳过（{}）。它们仍保留在场景文件中，\
                     但运行时不会生效。",
                    统计.跳过组件数,
                    统计.跳过类型.join("、")
                ));
            }
        }

        UiAction::暂停运行 => match 运行时.状态 {
            运行状态::运行中 => {
                运行时.暂停();
                编辑器.信息("已暂停");
            }
            运行状态::已暂停 => {
                运行时.继续();
                编辑器.信息("已继续");
            }
            运行状态::已停止 => {
                编辑器.警告("游戏未在运行，无法暂停");
            }
        },

        UiAction::停止运行 => {
            if 运行时.状态.在运行() {
                运行时.停止();
                编辑器.信息("已停止运行，运行时世界的改动已全部丢弃");
            } else {
                编辑器.警告("游戏未在运行");
            }
        }

        UiAction::单步一帧 => {
            if 运行时.状态 == 运行状态::已暂停 {
                运行时.已推进帧数 += 1;
                编辑器.信息(format!("已单步到第 {} 帧", 运行时.已推进帧数));
            } else {
                编辑器.警告("只有暂停状态下才能单步");
            }
        }

        // ---------------------------------------------------------------
        // 界面（只改界面状态，不碰文档）
        // ---------------------------------------------------------------
        UiAction::聚焦面板(面板) => {
            界面状态.聚焦面板(面板);
            // 面板被加进布局或切到前台，布局内容变了，需要写盘。
            布局待保存.脏 = true;
        }

        UiAction::恢复默认布局 => {
            界面状态.恢复默认布局();
            布局待保存.脏 = true;
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态.工作区.当前().显示名(语言);
            编辑器.结构化信息("log_workspace_reset", vec![日志参数::用户数据(名称)]);
        }

        // ---------------- 工作区 ----------------
        UiAction::切换工作区(id) => {
            let 语言 = 界面状态.语言;
            match 界面状态.工作区.切换(&id) {
                Ok(()) => {
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.工作区.当前().显示名(语言);
                    编辑器
                        .结构化信息("log_workspace_switched", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.错误(错误.文案(语言)),
            }
        }

        UiAction::打开工作区对话框 { 复制当前 } => {
            let 语言 = 界面状态.语言;
            let 默认名 = if 复制当前 {
                语言.填充(
                    "workspace_copy_name",
                    &[&界面状态.工作区.当前().显示名(语言)],
                )
            } else {
                语言.填充("workspace_new_name", &[&(界面状态.工作区.列表().len() + 1)])
            };
            界面状态.工作区对话框 = Some(工作区对话框::新建(复制当前, 默认名));
        }

        UiAction::新建工作区 {
            名称, 复制当前
        } => {
            let 语言 = 界面状态.语言;
            match 界面状态.工作区.新建工作区(&名称, 复制当前, 语言) {
                Ok(_) => {
                    // 成功后关闭对话框：失败时它保持打开并显示原因。
                    界面状态.工作区对话框 = None;
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.工作区.当前().显示名(语言);
                    编辑器.结构化信息("log_workspace_created", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => {
                    let 文案 = 错误.文案(语言);
                    if let Some(对话框状态) = 界面状态.工作区对话框.as_mut() {
                        对话框状态.错误 = Some(文案.clone());
                    }
                    编辑器.警告(文案);
                }
            }
        }

        UiAction::重命名工作区 { id, 新名称 } => {
            let 语言 = 界面状态.语言;
            match 界面状态.工作区.重命名(&id, &新名称, 语言) {
                Ok(()) => {
                    界面状态.工作区对话框 = None;
                    布局待保存.脏 = true;
                    let 名称 = 界面状态
                        .工作区
                        .查找(&id)
                        .map(|项| 项.显示名(语言))
                        .unwrap_or_else(|| 新名称.clone());
                    编辑器.结构化信息("log_workspace_renamed", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => {
                    let 文案 = 错误.文案(语言);
                    if let Some(对话框状态) = 界面状态.工作区对话框.as_mut() {
                        对话框状态.错误 = Some(文案.clone());
                    }
                    编辑器.警告(文案);
                }
            }
        }

        UiAction::删除工作区(id) => {
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态
                .工作区
                .查找(&id)
                .map(|项| 项.显示名(语言))
                .unwrap_or_else(|| id.clone());
            match 界面状态.工作区.删除(&id, 语言) {
                Ok(()) => {
                    界面状态.工作区对话框 = None;
                    布局待保存.脏 = true;
                    编辑器.结构化信息("log_workspace_deleted", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
        }

        UiAction::重置当前工作区 => {
            界面状态.恢复默认布局();
            布局待保存.脏 = true;
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态.工作区.当前().显示名(语言);
            编辑器.结构化信息("log_workspace_reset", vec![日志参数::用户数据(名称)]);
        }

        UiAction::重置全部内置工作区 => {
            let 语言 = 界面状态.语言;
            let 数量 = 界面状态.工作区.重置全部内置();
            布局待保存.脏 = true;
            编辑器.结构化信息(
                "log_workspace_reset_all",
                vec![日志参数::用户数据(数量.to_string())],
            );
            let _ = 语言;
        }

        // ---------------- 主开发模式 ----------------
        UiAction::切换模式(模式) => {
            if 界面状态.模式 == 模式 {
                return;
            }
            match 界面状态.切换模式(模式) {
                Ok(()) => {
                    布局待保存.脏 = true;
                    // 进入脚本模式时把脚本面板切到前台：
                    // 否则用户看到的还是上一次的视口标签，"进了脚本模式却看不到编辑器"。
                    if 模式 == editor_ui::开发模式::脚本 {
                        界面状态.聚焦面板(editor_ui::Tab::脚本);
                    }
                    编辑器.结构化信息(
                        "log_mode_switched",
                        vec![日志参数::用户数据(
                            界面状态.语言.取(模式.名称键()).to_string(),
                        )],
                    );
                }
                Err(错误) => 编辑器.错误(错误),
            }
        }

        UiAction::打开脚本(路径) => {
            let 语言 = 界面状态.语言;
            let Some(项目) = 编辑器.项目.as_ref() else {
                编辑器.警告(语言.取("script_no_project").to_string());
                return;
            };
            let 绝对 = 项目.绝对路径(&路径);
            match std::fs::read_to_string(&绝对) {
                Ok(文本) => {
                    界面状态.脚本.打开(editor_ui::script::脚本文档::新建(
                        Some(路径.clone()),
                        文本,
                    ));
                    // 打开脚本 = 进入脚本模式，并在脚本面板里显示。
                    let _ = 界面状态.切换模式(editor_ui::开发模式::脚本);
                    界面状态.聚焦面板(editor_ui::Tab::脚本);
                    布局待保存.脏 = true;
                    编辑器.结构化信息(
                        "log_script_opened",
                        vec![日志参数::用户数据(路径.文本().to_string())],
                    );
                }
                Err(错误) => 编辑器.错误(语言.填充("script_open_failed", &[&错误.to_string()])),
            }
        }

        UiAction::保存脚本 => {
            let Some(文档) = 界面状态.脚本.文档.clone() else {
                return;
            };
            match 文档.路径.clone() {
                Some(路径) => {
                    let 语言 = 界面状态.语言;
                    保存脚本文本(编辑器, 语言, &路径, &文档.文本);
                }
                None => 请求对话框(
                    对话框,
                    编辑器,
                    文件对话框请求::脚本另存为(文档.文本.clone()),
                ),
            }
            if let Some(路径) = 界面状态
                .脚本
                .文档
                .as_ref()
                .and_then(|文档| 文档.路径.clone())
                && 界面状态
                    .脚本
                    .文档
                    .as_ref()
                    .map(|文档| !文档.有未保存修改())
                    .unwrap_or(false)
            {
                界面状态.脚本.标记已保存(Some(路径));
            }
        }

        UiAction::脚本另存为 => {
            let Some(文档) = 界面状态.脚本.文档.clone() else {
                return;
            };
            请求对话框(
                对话框,
                编辑器,
                文件对话框请求::脚本另存为(文档.文本.clone()),
            );
        }

        // ---------------- 项目运行（独立进程） ----------------
        UiAction::运行项目 => match 启动项目运行(编辑器, 界面状态, 项目运行) {
            Ok(()) => 编辑器.信息("已启动项目运行（独立进程）".to_string()),
            Err(错误) => 编辑器.错误(错误),
        },
        UiAction::重新运行项目 => {
            项目运行.停止();
            match 启动项目运行(编辑器, 界面状态, 项目运行) {
                Ok(()) => 编辑器.信息("已重新启动项目运行".to_string()),
                Err(错误) => 编辑器.错误(错误),
            }
        }
        UiAction::停止项目 => {
            if 项目运行.状态.在运行() {
                项目运行.停止();
                编辑器.信息("已停止项目运行".to_string());
            } else {
                编辑器.警告("当前没有正在运行的项目进程".to_string());
            }
        }

        // ---------------- 视口命令 ----------------
        UiAction::视口适应窗口 => 界面状态.视口命令.适应窗口 = true,
        UiAction::视口重置视图 => 界面状态.视口命令.重置视图 = true,
        UiAction::三维重置轨道 => {
            界面状态.三维相机.重置();
            界面状态.视口命令.重置轨道 = true;
        }
        UiAction::聚焦选中实体 => 界面状态.视口命令.聚焦选中 = true,

        UiAction::浮动面板(面板) => {
            let 语言 = 界面状态.语言;
            if 界面状态.工作区.浮动面板(面板) {
                布局待保存.脏 = true;
                编辑器.结构化信息(
                    "log_panel_floated",
                    vec![日志参数::用户数据(面板.标题(语言).to_string())],
                );
            } else {
                编辑器.警告(语言.填充("panel_cannot_float", &[&面板.标题(语言)]));
            }
        }

        UiAction::停靠全部浮动面板 => {
            let 语言 = 界面状态.语言;
            let 数量 = 界面状态.工作区.停靠全部浮动();
            if 数量 > 0 {
                布局待保存.脏 = true;
            }
            编辑器.结构化信息(
                "log_panels_docked",
                vec![日志参数::用户数据(数量.to_string())],
            );
            let _ = 语言;
        }

        // ---------------- 主题 ----------------
        UiAction::设置主题(id) => {
            let 语言 = 界面状态.语言;
            match 界面状态.主题库.切换(&id) {
                Ok(()) => {
                    // 切主题时丢弃未保存的草稿：否则用户会看到"切了主题但
                    // 颜色还是草稿里的"，而且下一次保存会把草稿写到新主题上。
                    界面状态.主题草稿 = None;
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.主题库.当前().显示名(语言);
                    编辑器.结构化信息("log_theme_switched", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.错误(错误.文案(语言)),
            }
        }

        UiAction::显示主题编辑器(显示) => {
            界面状态.显示主题编辑器 = 显示;
            if 显示 {
                // 打开时从当前主题拷一份草稿，之后所有编辑都只改草稿。
                界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
            } else {
                界面状态.主题草稿 = None;
            }
        }

        UiAction::关闭主题编辑器 => {
            界面状态.显示主题编辑器 = false;
            // 丢弃草稿 = 取消；界面下一帧自动回到主题库里的当前主题。
            界面状态.主题草稿 = None;
        }

        UiAction::保存主题草稿 => {
            let 语言 = 界面状态.语言;
            let Some(草稿) = 界面状态.主题草稿.clone() else {
                return;
            };
            let 名称 = 草稿.显示名(语言);
            match 界面状态.主题库.保存(草稿) {
                Ok(()) => {
                    界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
                    布局待保存.脏 = true;
                    编辑器.结构化信息("log_theme_saved", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
        }

        UiAction::另存为主题 { 名称 } => {
            let 语言 = 界面状态.语言;
            let Some(草稿) = 界面状态.主题草稿.clone() else {
                return;
            };
            match 界面状态.主题库.另存为(草稿, &名称, 语言) {
                Ok(_) => {
                    界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.主题库.当前().显示名(语言);
                    编辑器.结构化信息("log_theme_created", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
        }

        UiAction::删除主题(id) => {
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态
                .主题库
                .按id(&id)
                .map(|主题| 主题.显示名(语言))
                .unwrap_or_else(|| id.clone());
            match 界面状态.主题库.删除(&id, 语言) {
                Ok(()) => {
                    界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
                    布局待保存.脏 = true;
                    编辑器.结构化信息("log_theme_deleted", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
        }

        UiAction::重置内置主题 => {
            let 语言 = 界面状态.语言;
            let id = 界面状态.主题库.当前id().to_string();
            界面状态.主题库.重置内置主题(&id);
            界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
            布局待保存.脏 = true;
            let 名称 = 界面状态.主题库.当前().显示名(语言);
            编辑器.结构化信息("log_theme_reset", vec![日志参数::用户数据(名称)]);
        }

        UiAction::重置全部内置主题 => {
            let 数量 = 界面状态.主题库.重置内置();
            界面状态.主题草稿 = None;
            布局待保存.脏 = true;
            编辑器.结构化信息(
                "log_theme_reset_all",
                vec![日志参数::用户数据(数量.to_string())],
            );
        }

        UiAction::导出主题 => {
            let 语言 = 界面状态.语言;
            let id = 界面状态.主题库.当前id().to_string();
            match 界面状态.主题库.导出(&id) {
                Ok(文本) => 请求对话框(对话框, 编辑器, 文件对话框请求::导出主题(文本)),
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
        }

        UiAction::导入主题 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::导入主题);
        }

        UiAction::设置语言(语言) => {
            if 界面状态.语言 == 语言 {
                return;
            }
            界面状态.语言 = 语言;
            // 语言属于"用户偏好"，要与窗口布局一样写进编辑器配置 ——
            // 否则重启后又会回到中文，用户会以为切换没生效。
            布局待保存.脏 = true;
            编辑器.结构化信息(
                "log_language_changed",
                vec![日志参数::用户数据(语言.自称().to_string())],
            );
        }

        UiAction::清空控制台 => {
            编辑器.清空日志();
        }

        UiAction::显示关于 => {
            界面状态.显示关于 = true;
        }
    }
}

/// 把编辑器控制台里的新日志转发到进程日志（stderr）。
///
/// # 为什么需要这一步
///
/// 编辑器的日志原本只存在内存里，是给「控制台」面板看的。
/// 这带来一个很实际的排查困境：**启动阶段出的错在事后完全查不到** ——
/// 进程退出后内存日志就没了，重定向 stderr 也拿不到任何线索，
/// 只能靠盯着截图里的控制台面板猜。实测中"打开项目后场景是空的"
/// 这个问题就因此查了很久。
///
/// 转发之后 `2> 日志.txt` 就能拿到完整记录，CI 里也能直接断言。
///
/// 用 `Local<usize>` 记住已转发的条数：编辑器日志是只增的 `Vec`，
/// 记下标即可，不必每帧重新扫描全部条目。
pub fn 转发控制台日志到标准错误(
    编辑器: Res<EditorStateHolder>,
    mut 已转发: Local<usize>,
) {
    let 日志 = 编辑器.状态.日志列表();

    // 「清空控制台」会把 Vec 清空，此时游标要跟着归零，
    // 否则新日志会被误判为"已经转发过"而永远不输出。
    if 日志.len() < *已转发 {
        *已转发 = 0;
    }
    if 日志.len() == *已转发 {
        return;
    }

    for 条目 in &日志[*已转发..] {
        match 条目.级别 {
            日志级别::信息 => info!(target: "编辑器控制台", "{}", 条目.诊断文本()),
            日志级别::警告 => warn!(target: "编辑器控制台", "{}", 条目.诊断文本()),
            日志级别::错误 => error!(target: "编辑器控制台", "{}", 条目.诊断文本()),
        }
    }
    *已转发 = 日志.len();
}

/// 示例项目安装根目录的环境变量覆盖（自动验收与自定义位置用）。
pub const 示例安装目录环境变量: &str = "BEVY_STUDIO_DEMO_DIR";

/// 示例项目的安装根目录。
///
/// 默认放在用户配置目录下（<配置目录>/示例项目），**不在仓库里**：
///
/// * 编辑器永远不会往仓库的 examples/ 里写文件；
/// * 用户对示例的任何改动都不会污染源码树，也不会被 git status 抓成噪声；
/// * 卸载或彻底重来只需要删这一个目录。
pub fn 示例安装目录() -> std::path::PathBuf {
    if let Ok(值) = std::env::var(示例安装目录环境变量)
        && !值.trim().is_empty()
    {
        return std::path::PathBuf::from(值);
    }
    crate::config::配置目录().join("示例项目")
}

/// 准备一个示例项目：需要时从模板安装到本地，然后返回可打开的目录。
///
/// 公开是为了让集成测试能**真正**验证"复制到仓库外 → 隐藏模板 → 仍能打开"
/// 这条交付契约（菜单动作本身需要点两下原生菜单，自动化成本高且脆）。
///
/// # 完整契约（这是"示例独立化"的落点）
///
/// 1. **模板发现**（editor_core::模板::发现模板）：
///    环境变量 BEVY_STUDIO_EXAMPLES_DIR → 可执行文件同级 examples/ → 开发期仓库兜底。
///    仓库路径只是**兜底来源之一**，不再是唯一来源，且完全可以用环境变量绕过。
/// 2. **已安装就直接打开**：目标目录里已经有 project.ron 时不再复制，
///    因此用户的修改不会被下一次点击覆盖。
/// 3. **未安装才复制**：目标已存在且非空时 复制模板到 默认**拒绝覆盖**
///    （一个字节都不写），错误信息原样上抛。
/// 4. **资源路径相对项目根**：复制出来的是完整项目目录，ssets/、scenes/
///    都在里面，打开后不依赖任何仓库路径。
///
/// 所以"复制出去之后把原始模板目录藏起来，项目仍然能打开"是这条设计的
/// 必然结果，而不是特例。
pub fn 准备示例项目(
    示例: editor_ui::dev_modes::示例项目,
) -> Result<std::path::PathBuf, String> {
    let 目标 = 示例安装目录().join(示例.目录名());
    // 已经安装过：直接打开，绝不覆盖用户对示例的改动。
    if 目标.join(editor_core::project::项目清单文件名).is_file() {
        return Ok(目标);
    }

    let 模板列表 =
        editor_core::模板::发现模板().map_err(|错误| format!("未找到可用模板：{错误}"))?;
    let 模板 = 模板列表
        .iter()
        .find(|模板| 模板.名称 == 示例.目录名())
        .ok_or_else(|| {
            let 可用: Vec<&str> = 模板列表.iter().map(|项| 项.名称.as_str()).collect();
            format!(
                "模板目录里没有 {}（已发现：{可用:?}；可用环境变量 {} 指定模板目录）",
                示例.目录名(),
                editor_core::模板::模板目录环境变量
            )
        })?;

    if let Some(父) = 目标.parent()
        && let Err(错误) = std::fs::create_dir_all(父)
    {
        return Err(format!("无法创建安装目录 {}：{错误}", 父.display()));
    }

    let 结果 = editor_core::模板::复制模板到(
        &模板.根目录,
        &目标,
        editor_core::模板::复制选项::default(),
    )
    .map_err(|错误| format!("安装示例项目失败：{错误}"))?;
    Ok(结果.目标)
}

/// 把脚本文本写入项目内的相对路径。
fn 保存脚本文本(
    编辑器: &mut 编辑器状态,
    语言: editor_core::i18n::语言,
    路径: &scene_doc::path::项目相对路径,
    文本: &str,
) {
    let Some(项目) = 编辑器.项目.as_ref() else {
        编辑器.警告(语言.取("script_no_project").to_string());
        return;
    };
    let 绝对 = 项目.绝对路径(路径);
    match std::fs::write(&绝对, 文本) {
        Ok(()) => 编辑器.结构化信息(
            "log_script_saved",
            vec![日志参数::用户数据(路径.文本().to_string())],
        ),
        Err(错误) => 编辑器.错误(语言.填充("script_save_failed", &[&错误.to_string()])),
    }
}

