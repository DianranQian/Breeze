//! 编辑域动作（命令执行、撤销重做、属性 / 组件 / 实体编辑、选择与拖动、
//! 操纵器变换事务、场景实例刷新、对齐分布）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;
use bevy::math::{Affine3A, Vec3};
use scene_doc::document::{变换数据, 实体标识};

/// 处理编辑域动作：认领属于本域的 `UiAction`，其余原样交回。
///
/// # 操纵器拖拽事务
///
/// `预览变换` / `提交变换` / `取消变换` 三条动作对应一次拖拽的三个时刻：
/// 预览（每帧）、提交（松手）、取消（Escape / 失焦 / 目标失效 / 换工具）。
/// 文档侧的三条通道在 `editor_core::state` 里，2D 与 3D 共用同一套，
/// 因此不会出现"2D 能撤销、3D 不能"这种两套历史的问题。
///
/// # 世界位移与局部平移
///
/// 视口拖动算出的偏移量在世界空间，而文档里的 `平移` 是相对父级的。
/// 父级带旋转或缩放时，两者不等：`拖动实体到` 先经
/// `editor_ui::world_space::拖拽局部位移` 换算，再写回文档；
/// 父子同时被选中时，子级的位移由祖先带动，不再重复写一遍。
///
/// 返回 `Err(动作)` 表示这条动作不属于编辑域；
/// 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
pub(super) fn 处理编辑动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;
    let 拖动 = &mut *上下文.拖动;

    match 动作 {
        UiAction::执行命令(命令) => {
            // 会产生新实体的命令走 `执行并选中`，其余走普通路径。
            //
            // 不这样做会出现一个很别扭的体验：点"新建实体"之后场景树里
            // 多了一项，但检查器仍然显示"未选中任何实体"，用户必须再点
            // 一次才能编辑它。
            //
            // 只对会新建实体的命令选中、而不是对所有命令都选中，是因为
            // 删除、重命名这类命令顺手改变选择会让用户困惑 ——
            // 删掉一个东西之后不应该自动选中别的东西。
            if matches!(
                命令,
                编辑器命令::新建实体 { .. } | 编辑器命令::创建预制件实例 { .. }
            ) {
                if let Err(错误) = 编辑器.执行并选中(命令) {
                    编辑器.错误(format!("操作失败：{错误}"));
                }
            } else {
                编辑器.执行并记录(命令);
            }
            Ok(())
        }

        UiAction::执行命令连续(命令) => {
            编辑器.执行并记录连续(命令);
            Ok(())
        }

        UiAction::撤销 => {
            编辑器.撤销一步();
            Ok(())
        }

        UiAction::重做 => {
            编辑器.重做一步();
            Ok(())
        }

        UiAction::修改属性(编辑请求) => {
            编辑器.设属性(编辑请求.实体, 编辑请求.组件, 编辑请求.属性, 编辑请求.新值);
            Ok(())
        }

        UiAction::添加组件 { 实体, 类型名 } => {
            let 组件 = 构造默认组件(编辑器, &类型名);
            match 组件 {
                Some(组件) => {
                    编辑器.添加组件(实体, 组件);
                }
                None => {
                    编辑器.错误(format!("组件 `{类型名}` 未注册，无法添加"));
                }
            }
            Ok(())
        }

        UiAction::删除组件 { 实体, 类型名 } => {
            编辑器.删除组件(实体, 类型名);
            Ok(())
        }

        UiAction::删除实体(标识) => {
            编辑器.删除实体(标识);
            Ok(())
        }

        UiAction::复制实体(标识) => {
            if let Some(结果) = 编辑器.执行并记录(编辑器命令::新建实体 {
                名称: 编辑器
                    .会话
                    .文档
                    .取(标识)
                    .map(|实体| format!("{}_副本", 实体.名称))
                    .unwrap_or_else(|| "副本".to_string()),
                父实体: 编辑器.会话.文档.取(标识).and_then(|实体| 实体.父实体),
                指定标识: None,
            }) {
                // 把源实体的组件也复制过来。
                if let (Some(新标识), Some(源)) = (结果.新实体, 编辑器.会话.文档.取(标识).cloned())
                {
                    for 组件 in 源.组件 {
                        编辑器.添加组件(新标识, 组件);
                    }
                    编辑器.选择.单选(新标识);
                }
            }
            Ok(())
        }

        UiAction::重命名实体 { 标识, 新名称 } => {
            编辑器.重命名实体(标识, 新名称);
            Ok(())
        }

        UiAction::选择(意图) => {
            eprintln!(
                "[诊断] 执行选择动作 {:?}（之前 {} 项）",
                意图,
                编辑器.选择.数量()
            );
            应用选择意图(&mut 编辑器.选择, 意图);
            Ok(())
        }
        UiAction::开始拖动实体 {
            实体,
            追加选择,
            按下世界,
        } => {
            if 追加选择 {
                应用选择意图(&mut 编辑器.选择, 选择意图::追加(实体));
            } else if !编辑器.选择.包含(实体) {
                // 只在点到的实体尚未被选中时才改选择：
                // 这样"拖动已选中的多个实体之一"不会把多选打散成单选。
                应用选择意图(&mut 编辑器.选择, 选择意图::单选(实体));
            }
            // 记录所有选中实体在按下那一刻的变换。
            拖动.项 = 编辑器
                .选择
                .全部()
                .into_iter()
                .filter_map(|标识| {
                    编辑器
                        .会话
                        .文档
                        .取(标识)
                        .and_then(|实体| 实体.变换)
                        .map(|变换| (标识, 变换))
                })
                .collect();
            bevy::log::debug!(
                "开始拖动 {} 个实体，按下世界坐标 ({:.2}, {:.2})",
                拖动.项.len(),
                按下世界.0,
                按下世界.1
            );
            Ok(())
        }
        UiAction::拖动实体到 { 世界偏移 } => {
            if 拖动.项.is_empty() {
                return Ok(());
            }
            // 以拖动开始时的位置为基准加上偏移，整批实体一条命令提交。
            // 用批量命令而不是逐个 `设变换`，是为了让整次拖动只占一个撤销步。
            let 项: Vec<_> = {
                let 选中 = 编辑器.选择.全部();
                let 世界 = editor_ui::world_space::世界空间::新建(
                    &编辑器.会话.文档,
                    上下文.世界逆矩阵,
                );
                拖动
                    .项
                    .iter()
                    .map(|(标识, 起始)| {
                        let 位移 = editor_ui::world_space::拖拽局部位移(
                            *标识,
                            (世界偏移.0, 世界偏移.1, 0.0),
                            &选中,
                            世界,
                        );
                        let mut 新变换 = *起始;
                        新变换.平移.0 = 起始.平移.0 + 位移.0;
                        新变换.平移.1 = 起始.平移.1 + 位移.1;
                        新变换.平移.2 = 起始.平移.2 + 位移.2;
                        (*标识, Some(新变换))
                    })
                    .collect()
            };
            // 拖动过程中的每一步都提交会污染撤销栈，因此这里**不**记为
            // 独立的历史步骤：靠 `结束拖动` 时的一次提交收尾。
            // 由于命令是幂等的（位置由起始值 + 偏移决定），
            // 反复执行同一条命令不会累积漂移。
            编辑器.执行并记录(编辑器命令::批量设变换 { 项 });
            Ok(())
        }
        UiAction::结束拖动 => {
            拖动.项.clear();
            Ok(())
        }
        UiAction::预览变换 { 项 } => {
            // 预览只改文档内容，不产生撤销记录。
            if 编辑器.预览变换(&项) {
                bevy::log::debug!(
                    "预览变换：{} 个实体，撤销步数={}",
                    项.len(),
                    编辑器.可撤销步数()
                );
            }
            Ok(())
        }
        UiAction::提交变换 { 起始, 最终 } => {
            let 起点数 = 编辑器.可撤销步数();
            let 提交了 = 编辑器.提交变换(&起始, &最终);
            let 步数差 = 编辑器.可撤销步数().saturating_sub(起点数);
            // 一次拖拽必须**恰好**一条撤销记录；多出或没有都说明事务出了问题。
            debug_assert!(
                !提交了 || 步数差 <= 1,
                "一次拖拽提交了 {步数差} 条撤销记录，事务被拆碎了"
            );
            if 提交了 {
                bevy::log::debug!("变换提交：{} 个实体，撤销记录 +{步数差}", 最终.len());
            }
            Ok(())
        }
        UiAction::取消变换 { 起始 } => {
            编辑器.取消变换(&起始);
            Ok(())
        }
        UiAction::从资源创建实体 { 资源, 父实体 } => {
            从资源创建实体(编辑器, &资源, 父实体);
            Ok(())
        }
        UiAction::更改实体父级 {
            实体, 新父实体
        } => {
            保持世界变换的层级拖动(编辑器, 上下文.世界变换, 实体, 新父实体);
            Ok(())
        }
        UiAction::刷新场景实例 => {
            let Some(选中) = 编辑器.选择.主选中() else {
                编辑器.警告("请先选中一个场景实例".to_string());
                return Ok(());
            };
            let 来源 = 编辑器
                .会话
                .文档
                .取(选中)
                .and_then(editor_core::instance::实例来源)
                .map(str::to_string);
            let Some(来源) = 来源 else {
                编辑器.警告("选中的实体不是场景实例（没有「场景实例」组件）".to_string());
                return Ok(());
            };
            let Ok(源路径) = scene_doc::path::项目相对路径::解析(&来源) else {
                编辑器.警告(format!("来源路径不合法：{来源}"));
                return Ok(());
            };
            let Some(项目) = 编辑器.项目.clone() else {
                编辑器.警告("没有打开的项目".to_string());
                return Ok(());
            };
            let 源文档 = match 项目.读取场景(&源路径) {
                Ok(读取) => 读取.文档,
                Err(错误) => {
                    编辑器.错误(format!("读取源场景失败：{错误}"));
                    return Ok(());
                }
            };
            // 在克隆上改，成功才提交成一条 `设为快照` 命令：
            // 刷新是整棵子树的替换，用快照命令撤销恰好一步。
            let mut 文档 = 编辑器.会话.文档.clone();
            match editor_core::instance::刷新实例(&mut 文档, 选中, &源路径, &源文档) {
                Some(结果) => {
                    let 根 = 结果.根实体;
                    if 编辑器
                        .执行并记录(editor_core::command::编辑器命令::设为快照 {
                            文档: Box::new(文档),
                        })
                        .is_some()
                    {
                        if let Some(根) = 根 {
                            编辑器.选择.单选(根);
                        }
                        编辑器.信息(format!("已从 {} 刷新场景实例", 源路径.文本()));
                    }
                }
                None => {
                    编辑器.警告("刷新失败：源场景为空或该实体已不是实例".to_string());
                }
            }
            Ok(())
        }
        UiAction::对齐选中 { 边 } => {
            对齐或分布选中(
                编辑器,
                上下文.世界变换,
                上下文.世界逆矩阵,
                对齐请求::对齐(边),
            );
            Ok(())
        }
        UiAction::分布选中 { 轴 } => {
            对齐或分布选中(
                编辑器,
                上下文.世界变换,
                上下文.世界逆矩阵,
                对齐请求::分布(轴),
            );
            Ok(())
        }

        其他 => Err(其他),
    }
}

/// 把实体挂到新父级下，同时保持它的世界变换不变。
///
/// # 数学
///
/// 新局部 = 新父级世界变换⁻¹ × 实体旧世界变换。
/// 两个世界变换都直接读 [`预览世界变换快照`]，父链上的旋转、缩放与嵌套
/// 已经包含在内，这里不做任何手写矩阵累加。根实体的父级世界变换取单位阵。
///
/// # 剪切
///
/// `Affine3A::to_scale_rotation_translation` 在父级非均匀缩放时会丢掉
/// 剪切分量。`变换数据` 只有平移、旋转、缩放三个分量，无法表达剪切，
/// 因此结果是这套表达能力内最接近的变换 —— 与旋转/缩放操纵器同一口径。
///
/// # 快照缺失
///
/// 实体或新父级没有世界变换时**拒绝执行**并写入控制台，而不是保留旧局部
/// 变换：后者正是用户最怕的换父级后瞬移。拒绝时文档不变、撤销栈不增加。
///
/// [`预览世界变换快照`]: crate::preview::预览世界变换快照
fn 保持世界变换的层级拖动(
    编辑器: &mut 编辑器状态,
    世界变换: &editor_ui::state::世界变换表,
    实体: 实体标识,
    新父实体: Option<实体标识>,
) {
    let Some(旧世界) = 世界变换.get(&实体).copied() else {
        编辑器.错误("层级拖动失败：预览尚未提供该实体的世界变换".to_string());
        return;
    };
    let 新父世界 = match 新父实体 {
        Some(父) => match 世界变换.get(&父).copied() {
            Some(变换) => 变换,
            None => {
                编辑器.错误("层级拖动失败：预览尚未提供新父级的世界变换".to_string());
                return;
            }
        },
        None => 变换数据::单位(),
    };

    let 新局部 = 仿射矩阵(新父世界).inverse() * 仿射矩阵(旧世界);
    if !新局部.is_finite() {
        编辑器.错误("层级拖动失败：新父级的世界变换不可逆".to_string());
        return;
    }
    let (缩放, 旋转, 平移) = 新局部.to_scale_rotation_translation();
    编辑器.执行并记录(编辑器命令::更改实体父级 {
        标识: 实体,
        新父实体,
        新变换: Some(变换数据 {
            平移: (平移.x, 平移.y, 平移.z),
            旋转: (旋转.x, 旋转.y, 旋转.z, 旋转.w),
            缩放: (缩放.x, 缩放.y, 缩放.z),
        }),
    });
}

/// `变换数据` → Bevy 仿射矩阵，用于世界空间里的父子变换反解。
fn 仿射矩阵(变换: 变换数据) -> Affine3A {
    Affine3A::from_scale_rotation_translation(
        Vec3::new(变换.缩放.0, 变换.缩放.1, 变换.缩放.2),
        bevy::math::Quat::from_xyzw(变换.旋转.0, 变换.旋转.1, 变换.旋转.2, 变换.旋转.3),
        Vec3::new(变换.平移.0, 变换.平移.1, 变换.平移.2),
    )
}
