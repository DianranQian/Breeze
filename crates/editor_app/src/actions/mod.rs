/// 请求弹出文件对话框。
fn 请求对话框(
    对话框: &mut 文件对话框通道, 编辑器: &mut 编辑器状态, 请求: 文件对话框请求
) {
    if 对话框.处理中 {
        编辑器.警告("已有文件对话框在处理中，请先完成上一个");
        return;
    }
    match 对话框.请求发送端.send(请求) {
        Ok(()) => 对话框.处理中 = true,
        Err(错误) => {
            编辑器.错误(format!("无法打开文件对话框：{错误}"));
        }
    }
}

/// 按注册表构造一个组件的默认实例数据。
///
/// 属性取注册表里声明的默认值，因此"添加组件"得到的永远是一份合法数据，
/// 而不是空属性表 —— 后者在 Inspector 里会显示成一堆空字段。
fn 构造默认组件(
    编辑器: &编辑器状态,
    类型名: &str,
) -> Option<scene_doc::document::组件数据> {
    let 类型 = 编辑器.注册表.查询(类型名)?;
    let mut 属性 = std::collections::BTreeMap::new();
    for 描述 in 类型.字段描述() {
        属性.insert(描述.字段名.clone(), 描述.默认值.clone());
    }
    Some(scene_doc::document::组件数据::新建(类型名, 属性))
}

/// 从资源创建一个实体。
///
/// 按资源类别决定挂什么组件：
/// * 图片 → `Sprite`，并自动取图片尺寸填进 `自定义尺寸`；
/// * 其余类别 → 只建一个空实体并在日志里说明尚未支持，
///   而不是悄悄建个空实体让用户以为成功了。
fn 从资源创建实体(
    编辑器: &mut 编辑器状态,
    资源: &scene_doc::path::项目相对路径,
    父实体: Option<scene_doc::document::实体标识>,
) {
    use scene_doc::property::资源类别;

    let 类别 = 资源
        .扩展名()
        .map(|扩展| 资源类别::由扩展名推断(&扩展))
        .unwrap_or(资源类别::其他);

    let 名称 = 资源
        .文件名()
        .rsplit_once('.')
        .map(|(基名, _)| 基名.to_string())
        .unwrap_or_else(|| 资源.文件名().to_string());

    let Some(标识) = 编辑器.新建实体(名称.clone(), 父实体) else {
        编辑器.错误("创建实体失败");
        return;
    };

    match 类别 {
        资源类别::图片 => {
            let Some(mut 组件) = 构造默认组件(编辑器, "Sprite") else {
                return;
            };
            组件.属性.insert(
                "贴图".to_string(),
                属性值::资源(资源引用值::按路径(资源.clone())),
            );
            // 读图片真实尺寸，让视口与运行时都用正确的包围盒。
            // 读不到就地说明，而不是猜一个尺寸。
            match 读取图片尺寸(编辑器, 资源) {
                Some((宽, 高)) => {
                    组件
                        .属性
                        .insert("自定义尺寸".to_string(), 属性值::二维(宽, 高));
                    编辑器.添加组件(标识, 组件);
                    编辑器.信息(format!("已从 {} 创建精灵（{}×{}）", 资源.文本(), 宽, 高));
                }
                None => {
                    编辑器.添加组件(标识, 组件);
                    编辑器.警告(format!(
                        "已从 {} 创建精灵，但无法读取图片尺寸，\
                         视口将按默认尺寸显示。请确认文件是有效的图片。",
                        资源.文本()
                    ));
                }
            }
        }
        // 刻意不写 `其他 =>`：`资源类别` 里正好有一个同名变体 `其他`，
        // 那样写会被解析成"绑定任意值到叫 `其他` 的变量"，
        // 而不是"匹配 `其他` 这个变体"（`bindings_with_variant_name` 会拒绝）。
        非图片类别 => {
            编辑器.信息(format!(
                "已创建实体 `{名称}`，但尚未为 {} 类资源实现自动组件（{}）。\
                 请手工添加需要的组件。",
                // 这条消息整体仍是中文，等日志结构化那一批再一起本地化；
                // 这里显式用中文渲染，行为与改造前完全一致。
                editor_core::i18n::语言::中文.取(非图片类别.词条键()),
                资源.文本()
            ));
        }
    }
}

/// 读取图片资源的像素尺寸。
fn 读取图片尺寸(
    编辑器: &编辑器状态,
    资源: &scene_doc::path::项目相对路径,
) -> Option<(f32, f32)> {
    let 项目 = 编辑器.项目.as_ref()?;
    let 绝对 = 项目.绝对路径(资源);
    let 图片 = image::ImageReader::open(&绝对).ok()?.decode().ok()?;
    Some((图片.width() as f32, 图片.height() as f32))
}

/// 推进运行时世界。
///
/// 当前运行时世界只承载"场景被正确构建"这一事实与统计数据；
/// 它还没有自己的系统与渲染（那属于里程碑 C/E 的后续工作）。
/// 这里诚实地统计帧数与耗时，不假装在跑一个完整游戏循环。
pub fn 推进运行时(
    mut 运行时: ResMut<运行时宿主>,
    mut 物理: ResMut<crate::physics_runtime::物理运行时状态>,
    mut 编辑器资源: ResMut<EditorStateHolder>,
    时间: Res<Time>,
) {
    if !运行时.状态.在运行() {
        return;
    }

    运行时.上一帧毫秒 = 时间.delta_secs() * 1000.0;
    if 运行时.状态 == 运行状态::运行中 {
        运行时.已推进帧数 += 1;
    }

    // 物理只在"运行中"步进：暂停时冻结（Godot 的暂停语义也是如此）。
    if 运行时.状态 != 运行状态::运行中 {
        return;
    }
    let Some(物理世界) = 物理.当前.as_mut() else {
        return;
    };
    物理世界.推进(时间.delta_secs());
    if let Some(世界) = 运行时.世界.as_mut() {
        物理世界.写回(世界);
    }
    // 碰撞/触发器事件进控制台：这是"运行调试"链路里最基本的一环。
    for 事件 in 物理世界.取出事件() {
        match 事件 {
            crate::physics_runtime::物理事件::开始接触 {
                甲, 乙, 传感器
            } => {
                if 传感器 {
                    编辑器资源.状态.结构化信息(
                        "log_physics_sensor_entered",
                        vec![日志参数::用户数据(甲), 日志参数::用户数据(乙)],
                    );
                } else {
                    编辑器资源.状态.结构化信息(
                        "log_physics_collision_started",
                        vec![日志参数::用户数据(甲), 日志参数::用户数据(乙)],
                    );
                }
            }
            crate::physics_runtime::物理事件::结束接触 { 甲, 乙 } => {
                编辑器资源.状态.结构化信息(
                    "log_physics_collision_stopped",
                    vec![日志参数::用户数据(甲), 日志参数::用户数据(乙)],
                );
            }
        }
    }
}

/// 推进动画预览的时间。
///
/// # 为什么动画时间是"文档之外"的状态
///
/// 播放时看着物体在动，但保存下来的场景文件里**没有中间帧** ——
/// 动画数据只在动画文档里（关键帧），运行时的姿态是每帧求值出来的。
/// 这条边界与 Godot 的 `AnimationMixer` 一致：混音器不改场景树，
/// 它每帧把求值结果写进节点；编辑器的"场景文件"里永远是原始姿态。
pub fn 推进动画播放(
    时间: Res<Time>,
    mut 编辑器: ResMut<EditorStateHolder>,
    mut 界面: ResMut<UiStateHolder>,
) {
    if !编辑器.状态.动画播放.播放中 {
        return;
    }
    let Some((时长, 循环)) = 编辑器
        .状态
        .动画
        .as_ref()
        .map(|会话| (会话.文档.时长, 会话.文档.循环))
    else {
        return;
    };
    let 旧时间 = 编辑器.状态.动画播放.时间;
    let 帧间隔 = 时间.delta_secs().min(0.1);
    let 新时间 = 编辑器.状态.动画播放.推进(时长, 循环, 帧间隔);

    // ---- 事件触发 ----
    //
    // 时间倒退（用户刚把播放头往回拖）不触发：那不是"播放跨过"。
    if 新时间 <= 旧时间 {
        return;
    }
    let 触发 = match 编辑器.状态.动画.as_ref() {
        Some(会话) => 会话.文档.区间事件(旧时间, 新时间),
        None => return,
    };
    if 触发.is_empty() {
        return;
    }
    let 语言 = 界面.状态.语言;
    for 事件 in 触发 {
        编辑器.状态.结构化信息(
            "log_anim_event_fired",
            vec![日志参数::用户数据(事件.摘要(语言))],
        );
        if 事件.类型 != editor_core::animation::事件类型::音效 {
            continue;
        }
        // 音效事件在编辑器里**真的播放**：不然用户只能靠猜。
        // 名称既可以是项目相对路径，也可以只是资源名。
        let 候选 = scene_doc::path::项目相对路径::解析(&事件.名称)
            .ok()
            .filter(|路径| {
                编辑器
                    .状态
                    .项目
                    .as_ref()
                    .is_some_and(|项目| 项目.绝对路径(路径).is_file())
            });
        match 候选 {
            Some(路径) => {
                界面.状态.试听请求 = editor_ui::state::试听请求 {
                    要播放: Some(路径),
                    要停止: false,
                };
            }
            None => {
                编辑器.状态.警告(format!(
                    "动画事件「{}」是音效类型，但找不到对应的项目内音频文件",
                    事件.名称
                ));
            }
        }
    }
}

/// 轮询构建进程，把新日志行写进控制台。
///
/// 日志走 `编辑器.状态` 而不是直接 eprintln：这样它们出现在控制台面板里，
/// 与场景编辑、运行日志在同一个地方，用户不需要在两个窗口之间对照。
pub fn 轮询构建(
    mut 构建: ResMut<crate::build::构建宿主>,
    mut 编辑器: ResMut<EditorStateHolder>,
) {
    let 日志 = 构建.轮询();
    for 行 in 日志 {
        编辑器.状态.信息(行);
    }
}

/// 把"配置 + 报告"同步成界面可读的快照。
///
/// 配置来自项目清单（权威），报告来自构建宿主（权威），
/// 界面只读这份快照。这样界面层永远不需要认识 `构建宿主` 的线程与管道。
pub fn 同步构建快照(
    编辑器: Res<EditorStateHolder>,
    构建: Res<crate::build::构建宿主>,
    mut 快照: ResMut<crate::plugin::构建快照资源>,
    mut 诊断: ResMut<crate::diagnostics::诊断中心>,
) {
    let 配置 = 编辑器
        .状态
        .项目
        .as_ref()
        .and_then(|项目| 项目.清单().构建.clone())
        .unwrap_or_default();
    if 快照.快照.配置 != 配置 {
        快照.快照.配置 = 配置;
    }
    // 统一诊断：每次构建报告有变化就增量采集一次。
    // 采集放在这里（而不是另起一个系统）是因为"报告变化"这件事
    // 已经在这里被判断过一次了，再判断一次只是多一次比较。
    诊断.采集构建(构建.报告(), Some(&快照.快照.配置), 构建.修订());
    // 修订号没变就不克隆：诊断里有几十个字符串，
    // 每帧克隆在 60 FPS 下是每秒几 MB 的无谓分配。
    if 快照.报告修订 != 构建.修订() {
        快照.快照.报告 = 构建.报告().clone();
        快照.报告修订 = 构建.修订();
    }
}

/// 运行入口在用户偏好里的键。
///
/// 键里带**规范化后的项目路径**：同一台机器上会打开多个项目，
/// 每个项目的运行入口必须互不影响。
pub fn 运行入口偏好键(项目根: &std::path::Path) -> String {
    format!("run_entry::{}", editor_ui::agent::规范化项目路径(项目根))
}

/// 打开项目后恢复"上次用的运行入口"。
///
/// # 失效入口的处理
///
/// 用户删掉 `[[bin]] server` 之后，偏好里记的入口就不存在了。
/// 这里**回退到默认目标并明确告知**，绝不静默替换 ——
/// 静默替换会让用户以为自己在跑 `server`，实际跑的是 `my_game`。
pub fn 恢复运行入口(编辑器: &mut 编辑器状态, 配置: &mut 编辑器配置资源) {
    let Some(项目) = 编辑器.项目.as_mut() else {
        return;
    };
    if 项目.类型() != editor_core::project::项目类型::原生Cargo {
        return;
    }
    let 键 = 运行入口偏好键(项目.根目录());
    let Some(文本) = 配置.0.偏好.get(&键).cloned() else {
        return;
    };
    let Some(入口) = editor_core::run_entry::运行入口::反序列化(&文本) else {
        配置.0.偏好.remove(&键);
        编辑器.结构化警告("log_run_entry_preference_corrupt", Vec::new());
        return;
    };
    let 说明 = 入口.标识();
    match 项目.设置运行入口(入口) {
        Ok(()) => 编辑器.结构化信息("log_run_entry_restored", vec![日志参数::用户数据(说明)]),
        Err(错误) => {
            配置.0.偏好.remove(&键);
            let _ = 项目.重新识别();
            编辑器.结构化警告(
                "log_run_entry_expired",
                vec![日志参数::用户数据(错误.to_string())],
            );
        }
    }
}

/// 系统：消费「构建并运行」的一次性意图。
///
/// 只有**真实构建成功**（退出码 0、状态为成功）才启动游戏。
/// 把"构建成功"当成"游戏跑起来了"是明确禁止的误解：
/// 这里只是启动进程，运行是否成功由运行管理器按真实退出码判断。
pub fn 构建完成后启动运行(
    mut 界面: ResMut<UiStateHolder>,
    mut 编辑器: ResMut<EditorStateHolder>,
    构建: Res<crate::build::构建宿主>,
    mut 项目运行: ResMut<crate::run::项目运行管理器>,
    mut 调试: ResMut<crate::debug_bridge::运行时调试管理器>,
) {
    if !界面.状态.构建后启动 {
        return;
    }
    if 构建.在运行() {
        return;
    }
    // 意图只消费一次：无论成功还是失败都要清掉。
    界面.状态.构建后启动 = false;
    match 构建.报告().状态 {
        editor_core::build::构建状态::成功 => {
            match 启动项目运行(&mut 编辑器.状态, &界面.状态, &mut 项目运行, &mut 调试)
            {
                Ok(()) => {}
                Err(错误) => 编辑器.状态.错误(错误),
            }
        }
        editor_core::build::构建状态::失败 => {
            编辑器.状态.结构化错误(
                "log_run_after_build_failed",
                vec![日志参数::用户数据(
                    "构建失败，未启动运行".to_string(),
                )],
            );
        }
        // 空闲/取消：没有可用的构建结果，不启动。
        _ => {}
    }
}

/// 把动画求值结果覆盖到预览实体的变换上。
///
/// # 为什么覆盖预览实体而不是场景文档
///
/// 播放动画时物体必须在动，但**保存下来的场景文件里不能有中间帧**：
/// 否则用户播放一次动画、保存一次场景，场景里的实体就被"烤"成了某一帧。
/// 这里只改 `Transform` 组件（渲染用的投影），文档一字未动 ——
/// 与 Godot 的 `AnimationMixer` 边界一致：混音器每帧写节点属性，
/// 编辑器文档里保留的是原始姿态。
///
/// # 什么时候生效
///
/// 只在"动画存在且（正在播放 或 播放头不在 0）"时覆盖：
/// * 刚新建动画、播放头还在 0 且暂停时，用户应该看到**文档姿态**，
///   否则他会以为自己刚才的拖拽没生效；
/// * 一旦播放或拖动播放头，动画接管显示 —— 这是时间轴应有的行为。
///
/// 停止播放（回到 0 秒）会自然恢复文档姿态，不需要额外的"还原"逻辑。
///
/// # 为什么放在 `actions` 而不是 `preview`
///
/// 它是"动作/播放状态 → 渲染投影"的最后一步，与 `推进动画播放` 是同一个
/// 数据流；而 `preview` 负责文档 → 实体的静态投影。分开之后，
/// 动画相关的一切都集中在动作层，预览层不需要知道时间轴的存在。
pub fn 应用动画预览(
    编辑器: Res<EditorStateHolder>,
    mut 预览查询: Query<
        (&crate::preview::预览来源, &mut Transform),
        With<crate::preview::预览实体>,
    >,
) {
    let 状态 = &编辑器.状态.动画播放;
    if 编辑器.状态.动画.is_none() {
        return;
    }
    if !状态.播放中 && 状态.时间 <= f32::EPSILON {
        return;
    }
    let 求值 = 编辑器.状态.动画求值();
    if 求值.is_empty() {
        return;
    }
    let 表: std::collections::HashMap<
        scene_doc::document::实体标识,
        scene_doc::document::变换数据,
    > = 求值.into_iter().collect();
    for (来源, mut 变换) in &mut 预览查询 {
        if let Some(项) = 表.get(&来源.0) {
            *变换 = crate::preview::变换转预览(*项);
        }
    }
}

/// 把资源导入状态同步成界面可读的快照。
///
/// 只在"换了项目"或"被标记需要刷新"（导入动作、资源删除、打开项目）时
/// 才真正扫盘：`扫描导入` 要遍历资源目录并读每个文件的元数据，
/// 每帧做一次会让大项目在纯绘制上掉帧。
pub fn 同步导入快照(
    编辑器: Res<EditorStateHolder>,
    mut 快照: ResMut<crate::plugin::导入快照资源>,
) {
    let 项目根 = 编辑器
        .状态
        .项目
        .as_ref()
        .map(|项目| 项目.根目录().to_path_buf());
    if !快照.需刷新 && 快照.最近项目根 == 项目根 {
        return;
    }
    快照.需刷新 = false;
    快照.最近项目根 = 项目根;

    let Some(项目) = 编辑器.状态.项目.as_ref() else {
        快照.状态表.clear();
        快照.摘要.clear();
        return;
    };
    let 清单 = 项目.读取导入清单();
    let 报告 = 项目.扫描导入(&清单);
    快照.状态表 = 报告
        .项
        .iter()
        .map(|项| (项.路径.文本().to_string(), 项.状态))
        .collect();
    快照.摘要 = 报告.摘要();
}

/// 收集运行时诊断信息，供界面显示。
pub fn 收集运行时诊断(
    运行时: Res<运行时宿主>,
    mut 诊断: ResMut<诊断资源>,
    编辑器: Res<EditorStateHolder>,
) {
    let 帧耗时 = 运行时.上一帧毫秒;
    诊断.0 = editor_ui::运行时诊断 {
        帧率: if 帧耗时 > 0.0 {
            1000.0 / 帧耗时
        } else {
            0.0
        },
        帧耗时毫秒: 帧耗时,
        实体总数: 运行时.运行时实体数(),
        组件类型数: 运行时.运行时组件类型数(),
        资源数: 编辑器
            .状态
            .项目
            .as_ref()
            .map(|项目| 项目.资源列表().len())
            .unwrap_or(0),
        已运行秒数: 运行时.已运行秒数(),
    };
}

