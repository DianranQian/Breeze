/// 把当前项目记进"最近项目"并同步界面状态。
///
/// # 为什么配置与界面状态必须一起改
///
/// 配置是持久化真相（写盘后重启仍在），界面状态是**本帧菜单要显示的那份**。
/// 只改一边的表现是：菜单里看不到刚打开的项目，或者重启后列表回退。
/// 因此这里只提供这一个入口，两处同时更新。
fn 记最近项目(
    编辑器: &编辑器状态,
    界面状态: &mut 界面状态,
    配置: &mut 编辑器配置资源,
    布局待保存: &mut 布局待保存,
) {
    let Some(项目) = 编辑器.项目.as_ref() else {
        return;
    };
    if 配置.0.记录最近项目(项目.根目录()) {
        布局待保存.脏 = true;
    }
    界面状态.最近项目 = 配置.0.最近项目列表.clone();
}

/// 打开一条诊断/日志指向的源码位置，并让脚本面板滚到对应行。///
/// 三个来源共用它：构建诊断、运行日志、场景校验问题。
/// 因此"定位到源码"只有一种行为，不会出现"构建面板能跳、控制台不能跳"。
pub fn 打开源码位置(
    编辑器: &mut 编辑器状态,
    界面状态: &mut 界面状态,
    文件: Option<&Path>,
    行: u32,
) {
    let Some(文件) = 文件 else {
        编辑器.警告(界面状态.语言.取("log_diagnostic_no_file").to_string());
        return;
    };
    // 诊断里的路径可能是相对的（rustc 对项目内文件给相对路径），
    // 相对路径必须相对**项目根**解析，而不是编辑器进程的工作目录。
    let 绝对 = if 文件.is_absolute() {
        文件.to_path_buf()
    } else {
        match 编辑器.项目.as_ref() {
            Some(项目) => 项目.根目录().join(文件),
            None => 文件.to_path_buf(),
        }
    };
    let 文本 = match std::fs::read_to_string(&绝对) {
        Ok(文本) => 文本,
        Err(错误) => {
            编辑器.错误(format!("无法打开 {}：{错误}", 绝对.display()));
            return;
        }
    };
    let 相对 = 编辑器.项目.as_ref().and_then(|项目| 项目.相对路径(&绝对));
    // 行号校验：诊断里的行号来自构建输出，可能与磁盘上的文件不一致
    // （用户改完代码没重新构建、或点的是旧日志）。越界不该跳到一个
    // 空位置让人以为"跳转坏了"，而应夹到有效范围并说明原因。
    let 总行数 = 文本.lines().count().max(1) as u32;
    let 目标行 = if 行 == 0 {
        编辑器.警告(format!(
            "诊断没有给出行号，已跳到 {} 的开头",
            绝对.display()
        ));
        1
    } else if 行 > 总行数 {
        编辑器.警告(format!(
            "行号 {行} 超出 {} 的范围（共 {总行数} 行），已跳到末行",
            绝对.display()
        ));
        总行数
    } else {
        行
    };
    界面状态
        .脚本
        .打开(editor_ui::script::脚本文档::新建(相对, 文本));
    界面状态.脚本.滚动到行 = Some(目标行.saturating_sub(1) as usize);
    界面状态.聚焦面板(editor_ui::Tab::脚本);
    编辑器.结构化信息(
        "log_diagnostic_opened",
        vec![
            日志参数::用户数据(绝对.display().to_string()),
            日志参数::用户数据(行.to_string()),
        ],
    );
}

/// 把编辑器控制台里的新日志转发到进程日志（stderr）。
///
/// # 为什么需要这一步
///
/// 编辑器的日志原本只存在内存里，是给「控制台」面板看的。
/// 这带来一个很实际的排查困境：**启动阶段出的错在事后完全查不到** ——
/// 进程退出后内存日志就没了，重定向 stderr 也拿不到任何线索，
/// 只能靠盯着截图里的控制台面板猜。实测中"打开项目后场景是空的"
/// 这个问题就因此查了很久。
///
/// 转发之后 `2> 日志.txt` 就能拿到完整记录，CI 里也能直接断言。
///
/// 用 `Local<usize>` 记住已转发的条数：编辑器日志是只增的 `Vec`，
/// 记下标即可，不必每帧重新扫描全部条目。
pub fn 转发控制台日志到标准错误(
    编辑器: Res<EditorStateHolder>,
    mut 已转发: Local<usize>,
) {
    let 日志 = 编辑器.状态.日志列表();

    // 「清空控制台」会把 Vec 清空，此时游标要跟着归零，
    // 否则新日志会被误判为"已经转发过"而永远不输出。
    if 日志.len() < *已转发 {
        *已转发 = 0;
    }
    if 日志.len() == *已转发 {
        return;
    }

    for 条目 in &日志[*已转发..] {
        match 条目.级别 {
            日志级别::信息 => info!(target: "编辑器控制台", "{}", 条目.诊断文本()),
            日志级别::警告 => warn!(target: "编辑器控制台", "{}", 条目.诊断文本()),
            日志级别::错误 => error!(target: "编辑器控制台", "{}", 条目.诊断文本()),
        }
    }
    *已转发 = 日志.len();
}

/// 示例项目安装根目录的环境变量覆盖（自动验收与自定义位置用）。
pub const 示例安装目录环境变量: &str = "BEVY_STUDIO_DEMO_DIR";

/// 示例项目的安装根目录。
///
/// 默认放在用户配置目录下（<配置目录>/示例项目），**不在仓库里**：
///
/// * 编辑器永远不会往仓库的 examples/ 里写文件；
/// * 用户对示例的任何改动都不会污染源码树，也不会被 git status 抓成噪声；
/// * 卸载或彻底重来只需要删这一个目录。
pub fn 示例安装目录() -> std::path::PathBuf {
    if let Ok(值) = std::env::var(示例安装目录环境变量)
        && !值.trim().is_empty()
    {
        return std::path::PathBuf::from(值);
    }
    crate::config::配置目录().join("示例项目")
}

/// 准备一个示例项目：需要时从模板安装到本地，然后返回可打开的目录。
///
/// 公开是为了让集成测试能**真正**验证"复制到仓库外 → 隐藏模板 → 仍能打开"
/// 这条交付契约（菜单动作本身需要点两下原生菜单，自动化成本高且脆）。
///
/// # 完整契约（这是"示例独立化"的落点）
///
/// 1. **模板发现**（editor_core::template::发现模板）：
///    环境变量 BEVY_STUDIO_EXAMPLES_DIR → 可执行文件同级 examples/ → 开发期仓库兜底。
///    仓库路径只是**兜底来源之一**，不再是唯一来源，且完全可以用环境变量绕过。
/// 2. **已安装就直接打开**：目标目录里已经有 project.ron 时不再复制，
///    因此用户的修改不会被下一次点击覆盖。
/// 3. **未安装才复制**：目标已存在且非空时 复制模板到 默认**拒绝覆盖**
///    （一个字节都不写），错误信息原样上抛。
/// 4. **资源路径相对项目根**：复制出来的是完整项目目录，ssets/、scenes/
///    都在里面，打开后不依赖任何仓库路径。
///
/// 所以"复制出去之后把原始模板目录藏起来，项目仍然能打开"是这条设计的
/// 必然结果，而不是特例。
pub fn 准备示例项目(
    示例: editor_ui::dev_modes::示例项目,
) -> Result<std::path::PathBuf, String> {
    let 目标 = 示例安装目录().join(示例.目录名());
    // 已经安装过：直接打开，绝不覆盖用户对示例的改动。
    if 目标.join(editor_core::project::项目清单文件名).is_file() {
        return Ok(目标);
    }

    let 模板列表 =
        editor_core::template::发现模板().map_err(|错误| format!("未找到可用模板：{错误}"))?;
    let 模板 = 模板列表
        .iter()
        .find(|模板| 模板.名称 == 示例.目录名())
        .ok_or_else(|| {
            let 可用: Vec<&str> = 模板列表.iter().map(|项| 项.名称.as_str()).collect();
            format!(
                "模板目录里没有 {}（已发现：{可用:?}；可用环境变量 {} 指定模板目录）",
                示例.目录名(),
                editor_core::template::模板目录环境变量
            )
        })?;

    if let Some(父) = 目标.parent()
        && let Err(错误) = std::fs::create_dir_all(父)
    {
        return Err(format!("无法创建安装目录 {}：{错误}", 父.display()));
    }

    let 结果 = editor_core::template::复制模板到(
        &模板.根目录,
        &目标,
        editor_core::template::复制选项::default(),
    )
    .map_err(|错误| format!("安装示例项目失败：{错误}"))?;
    Ok(结果.目标)
}

/// 把一个文本文件写进项目内的相对路径，父目录不存在时自动创建。
///
/// 瓦片地图与瓦片集都走这里：路径越界检查与"父目录不存在"的
/// 处理只实现一次，面板不需要知道磁盘布局。
fn 写入项目文本(
    编辑器: &编辑器状态, 相对文本: &str, 文本: &str
) -> Result<(), String> {
    let 项目 = 编辑器
        .项目
        .as_ref()
        .ok_or_else(|| "尚未打开项目".to_string())?;
    let 相对 = scene_doc::path::项目相对路径::解析(相对文本)
        .map_err(|错误| format!("路径无效：{错误}"))?;
    let 绝对 = 项目.绝对路径(&相对);
    if let Some(父) = 绝对.parent()
        && let Err(错误) = std::fs::create_dir_all(父)
    {
        return Err(format!("无法创建目录 {}：{错误}", 父.display()));
    }
    std::fs::write(&绝对, 文本).map_err(|错误| format!("写入 {} 失败：{错误}", 绝对.display()))
}

/// 把脚本文本写入项目内的相对路径。
fn 保存脚本文本(
    编辑器: &mut 编辑器状态,
    语言: editor_core::i18n::语言,
    路径: &scene_doc::path::项目相对路径,
    文本: &str,
) {
    let Some(项目) = 编辑器.项目.as_ref() else {
        编辑器.警告(语言.取("script_no_project").to_string());
        return;
    };
    let 绝对 = 项目.绝对路径(路径);
    match std::fs::write(&绝对, 文本) {
        Ok(()) => 编辑器.结构化信息(
            "log_script_saved",
            vec![日志参数::用户数据(路径.文本().to_string())],
        ),
        Err(错误) => 编辑器.错误(语言.填充("script_save_failed", &[&错误.to_string()])),
    }
}

