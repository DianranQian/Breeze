/// 界面绘制所需的只读资源。
///
/// # 为什么用 `SystemParam` 打包
///
/// `绘制编辑器界面` 原本要写 9 个参数，其中四个都是"只读的展示数据源"
/// （配色、缩略图、诊断、预览渲染目标）。参数一多，
/// 调用点就看不出哪些是输入、哪些是输出，而且每加一个数据源
/// 都要再改一次函数签名。
///
/// Bevy 的 `#[derive(SystemParam)]` 正是为这种情况准备的：
/// 它把多个 `Res` 聚合成一个参数，系统内部照常按字段名访问，
/// 调度器仍然能正确推导每个资源的访问权限
/// （打包不会让系统意外获得写权限）。
/// Bevy 的 `derive(SystemParam)` 要求生命周期必须命名为 `'w`（World 数据）
/// 或 `'s`（SystemParam 自身状态）。这里访问的都是 World 里的资源，
/// 因此用 `'w`。
#[derive(bevy::ecs::system::SystemParam)]
pub struct 绘制数据源<'w> {
    /// 资源缩略图纹理表。
    缩略图: Res<'w, 缩略图缓存>,
    /// 瓦片集图集纹理表。
    瓦片图集: Res<'w, crate::tilemap_textures::瓦片图集纹理>,
    /// 运行时诊断信息。
    诊断: Res<'w, 诊断资源>,
    /// 视口预览渲染目标。
    渲染目标: Res<'w, crate::preview::预览渲染目标>,
    /// 图标纹理缓存。
    图标: ResMut<'w, crate::plugin::图标资源>,
}

/// 绘制编辑器界面。
///
/// # 必须注册在 `EguiPrimaryContextPass` 里
///
/// `bevy_egui` 的 `run_egui_context_pass_loop_system`（跑在 `PostUpdate`）
/// 做的是：
///
/// ```text
/// ctx.run_ui(input, |_| world.try_run_schedule(EguiPrimaryContextPass))
///                  ↑                                    ↑
///          这里才加载字体                     界面绘制必须发生在这里面
/// ```
///
/// 也就是说 `Context::run()` 在闭包**外面**被调用，而界面绘制发生在
/// **闭包里面**。如果把绘制系统放到 `Update`，它会在字体加载之前跑，
/// egui 直接 panic：`No fonts available until first call to Context::run()`。
///
/// 这是本阶段踩到的一个真实崩溃，因此把这层关系写在文档注释里。
///
/// 好处是数据流依然清晰：`Update` 负责"改数据"，
/// `EguiPrimaryContextPass` 负责"把数据画出来"。
/// 参数偏多同样是"资源汇合点"的固有形态：界面要读文档、界面状态、配置、
/// 构建与导入快照 —— 拆成多个系统反而会让"同一帧看到的数据"不一致。
#[allow(clippy::too_many_arguments)]
pub fn 绘制编辑器界面(
    mut 上下文: EguiContexts,
    mut 界面: ResMut<UiStateHolder>,
    编辑器: Res<EditorStateHolder>,
    运行时: Res<运行时宿主>,
    构建快照: Res<crate::plugin::构建快照资源>,
    导入快照: Res<crate::plugin::导入快照资源>,
    运行快照: Res<crate::run::运行快照资源>,
    诊断快照: Res<crate::diagnostics::诊断快照资源>,
    调试: Res<crate::debug_bridge::运行时调试管理器>,
    mut 数据源: 绘制数据源,
    mut 布局待保存: ResMut<布局待保存>,
) {
    let Ok(上下文) = 上下文.ctx_mut() else {
        return;
    };

    // 把 `界面.状态` 与 `界面.动作` 分开借用：
    // 二者都是 `UiStateHolder` 的字段，直接写 `&mut 界面.状态` 与
    // `&mut 界面.动作` 会同时可变借用 `界面`。先取出引用即可。
    let UiStateHolder { 状态, 动作 } = &mut *界面;

    // 记录绘制前的布局，用于检测用户是否拖动/关闭了面板。
    //
    // 布局改动**不需要**额外的动作：用户在 `DockArea` 上的拖动、关闭、
    // 分隔条调整都是 egui_dock 直接改 `状态.停靠` 的，不经过动作队列。
    // 因此这里用"绘制前后对比指纹"来捕获它们。
    let 绘制前布局 = 状态.布局指纹();
    // 帮助窗口要显示配置目录；配置目录() 每次都解析环境变量，
    // 因此这里取一次，整帧共用。
    let 配置目录 = crate::config::配置目录();

    绘制一帧(
        上下文,
        绘制环境 {
            编辑器: &编辑器.状态,
            图标: &mut 数据源.图标.0,
            缩略图: &数据源.缩略图.纹理,
            瓦片图集: &数据源.瓦片图集.纹理,
            视口纹理: 数据源.渲染目标.渲染结果(),
            运行时: &运行时,
            诊断: &数据源.诊断.0,
            构建: &构建快照.快照,
            导入状态: &导入快照.状态表,
            运行: &运行快照.快照,
            调试: 调试.快照(),
            调试历史: 调试.历史(),
            统一诊断: &诊断快照.快照,
            配置目录: &配置目录,
        },
        状态,
        动作,
    );

    if 状态.布局指纹() != 绘制前布局 {
        布局待保存.脏 = true;
    }
}

/// 把当前界面/主题/工作区写进配置文件并落盘。返回是否成功。
///
/// # 为什么抽成独立函数
///
/// 它有两个调用点：定期写盘（拖动分隔条后攒 2 秒）与**退出前写盘**。
/// 后者是必需的：用户改完布局立刻关窗口时，攒批机制根本来不及触发，
/// 改动会丢失。实测就是靠"重启后恢复"这条验收抓到了这个缺陷。
fn 写入配置文件(界面: &UiStateHolder, 配置: &mut 编辑器配置资源) -> bool {
    match 界面.状态.布局存档为文本() {
        Ok(文本) => {
            配置.0.工作区 = Some(文本);
            // 旧字段写盘时清空：迁移只做一次，之后以工作区集为准。
            配置.0.布局 = None;
            配置.0.格式版本 = 配置格式版本;
            match 界面.状态.主题库.序列化为文本() {
                Ok(主题文本) => 配置.0.主题 = Some(主题文本),
                Err(错误) => warn!(
                    "主题序列化失败（本次只保存布局）：{}",
                    错误.文案(界面.状态.语言)
                ),
            }
            配置
                .0
                .偏好
                .insert("语言".to_string(), 界面.状态.语言.代号().to_string());
            match 配置.0.保存(&配置文件路径()) {
                Ok(()) => true,
                Err(错误) => {
                    warn!("配置保存失败：{错误}");
                    false
                }
            }
        }
        Err(错误) => {
            warn!("布局存档序列化失败：{错误}");
            false
        }
    }
}

/// 定期把布局写盘。
///
/// # 为什么用攒批而不是立即写
///
/// 用户拖动分隔条时布局**每帧**都在变。立即写盘意味着拖动一秒
/// 就要写 60 次文件 —— 既浪费 IO，也会让磁盘上反复出现半成品内容。
/// 攒够 [`布局写盘间隔`] 再写一次，既不会明显丢改动，也几乎不产生
/// 可观测的开销。
pub fn 保存窗口布局(
    时间: Res<Time>,
    mut 待保存: ResMut<布局待保存>,
    mut 配置: ResMut<编辑器配置资源>,
    界面: Res<UiStateHolder>,
) {
    // 直接用指纹判断布局是否变化：egui_dock 的拖拽/关闭/浮动不经过
    // 动作队列，只靠 `脏` 标记会漏掉这些真实用户操作。
    let 当前指纹 = 界面.状态.工作区.布局指纹();
    if 当前指纹 != 待保存.上次指纹 {
        待保存.上次指纹 = 当前指纹;
        待保存.脏 = true;
    }
    if !待保存.脏 {
        待保存.累计秒 = 0.0;
        return;
    }

    待保存.累计秒 += 时间.delta_secs();
    if 待保存.累计秒 < 布局写盘间隔 {
        return;
    }
    待保存.累计秒 = 0.0;

    if 写入配置文件(&界面, &mut 配置) {
        待保存.脏 = false;
    }
}

/// 退出前把未写盘的配置落盘。
///
/// 放在 `Last`：`AppExit` 消息在本帧产生后、引擎真正退出之前执行，
/// 因此"改完立刻关闭"不会丢改动。写失败只记录警告，不阻止退出。
pub fn 退出时保存配置(
    mut 退出消息: MessageReader<AppExit>,
    待保存: Res<布局待保存>,
    mut 配置: ResMut<编辑器配置资源>,
    界面: Res<UiStateHolder>,
) {
    if 退出消息.read().next().is_none() {
        return;
    }
    // 无条件写：用户可能只是拖了一下分割线/标签，这些操作不进动作队列，
    // `待保存.脏` 不一定被置位。退出时按当前真实布局落盘才不会丢改动。
    let _ = 待保存;
    if 写入配置文件(&界面, &mut 配置) {
        info!("已在退出前保存编辑器配置");
    }
}

/// 解析并启动当前项目的运行进程。
///
/// 目标类型由项目清单决定（见 [`crate::run::解析运行命令`]）：
/// 声明了 `运行` 就是真实可执行程序，没声明就是独立预览进程。
/// 两种情况的启动与停止走同一条链路，因此日志、PID、停止、退出清理都没有分叉。
fn 启动项目运行(
    编辑器: &mut 编辑器状态,
    界面: &editor_ui::界面状态,
    管理器: &mut crate::run::项目运行管理器,
    调试: &mut crate::debug_bridge::运行时调试管理器,
) -> Result<(), String> {
    let Some(项目) = 编辑器.项目.as_ref() else {
        return Err("还没有打开项目：请先新建或打开一个项目".to_string());
    };
    let 根 = 项目.根目录();
    let 清单 = 项目.清单().clone();
    let 类型 = 项目.类型();
    let 入口 = 项目.运行入口().cloned();
    let 可执行 =
        std::env::current_exe().map_err(|错误| format!("无法定位编辑器可执行文件：{错误}"))?;
    let 模式 = 界面.模式.id();
    let mut 命令 =
        crate::run::解析运行命令(根, 模式, &可执行, Some(&清单), 类型, 入口.as_ref())?;
    // 目标类型必须进控制台：用户要能一眼看出这次跑的是预览进程还是真实程序。
    let 命令类型 = 命令.目标类型;
    let 显示 = 命令.显示();
    let 入口标识 = 命令.入口.as_ref().map(|入口| 入口.标识());

    // ---- 调试桥：只给真实游戏进程注入调试环境 ----
    //
    // 独立预览进程是"再启动一个微风"，它不会加载游戏的 Bevy 调试插件，
    // 因此不能假装它有运行时通道。
    let mut 运行实例标识 = None;
    if 命令类型.是预览进程() {
        调试.标记未启用("当前运行目标是独立预览进程，不提供游戏运行时调试");
    } else {
        let 项目标识 = 根.display().to_string();
        match 调试.准备启动(&项目标识) {
            Ok((标识, 环境)) => {
                命令.环境.extend(环境);
                运行实例标识 = Some(标识);
            }
            Err(错误) => {
                // 调试不可用不能阻止游戏启动：记录并继续，检查器会显示失败原因。
                调试.启动失败(format!("调试监听启动失败：{错误}"));
                编辑器.警告(format!("运行时调试不可用：{错误}"));
            }
        }
    }

    match 管理器.启动带标识(命令, 运行实例标识.clone()) {
        Ok(()) => {}
        Err(错误) => {
            调试.启动失败(format!("游戏进程启动失败：{错误}"));
            return Err(错误);
        }
    }
    调试.标记游戏运行(true);
    编辑器.信息(format!(
        "运行目标：{}",
        match 命令类型 {
            crate::run::运行目标类型::独立预览进程 =>
                "独立预览进程（不是游戏运行时）".to_string(),
            crate::run::运行目标类型::项目可执行程序 =>
                "项目声明的可执行程序".to_string(),
            crate::run::运行目标类型::Cargo可执行目标 => match 入口标识 {
                Some(标识) => format!("Cargo 可执行目标 `{标识}`（{显示}）"),
                None => format!("Cargo 可执行目标（{显示}）"),
            },
        }
    ));
    Ok(())
}

/// 对齐/分布请求。
enum 对齐请求 {
    对齐(editor_core::arrange::对齐边),
    分布(editor_core::arrange::分布轴),
}

/// 把"选中的多个实体"按请求对齐或分布。
///
/// 只产生**一条** `批量设变换` 命令：用户按一次 Ctrl+Z 应当回到整批操作
/// 之前，而不是逐个退回。
fn 对齐或分布选中(编辑器: &mut 编辑器状态, 请求: 对齐请求) {
    let 选中 = 编辑器.选择.全部();
    if 选中.len() < 2 {
        编辑器.警告("对齐/分布需要至少选中两个实体".to_string());
        return;
    }

    // 收集世界 AABB：复用 2D 视口的尺寸推断，保证"看到的框"就是"对齐用的框"。
    let mut 盒子 = Vec::with_capacity(选中.len());
    let mut 标识列表 = Vec::with_capacity(选中.len());
    for 标识 in &选中 {
        let Some(框) = editor_ui::viewport_panel::计算实体框(&编辑器.会话.文档, *标识)
        else {
            continue;
        };
        盒子.push(editor_core::arrange::对齐盒 {
            位置: 框.中心,
            最小: (框.中心.0 - 框.半宽, 框.中心.1 - 框.半高),
            最大: (框.中心.0 + 框.半宽, 框.中心.1 + 框.半高),
        });
        标识列表.push(*标识);
    }
    if 盒子.len() < 2 {
        编辑器.警告("选中的实体里没有足够的可变换对象".to_string());
        return;
    }

    let 位移 = match 请求 {
        对齐请求::对齐(边) => editor_core::arrange::计算对齐(&盒子, 边),
        对齐请求::分布(轴) => editor_core::arrange::计算分布(&盒子, 轴),
    };

    let mut 项 = Vec::new();
    for (标识, 偏移) in 标识列表.iter().zip(位移) {
        if 偏移.0.abs() < f32::EPSILON && 偏移.1.abs() < f32::EPSILON {
            continue;
        }
        let Some(当前) = 编辑器.会话.文档.取(*标识).and_then(|实体| 实体.变换)
        else {
            continue;
        };
        let mut 新变换 = 当前;
        新变换.平移.0 += 偏移.0;
        新变换.平移.1 += 偏移.1;
        项.push((*标识, Some(新变换)));
    }
    if 项.is_empty() {
        // 已经对齐好了：不写撤销栈，只给一句提示。
        编辑器.信息("已经对齐，没有需要移动的实体".to_string());
        return;
    }
    let 数量 = 项.len();
    if 编辑器
        .执行并记录(editor_core::command::编辑器命令::批量设变换 { 项 })
        .is_some()
    {
        编辑器.信息(format!("已调整 {数量} 个实体"));
    }
}

/// 扫描项目 `saves/` 目录，填充存档浏览器。
///
/// 只读：不创建目录、不删除任何文件 —— 存档属于玩家，编辑器越权删改
/// 会让游戏自己维护的"手动/自动存档"语义失效。
fn 扫描存档槽位(编辑器: &mut 编辑器状态, 界面状态: &mut 界面状态) {
    let Some(项目) = 编辑器.项目.as_ref() else {
        界面状态.存档槽位.clear();
        界面状态.存档损坏.clear();
        界面状态.存档目录 = None;
        return;
    };
    let 目录 = 项目.根目录().join("saves");
    界面状态.存档目录 = Some(目录.display().to_string());
    let (槽位, 损坏) = editor_ui::savegame_panel::扫描(&目录);
    界面状态.存档槽位 = 槽位;
    界面状态.存档损坏 = 损坏;
}
