//! 预制件域动作（实例同步 / 批量同步 / 脱钩节点重新纳入）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;

/**
 * 处理预制件域动作：认领属于本域的 `UiAction`，其余原样交回。
 *
 * # 为什么这一族要放在一起
 *
 * 三条动作共用同一条数据链：界面层手上只有实例根 / 模板标识 / 节点
 * 地址，模板解析（从模板目录取**当前落盘版本**）与事务执行（在文档
 * 克隆上跑命令、成功才提交回正本）都在编辑器状态的同名方法里。
 * 动作层只做「调用 + 失败写控制台」，不做任何文档读写。
 *
 * # 失败为什么不静默
 *
 * 同步失败的原因（模板缺失、版本倒退、地址不在脱钩集合里）都是用户
 * 需要知道才能纠正的，因此错误一律写进控制台并保持文档原样，而不是
 * 吞掉或弹出无信息的提示。
 *
 * 返回 `Err(动作)` 表示这条动作不属于预制件域；
 * 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
 */
pub(super) fn 处理预制件动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;

    match 动作 {
        UiAction::同步预制件实例 { 实例根 } => {
            if let Err(错误) = 编辑器.同步预制件实例(实例根) {
                编辑器.错误(format!("同步预制件实例失败：{错误}"));
            }
            Ok(())
        }

        UiAction::同步预制件模板 { 模板 } => {
            if let Err(错误) = 编辑器.同步预制件模板(模板) {
                编辑器.错误(format!("批量同步预制件实例失败：{错误}"));
            }
            Ok(())
        }

        UiAction::重新纳入预制件节点 { 记录键, 地址 } => {
            if let Err(错误) = 编辑器.重新纳入预制件节点(记录键, 地址) {
                编辑器.错误(format!("重新纳入预制件节点失败：{错误}"));
            }
            Ok(())
        }

        UiAction::刷新预制件目录 => {
            编辑器.刷新预制件目录();
            Ok(())
        }

        UiAction::恢复预制件字段默认值 {
            实体, 组件, 属性
        } => {
            if let Err(错误) = 编辑器.恢复预制件字段默认值(实体, &组件, &属性)
            {
                编辑器.错误(format!("恢复 {组件}.{属性} 的模板默认值失败：{错误}"));
            }
            Ok(())
        }

        其他 => Err(其他),
    }
}
