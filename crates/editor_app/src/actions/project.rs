//! 项目域动作（项目生命周期 + 场景文件的打开 / 保存 / 另存为 / 实例化 / 子场景导出）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;

/// 项目域动作（项目生命周期 + 场景文件的打开 / 保存 / 另存为 / 实例化 / 子场景导出）。
///
/// # 为什么换项目要在这里集中重置
///
/// 换项目意味着构建状态、导入快照、运行时世界、运行进程、诊断历史全部作废。
/// 这些重置只在 `切换项目后重置` 与 `项目运行.重置()` 里做一次，
/// 新增一条"打开项目"的入口时不可能漏掉某一项。
///
/// 返回 `Err(动作)` 表示这条动作不属于项目域，原样交回调用者；
/// 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
pub(super) fn 处理项目动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;
    let 运行时 = &mut *上下文.运行时;
    let 对话框 = &mut *上下文.对话框;
    let 界面状态 = &mut *上下文.界面状态;
    let 布局待保存 = &mut *上下文.布局待保存;
    let 项目运行 = &mut *上下文.项目运行;
    let 构建 = &mut *上下文.构建;
    let 配置 = &mut *上下文.配置;
    let 导入 = &mut *上下文.导入;
    let 诊断 = &mut *上下文.诊断;

    match 动作 {
        UiAction::新建项目 { 名称 } => {
            请求对话框(对话框, 编辑器, 文件对话框请求::选择新建项目目录 { 名称 });
            Ok(())
        }

        UiAction::请求打开项目 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::选择项目目录);
            Ok(())
        }

        UiAction::打开示例项目(示例) => {
            match 准备示例项目(示例) {
                Ok(目录) => match 编辑器.打开项目(&目录) {
                    Ok(()) => {
                        let 语言 = 界面状态.语言;
                        let _ = 界面状态.切换模式(示例.默认模式());
                        界面状态.聚焦面板(editor_ui::Tab::视口);
                        // 2D 场景打开后把视口对准整张地图；3D 场景不自动拉远 ——
                        // 48×48 竞技场拉到全景后角色只有十几像素，反而更差。
                        // 3D 用户仍可点「适应窗口」主动拉远。
                        if !界面状态.模式.是三维() {
                            界面状态.视口命令.适应窗口 = true;
                        }
                        布局待保存.脏 = true;
                        编辑器.结构化信息(
                            "log_example_opened",
                            vec![日志参数::用户数据(目录.display().to_string())],
                        );
                        let _ = 语言;
                        记最近项目(编辑器, 界面状态, 配置, 布局待保存);
                        切换项目后重置(
                            构建,
                            导入,
                            运行时,
                            界面状态,
                            编辑器.项目.as_ref().map(|项目| 项目.根目录()),
                        );
                        项目运行.重置();
                        诊断.清空();
                        恢复运行入口(编辑器, 配置);
                    }
                    Err(错误) => {
                        编辑器.错误(format!("{}：{错误}", 界面状态.语言.取("open_demo_failed")))
                    }
                },
                Err(错误) => {
                    编辑器.错误(format!("{}：{错误}", 界面状态.语言.取("open_demo_failed")))
                }
            }
            Ok(())
        }

        UiAction::打开项目(目录) => {
            match 编辑器.打开项目(&目录) {
                Ok(()) => {
                    if !界面状态.模式.是三维() {
                        界面状态.视口命令.适应窗口 = true;
                    }
                    记最近项目(编辑器, 界面状态, 配置, 布局待保存);
                    切换项目后重置(
                        构建,
                        导入,
                        运行时,
                        界面状态,
                        编辑器.项目.as_ref().map(|项目| 项目.根目录()),
                    );
                    项目运行.重置();
                    诊断.清空();
                    恢复运行入口(编辑器, 配置);
                    // 原生工程的识别来源要如实告诉用户：走了元数据还是静态兜底。
                    // 先把要报告的内容取出来，再写日志 —— 日志接口要 `&mut 编辑器`。
                    let 识别报告 = 编辑器.项目.as_ref().and_then(|项目| {
                        项目.识别来源().map(|来源| {
                            (来源.代号().to_string(), 项目.识别提示().map(str::to_string))
                        })
                    });
                    if let Some((来源, 提示)) = 识别报告 {
                        编辑器.结构化信息(
                            "log_cargo_recognized_source",
                            vec![日志参数::用户数据(来源)],
                        );
                        if let Some(提示) = 提示 {
                            编辑器.结构化警告(
                                "log_cargo_metadata_fallback",
                                vec![日志参数::用户数据(提示)],
                            );
                        }
                    }
                }
                Err(错误) => 编辑器.错误(format!("打开项目失败：{错误}")),
            }
            Ok(())
        }

        UiAction::关闭项目 => {
            // 停止运行时：项目都关了，运行时世界不应继续存在。
            编辑器.关闭项目();
            切换项目后重置(
                构建,
                导入,
                运行时,
                界面状态,
                编辑器.项目.as_ref().map(|项目| 项目.根目录()),
            );
            // 运行进程、运行历史与诊断都必须跟着项目一起消失：
            // 关掉项目后还留着一个游戏进程在跑，是最难解释的状态。
            项目运行.重置();
            诊断.清空();
            Ok(())
        }

        UiAction::新建场景 => {
            let 名称 = 编辑器
                .项目
                .as_ref()
                .map(|_| "新场景".to_string())
                .unwrap_or_else(|| "未命名场景".to_string());
            编辑器.新建场景(名称);
            Ok(())
        }

        UiAction::打开场景(路径) => {
            if let Err(错误) = 编辑器.打开场景(&路径) {
                编辑器.错误(format!("打开场景失败：{错误}"));
            } else if !界面状态.模式.是三维() {
                界面状态.视口命令.适应窗口 = true;
            }
            Ok(())
        }

        UiAction::请求场景另存为 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::场景另存为);
            Ok(())
        }

        UiAction::请求打开场景 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::打开场景文件);
            Ok(())
        }

        UiAction::请求实例化场景 => {
            if 编辑器.项目.is_none() {
                编辑器.警告(界面状态.语言.取("log_build_no_project").to_string());
                return Ok(());
            }
            请求对话框(对话框, 编辑器, 文件对话框请求::实例化场景文件);
            Ok(())
        }

        UiAction::请求导出子场景 => {
            if 编辑器.项目.is_none() {
                编辑器.警告(界面状态.语言.取("log_build_no_project").to_string());
                return Ok(());
            }
            if 编辑器.选择.主选中().is_none() {
                编辑器.警告(界面状态.语言.取("subscene_need_selection").to_string());
                return Ok(());
            }
            请求对话框(对话框, 编辑器, 文件对话框请求::子场景另存为);
            Ok(())
        }

        UiAction::导出子场景 { 根, 路径 } => {
            let Some(项目) = 编辑器.项目.as_ref() else {
                编辑器.警告(界面状态.语言.取("log_build_no_project").to_string());
                return Ok(());
            };
            let 场景名 = 路径
                .文件名()
                .trim_end_matches(".scene.ron")
                .trim_end_matches(".ron")
                .to_string();
            let Some(新文档) = editor_core::instance::导出子树(&编辑器.会话.文档, 根, &场景名)
            else {
                编辑器.结构化警告(
                    "log_subscene_missing_root",
                    vec![日志参数::用户数据(根.to_string())],
                );
                return Ok(());
            };
            let 数量 = 新文档.实体数量();
            match 项目.保存场景(&路径, &新文档) {
                Ok(()) => 编辑器.结构化信息(
                    "log_subscene_done",
                    vec![
                        日志参数::用户数据(路径.文本().to_string()),
                        日志参数::用户数据(数量.to_string()),
                    ],
                ),
                Err(错误) => 编辑器.错误(format!("保存子场景失败：{错误}")),
            }
            Ok(())
        }

        UiAction::实例化场景(源路径) => {
            let Some(项目) = 编辑器.项目.as_ref() else {
                编辑器.警告(界面状态.语言.取("log_build_no_project").to_string());
                return Ok(());
            };
            // 源场景从磁盘读，而不是从当前会话复制：实例化的语义是
            // "把那个场景的内容放进来"，当前会话里可能有未保存改动，
            // 那不应当被带进实例。
            let 源 = match 项目.读取场景(&源路径) {
                Ok(读取) => 读取.文档,
                Err(错误) => {
                    编辑器.错误(format!("实例化失败：读不到 {}：{错误}", 源路径.文本()));
                    return Ok(());
                }
            };
            let mut 新文档 = 编辑器.会话.文档.clone();
            let 结果 = editor_core::instance::实例化为(
                &mut 新文档,
                &源,
                Some(&源路径),
                // 挂到当前主选中实体下：用户在场景树里选了一个容器再实例化，
                // 得到的就是"放进这个容器"。没选中则作为顶层。
                编辑器.选择.主选中(),
            );
            if !结果.有效() {
                编辑器.结构化警告(
                    "log_instance_empty",
                    vec![日志参数::用户数据(源路径.文本().to_string())],
                );
                return Ok(());
            }
            // 整个实例化是一个撤销步：走"设为快照"命令，
            // 与拖拽/属性编辑共用同一套差量撤销，不引入第二套撤销通道。
            match 编辑器.执行(editor_core::command::编辑器命令::设为快照 {
                文档: Box::new(新文档),
            }) {
                Ok(_) => {
                    if let Some(根) = 结果.根实体 {
                        编辑器.选择.单选(根);
                    }
                    编辑器.结构化信息(
                        "log_instance_done",
                        vec![
                            日志参数::用户数据(源路径.文本().to_string()),
                            日志参数::用户数据(结果.复制实体数.to_string()),
                        ],
                    );
                    界面状态.视口命令.适应窗口 = false;
                }
                Err(错误) => 编辑器.错误(format!("实例化失败：{错误}")),
            }
            Ok(())
        }

        UiAction::场景另存为(路径) => {
            if let Err(错误) = 编辑器.保存场景到(&路径) {
                编辑器.错误(format!("保存场景失败：{错误}"));
            } else {
                crate::recovery_autosave::保存后清理恢复点(编辑器);
            }
            Ok(())
        }

        UiAction::保存场景 => {
            // 尚未关联文件时，先让用户选一个路径，而不是直接报错。
            if 编辑器.场景已保存到磁盘() {
                if let Err(错误) = 编辑器.保存场景() {
                    编辑器.错误(format!("保存场景失败：{错误}"));
                } else {
                    crate::recovery_autosave::保存后清理恢复点(编辑器);
                }
            } else if 编辑器.项目.is_some() {
                请求对话框(对话框, 编辑器, 文件对话框请求::场景另存为);
            } else {
                编辑器.错误("尚未打开项目，无法保存场景");
            }
            Ok(())
        }

        其他 => Err(其他),
    }
}
