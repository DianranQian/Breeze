//! 保存域动作（存档槽位浏览 / 自动保存恢复点的恢复、丢弃与提示关闭）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;

/// 处理保存域动作：认领属于本域的 `UiAction`，其余原样交回。
///
/// # 为什么这一族要放在一起
///
/// 恢复点属于编辑器会话的"容错"链路：动作只负责更新 `恢复点候选` 列表和
/// 提示开关，读写盘交给 `crate::recovery_autosave`、`editor_core::recovery`
/// 与本文件外的 `扫描存档槽位`。集中一处，改动恢复语义时不会漏掉
/// "恢复后要出候选、丢弃后也要出候选"这条对称规则。
///
/// 返回 `Err(动作)` 表示这条动作不属于保存域；
/// 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
pub(super) fn 处理保存动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;
    let 界面状态 = &mut *上下文.界面状态;

    match 动作 {
        UiAction::显示存档槽位(显示) => {
            界面状态.显示存档槽位 = 显示;
            if 显示 {
                扫描存档槽位(编辑器, 界面状态);
            }
            Ok(())
        }

        UiAction::刷新存档槽位 => {
            扫描存档槽位(编辑器, 界面状态);
            Ok(())
        }

        UiAction::恢复自动保存(元数据) => {
            match crate::recovery_autosave::恢复恢复点(编辑器, &元数据) {
                Ok(()) => {
                    // 恢复成功后把它从候选里移除：同一次启动不该反复提示。
                    界面状态.恢复点候选.retain(|项| 项.标识 != 元数据.标识);
                    let 语言 = 界面状态.语言;
                    编辑器.结构化信息(
                        "log_recovery_restored",
                        vec![日志参数::用户数据(元数据.场景名.clone())],
                    );
                    let _ = 语言;
                }
                Err(错误) => {
                    编辑器.错误(format!("恢复自动保存失败：{错误}"));
                }
            }
            Ok(())
        }

        UiAction::丢弃自动保存(元数据) => {
            let Some(项目) = 编辑器.项目.as_ref() else {
                编辑器.警告("没有打开的项目".to_string());
                return Ok(());
            };
            let 存储 = editor_core::recovery::恢复点存储::新建(项目.根目录());
            match 存储.丢弃(&元数据) {
                Ok(()) => {
                    界面状态.恢复点候选.retain(|项| 项.标识 != 元数据.标识);
                    编辑器.结构化信息(
                        "log_recovery_discarded",
                        vec![日志参数::用户数据(元数据.场景名.clone())],
                    );
                }
                Err(错误) => 编辑器.错误(format!("丢弃恢复点失败：{错误}")),
            }
            Ok(())
        }

        UiAction::关闭恢复提示 => {
            // 只关提示，不删恢复点：用户可能只是现在不想处理。
            界面状态.恢复点候选.clear();
            界面状态.恢复点错误 = None;
            Ok(())
        }

        其他 => Err(其他),
    }
}
