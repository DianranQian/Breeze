//! 设置域动作（项目设置表单 / 最近项目列表 / 帮助窗口 / 配置目录）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;

/// 处理设置域动作：认领属于本域的 `UiAction`，其余原样交回。
///
/// # 这一族的共同点
///
/// 它们改的都是"编辑器自己的偏好"：项目设置写回 `project.ron`，
/// 最近项目写回用户配置并置 `布局待保存.脏`，帮助与配置目录只动界面开关。
/// 都不碰场景文档，因此撤销栈看不到它们 —— 出错时的补救只有一致的
/// "把错误回填到表单"这一条路径，放在一处才不会写歪。
///
/// 返回 `Err(动作)` 表示这条动作不属于设置域；
/// 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
pub(super) fn 处理设置动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;
    let 界面状态 = &mut *上下文.界面状态;
    let 配置 = &mut *上下文.配置;
    let 布局待保存 = &mut *上下文.布局待保存;

    match 动作 {
        UiAction::显示项目设置(显示) => {
            界面状态.显示项目设置 = 显示;
            界面状态.项目设置错误 = None;
            if 显示 {
                界面状态.项目设置草稿 = 编辑器.项目.as_ref().map(|项目| 项目.设置视图());
                if 界面状态.项目设置草稿.is_none() {
                    编辑器.警告(界面状态.语言.取("project_settings_no_project").to_string());
                }
            } else {
                界面状态.项目设置草稿 = None;
            }
            Ok(())
        }

        UiAction::保存项目设置(设置) => {
            let Some(项目) = 编辑器.项目.as_mut() else {
                界面状态.项目设置错误 =
                    Some(界面状态.语言.取("project_settings_no_project").to_string());
                界面状态.显示项目设置 = true;
                return Ok(());
            };
            // 原生 Cargo 工程：设置来自 `Cargo.toml`，微风不写它。
            // 必须在调用 应用设置 之前挡住 —— 否则内存清单会被改掉，
            // 保存又必然失败，用户看到的是"改了一半又弹回来"。
            if !项目.类型().清单可写() {
                界面状态.项目设置错误 = Some(
                    界面状态
                        .语言
                        .取("project_settings_native_readonly")
                        .to_string(),
                );
                界面状态.显示项目设置 = true;
                return Ok(());
            }
            match 项目.应用设置(&设置) {
                Ok(()) => match 项目.保存清单() {
                    Ok(()) => {
                        编辑器.结构化信息(
                            "log_project_settings_saved",
                            vec![日志参数::用户数据(设置.名称.clone())],
                        );
                        界面状态.项目设置草稿 = None;
                        界面状态.项目设置错误 = None;
                        // 关闭对话框：保存成功后用户应该回到编辑器，
                        // 而不是继续盯着一个已经保存过的表单。
                        界面状态.显示项目设置 = false;
                    }
                    Err(错误) => {
                        界面状态.项目设置错误 = Some(format!("保存 project.ron 失败：{错误}"));
                        界面状态.显示项目设置 = true;
                    }
                },
                Err(错误) => {
                    // 校验失败：清单未被修改，错误回到对话框里，
                    // 用户的草稿仍然保留，可以直接改。
                    界面状态.项目设置错误 = Some(错误.to_string());
                    界面状态.显示项目设置 = true;
                }
            }
            Ok(())
        }

        UiAction::打开最近项目(目录) => {
            if !目录.is_dir() {
                编辑器.警告(
                    界面状态
                        .语言
                        .填充("recent_project_gone", &[&目录.display().to_string()]),
                );
                // 失效项目从列表里移除：留着一个点不动的条目只会反复误导用户。
                配置.0.移除最近项目(&目录);
                界面状态.最近项目 = 配置.0.最近项目列表.clone();
                布局待保存.脏 = true;
                return Ok(());
            }
            let 动作列表 = vec![UiAction::打开项目(目录.clone())];
            for 动作 in 动作列表 {
                // 子模块拿不到逐字段的 13 份借用，直接把整条上下文交回分派入口：
                // 这里此刻没有其它字段借用存活，语义与原先逐字段重建上下文完全一致。
                执行单个动作(动作, 上下文);
            }
            Ok(())
        }

        UiAction::移除最近项目(目录) => {
            if 配置.0.移除最近项目(&目录) {
                // 界面状态必须同步：最近项目菜单直接读它，只改配置的话
                // 用户点完 ✕ 会看到那一行还在，直到重启。
                界面状态.最近项目 = 配置.0.最近项目列表.clone();
                布局待保存.脏 = true;
                编辑器.结构化信息(
                    "log_recent_removed",
                    vec![日志参数::用户数据(目录.display().to_string())],
                );
            }
            Ok(())
        }

        UiAction::清除最近项目 => {
            配置.0.清空最近项目();
            界面状态.最近项目.clear();
            布局待保存.脏 = true;
            编辑器.结构化信息("log_recent_cleared", Vec::new());
            Ok(())
        }

        UiAction::显示帮助(显示) => {
            界面状态.显示帮助 = 显示;
            Ok(())
        }

        UiAction::打开配置目录 => {
            let 目录 = crate::config::配置目录();
            // 目录可能还不存在（首次启动、还没写过配置）：先建出来，
            // 否则"打开配置目录"会打开一个不存在的路径而失败。
            if let Err(错误) = std::fs::create_dir_all(&目录) {
                编辑器.错误(format!("创建配置目录失败：{错误}"));
                return Ok(());
            }
            match opener::open(&目录) {
                Ok(()) => 编辑器.结构化信息(
                    "log_config_dir_opened",
                    vec![日志参数::用户数据(目录.display().to_string())],
                ),
                Err(错误) => 编辑器.错误(format!("打开配置目录失败：{错误}")),
            }
            Ok(())
        }

        其他 => Err(其他),
    }
}
