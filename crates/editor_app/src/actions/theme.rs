//! 主题域动作（切换 / 编辑草稿 / 保存另存 / 删除 / 重置 / 导入导出）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;

/// 主题域动作（切换 / 编辑草稿 / 保存另存 / 删除 / 重置 / 导入导出）。
///
/// # 为什么所有编辑都只改草稿
///
/// 主题一改就生效，若直接写回主题库，用户"取消"时无法回退，
/// 未保存的改动还会被下一次保存带进配置。因此编辑器只操作
/// `界面状态.主题草稿`，只有"保存主题草稿 / 另存为主题"才落库。
///
/// 返回 `Err(动作)` 表示这条动作不属于主题域，原样交回调用者；
/// 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
pub(super) fn 处理主题动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;
    let 界面状态 = &mut *上下文.界面状态;
    let 布局待保存 = &mut *上下文.布局待保存;
    let 对话框 = &mut *上下文.对话框;

    match 动作 {
        UiAction::设置主题(id) => {
            let 语言 = 界面状态.语言;
            match 界面状态.主题库.切换(&id) {
                Ok(()) => {
                    // 切主题时丢弃未保存的草稿：否则用户会看到"切了主题但
                    // 颜色还是草稿里的"，而且下一次保存会把草稿写到新主题上。
                    界面状态.主题草稿 = None;
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.主题库.当前().显示名(语言);
                    编辑器.结构化信息("log_theme_switched", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.错误(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::显示主题编辑器(显示) => {
            界面状态.显示主题编辑器 = 显示;
            if 显示 {
                // 打开时从当前主题拷一份草稿，之后所有编辑都只改草稿。
                界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
            } else {
                界面状态.主题草稿 = None;
            }
            Ok(())
        }

        UiAction::关闭主题编辑器 => {
            界面状态.显示主题编辑器 = false;
            // 丢弃草稿 = 取消；界面下一帧自动回到主题库里的当前主题。
            界面状态.主题草稿 = None;
            Ok(())
        }

        UiAction::保存主题草稿 => {
            let 语言 = 界面状态.语言;
            let Some(草稿) = 界面状态.主题草稿.clone() else {
                return Ok(());
            };
            let 名称 = 草稿.显示名(语言);
            match 界面状态.主题库.保存(草稿) {
                Ok(()) => {
                    界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
                    布局待保存.脏 = true;
                    编辑器.结构化信息("log_theme_saved", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::另存为主题 { 名称 } => {
            let 语言 = 界面状态.语言;
            let Some(草稿) = 界面状态.主题草稿.clone() else {
                return Ok(());
            };
            match 界面状态.主题库.另存为(草稿, &名称, 语言) {
                Ok(_) => {
                    界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.主题库.当前().显示名(语言);
                    编辑器.结构化信息("log_theme_created", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::删除主题(id) => {
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态
                .主题库
                .按id(&id)
                .map(|主题| 主题.显示名(语言))
                .unwrap_or_else(|| id.clone());
            match 界面状态.主题库.删除(&id, 语言) {
                Ok(()) => {
                    界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
                    布局待保存.脏 = true;
                    编辑器.结构化信息("log_theme_deleted", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::重置内置主题 => {
            let 语言 = 界面状态.语言;
            let id = 界面状态.主题库.当前id().to_string();
            界面状态.主题库.重置内置主题(&id);
            界面状态.主题草稿 = Some(界面状态.主题库.当前().clone());
            布局待保存.脏 = true;
            let 名称 = 界面状态.主题库.当前().显示名(语言);
            编辑器.结构化信息("log_theme_reset", vec![日志参数::用户数据(名称)]);
            Ok(())
        }

        UiAction::重置全部内置主题 => {
            let 数量 = 界面状态.主题库.重置内置();
            界面状态.主题草稿 = None;
            布局待保存.脏 = true;
            编辑器.结构化信息(
                "log_theme_reset_all",
                vec![日志参数::用户数据(数量.to_string())],
            );
            Ok(())
        }

        UiAction::导出主题 => {
            let 语言 = 界面状态.语言;
            let id = 界面状态.主题库.当前id().to_string();
            match 界面状态.主题库.导出(&id) {
                Ok(文本) => 请求对话框(对话框, 编辑器, 文件对话框请求::导出主题(文本)),
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::导入主题 => {
            请求对话框(对话框, 编辑器, 文件对话框请求::导入主题);
            Ok(())
        }

        其他 => Err(其他),
    }
}
