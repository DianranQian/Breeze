//! 界面域动作（面板聚焦与浮动 / 布局恢复 / 工作区 / 开发模式 / 视口命令 / 语言 / 控制台）。
//!
//! 从 `actions/mod.rs` 拆出；分派入口仍是 `super::执行单个动作`。

use super::*;

/// 处理界面域动作：认领属于本域的 `UiAction`，其余原样交回。
///
/// # 为什么这一族只改界面状态
///
/// 它们不碰场景文档，但几乎都要把 `布局待保存.脏` 置位 —— 布局是这些动作的
/// 唯一持久化副作用。集中在一处，新增面板类动作时不会漏掉"改完不写盘"。
///
/// 返回 `Err(动作)` 表示这条动作不属于界面域；
/// 总表仍保留这些变体的哨兵分支，穷尽性检查不会因此放宽。
pub(super) fn 处理界面动作(
    动作: UiAction,
    上下文: &mut 动作上下文<'_>,
) -> Result<(), UiAction> {
    let 编辑器 = &mut *上下文.编辑器;
    let 界面状态 = &mut *上下文.界面状态;
    let 布局待保存 = &mut *上下文.布局待保存;

    match 动作 {
        // 打开资源选择器。
        //
        // 只记录"给哪个字段选"以及字段要求的类别，不预先拷贝资源列表：
        // 列表由注册表在绘制时读取，保证选择器打开期间刷新动作也能生效。
        // 搜索与类别页签从默认值开始，用户上次的筛选不跨字段残留。
        UiAction::打开资源选择器 {
            实体,
            组件,
            属性,
            类别,
        } => {
            界面状态.资源选择器 = Some(资源选择器状态::新建(实体, 组件, 属性, 类别));
            Ok(())
        }

        // 材质编辑器的贴图槽：同一个选择器，落点换成材质草稿。
        // 草稿不存在时也照样打开 —— 用户仍能浏览资源库，只是选中后
        // 写回会被拒（动作层会给出「材质编辑器已关闭」的警告）。
        UiAction::打开材质资源选择器 {
            材质路径,
            属性,
            类别,
        } => {
            界面状态.资源选择器 = Some(资源选择器状态::新建材质(材质路径, 属性, 类别));
            Ok(())
        }

        UiAction::聚焦面板(面板) => {
            界面状态.聚焦面板(面板);
            // 面板被加进布局或切到前台，布局内容变了，需要写盘。
            布局待保存.脏 = true;
            Ok(())
        }

        UiAction::恢复默认布局 => {
            界面状态.恢复默认布局();
            布局待保存.脏 = true;
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态.工作区.当前().显示名(语言);
            编辑器.结构化信息("log_workspace_reset", vec![日志参数::用户数据(名称)]);
            Ok(())
        }

        UiAction::切换工作区(id) => {
            let 语言 = 界面状态.语言;
            match 界面状态.工作区.切换(&id) {
                Ok(()) => {
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.工作区.当前().显示名(语言);
                    编辑器
                        .结构化信息("log_workspace_switched", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.错误(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::打开工作区对话框 { 复制当前 } => {
            let 语言 = 界面状态.语言;
            let 默认名 = if 复制当前 {
                语言.填充(
                    "workspace_copy_name",
                    &[&界面状态.工作区.当前().显示名(语言)],
                )
            } else {
                语言.填充("workspace_new_name", &[&(界面状态.工作区.列表().len() + 1)])
            };
            界面状态.工作区对话框 = Some(工作区对话框::新建(复制当前, 默认名));
            Ok(())
        }

        UiAction::新建工作区 {
            名称, 复制当前
        } => {
            let 语言 = 界面状态.语言;
            match 界面状态.工作区.新建工作区(&名称, 复制当前, 语言) {
                Ok(_) => {
                    // 成功后关闭对话框：失败时它保持打开并显示原因。
                    界面状态.工作区对话框 = None;
                    布局待保存.脏 = true;
                    let 名称 = 界面状态.工作区.当前().显示名(语言);
                    编辑器.结构化信息("log_workspace_created", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => {
                    let 文案 = 错误.文案(语言);
                    if let Some(对话框状态) = 界面状态.工作区对话框.as_mut() {
                        对话框状态.错误 = Some(文案.clone());
                    }
                    编辑器.警告(文案);
                }
            }
            Ok(())
        }

        UiAction::重命名工作区 { id, 新名称 } => {
            let 语言 = 界面状态.语言;
            match 界面状态.工作区.重命名(&id, &新名称, 语言) {
                Ok(()) => {
                    界面状态.工作区对话框 = None;
                    布局待保存.脏 = true;
                    let 名称 = 界面状态
                        .工作区
                        .查找(&id)
                        .map(|项| 项.显示名(语言))
                        .unwrap_or_else(|| 新名称.clone());
                    编辑器.结构化信息("log_workspace_renamed", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => {
                    let 文案 = 错误.文案(语言);
                    if let Some(对话框状态) = 界面状态.工作区对话框.as_mut() {
                        对话框状态.错误 = Some(文案.clone());
                    }
                    编辑器.警告(文案);
                }
            }
            Ok(())
        }

        UiAction::删除工作区(id) => {
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态
                .工作区
                .查找(&id)
                .map(|项| 项.显示名(语言))
                .unwrap_or_else(|| id.clone());
            match 界面状态.工作区.删除(&id, 语言) {
                Ok(()) => {
                    界面状态.工作区对话框 = None;
                    布局待保存.脏 = true;
                    编辑器.结构化信息("log_workspace_deleted", vec![日志参数::用户数据(名称)]);
                }
                Err(错误) => 编辑器.警告(错误.文案(语言)),
            }
            Ok(())
        }

        UiAction::重置当前工作区 => {
            界面状态.恢复默认布局();
            布局待保存.脏 = true;
            let 语言 = 界面状态.语言;
            let 名称 = 界面状态.工作区.当前().显示名(语言);
            编辑器.结构化信息("log_workspace_reset", vec![日志参数::用户数据(名称)]);
            Ok(())
        }

        UiAction::重置全部内置工作区 => {
            let 语言 = 界面状态.语言;
            let 数量 = 界面状态.工作区.重置全部内置();
            布局待保存.脏 = true;
            编辑器.结构化信息(
                "log_workspace_reset_all",
                vec![日志参数::用户数据(数量.to_string())],
            );
            let _ = 语言;
            Ok(())
        }

        UiAction::切换模式(模式) => {
            if 界面状态.模式 == 模式 {
                return Ok(());
            }
            match 界面状态.切换模式(模式) {
                Ok(()) => {
                    布局待保存.脏 = true;
                    // 进入脚本模式时把脚本面板切到前台：
                    // 否则用户看到的还是上一次的视口标签，"进了脚本模式却看不到编辑器"。
                    if 模式 == editor_ui::开发模式::脚本 {
                        界面状态.聚焦面板(editor_ui::Tab::脚本);
                    }
                    编辑器.结构化信息(
                        "log_mode_switched",
                        vec![日志参数::用户数据(
                            界面状态.语言.取(模式.名称键()).to_string(),
                        )],
                    );
                }
                Err(错误) => 编辑器.错误(错误),
            }
            Ok(())
        }

        UiAction::视口适应窗口 => {
            界面状态.视口命令.适应窗口 = true;
            Ok(())
        }

        UiAction::视口重置视图 => {
            界面状态.视口命令.重置视图 = true;
            Ok(())
        }

        UiAction::三维重置轨道 => {
            界面状态.三维相机.重置();
            界面状态.视口命令.重置轨道 = true;
            Ok(())
        }

        UiAction::聚焦选中实体 => {
            界面状态.视口命令.聚焦选中 = true;
            Ok(())
        }

        UiAction::浮动面板(面板) => {
            let 语言 = 界面状态.语言;
            if 界面状态.工作区.浮动面板(面板) {
                布局待保存.脏 = true;
                编辑器.结构化信息(
                    "log_panel_floated",
                    vec![日志参数::用户数据(面板.标题(语言).to_string())],
                );
            } else {
                编辑器.警告(语言.填充("panel_cannot_float", &[&面板.标题(语言)]));
            }
            Ok(())
        }

        UiAction::停靠全部浮动面板 => {
            let 语言 = 界面状态.语言;
            let 数量 = 界面状态.工作区.停靠全部浮动();
            if 数量 > 0 {
                布局待保存.脏 = true;
            }
            编辑器.结构化信息(
                "log_panels_docked",
                vec![日志参数::用户数据(数量.to_string())],
            );
            let _ = 语言;
            Ok(())
        }

        UiAction::设置语言(语言) => {
            if 界面状态.语言 == 语言 {
                return Ok(());
            }
            界面状态.语言 = 语言;
            // 语言属于"用户偏好"，要与窗口布局一样写进编辑器配置 ——
            // 否则重启后又会回到中文，用户会以为切换没生效。
            布局待保存.脏 = true;
            编辑器.结构化信息(
                "log_language_changed",
                vec![日志参数::用户数据(语言.自称().to_string())],
            );
            Ok(())
        }

        UiAction::清空控制台 => {
            编辑器.清空日志();
            Ok(())
        }

        UiAction::显示关于 => {
            界面状态.显示关于 = true;
            Ok(())
        }

        其他 => Err(其他),
    }
}
