//! 内置 BSN 场景模板：官方 BSN 能力接进编辑器文档管线的**唯一入口**。
//!
//! # 这个模块为什么存在
//!
//! `crates/bsn_bridge` 是通用适配层：它只认识 `scene_doc` 与 Bevy，
//! 不知道本项目注册了哪些组件。而"用 BSN 描述一个本项目的 2D 关卡原型"
//! 必须知道 `Sprite属性`、`编辑器相机2d` 这些**编辑器自己的组件类型**。
//! 于是具体模板与具体提取器放在这里 —— 这是依赖方向决定的：
//!
//! ```text
//! editor_app（本模块：具体组件 + 具体模板）
//!      └──> bsn_bridge（通用机制）
//!              └──> scene_doc / bevy
//! ```
//!
//! # 中文字段名与 BSN 语法的冲突
//!
//! 本项目的组件类型是中文命名（`Sprite属性`、`编辑器相机2d`）。但 `bsn!`
//! 用"首字符是否大写"判断路径是类型还是值，汉字没有大小写，所以
//! **中文命名的组件类型不能直接写进 `bsn!`**。
//!
//! 本项目采用的绕法是"经变量插入"：
//!
//! ```text
//! let 主相机 = 编辑器相机2d { 正交半高: 360.0 };
//! bsn! { ... 主相机 ... }
//! ```
//!
//! 这样既不需要给组件改名（会破坏现有注册表与场景文件），
//! 也不需要绕过官方宏。约束与两种绕法的可执行证据在
//! `crates/bsn_bridge/tests/标识符约束.rs`。
//!
//! # 这些模板不绕过文档层
//!
//! 模板只负责把实体实例化进一个临时世界；随后**立即**提取成
//! [`scene_doc::场景文档`]，再交给 `编辑器状态` 按常规流程管理。
//! 没有任何路径让 BSN 模板直接产出运行时实体并绕开文档 ——
//! 撤销重做、实体身份与保存逻辑因此完全不受影响。

use bevy::prelude::*;

use bsn_bridge::{
    在世界上实例化, 提取产物, 提取并校验, 提取配置, 组件提取器, BSN宿主, BSN场景模板, BSN错误,
};
use scene_doc::document::场景文档;
use scene_doc::path::项目相对路径;
use scene_doc::property::颜色值;
use scene_doc::registry::组件注册表;

use crate::scene_bridge::{默认组件注册表, 编辑器相机2d, 可见性属性, Sprite属性};

/// 世界侧 `Visibility` → 文档侧 [`可见性属性`]。
///
/// 必须与 `scene_bridge` 里"文档 → 世界"的映射（`true → Inherited`、
/// `false → Hidden`）互为逆映射，否则一会儿保存一会儿加载之后，
/// 用户明明没改，可见性却会漂移。集成测试
/// `可见性映射是稳定定点` 守住这条。
pub fn 可见性转文档(可见性: &Visibility) -> 可见性属性 {
    可见性属性 {
        可见: *可见性 != Visibility::Hidden,
    }
}

/// 编辑器侧受支持组件的提取器清单。
///
/// 与 [`默认组件注册表`] 必须一一对应：注册表里每个可编辑组件，
/// 只要它可能出现在 BSN 场景里，就必须在这里有一条提取器，
/// 否则提取时会被判为"未转换组件"而拒绝 —— 这正是我们要的行为，
/// 它保证"注册表说有、运行时没有"这类不匹配不会静默通过。
///
/// `Transform` **不**在这张表里：它映射到场景实体的 `变换` 字段，
/// 而不是一个文档组件。这一点由 `bsn_bridge` 的提取层内建处理。
pub fn 编辑器提取器() -> Vec<组件提取器> {
    vec![
        组件提取器::新建::<Sprite属性>("Sprite"),
        组件提取器::新建::<编辑器相机2d>("Camera2d"),
        组件提取器::带转换::<Visibility, 可见性属性>("Visibility", 可见性转文档),
    ]
}

/// 把一个 BSN 模板转成场景文档（严格模式）。
///
/// 流程：新建临时 BSN 宿主 → 实例化模板 → 用编辑器的注册表与提取器
/// 提取成文档 → 丢弃临时世界。**临时世界不会泄漏到编辑器里**。
///
/// 只要场景里存在无法转换的组件就返回错误，不会返回一份缺数据的文档。
pub fn 从模板生成文档(
    模板: &dyn BSN场景模板, 场景名: &str
) -> Result<提取产物, BSN错误> {
    let mut 宿主 = BSN宿主::新建();
    let 根 = 模板.实例化(宿主.世界可变())?;
    let 注册表: 组件注册表 = 默认组件注册表();
    let 配置 = 提取配置::新建(&注册表, 编辑器提取器());
    提取并校验(宿主.世界(), 根, 场景名, &配置)
}

/// 把一个 BSN 模板直接转成可交给编辑器会话的文档。
///
/// 这是给 UI / 动作层用的便利函数：它只返回文档，错误已带上足够上下文。
pub fn 从模板生成场景(模板: &dyn BSN场景模板, 场景名: &str) -> Result<场景文档, BSN错误> {
    从模板生成文档(模板, 场景名).map(|产物| 产物.文档)
}

