/// 二维关卡原型模板：根 + 主相机 + 背景板 + 玩家。
///
/// 覆盖了原型要求的全部要素：多个实体、名称、位置/旋转/缩放、
/// 两层层级、以及**编辑器自己注册的**组件（`Sprite属性`、`编辑器相机2d`）
/// 与一个资源引用（背景板贴图）。
pub struct 二维原型模板;

impl BSN场景模板 for 二维原型模板 {
    fn 标识(&self) -> &'static str {
        "editor_2d_prototype"
    }

    fn 名称键(&self) -> &'static str {
        "bsn_template_editor_2d_prototype"
    }

    fn 实例化(&self, 世界: &mut World) -> Result<Entity, BSN错误> {
        // 中文命名的组件类型经变量插入，见模块文档。
        let 主相机 = 编辑器相机2d { 正交半高: 360.0 };
        let 背景板 = Sprite属性 {
            颜色: 颜色值::srgb(0.10, 0.12, 0.16, 1.0),
            ..Default::default()
        };
        let 玩家 = Sprite属性 {
            贴图路径: 项目相对路径::解析("textures/玩家.png").ok(),
            颜色: 颜色值::srgb(0.30, 0.68, 1.0, 1.0),
            自定义尺寸: Some((48.0, 48.0)),
            ..Default::default()
        };

        在世界上实例化(
            世界,
            bsn! {
                #二维关卡
                Transform { translation: { Vec3::new(0.0, 0.0, 0.0) } }
                Children [
                    #主相机
                    主相机
                    Transform { translation: { Vec3::new(0.0, 0.0, 1000.0) } }
                    --
                    #背景板
                    背景板
                    Transform {
                        translation: { Vec3::new(0.0, 0.0, -10.0) },
                        scale: { Vec3::new(8.0, 4.5, 1.0) }
                    }
                    --
                    #玩家
                    玩家
                    Transform {
                        translation: { Vec3::new(0.0, -80.0, 0.0) },
                        rotation: { Quat::from_rotation_z(0.15) },
                        scale: { Vec3::new(1.0, 1.0, 1.0) }
                    }
                    Visibility::Visible
                ]
            },
        )
    }
}

/// 内置模板的静态元信息，供界面列出与测试核对。
pub const 内置模板说明: &[bsn_bridge::模板说明] = &[bsn_bridge::模板说明 {
    标识: "editor_2d_prototype",
    名称键: "bsn_template_editor_2d_prototype",
    预期实体数: 4,
    预期最大深度: 1,
}];

/// 全部编辑器内置模板。
pub fn 内置模板列表() -> Vec<Box<dyn BSN场景模板>> {
    vec![Box::new(二维原型模板)]
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 模板列表与说明表一一对应() {
        let 模板 = 内置模板列表();
        assert_eq!(模板.len(), 内置模板说明.len());
        for (项, 说明) in 模板.iter().zip(内置模板说明.iter()) {
            assert_eq!(项.标识(), 说明.标识);
            assert_eq!(项.名称键(), 说明.名称键);
        }
    }

    #[test]
    fn 说明表的规模与真实提取结果一致() {
        for 模板 in 内置模板列表() {
            let 说明 = 内置模板说明
                .iter()
                .find(|说明| 说明.标识 == 模板.标识())
                .expect("模板缺少说明条目");
            let 产物 = 从模板生成文档(模板.as_ref(), "规模核对").expect("应无损失提取");
            assert_eq!(
                产物.报告.实体数, 说明.预期实体数,
                "模板 `{}` 的实体数与说明不符",
                模板.标识()
            );
            assert_eq!(
                产物.报告.最大深度, 说明.预期最大深度,
                "模板 `{}` 的层级深度与说明不符",
                模板.标识()
            );
        }
    }

    #[test]
    fn 编辑器提取器与注册表组件名对齐() {
        let 注册表 = 默认组件注册表();
        let 提取器名: std::collections::BTreeSet<&str> = 编辑器提取器()
            .iter()
            .map(|提取器| 提取器.组件名)
            .collect();

        for 组件名 in 注册表.组件名列表() {
            // Transform 走 `变换` 字段，不是文档组件，因此不在提取器表里。
            if 组件名 == "Transform" {
                continue;
            }
            assert!(
                提取器名.contains(组件名.as_str()),
                "注册表组件 `{组件名}` 没有对应的提取器；从 BSN 提取时会被判为未转换"
            );
        }
    }

    #[test]
    fn 可见性映射是稳定定点() {
        // 文档侧 true → 世界 Inherited → 文档侧 true。
        let 世界侧 = Visibility::Inherited;
        assert_eq!(可见性转文档(&世界侧), 可见性属性 { 可见: true });

        // 文档侧 false → 世界 Hidden → 文档侧 false。
        let 世界侧 = Visibility::Hidden;
        assert_eq!(可见性转文档(&世界侧), 可见性属性 { 可见: false });

        // Bevy 的 Visible 也算可见，且回不到 Visible —— 这是**已知的有损**，
        // `scene_bridge` 的字段提示里已经写明。
        assert_eq!(
            可见性转文档(&Visibility::Visible),
            可见性属性 { 可见: true }
        );
    }

    #[test]
    fn 模板产出的文档通过自身校验() {
        let 产物 = 从模板生成文档(&二维原型模板, "校验").expect("提取");
        assert!(
            产物.报告.文档校验.无问题(),
            "BSN 模板产出的文档必须自洽：{}",
            产物.报告.文档校验.摘要()
        );
        assert!(!产物.报告.有数据损失());
    }
}
