//! 自动保存与恢复点的**应用层接线**。
//!
//! 纯存储逻辑在 `editor_core::recovery`：写索引、编码场景、保留上限、
//! 丢弃与损坏处理。这里只负责三件事：
//!
//! 1. **什么时候写**：文档修订号变了、且距离上次写入超过间隔；
//! 2. **什么时候删**：场景保存成功、用户显式恢复或丢弃；
//! 3. **启动时发现什么**：把恢复点列表装进界面状态，交给对话框显示。
//!
//! # 为什么不做"退出时写恢复点"
//!
//! 正常退出意味着用户已经选择了保存或放弃。退出时再写一个恢复点，
//! 下次启动会冒出一条"上次可能有未保存修改"——而那是用户主动关的，
//! 属于假警报。恢复点只服务于**非正常结束**。
//!
//! # 为什么间隔是 30 秒、且必须先有修订变化
//!
//! 编码整个场景在 1000 实体量级约几毫秒。每帧写会拖慢编辑；
//! 只在"改了东西"之后写，才既有意义又不浪费。30 秒是常见编辑器的默认节奏。

use bevy::prelude::*;
use editor_core::project::项目描述;
use editor_core::recovery::{比场景更新, 恢复点存储, 默认自动保存间隔秒};
use editor_core::state::编辑器状态;

use crate::plugin::{EditorStateHolder, UiStateHolder};

/// 自动保存运行时状态。
#[derive(Resource, Default)]
pub struct 自动保存状态 {
    /// 上次写恢复点的时刻（`None` 表示本次会话还没写过）。
    上次写入: Option<std::time::Instant>,
    /// 上次写入时的文档修订号。
    上次修订: u64,
    /// 上次写入失败的原因（只显示一次，避免每帧刷日志）。
    最后错误: Option<String>,
}

/// 当前秒级时间戳（与 `editor_core` 内部保持同一口径）。
fn 当前时间秒() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|时长| 时长.as_secs())
        .unwrap_or(0)
}

/// 从编辑器状态取恢复点存储（没有项目时返回 `None`）。
fn 取存储(编辑器: &编辑器状态) -> Option<恢复点存储> {
    let 项目 = 编辑器.项目.as_ref()?;
    Some(恢复点存储::新建(项目.根目录()))
}

/// 定期写恢复点。
///
/// 必须排在 `actions::执行动作队列` 之后：本帧刚做的编辑应当进入本次恢复点，
/// 而不是等下一帧。
pub fn 自动保存(
    mut 状态: ResMut<自动保存状态>,
    mut 界面: ResMut<UiStateHolder>,
    编辑器: Res<EditorStateHolder>,
) {
    let 编辑 = &编辑器.状态;
    let Some(存储) = 取存储(编辑) else {
        return;
    };
    // 只有真的改过才写。`有未保存修改` 覆盖了撤销栈与隐式修复两条路径。
    if !编辑.有未保存修改() {
        return;
    }
    let 修订 = 编辑.文档修订();
    if 修订 == 状态.上次修订 {
        return;
    }
    let 该写 = match 状态.上次写入 {
        None => true,
        Some(上次) => 上次.elapsed().as_secs() >= 默认自动保存间隔秒,
    };
    if !该写 {
        return;
    }

    match 存储.写入(编辑.会话.路径.as_ref(), &编辑.会话.文档, 当前时间秒()) {
        Ok(元数据) => {
            状态.上次写入 = Some(std::time::Instant::now());
            状态.上次修订 = 修订;
            状态.最后错误 = None;
            // 让对话框/状态栏能看到"刚写了恢复点"，但不要刷屏：
            // 只在界面提示里更新一行，不写控制台。
            界面.状态.最近恢复点时间 = Some(元数据.时间);
        }
        Err(错误) => {
            状态.上次写入 = Some(std::time::Instant::now());
            状态.上次修订 = 修订;
            if 状态.最后错误.as_deref() != Some(错误.as_str()) {
                状态.最后错误 = Some(错误.clone());
                bevy::log::warn!("自动保存恢复点失败：{错误}");
            }
        }
    }
}

/// 保存成功后清掉该场景的恢复点。
///
/// 由动作层在 `保存场景到` 之后调用：恢复点的意义是"还有没保存的东西"，
/// 保存了它就该消失，否则下次启动会提示"恢复上次修改"——恢复出来一模一样。
pub fn 保存后清理恢复点(编辑器: &编辑器状态) {
    let Some(项目) = 编辑器.项目.as_ref() else {
        return;
    };
    let 存储 = 恢复点存储::新建(项目.根目录());
    if let Err(错误) = 存储.丢弃场景(编辑器.会话.路径.as_ref()) {
        bevy::log::warn!("清理恢复点失败：{错误}");
        return;
    }
    // 首次保存会把"未命名场景"变成有路径的场景，但恢复点是在保存**之前**
    // 写的，它的场景路径是 `None`。只按新路径清理会漏掉它，
    // 下次启动就会提示一个和磁盘完全一样的"恢复点"。
    if let Err(错误) = 存储.丢弃场景(None) {
        bevy::log::warn!("清理未命名场景恢复点失败：{错误}");
    }
}

/// 启动时扫描恢复点，把"比磁盘新"的那些放进界面状态。
///
/// 不自动恢复：自动把旧内容装进编辑器会覆盖用户刚打开的场景，
/// 而且撤销栈已经被清空，用户退不回去。只提示，由用户决定。
pub fn 启动扫描恢复点(mut 界面: ResMut<UiStateHolder>, 编辑器: Res<EditorStateHolder>) {
    let Some(项目) = 编辑器.状态.项目.as_ref() else {
        return;
    };
    扫描项目恢复点(&mut 界面.状态, 项目);
}

/// 供启动系统与测试共用的扫描实现。
pub fn 扫描项目恢复点(界面: &mut editor_ui::界面状态, 项目: &项目描述) {
    let 存储 = 恢复点存储::新建(项目.根目录());
    let 列表 = match 存储.读取索引() {
        Ok(索引) => 索引.恢复点,
        Err(错误) => {
            // 索引坏了不阻止启动，但要如实说。
            界面.恢复点错误 = Some(错误);
            return;
        }
    };
    let mut 候选 = Vec::new();
    for 元数据 in 列表 {
        // 只提示"比磁盘上的场景更新"的恢复点：否则用户每次启动都会被
        // 已经过时的恢复点打扰。
        let 场景绝对 = 元数据
            .场景路径
            .as_deref()
            .and_then(|文本| scene_doc::path::项目相对路径::解析(文本).ok())
            .map(|路径| 项目.绝对路径(&路径));
        let 值得提示 = match 场景绝对 {
            Some(路径) => 比场景更新(元数据.时间, &路径),
            // 未命名场景没有磁盘文件，恢复点一定更新。
            None => true,
        };
        if 值得提示 {
            候选.push(元数据);
        }
    }
    候选.sort_by_key(|项| std::cmp::Reverse(项.时间));
    界面.恢复点候选 = 候选;
    界面.恢复点错误 = None;
}

/// 恢复一个恢复点：把内容装进编辑器，并标记为未保存。
///
/// 不写盘：用户看到内容后自己决定保存到哪里。这样即使恢复错了，
/// 也不会破坏磁盘上的原场景。
pub fn 恢复恢复点(编辑器: &mut 编辑器状态, 元数据: &editor_core::recovery::恢复点元数据) -> Result<(), String> {
    let Some(项目) = 编辑器.项目.as_ref() else {
        return Err("没有打开的项目".to_string());
    };
    let 存储 = 恢复点存储::新建(项目.根目录());
    let 文档 = 存储.读取内容(元数据)?;
    let 路径 = 元数据
        .场景路径
        .as_deref()
        .and_then(|文本| scene_doc::path::项目相对路径::解析(文本).ok());
    编辑器.应用已载入场景(文档, 路径);
    // 恢复出来的内容与磁盘不一致，必须让保存按钮亮起来。
    编辑器.撤销.强制标记未保存();
    编辑器.警告(format!(
        "已恢复「{}」的自动保存内容（{} 个实体，记录时间 {}）。请检查后保存到目标场景；磁盘上的原文件未被修改。",
        元数据.场景名, 元数据.实体数, 元数据.时间
    ));
    Ok(())
}
