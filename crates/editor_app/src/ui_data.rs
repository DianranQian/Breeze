//! 界面组件的纯投影：把文档里的 `UiNode` / `UiText` / `UiButton` / `UiImage`
//! 解释成与渲染无关的「界面项」。
//!
//! # 为什么单独一层
//!
//! 同一份场景数据有两个消费方：
//!
//! * 编辑器预览（`ui_preview`）——画在预览相机的渲染目标上；
//! * 运行时世界（`ui_runtime`）——点「运行」后投影成真实的 Bevy UI 节点。
//!
//! 两边如果各写一遍"面板优先、按钮其次、缺省尺寸是多少"，必然会在某次改动后
//! 悄悄分叉：预览里按钮在左上角、运行起来跑到别处。因此几何与内容的解释只
//! 留在这里一份，渲染侧只做"界面项 → Bevy 组件"的机械翻译。
//!
//! # 几何与内容的优先级
//!
//! | 实体挂载 | 盒子来源 | 内容 |
//! | --- | --- | --- |
//! | `UiNode` | 面板自己的锚点/偏移/宽高 | 下面按内容层再选 |
//! | 无面板 + `UiImage` | 图片自己的锚点/偏移/宽高 | 图片 |
//! | 无面板 + `UiButton` | 240×64，左上 (40, 40) | 按钮文案 |
//! | 无面板 + `UiText` | 由文字自动撑开，左上 (40, 40) | 文本文案 |
//!
//! 内容层优先级：按钮 > 文本 > 图片。一个实体同时挂两种内容时只画优先级
//! 最高的那种 —— 叠着画会重影，而用户真正想要的是"换一种内容"，
//! 分开两个实体反而更清楚。

use scene_doc::document::{场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::property::{属性值, 颜色值};

use crate::ui_components::{
    文本对齐, 界面图片组件名, 界面按钮组件名, 界面文本组件名, 界面面板组件名,
};

/// 界面元素的内容层。
#[derive(Debug, Clone, PartialEq)]
pub enum 界面内容 {
    /// 一段文字（来自 `UiText` 或 `UiButton`）。
    文案(文案项),
    /// 一张图片（来自 `UiImage`）。
    图片(图片项),
}

/// 文案参数。
#[derive(Debug, Clone, PartialEq)]
pub struct 文案项 {
    /// 文本内容。
    pub 文本: String,
    /// 字号（设计分辨率下的像素）。
    pub 字号: f32,
    /// 文字颜色。
    pub 颜色: 颜色值,
    /// 文本在自身盒内的水平对齐。
    pub 对齐: 文本对齐,
}

/// 图片参数。
#[derive(Debug, Clone, PartialEq)]
pub struct 图片项 {
    /// 贴图的项目相对路径；`None` 时画成纯色块。
    pub 贴图路径: Option<项目相对路径>,
    /// 与贴图逐像素相乘的着色。
    pub 着色: 颜色值,
}

/// 一个界面元素的布局盒与内容（纯数据）。
#[derive(Debug, Clone, PartialEq)]
pub struct 界面项 {
    /// 来源实体。
    pub 来源: 实体标识,
    /// 锚点预设。
    pub 锚点: editor_core::ui_layout::界面锚点,
    /// 相对锚点的像素偏移。
    pub 偏移: (f32, f32),
    /// 宽、高（像素）。`0` 表示由内容自动撑开。
    pub 尺寸: (f32, f32),
    /// 盒子背景色。
    pub 背景色: 颜色值,
    /// 内容层；`None` 表示只有底色。
    pub 内容: Option<界面内容>,
}

/// 把颜色值转成 Bevy 颜色。
///
/// 界面颜色一律按 sRGB 解释并夹在合法范围：界面文档里没有线性空间这个概念，
/// 允许越界只会让颜色在投影后悄悄变成另一块颜色。
pub fn 颜色转_bevy(颜色: 颜色值) -> bevy::prelude::Color {
    bevy::prelude::Color::srgba(
        颜色.红.clamp(0.0, 1.0),
        颜色.绿.clamp(0.0, 1.0),
        颜色.蓝.clamp(0.0, 1.0),
        颜色.透明度.clamp(0.0, 1.0),
    )
}

fn 取浮点(组件: &组件数据, 字段: &str, 默认: f32) -> f32 {
    组件.属性.get(字段).and_then(属性值::取浮点).unwrap_or(默认)
}

fn 取颜色(组件: &组件数据, 字段: &str, 默认: 颜色值) -> 颜色值 {
    组件.属性.get(字段).and_then(属性值::取颜色).unwrap_or(默认)
}

fn 取文本(组件: &组件数据, 字段: &str, 默认: &str) -> String {
    match 组件.属性.get(字段) {
        Some(属性值::文本(文本)) => 文本.clone(),
        _ => 默认.to_string(),
    }
}

fn 取锚点(组件: Option<&组件数据>) -> editor_core::ui_layout::界面锚点 {
    match 组件.and_then(|组件| 组件.属性.get("锚点")) {
        Some(属性值::枚举(枚举)) => {
            editor_core::ui_layout::界面锚点::由值(&枚举.变体名, 枚举.序号)
        }
        _ => editor_core::ui_layout::界面锚点::左上,
    }
}

fn 取对齐(组件: Option<&组件数据>) -> 文本对齐 {
    match 组件.and_then(|组件| 组件.属性.get("对齐")) {
        Some(属性值::枚举(枚举)) => 文本对齐::由值(&枚举.变体名, 枚举.序号),
        _ => 文本对齐::左,
    }
}

fn 取资源路径(组件: &组件数据, 字段: &str) -> Option<项目相对路径> {
    组件
        .属性
        .get(字段)
        .and_then(属性值::取资源)
        .map(|引用| 引用.路径.clone())
}

/// 从文档里收集界面元素（纯函数，预览与运行时共用）。
pub fn 收集界面项(文档: &场景文档) -> Vec<界面项> {
    let mut 结果 = Vec::new();
    for 标识 in 文档.文档遍历() {
        let Some(实体) = 文档.取(标识) else {
            continue;
        };
        let 面板 = 实体.取组件(界面面板组件名);
        let 按钮 = 实体.取组件(界面按钮组件名);
        let 文本 = 实体.取组件(界面文本组件名);
        let 图片 = 实体.取组件(界面图片组件名);
        if 面板.is_none() && 按钮.is_none() && 文本.is_none() && 图片.is_none() {
            continue;
        }

        // 几何：面板 > 图片 > 按钮 > 纯文本。
        let (锚点, 尺寸, 偏移, 背景色) = if let Some(组件) = 面板 {
            (
                取锚点(Some(组件)),
                (
                    取浮点(组件, "宽度", 320.0).max(0.0),
                    取浮点(组件, "高度", 180.0).max(0.0),
                ),
                (取浮点(组件, "偏移X", 40.0), 取浮点(组件, "偏移Y", 40.0)),
                取颜色(组件, "背景色", 颜色值::srgb(0.10, 0.12, 0.16, 0.88)),
            )
        } else if let Some(组件) = 图片 {
            (
                取锚点(Some(组件)),
                (
                    取浮点(组件, "宽度", 256.0).max(0.0),
                    取浮点(组件, "高度", 256.0).max(0.0),
                ),
                (取浮点(组件, "偏移X", 40.0), 取浮点(组件, "偏移Y", 40.0)),
                颜色值::srgb(0.0, 0.0, 0.0, 0.0),
            )
        } else if let Some(组件) = 按钮 {
            (
                取锚点(None),
                (240.0, 64.0),
                (40.0, 40.0),
                取颜色(组件, "背景色", 颜色值::srgb(0.20, 0.48, 0.85, 1.0)),
            )
        } else {
            // 纯文本：不给固定尺寸，让文字自己撑开。
            (
                取锚点(None),
                (0.0, 0.0),
                (40.0, 40.0),
                颜色值::srgb(0.0, 0.0, 0.0, 0.0),
            )
        };

        // 内容：按钮 > 文本 > 图片。
        let 内容 = if let Some(组件) = 按钮 {
            Some(界面内容::文案(文案项 {
                文本: 取文本(组件, "文本", "按钮"),
                字号: 取浮点(组件, "字号", 22.0).clamp(1.0, 512.0),
                颜色: 取颜色(组件, "文字颜色", 颜色值::白()),
                // 按钮文案在按钮盒里居中：这是按钮与普通文本的唯一语义差别。
                对齐: 文本对齐::居中,
            }))
        } else if let Some(组件) = 文本 {
            Some(界面内容::文案(文案项 {
                文本: 取文本(组件, "文本", "文字"),
                字号: 取浮点(组件, "字号", 24.0).clamp(1.0, 512.0),
                颜色: 取颜色(组件, "颜色", 颜色值::白()),
                对齐: 取对齐(Some(组件)),
            }))
        } else {
            图片.map(|组件| {
                界面内容::图片(图片项 {
                    贴图路径: 取资源路径(组件, "贴图"),
                    着色: 取颜色(组件, "着色", 颜色值::白()),
                })
            })
        };

        结果.push(界面项 {
            来源: 标识,
            锚点,
            偏移,
            尺寸,
            背景色,
            内容,
        });
    }
    结果
}

/// 把一个界面项换算成设计分辨率下的像素矩形。
pub fn 计算矩形(
    项: &界面项, 设计宽: f32, 设计高: f32
) -> editor_core::ui_layout::像素矩形 {
    editor_core::ui_layout::计算像素矩形(
        editor_core::ui_layout::界面盒 {
            锚点: 项.锚点,
            偏移x: 项.偏移.0,
            偏移y: 项.偏移.1,
            宽: 项.尺寸.0,
            高: 项.尺寸.1,
        },
        设计宽,
        设计高,
    )
}

#[cfg(test)]
mod 测试 {
    use super::*;

    fn 挂组件(
        文档: &mut 场景文档,
        名称: &str,
        组件名: &str,
        字段: &[(&str, 属性值)],
    ) -> 实体标识 {
        let 标识 = 文档.生成实体(名称, None);
        let 属性: std::collections::BTreeMap<String, 属性值> = 字段
            .iter()
            .map(|(键, 值)| ((*键).to_string(), 值.clone()))
            .collect();
        if let Some(实体) = 文档.取可变(标识) {
            实体.加组件(组件数据::新建(组件名, 属性));
        }
        标识
    }

    #[test]
    fn 面板几何优先于内容层() {
        let mut 文档 = 场景文档::新建("界面");
        挂组件(
            &mut 文档,
            "面板",
            界面面板组件名,
            &[
                ("宽度", 属性值::浮点(800.0)),
                ("高度", 属性值::浮点(600.0)),
                ("偏移X", 属性值::浮点(10.0)),
                ("偏移Y", 属性值::浮点(20.0)),
            ],
        );
        let 标识 = 挂组件(
            &mut 文档,
            "混合",
            界面面板组件名,
            &[("宽度", 属性值::浮点(400.0))],
        );
        if let Some(实体) = 文档.取可变(标识) {
            实体.加组件(组件数据::新建(
                界面图片组件名,
                [("宽度".to_string(), 属性值::浮点(999.0))]
                    .into_iter()
                    .collect(),
            ));
        }

        let 项 = 收集界面项(&文档);
        assert_eq!(项[0].尺寸, (800.0, 600.0));
        assert_eq!(项[0].偏移, (10.0, 20.0));
        assert!(项[0].内容.is_none(), "只有面板时没有内容层");
        assert_eq!(项[1].尺寸, (400.0, 180.0), "面板尺寸战胜图片尺寸");
        assert!(matches!(项[1].内容, Some(界面内容::图片(_))));
    }

    #[test]
    fn 图片按自己的锚点放置() {
        let mut 文档 = 场景文档::新建("界面");
        挂组件(
            &mut 文档,
            "徽标",
            界面图片组件名,
            &[
                ("宽度", 属性值::浮点(64.0)),
                ("高度", 属性值::浮点(32.0)),
                ("偏移X", 属性值::浮点(12.0)),
                ("偏移Y", 属性值::浮点(8.0)),
                (
                    "锚点",
                    属性值::枚举(scene_doc::property::枚举值::新建("BottomRight", 3)),
                ),
            ],
        );
        let 项 = 收集界面项(&文档);
        assert_eq!(项[0].锚点, editor_core::ui_layout::界面锚点::右下);
        let 矩形 = 计算矩形(&项[0], 800.0, 600.0);
        assert_eq!(
            (矩形.左, 矩形.上),
            (800.0 - 64.0 - 12.0, 600.0 - 32.0 - 8.0)
        );
    }

    #[test]
    fn 无面板按钮用自身背景色并居中() {
        let mut 文档 = 场景文档::新建("界面");
        挂组件(&mut 文档, "开始", 界面按钮组件名, &[]);
        let 项 = 收集界面项(&文档);
        assert_eq!(项[0].尺寸, (240.0, 64.0));
        let 背景 = 项[0].背景色;
        assert!(背景.透明度 > 0.0, "无面板按钮必须有可见背景，实际 {背景:?}");
        let Some(界面内容::文案(文案)) = &项[0].内容 else {
            panic!("按钮必须带文案");
        };
        assert_eq!(文案.文本, "按钮");
        assert_eq!(文案.对齐, 文本对齐::居中);
    }

    #[test]
    fn 内容层优先级是按钮大于文本大于图片() {
        let mut 文档 = 场景文档::新建("界面");
        let 标识 = 挂组件(&mut 文档, "全挂", 界面按钮组件名, &[]);
        if let Some(实体) = 文档.取可变(标识) {
            实体.加组件(组件数据::新建(界面文本组件名, Default::default()));
            实体.加组件(组件数据::新建(界面图片组件名, Default::default()));
        }
        let 项 = 收集界面项(&文档);
        assert!(matches!(项[0].内容, Some(界面内容::文案(_))));
        let Some(界面内容::文案(文案)) = &项[0].内容 else {
            unreachable!()
        };
        assert_eq!(文案.文本, "按钮", "按钮文案优先于文本与图片");
    }

    #[test]
    fn 非界面实体不计入() {
        let mut 文档 = 场景文档::新建("界面");
        文档.生成实体("箱子", None);
        assert!(收集界面项(&文档).is_empty());
    }
}
