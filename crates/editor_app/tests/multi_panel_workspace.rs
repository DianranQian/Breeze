#[test]
fn 面板布局可以序列化并原样恢复() {
    let mut 世界 = 建测试世界();

    // 先改乱布局：只留视口，再把控制台加回来。
    {
        let mut 界面 = 世界.resource_mut::<UiStateHolder>();
        界面
            .状态
            .设定当前布局(egui_dock::DockState::new(vec![Tab::视口]));
        界面.状态.聚焦面板(Tab::控制台);
    }

    let 序列化 = {
        let 界面 = 世界.resource::<UiStateHolder>();
        界面.状态.工作区序列化为文本().expect("工作区应当能序列化")
    };
    assert!(!序列化.is_empty());

    // 恢复到一个全新的界面状态里 —— 模拟"重启编辑器后读配置"。
    let mut 界面 = UiStateHolder::新建();
    assert_ne!(
        界面.状态.布局指纹(),
        世界.resource::<UiStateHolder>().状态.布局指纹(),
        "新界面应当是默认布局，与改乱后的布局不同（否则这条测试没有意义）"
    );

    界面
        .状态
        .从文本恢复工作区(&序列化)
        .expect("工作区应当能恢复");

    assert_eq!(
        界面.状态.布局指纹(),
        世界.resource::<UiStateHolder>().状态.布局指纹(),
        "序列化再恢复之后，每个面板的位置必须完全一致"
    );
    assert!(界面.状态.面板可见(Tab::视口));
    assert!(界面.状态.面板可见(Tab::控制台));
    assert!(
        !界面.状态.面板可见(Tab::场景树),
        "被关闭的面板恢复后仍应是关闭的（否则用户关不掉面板）"
    );
}

