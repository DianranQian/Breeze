/// 组件注册表里的显示名与提示必须是**合法的词条键**。
///
/// # 这是一条回归测试
///
/// 上一轮把 `属性描述.显示名` 的类型改成了 `&'static str`，
/// 但注册表里塞进去的仍是**中文**（`布尔("可见", "可见", true)`）。
/// Inspector 执行 `语言.取("可见")` 查不到键，于是英文模式下
/// 字段名与提示依然是中文 —— 而当时所有测试都是绿的：
/// 类型对、词表完整、调用点核对也通过（因为字形上没有"调用"）。
///
/// 这条直接盯住"注册表里的显示名必须是键"：只要有人再往里写中文，
/// `语言::有键` 就会失败并指出是哪一条。
#[test]
fn 注册表里的显示名与提示都是合法词条键() {
    use editor_core::i18n::语言;

    let 注册表 = editor_app::scene_bridge::默认组件注册表();
    let mut 非法 = Vec::new();

    for 组件名 in editor_app::scene_bridge::内置组件名列表() {
        let Ok(类型) = 注册表.要求(&组件名) else {
            continue;
        };
        for 描述 in 类型.字段描述() {
            if !语言::中文.有键(描述.显示名) {
                非法.push(format!(
                    "{组件名}.{} 的显示名 `{}`",
                    描述.字段名, 描述.显示名
                ));
            }
            // 提示可以为空（表示没有提示），非空时必须也是键
            if !描述.提示.is_empty() && !语言::中文.有键(描述.提示) {
                非法.push(format!("{组件名}.{} 的提示 `{}`", 描述.字段名, 描述.提示));
            }
        }
    }

    assert!(
        非法.is_empty(),
        "以下注册表条目存的不是词条键（英文模式下会原样显示）：{非法:#?}"
    );
}

/// 注册表里的显示名不能直接就是中文。
///
/// 与上一条互补：上一条要求"是合法的键"，这一条明确禁止"把中文当键"。
/// 两条一起，既挡住拼错的键，也挡住中文原文。
#[test]
fn 注册表里的显示名不含中文() {
    let 注册表 = editor_app::scene_bridge::默认组件注册表();
    let mut 含中文 = Vec::new();

    for 组件名 in editor_app::scene_bridge::内置组件名列表() {
        let Ok(类型) = 注册表.要求(&组件名) else {
            continue;
        };
        for 描述 in 类型.字段描述() {
            for (字段, 值) in [("显示名", 描述.显示名), ("提示", 描述.提示)] {
                if 值.chars().any(
                    |c| matches!(u32::from(c), 0x3000..=0x303F | 0x4E00..=0x9FFF | 0xFF00..=0xFFEF),
                ) {
                    含中文.push(format!("{组件名}.{} 的{字段} `{值}`", 描述.字段名));
                }
            }
        }
    }

    assert!(
        含中文.is_empty(),
        "注册表把中文当成了键 —— 应当改为 ASCII 符号键、由界面查表：{含中文:#?}"
    );
}

