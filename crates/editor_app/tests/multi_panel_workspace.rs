    for 名称 in ["预览精灵", "编辑器相机", "网格线", "坐标轴", "选中框"] {
        世界.spawn((Name::new(名称.to_string()), Transform::default()));
    }
    // 再加一个与文档实体同名的干扰项，确认不是靠名字区分
    世界.spawn((Name::new("用户实体甲".to_string()), Transform::default()));

    let 渲染世界实体数 = 世界.entities().count_spawned();
    assert!(
        渲染世界实体数 > 2,
        "渲染世界里应当有额外的辅助实体（否则这条测试没有意义）"
    );

    // 保存场景
    let 场景路径 = 项目相对路径::解析("scenes/纯净.scene.ron").unwrap();
    推动作(&mut 世界, vec![UiAction::场景另存为(场景路径.clone())]);
