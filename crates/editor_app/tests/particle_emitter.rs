#[test]
fn 粒子组件字段可供检查器编辑() {
    let 注册表 = 全部内置组件注册表();
    assert!(注册表.已注册(粒子发射器组件名));

    let 类型 = 粒子发射器组件类型;
    let 字段: Vec<&str> = 类型
        .字段描述()
        .iter()
        .map(|描述| 描述.字段名.as_str())
        .collect();
    assert_eq!(
        字段,
        [
            发射速率字段,
            生命周期字段,
            初始速度字段,
            颜色字段,
            粒子大小字段
        ]
    );

    let mut 实例 = 类型.默认实例();
    let mut 数据 = std::collections::BTreeMap::new();
    数据.insert(发射速率字段.to_string(), 属性值::浮点(999.0));
    数据.insert(生命周期字段.to_string(), 属性值::浮点(0.0));
    数据.insert(粒子大小字段.to_string(), 属性值::浮点(99.0));
    assert!(类型.实例化(实例.as_mut(), &数据));

    let 属性 = 实例.downcast_ref::<粒子发射器属性>().unwrap();
    assert_eq!(属性.发射速率, 最大发射速率, "离谱的速率要被夹住");
    assert_eq!(属性.生命周期, 0.1, "寿命不能为零");
    assert_eq!(属性.粒子大小, 最大粒子大小);

    let 导出 = 类型.导出(实例.as_ref()).expect("必须能导出");
    assert_eq!(
        导出.get(发射速率字段).and_then(属性值::取浮点),
        Some(最大发射速率)
    );
}
