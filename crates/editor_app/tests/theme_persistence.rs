//! 中文名：主题持久化
//! 主题持久化与"主题 / 工作区互不干扰"的端到端测试。
//!
//! # 为什么这两件事要放在一起测
//!
//! 主题与工作区是两个独立的配置维度。它们最容易出的问题不是"各自坏了"，
//! 而是**互相踩到**：切主题把布局重置了、改布局把主题覆盖了、
//! 主题存档损坏连带工作区一起丢。这些都必须用真实配置文件路径来验证，
//! 否则只是"数据结构自洽"而不是"行为正确"。
//!
//! 所有测试都用独立的临时配置目录，不会碰真实用户配置。

use editor_app::config::编辑器配置;
use editor_ui::theme::{主题库, 内置主题};
use editor_ui::{Tab, 界面状态};

fn 临时配置路径(目录: &tempfile::TempDir) -> std::path::PathBuf {
    目录.path().join("BevyStudio").join("config.ron")
}

/// 把主题库写进配置并读回。
fn 往返(界面: &界面状态, 路径: &std::path::Path) -> 主题库 {
    let 配置 = 编辑器配置 {
        主题: Some(界面.主题库.序列化为文本().expect("主题应当能序列化")),
        ..Default::default()
    };
    配置.保存(路径).expect("配置应当能保存");
    let 读回 = 编辑器配置::载入(路径);
    主题库::从文本恢复(读回.主题.as_deref().expect("配置里应当有主题")).expect("主题应当能恢复")
}

#[test]
fn 主题库写入配置后重启能恢复当前主题() {
    let 目录 = tempfile::tempdir().unwrap();
    let 路径 = 临时配置路径(&目录);

    let mut 界面 = 界面状态::新建();
    let 草稿 = 界面
        .主题库
        .新建主题("夜间护眼", editor_ui::i18n::语言::中文)
        .expect("新建应当成功");
    let id = 草稿.id.clone();
    let mut 草稿 = 草稿;
    草稿.配色.强调 = egui::Color32::from_rgb(1, 2, 3);
    草稿.外观.基础字号 = 15.0;
    界面.主题库.保存(草稿).unwrap();

    let 恢复 = 往返(&界面, &路径);
    assert_eq!(恢复.当前id(), id, "重启后应当回到上次的主题");
    assert_eq!(恢复.当前().配色.强调, egui::Color32::from_rgb(1, 2, 3));
    assert_eq!(恢复.当前().外观.基础字号, 15.0);
    assert_eq!(恢复.用户数量(), 1);
}

#[test]
fn 切主题不改变工作区布局() {
    let mut 界面 = 界面状态::新建();
    let 布局前 = 界面.布局指纹();
    let 工作区前 = 界面.工作区.当前id().to_string();

    界面
        .主题库
        .切换(内置主题::浅色.id())
        .expect("切主题应当成功");

    assert_eq!(界面.布局指纹(), 布局前, "切主题不得改变面板布局");
    assert_eq!(界面.工作区.当前id(), 工作区前, "切主题不得改变工作区");
}

#[test]
fn 切工作区不改变主题() {
    let mut 界面 = 界面状态::新建();
    界面.主题库.切换(内置主题::高对比度.id()).unwrap();
    let 主题前 = 界面.主题库.当前id().to_string();

    界面
        .工作区
        .切换(editor_ui::workspaces::内置工作区::场景.id())
        .expect("切工作区应当成功");

    assert_eq!(界面.主题库.当前id(), 主题前, "切工作区不得改变主题");
}

#[test]
fn 切语言不改变主题与工作区() {
    let mut 界面 = 界面状态::新建();
    let 主题前 = 界面.主题库.当前id().to_string();
    let 工作区前 = 界面.工作区.当前id().to_string();
    let 布局前 = 界面.布局指纹();

    界面.语言 = editor_ui::i18n::语言::英文;

    assert_eq!(界面.主题库.当前id(), 主题前);
    assert_eq!(界面.工作区.当前id(), 工作区前);
    assert_eq!(界面.布局指纹(), 布局前);
    // 面板 ID 与词条都随语言切换，但布局里的面板身份不变。
    assert!(界面.面板可见(Tab::视口));
}

#[test]
fn 损坏的主题存档回退内置且不影响工作区() {
    let 目录 = tempfile::tempdir().unwrap();
    let 路径 = 临时配置路径(&目录);

    // 同一份配置里放一个合法工作区 + 一个坏主题。
    let 界面 = 界面状态::新建();
    let 配置 = 编辑器配置 {
        工作区: Some(界面.工作区序列化为文本().unwrap()),
        主题: Some("这不是 RON {{{".to_string()),
        ..Default::default()
    };
    配置.保存(&路径).unwrap();

    let 读回 = 编辑器配置::载入(&路径);
    assert_eq!(读回.格式版本, 2, "坏主题不应让整个配置失效");

    // 工作区必须完好。
    let mut 恢复 = 界面状态::新建();
    恢复
        .从文本恢复工作区(读回.工作区.as_deref().unwrap())
        .expect("工作区应当能恢复");
    assert!(恢复.面板可见(Tab::视口));

    // 主题回退到内置深色。
    let 主题结果 = 主题库::从文本恢复(读回.主题.as_deref().unwrap());
    assert!(主题结果.is_err(), "坏主题必须返回错误");
    let 回退 = 主题结果.unwrap_or_else(|_| 主题库::新建());
    assert_eq!(回退.当前id(), 内置主题::深色.id());
}

#[test]
fn 外观参数在存档里被收敛到安全区间() {
    let 目录 = tempfile::tempdir().unwrap();
    let 路径 = 临时配置路径(&目录);

    // 手写一个外观极端值，模拟用户手改配置文件。
    let mut 界面 = 界面状态::新建();
    let 草稿 = 界面
        .主题库
        .新建主题("极端", editor_ui::i18n::语言::中文)
        .unwrap();
    let mut 草稿 = 草稿;
    草稿.外观.缩放 = 99.0;
    草稿.外观.间距 = 0.0;
    界面.主题库.保存(草稿).unwrap();

    let 恢复 = 往返(&界面, &路径);
    let 外观 = 恢复.当前().外观.收敛();
    assert!(外观.缩放 <= 2.0, "缩放必须被夹到上限");
    assert!(外观.间距 >= 2.0, "间距必须被夹到下限");
}

#[test]
fn 内置主题被修改后能恢复出厂配色() {
    let mut 界面 = 界面状态::新建();
    let 原强调 = 界面.主题库.当前().配色.强调;
    let mut 草稿 = 界面.主题库.当前().clone();
    草稿.配色.强调 = egui::Color32::from_rgb(9, 9, 9);
    界面.主题库.保存(草稿).unwrap();
    assert_eq!(
        界面.主题库.当前().配色.强调,
        egui::Color32::from_rgb(9, 9, 9)
    );

    let id = 界面.主题库.当前id().to_string();
    assert!(界面.主题库.重置内置主题(&id));
    assert_eq!(界面.主题库.当前().配色.强调, 原强调);
}
