//! 工作区持久化的端到端测试（不启动 Bevy 应用）。
//!
//! # 为什么这些测试必须用独立临时目录
//!
//! 工作区配置落在用户配置目录（Windows 上是 `%APPDATA%\BevyStudio\config.ron`）。
//! 测试如果走真实路径，会**覆盖开发者自己的工作区**，而且测试之间互相污染 ——
//! 两个测试并行跑时谁先写谁后读完全不确定。
//!
//! 因此这里每个测试都 `tempfile::tempdir()` 一个目录，把配置路径指过去。
//! 这也是需求里明确要求的一点。
//!
//! # 覆盖的行为
//!
//! * 工作区集能写进配置文件并原样读回（重启恢复）；
//! * 旧版单布局配置被迁移成工作区，且用户上次的布局不丢；
//! * 损坏的配置/存档安全回退，不会让编辑器打不开；
//! * 在某个工作区里改布局不影响其他工作区；
//! * 语言切换不改变工作区身份与布局。

use editor_app::config::{编辑器配置, 配置格式版本};
use editor_ui::workspaces::{内置工作区, 工作区集};
use editor_ui::{Tab, 界面状态};

/// 建一个隔离的配置路径。
fn 临时配置路径(目录: &tempfile::TempDir) -> std::path::PathBuf {
    目录.path().join("BevyStudio").join("config.ron")
}

/// 把界面状态里的工作区集写进配置并落盘，再读回来恢复。
fn 往返(界面: &界面状态, 路径: &std::path::Path) -> 界面状态 {
    let mut 配置 = 编辑器配置 {
        工作区: Some(界面.工作区序列化为文本().expect("应当能序列化工作区")),
        ..Default::default()
    };
    配置
        .偏好
        .insert("语言".to_string(), 界面.语言.代号().to_string());
    配置.保存(路径).expect("配置应当能保存");

    let 读回 = 编辑器配置::载入(路径);
    let 文本 = 读回.工作区.expect("配置里应当有工作区");
    let mut 恢复 = 界面状态::新建();
    恢复.从文本恢复工作区(&文本).expect("工作区应当能恢复");
    if let Some(代号) = 读回.偏好.get("语言") {
        恢复.语言 = editor_ui::i18n::语言::从代号(代号);
    }
    恢复
}

#[test]
fn 工作区集写入配置后重启能恢复当前项() {
    let 目录 = tempfile::tempdir().unwrap();
    let 路径 = 临时配置路径(&目录);

    let mut 界面 = 界面状态::新建();
    let id = 界面
        .工作区
        .新建工作区("关卡设计", false, editor_ui::i18n::语言::中文)
        .expect("新建工作区应当成功");
    // 在用户工作区里关掉几个面板，制造一个可辨认的布局。
    界面
        .工作区
        .布局_mut()
        .retain_tabs(|面板| *面板 != Tab::性能);

    let 恢复 = 往返(&界面, &路径);
    assert_eq!(恢复.工作区.当前id(), id, "重启后应当回到上次的工作区");
    assert_eq!(恢复.工作区.列表().len(), 5, "用户工作区必须随配置一起保存");
    assert!(!恢复.面板可见(Tab::性能), "工作区里的布局改动必须一起恢复");
}

#[test]
fn 旧版单布局配置被迁移成工作区() {
    let mut 配置 = 编辑器配置 {
        格式版本: 1,
        布局: Some(ron::ser::to_string(&内置工作区::场景.预设()).unwrap()),
        工作区: None,
        ..Default::default()
    };

    // 启动流程里的迁移分支（与 `plugin::恢复窗口布局` 相同逻辑）。
    let 集 = 工作区集::从旧布局迁移(
        配置.布局.as_deref().unwrap(),
        editor_ui::i18n::语言::中文,
    )
    .expect("旧配置应当能迁移");

    assert_eq!(集.当前id(), "user-migrated");
    assert!(集.面板可见(Tab::视口));
    assert_eq!(集.列表().len(), 5, "四个内置 + 一个迁移工作区");
    // 迁移后再保存，写出的应当是格式版本 2 的工作区字段。
    配置.工作区 = Some(集.序列化为文本().unwrap());
    assert!(配置.工作区.is_some());
}

#[test]
fn 损坏的工作区存档安全回退到内置工作区() {
    let 目录 = tempfile::tempdir().unwrap();
    let 路径 = 临时配置路径(&目录);
    // 手写配置文件时先建好目录（`编辑器配置::保存` 会自己建，
    // 但这里绕过了它，直接写文件）。
    std::fs::create_dir_all(路径.parent().unwrap()).unwrap();
    std::fs::write(&路径, "(格式版本: 2, 工作区: Some(\"这不是 RON\"))").unwrap();

    let 配置 = 编辑器配置::载入(&路径);
    assert_eq!(配置.格式版本, 2, "损坏的工作区不应让整个配置失败");

    let mut 界面 = 界面状态::新建();
    let 结果 = 界面.从文本恢复工作区(配置.工作区.as_deref().unwrap());
    assert!(结果.is_err(), "坏存档必须返回错误");
    assert_eq!(
        界面.工作区.当前id(),
        内置工作区::通用.id(),
        "恢复失败时界面必须保持可用的内置工作区"
    );
    assert!(界面.面板可见(Tab::视口));
}

#[test]
fn 一个工作区的改动不影响其他工作区() {
    let 目录 = tempfile::tempdir().unwrap();
    let 路径 = 临时配置路径(&目录);

    let mut 界面 = 界面状态::新建();
    // 在通用工作区里关掉控制台
    界面
        .工作区
        .布局_mut()
        .retain_tabs(|面板| *面板 != Tab::控制台);
    assert!(!界面.面板可见(Tab::控制台));

    // 切到场景工作区：它自己的布局必须有控制台
    界面
        .工作区
        .切换(内置工作区::场景.id())
        .expect("切换应当成功");
    assert!(界面.面板可见(Tab::控制台));

    // 往返之后，两个工作区的差异必须都还在
    let mut 恢复 = 往返(&界面, &路径);
    assert_eq!(恢复.工作区.当前id(), 内置工作区::场景.id());
    assert!(恢复.面板可见(Tab::控制台));
    // 切回通用：通用里的控制台仍是关闭状态（改动互不覆盖）。
    恢复
        .工作区
        .切换(内置工作区::通用.id())
        .expect("切回通用应当成功");
    assert!(
        !恢复.面板可见(Tab::控制台),
        "通用工作区里关掉的控制台必须保持关闭，不能被场景工作区的布局覆盖"
    );
}

#[test]
fn 切换语言不改变工作区身份与布局() {
    let mut 界面 = 界面状态::新建();
    let id = 界面
        .工作区
        .新建工作区("我的布局", false, editor_ui::i18n::语言::中文)
        .unwrap();
    let 指纹 = 界面.布局指纹();

    界面.语言 = editor_ui::i18n::语言::英文;

    assert_eq!(界面.工作区.当前id(), id, "语言不影响工作区 id");
    assert_eq!(界面.布局指纹(), 指纹, "语言不影响布局");
    assert_eq!(
        界面.工作区.当前().显示名(界面.语言),
        "我的布局",
        "用户工作区名称不翻译"
    );
    assert_eq!(
        界面.工作区.当前().显示名(editor_ui::i18n::语言::中文),
        "我的布局"
    );
}

