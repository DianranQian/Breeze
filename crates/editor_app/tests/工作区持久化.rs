#[test]
fn 内置工作区不能被删除且删除当前用户工作区安全回退() {
    let mut 界面 = 界面状态::新建();
    let 语言 = 界面.语言;
    assert!(
        界面.工作区.删除(内置工作区::通用.id(), 语言).is_err(),
        "内置工作区必须受保护"
    );

    let id = 界面.工作区.新建工作区("临时", false, 语言).unwrap();
    assert_eq!(界面.工作区.当前id(), id);
    界面.工作区.删除(&id, 语言).unwrap();
    assert_eq!(界面.工作区.当前id(), 内置工作区::通用.id());
    assert!(界面.面板可见(Tab::视口), "回退后的布局必须可用");
}
