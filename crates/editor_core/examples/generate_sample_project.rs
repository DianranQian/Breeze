//! 中文名：生成示例项目
//! 生成一个用于验证的示例项目。
//!
//! # 为什么用这个脚本而不是手写场景文件
//!
//! 场景文件是 RON，字段多、有 `Option`、有嵌套枚举，手写极容易出错 ——
//! 而且出错的形式很隐蔽：文件语法不对时编辑器只会显示一个空场景。
//!
//! 实测中手写这份 RON 连续踩了两次坑：
//!
//! 1. 字段之间漏了换行、多出一个逗号；
//! 2. `父实体` 与 `变换` 是 `Option<...>`，必须写 `Some(...)` ——
//!    而 `Expected option` 这种报错，不给行号根本猜不到是哪个字段。
//!
//! 换成走**编辑器自己的 API**（`新建实体` / `执行` / `添加组件` / `保存场景到`）
//! 之后，这类错误在结构上就不可能出现了：写出来的文件必然能被自己读回来，
//! 因为读写走的是同一套类型。
//!
//! # 用法
//!
//! ```powershell
//! cargo run -p editor_core --example generate_sample_project
//! $env:BEVY_STUDIO_OPEN_PROJECT = "<仓库>\.verify\示例项目"
//! .\bevy-studio.exe
//! ```

use std::path::PathBuf;

use editor_core::command::编辑器命令;
use editor_core::state::编辑器状态;
use scene_doc::document::{变换数据, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::property::{属性值, 颜色值};

type 结果<T> = Result<T, Box<dyn std::error::Error>>;

fn main() -> 结果<()> {
    // 输出到仓库根目录下的 `.verify/示例项目`
    let 仓库根 = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|目录| 目录.parent())
        .ok_or("定位仓库根目录失败")?
        .to_path_buf();
    let 项目根 = 仓库根.join(".verify").join("示例项目");
    if 项目根.exists() {
        std::fs::remove_dir_all(&项目根)?;
    }

    let mut 编辑器 = 编辑器状态::新建();
    编辑器.创建项目(&项目根, "示例项目")?;

    // ---- 关卡根：纯逻辑节点，只有变换，不带渲染组件 ----
    let 关卡根 = 新建(&mut 编辑器, "关卡根", None)?;

    // 每个精灵用不同的颜色，便于在截图里核对"谁渲染成了什么颜色"。
    // 起个别名，免得这一行因为类型太长被 clippy 判为"类型过于复杂"。
    type 方块 = (&'static str, (f32, f32), (f32, f32), (f32, f32, f32));
    let 条目: [方块; 4] = [
        ("玩家", (0.0, 0.0), (96.0, 96.0), (0.25, 0.65, 1.0)),
        ("敌人甲", (260.0, 60.0), (80.0, 80.0), (1.0, 0.35, 0.3)),
        ("敌人乙", (260.0, -120.0), (80.0, 80.0), (1.0, 0.75, 0.2)),
        ("地面", (0.0, -260.0), (700.0, 60.0), (0.35, 0.8, 0.4)),
    ];

    for (名称, 位置, 尺寸, 颜色) in 条目 {
        let 标识 = 新建(&mut 编辑器, 名称, Some(关卡根))?;
        装配精灵(
            &mut 编辑器,
            标识,
            位置,
            尺寸,
            颜色值::srgb(颜色.0, 颜色.1, 颜色.2, 1.0),
        )?;
    }

    // 选中玩家，这样截图里能看到选中高亮与 Inspector 内容。
    if let Some(玩家) = 编辑器
        .会话
        .文档
        .实体表
        .values()
        .find(|实体| 实体.名称 == "玩家")
        .map(|实体| 实体.标识)
    {
        编辑器.选择.单选(玩家);
    }

    let 场景路径 = 项目相对路径::解析("scenes/主关卡.scene.ron")?;
    编辑器.保存场景到(&场景路径)?;

    // 把启动场景写进项目清单，使编辑器打开项目时自动载入它。
    {
        let 项目 = 编辑器.项目.as_mut().ok_or("项目未被创建")?;
        项目.清单可变().启动场景 = Some(场景路径.clone());
        项目.保存清单()?;
    }

    println!("示例项目已生成：{}", 项目根.display());
    println!("启动场景：{}", 场景路径.文本());
    println!(
        "实体：{}",
        编辑器
            .会话
            .文档
            .实体表
            .values()
            .map(|实体| 实体.名称.as_str())
            .collect::<Vec<_>>()
            .join("、")
    );
    for 条目 in 编辑器.日志列表() {
        println!("  [{:?}] {}", 条目.级别, 条目.诊断文本());
    }

    Ok(())
}

/// 新建实体并返回它的标识。
fn 新建(
    编辑器: &mut 编辑器状态, 名称: &str, 父: Option<实体标识>
) -> 结果<实体标识> {
    编辑器
        .新建实体(名称.to_string(), 父)
        .ok_or_else(|| format!("新建实体 `{名称}` 失败").into())
}

/// 给实体装上 `Transform` 与 `Sprite`，让它成为可见的方块。
///
/// 全部走 `编辑器状态::执行` 与 `添加组件`，因此结果必然是
/// "编辑器自己一定读得回来"的合法结构。
fn 装配精灵(
    编辑器: &mut 编辑器状态,
    标识: 实体标识,
    位置: (f32, f32),
    尺寸: (f32, f32),
    颜色: 颜色值,
) -> 结果<()> {
    编辑器.执行(编辑器命令::设变换 {
        标识,
        变换: Some(变换数据 {
            平移: (位置.0, 位置.1, 0.0),
            旋转: (0.0, 0.0, 0.0, 1.0),
            缩放: (1.0, 1.0, 1.0),
        }),
    })?;

    let 属性 = [
        ("颜色".to_string(), 属性值::颜色(颜色)),
        ("自定义尺寸".to_string(), 属性值::二维(尺寸.0, 尺寸.1)),
        ("水平翻转".to_string(), 属性值::布尔(false)),
        ("垂直翻转".to_string(), 属性值::布尔(false)),
    ]
    .into_iter()
    .collect();

    if !编辑器.添加组件(标识, 组件数据::新建("Sprite", 属性)) {
        return Err(format!("给实体 {标识} 添加 Sprite 组件失败").into());
    }
    Ok(())
}
