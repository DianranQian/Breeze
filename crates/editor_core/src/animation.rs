    #[test]
    fn 四元数插值走最短路径且保持单位长度() {
        // 两个几乎相反的四元数（绕 Y 轴 350° 与 0°）。
        let 半角 = 350f32.to_radians() / 2.0;
        let 起点 = 关键帧值::四元数([0.0, 0.0, 0.0, 1.0]);
        let 终点 = 关键帧值::四元数([0.0, 半角.sin(), 0.0, 半角.cos()]);
        let 关键帧值::四元数(q) = 起点.插值(&终点, 0.5) else {
            panic!("类型应当保持");
        };
        let 模长 = (q[0] * q[0] + q[1] * q[1] + q[2] * q[2] + q[3] * q[3]).sqrt();
        assert!((模长 - 1.0).abs() < 1e-5, "插值后必须是单位四元数");
        // 最短路径：中途应当接近 0° 而不是 175°，即 w 应当仍然很大。
        assert!(q[3] > 0.9, "四元数插值走了远路：w = {}", q[3]);
    }
