//! 动画文档：关键帧、轨道、求值与磁盘往返。
//!
//! # 参考的 Godot 结构
//!
//! Godot 的动画系统分三层（`scene/animation/animation_mixer.cpp`、
//! `scene/resources/animation.cpp`、`editor/animation/`）：
//!
//! | 层 | 职责 | 本模块对应 |
//! | --- | --- | --- |
//! | `Animation` | 轨道 + 关键帧 + 插值，纯数据 | [`动画文档`] |
//! | `AnimationMixer` | 时间推进、循环、把值写回节点 | [`动画文档::求值`] + `editor_app` 的播放系统 |
//! | 编辑器时间轴 | 播放头、关键帧增删、录制 | `editor_ui::timeline_panel` |
//!
//! 关键取舍：**轨道按"实体标识 + 变换属性"寻址**，而不是 Godot 的节点路径。
//! 微风用 UUID 标识实体（见 `scene_doc::document::实体标识`），
//! 路径会随重命名/搬动失效，UUID 不会 —— 这正是撤销栈与资源引用
//! 已经在用的同一套身份机制，不必再发明一套。
//!
//! # 编辑态与播放态
//!
//! 播放**不写场景文档**。求值结果只用来覆盖预览实体的 `Transform`
//! （见 `editor_app::preview::应用动画预览`），因此"播放时看着它在动"
//! 与"保存下的场景文件里没有中间帧"同时成立。

