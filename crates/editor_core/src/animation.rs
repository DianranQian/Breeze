/// 动画文件格式版本。
///
/// 与场景文档同样的策略：加字段保持版本，改语义才递增。
pub const 动画格式版本: u32 = 1;

/// 新建动画的默认时长（秒）。
pub const 默认动画时长: f32 = 2.0;

/// 允许的最短/最长动画时长。
pub const 最小时长: f32 = 0.01;
/// 允许的最长动画时长。
pub const 最大时长: f32 = 3600.0;

/// 关键帧时间比较的容差。
///
/// 时间轴上的"同一个位置"是浮点值，用户点两次不可能落在同一位。
/// 用 1ms 作为同一帧的判定，既能合并重复关键帧，又不会误合并
/// 用户真正想放在相邻 2ms 处的两帧。
pub const 时间容差: f32 = 0.001;

/// 动画属性的种类：只覆盖变换的三个分量。
///
/// 先做变换是刻意的：它是"会动的场景"里 95% 的用例，
/// 而且有明确、可测的数学。颜色/自定义属性留给
/// [`动画属性`] 的后续变体与轨道扩展点，不在此处预先抽象。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum 动画属性 {
    /// 位置。
    平移,
    /// 旋转（四元数）。
    旋转,
    /// 缩放。
    缩放,
}

impl 动画属性 {
    /// 全部属性，供界面列出可添加的轨道。
    pub const 全部: [Self; 3] = [Self::平移, Self::旋转, Self::缩放];

    /// 稳定代号，写进动画文件。
    pub fn 代号(self) -> &'static str {
        match self {
            Self::平移 => "translation",
            Self::旋转 => "rotation",
            Self::缩放 => "scale",
        }
    }

    /// 由代号解析。
    pub fn 从代号(代号: &str) -> Option<Self> {
        Self::全部.into_iter().find(|属性| 属性.代号() == 代号)
    }

    /// 词条键。
    pub fn 词条键(self) -> &'static str {
        match self {
            Self::平移 => "anim_property_translation",
            Self::旋转 => "anim_property_rotation",
            Self::缩放 => "anim_property_scale",
        }
    }

    /// 从实体的变换里取出该属性的值。
    pub fn 取(self, 变换: 变换数据) -> 关键帧值 {
        match self {
            Self::平移 => 关键帧值::向量3([变换.平移.0, 变换.平移.1, 变换.平移.2]),
            Self::旋转 => {
                关键帧值::四元数([变换.旋转.0, 变换.旋转.1, 变换.旋转.2, 变换.旋转.3])
            }
            Self::缩放 => 关键帧值::向量3([变换.缩放.0, 变换.缩放.1, 变换.缩放.2]),
        }
    }

    /// 把值写回变换。
    pub fn 写入(self, 变换: &mut 变换数据, 值: &关键帧值) {
        match (self, 值) {
            (Self::平移, 关键帧值::向量3(v)) => 变换.平移 = (v[0], v[1], v[2]),
            (Self::缩放, 关键帧值::向量3(v)) => 变换.缩放 = (v[0], v[1], v[2]),
            (Self::旋转, 关键帧值::四元数(q)) => {
                变换.旋转 = (q[0], q[1], q[2], q[3]);
                变换.归一化旋转();
            }
            // 类型不匹配（手改文件造成）时保持原值：静默改错数据
            // 比"这一帧不动"糟得多。
            _ => {}
        }
    }
}

/// 一帧的值。
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub enum 关键帧值 {
    /// 三分量（平移、缩放）。
    向量3([f32; 3]),
    /// 四元数旋转。
    四元数([f32; 4]),
}

impl 关键帧值 {
    /// 是否与另一个值相同（带浮点容差）。
    pub fn 近似等于(&self, 其他: &Self) -> bool {
        match (self, 其他) {
            (Self::向量3(a), Self::向量3(b)) => {
                a.iter().zip(b).all(|(x, y)| (x - y).abs() < 1e-5)
            }
            (Self::四元数(a), Self::四元数(b)) => {
                a.iter().zip(b).all(|(x, y)| (x - y).abs() < 1e-5)
            }
            _ => false,
        }
    }

    /// 插值。`t` 会被夹到 `0..=1`。
    ///
    /// 四元数用**最短路径的归一化线性插值**（nlerp）而不是完整 slerp：
    /// 编辑器里每帧都会重新求值，nlerp 的角速度不均匀在预览中几乎不可见，
    /// 而它不会像 slerp 那样在两点几乎重合时数值抖动。
    pub fn 插值(&self, 下一个: &Self, t: f32) -> Self {
        let t = t.clamp(0.0, 1.0);
        match (self, 下一个) {
            (Self::向量3(a), Self::向量3(b)) => {
                let mut 结果 = [0.0; 3];
                for i in 0..3 {
                    结果[i] = a[i] + (b[i] - a[i]) * t;
                }
                Self::向量3(结果)
            }
            (Self::四元数(a), Self::四元数(b)) => {
                // 点积为负说明两帧在四元数球面的两侧，
                // 直接插值会绕远路（转 350° 而不是 10°）。
                let 点积: f32 = (0..4).map(|i| a[i] * b[i]).sum();
                let 符号 = if 点积 < 0.0 { -1.0 } else { 1.0 };
                let mut 结果 = [0.0; 4];
                for i in 0..4 {
                    结果[i] = a[i] + (b[i] * 符号 - a[i]) * t;
                }
                let 模长 =
                    (结果[0] * 结果[0] + 结果[1] * 结果[1] + 结果[2] * 结果[2] + 结果[3] * 结果[3])
                        .sqrt();
                if 模长 > f32::EPSILON {
                    for 分量 in &mut 结果 {
                        *分量 /= 模长;
                    }
                }
                Self::四元数(结果)
            }
            _ => *self,
        }
    }
}

/// 关键帧切线：**速度**（单位/秒），不是控制点。
///
/// # 为什么用速度而不是 Bezier 控制点
///
/// 时间轴上的横轴是时间、纵轴是值，因此三次 Hermite 的自然输入是
/// "这一帧处的速度"。用速度还有一个实际好处：把切线清零 = 端点静止，
/// 这在编辑器里是最常用的一步（"让它停一下再走"），而 Bezier 控制点
/// 需要用户理解两个坐标各自的意义。
///
/// 只支持三分量（平移/缩放/旋转用四元数，见 [`插值模式::三次`] 的说明）。
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub enum 切线 {
    /// 三分量速度（每秒变化量）。
    向量3([f32; 3]),
}

impl 切线 {
    /// 取三分量值；若与值类型不匹配则返回 `None`。
    pub fn 取向量3(&self) -> Option<[f32; 3]> {
        match self {
            切线::向量3(值) => Some(*值),
        }
    }

    /// 全零切线（"在这里停住"）。
    pub fn 静止() -> Self {
        切线::向量3([0.0; 3])
    }
}
/// 一个关键帧。
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct 关键帧 {
    /// 时间（秒），从动画起点算起。
    pub 时间: f32,
    /// 值。
    pub 值: 关键帧值,
    /// 出切线（离开本帧时的速度，单位：每秒）。
    ///
    /// None = 自动切线（由相邻帧按 Catmull-Rom 规则推算）。
    /// 只有 插值模式::三次 会用到它：其它模式下切线不参与求值，
    /// 但依然会被保存 —— 这样用户切换插值时不必重填切线。
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub 出切线: Option<切线>,
    /// 入切线（到达本帧时的速度，单位：每秒）。
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub 入切线: Option<切线>,
}

impl 关键帧 {
    /// 构造。
    pub fn 新建(时间: f32, 值: 关键帧值) -> Self {
        Self {
            时间: 时间.max(0.0),
            值,
            出切线: None,
            入切线: None,
        }
    }

    /// 是否设置了自定义切线（任一端）。
    pub fn 有自定义切线(&self) -> bool {
        self.出切线.is_some() || self.入切线.is_some()
    }
}

/// 一条轨道：某个实体的某个属性随时间变化。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct 动画轨道 {
    /// 目标实体。
    pub 实体: 实体标识,
    /// 属性。
    pub 属性: 动画属性,
    /// 关键帧，**始终按时间升序**。
    #[serde(default)]
    pub 关键帧: Vec<关键帧>,
    /// 插值方式。
    ///
    /// Godot 的 `Animation` 每个轨道可设 interpolation（Nearest/Linear/Cubic）。
    /// 这里先做 Step 与 Linear：Step 用于"逐格切换"（精灵帧、开关类动画），
    /// 它和 Linear 的差别体现在采样结果上，属于**数据**而不是界面偏好，必须存盘。
    #[serde(default)]
    pub 插值: 插值模式,
}

/// 轨道插值方式。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum 插值模式 {
    /// 线性插值：两个关键帧之间连续过渡（Godot 的 `Linear`）。
    #[default]
    线性,
    /// 步进插值：保持左侧关键帧的值，到下一个关键帧时**跳变**（Godot 的 `Nearest`）。
    步进,
    /// 平滑插值：两端速度为 0 的缓入缓出（smoothstep）。
    ///
    /// # 与 `三次` 的区别
    ///
    /// `平滑` 是**固定的** smoothstep 缓动：两端速度永远为 0，与关键帧数据无关。
    /// 它是 `三次` 在"两端切线都为 0"时的特例。旧动画文件默认用它，
    /// 因此行为保持不变。
    平滑,
    /// 三次曲线（Hermite）：使用关键帧自己的入/出切线。
    ///
    /// # 与 `平滑` 的区别（这是真正实现 Cubic 的关键）
    ///
    /// `三次` 按三次 Hermite 求值：`p(t) = h00·p0 + h10·(m0·dt) + h01·p1 + h11·(m1·dt)`，
    /// 其中 `m0/m1` 是出/入切线（速度）。切线缺失时按 Catmull-Rom 规则由相邻帧
    /// 推算，因此**不填切线也能得到平滑且中途不停顿**的曲线；把切线设成 0
    /// 就退化成 `平滑`。
    ///
    /// # 旋转为什么降级
    ///
    /// 四元数的速度属于切空间（角速度向量），三次插值需要 squad 系列公式；
    /// 本项目旋转轨道存的是四元数本身。这里诚实降级为 `平滑`（nlerp +
    /// smoothstep），并在时间轴上标注。静默用标量公式处理四元数会产生
    /// "转着转着突然抽搐"的曲线，比降级更糟。
    三次,
}

impl 插值模式 {
    /// 全部可选方式。
    pub const 全部: [插值模式; 4] = [
        插值模式::线性,
        插值模式::步进,
        插值模式::平滑,
        插值模式::三次,
    ];

    /// 场景/动画文件里的变体名（英文，向运行时看齐）。
    pub fn 变体名(&self) -> &'static str {
        match self {
            插值模式::线性 => "Linear",
            插值模式::步进 => "Step",
            插值模式::平滑 => "Smooth",
            插值模式::三次 => "Cubic",
        }
    }

    /// 序号（下拉与落盘共用）。
    pub fn 序号(&self) -> u32 {
        match self {
            插值模式::线性 => 0,
            插值模式::步进 => 1,
            插值模式::平滑 => 2,
            插值模式::三次 => 3,
        }
    }

    /// 由变体名与序号还原；未知名字退回线性（旧文件的默认行为）。
    pub fn 由值(变体名: &str, 序号: u32) -> Self {
        match 变体名 {
            "Step" | "Nearest" | "步进" => 插值模式::步进,
            "Smooth" | "平滑" => 插值模式::平滑,
            "Cubic" | "三次" => 插值模式::三次,
            "Linear" | "线性" => 插值模式::线性,
            _ => match 序号 {
                1 => 插值模式::步进,
                2 => 插值模式::平滑,
                3 => 插值模式::三次,
                _ => 插值模式::线性,
            },
        }
    }

    /// 显示名词条键。
    pub fn 词条键(&self) -> &'static str {
        match self {
            插值模式::线性 => "interp_linear",
            插值模式::步进 => "interp_step",
            插值模式::平滑 => "interp_smooth",
            插值模式::三次 => "interp_cubic",
        }
    }
}

/// 三次（Hermite）求值。
///
/// `p(t) = h00·p0 + h10·(m0·dt) + h01·p1 + h11·(m1·dt)`，其中
/// `h00 = 2t³-3t²+1`、`h10 = t³-2t²+t`、`h01 = -2t³+3t²`、`h11 = t³-t²`，
/// `dt = 右帧时间 - 左帧时间`，`m0/m1` 是出/入切线（值/秒）。
///
/// 切线缺失时按 **Catmull-Rom** 推算：`m = (后一帧值 - 前一帧值) / (后一帧时间 - 前一帧时间)`，
/// 端点处退化为该段的割线斜率。这样没填切线的动画也不会"每帧都停顿"。
///
/// 四元数返回 `平滑` 的结果（见 `插值模式::三次` 的说明）。
fn 三次求值(
    帧列表: &[关键帧],
    左下标: usize,
    右下标: usize,
    t: f32,
    左帧: &关键帧,
    右帧: &关键帧,
    跨度: f32,
) -> 关键帧值 {
    let (关键帧值::向量3(p0), 关键帧值::向量3(p1)) = (左帧.值, 右帧.值) else {
        // 旋转/其它类型：诚实降级为平滑，不用标量公式硬算四元数。
        let 缓动 = t * t * (3.0 - 2.0 * t);
        return 左帧.值.插值(&右帧.值, 缓动);
    };

    let 自动切线 = |下标: usize| -> [f32; 3] {
        // Catmull-Rom：用前后两帧的中心差分近似速度。
        let 前 = 下标.saturating_sub(1);
        let 后 = (下标 + 1).min(帧列表.len() - 1);
        let 前帧 = &帧列表[前];
        let 后帧 = &帧列表[后];
        let 时间差 = 后帧.时间 - 前帧.时间;
        let (关键帧值::向量3(前值), 关键帧值::向量3(后值)) = (前帧.值, 后帧.值)
        else {
            return [0.0; 3];
        };
        if 时间差.abs() <= f32::EPSILON {
            return [0.0; 3];
        }
        let mut 结果 = [0.0; 3];
        for i in 0..3 {
            结果[i] = (后值[i] - 前值[i]) / 时间差;
        }
        结果
    };

    let m0 = 左帧
        .出切线
        .and_then(|切线| 切线.取向量3())
        .unwrap_or_else(|| 自动切线(左下标));
    let m1 = 右帧
        .入切线
        .and_then(|切线| 切线.取向量3())
        .unwrap_or_else(|| 自动切线(右下标));

    let t = t.clamp(0.0, 1.0);
    let t2 = t * t;
    let t3 = t2 * t;
    let h00 = 2.0 * t3 - 3.0 * t2 + 1.0;
    let h10 = t3 - 2.0 * t2 + t;
    let h01 = -2.0 * t3 + 3.0 * t2;
    let h11 = t3 - t2;
    let mut 结果 = [0.0; 3];
    for i in 0..3 {
        结果[i] = h00 * p0[i] + h10 * (m0[i] * 跨度) + h01 * p1[i] + h11 * (m1[i] * 跨度);
    }
    关键帧值::向量3(结果)
}
impl 动画轨道 {
    /// 新建空轨道。
    pub fn 新建(实体: 实体标识, 属性: 动画属性) -> Self {
        Self {
            实体,
            属性,
            关键帧: Vec::new(),
            // 默认线性：与旧版本行为一致，旧动画文件读进来不会突然"变卡顿"。
            插值: 插值模式::线性,
        }
    }

    /// 插入或替换一帧（时间相同则替换）。
    ///
    /// 返回 `true` 表示新增，`false` 表示替换了同一时刻的旧帧。
    pub fn 插入(&mut self, 帧: 关键帧) -> bool {
        if let Some(旧) = self
            .关键帧
            .iter_mut()
            .find(|旧| (旧.时间 - 帧.时间).abs() <= 时间容差)
        {
            *旧 = 帧;
            return false;
        }
        self.关键帧.push(帧);
        self.排序();
        true
    }

    /// 删除时间最接近的一帧（容差内）。返回是否删掉了。
    pub fn 删除(sel: &mut 动画轨道, 时间: f32) -> bool {
        let Some((下标, _)) = Self::最近帧(&sel.关键帧, 时间) else {
            return false;
        };
        if (sel.关键帧[下标].时间 - 时间).abs() > 时间容差 {
            return false;
        }
        sel.关键帧.remove(下标);
        true
    }

    /// 找到时间上最接近的帧。
    pub fn 最近帧(帧列表: &[关键帧], 时间: f32) -> Option<(usize, &关键帧)> {
        帧列表.iter().enumerate().min_by(|(_, a), (_, b)| {
            (a.时间 - 时间)
                .abs()
                .partial_cmp(&(b.时间 - 时间).abs())
                .unwrap_or(std::cmp::Ordering::Equal)
        })
    }

    /// 按时间升序排序。插入后必须调用。
    pub fn 排序(&mut self) {
        self.关键帧.sort_by(|a, b| {
            a.时间
                .partial_cmp(&b.时间)
                .unwrap_or(std::cmp::Ordering::Equal)
        });
    }

    /// 求值。没有关键帧时返回 `None`，调用方保留文档原值。
    pub fn 求值(&self, 时间: f32) -> Option<关键帧值> {
        let 帧列表 = &self.关键帧;
        match 帧列表.len() {
            0 => None,
            1 => Some(帧列表[0].值),
            _ => {
                if 时间 <= 帧列表[0].时间 {
                    return Some(帧列表[0].值);
                }
                let 最后 = 帧列表.last()?;
                if 时间 >= 最后.时间 {
                    return Some(最后.值);
                }
                // 二分找到第一个时间大于 `时间` 的帧。
                let 右 = 帧列表.partition_point(|帧| 帧.时间 <= 时间);
                let 左帧 = &帧列表[右 - 1];
                let 右帧 = &帧列表[右];
                let 跨度 = 右帧.时间 - 左帧.时间;
                if 跨度 <= f32::EPSILON {
                    return Some(右帧.值);
                }
                let t = (时间 - 左帧.时间) / 跨度;
                match self.插值 {
                    // 步进：保持左帧直到右帧时刻才跳变（等价于"取左帧值"）。
                    插值模式::步进 => Some(左帧.值),
                    插值模式::线性 => Some(左帧.值.插值(&右帧.值, t)),
                    // 平滑：smoothstep（两端速度为 0，中间最快）。
                    插值模式::平滑 => {
                        let 缓动 = t * t * (3.0 - 2.0 * t);
                        Some(左帧.值.插值(&右帧.值, 缓动))
                    }
                    // 三次：Hermite，用关键帧切线；四元数/缺数据时降级为平滑。
                    插值模式::三次 => {
                        Some(三次求值(帧列表, 右 - 1, 右, t, 左帧, 右帧, 跨度))
                    }
                }
            }
        }
    }
}

/// 动画事件的种类。
///
/// # 为什么是枚举而不是自由字符串
///
/// 事件最终要驱动**真实行为**（播放音效、调用游戏逻辑）。如果只有字符串
/// 标签，编辑器无法回答"这个事件会被谁消费"，也无法在类型层面区分
/// "我能直接试听"和"这只对游戏代码有意义"。枚举把这两类分开：
/// [`事件类型::音效`] 在编辑器里能直接试听，其余两类只记录并交给运行时。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum 事件类型 {
    /// 音效：`名称` 是资源路径（或资源名），编辑器可直接试听。
    音效,
    /// 游戏逻辑事件：`名称` 是游戏侧约定的事件名。
    逻辑,
    /// 自定义：留给插件或项目自己的语义，编辑器只负责保存与触发记录。
    自定义,
}

impl 事件类型 {
    /// 全部类型（界面按此顺序展示）。
    pub const 全部: [事件类型; 3] = [事件类型::音效, 事件类型::逻辑, 事件类型::自定义];

    /// 稳定代号（写进文件；与显示名无关）。
    pub fn 代号(self) -> &'static str {
        match self {
            Self::音效 => "audio",
            Self::逻辑 => "logic",
            Self::自定义 => "custom",
        }
    }

    /// 由代号恢复。
    pub fn 从代号(代号: &str) -> Option<Self> {
        Self::全部.into_iter().find(|类型| 类型.代号() == 代号)
    }

    /// 词条键（界面显示名）。
    pub fn 词条键(self) -> &'static str {
        match self {
            Self::音效 => "anim_event_audio",
            Self::逻辑 => "anim_event_logic",
            Self::自定义 => "anim_event_custom",
        }
    }
}

/// 动画时间轴上的一个事件。
///
/// # 与关键帧的区别
///
/// 关键帧描述"属性在某一时刻是什么值"，是**连续求值**的输入；
/// 事件描述"在某一刻发生了什么事"，是**离散触发**的输入。
/// 两者都挂在时间轴上，但运行时语义完全不同：事件在跨过它的那一帧
/// 触发一次，重复求值不会重复触发。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct 动画事件 {
    /// 触发时间（秒）。
    pub 时间: f32,
    /// 事件类型。
    pub 类型: 事件类型,
    /// 名称：音效类型时是资源标识，其它类型是游戏侧约定名。
    pub 名称: String,
    /// 可选参数（例如音量、事件载荷）。自由文本，由消费方解释。
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub 参数: Option<String>,
}

impl 动画事件 {
    /// 新建一个事件。
    pub fn 新建(时间: f32, 类型: 事件类型, 名称: impl Into<String>) -> Self {
        Self {
            时间: 时间.max(0.0),
            类型,
            名称: 名称.into(),
            参数: None,
        }
    }

    /// 一句话摘要（界面与日志共用）。
    pub fn 摘要(&self, 语言: 语言) -> String {
        let 名称 = format!("{}：{}", 语言.取(self.类型.词条键()), self.名称);
        match &self.参数 {
            Some(参数) if !参数.trim().is_empty() => {
                format!("{:.3}s {名称}（{参数}）", self.时间)
            }
            _ => format!("{:.3}s {名称}", self.时间),
        }
    }
}

/// 一份动画文档（对应 Godot 的一个 `Animation` 资源）。
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct 动画文档 {
    /// 格式版本。
    #[serde(default = "默认格式版本")]
    pub 格式版本: u32,
    /// 片段名。
    pub 名称: String,
    /// 时长（秒）。
    pub 时长: f32,
    /// 是否循环。
    #[serde(default)]
    pub 循环: bool,
    /// 轨道。
    #[serde(default)]
    pub 轨道: Vec<动画轨道>,
    /// 时间轴事件（音效 / 逻辑 / 自定义）。
    ///
    /// `serde(default)`：旧动画文件里没有这个字段，读过之后按空列表处理；
    /// 保存时若为空会被省略，不改变旧文件的外观。
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub 事件: Vec<动画事件>,
}

fn 默认格式版本() -> u32 {
    动画格式版本
}

impl Default for 动画文档 {
    fn default() -> Self {
        Self::新建("动画")
    }
}

impl 动画文档 {
    /// 新建空动画。
    pub fn 新建(名称: impl Into<String>) -> Self {
        Self {
            格式版本: 动画格式版本,
            名称: 名称.into(),
            时长: 默认动画时长,
            循环: true,
            轨道: Vec::new(),
            事件: Vec::new(),
        }
    }

    /// 轨道数量。
    pub fn 轨道数量(&self) -> usize {
        self.轨道.len()
    }

    /// 关键帧总数。
    pub fn 关键帧总数(&self) -> usize {
        self.轨道.iter().map(|轨道| 轨道.关键帧.len()).sum()
    }

    /// 是否为空（没有任何轨道、关键帧或事件）。
    pub fn 为空(&self) -> bool {
        self.关键帧总数() == 0 && self.事件.is_empty()
    }

    // ------------------------------------------------------------------
    // 事件
    // ------------------------------------------------------------------

    /// 事件数量。
    pub fn 事件数量(&self) -> usize {
        self.事件.len()
    }

    /// 插入一个事件并保持按时间排序。
    ///
    /// 时间会被夹到 `0..=时长`：一个超出片段末尾的事件永远不会被触发，
    /// 留着它只会让用户在时间轴上看到一个点不到的位置。
    pub fn 插入事件(&mut self, mut 事件: 动画事件) -> bool {
        事件.时间 = 事件.时间.clamp(0.0, self.时长.max(最小时长));
        if 事件.名称.trim().is_empty() {
            return false;
        }
        self.事件.push(事件);
        self.事件.sort_by(|甲, 乙| 甲.时间.total_cmp(&乙.时间));
        true
    }

    /// 删除事件时的命中容差。
    ///
    /// 比关键帧的 [`时间容差`] 宽：事件在时间轴上是一个图标，
    /// 用户点它时落点本来就会有十几毫秒的偏差；按 0.001s 判会"怎么点都删不掉"。
    pub const 事件删除容差: f32 = 0.05;

    /// 删除时间最接近 `时间` 的一个事件（容差内）。返回是否删除。
    pub fn 删除事件最近(&mut self, 时间: f32) -> bool {
        let Some((下标, _)) = self
            .事件
            .iter()
            .enumerate()
            .min_by(|(_, 甲), (_, 乙)| (甲.时间 - 时间).abs().total_cmp(&(乙.时间 - 时间).abs()))
            .filter(|(_, 事件)| (事件.时间 - 时间).abs() <= Self::事件删除容差)
        else {
            return false;
        };
        self.事件.remove(下标);
        true
    }

    /// 收集 `(旧时刻, 新时刻]` 内应触发的事件；循环回绕时拆成两段。
    ///
    /// # 为什么是左开右闭
    ///
    /// 事件在**跨过它的那一帧**触发一次。若用左闭右闭，停在某个事件时间上
    /// 反复推进（速度为 0 或每帧只挪一点点）就会重复触发同一事件；
    /// 用左开右闭则每个事件在正常前进时恰好触发一次。
    ///
    /// 时间倒退（用户把播放头往回拖）**不触发**：那不是"播放跨过"，
    /// 而是"用户跳转"，重新触发音效会让人莫名其妙。调用方在倒退时不要调用。
    pub fn 区间事件(&self, 旧: f32, 新: f32) -> Vec<动画事件> {
        if 新 <= 旧 {
            return Vec::new();
        }
        let 时长 = self.时长.max(最小时长);
        let mut 命中: Vec<&动画事件> = Vec::new();
        if self.循环 && 新 > 时长 {
            // 先取本圈剩余部分，再取绕回后的开头。
            命中.extend(
                self.事件
                    .iter()
                    .filter(|事件| 事件.时间 > 旧 && 事件.时间 <= 时长),
            );
            let 回绕到 = 新 % 时长;
            命中.extend(self.事件.iter().filter(|事件| 事件.时间 <= 回绕到));
        } else {
            命中.extend(
                self.事件
                    .iter()
                    .filter(|事件| 事件.时间 > 旧 && 事件.时间 <= 新),
            );
        }
        let mut 命中: Vec<动画事件> = 命中.into_iter().cloned().collect();
        命中.sort_by(|甲, 乙| 甲.时间.total_cmp(&乙.时间));
        命中.dedup_by(|甲, 乙| 甲.时间 == 乙.时间 && 甲.类型 == 乙.类型 && 甲.名称 == 乙.名称);
        命中
    }

    /// 校验事件：返回**用户需要处理**的问题（不阻止保存）。
    ///
    /// 事件是数据，不是代码：空名称或时间越界都只是让事件不生效，
    /// 不值得阻止保存整个动画。这里只把问题说清楚。
    pub fn 校验事件(&self) -> Vec<String> {
        let mut 问题 = Vec::new();
        for (序号, 事件) in self.事件.iter().enumerate() {
            if 事件.名称.trim().is_empty() {
                问题.push(format!("第 {} 个事件没有名称", 序号 + 1));
            }
            if 事件.时间 < 0.0 || 事件.时间 > self.时长 + 时间容差 {
                问题.push(format!(
                    "事件「{}」的时间 {:.3}s 不在 0..={:.3}s 内",
                    事件.名称, 事件.时间, self.时长
                ));
            }
        }
        问题
    }

    /// 找一条已有轨道。
    pub fn 查找轨道(
        &self, 实体: 实体标识, 属性: 动画属性
    ) -> Option<&动画轨道> {
        self.轨道
            .iter()
            .find(|轨道| 轨道.实体 == 实体 && 轨道.属性 == 属性)
    }

    /// 找一条已有轨道（可变）。
    pub fn 查找轨道可变(
        &mut self,
        实体: 实体标识,
        属性: 动画属性,
    ) -> Option<&mut 动画轨道> {
        self.轨道
            .iter_mut()
            .find(|轨道| 轨道.实体 == 实体 && 轨道.属性 == 属性)
    }

    /// 取或创建一条轨道。
    pub fn 轨道路径(
        &mut self, 实体: 实体标识, 属性: 动画属性
    ) -> &mut 动画轨道 {
        if self
            .轨道
            .iter()
            .all(|轨道| 轨道.实体 != 实体 || 轨道.属性 != 属性)
        {
            self.轨道.push(动画轨道::新建(实体, 属性));
        }
        self.轨道
            .iter_mut()
            .find(|轨道| 轨道.实体 == 实体 && 轨道.属性 == 属性)
            .expect("刚刚保证存在")
    }

    /// 删除一条轨道（连带其关键帧）。
    pub fn 删除轨道(&mut self, 实体: 实体标识, 属性: 动画属性) -> bool {
        let 前 = self.轨道.len();
        self.轨道
            .retain(|轨道| 轨道.实体 != 实体 || 轨道.属性 != 属性);
        self.轨道.len() != 前
    }

    /// 删除某个实体的全部轨道（实体被删除时调用）。
    pub fn 删除实体轨道(&mut self, 实体: 实体标识) -> usize {
        let 前 = self.轨道.len();
        self.轨道.retain(|轨道| 轨道.实体 != 实体);
        前 - self.轨道.len()
    }

    /// 把时间按循环/夹取规则映射到 `0..=时长`（**求值**用）。
    ///
    /// 循环只在**严格超出**时长时回绕：播放头停在 `时长` 上是合法状态，
    /// 它代表"最后一个关键帧所在的时刻"。若把 `时长` 也回绕成 0，
    /// 末尾那一帧就永远采样不到，而用户在终点录的那一帧会被静默忽略。
    pub fn 采样时间(&self, 时间: f32) -> f32 {
        let 时长 = self.时长.max(最小时长);
        let 时间 = 时间.max(0.0);
        if self.循环 && 时间 > 时长 {
            时间 % 时长
        } else {
            时间.min(时长)
        }
    }

    /// 把时间夹到 `0..=时长`（**录制**用）。
    ///
    /// 录制绝不回绕：在 2 秒长的动画里把播放头拖到 2 秒处录一帧，
    /// 必须落在 2.0，而不是被 `% 2.0` 变成 0.0 覆盖掉起点那一帧。
    pub fn 录制时间(&self, 时间: f32) -> f32 {
        let 时长 = self.时长.max(最小时长);
        时间.clamp(0.0, 时长)
    }

    /// 在给定时间求值，得到每个实体的完整变换。
    ///
    /// `基准` 是场景文档：**没有被动画覆盖的分量保留文档里的值**。
    /// 若实体已不在文档里（被删掉了但轨道还在），该实体不会出现在结果里 ——
    /// 动画不该凭空创造实体。
    pub fn 求值(&self, 基准: &场景文档, 时间: f32) -> Vec<(实体标识, 变换数据)> {
        let 时间 = self.采样时间(时间);
        let mut 表: BTreeMap<实体标识, 变换数据> = BTreeMap::new();
        for 轨道 in &self.轨道 {
            let Some(实体) = 基准.取(轨道.实体) else {
                continue;
            };
            let Some(基准变换) = 实体.变换 else {
                continue;
            };
            let Some(值) = 轨道.求值(时间) else {
                continue;
            };
            let 变换 = 表.entry(轨道.实体).or_insert(基准变换);
            轨道.属性.写入(变换, &值);
        }
        表.into_iter().collect()
    }

    /// 把当前文档里实体的属性值录成关键帧。
    ///
    /// 返回 `true` 表示新增，`false` 表示替换了同一时刻的帧。
    /// 实体不存在或没有变换时返回 `None`。
    pub fn 录制关键帧(
        &mut self,
        文档: &场景文档,
        实体: 实体标识,
        属性: 动画属性,
        时间: f32,
    ) -> Option<bool> {
        let 变换 = 文档.取(实体)?.变换?;
        let 帧 = 关键帧::新建(self.录制时间(时间), 属性.取(变换));
        Some(self.轨道路径(实体, 属性).插入(帧))
    }

    /// 检查一致性，返回人读的问题列表（可进控制台）。
    ///
    /// 只报告**真正会让动画行为出错**的问题：悬空实体、负时间、空轨道。
    /// 不报告"时长太短"这类口味问题。
    pub fn 校验(&self, 文档: &场景文档) -> Vec<String> {
        let mut 问题 = Vec::new();
        if self.时长 < 最小时长 || self.时长 > 最大时长 {
            问题.push(format!("动画时长 {} 超出允许范围", self.时长));
        }
        for 轨道 in &self.轨道 {
            if !文档.存在(轨道.实体) {
                问题.push(format!("轨道指向的实体 {} 已不在场景里", 轨道.实体));
            }
            if 轨道.关键帧.is_empty() {
                问题.push("存在没有任何关键帧的空轨道".to_string());
            }
            for 帧 in &轨道.关键帧 {
                if 帧.时间 < 0.0 || !帧.时间.is_finite() {
                    问题.push("关键帧时间非法".to_string());
                    break;
                }
            }
        }
        问题
    }

    /// 编码为 RON 文本（美化输出，便于进 Git）。
    pub fn 编码(&self) -> 场景结果<String> {
        let 配置 = ron::ser::PrettyConfig::default()
            .struct_names(false)
            .depth_limit(32)
            .new_line("\n".to_string());
        ron::ser::to_string_pretty(self, 配置)
            .map_err(|错误| 场景错误::编码失败(错误.to_string()))
    }

    /// 从文本解码。版本过新时拒绝，而不是尽力解析。
    pub fn 解码(文本: &str, 路径: &Path) -> 场景结果<Self> {
        let 文档: Self = ron::from_str(文本).map_err(|来源| 场景错误::格式解析 {
            路径: 路径.to_path_buf(),
            来源: Box::new(来源),
        })?;
        if 文档.格式版本 > 动画格式版本 {
            return Err(场景错误::版本过新 {
                文件版本: 文档.格式版本,
                支持版本: 动画格式版本,
            });
        }
        Ok(文档)
    }

    /// 显示名。空名回退到"未命名动画"。
    pub fn 显示名(&self, 语言: 语言) -> String {
        if self.名称.trim().is_empty() {
            语言.取("anim_untitled").to_string()
        } else {
            self.名称.clone()
        }
    }
}

/// 编辑器里打开的一份动画 + 它的磁盘状态。
///
/// 与 [`crate::state::场景会话`] 同一思路：文档是权威数据，
/// 另存一份"已保存文本"用于判断未保存修改。
#[derive(Debug, Clone, PartialEq)]
pub struct 动画会话 {
    /// 文档。
    pub 文档: 动画文档,
    /// 项目内路径。`None` 表示尚未保存过。
    pub 路径: Option<项目相对路径>,
    /// 最后一次落盘的文本。
    pub 已保存文本: String,
    /// 撤销栈（快照）。
    ///
    /// # 为什么动画不共用场景的撤销栈
    ///
    /// 场景撤销栈记的是"命令 + 差量"，目标是场景文档；动画是另一份文档
    /// （Godot 里也是独立资源）。把它塞进场景栈会让"撤销一次场景编辑"与
    /// "撤销一次关键帧编辑"交错，用户无法预期。这里用一个容量很小的快照栈
    /// 专门服务动画编辑：动画通常只有几十条轨道，快照代价可忽略。
    历史: Vec<动画文档>,
    /// 重做栈。
    重做栈: Vec<动画文档>,
}

impl 动画会话 {
    /// 记录一步（在**修改之前**调用）。
    ///
    /// 只保留最近 [`动画会话::最大历史`] 步：动画快照体积小，但无限增长没有意义。
    pub fn 记一步(&mut self) {
        self.历史.push(self.文档.clone());
        if self.历史.len() > Self::最大历史 {
            self.历史.remove(0);
        }
        self.重做栈.clear();
    }

    /// 撤销一步。返回是否真的撤销了。
    pub fn 撤销(&mut self) -> bool {
        let Some(上一步) = self.历史.pop() else {
            return false;
        };
        self.重做栈.push(std::mem::replace(&mut self.文档, 上一步));
        true
    }

    /// 重做一步。返回是否真的重做了。
    pub fn 重做(&mut self) -> bool {
        let Some(下一步) = self.重做栈.pop() else {
            return false;
        };
        self.历史.push(std::mem::replace(&mut self.文档, 下一步));
        true
    }

    /// 可撤销步数。
    pub fn 可撤销步数(&self) -> usize {
        self.历史.len()
    }

    /// 可重做步数。
    pub fn 可重做步数(&self) -> usize {
        self.重做栈.len()
    }

    /// 历史容量上限。
    pub const 最大历史: usize = 64;
    /// 新建未命名动画会话。
    pub fn 新建(名称: impl Into<String>) -> Self {
        let 文档 = 动画文档::新建(名称);
        let 已保存文本 = 文档.编码().unwrap_or_default();
        Self {
            文档,
            路径: None,
            已保存文本,
            历史: Vec::new(),
            重做栈: Vec::new(),
        }
    }

    /// 由已解码的文档与路径构造（标记为"刚保存过"）。
    pub fn 已保存(文档: 动画文档, 路径: 项目相对路径) -> Self {
        let 已保存文本 = 文档.编码().unwrap_or_default();
        Self {
            文档,
            路径: Some(路径),
            已保存文本,
            历史: Vec::new(),
            重做栈: Vec::new(),
        }
    }

    /// 是否有未保存修改。
    pub fn 有未保存修改(&self) -> bool {
        self.文档
            .编码()
            .map(|文本| 文本 != self.已保存文本)
            .unwrap_or(true)
    }

    /// 标记为已保存（同时可更新路径）。
    pub fn 标记已保存(&mut self, 路径: Option<项目相对路径>) {
        if let Some(路径) = 路径 {
            self.路径 = Some(路径);
        }
        self.已保存文本 = self.文档.编码().unwrap_or_default();
    }

    /// 磁盘上的绝对路径（若有项目根与相对路径）。
    pub fn 绝对路径(&self, 项目根: &Path) -> Option<std::path::PathBuf> {
        self.路径.as_ref().map(|路径| 路径.拼接(项目根))
    }
}

/// 动画在编辑器里的播放状态（**只影响预览，不写文档**）。
#[derive(Debug, Clone, Copy, PartialEq, Default)]
pub struct 动画播放状态 {
    /// 是否正在播放。
    pub 播放中: bool,
    /// 当前时间（秒）。
    pub 时间: f32,
    /// 播放速度倍率。
    pub 速度: f32,
}

impl 动画播放状态 {
    /// 默认速度。
    pub const 默认速度: f32 = 1.0;

    /// 新建（暂停在 0 秒）。
    pub fn 新建() -> Self {
        Self {
            播放中: false,
            时间: 0.0,
            速度: Self::默认速度,
        }
    }

    /// 推进时间。返回新的时间。
    pub fn 推进(&mut self, 时长: f32, 循环: bool, 帧间隔秒: f32) -> f32 {
        let 时长 = 时长.max(最小时长);
        if self.播放中 {
            self.时间 += 帧间隔秒 * self.速度.max(0.0);
        }
        if self.时间 < 0.0 {
            self.时间 = 0.0;
        }
        if self.时间 > 时长 {
            if 循环 {
                self.时间 %= 时长;
            } else {
                self.时间 = 时长;
                self.播放中 = false;
            }
        }
        self.时间
    }

    /// 跳到指定时间并夹取。
    pub fn 定位(&mut self, 时间: f32, 时长: f32) {
        self.时间 = 时间.clamp(0.0, 时长.max(最小时长));
    }
}

