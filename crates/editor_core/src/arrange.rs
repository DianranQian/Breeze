//! 多选对齐与分布：纯几何计算，不碰文档、不碰 UI。
//!
//! # 为什么先算成"平移修正"而不是直接写变换
//!
//! 对齐/分布只应该改**位置**，而且必须保持每个实体自身相对锚点的偏移语义。
//! 如果把计算写死在命令里，2D 与 3D、以及将来 UI 的对齐就只能各写一套。
//! 这里输入"盒子 + 对齐边"，输出"每个实体位置应该移动多少"：
//!
//! ```text
//! 盒子（世界 AABB）  ──对齐/分布纯函数──▶  每个实体的平移修正
//! ```
//!
//! 调用方（`editor_app`）再把修正转成一条 `批量设变换` 命令 ——
//! 于是无论从菜单、浮动工具条还是快捷键触发，撤销都恰好一步。
//!
//! # 坐标系
//!
//! 输入是**世界坐标 AABB**。2D 视口里的实体可能挂在父子层级下，
//! 由调用方负责把局部变换累乘成世界 AABB；本模块不猜父级。

/// 一个可参与对齐的实体的世界 AABB。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 对齐盒 {
    /// 实体所在世界位置（通常是平移）。
    pub 位置: (f32, f32),
    /// AABB 最小角。
    pub 最小: (f32, f32),
    /// AABB 最大角。
    pub 最大: (f32, f32),
}

impl 对齐盒 {
    /// 由中心与尺寸构造。
    pub fn 由中心尺寸(位置: (f32, f32), 尺寸: (f32, f32)) -> Self {
        let 半宽 = 尺寸.0.abs() * 0.5;
        let 半高 = 尺寸.1.abs() * 0.5;
        Self {
            位置,
            最小: (位置.0 - 半宽, 位置.1 - 半高),
            最大: (位置.0 + 半宽, 位置.1 + 半高),
        }
    }

    /// 宽度。
    pub fn 宽(&self) -> f32 {
        self.最大.0 - self.最小.0
    }

    /// 高度。
    pub fn 高(&self) -> f32 {
        self.最大.1 - self.最小.1
    }

    /// 中心。
    pub fn 中心(&self) -> (f32, f32) {
        (
            (self.最小.0 + self.最大.0) * 0.5,
            (self.最小.1 + self.最大.1) * 0.5,
        )
    }
}

/// 对齐边。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 对齐边 {
    /// 左边缘对齐。
    左,
    /// 水平中心对齐。
    水平居中,
    /// 右边缘对齐。
    右,
    /// 上边缘对齐。
    上,
    /// 垂直中心对齐。
    垂直居中,
    /// 下边缘对齐。
    下,
}

impl 对齐边 {
    /// 全部六种（工具条按此顺序展示）。
    pub const 全部: [对齐边; 6] = [
        对齐边::左,
        对齐边::水平居中,
        对齐边::右,
        对齐边::上,
        对齐边::垂直居中,
        对齐边::下,
    ];

    /// 词条键（界面显示名）。
    pub fn 词条键(self) -> &'static str {
        match self {
            对齐边::左 => "align_left",
            对齐边::水平居中 => "align_center_h",
            对齐边::右 => "align_right",
            对齐边::上 => "align_top",
            对齐边::垂直居中 => "align_center_v",
            对齐边::下 => "align_bottom",
        }
    }
}

/// 分布轴。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 分布轴 {
    /// 水平等距。
    水平,
    /// 垂直等距。
    垂直,
}

impl 分布轴 {
    /// 词条键。
    pub fn 词条键(self) -> &'static str {
        match self {
            分布轴::水平 => "distribute_h",
            分布轴::垂直 => "distribute_v",
        }
    }
}

/// 对齐：把每个盒子按 `边` 对齐到**所有盒子合并后的包围盒**。
///
/// 返回每个输入盒子的位移 `(dx, dy)`，顺序与输入一致。
///
/// 少于两个盒子时返回全零：单个物体"对齐到自己"没有意义，
/// 但返回零比返回错误更好用 —— 调用方不需要为"只选了一个"写分支。
pub fn 计算对齐(盒子: &[对齐盒], 边: 对齐边) -> Vec<(f32, f32)> {
    if 盒子.len() < 2 {
        return vec![(0.0, 0.0); 盒子.len()];
    }
    let 最小x = 盒子
        .iter()
        .map(|盒| 盒.最小.0)
        .fold(f32::INFINITY, f32::min);
    let 最大x = 盒子
        .iter()
        .map(|盒| 盒.最大.0)
        .fold(f32::NEG_INFINITY, f32::max);
    let 最小y = 盒子
        .iter()
        .map(|盒| 盒.最小.1)
        .fold(f32::INFINITY, f32::min);
    let 最大y = 盒子
        .iter()
        .map(|盒| 盒.最大.1)
        .fold(f32::NEG_INFINITY, f32::max);
    let 中心x = (最小x + 最大x) * 0.5;
    let 中心y = (最小y + 最大y) * 0.5;

    盒子
        .iter()
        .map(|盒| match 边 {
            对齐边::左 => (最小x - 盒.最小.0, 0.0),
            对齐边::右 => (最大x - 盒.最大.0, 0.0),
            对齐边::水平居中 => (中心x - 盒.中心().0, 0.0),
            对齐边::上 => (0.0, 最大y - 盒.最大.1),
            对齐边::下 => (0.0, 最小y - 盒.最小.1),
            对齐边::垂直居中 => (0.0, 中心y - 盒.中心().1),
        })
        .collect()
}

/// 分布：让两端盒子不动，中间盒子的**中心**等距。
///
/// 这是 Godot/Unity 的"等间距分布"语义：间距按可用空间平均分，
/// 而不是按固定间隔推。少于三个盒子时没有"中间"可分，返回全零。
///
/// 同一轴向的盒子会先按中心排序，再按排序后的次序分配位置；
/// 返回值仍与**输入顺序**一一对应。
pub fn 计算分布(盒子: &[对齐盒], 轴: 分布轴) -> Vec<(f32, f32)> {
    let mut 结果 = vec![(0.0, 0.0); 盒子.len()];
    if 盒子.len() < 3 {
        return 结果;
    }
    let 取中心 = |盒: &对齐盒| match 轴 {
        分布轴::水平 => 盒.中心().0,
        分布轴::垂直 => 盒.中心().1,
    };
    let mut 次序: Vec<usize> = (0..盒子.len()).collect();
    次序.sort_by(|甲, 乙| 取中心(&盒子[*甲]).total_cmp(&取中心(&盒子[*乙])));

    let 首 = 取中心(&盒子[次序[0]]);
    let 尾 = 取中心(&盒子[*次序.last().expect("至少三个")]);
    let 步长 = (尾 - 首) / (盒子.len() - 1) as f32;
    for (第几个, 下标) in 次序.iter().enumerate() {
        let 目标 = 首 + 步长 * 第几个 as f32;
        let 当前 = 取中心(&盒子[*下标]);
        let 差 = 目标 - 当前;
        结果[*下标] = match 轴 {
            分布轴::水平 => (差, 0.0),
            分布轴::垂直 => (0.0, 差),
        };
    }
    结果
}

#[cfg(test)]
mod 测试 {
    use super::*;

    fn 盒(x: f32, y: f32, w: f32, h: f32) -> 对齐盒 {
        对齐盒::由中心尺寸((x, y), (w, h))
    }

    #[test]
    fn 左对齐把所有盒子推到最左边缘() {
        let 盒子 = vec![盒(0.0, 0.0, 2.0, 2.0), 盒(10.0, 5.0, 4.0, 2.0)];
        let 位移 = 计算对齐(&盒子, 对齐边::左);
        assert_eq!(位移[0].0, 0.0, "最左者不动");
        // 第二个盒子左边缘在 8，目标是 -1（第一个盒子最小角）。
        assert!((位移[1].0 - (-9.0)).abs() < 1e-5, "位移：{:?}", 位移[1]);
        assert_eq!(位移[1].1, 0.0, "对齐不能改另一轴");
    }

    #[test]
    fn 右对齐以整体右边界为准() {
        let 盒子 = vec![盒(0.0, 0.0, 2.0, 2.0), 盒(10.0, 0.0, 4.0, 2.0)];
        let 位移 = 计算对齐(&盒子, 对齐边::右);
        assert_eq!(位移[1].0, 0.0);
        // 第一个盒子右边缘 1 → 12。
        assert!((位移[0].0 - 11.0).abs() < 1e-5);
    }

    #[test]
    fn 水平居中以上下通道的中线为准() {
        let 盒子 = vec![盒(0.0, 0.0, 2.0, 2.0), 盒(10.0, 0.0, 2.0, 2.0)];
        let 位移 = 计算对齐(&盒子, 对齐边::水平居中);
        // 整体范围 [-1, 11]，中心 5；第一个盒子中心 0 → 5。
        assert!((位移[0].0 - 5.0).abs() < 1e-5);
        assert!((位移[1].0 - (-5.0)).abs() < 1e-5);
    }

    #[test]
    fn 少于两个盒子时对齐返回零位移() {
        let 位移 = 计算对齐(&[盒(3.0, 4.0, 1.0, 1.0)], 对齐边::左);
        assert_eq!(位移, vec![(0.0, 0.0)]);
        assert!(计算对齐(&[], 对齐边::上).is_empty());
    }

    #[test]
    fn 水平分布保持两端不动且中间等距() {
        let 盒子 = vec![
            盒(0.0, 0.0, 2.0, 2.0),
            盒(3.0, 0.0, 2.0, 2.0),
            盒(20.0, 0.0, 2.0, 2.0),
        ];
        let 位移 = 计算分布(&盒子, 分布轴::水平);
        assert_eq!(位移[0], (0.0, 0.0), "首端不动");
        assert_eq!(位移[2], (0.0, 0.0), "末端不动");
        // 中心应从 3 移到 10。
        assert!((位移[1].0 - 7.0).abs() < 1e-5, "位移：{:?}", 位移[1]);
        assert_eq!(位移[1].1, 0.0);
    }

    #[test]
    fn 分布按中心排序而不是按输入顺序() {
        let 盒子 = vec![
            盒(20.0, 0.0, 2.0, 2.0),
            盒(0.0, 0.0, 2.0, 2.0),
            盒(3.0, 0.0, 2.0, 2.0),
        ];
        let 位移 = 计算分布(&盒子, 分布轴::水平);
        assert_eq!(位移[1], (0.0, 0.0), "最左者不动");
        assert_eq!(位移[0], (0.0, 0.0), "最右者不动");
        assert!((位移[2].0 - 7.0).abs() < 1e-5, "中间的推到中点");
    }

    #[test]
    fn 少于三个盒子时分布返回零位移() {
        let 盒子 = vec![盒(0.0, 0.0, 1.0, 1.0), 盒(5.0, 0.0, 1.0, 1.0)];
        assert_eq!(计算分布(&盒子, 分布轴::垂直).len(), 2);
        assert!(
            计算分布(&盒子, 分布轴::垂直)
                .iter()
                .all(|位移| *位移 == (0.0, 0.0))
        );
    }

    #[test]
    fn 垂直方向的对齐与分布互不串轴() {
        let 盒子 = vec![
            盒(0.0, 0.0, 2.0, 2.0),
            盒(5.0, 10.0, 2.0, 4.0),
            盒(0.0, 20.0, 2.0, 2.0),
        ];
        let 对齐 = 计算对齐(&盒子, 对齐边::上);
        assert!(对齐.iter().all(|(x, _)| *x == 0.0), "上对齐不该动 x");
        let 分布 = 计算分布(&盒子, 分布轴::垂直);
        assert!(分布.iter().all(|(x, _)| *x == 0.0), "垂直分布不该动 x");
        assert_eq!(分布[0], (0.0, 0.0));
        assert_eq!(分布[2], (0.0, 0.0));
    }
}
