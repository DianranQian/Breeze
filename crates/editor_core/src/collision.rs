//! 碰撞相关的**纯数据**读取（无 Bevy、无 egui）。
//!
//! # 为什么单独一个模块
//!
//! 碰撞体的解析要被两处使用：2D 视口的轮廓叠加（`editor_ui`）与将来的
//! 物理集成（运行时）。前者不能依赖 `editor_app`（依赖方向是单向的
//! `editor_app → editor_ui → editor_core`），因此"从组件数据里读出形状"
//! 这件事放在这一层，两边共用同一份语义。
//!
//! 组件类型名与字段名在这里是**字符串常量**：场景文件里的组件名就是这些
//! 字符串，谁定义 `组件类型` 实现谁就得用同一组名字。把它们集中在常量里，
//! 改名时只有一处要改。

/// 碰撞体组件的类型名（与 `editor_app::physics_components` 一致）。
pub const 碰撞体组件名: &str = "碰撞体2d";

/// 刚体组件的类型名。
pub const 刚体组件名: &str = "刚体2d";

/// 音频组件的类型名（与 `editor_app::audio_components` 一致）。
///
/// 放在这里而不是新建模块：界面层（`editor_ui`）需要按组件名判断
/// “这一行有没有音频”，而它**不能依赖 `editor_app`**（依赖方向单向）。
/// 组件名字符串是场景文件格式的一部分，集中一处才不会改漏。
pub const 音频组件名: &str = "音频";

/// 碰撞形状（与场景文件里的变体名对应）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 碰撞形状 {
    /// 矩形（宽度/高度）。
    矩形,
    /// 圆形（半径）。
    圆形,
}

impl 碰撞形状 {
    /// 由场景文件里的变体名还原。未知名字退化为矩形（最常见的那一种），
    /// 而不是让整个组件失效。
    pub fn 由变体名(名字: &str) -> Self {
        match 名字 {
            "Circle" | "圆形" => 碰撞形状::圆形,
            _ => 碰撞形状::矩形,
        }
    }
}

/// 解析出来的碰撞体参数。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 碰撞体 {
    /// 形状。
    pub 形状: 碰撞形状,
    /// 宽度（矩形）。
    pub 宽度: f32,
    /// 高度（矩形）。
    pub 高度: f32,
    /// 半径（圆形）。
    pub 半径: f32,
    /// 是否只是触发器。
    pub 触发器: bool,
}

impl 碰撞体 {
    /// 从组件的属性表里解析。
    ///
    /// 缺字段时用默认值，非法尺寸夹到正数：手改过的场景文件不应该
    /// 让碰撞体画成一条看不见的线。
    pub fn 从属性(
        属性: &std::collections::BTreeMap<String, scene_doc::property::属性值>,
    ) -> Self {
        use scene_doc::property::属性值;
        let 形状 = 属性
            .get("形状")
            .and_then(|值| match 值 {
                属性值::枚举(枚举) => Some(碰撞形状::由变体名(&枚举.变体名)),
                _ => None,
            })
            .unwrap_or(碰撞形状::矩形);
        let 取 = |键: &str, 默认: f32| {
            属性
                .get(键)
                .and_then(属性值::取浮点)
                .unwrap_or(默认)
                .max(0.001)
        };
        Self {
            形状,
            宽度: 取("宽度", 1.0),
            高度: 取("高度", 1.0),
            半径: 取("半径", 0.5),
            触发器: 属性.get("触发器").and_then(属性值::取布尔).unwrap_or(false),
        }
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use scene_doc::property::{属性值, 枚举值};

    fn 属性表(项: &[(&str, 属性值)]) -> std::collections::BTreeMap<String, 属性值> {
        项.iter()
            .map(|(键, 值)| ((*键).to_string(), 值.clone()))
            .collect()
    }

    #[test]
    fn 解析矩形() {
        let 碰撞 = 碰撞体::从属性(&属性表(&[
            ("形状", 属性值::枚举(枚举值::新建("Rectangle", 0))),
            ("宽度", 属性值::浮点(3.0)),
            ("高度", 属性值::浮点(2.0)),
            ("触发器", 属性值::布尔(true)),
        ]));
        assert_eq!(碰撞.形状, 碰撞形状::矩形);
        assert_eq!((碰撞.宽度, 碰撞.高度), (3.0, 2.0));
        assert!(碰撞.触发器);
    }

    #[test]
    fn 解析圆形() {
        let 碰撞 = 碰撞体::从属性(&属性表(&[
            ("形状", 属性值::枚举(枚举值::新建("Circle", 1))),
            ("半径", 属性值::浮点(1.5)),
        ]));
        assert_eq!(碰撞.形状, 碰撞形状::圆形);
        assert_eq!(碰撞.半径, 1.5);
    }

    #[test]
    fn 缺字段用默认值() {
        let 碰撞 = 碰撞体::从属性(&属性表(&[]));
        assert_eq!(碰撞.形状, 碰撞形状::矩形);
        assert_eq!((碰撞.宽度, 碰撞.高度, 碰撞.半径), (1.0, 1.0, 0.5));
        assert!(!碰撞.触发器);
    }

    #[test]
    fn 未知变体名退化为矩形() {
        assert_eq!(碰撞形状::由变体名("三角形"), 碰撞形状::矩形);
        assert_eq!(碰撞形状::由变体名("Circle"), 碰撞形状::圆形);
    }
}
