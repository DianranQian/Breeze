//! 编辑命令：所有对场景文档的修改都必须表达成一个命令。
//!
//! # 为什么把修改做成数据而不是方法调用
//!
//! 需求里有一条硬约束：
//!
//! > 保存、撤销、重做、复制、粘贴等操作必须共享一致的数据修改规则。
//!
//! 如果"右键删除"调一个方法、"工具栏删除"调另一个方法，那么撤销栈
//! 必须知道两个入口、且两处都要维护自己的反操作逻辑。规模一大，
//! 某条路径漏了撤销记录或者少清理了选择集，就会出现"撤销后场景错乱"。
//!
//! 把修改抽成**枚举值**之后，所有入口都只做一件事：构造命令 → 交给
//! [`crate::state::编辑器状态::执行`]。于是：
//!
//! * 撤销/重做只需要一个实现（见 [`crate::undo`]）；
//! * 命令是纯数据，可以序列化、可以在测试里直接构造、将来可以做宏录制；
//! * 命令的校验与执行集中在一处，不可能出现两条路径行为不一致。

use std::collections::BTreeMap;

use scene_doc::document::{变换数据, 场景文档, 实体标识, 组件数据};
use scene_doc::error::{场景结果, 场景错误};
use scene_doc::path::项目相对路径;
use scene_doc::property::属性值;

use crate::i18n::语言;

/// 命令执行结果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 命令结果 {
    /// 本次命令实际影响的实体（供 UI 更新选择集、刷新视口使用）。
    pub 影响实体: Vec<实体标识>,
    /// 若命令创建了新实体，这里是其标识。
    ///
    /// 这个字段是**重做可复现性**的关键：重做时复用同一个标识，
    /// 才能保证"重做之后场景与撤销前一模一样"。若重做时重新生成
    /// UUID，那么任何记录了标识的外部状态（选择集、剪贴板、引用）
    /// 都会在重做后指向不存在的实体。
    pub 新实体: Option<实体标识>,
}

impl 命令结果 {
    /// 无副作用的空结果。
    pub fn 空() -> Self {
        Self {
            影响实体: Vec::new(),
            新实体: None,
        }
    }

    /// 只影响一个实体。
    pub fn 单个(标识: 实体标识) -> Self {
        Self {
            影响实体: vec![标识],
            新实体: None,
        }
    }
}

/// 一条编辑命令。
#[derive(Debug, Clone, PartialEq)]
pub enum 编辑器命令 {
    /// 新建实体。
    新建实体 {
        /// 实体名称。
        名称: String,
        /// 父实体，`None` 表示顶层。
        父实体: Option<实体标识>,
        /// 期望使用的实体标识。`None` 表示新建 UUID；
        /// 重做时会带上首次执行时生成的标识，保证可复现。
        指定标识: Option<实体标识>,
    },

    /// 删除实体及其整个子树。
    删除实体 {
        /// 目标实体。
        标识: 实体标识,
    },

    /// 重命名实体。
    重命名实体 {
        /// 目标实体。
        标识: 实体标识,
        /// 新名称。
        新名称: String,
    },

    /// 改变实体的父实体或兄弟顺序。
    重设父子 {
        /// 目标实体。
        标识: 实体标识,
        /// 新父实体。
        新父实体: Option<实体标识>,
        /// 在兄弟中的次序。
        新次序: u32,
    },

    /// 在兄弟间上移一位。
    上移实体 {
        /// 目标实体。
        标识: 实体标识,
    },

    /// 在兄弟间下移一位。
    下移实体 {
        /// 目标实体。
        标识: 实体标识,
    },

    /// 设置本地变换。
    设变换 {
        /// 目标实体。
        标识: 实体标识,
        /// 新变换。`None` 表示移除变换组件。
        变换: Option<变换数据>,
    },

    /// 批量设置多个实体的变换（多选拖动时用一条命令，撤销才是一步）。
    批量设变换 {
        /// 每项的"原变换 → 新变换"。
        项: Vec<(实体标识, Option<变换数据>)>,
    },

    /// 添加组件。
    添加组件 {
        /// 目标实体。
        标识: 实体标识,
        /// 要添加的组件数据。
        组件: 组件数据,
    },

    /// 删除组件。
    删除组件 {
        /// 目标实体。
        标识: 实体标识,
        /// 组件类型名。
        类型名: String,
    },

    /// 设置组件的一个属性。
    ///
    /// 只改单个字段而不是整份组件，好处是撤销栈里保存的是
    /// "改了什么"而非"改之前的整份组件"，语义更清晰。
    设组件属性 {
        /// 目标实体。
        标识: 实体标识,
        /// 组件类型名。
        类型名: String,
        /// 属性名。
        属性名: String,
        /// 新值。
        新值: 属性值,
    },

    /// 批量设置属性（Inspector 多选编辑用）。
    批量设属性 {
        /// 每项为 "实体 → 组件类型 → 属性名 → 新值"。
        项: Vec<(实体标识, String, String, 属性值)>,
    },

    /// 替换整个实体（复制粘贴、从资源重建实体等复合操作用）。
    替换实体 {
        /// 要写入的完整实体数据。
        实体: Box<scene_doc::document::场景实体>,
    },

    /// 把整份文档内容设为给定快照（用于"应用运行时修改到场景"这类
    /// 语义上就是整体替换的操作）。
    设为快照 {
        /// 目标文档快照。
        文档: Box<场景文档>,
    },

    /// 把文档里指向某资源的引用改到新路径。
    ///
    /// # 为什么必须是一条命令，而不是"打开文档后直接改"
    ///
    /// 资源重命名/移动往往发生在**打开中的场景**上。文件名已经改了，
    /// 场景里的引用若不同步，下一次保存出去就是断链。
    /// 把它做成命令有三个直接好处：
    ///
    /// 1. 与其它编辑共享事务语义：失败时文档回到原样，不会留下改了一半的引用；
    /// 2. 进撤销栈：用户误改名后按 Ctrl+Z 能连引用一起退回（差量里本来就记
    ///    实体与资源表，`文档差量::比较` 会把这两处变化都捕获）；
    /// 3. 重做可复现：命令携带旧/新路径，不依赖当时磁盘状态。
    ///
    /// 注意它**只改文档**，不动磁盘文件。文件系统操作由调用方先做，
    /// 因为"文件已经改名、文档还没改"与"文档已经改、文件还没改名"
    /// 都有中间态风险；本项目选择先动文件、再提交命令，失败时把文件改回去。
    改资源路径 {
        /// 旧路径。
        旧路径: 项目相对路径,
        /// 新路径。
        新路径: 项目相对路径,
    },
}

impl 编辑器命令 {
    /// 命令显示名对应的词条键。与语言无关，供界面按当前语言解析。
    pub fn 显示名键(&self) -> &'static str {
        match self {
            编辑器命令::新建实体 { .. } => "new_entity_2",
            编辑器命令::删除实体 { .. } => "delete_entity",
            编辑器命令::重命名实体 { .. } => "rename_entity",
            编辑器命令::重设父子 { .. } => "command_reparent",
            编辑器命令::上移实体 { .. } => "command_move_entity_up",
            编辑器命令::下移实体 { .. } => "command_move_entity_down",
            编辑器命令::设变换 { .. } => "command_set_transform",
            编辑器命令::批量设变换 { .. } => "command_batch_set_transform",
            编辑器命令::添加组件 { .. } => "add_component",
            编辑器命令::删除组件 { .. } => "remove_component",
            编辑器命令::设组件属性 { .. } => "command_set_property",
            编辑器命令::批量设属性 { .. } => "command_batch_set_property",
            编辑器命令::替换实体 { .. } => "command_replace_entity",
            编辑器命令::设为快照 { .. } => "command_apply_snapshot",
            编辑器命令::改资源路径 { .. } => "command_asset_path",
        }
    }

    /// 连续编辑的合并键：`None` 表示这条命令永不与其他命令合并。
    ///
    /// # 只有"连续型"命令才有合并键
    ///
    /// 拖一次数值框会逐帧发出 `设变换`；如果每帧一条撤销记录，用户要按
    /// 几十次 Ctrl+Z 才能退回拖拽前。Godot 的 `UndoRedo` 用 MERGE_* 解决
    /// 这类问题，这里用"动作名 + 目标"作为合并身份：
    ///
    /// * 同一个实体的同一个属性 → 可合并（一次拖拽 = 一步撤销）；
    /// * 不同实体 / 不同属性 → 不合并（撤销不会连带改掉别的东西）；
    /// * 结构性操作（新建/删除/层级/替换/整体快照）→ 永不合并，
    ///   它们的"中间状态"没有意义，合并反而会让撤销跳步。
    pub fn 合并键(&self) -> Option<crate::undo::合并键> {
        use crate::undo::合并键;
        match self {
            编辑器命令::设变换 { 标识, .. } => {
                Some(合并键::新建("set_transform", 标识.to_string()))
            }
            编辑器命令::批量设变换 { 项 } => Some(合并键::新建(
                "batch_set_transform",
                聚合目标(项.iter().map(|(标识, _)| *标识)),
            )),
            编辑器命令::设组件属性 {
                标识,
                类型名,
                属性名,
                ..
            } => Some(合并键::新建(
                "set_property",
                属性目标(标识, 类型名, 属性名),
            )),
            编辑器命令::批量设属性 { 项 } => Some(合并键::新建(
                "batch_set_property",
                聚合目标(
                    项.iter()
                        .map(|(标识, 类型名, 属性名, _)| 属性目标(标识, 类型名, 属性名)),
                ),
            )),
            _ => None,
        }
    }

    /// 用于撤销栈显示的命令名，按给定语言取词条。
    pub fn 显示名(&self, 语言: 语言) -> &'static str {
        语言.取(self.显示名键())
    }

    /// 全部命令显示名键，供词表覆盖核对枚举。
    pub fn 全部显示名键() -> [&'static str; 15] {
        [
            "new_entity_2",
            "delete_entity",
            "rename_entity",
            "command_reparent",
            "command_move_entity_up",
            "command_move_entity_down",
            "command_set_transform",
            "command_batch_set_transform",
            "add_component",
            "remove_component",
            "command_set_property",
            "command_batch_set_property",
            "command_replace_entity",
            "command_apply_snapshot",
            "command_asset_path",
        ]
    }

    /// 执行命令，修改给定文档。
    ///
    /// # 事务性
    ///
    /// 本方法**可能部分修改文档后才失败**（例如批量操作中途某项非法）。
    /// 因此调用方必须遵循 [`crate::state::编辑器状态`] 的约定：
    /// **在文档的克隆上执行**，成功才提交回正本。
    /// 这样失败的命令天然不留下任何痕迹，无需为每条命令写反向操作。
    pub fn 应用(&self, 文档: &mut 场景文档) -> 场景结果<命令结果> {
        match self {
            Self::新建实体 {
                名称,
                父实体,
                指定标识,
            } => {
                if let Some(父) = 父实体
                    && !文档.存在(*父)
                {
                    return Err(场景错误::非法(format!("父实体 {父} 不存在")));
                }
                let 名称 = 文档.去重名称(名称);
                let 标识 = 指定标识.unwrap_or_else(实体标识::新建);

                // 指定的标识可能已被占用（例如粘贴时与既有实体冲突），
                // 此时退化为新生成一个，而不是覆盖既有实体。
                let 标识 = if 文档.存在(标识) {
                    实体标识::新建()
                } else {
                    标识
                };

                let mut 实体 = scene_doc::document::场景实体::新建(名称);
                实体.标识 = 标识;
                实体.父实体 = *父实体;
                实体.次序 = 文档.下一个次序(*父实体);
                文档.插入实体(实体);

                Ok(命令结果 {
                    影响实体: vec![标识],
                    新实体: Some(标识),
                })
            }

            Self::删除实体 { 标识 } => {
                if !文档.存在(*标识) {
                    return Err(场景错误::非法(format!("实体 {标识} 不存在")));
                }
                let 已删 = 文档.删除实体(*标识);
                Ok(命令结果 {
                    影响实体: 已删,
                    新实体: None,
                })
            }

            Self::重命名实体 { 标识, 新名称 } => {
                if !文档.重命名(*标识, 新名称.clone()) {
                    return Err(场景错误::非法(format!("实体 {标识} 不存在")));
                }
                Ok(命令结果::单个(*标识))
            }

            Self::重设父子 {
                标识,
                新父实体,
                新次序,
            } => {
                文档.设为子实体(*标识, *新父实体, *新次序)?;
                Ok(命令结果::单个(*标识))
            }

            Self::上移实体 { 标识 } => {
                if !文档.上移(*标识) {
                    // 已经在最前，不是错误，只是没有变化。
                    return Ok(命令结果::空());
                }
                Ok(命令结果::单个(*标识))
            }

            Self::下移实体 { 标识 } => {
                if !文档.下移(*标识) {
                    return Ok(命令结果::空());
                }
                Ok(命令结果::单个(*标识))
            }

            Self::设变换 { 标识, 变换 } => {
                let 实体 = 文档
                    .取可变(*标识)
                    .ok_or_else(|| 场景错误::非法(format!("实体 {标识} 不存在")))?;
                实体.变换 = *变换;
                Ok(命令结果::单个(*标识))
            }

            Self::批量设变换 { 项 } => {
                // 先整体校验，再统一写入。这样"中途失败"不会发生，
                // 调用方拿到的要么是全部成功，要么是原样未动。
                for (标识, _) in 项 {
                    if !文档.存在(*标识) {
                        return Err(场景错误::非法(format!("实体 {标识} 不存在")));
                    }
                }
                for (标识, 变换) in 项 {
                    if let Some(实体) = 文档.取可变(*标识) {
                        实体.变换 = *变换;
                        if let Some(值) = &mut 实体.变换 {
                            值.归一化旋转();
                        }
                    }
                }
                Ok(命令结果 {
                    影响实体: 项.iter().map(|(标识, _)| *标识).collect(),
                    新实体: None,
                })
            }

            Self::添加组件 { 标识, 组件 } => {
                let 实体 = 文档
                    .取可变(*标识)
                    .ok_or_else(|| 场景错误::非法(format!("实体 {标识} 不存在")))?;
                if !实体.加组件(组件.clone()) {
                    return Err(场景错误::非法(format!(
                        "实体 {标识} 已有组件 `{}`",
                        组件.类型名
                    )));
                }
                Ok(命令结果::单个(*标识))
            }

            Self::删除组件 { 标识, 类型名 } => {
                let 实体 = 文档
                    .取可变(*标识)
                    .ok_or_else(|| 场景错误::非法(format!("实体 {标识} 不存在")))?;
                if !实体.删组件(类型名) {
                    return Err(场景错误::非法(
                        format!("实体 {标识} 没有组件 `{类型名}`"),
                    ));
                }
                // 组件没了，可能连带资源引用也没了，同步清理资源表。
                文档.清理资源表();
                Ok(命令结果::单个(*标识))
            }

            Self::设组件属性 {
                标识,
                类型名,
                属性名,
                新值,
            } => {
                let 实体 = 文档
                    .取可变(*标识)
                    .ok_or_else(|| 场景错误::非法(format!("实体 {标识} 不存在")))?;
                let 组件 = 实体.取组件可变(类型名).ok_or_else(|| {
                    场景错误::非法(format!("实体 {标识} 没有组件 `{类型名}`"))
                })?;

                // 先收拢再写入：把 NaN、越界颜色这类非法值挡在文档之外。
                let mut 新值 = 新值.clone();
                新值.收拢();
                组件.属性.insert(属性名.clone(), 新值);

                // 若改的是资源引用，需要同步资源表。
                文档.同步资源表();
                Ok(命令结果::单个(*标识))
            }

            Self::批量设属性 { 项 } => {
                for (标识, 类型名, _, _) in 项 {
                    let 实体 = 文档
                        .取(*标识)
                        .ok_or_else(|| 场景错误::非法(format!("实体 {标识} 不存在")))?;
                    if !实体.有组件(类型名) {
                        return Err(场景错误::非法(
                            format!("实体 {标识} 没有组件 `{类型名}`"),
                        ));
                    }
                }
                for (标识, 类型名, 属性名, 新值) in 项 {
                    if let Some(实体) = 文档.取可变(*标识)
                        && let Some(组件) = 实体.取组件可变(类型名)
                    {
                        let mut 新值 = 新值.clone();
                        新值.收拢();
                        组件.属性.insert(属性名.clone(), 新值);
                    }
                }
                文档.同步资源表();
                Ok(命令结果 {
                    影响实体: 项.iter().map(|(标识, _, _, _)| *标识).collect(),
                    新实体: None,
                })
            }

            Self::替换实体 { 实体 } => {
                let 标识 = 实体.标识;
                文档.插入实体((**实体).clone());
                文档.同步资源表();
                Ok(命令结果 {
                    影响实体: vec![标识],
                    新实体: None,
                })
            }

            Self::设为快照 { 文档: 快照 } => {
                文档.覆盖为(快照);
                Ok(命令结果 {
                    影响实体: 文档.实体表.keys().copied().collect(),
                    新实体: None,
                })
            }

            Self::改资源路径 {
                旧路径, 新路径
            } => {
                // 旧路径连一个引用都没有时不是错误：资源文件可能刚被导入、
                // 还没被任何场景使用。此时命令是空操作，不会进撤销栈
                // （`文档差量::为空` 会把它过滤掉），用户不会看到"撤销了一次
                // 却什么都没变"。
                文档.改资源路径(旧路径, 新路径);
                // 影响实体 = 改写后仍引用新路径的实体，用于刷新视口与选择集。
                let 扫描 = scene_doc::asset_refs::文档资源引用::扫描(文档);
                let mut 实体: Vec<实体标识> =
                    扫描.引用位置(新路径).iter().map(|位置| 位置.实体).collect();
                实体.sort();
                实体.dedup();
                Ok(命令结果 {
                    影响实体: 实体,
                    新实体: None,
                })
            }
        }
    }
}

/// 从属性表构造一个组件数据。
///
/// 这是一个便捷构造器，避免调用点重复写 `BTreeMap` 类型标注。
pub fn 构造组件(
    类型名: impl Into<String>, 属性: BTreeMap<String, 属性值>
) -> 组件数据 {
    组件数据::新建(类型名, 属性)
}
/// 把一组目标描述聚合成一个稳定的合并键目标。
///
/// 排序后拼接：多选拖动时命令项的顺序可能因选择集遍历顺序而变，
/// 不排序会让"同一次拖拽"被当成不同目标而拆成多条撤销记录。
fn 聚合目标(目标: impl Iterator<Item = impl std::fmt::Display>) -> String {
    let mut 列表: Vec<String> = 目标.map(|项| 项.to_string()).collect();
    列表.sort();
    列表.join(",")
}
/// "实体 / 组件类型 / 属性名"形式的合并目标。
///
/// 刻意不用 `format!` 拼带中文占位符的字面量：那会被界面文案扫描器
/// 当成待翻译的 UI 文案。这里是内部键，不该出现在词表里。
fn 属性目标(标识: &实体标识, 类型名: &str, 属性名: &str) -> String {
    let mut 结果 = 标识.to_string();
    结果.push('/');
    结果.push_str(类型名);
    结果.push('/');
    结果.push_str(属性名);
    结果
}
