//! 场景实例化：把另一份场景的内容并入当前文档。
//!
//! # 参考的 Godot 设计
//!
//! Godot 的 `PackedScene::instantiate()` 做三件事（`scene/resources/packed_scene.cpp`）：
//!
//! 1. **重映射身份**：源场景里的 `NodePath`/`owner` 全部按实例内的新对应关系重建；
//! 2. **保层级**：子节点关系原样复制，实例根挂到调用方指定的父节点下；
//! 3. **留来源**：实例记住自己是哪个 `PackedScene` 产生的，供后续"回到源场景"、
//!    依赖检查与局部覆盖使用。
//!
//! 微风没有节点路径，身份是 `实体标识`（UUID），因此第 1 步变成"建 UUID 映射表"；
//! 第 3 步用两处记录：目标文档的 `资源表` 里登记来源场景（依赖检查与打包会用到），
//! 以及实例根上的 `场景实例` 标记组件（Inspector 里能直接看到来自哪个场景）。
//!
//! # 为什么不做"引用式实例"
//!
//! 引用式实例（实例只保存源场景路径，渲染时再展开）需要一套覆盖/还原语义，
//! 那是成熟引擎里最复杂的部分之一。这里先做**深拷贝 + 来源标记**：
//! 实例内容可以被自由编辑，来源信息用来回答"它从哪来"。
//! 等覆盖机制真正需要时，标记组件就是它的挂载点。

use scene_doc::document::{场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::property::属性值;

/// 实例根上的标记组件类型名。
///
/// 它出现在 Inspector 里，用户可以一眼看到"这个实体来自哪个场景"。
/// 组件是普通的数据组件：运行时桥接不认识它会跳过（并给出诊断），
/// 这正是"编辑器专有元数据"应有的表现，而不是往运行时塞一个假组件。
pub const 实例标记组件: &str = "场景实例";

/// 标记组件里记录来源路径的属性名。
pub const 来源属性: &str = "源场景";

/// 实例化的结果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 实例化结果 {
    /// 实例根（源场景的顶层实体被合并后的新实体）。源场景为空时为 `None`。
    pub 根实体: Option<实体标识>,
    /// 复制的实体数。
    pub 复制实体数: usize,
    /// 一并登记的资源引用数。
    pub 资源引用数: usize,
}

impl 实例化结果 {
    /// 是否真的插入了内容。
    pub fn 有效(&self) -> bool {
        self.复制实体数 > 0
    }
}

/// 把 `源` 场景的内容并入 `目标` 文档。
///
/// `父实体` 是实例的挂载点：`None` 表示作为顶层实体插入。
/// 返回实例根（若源场景有顶层实体）。
///
/// # 身份与层级
///
/// 内部按 `源.深度优先遍历()` 的顺序处理：父节点永远先于子节点被插入，
/// 因此"父实体的新 id"在需要时一定已经算出来了。
/// 源的顶层实体（`父实体 == None`）统一挂到 `父实体` 下；
/// 源内部的多层父子关系原样保留。
///
/// # 名称
///
/// 用 `目标.去重名称` 生成不冲突的名字。同名的两个实例在场景树里
/// 会显示成 `宝箱`、`宝箱 2`，而不是两个一模一样的 `宝箱` ——
/// 重名不会破坏数据（身份靠 UUID），但会让人点错。
pub fn 实例化为(
    目标: &mut 场景文档,
    源: &场景文档,
    源路径: &项目相对路径,
    父实体: Option<实体标识>,
) -> 实例化结果 {
    if 源.实体数量() == 0 {
        return 实例化结果 {
            根实体: None,
            复制实体数: 0,
            资源引用数: 0,
        };
    }

    // 父实体若指向一个不存在的实体，当作"挂到顶层"处理：
    // 让调用方拿到一个能用的结果，而不是插入一批悬空实体。
    let 父实体 = 父实体.filter(|标识| 目标.存在(*标识));

    let mut 映射: std::collections::HashMap<实体标识, 实体标识> = std::collections::HashMap::new();
    let mut 根实体 = None;
    let mut 复制实体数 = 0;

    for (旧标识, 深度) in 源.深度优先遍历() {
        let Some(旧实体) = 源.取(旧标识) else {
            continue;
        };
        let mut 新实体 = 旧实体.clone();
        新实体.标识 = 实体标识::新建();
        新实体.次序 = 0;
        新实体.编辑器展开 = false;

        // 父实体：源内部的父节点用映射表；顶层实体挂到调用方指定的父下。
        let 新父 = match 旧实体.父实体 {
            Some(旧父) => 映射.get(&旧父).copied().or(父实体),
            None => 父实体,
        };
        新实体.父实体 = 新父;
        新实体.名称 = 目标.去重名称(&旧实体.名称);
        新实体.次序 = 目标.下一个次序(新父);

        if 旧实体.父实体.is_none() && 根实体.is_none() {
            根实体 = Some(新实体.标识);
        }
        映射.insert(旧标识, 新实体.标识);
        目标.插入实体(新实体);
        复制实体数 += 1;

        // 深度只用于排序，避免未使用变量告警。
        let _ = 深度;
    }

    // 实例根上留来源标记：Inspector 可见，也方便将来做"定位到源场景"。
    if let Some(根) = 根实体
        && let Some(实体) = 目标.取可变(根)
    {
        实体.加组件(标记组件(源路径));
    }

    // 资源引用整体并入：实例带来的贴图/音频也要进入目标的资源表，
    // 否则依赖检查与打包会漏掉它们。
    let mut 新增引用 = 0;
    for (路径, 引用) in &源.资源表 {
        if !目标.资源表.contains_key(路径) {
            新增引用 += 1;
        }
        目标.资源表.insert(路径.clone(), 引用.clone());
    }
    // 来源场景本身也登记为一条引用：删掉源场景时依赖检查会报出来。
    if !目标.资源表.contains_key(源路径)
        && let Some(引用) = 新引用(源路径)
    {
        目标.资源表.insert(源路径.clone(), 引用);
        新增引用 += 1;
    }

    实例化结果 {
        根实体,
        复制实体数,
        资源引用数: 新增引用,
    }
}

/// 构造"场景实例"标记组件。
fn 标记组件(源路径: &项目相对路径) -> 组件数据 {
    let mut 属性 = std::collections::BTreeMap::new();
    属性.insert(
        来源属性.to_string(),
        属性值::文本(源路径.文本().to_string()),
    );
    组件数据::新建(实例标记组件, 属性)
}

/// 构造一条资源引用（类别由路径推断，交给 `scene_doc` 的既有逻辑）。
fn 新引用(路径: &项目相对路径) -> Option<scene_doc::document::资源引用> {
    Some(scene_doc::document::资源引用 {
        路径: 路径.clone(),
        唯一标识: None,
    })
}

/// 从实体的标记组件里读出来源场景。
pub fn 实例来源(实体: &scene_doc::document::场景实体) -> Option<&str> {
    实体
        .取组件(实例标记组件)?
        .属性
        .get(来源属性)
        .and_then(|值| match 值 {
            属性值::文本(文本) => Some(文本.as_str()),
            _ => None,
        })
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use scene_doc::document::场景实体;

    /// 造一个"子场景"：根 + 两个子节点，其中一个带组件。
    fn 造源场景() -> 场景文档 {
        let mut 文档 = 场景文档::新建("宝箱");
        let 根 = 文档.生成实体("宝箱", None);
        let 盖 = 文档.生成实体("盖子", Some(根));
        let 锁 = 文档.生成实体("锁", Some(根));
        if let Some(实体) = 文档.取可变(锁) {
            实体.加组件(组件数据::标记("Sprite"));
        }
        文档.资源表.insert(
            项目相对路径::解析("assets/chest.png").unwrap(),
            scene_doc::document::资源引用 {
                路径: 项目相对路径::解析("assets/chest.png").unwrap(),
                唯一标识: None,
            },
        );
        let _ = (根, 盖);
        文档
    }

    fn 造目标文档() -> 场景文档 {
        let mut 文档 = 场景文档::新建("关卡");
        let 地面 = 文档.生成实体("地面", None);
        let _ = 地面;
        文档
    }

    #[test]
    fn 实例化复制整棵子树并重映射身份() {
        let 源 = 造源场景();
        let mut 目标 = 造目标文档();
        let 原数量 = 目标.实体数量();

        let 结果 = 实例化为(
            &mut 目标,
            &源,
            &项目相对路径::解析("scenes/宝箱.scene.ron").unwrap(),
            None,
        );

        assert_eq!(结果.复制实体数, 3);
        assert_eq!(目标.实体数量(), 原数量 + 3, "实例应当插入 3 个实体");
        // 身份必须全部是新的：否则会与源场景的实体冲突。
        for (旧标识, _) in 源.深度优先遍历() {
            assert!(
                !目标.存在(旧标识),
                "实例不能复用源场景的实体标识（{旧标识}）"
            );
        }
        // 层级：根的父是 None（顶层），两个子节点的父是新的根。
        let 根 = 结果.根实体.expect("应当有实例根");
        let 根实体 = 目标.取(根).expect("根应当存在");
        assert_eq!(根实体.父实体, None);
        let 子: Vec<_> = 目标.子实体列表(Some(根)).into_iter().collect();
        assert_eq!(子.len(), 2, "两个子节点应当挂在新根下");
        // 组件被原样复制。
        let 有精灵 = 子
            .iter()
            .any(|标识| 目标.取(*标识).is_some_and(|实体| 实体.有组件("Sprite")));
        assert!(有精灵, "子节点上的组件必须跟着复制");
    }

    #[test]
    fn 实例根带来源标记与资源引用() {
        let 源 = 造源场景();
        let mut 目标 = 造目标文档();
        let 来源路径 = 项目相对路径::解析("scenes/宝箱.scene.ron").unwrap();
        let 结果 = 实例化为(&mut 目标, &源, &来源路径, None);
        let 根 = 结果.根实体.unwrap();
        let 实体 = 目标.取(根).unwrap();
        assert_eq!(
            实例来源(实体),
            Some("scenes/宝箱.scene.ron"),
            "实例根必须记住来源"
        );
        // 源场景内部的资源 + 来源场景本身都进了资源表。
        assert!(目标.资源表.contains_key(&来源路径));
        assert!(
            目标
                .资源表
                .keys()
                .any(|路径| 路径.文本().ends_with("chest.png")),
            "实例引用的资源必须并入目标资源表"
        );
        assert_eq!(结果.资源引用数, 2);
    }

    #[test]
    fn 挂到指定父实体下() {
        let 源 = 造源场景();
        let mut 目标 = 造目标文档();
        let 容器 = 目标.生成实体("容器", None);
        实例化为(
            &mut 目标,
            &源,
            &项目相对路径::解析("a.scene.ron").unwrap(),
            Some(容器),
        );
        let 子 = 目标.子实体列表(Some(容器));
        assert_eq!(子.len(), 1, "实例根应当挂到容器下");
        // 再验证孙节点仍在实例根下（层级没有被压平）。
        assert_eq!(目标.子实体列表(Some(子[0])).len(), 2);
    }

    #[test]
    fn 同名两次实例化会得到不同名字() {
        let 源 = 造源场景();
        let mut 目标 = 造目标文档();
        let 路径 = 项目相对路径::解析("a.scene.ron").unwrap();
        let 第一次 = 实例化为(&mut 目标, &源, &路径, None);
        实例化为(&mut 目标, &源, &路径, None);

        let 名1 = 目标.取(第一次.根实体.unwrap()).unwrap().名称.clone();
        let 全部名称: Vec<String> = 目标
            .深度优先遍历()
            .into_iter()
            .filter_map(|(标识, _)| 目标.取(标识).map(|实体| 实体.名称.clone()))
            .collect();
        assert_eq!(
            全部名称.iter().filter(|名称| **名称 == 名1).count(),
            1,
            "同名实体必须被去重：{全部名称:?}"
        );
        assert!(
            全部名称.iter().any(|名称| 名称.contains('2')),
            "第二个实例应当拿到带序号的名字：{全部名称:?}"
        );
    }

    #[test]
    fn 空源场景不产生任何实体() {
        let 源 = 场景文档::新建("空");
        let mut 目标 = 造目标文档();
        let 结果 = 实例化为(
            &mut 目标,
            &源,
            &项目相对路径::解析("a.scene.ron").unwrap(),
            None,
        );
        assert!(!结果.有效());
        assert_eq!(目标.实体数量(), 1);
    }

    #[test]
    fn 不存在的父实体退化为顶层() {
        let 源 = 造源场景();
        let mut 目标 = 造目标文档();
        let 幽灵 = 实体标识::新建();
        let 结果 = 实例化为(
            &mut 目标,
            &源,
            &项目相对路径::解析("a.scene.ron").unwrap(),
            Some(幽灵),
        );
        let 根 = 结果.根实体.unwrap();
        assert_eq!(目标.取(根).unwrap().父实体, None);
    }

    #[test]
    fn 通过快照命令可撤销() {
        use crate::command::编辑器命令;
        use crate::state::编辑器状态;

        let 源 = 造源场景();
        let mut 编辑器 = 编辑器状态::新建();
        let 原数量 = 编辑器.会话.文档.实体数量();
        let 快照 = 编辑器.会话.文档.clone();
        let mut 文档 = 编辑器.会话.文档.clone();
        实例化为(
            &mut 文档,
            &源,
            &项目相对路径::解析("a.scene.ron").unwrap(),
            None,
        );
        编辑器
            .执行(编辑器命令::设为快照 {
                文档: Box::new(文档),
            })
            .expect("设为快照应当成功");
        assert_eq!(编辑器.会话.文档.实体数量(), 原数量 + 3);

        assert!(编辑器.撤销一步(), "实例化应当是一个撤销步");
        assert_eq!(
            编辑器.会话.文档.实体数量(),
            原数量,
            "撤销后应当回到实例化之前"
        );
        let _ = 快照;
        let _: Option<场景实体> = None;
    }
}
