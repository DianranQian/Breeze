    #[test]
    fn 导出子树只包含该子树并换新身份() {
        let mut 源 = 场景文档::新建("关卡");
        let 容器 = 源.生成实体("容器", None);
        let 甲 = 源.生成实体("甲", Some(容器));
        let _甲子 = 源.生成实体("甲子", Some(甲));
        let 旁观者 = 源.生成实体("旁观者", None);
        if let Some(实体) = 源.取可变(甲) {
            实体.加组件(组件数据::标记("Sprite"));
        }
        // 资源表里既有子树用到的，也有旁观者用到的。
        源.资源表.insert(
            项目相对路径::解析("assets/used.png").unwrap(),
            scene_doc::document::资源引用 {
                路径: 项目相对路径::解析("assets/used.png").unwrap(),
                唯一标识: None,
            },
        );

        let 导出 = 导出子树(&源, 甲, "甲").expect("导出应当成功");
        assert_eq!(导出.实体数量(), 2, "应当只导出甲与其子节点");
        // 身份全换。
        for 旧 in [容器, 甲, 旁观者] {
            assert!(!导出.存在(旧), "导出不能沿用源文档的实体标识");
        }
        // 新的根是顶层，且原父（容器）没有被带过来。
        let 新根 = *导出.顶层顺序.first().expect("导出文档应当有一个顶层实体");
        assert_eq!(导出.取(新根).unwrap().名称, "甲");
        assert_eq!(导出.取(新根).unwrap().父实体, None);
        assert_eq!(导出.子实体列表(Some(新根)).len(), 1, "子节点层级要保留");
        // 组件跟着走。
        assert!(导出.取(新根).unwrap().有组件("Sprite"));
        // 空的资源表（甲没有资源引用）——旁观者的引用不该被带进来。
        assert!(
            导出.资源表.is_empty(),
            "资源表应当按新文档重建：{:?}",
            导出.资源表
        );
    }

