    #[test]
    fn 字段描述覆盖每个可编辑字段且词条齐全() {
        let 描述 = 材质资源::字段描述();
        let 导出 = 材质资源::新建("石板路").导出属性();
        assert_eq!(描述.len(), 7, "材质有 7 个可编辑字段");
        for 字段 in &描述 {
            assert!(
                导出.contains_key(&字段.字段名),
                "字段描述里的 `{}` 在导出表里找不到：两处字段集合已经不同步",
                字段.字段名
            );
            assert!(
                字段.种类.接受(&字段.默认值),
                "`{}` 的默认值必须符合它声明的种类，否则控件一打开就是脏值",
                字段.字段名
            );
            for 语种 in 语言::全部 {
                assert_ne!(
                    语种.取(字段.显示名),
                    字段.显示名,
                    "显示名词条必须已在词表里，否则界面把键名漏给用户"
                );
                assert_ne!(
                    语种.取(字段.提示),
                    字段.提示,
                    "悬停提示同样要有词条：{}",
                    字段.字段名
                );
            }
        }
    }

