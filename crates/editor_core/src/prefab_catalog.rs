/*!
模板目录与实例状态。

# 这一层解决什么问题

`scene_doc::prefab` 只保存"实例记录里写了什么"，不负责回答
"磁盘上的模板现在是什么样"。层级面板要在每一行上显示
"模板有更新 / 实例有本地修改 / 模板文件被外部改过"，就必须把
**场景文档**与**模板目录**放在一起比较。

本模块因此做两件事：

1. [`预制件目录`]：项目 `prefabs/` 下所有模板的只读索引，按标识查找；
   指纹在加载时算一次并缓存，避免面板每帧重新编码整个模板；
2. [`预制件实例状态`]：把某条实例记录与目录里的模板比较，得到布尔标记；
   UI 只消费标记，不关心版本号与指纹的比较规则。

# 三种"不一致"必须分开

| 情况 | 含义 | 处理 |
| --- | --- | --- |
| 模板版本高于实例 | 正常的模板更新，等待用户同步 | 显示待同步，不算错误 |
| 版本相同、指纹不同 | 文件被手改但版本号没变 | 警告用户，提示手动同步 |
| 目录里找不到模板 | 文件被删/改名/标识不匹配 | 警告用户，实例仍可编辑 |

把三者混成一个"有问题"布尔值会让用户无法判断该点同步、该查 Git，
还是该找回模板文件。
*/

use std::collections::BTreeMap;

use scene_doc::document::{场景文档, 实体标识};
use scene_doc::path::项目相对路径;
use scene_doc::prefab::{预制件实例记录, 预制件文档, 预制件标识};

use crate::project::项目描述;

/**
 * 加载模板目录时发现的问题。
 *
 * 这些问题只与磁盘上的模板文件有关，与任何场景实例无关；场景里的
 * 实例问题由 [`预制件告警`] 表达。分开是因为它们的修复动作不同：
 * 目录问题要用户修文件，实例问题可以点一次"同步"解决。
 */
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 模板目录问题 {
    /// 模板文件存在但读不出来或解析失败。
    读取失败 {
        路径: 项目相对路径, 摘要: String
    },
    /// 两个模板文件声明了同一个模板标识。
    标识重复 {
        路径: 项目相对路径,
        标识: 预制件标识,
        首个路径: 项目相对路径,
    },
}

impl 模板目录问题 {
    /// 面向控制台的一句话描述。
    pub fn 描述(&self) -> String {
        match self {
            Self::读取失败 { 路径, 摘要 } => {
                format!("预制件 {} 读取失败：{摘要}", 路径.文本())
            }
            Self::标识重复 {
                路径,
                标识,
                首个路径,
            } => format!(
                "预制件 {} 与 {} 声明了同一个模板标识 {}，后者已忽略",
                路径.文本(),
                首个路径.文本(),
                标识.0
            ),
        }
    }
}

/**
 * 场景里的实例与模板目录不一致的告警。
 *
 * 字段字典：
 * * `实例根` —— 出问题的实例根实体，用于在层级面板定位；
 * * `模板路径` —— 实例记录里保存的模板路径，文件缺失时用于提示去哪找；
 * * `记录版本 / 模板版本` —— 版本倒退时需要同时展示两边才能判断谁旧；
 * * `版本` —— 指纹不一致发生在哪一版。
 */
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 预制件告警 {
    模板缺失 {
        实例根: 实体标识,
        模板路径: 项目相对路径,
    },
    模板版本倒退 {
        实例根: 实体标识,
        记录版本: u64,
        模板版本: u64,
    },
    指纹不一致 {
        实例根: 实体标识,
        模板路径: 项目相对路径,
        版本: u64,
    },
}

impl 预制件告警 {
    /// 面向控制台的一句话描述。
    pub fn 描述(&self) -> String {
        match self {
            Self::模板缺失 {
                实例根, 模板路径
            } => format!(
                "实例 {实例根} 引用的预制件 {} 不存在（模板可能被删除或改名）",
                模板路径.文本()
            ),
            Self::模板版本倒退 {
                实例根,
                记录版本,
                模板版本,
            } => format!(
                "实例 {实例根} 期望预制件版本 {记录版本}，但文件里是更旧的 {模板版本}；请找回正确版本",
            ),
            Self::指纹不一致 {
                实例根,
                模板路径,
                版本,
            } => format!(
                "预制件 {} 的版本仍为 {版本}，但内容指纹已变化：文件可能被外部修改，实例 {实例根} 需要手动同步",
                模板路径.文本()
            ),
        }
    }
}

/**
 * 层级面板使用的实例状态标记。
 *
 * 字段字典：
 * * `待同步` —— 模板版本领先于实例已展开版本；
 * * `有覆盖` —— 实例存在本地字段覆盖（用户改过内容）；
 * * `模板缺失` —— 目录里找不到记录引用的模板；
 * * `指纹不一致` —— 版本没变但模板内容变了，属于外部手改。
 *
 * 四个标记可以同时成立：例如实例既有覆盖，模板又被更新。UI 因此逐项
 * 绘制图标，而不是从枚举里只能选一个。
 */
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct 预制件实例状态 {
    pub 待同步: bool,
    pub 有覆盖: bool,
    pub 模板缺失: bool,
    pub 指纹不一致: bool,
}

impl 预制件实例状态 {
    /// 是否需要用户注意（待同步也算，因为它是可执行的动作）。
    pub fn 需要处理(&self) -> bool {
        self.待同步 || self.有覆盖 || self.模板缺失 || self.指纹不一致
    }
}

/// 目录里的一条模板及其预计算指纹。
#[derive(Debug, Clone)]
struct 目录条目 {
    模板: 预制件文档,
    路径: Option<项目相对路径>,
    指纹: u64,
}

/**
 * 面板展示一条模板所需的只读视图。
 *
 * 字段字典：
 * * `标识` —— 模板身份，实例记录里引用的就是它；
 * * `模板` —— 模板内容，创建实例时克隆一封交给命令；
 * * `路径` —— 模板文件的项目相对路径，内存构造的目录没有路径。
 *
 * 用借用视图而不是克隆：面板每帧遍历全部模板，克隆整份模板只为了画一行
 * 名字，代价与收益不成比例。
 */
#[derive(Debug, Clone, Copy)]
pub struct 模板条目<'a> {
    pub 标识: 预制件标识,
    pub 模板: &'a 预制件文档,
    pub 路径: Option<&'a 项目相对路径>,
}

/**
 * 项目模板目录的只读索引。
 *
 * 内部用 `BTreeMap<预制件标识, 目录条目>`：按标识查找是 O(log n)，
 * 且遍历顺序稳定，便于测试与调试输出。路径只用于提示，不参与身份判断；
 * 模板文件改名/移动后只要标识不变，实例引用仍然有效。
 */
#[derive(Debug, Clone, Default)]
pub struct 预制件目录 {
    按标识: BTreeMap<预制件标识, 目录条目>,
}

impl 预制件目录 {
    /**
     * 扫描并加载项目里的全部模板。
     *
     * 返回目录与问题列表。单个文件失败不会中止整体加载：一个坏模板
     * 不应该让其它模板在层级面板里全部变成"缺失"。
     */
    pub fn 加载(项目: &项目描述) -> (Self, Vec<模板目录问题>) {
        let mut 目录 = Self::default();
        let mut 问题 = Vec::new();
        for 路径 in 项目.预制件列表() {
            match 项目.读取预制件(&路径) {
                Ok(模板) => {
                    let 标识 = 模板.头.标识;
                    if let Some(既有) = 目录.按标识.get(&标识) {
                        let 首个路径 = 既有.路径.clone().unwrap_or_else(|| 路径.clone());
                        问题.push(模板目录问题::标识重复 {
                            路径,
                            标识,
                            首个路径,
                        });
                        continue;
                    }
                    let 指纹 = 模板.内容指纹();
                    目录.按标识.insert(
                        标识,
                        目录条目 {
                            模板,
                            路径: Some(路径),
                            指纹,
                        },
                    );
                }
                Err(错误) => 问题.push(模板目录问题::读取失败 {
                    路径,
                    摘要: 错误.to_string(),
                }),
            }
        }
        (目录, 问题)
    }

    /**
     * 从内存中的模板列表构造目录。
     *
     * 用于测试以及"模板来自非项目目录"的调用方；路径未知，因此
     * [`预制件目录::路径`] 会返回 `None`，但身份与指纹仍然可用。
     */
    pub fn 从模板列表(模板: impl IntoIterator<Item = 预制件文档>) -> Self {
        let mut 目录 = Self::default();
        for 模板 in 模板 {
            let 标识 = 模板.头.标识;
            let 指纹 = 模板.内容指纹();
            目录.按标识.insert(
                标识,
                目录条目 {
                    模板,
                    路径: None,
                    指纹,
                },
            );
        }
        目录
    }

    /// 按标识取模板。
    pub fn 取(&self, 标识: &预制件标识) -> Option<&预制件文档> {
        self.按标识.get(标识).map(|条目| &条目.模板)
    }

    /// 按标识取模板文件路径（内存构造的目录没有路径）。
    pub fn 路径(&self, 标识: &预制件标识) -> Option<&项目相对路径> {
        self.按标识.get(标识).and_then(|条目| 条目.路径.as_ref())
    }

    /// 按标识取预计算的内容指纹。
    pub fn 指纹(&self, 标识: &预制件标识) -> Option<u64> {
        self.按标识.get(标识).map(|条目| 条目.指纹)
    }

    /// 模板数量。
    pub fn 数量(&self) -> usize {
        self.按标识.len()
    }

    /**
     * 按标识顺序遍历全部模板。
     *
     * 顺序取自 `BTreeMap` 的键序：稳定、可复现，面板每帧遍历不会跳动。
     * 面板据此画"模板列表"，实例状态查询仍走按标识直取。
     */
    pub fn 条目列表(&self) -> impl Iterator<Item = 模板条目<'_>> {
        self.按标识.iter().map(|(标识, 条目)| 模板条目 {
            标识: *标识,
            模板: &条目.模板,
            路径: 条目.路径.as_ref(),
        })
    }

    /**
     * 计算一条实例记录的状态。
     *
     * 比较规则：
     * 1. 目录里有模板时，用模板的**当前版本**判断待同步，而不是记录里
     *    保存的目标版本 —— 后者只有在同步命令执行后才会推进；
     * 2. 模板缺失时退回记录自身的版本关系，同时置 `模板缺失`；
     * 3. 只有版本相同才比较指纹；版本不同时指纹变化属于正常更新。
     */
    pub fn 实例状态(&self, 记录: &预制件实例记录) -> 预制件实例状态 {
        let Some(条目) = self.按标识.get(&记录.模板.标识) else {
            return 预制件实例状态 {
                待同步: 记录.待同步(),
                有覆盖: 记录.有覆盖(),
                模板缺失: true,
                指纹不一致: false,
            };
        };
        预制件实例状态 {
            待同步: 记录.待同步到(条目.模板.头.版本),
            有覆盖: 记录.有覆盖(),
            模板缺失: false,
            指纹不一致: 条目.模板.头.版本 == 记录.模板.版本 && 条目.指纹 != 记录.模板.内容指纹,
        }
    }

    /**
     * 检查当前场景里的所有实例，返回需要告警的条目。
     *
     * 不报告"待同步"：那是正常的工作流状态，由 UI 的蓝色箭头表达，
     * 每打开一次场景就往控制台刷一遍"你有更新"只会制造噪音。
     */
    pub fn 检查(&self, 文档: &场景文档) -> Vec<预制件告警> {
        let mut 告警 = Vec::new();
        for (实例根, 记录) in &文档.预制件实例表 {
            let Some(条目) = self.按标识.get(&记录.模板.标识) else {
                告警.push(预制件告警::模板缺失 {
                    实例根: *实例根,
                    模板路径: 记录.模板.路径.clone(),
                });
                continue;
            };
            if 条目.模板.头.版本 < 记录.模板.版本 {
                告警.push(预制件告警::模板版本倒退 {
                    实例根: *实例根,
                    记录版本: 记录.模板.版本,
                    模板版本: 条目.模板.头.版本,
                });
            } else if 条目.模板.头.版本 == 记录.模板.版本 && 条目.指纹 != 记录.模板.内容指纹
            {
                告警.push(预制件告警::指纹不一致 {
                    实例根: *实例根,
                    模板路径: 记录.模板.路径.clone(),
                    版本: 记录.模板.版本,
                });
            }
        }
        告警
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use scene_doc::document::场景文档;
    use scene_doc::path::项目相对路径;
    use scene_doc::prefab::{覆盖键, 预制件实例记录};

    fn 造模板() -> 预制件文档 {
        let mut 场景 = 场景文档::新建("敌人模板");
        let 根 = 场景.生成实体("敌人", None);
        预制件文档::新建("敌人", 根, 场景)
    }

    fn 路径() -> 项目相对路径 {
        项目相对路径::解析("prefabs/敌人.prefab.ron").expect("路径")
    }

    fn 造文档(模板: &预制件文档) -> (场景文档, 实体标识) {
        let mut 文档 = 场景文档::新建("关卡");
        let 实例根 = 文档.生成实体("敌人实例", None);
        let mut 记录 = 预制件实例记录::新建(模板.引用(路径()));
        记录.展开版本 = 模板.头.版本;
        文档.预制件实例表.insert(实例根, 记录);
        (文档, 实例根)
    }

    #[test]
    fn 同版本改内容会报告指纹不一致() {
        let 模板 = 造模板();
        let (文档, _) = 造文档(&模板);

        let 目录 = 预制件目录::从模板列表([模板.clone()]);
        assert!(目录.检查(&文档).is_empty(), "内容一致时不应告警");

        let mut 被改 = 模板;
        被改.场景.取可变(被改.头.根).expect("根").名称 = "被手改的敌人".to_string();
        let 目录 = 预制件目录::从模板列表([被改]);
        let 告警 = 目录.检查(&文档);
        assert_eq!(告警.len(), 1);
        assert!(matches!(告警[0], 预制件告警::指纹不一致 { .. }));
    }

    #[test]
    fn 版本推进属于待同步而不是指纹告警() {
        let 模板 = 造模板();
        let (文档, 实例根) = 造文档(&模板);

        let mut 新版 = 模板;
        新版.头.版本 = 2;
        新版.场景.取可变(新版.头.根).expect("根").名称 = "敌人二代".to_string();
        let 目录 = 预制件目录::从模板列表([新版]);

        assert!(目录.检查(&文档).is_empty(), "版本更新是正常状态，不该告警");
        let 状态 = 目录.实例状态(&文档.预制件实例表[&实例根]);
        assert!(状态.待同步);
        assert!(!状态.指纹不一致);
        assert!(!状态.模板缺失);
    }

    #[test]
    fn 模板缺失会标记状态并告警() {
        let 模板 = 造模板();
        let (文档, 实例根) = 造文档(&模板);
        let 目录 = 预制件目录::default();

        let 告警 = 目录.检查(&文档);
        assert_eq!(告警.len(), 1);
        assert!(matches!(告警[0], 预制件告警::模板缺失 { .. }));
        assert!(目录.实例状态(&文档.预制件实例表[&实例根]).模板缺失);
    }

    #[test]
    fn 本地覆盖会标记已修改() {
        let 模板 = 造模板();
        let (mut 文档, 实例根) = 造文档(&模板);
        文档.预制件实例表.get_mut(&实例根).expect("记录").覆盖.设值(
            覆盖键::整组件(scene_doc::prefab::节点地址::根(), "Sprite"),
            scene_doc::property::属性值::文本("红".to_string()),
        );

        let 目录 = 预制件目录::从模板列表([模板]);
        let 状态 = 目录.实例状态(&文档.预制件实例表[&实例根]);
        assert!(状态.有覆盖);
        assert!(状态.需要处理());
    }

    /**
     * 验证面板依赖的两条性质：条目数与模板数一致，遍历顺序与键序一致。
     *
     * 顺序稳定是面板不闪动的前提：`BTreeMap` 按键排序，而键是随机 UUID，
     * 因此这里不能假设插入次序，只能断言"遍历结果已按标识升序"。
     */
    #[test]
    fn 条目列表按标识顺序遍历且内存目录没有路径() {
        let 甲 = 造模板();
        let mut 乙 = 造模板();
        乙.头.名称 = "道具".to_string();
        let 目录 = 预制件目录::从模板列表([甲, 乙]);

        let 条目: Vec<_> = 目录.条目列表().collect();
        assert_eq!(条目.len(), 目录.数量());

        let 标识: Vec<_> = 条目.iter().map(|条目| 条目.标识).collect();
        let mut 排序后 = 标识.clone();
        排序后.sort();
        assert_eq!(标识, 排序后, "遍历顺序必须与 BTreeMap 键序一致");
        assert!(
            条目.iter().all(|条目| 条目.路径.is_none()),
            "内存构造的目录没有文件路径"
        );
    }
}
