    /**
     * 验证面板依赖的两条性质：条目数与模板数一致，遍历顺序与键序一致。
     *
     * 顺序稳定是面板不闪动的前提：`BTreeMap` 按键排序，而键是随机 UUID，
     * 因此这里不能假设插入次序，只能断言"遍历结果已按标识升序"。
     */
    #[test]
    fn 条目列表按标识顺序遍历且内存目录没有路径() {
        let 甲 = 造模板();
        let mut 乙 = 造模板();
        乙.头.名称 = "道具".to_string();
        let 目录 = 预制件目录::从模板列表([甲, 乙]);

        let 条目: Vec<_> = 目录.条目列表().collect();
        assert_eq!(条目.len(), 目录.数量());

        let 标识: Vec<_> = 条目.iter().map(|条目| 条目.标识).collect();
        let mut 排序后 = 标识.clone();
        排序后.sort();
        assert_eq!(标识, 排序后, "遍历顺序必须与 BTreeMap 键序一致");
        assert!(
            条目.iter().all(|条目| 条目.路径.is_none()),
            "内存构造的目录没有文件路径"
        );
    }

    /**
     * 在模板根下挂一个引用 `内层` 的站点，得到深一层的模板。
     */
    fn 套一层(名称: &str, 内层: &预制件文档, 内层路径: &str) -> 预制件文档 {
        let mut 场景 = 场景文档::新建(名称);
        let 根 = 场景.生成实体(名称, None);
        let 站点 = 场景.生成实体("站点", Some(根));
        场景.预制件实例表.insert(
            站点,
            预制件实例记录::新建(
                内层.引用(项目相对路径::解析(内层路径).expect("测试里的路径始终合法")),
            ),
        );
        预制件文档::新建(名称, 根, 场景)
    }

    /**
     * 超过上限的嵌套链作为目录问题报出，正好等于上限的不算问题。
     *
     * 四层链 `载具→枪→弹匣→敌人` 的深度依次是 4/3/2/1：上限取 2 时只报
     * 前两份。若把"等于上限"也报出来，用户会收到一条其实能正常展开的告警。
     *
     * 模板标识是随机 UUID，因此结果顺序只能断言"按标识升序"，不能假设
     * 它等于构造顺序 —— 这条性质来自依赖图的 `BTreeMap` 键序。
     */
    #[test]
    fn 嵌套超过上限的模板报成目录问题() {
        let 丁 = 造模板();
        let 丙 = 套一层("弹匣", &丁, "prefabs/敌人.prefab.ron");
        let 乙 = 套一层("枪", &丙, "prefabs/弹匣.prefab.ron");
        let 甲 = 套一层("载具", &乙, "prefabs/枪.prefab.ron");
        let 目录 =
            预制件目录::从模板列表([甲.clone(), 乙.clone(), 丙.clone(), 丁.clone()]);

        let 问题 = 目录.检查嵌套深度(2);
        assert_eq!(问题.len(), 2, "深度 4 与 3 超限，深度 2 正好等于上限");

        let 标识: Vec<预制件标识> = 问题
            .iter()
            .map(|问题| match 问题 {
                模板目录问题::嵌套过深 {
                    标识,
                    名称,
                    深度,
                    上限,
                    ..
                } => {
                    assert_eq!(*上限, 2);
                    assert!(*深度 > 2, "报出来的都必须真的超限");
                    assert!(名称 == "载具" || 名称 == "枪", "超限的两份模板：{名称}");
                    *标识
                }
                其他 => panic!("只该产出嵌套过深：{其他:?}"),
            })
            .collect();
        let mut 按标识 = 标识.clone();
        按标识.sort();
        assert_eq!(标识, 按标识, "顺序必须取自依赖图键序，日志才可比对");

        let 载具描述 = 问题
            .iter()
            .find(|项| matches!(项, 模板目录问题::嵌套过深 { 名称, .. } if 名称 == "载具"))
            .expect("深度 4 的载具必须在结果里")
            .描述();
        assert!(
            载具描述.contains("展开上限 2"),
            "告警要给出上限：{载具描述}"
        );

        assert!(
            目录.检查嵌套深度(scene_doc::最大嵌套深度).is_empty(),
            "四层链在真实上限 8 之下完全合法，不该报"
        );
    }

    /**
     * 目录可以不做任何转换就交给嵌套展开规划器。
     *
     * 守住解析器实现真的按标识命中：命中失败时规划器会把站点降级成普通
     * 节点并记一条"模板缺失"告警，展开结果看起来"少了内容"却没有任何错误。
     */
    #[test]
    fn 目录作为解析器供规划器展开内层() {
        let 内层 = 造模板();
        let 外层 = 套一层("枪", &内层, "prefabs/敌人.prefab.ron");
        let 目录 = 预制件目录::从模板列表([内层.clone(), 外层.clone()]);

        let 实例根 = 实体标识::新建();
        let 记录 = 预制件实例记录::新建(
            外层.引用(项目相对路径::解析("prefabs/枪.prefab.ron").expect("路径")),
        );
        let 计划 = scene_doc::prefab_nested::规划嵌套展开(
            实例根,
            &外层,
            &记录,
            &BTreeMap::new(),
            &目录,
            scene_doc::最大嵌套深度,
        )
        .expect("目录齐全时规划不该失败");

        assert!(计划.告警.is_empty(), "不该有任何降级：{:?}", 计划.告警);
        assert_eq!(计划.内层实例数(), 1, "站点必须由目录里的模板展开");
    }
