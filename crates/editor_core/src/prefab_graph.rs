    /**
     * 深度口径必须是展开器的层数口径：模板自己算第 1 层，每个站点再深一层。
     *
     * 菱形依赖取**最长**那条分支，因为展开时两条分支都会走，决定超限
     * 的是最深的一行实体而不是先遍历到哪一支。
     */
    #[test]
    fn 最长嵌套深度按站点层数计数() {
        let 甲 = 预制件标识::新建();
        let 乙 = 预制件标识::新建();
        let 丙 = 预制件标识::新建();
        let 丁 = 预制件标识::新建();

        let 直链 = {
            let mut 图 = 预制件依赖图::default();
            加(&mut 图, 甲, "甲", &[乙]);
            加(&mut 图, 乙, "乙", &[丙]);
            加(&mut 图, 丙, "丙", &[]);
            图.最长嵌套深度()
        };
        assert_eq!(直链.get(&丙), Some(&1), "不带内层实例的模板本身就是一层");
        assert_eq!(直链.get(&乙), Some(&2));
        assert_eq!(直链.get(&甲), Some(&3));

        let 菱形 = {
            let mut 图 = 预制件依赖图::default();
            加(&mut 图, 甲, "甲", &[乙, 丙]);
            加(&mut 图, 乙, "乙", &[丁]);
            加(&mut 图, 丙, "丙", &[]);
            加(&mut 图, 丁, "丁", &[]);
            图.最长嵌套深度()
        };
        assert_eq!(菱形.get(&甲), Some(&3), "甲→乙→丁 是更深的那条分支");
        assert_eq!(菱形.get(&乙), Some(&2));
        assert_eq!(菱形.get(&丙), Some(&1));
    }

