    /**
     * 环上的模板以及能走到环的模板都不进入深度结果。
     *
     * 它们的深度没有上界，报成"嵌套过深"会把用户引向"把链改短"这个错误
     * 的修复动作；同一个结构由 [`预制件依赖图::检测环`] 报成循环引用。
     */
    #[test]
    fn 能走到环的节点没有定义深度() {
        let 甲 = 预制件标识::新建();
        let 乙 = 预制件标识::新建();
        let 戊 = 预制件标识::新建();
        let 独立 = 预制件标识::新建();

        let mut 图 = 预制件依赖图::default();
        加(&mut 图, 甲, "甲", &[乙]);
        加(&mut 图, 乙, "乙", &[甲]);
        加(&mut 图, 戊, "戊", &[甲]);
        加(&mut 图, 独立, "独立", &[]);

        let 深度 = 图.最长嵌套深度();
        assert_eq!(深度.keys().copied().collect::<Vec<_>>(), vec![独立]);
        assert_eq!(图.检测环经过(&甲).len(), 1, "同一结构要走环检测这条通道");
    }
