/// 判断场景名是否只是"新建时的占位名"，从而允许在首次保存时被文件名替换。
///
/// 只认明确列出的占位名，不做模糊匹配：用户真的把场景命名为"主场景"
/// 是完全合理的，不能被静默改掉。
fn is_占位场景名(名称: &str) -> bool {
    matches!(名称, "未命名场景" | "主场景")
}

/// 从 `scenes/关卡.scene.ron` 这样的路径里取出 `关卡` 作为场景基准名。
///
/// 只剥掉末尾连续的已知扩展名，而不是"取最后一个点之前的部分" ——
/// 后者会把 `关卡.v2.scene.ron` 变成 `关卡`，丢掉用户刻意写进名字里的版本号。
fn 场景基准名(路径: &项目相对路径) -> Option<String> {
    let mut 名字 = 路径.文件名();
    for 已知扩展 in [".scene.ron", ".scn.ron", ".ron", ".scene", ".scn"] {
        if let Some(剩余) = 名字.strip_suffix(已知扩展) {
            名字 = 剩余;
            break;
        }
    }
    let 名字 = 名字.trim();
    if 名字.is_empty() {
        None
    } else {
        Some(名字.to_string())
    }
}

/// 取当前 Unix 时间戳（秒）。取不到时返回 `None`，
/// 而不是把 0 当作"1970 年保存"写进文件。
fn 当前时间秒() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|时长| 时长.as_secs())
        .unwrap_or(0)
}

