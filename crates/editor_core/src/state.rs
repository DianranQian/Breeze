    /// 动画的默认保存路径：`animations/<场景名>.anim.ron`。
    ///
    /// 用场景名而不是动画名，是因为用户的心智模型是"这个关卡的动画"；
    /// 一个场景对应一份动画，重新打开项目后能直接找回来。
    pub fn 默认动画路径(&self) -> Option<项目相对路径> {
        let 基准名 = if is_占位场景名(&self.会话.文档.元数据.场景名) {
            self.会话
                .路径
                .as_ref()
                .and_then(场景基准名)
                .unwrap_or_else(|| "动画".to_string())
        } else {
            self.会话.文档.元数据.场景名.clone()
        };
        let 文件名 = format!("{}.anim.ron", crate::project::清理文件名(&基准名));
        项目相对路径::解析(format!("{}/{}", crate::project::目录名::动画, 文件名)).ok()
    }

    /// 打开项目中的一个动画文件。
    pub fn 打开动画(&mut self, 路径: &项目相对路径) -> 场景结果<()> {
        let Some(项目) = self.项目.as_ref() else {
            return Err(场景错误::非法("尚未打开项目，无法打开动画文件"));
        };
        let 绝对 = 路径.拼接(项目.根目录());
        let 文本 =
            std::fs::read_to_string(&绝对).map_err(|错误| 场景错误::文件(&绝对, 错误))?;
        let 文档 = 动画文档::解码(&文本, &绝对)?;
        let 问题 = 文档.校验(&self.会话.文档);
        self.动画 = Some(动画会话::已保存(文档, 路径.clone()));
        self.动画播放 = 动画播放状态::新建();
        self.结构化信息(
            "log_animation_opened",
            vec![日志参数::用户数据(路径.文本().to_string())],
        );
        for 问题 in 问题 {
            self.警告(format!("动画校验：{问题}"));
        }
        Ok(())
    }

    /// 保存当前动画到指定路径。
    pub fn 保存动画到(&mut self, 路径: &项目相对路径) -> 场景结果<()> {
        let Some(项目根) = self.项目.as_ref().map(|项目| 项目.根目录().to_path_buf())
        else {
            return Err(场景错误::非法("尚未打开项目，无法保存动画文件"));
        };
        let Some(会话) = self.动画.as_mut() else {
            return Err(场景错误::非法("当前没有动画可保存"));
        };
        let 绝对 = 路径.拼接(&项目根);
        if let Some(父目录) = 绝对.parent() {
            std::fs::create_dir_all(父目录)
                .map_err(|错误| 场景错误::文件(父目录.to_path_buf(), 错误))?;
        }
        会话.文档.格式版本 = crate::animation::动画格式版本;
        let 文本 = 会话.文档.编码()?;
        // 原子写：先写临时文件再改名，中途崩溃不会留下半个动画文件。
        let 临时 = 绝对.with_extension("ron.tmp");
        std::fs::write(&临时, 文本.as_bytes())
            .map_err(|错误| 场景错误::文件(临时.clone(), 错误))?;
        std::fs::rename(&临时, &绝对).map_err(|错误| 场景错误::文件(绝对.clone(), 错误))?;
        会话.标记已保存(Some(路径.clone()));
        self.结构化信息(
            "log_animation_saved",
            vec![日志参数::用户数据(路径.文本().to_string())],
        );
        Ok(())
    }

    /// 保存当前动画到它已关联的路径。
    pub fn 保存动画(&mut self) -> 场景结果<()> {
        let Some(路径) = self.动画.as_ref().and_then(|会话| 会话.路径.clone()) else {
            return Err(场景错误::非法("当前动画尚未保存过，请先指定保存路径"));
        };
        self.保存动画到(&路径)
    }

    /// 把播放头时间夹到当前动画时长内。
    pub fn 动画定位(&mut self, 时间: f32) {
        let Some(会话) = self.动画.as_ref() else {
            return;
        };
        let 时长 = 会话.文档.时长;
        self.动画播放.定位(时间, 时长);
    }

    /// 在播放头处，为选中实体的指定属性录制关键帧。
    ///
    /// 返回真正录制成功的属性数量。没有动画、没有选中实体时返回 0，
    /// 调用方据此给出提示，而不是静默什么都不做。
    pub fn 录制选中实体关键帧(&mut self, 属性列表: &[动画属性]) -> usize {
        let 时间 = self.动画播放.时间;
        let 选中: Vec<实体标识> = self.选择.全部();
        let Some(会话) = self.动画.as_mut() else {
            return 0;
        };
        let mut 成功 = 0;
        for 实体 in 选中 {
            for 属性 in 属性列表 {
                if 会话
                    .文档
                    .录制关键帧(&self.会话.文档, 实体, *属性, 时间)
                    .is_some()
                {
                    成功 += 1;
                }
            }
        }
        成功
    }

