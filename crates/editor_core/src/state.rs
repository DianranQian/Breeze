//! 编辑器状态：把文档、项目、选择集与撤销栈组合成可被 UI 驱动的一体。
//!
//! # 事务边界在哪里
//!
//! 所有对文档的修改都必须经过 [`编辑器状态::执行`]。这个方法做四件事，
//! 且顺序不可交换：
//!
//! 1. **克隆**当前文档；
//! 2. 在克隆上 [`编辑器命令::应用`]；
//! 3. 失败则整体放弃，正本一字未动；
//! 4. 成功才提交回正本，并记录撤销条目。
//!
//! "在克隆上执行"是这套设计能同时满足"命令可以部分执行后失败"和
//! "失败不留痕迹"的关键。代价是每次编辑都要克隆一次文档 —— 对
//! 常见规模（数百到数千实体）这是微秒到毫秒级，可以接受；
//! 真正的性能红线是**不能每次改属性都重新序列化整个项目**，
//! 而克隆与序列化是两件事（见 [`crate::undo`] 的字节估算注释）。

