/// 编辑器的一次操作日志条目。用于底部控制台面板。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 日志条目 {
    /// 严重程度。
    pub 级别: 日志级别,
    /// 内容。见 [`日志内容`]。
    pub 内容: 日志内容,
}

/// 一条日志的结构化参数。
///
/// 参数**不参与翻译**：模板按语言翻译，参数按原样填进去。
/// 区分种类是把"这是用户数据"写在类型上 ——
/// 路径、实体名、场景名、资源名属于用户数据，任何语言下都不该被翻译。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 日志参数 {
    /// 用户数据：文件路径、实体名、场景名、资源名。**绝不翻译**。
    用户数据(String),
    /// 技术诊断文本（例如底层库的原始错误原因）。
    诊断(String),
    /// 数值。
    数值(i64),
    /// 一个**可再翻译的子消息**。
    ///
    /// # 为什么需要它
    ///
    /// 真实场景是"外层模板 + 内层原因"，两层都要能翻译，例如
    /// `自动载入场景失败：<文件读写失败：路径 —— 原因>`。
    /// 若把内层先渲染成字符串再当参数塞进去，内层就**固化在**
    /// 生成日志时的语言里，切换语言也变不回来 —— 这正是本轮要避免的。
    ///
    /// 嵌套之后，两种语言的模板与参数都保留到显示时，
    /// 整条消息（含嵌套部分）可以一起按当前语言重新渲染。
    子消息 {
        /// 子消息的词条键。
        标识: &'static str,
        /// 子消息的参数。
        参数: Vec<日志参数>,
    },
}

impl 日志参数 {
    /// 由 `scene_doc` 的结构化错误参数转换而来。
    ///
    /// 路径是用户数据、诊断是技术文本，两者都不翻译 ——
    /// 这个映射把"不翻译"这件事写进了类型。
    pub fn 从错误参数(参数: scene_doc::error::错误参数) -> Self {
        match 参数 {
            scene_doc::error::错误参数::路径(路径) => {
                日志参数::用户数据(路径.display().to_string())
            }
            scene_doc::error::错误参数::数值(数值) => 日志参数::数值(数值 as i64),
            scene_doc::error::错误参数::诊断(文本) => 日志参数::诊断(文本),
        }
    }

    /// 由 `scene_doc` 的结构化错误构造一条可翻译的子消息。
    pub fn 从场景错误(错误: &scene_doc::error::场景错误) -> Self {
        日志参数::子消息 {
            标识: 错误.消息键(),
            参数: 错误.参数().into_iter().map(Self::从错误参数).collect(),
        }
    }

    /// 按给定语言渲染本参数（嵌套子消息递归渲染，保证整条消息语言一致）。
    pub fn 渲染(&self, 语言: crate::i18n::语言) -> String {
        match self {
            日志参数::用户数据(文本) | 日志参数::诊断(文本) => 文本.clone(),
            日志参数::数值(数值) => 数值.to_string(),
            日志参数::子消息 { 标识, 参数 } => 渲染模板(语言, 标识, 参数),
        }
    }
}

impl std::fmt::Display for 日志参数 {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            日志参数::用户数据(文本) | 日志参数::诊断(文本) => {
                write!(f, "{文本}")
            }
            日志参数::数值(数值) => write!(f, "{数值}"),
            日志参数::子消息 { 标识, .. } => write!(f, "{标识}"),
        }
    }
}

/// 日志条目的内容。
///
/// # 为什么要分两种情况
///
/// 日志的**身份不能是自然语言句子** —— 否则改一句中文就等于换了身份，
/// 而且没法按语言重新渲染。所以已迁移的条目存"稳定标识 + 参数"。
///
/// 但仓库里还有几十个调用点没迁移，本轮也不打算一次改完。
/// [`日志内容::自由文本`] 让那些调用点**保持原有行为**，
/// 从而支持分批迁移 —— 而不是为了看起来干净把日志删掉。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 日志内容 {
    /// 已结构化：稳定标识 + 参数，按当前语言渲染。
    结构化 {
        /// 词条键。与语言无关。
        标识: &'static str,
        /// 结构化参数。
        参数: Vec<日志参数>,
    },
    /// 尚未迁移的自由文本：原样显示，不做翻译。
    自由文本(String),
}

/// 按语言填充模板里的 `{}`，参数可以是嵌套的**可翻译子消息**。
///
/// # 为什么不用 `语言::填充`
///
/// `填充` 接收 `&dyn Display`，而 `Display` 拿不到语言 ——
/// 嵌套子消息就没法按目标语言渲染。日志需要"整条消息语言一致"，
/// 所以这里自己走一遍占位符，把语言一路传下去。
fn 渲染模板(
    语言: crate::i18n::语言, 标识: &'static str, 参数: &[日志参数]
) -> String {
    let 模板 = 语言.取(标识);
    let mut 结果 = String::with_capacity(模板.len() + 32);
    let mut 迭代 = 参数.iter();
    let mut 剩余 = 模板;
    while let Some(左) = 剩余.find("{}") {
        结果.push_str(&剩余[..左]);
        match 迭代.next() {
            Some(值) => 结果.push_str(&值.渲染(语言)),
            None => 结果.push_str("{}"),
        }
        剩余 = &剩余[左 + 2..];
    }
    结果.push_str(剩余);
    结果
}

impl 日志条目 {
    /// 按给定语言渲染成可显示文本。
    ///
    /// 关键点：渲染发生在**显示时**而不是产生时，
    /// 因此切换语言后，缓存里的历史日志会跟着变成新语言。
    pub fn 渲染(&self, 语言: crate::i18n::语言) -> String {
        match &self.内容 {
            日志内容::结构化 { 标识, 参数 } => 渲染模板(语言, 标识, 参数),
            日志内容::自由文本(文本) => 文本.clone(),
        }
    }

    /// 稳定标识。自由文本条目没有标识，返回 `None`。
    ///
    /// 供测试与日志检索使用：它能在不关心语言的前提下定位一条日志。
    pub fn 标识(&self) -> Option<&'static str> {
        match &self.内容 {
            日志内容::结构化 { 标识, .. } => Some(标识),
            日志内容::自由文本(_) => None,
        }
    }

    /// 开发者诊断文本：始终是中文原文/技术文本，不随界面语言变化。
    ///
    /// 用于 stderr 转发这类开发侧通道 —— 那里需要的是**稳定的检索文本**，
    /// 而不是随用户语言变化的展示文本。
    pub fn 诊断文本(&self) -> String {
        self.渲染(crate::i18n::语言::中文)
    }
}

/// 日志级别。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 日志级别 {
    /// 普通信息。
    信息,
    /// 警告。
    警告,
    /// 错误。
    错误,
}

impl 日志级别 {
    /// 用于显示的前缀（按当前语言）。
    ///
    /// 原先返回硬编码中文 `[信息]/[警告]/[错误]`，英文模式下控制台
    /// 每行前面都挂着一个中文前缀 —— 这也是界面中文残留的一处。
    pub fn 前缀(&self, 语言: crate::i18n::语言) -> &'static str {
        match self {
            日志级别::信息 => 语言.取("log_level_info"),
            日志级别::警告 => 语言.取("log_level_warning"),
            日志级别::错误 => 语言.取("log_level_error"),
        }
    }
}

/// 从未保存过的新场景所用的名字。
