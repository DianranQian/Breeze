    // ------------------------------------------------------------------
    // 变换拖拽事务：预览 → 提交 / 取消
    //
    // # 为什么需要单独一条通道
    //
    // `执行` 每次都会**克隆整份文档**并把"执行前"快照压进撤销栈。操纵器拖拽
    // 每帧都要更新预览，如果走 `执行`，一次 1 秒的拖拽就会压进 ~60 条撤销
    // 记录、克隆 60 份文档 —— 用户按一次 Ctrl+Z 只能退回一个鼠标像素，
    // 大场景下还会明显掉帧。
    //
    // 因此拖拽期间的预览走 [`编辑器状态::预览变换`]：只改文档内容、只递增
    // 修订号（让预览视口重建），**不碰撤销栈**。松手时由
    // [`编辑器状态::提交变换`] 恢复起始状态再执行**一条**批量命令，
    // 于是整次拖拽恰好对应一条撤销记录。
    // ------------------------------------------------------------------

    /// 当前可撤销的步数（供界面与自动验收核对"一次拖拽一条记录"）。
    pub fn 可撤销步数(&self) -> usize {
        self.撤销.可撤销步数()
    }

    /// 撤销栈当前估算占用的字节数（诊断与性能测试用）。
    pub fn 撤销内存估算字节(&self) -> usize {
        self.撤销.估算字节()
    }

    /// 最近几条撤销记录的显示名（最新的在最后）。
    ///
    /// 用于诊断"撤销栈为什么涨得这么快"：只看步数只能知道涨了，
    /// 看名字才能知道是谁在记。
    pub fn 最近撤销条目(&self, 数量: usize) -> Vec<String> {
        self.撤销.最近条目名(数量)
    }

    /// 把给定变换**直接写入文档**，不产生撤销记录。
    ///
    /// 只用于操纵器拖拽期间的实时预览。返回值表示文档是否真的变了
    /// （调用方可据此避免无意义的修订号递增）。
    pub fn 预览变换(&mut self, 项: &[(实体标识, 变换数据)]) -> bool {
        let mut 改动 = false;
        for (标识, 变换) in 项 {
            let Some(实体) = self.会话.文档.取可变(*标识) else {
                continue;
            };
            if 实体.变换 != Some(*变换) {
                实体.变换 = Some(*变换);
                改动 = true;
            }
        }
        if 改动 {
            self.标记文档已变更();
        }
        改动
    }

    /// 提交一次变换编辑：`起始 → 最终`，只产生**一条**撤销记录。
    ///
    /// # 为什么先把文档恢复成起始状态
    ///
    /// `执行` 把**当前**文档当作撤销条目的"执行前"快照。预览已经把文档
    /// 改成了最终值，若不先恢复，撤销只会回到"预览的最后一帧"，
    /// 而不是拖拽开始前 —— 用户会看到"撤销一次只退了一点点"。
    ///
    /// 返回是否真的产生了提交（没有实际变化时不记历史）。
    pub fn 提交变换(
        &mut self,
        起始: &[(实体标识, 变换数据)],
        最终: &[(实体标识, 变换数据)],
    ) -> bool {
        self.预览变换(起始);
        let 项: Vec<(实体标识, Option<变换数据>)> = 最终
            .iter()
            .filter(|(标识, 变换)| {
                // 只把真正变了的分量写进命令：未操作轴与未选实体都不进命令，
                // 它们的状态因此必然保持不变。
                起始
                    .iter()
                    .find(|(起标识, _)| 起标识 == 标识)
                    .map(|(_, 起变换)| 起变换 != 变换)
                    .unwrap_or(true)
            })
            .map(|(标识, 变换)| (*标识, Some(*变换)))
            .collect();
        if 项.is_empty() {
            return false;
        }
        self.执行并记录(编辑器命令::批量设变换 { 项 }).is_some()
    }

    /// 取消预览：把文档恢复成起始变换，不产生撤销记录。
    pub fn 取消变换(&mut self, 起始: &[(实体标识, 变换数据)]) {
        self.预览变换(起始);
    }

    // ------------------------------------------------------------------
    // 命令执行
    // ------------------------------------------------------------------

    /// 执行一条命令。这是**唯一**允许修改文档的入口。
    pub fn 执行(&mut self, 命令: 编辑器命令) -> 场景结果<命令结果> {
        self.执行内部(命令, false)
    }

    /// 执行一条**连续编辑**命令（数值框/滑块拖拽中的一帧）。
    ///
    /// 与 [`编辑器状态::执行`] 的唯一区别是：撤销栈会把连续发生的同目标
    /// 编辑合并成一条记录，用户按一次 Ctrl+Z 就退回整段拖拽之前。
    pub fn 执行连续(&mut self, 命令: 编辑器命令) -> 场景结果<命令结果> {
        self.执行内部(命令, true)
    }

    /// 执行命令的统一实现。
    fn 执行内部(
        &mut self, 命令: 编辑器命令, 连续: bool
    ) -> 场景结果<命令结果> {
        // # 为什么只克隆一次
        //
        // 旧实现克隆两次（一次做"执行前"快照、一次做工作副本），实测
        // 1000 实体时每次 47µs，且要把整份文档压进撤销栈。
        // 现在只留一份"执行前"内容用于**比较出差量**，命令直接在正本上执行；
        // 失败时用这份内容整体回滚，语义与"在副本上执行"完全一致。
        let 执行前 = self.会话.文档.clone();

        let 结果 = match 命令.应用(&mut self.会话.文档) {
            Ok(结果) => 结果,
            Err(错误) => {
                // 失败必须让正本回到原样：命令可能已经改了一半。
                self.会话.文档.覆盖为(&执行前);
                return Err(错误);
            }
        };

        let 差量 = 文档差量::比较(&执行前, &self.会话.文档);

        // 成功的命令也可能什么都没改（例如把变换设成与原值相同）。
        // 这种"空操作"不该出现在历史里：用户按一次撤销却什么都没发生，
        // 比不能撤销更让人困惑。
        if !差量.为空() {
            if 连续 {
                self.撤销.提交连续(命令, 差量, 结果.新实体);
            } else {
                self.撤销.提交(命令, 差量, 结果.新实体);
            }
        }

        // 选择集必须跟着文档走，否则删除后会出现"幽灵选中"。
        self.选择.清理失效项(&self.会话.文档);
        self.标记文档已变更();

        Ok(结果)
    }

    /// 执行命令并把结果里的实体设为当前选择（UI 新建实体时的常见需求）。
    pub fn 执行并选中(&mut self, 命令: 编辑器命令) -> 场景结果<命令结果> {
        let 结果 = self.执行(命令)?;
        if let Some(标识) = 结果.新实体 {
            self.选择.单选(标识);
        }
        Ok(结果)
    }

    /// 执行一条连续编辑命令，失败时只记控制台（供 UI 拖拽逐帧调用）。
    pub fn 执行并记录连续(&mut self, 命令: 编辑器命令) -> Option<命令结果> {
        match self.执行连续(命令) {
            Ok(结果) => Some(结果),
            Err(错误) => {
                self.错误(format!("操作失败：{错误}"));
                None
            }
        }
    }

    /// 执行命令，失败时把错误记入控制台而不是向上传播。
    ///
    /// 供 UI 事件处理使用：UI 里每个按钮都写一遍错误处理既啰嗦又容易漏。
    pub fn 执行并记录(&mut self, 命令: 编辑器命令) -> Option<命令结果> {
        match self.执行(命令) {
            Ok(结果) => Some(结果),
            Err(错误) => {
                self.错误(format!("操作失败：{错误}"));
                None
            }
        }
    }

    // ------------------------------------------------------------------
    // 撤销 / 重做
    // ------------------------------------------------------------------

    /// 撤销一步。返回是否真的撤销了什么。
    pub fn 撤销一步(&mut self) -> bool {
        let Some(条目) = self.撤销.弹出撤销() else {
            self.信息("没有可撤销的操作");
            return false;
        };

        // 只把差量里记过的字段还原，其余保持现状。
        条目.差量.逆向应用(&mut self.会话.文档);
        let 名称 = 条目.显示名.clone();
        self.撤销.推入重做(条目);
        self.选择.清理失效项(&self.会话.文档);
        self.标记文档已变更();
        self.信息(format!("已撤销：{名称}"));
        true
    }

    /// 重做一步。返回是否真的重做了什么。
    pub fn 重做一步(&mut self) -> bool {
        let Some(条目) = self.撤销.弹出重做() else {
            self.信息("没有可重做的操作");
            return false;
        };

        // 在克隆上重放命令，失败则把条目放回去，避免历史与文档脱节。
        //
        // 必须用 `重做命令` 而不是原始命令：原始 `新建实体` 命令的
        // `指定标识` 是 `None`，直接重放会生成一个新的 UUID，
        // 导致"重做后实体标识变了"这种极难排查的问题。
        let 重放命令 = 条目.重做用命令();
        let mut 工作副本 = self.会话.文档.clone();
        match 重放命令.应用(&mut 工作副本) {
            Ok(_) => {
                self.会话.文档 = 工作副本;
                let 名称 = 条目.显示名.clone();
                self.撤销.推入已应用(条目);
                self.选择.清理失效项(&self.会话.文档);
                self.标记文档已变更();
                self.信息(format!("已重做：{名称}"));
                true
            }
            Err(错误) => {
                self.错误(format!("重做失败，历史已回退：{错误}"));
                self.撤销.推入重做(条目);
                false
            }
        }
    }

    // ------------------------------------------------------------------
    // 便捷编辑操作（都走 执行，因此自动获得撤销能力）
    // ------------------------------------------------------------------

    /// 在指定父实体下新建一个实体，并选中它。
    pub fn 新建实体(
        &mut self,
        名称: impl Into<String>,
        父实体: Option<实体标识>,
    ) -> Option<实体标识> {
        // 必须用 `执行并选中` 而不是 `执行并记录`：
        // 后者只执行不选中，新建出来的实体会立刻失去选中状态，
        // 用户点"添加节点"之后看不到 Inspector 有任何反应。
        let 结果 = self
            .执行并选中(编辑器命令::新建实体 {
                名称: 名称.into(),
                父实体,
                指定标识: None,
            })
            .map_err(|错误| {
                self.错误(format!("新建实体失败：{错误}"));
                错误
            })
            .ok()?;
        结果.新实体
    }

