    /// 新建一个空场景，丢弃当前场景（调用方应先确认未保存修改）。
    pub fn 新建场景(&mut self, 名称: impl Into<String>) {
        let 名称 = 名称.into();
        self.会话 = 场景会话::新建(名称.clone());
        self.选择.清空();
        self.撤销.清空();
        self.标记文档已变更();
        self.结构化信息("log_scene_created", vec![日志参数::用户数据(名称.clone())]);
    }

    /// 打开项目中的一个场景。
    pub fn 打开场景(&mut self, 路径: &项目相对路径) -> 场景结果<()> {
        let Some(项目) = self.项目.as_ref() else {
            return Err(场景错误::非法("尚未打开项目，无法打开场景文件"));
        };

        let 读取结果: 读取结果 = 项目.读取场景(路径)?;
        let 校验 = 读取结果.文档.校验();
        let mut 文档 = 读取结果.文档;

        // 路径失效时按 UID 找回：用户可能在文件管理器里移动过资源。
        //
        // 这一步发生在"装进编辑器"之前，因此不产生撤销记录 ——
        // 用户看到的已经是修好的场景。改过的文档会被标记为未保存，
        // 提示用户保存，而不是悄悄在内存里改完、下次打开又坏掉。
        let 修复 = 项目.按标识修复文档(&mut 文档);

        self.应用已载入场景(文档, Some(路径.clone()));

        if !修复.已修复.is_empty() {
            let 摘要 = 修复
                .已修复
                .iter()
                .map(|(旧, 新)| format!("{} → {}", 旧.文本(), 新.文本()))
                .collect::<Vec<_>>()
                .join("；");
            self.警告(format!(
                "有 {} 处资源引用按 UID 重连（文件已被移动）：{摘要}。请保存场景以固定结果。",
                修复.已修复.len()
            ));
            self.标记文档已变更();
            // 修复不在撤销栈里，必须显式置脏，否则用户会以为"打开就是已保存"，
            // 关掉之后修复结果直接丢失。
            self.撤销.强制标记未保存();
        }
        for 路径 in &修复.无标识缺失 {
            self.警告(format!(
                "资源 {} 不存在，且场景里没有记录它的 UID，无法自动找回",
                路径.文本()
            ));
        }
        for 路径 in &修复.冲突 {
            self.警告(format!(
                "资源 {} 的 UID 在标识表里对应多个路径，已跳过自动修复（需要人工确认）",
                路径.文本()
            ));
        }
        for 路径 in &修复.无法找回 {
            self.警告(format!(
                "资源 {} 不存在，标识表里也找不到它的当前位置",
                路径.文本()
            ));
        }

        // 从备份恢复是重要事件，必须让用户知道。
        if 读取结果.从备份恢复 {
            self.警告(format!(
                "场景 {} 的主文件无法解析，已从 {} 恢复内容。请检查后再保存。",
                路径.文本(),
                读取结果.来源路径.display()
            ));
        } else {
            self.结构化信息(
                "log_scene_opened",
                vec![日志参数::用户数据(路径.文本().to_string())],
            );
        }

        if !校验.无问题() {
            self.警告(format!("场景校验发现问题：{}", 校验.摘要()));
        }
        if !校验.悬空父实体.is_empty() {
            self.警告(format!(
                "有 {} 个实体的父实体不存在，已在场景树中作为顶层显示",
                校验.悬空父实体.len()
            ));
        }
        if !校验.未注册组件.is_empty() {
            let 名字: Vec<&str> = 校验
                .未注册组件
                .iter()
                .map(|(_, 类型名)| 类型名.as_str())
                .collect();
            self.警告(format!(
                "场景包含 {} 处未注册组件（{}）。它们会原样保留在文件中，但暂时无法在 Inspector 中编辑。",
                校验.未注册组件.len(),
                名字.join("、")
            ));
        }
        Ok(())
    }

    /// 把一份已解析的文档装进编辑器，重置选择与历史。
    pub fn 应用已载入场景(
        &mut self, 文档: 场景文档, 路径: Option<项目相对路径>
    ) {
        self.会话 = 场景会话 { 文档, 路径 };
        self.选择.清空();
        self.撤销.清空();
        self.标记文档已变更();
    }

    /// 保存当前场景到指定路径。成功后会标记保存点。
    pub fn 保存场景到(&mut self, 路径: &项目相对路径) -> 场景结果<()> {
        let Some(项目) = self.项目.as_mut() else {
            return Err(场景错误::非法("尚未打开项目，无法保存场景文件"));
        };

        // 保存前同步资源表，保证文件里的引用登记完整。
        self.会话.文档.同步资源表();
        self.会话.文档.元数据.保存时间 = Some(当前时间秒());

        // 首次把未命名场景存到某个路径时，用文件名作为场景名。
        //
        // 没有这一步会出现一个很别扭的现象：新建项目自动创建的"主场景"
        // 存成 `scenes/关卡.scene.ron` 之后，重新打开项目却显示名叫"主场景"，
        // 因为它其实一直没有名字，只是沿用了新建时的占位名。
        // 用户自定义过的名字不会被覆盖。
        if is_占位场景名(&self.会话.文档.元数据.场景名)
            && let Some(基准名) = 场景基准名(路径)
        {
            self.会话.文档.元数据.场景名 = 基准名;
        }

        // 把 UID 写进场景（表 → 文档），同时把文档里已有的 UID 补进表
        // （文档 → 表）。这一步必须在写文件之前：写出去的场景就是
        // "以后能按 UID 找回引用"的那一份。
        let 补入 = 项目.对齐文档标识(&mut self.会话.文档);
        let 标识错误 = if 补入 > 0 {
            项目.保存资源标识().err().map(|错误| 错误.to_string())
        } else {
            None
        };

        // 保存成功之后才改路径 —— 失败时不应让编辑器"以为"已经关联了文件。
        项目.保存场景(路径, &self.会话.文档)?;
        self.会话.路径 = Some(路径.clone());
        // 标识表写不进去不是"保存场景"失败的理由：场景本身仍然有效。
        // 但必须让用户知道，否则下次外部移动资源就找不回来了。
        if let Some(错误) = 标识错误 {
            self.警告(format!("资源标识表保存失败（场景已保存）：{错误}"));
        }
        self.撤销.标记已保存();
        self.结构化信息(
            "log_scene_saved",
            vec![日志参数::用户数据(路径.文本().to_string())],
        );
        Ok(())
    }

    /// 保存当前场景到它已关联的路径。
    pub fn 保存场景(&mut self) -> 场景结果<()> {
        let Some(路径) = self.会话.路径.clone() else {
            return Err(场景错误::非法("当前场景尚未保存过，请先指定保存路径"));
        };
        self.保存场景到(&路径)
    }

    /// 是否有未保存修改。
    pub fn 有未保存修改(&self) -> bool {
        self.撤销.有未保存修改()
    }

