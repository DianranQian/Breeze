//! 编辑器状态：把文档、项目、选择集与撤销栈组合成可被 UI 驱动的一体。
//!
//! # 事务边界在哪里
//!
//! 所有对文档的修改都必须经过 [`编辑器状态::执行`]。这个方法做四件事，
//! 且顺序不可交换：
//!
//! 1. **克隆**当前文档；
//! 2. 在克隆上 [`编辑器命令::应用`]；
//! 3. 失败则整体放弃，正本一字未动；
//! 4. 成功才提交回正本，并记录撤销条目。
//!
//! "在克隆上执行"是这套设计能同时满足"命令可以部分执行后失败"和
//! "失败不留痕迹"的关键。代价是每次编辑都要克隆一次文档 —— 对
//! 常见规模（数百到数千实体）这是微秒到毫秒级，可以接受；
//! 真正的性能红线是**不能每次改属性都重新序列化整个项目**，
//! 而克隆与序列化是两件事（见 [`crate::undo`] 的字节估算注释）。

use std::path::PathBuf;
use std::sync::Arc;

use scene_doc::document::{场景文档, 实体标识, 组件数据};
use scene_doc::error::{场景错误, 场景结果};
use scene_doc::path::项目相对路径;
use scene_doc::property::属性值;
use scene_doc::registry::组件注册表;
use scene_doc::storage::读取结果;

use crate::command::{命令结果, 编辑器命令};
use crate::project::{项目描述, 项目结果};
use crate::selection::选择集;
use crate::undo::撤销栈;

/// 编辑器的一次操作日志条目。用于底部控制台面板。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 日志条目 {
    /// 严重程度。
    pub 级别: 日志级别,
    /// 消息正文。
    pub 消息: String,
}

/// 日志级别。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum 日志级别 {
    /// 普通信息。
    信息,
    /// 警告。
    警告,
    /// 错误。
    错误,
}

impl 日志级别 {
    /// 用于显示的前缀。
    pub fn 前缀(&self) -> &'static str {
        match self {
            日志级别::信息 => "[信息]",
            日志级别::警告 => "[警告]",
            日志级别::错误 => "[错误]",
        }
    }
}

/// 当前场景的文档状态。
#[derive(Debug, Clone)]
pub struct 场景会话 {
    /// 场景文档。权威数据。
    pub 文档: 场景文档,
    /// 场景在项目中的路径。`None` 表示尚未保存过（未命名场景）。
    pub 路径: Option<项目相对路径>,
}

impl 场景会话 {
    /// 创建一个未命名的新场景。
    pub fn 新建(名称: impl Into<String>) -> Self {
        Self {
            文档: 场景文档::新建(名称),
            路径: None,
        }
    }
}

/// 编辑器全局状态。
#[derive(Debug)]
pub struct 编辑器状态 {
    /// 已打开的项目。`None` 表示尚未打开项目（此时仍可编辑临时场景）。
    pub 项目: Option<项目描述>,
    /// 当前场景会话。
    pub 会话: 场景会话,
    /// 当前选择。
    pub 选择: 选择集,
    /// 撤销栈。
    pub 撤销: 撤销栈,
    /// 组件注册表。
    pub 注册表: 组件注册表,
    /// 控制台日志。
    日志: Vec<日志条目>,
    /// 日志上限，超出后丢弃最旧的。
    日志上限: usize,
}

impl Default for 编辑器状态 {
    fn default() -> Self {
        Self::新建()
    }
}

impl 编辑器状态 {
    /// 创建一个只加载了内置组件、未打开任何项目的编辑器状态。
    pub fn 新建() -> Self {
        Self {
            项目: None,
            会话: 场景会话::新建("未命名场景"),
            选择: 选择集::新建(),
            撤销: 撤销栈::新建(),
            注册表: 组件注册表::新建(),
            日志: Vec::new(),
            日志上限: 2000,
        }
    }

    // ------------------------------------------------------------------
    // 日志
    // ------------------------------------------------------------------

    /// 追加一条日志。
    pub fn 记日志(&mut self, 级别: 日志级别, 消息: impl Into<String>) {
        self.日志.push(日志条目 {
            级别,
            消息: 消息.into(),
        });
        if self.日志.len() > self.日志上限 {
            let 超出 = self.日志.len() - self.日志上限;
            self.日志.drain(0..超出);
        }
    }

    /// 记录一条信息。
    pub fn 信息(&mut self, 消息: impl Into<String>) {
        self.记日志(日志级别::信息, 消息);
    }

    /// 记录一条警告。
    pub fn 警告(&mut self, 消息: impl Into<String>) {
        self.记日志(日志级别::警告, 消息);
    }

    /// 记录一条错误。
    pub fn 错误(&mut self, 消息: impl Into<String>) {
        self.记日志(日志级别::错误, 消息);
    }

    /// 所有日志。
    pub fn 日志列表(&self) -> &[日志条目] {
        &self.日志
    }

    /// 清空日志。
    pub fn 清空日志(&mut self) {
        self.日志.clear();
    }

    /// 错误与警告数量（用于控制台标签页上的角标）。
    pub fn 问题数量(&self) -> usize {
        self.日志
            .iter()
            .filter(|条目| 条目.级别 >= 日志级别::警告)
            .count()
    }

    // ------------------------------------------------------------------
    // 项目
    // ------------------------------------------------------------------

    /// 创建并打开一个项目。
    pub fn 创建项目(
        &mut self,
        根目录: impl AsRef<std::path::Path>,
        名称: impl Into<String>,
    ) -> 项目结果<()> {
        let 名称 = 名称.into();
        let 项目 = 项目描述::创建(根目录, 名称.clone())?;
        self.信息(format!("已创建项目 `{名称}` 于 {}", 项目.根目录().display()));
        self.项目 = Some(项目);
        // 新项目配一个新的空场景，避免把上一个项目的场景带过来。
        self.新建场景("主场景");
        Ok(())
    }

    /// 打开一个已有项目。
    pub fn 打开项目(&mut self, 根目录: impl AsRef<std::path::Path>) -> 项目结果<()> {
        let 项目 = 项目描述::打开(根目录)?;
        let 名称 = 项目.名称().to_string();
        let 场景数 = 项目.场景列表().len();
        let 资源数 = 项目.资源列表().len();
        self.项目 = Some(项目);
        self.信息(format!(
            "已打开项目 `{名称}`：{场景数} 个场景，{资源数} 个资源"
        ));
        // 打开项目后自动载入启动场景（若有），否则载入场景目录里的第一个。
        let 待载 = self
            .项目
            .as_ref()
            .and_then(|项目| 项目.清单().启动场景.clone())
            .or_else(|| {
                self.项目
                    .as_ref()
                    .and_then(|项目| 项目.场景列表().into_iter().next())
            });
        if let Some(路径) = 待载 {
            let _ = self.打开场景(&路径);
        } else {
            self.新建场景("主场景");
        }
        Ok(())
    }

    /// 关闭当前项目。未保存的修改会被记录为警告，但不会阻止关闭 ——
    /// 是否保存应由调用方（UI）先询问用户。
    pub fn 关闭项目(&mut self) {
        if self.有未保存修改() {
            self.警告("关闭项目时有未保存的场景修改，这些修改已丢弃");
        }
        self.项目 = None;
        self.新建场景("未命名场景");
    }

    /// 项目名（未打开项目时返回占位名）。
    pub fn 项目名(&self) -> &str {
        self.项目
            .as_ref()
            .map_or("（未打开项目）", |项目| 项目.名称())
    }

    /// 当前场景的显示名。
    pub fn 场景名(&self) -> &str {
        &self.会话.文档.元数据.场景名
    }

    /// 当前场景是否已关联到一个文件。
    pub fn 场景已保存到磁盘(&self) -> bool {
        self.会话.路径.is_some()
    }

    /// 当前场景文件的绝对路径（若已关联）。
    pub fn 场景绝对路径(&self) -> Option<PathBuf> {
        let 相对 = self.会话.路径.as_ref()?;
        let 项目 = self.项目.as_ref()?;
        Some(项目.绝对路径(相对))
    }

    // ------------------------------------------------------------------
    // 场景生命周期
    // ------------------------------------------------------------------

    /// 新建一个空场景，丢弃当前场景（调用方应先确认未保存修改）。
    pub fn 新建场景(&mut self, 名称: impl Into<String>) {
        let 名称 = 名称.into();
        self.会话 = 场景会话::新建(名称.clone());
        self.选择.清空();
        self.撤销.清空();
        self.信息(format!("已新建场景 `{名称}`"));
    }

    /// 打开项目中的一个场景。
    pub fn 打开场景(&mut self, 路径: &项目相对路径) -> 场景结果<()> {
        let Some(项目) = self.项目.as_ref() else {
            return Err(场景错误::非法("尚未打开项目，无法打开场景文件"));
        };

        let 读取结果: 读取结果 = 项目.读取场景(路径)?;
        let 校验 = 读取结果.文档.校验();

        self.应用已载入场景(读取结果.文档, Some(路径.clone()));

        // 从备份恢复是重要事件，必须让用户知道。
        if 读取结果.从备份恢复 {
            self.警告(format!(
                "场景 {} 的主文件无法解析，已从 {} 恢复内容。请检查后再保存。",
                路径.文本(),
                读取结果.来源路径.display()
            ));
        } else {
            self.信息(format!("已打开场景 {}", 路径.文本()));
        }

        if !校验.无问题() {
            self.警告(format!("场景校验发现问题：{}", 校验.摘要()));
        }
        if 校验.悬空父实体.len() > 0 {
            self.警告(format!(
                "有 {} 个实体的父实体不存在，已在场景树中作为顶层显示",
                校验.悬空父实体.len()
            ));
        }
        if !校验.未注册组件.is_empty() {
            let 名字: Vec<&str> = 校验
                .未注册组件
                .iter()
                .map(|(_, 类型名)| 类型名.as_str())
                .collect();
            self.警告(format!(
                "场景包含 {} 处未注册组件（{}）。它们会原样保留在文件中，但暂时无法在 Inspector 中编辑。",
                校验.未注册组件.len(),
                名字.join("、")
            ));
        }
        Ok(())
    }

    /// 把一份已解析的文档装进编辑器，重置选择与历史。
    pub fn 应用已载入场景(&mut self, 文档: 场景文档, 路径: Option<项目相对路径>) {
        self.会话 = 场景会话 { 文档, 路径 };
        self.选择.清空();
        self.撤销.清空();
    }

    /// 保存当前场景到指定路径。成功后会标记保存点。
    pub fn 保存场景到(&mut self, 路径: &项目相对路径) -> 场景结果<()> {
        let Some(项目) = self.项目.as_ref() else {
            return Err(场景错误::非法("尚未打开项目，无法保存场景文件"));
        };

        // 保存前同步资源表，保证文件里的引用登记完整。
        self.会话.文档.同步资源表();
        self.会话.文档.元数据.保存时间 = Some(当前时间秒());

        // 首次把未命名场景存到某个路径时，用文件名作为场景名。
        //
        // 没有这一步会出现一个很别扭的现象：新建项目自动创建的"主场景"
        // 存成 `scenes/关卡.scene.ron` 之后，重新打开项目却显示名叫"主场景"，
        // 因为它其实一直没有名字，只是沿用了新建时的占位名。
        // 用户自定义过的名字不会被覆盖。
        if is_占位场景名(&self.会话.文档.元数据.场景名) {
            if let Some(基准名) = 场景基准名(路径) {
                self.会话.文档.元数据.场景名 = 基准名;
            }
        }

        // 保存成功之后才改路径 —— 失败时不应让编辑器"以为"已经关联了文件。
        项目.保存场景(路径, &self.会话.文档)?;
        self.会话.路径 = Some(路径.clone());
        self.撤销.标记已保存();
        self.信息(format!("已保存场景 {}", 路径.文本()));
        Ok(())
    }

    /// 保存当前场景到它已关联的路径。
    pub fn 保存场景(&mut self) -> 场景结果<()> {
        let Some(路径) = self.会话.路径.clone() else {
            return Err(场景错误::非法("当前场景尚未保存过，请先指定保存路径"));
        };
        self.保存场景到(&路径)
    }

    /// 是否有未保存修改。
    pub fn 有未保存修改(&self) -> bool {
        self.撤销.有未保存修改()
    }

    // ------------------------------------------------------------------
    // 命令执行
    // ------------------------------------------------------------------

    /// 执行一条命令。这是**唯一**允许修改文档的入口。
    pub fn 执行(&mut self, 命令: 编辑器命令) -> 场景结果<命令结果> {
        let 执行前 = Arc::new(self.会话.文档.clone());

        // 在克隆上执行 —— 失败时正本未被触碰。
        let mut 工作副本 = self.会话.文档.clone();
        let 结果 = 命令.应用(&mut 工作副本)?;

        // 成功：提交回正本并记录撤销条目。
        self.会话.文档 = 工作副本;
        self.撤销
            .提交(命令, 执行前, 结果.新实体);

        // 选择集必须跟着文档走，否则删除后会出现"幽灵选中"。
        self.选择.清理失效项(&self.会话.文档);

        Ok(结果)
    }

    /// 执行命令并把结果里的实体设为当前选择（UI 新建实体时的常见需求）。
    pub fn 执行并选中(&mut self, 命令: 编辑器命令) -> 场景结果<命令结果> {
        let 结果 = self.执行(命令)?;
        if let Some(标识) = 结果.新实体 {
            self.选择.单选(标识);
        }
        Ok(结果)
    }

    /// 执行命令，失败时把错误记入控制台而不是向上传播。
    ///
    /// 供 UI 事件处理使用：UI 里每个按钮都写一遍错误处理既啰嗦又容易漏。
    pub fn 执行并记录(&mut self, 命令: 编辑器命令) -> Option<命令结果> {
        match self.执行(命令) {
            Ok(结果) => Some(结果),
            Err(错误) => {
                self.错误(format!("操作失败：{错误}"));
                None
            }
        }
    }

    // ------------------------------------------------------------------
    // 撤销 / 重做
    // ------------------------------------------------------------------

    /// 撤销一步。返回是否真的撤销了什么。
    pub fn 撤销一步(&mut self) -> bool {
        let Some(条目) = self.撤销.弹出撤销() else {
            self.信息("没有可撤销的操作");
            return false;
        };

        // 用命令执行前的快照覆盖当前文档。
        self.会话.文档.覆盖为(&条目.执行前);
        let 名称 = 条目.显示名.clone();
        self.撤销.推入重做(条目);
        self.选择.清理失效项(&self.会话.文档);
        self.信息(format!("已撤销：{名称}"));
        true
    }

    /// 重做一步。返回是否真的重做了什么。
    pub fn 重做一步(&mut self) -> bool {
        let Some(条目) = self.撤销.弹出重做() else {
            self.信息("没有可重做的操作");
            return false;
        };

        // 在克隆上重放命令，失败则把条目放回去，避免历史与文档脱节。
        //
        // 必须用 `重做命令` 而不是原始命令：原始 `新建实体` 命令的
        // `指定标识` 是 `None`，直接重放会生成一个新的 UUID，
        // 导致"重做后实体标识变了"这种极难排查的问题。
        let 重放命令 = 条目.重做用命令();
        let mut 工作副本 = self.会话.文档.clone();
        match 重放命令.应用(&mut 工作副本) {
            Ok(_) => {
                self.会话.文档 = 工作副本;
                let 名称 = 条目.显示名.clone();
                self.撤销.推入已应用(条目);
                self.选择.清理失效项(&self.会话.文档);
                self.信息(format!("已重做：{名称}"));
                true
            }
            Err(错误) => {
                self.错误(format!("重做失败，历史已回退：{错误}"));
                self.撤销.推入重做(条目);
                false
            }
        }
    }

    // ------------------------------------------------------------------
    // 便捷编辑操作（都走 执行，因此自动获得撤销能力）
    // ------------------------------------------------------------------

    /// 在指定父实体下新建一个实体，并选中它。
    pub fn 新建实体(
        &mut self,
        名称: impl Into<String>,
        父实体: Option<实体标识>,
    ) -> Option<实体标识> {
        // 必须用 `执行并选中` 而不是 `执行并记录`：
        // 后者只执行不选中，新建出来的实体会立刻失去选中状态，
        // 用户点"添加节点"之后看不到 Inspector 有任何反应。
        let 结果 = self
            .执行并选中(编辑器命令::新建实体 {
                名称: 名称.into(),
                父实体,
                指定标识: None,
            })
            .map_err(|错误| {
                self.错误(format!("新建实体失败：{错误}"));
                错误
            })
            .ok()?;
        结果.新实体
    }

    /// 删除一个实体及其子树。
    pub fn 删除实体(&mut self, 标识: 实体标识) -> bool {
        self.执行并记录(编辑器命令::删除实体 { 标识 })
            .is_some()
    }

    /// 重命名实体。
    pub fn 重命名实体(&mut self, 标识: 实体标识, 新名称: impl Into<String>) -> bool {
        self.执行并记录(编辑器命令::重命名实体 {
            标识,
            新名称: 新名称.into(),
        })
        .is_some()
    }

    /// 修改组件的一个属性。
    pub fn 设属性(
        &mut self,
        标识: 实体标识,
        类型名: impl Into<String>,
        属性名: impl Into<String>,
        新值: 属性值,
    ) -> bool {
        self.执行并记录(编辑器命令::设组件属性 {
            标识,
            类型名: 类型名.into(),
            属性名: 属性名.into(),
            新值,
        })
        .is_some()
    }

    /// 添加组件。
    pub fn 添加组件(&mut self, 标识: 实体标识, 组件: 组件数据) -> bool {
        self.执行并记录(编辑器命令::添加组件 { 标识, 组件 })
            .is_some()
    }

    /// 删除组件。
    pub fn 删除组件(&mut self, 标识: 实体标识, 类型名: impl Into<String>) -> bool {
        self.执行并记录(编辑器命令::删除组件 {
            标识,
            类型名: 类型名.into(),
        })
        .is_some()
    }
}

/// 判断场景名是否只是"新建时的占位名"，从而允许在首次保存时被文件名替换。
///
/// 只认明确列出的占位名，不做模糊匹配：用户真的把场景命名为"主场景"
/// 是完全合理的，不能被静默改掉。
fn is_占位场景名(名称: &str) -> bool {
    matches!(名称, "未命名场景" | "主场景")
}

/// 从 `scenes/关卡.scene.ron` 这样的路径里取出 `关卡` 作为场景基准名。
///
/// 只剥掉末尾连续的已知扩展名，而不是"取最后一个点之前的部分" ——
/// 后者会把 `关卡.v2.scene.ron` 变成 `关卡`，丢掉用户刻意写进名字里的版本号。
fn 场景基准名(路径: &项目相对路径) -> Option<String> {
    let mut 名字 = 路径.文件名();
    for 已知扩展 in [".scene.ron", ".scn.ron", ".ron", ".scene", ".scn"] {
        if let Some(剩余) = 名字.strip_suffix(已知扩展) {
            名字 = 剩余;
            break;
        }
    }
    let 名字 = 名字.trim();
    if 名字.is_empty() {
        None
    } else {
        Some(名字.to_string())
    }
}

/// 取当前 Unix 时间戳（秒）。取不到时返回 `None`，
/// 而不是把 0 当作"1970 年保存"写进文件。
fn 当前时间秒() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|时长| 时长.as_secs())
        .unwrap_or(0)
}
