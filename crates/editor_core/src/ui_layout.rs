//! 界面布局：把"锚点 + 偏移 + 尺寸"换算成视口里的像素矩形。
//!
//! # 为什么要锚点（而不是继续用绝对坐标）
//!
//! 绝对像素坐标在**一种**分辨率下是对的。游戏一旦换分辨率或窗口缩放，
//! "右下角的按钮"就会跑到中间去。Godot 的 `Control` 用 anchor（0..1 相对
//! 父容器）+ offset（像素微调）解决这件事：锚点决定"贴在容器的哪条边上"，
//! 偏移决定"离那条边多远"。
//!
//! 微风先取 Godot 预设锚点里最常用的五个，而不是完整的九宫格自由锚点：
//! 预设覆盖了绝大多数需求，且界面上是一个下拉而不是四个小的 0..1 输入框
//! （后者容易摆出一个"既贴左又贴右"的无意义组合）。
//!
//! | 预设 | 语义 | Godot 对应 |
//! | --- | --- | --- |
//! | 左上 | 距左上角固定偏移 | `PRESET_TOP_LEFT` |
//! | 顶部居中 | 水平居中、贴顶 | `PRESET_CENTER_TOP` |
//! | 居中 | 正中 | `PRESET_CENTER` |
//! | 右下 | 距右下角固定偏移 | `PRESET_BOTTOM_RIGHT` |
//! | 拉伸 | 铺满视口，四边各留偏移 | `PRESET_FULL_RECT` |
//!
//! # 为什么是纯函数
//!
//! 换算只依赖"盒子 + 视口尺寸"，没有任何渲染状态。抽成纯函数后，
//! 每个预设都能用几个数字断言清楚——这类"差一个半宽"的 bug 靠看截图
//! 极难发现，靠测试是一行事。

use serde::{Deserialize, Serialize};

/// 预设锚点。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum 界面锚点 {
    /// 贴左上角：偏移是左上角到视口左上角的距离。
    #[default]
    左上,
    /// 顶部居中：水平居中，垂直贴顶。
    顶部居中,
    /// 正中：以视口中心为参考点。
    居中,
    /// 右下角：偏移是右下角到视口右下角的距离。
    右下,
    /// 铺满视口：四边各留一点偏移。
    拉伸,
}

impl 界面锚点 {
    /// 全部预设（顺序即下拉顺序）。
    pub const 全部: [界面锚点; 5] = [
        界面锚点::左上,
        界面锚点::顶部居中,
        界面锚点::居中,
        界面锚点::右下,
        界面锚点::拉伸,
    ];

    /// 场景文件里使用的变体名（英文，向运行时看齐）。
    pub fn 变体名(&self) -> &'static str {
        match self {
            界面锚点::左上 => "TopLeft",
            界面锚点::顶部居中 => "TopCenter",
            界面锚点::居中 => "Center",
            界面锚点::右下 => "BottomRight",
            界面锚点::拉伸 => "Stretch",
        }
    }

    /// 下拉序号。
    pub fn 序号(&self) -> u32 {
        match self {
            界面锚点::左上 => 0,
            界面锚点::顶部居中 => 1,
            界面锚点::居中 => 2,
            界面锚点::右下 => 3,
            界面锚点::拉伸 => 4,
        }
    }

    /// 由变体名与序号还原；未知名字按序号兜底，保证旧文件仍可用。
    pub fn 由值(变体名: &str, 序号: u32) -> Self {
        match 变体名 {
            "TopLeft" | "左上" => 界面锚点::左上,
            "TopCenter" | "顶部居中" => 界面锚点::顶部居中,
            "Center" | "居中" => 界面锚点::居中,
            "BottomRight" | "右下" => 界面锚点::右下,
            "Stretch" | "拉伸" => 界面锚点::拉伸,
            _ => match 序号 {
                1 => 界面锚点::顶部居中,
                2 => 界面锚点::居中,
                3 => 界面锚点::右下,
                4 => 界面锚点::拉伸,
                _ => 界面锚点::左上,
            },
        }
    }

    /// 词条键（显示名）。
    pub fn 词条键(&self) -> &'static str {
        match self {
            // 词条表里已有这些界面方向词。
            界面锚点::左上 => "anchor_top_left",
            界面锚点::顶部居中 => "anchor_top_center",
            界面锚点::居中 => "anchor_center",
            界面锚点::右下 => "anchor_bottom_right",
            界面锚点::拉伸 => "anchor_stretch",
        }
    }
}

/// 一个界面盒子的布局参数（与组件字段一一对应）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 界面盒 {
    /// 锚点预设。
    pub 锚点: 界面锚点,
    /// 水平偏移（像素）。
    pub 偏移x: f32,
    /// 垂直偏移（像素）。
    pub 偏移y: f32,
    /// 宽度（像素；拉伸时忽略）。
    pub 宽: f32,
    /// 高度（像素；拉伸时忽略）。
    pub 高: f32,
}

impl Default for 界面盒 {
    fn default() -> Self {
        Self {
            锚点: 界面锚点::左上,
            偏移x: 40.0,
            偏移y: 40.0,
            宽: 320.0,
            高: 180.0,
        }
    }
}

/// 换算后的像素矩形（左上角 + 宽高）。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 像素矩形 {
    /// 左边界。
    pub 左: f32,
    /// 上边界。
    pub 上: f32,
    /// 宽。
    pub 宽: f32,
    /// 高。
    pub 高: f32,
}

/// 把界面盒换算成像素矩形。
///
/// * `左上`：偏移就是左上角位置；
/// * `顶部居中`：水平居中，`偏移x` 是相对中心的微调；
/// * `居中`：中心对齐，偏移相对中心；
/// * `右下`：`偏移x/偏移y` 是**距右边/下边**的距离（正数向内），
///   这样"贴右下角 20 像素"就写 20，而不是写一个负数；
/// * `拉伸`：宽高等于视口减去两侧偏移。
pub fn 计算像素矩形(盒: 界面盒, 视口宽: f32, 视口高: f32) -> 像素矩形 {
    let 宽 = 盒.宽.max(0.0);
    let 高 = 盒.高.max(0.0);
    match 盒.锚点 {
        界面锚点::左上 => 像素矩形 {
            左: 盒.偏移x,
            上: 盒.偏移y,
            宽,
            高,
        },
        界面锚点::顶部居中 => 像素矩形 {
            左: (视口宽 - 宽) * 0.5 + 盒.偏移x,
            上: 盒.偏移y,
            宽,
            高,
        },
        界面锚点::居中 => 像素矩形 {
            左: (视口宽 - 宽) * 0.5 + 盒.偏移x,
            上: (视口高 - 高) * 0.5 + 盒.偏移y,
            宽,
            高,
        },
        界面锚点::右下 => 像素矩形 {
            左: 视口宽 - 宽 - 盒.偏移x,
            上: 视口高 - 高 - 盒.偏移y,
            宽,
            高,
        },
        界面锚点::拉伸 => 像素矩形 {
            左: 盒.偏移x,
            上: 盒.偏移y,
            // 两侧都留偏移：贴边时偏移为 0。
            宽: (视口宽 - 盒.偏移x * 2.0).max(0.0),
            高: (视口高 - 盒.偏移y * 2.0).max(0.0),
        },
    }
}

/// 设计分辨率到目标尺寸的适配结果。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 适配缩放 {
    /// 等比缩放系数。
    pub 缩放: f32,
    /// 水平留边（居中用的偏移）。
    pub 偏移x: f32,
    /// 垂直留边。
    pub 偏移y: f32,
}

/// 把设计分辨率按"等比铺满目标区域"算成缩放与留边（letterbox）。
///
/// # 为什么用 `min` 而不是 `max`
///
/// `min` 保证整个设计画面都在目标区域内（可能留边），`max` 会裁掉一部分。
/// 界面编辑里"看不到右下角的按钮"比"两侧有黑边"糟糕得多，因此取 `min`，
/// 并把剩余空间平均分到两侧（居中）。
pub fn 适配缩放(
    设计宽: f32, 设计高: f32, 目标宽: f32, 目标高: f32
) -> 适配缩放 {
    // 设计尺寸为 0 时没有可用比例：退回 1.0，让调用方至少画出东西。
    if 设计宽 <= 0.0 || 设计高 <= 0.0 {
        return 适配缩放 {
            缩放: 1.0,
            偏移x: 0.0,
            偏移y: 0.0,
        };
    }
    let 缩放 = (目标宽 / 设计宽).min(目标高 / 设计高);
    let 缩放 = if 缩放.is_finite() && 缩放 > 0.0 {
        缩放
    } else {
        1.0
    };
    适配缩放 {
        缩放,
        偏移x: (目标宽 - 设计宽 * 缩放) * 0.5,
        偏移y: (目标高 - 设计高 * 缩放) * 0.5,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    fn 盒(锚点: 界面锚点, 偏移x: f32, 偏移y: f32, 宽: f32, 高: f32) -> 界面盒 {
        界面盒 {
            锚点,
            偏移x,
            偏移y,
            宽,
            高,
        }
    }

    #[test]
    fn 适配缩放等比并居中() {
        // 1920×1080 放进 512×512：按宽度算 512/1920≈0.2667，
        // 高度只剩 1080*0.2667≈288，上下各留 (512-288)/2=112。
        let 结果 = 适配缩放(1920.0, 1080.0, 512.0, 512.0);
        assert!((结果.缩放 - 512.0 / 1920.0).abs() < 1e-6);
        assert!((结果.偏移x - 0.0).abs() < 1e-3);
        assert!((结果.偏移y - (512.0 - 1080.0 * 结果.缩放) * 0.5).abs() < 1e-3);
        assert!(结果.偏移y > 0.0, "上下应当留边");
    }

    #[test]
    fn 适配缩放设计尺寸为零时退回原尺寸() {
        let 结果 = 适配缩放(0.0, 0.0, 512.0, 512.0);
        assert_eq!(结果.缩放, 1.0);
    }

    #[test]
    fn 适配缩放同尺寸不缩放() {
        let 结果 = 适配缩放(512.0, 512.0, 512.0, 512.0);
        assert_eq!(结果.缩放, 1.0);
        assert_eq!((结果.偏移x, 结果.偏移y), (0.0, 0.0));
    }

    #[test]
    fn 左上按偏移放置() {
        let 矩形 = 计算像素矩形(盒(界面锚点::左上, 10.0, 20.0, 100.0, 50.0), 800.0, 600.0);
        assert_eq!(
            矩形,
            像素矩形 {
                左: 10.0,
                上: 20.0,
                宽: 100.0,
                高: 50.0
            }
        );
    }

    #[test]
    fn 顶部居中水平居中() {
        let 矩形 = 计算像素矩形(盒(界面锚点::顶部居中, 0.0, 0.0, 200.0, 40.0), 800.0, 600.0);
        assert_eq!(矩形.左, 300.0, "800 宽视口放 200 宽的盒子应当左偏 300");
        assert_eq!(矩形.上, 0.0);
    }

    #[test]
    fn 居中落在正中间() {
        let 矩形 = 计算像素矩形(盒(界面锚点::居中, 0.0, 0.0, 200.0, 100.0), 800.0, 600.0);
        assert_eq!((矩形.左, 矩形.上), (300.0, 250.0));
        // 中心点必须等于视口中心。
        assert_eq!(矩形.左 + 矩形.宽 * 0.5, 400.0);
        assert_eq!(矩形.上 + 矩形.高 * 0.5, 300.0);
    }

    #[test]
    fn 右下按到边距离放置() {
        let 矩形 = 计算像素矩形(盒(界面锚点::右下, 20.0, 30.0, 100.0, 40.0), 800.0, 600.0);
        assert_eq!(矩形.左, 800.0 - 100.0 - 20.0);
        assert_eq!(矩形.上, 600.0 - 40.0 - 30.0);
        // 右边界距视口右边正好 20。
        assert_eq!(800.0 - (矩形.左 + 矩形.宽), 20.0);
    }

    #[test]
    fn 拉伸铺满并留偏移() {
        let 矩形 = 计算像素矩形(盒(界面锚点::拉伸, 8.0, 8.0, 0.0, 0.0), 800.0, 600.0);
        assert_eq!((矩形.左, 矩形.上), (8.0, 8.0));
        assert_eq!((矩形.宽, 矩形.高), (784.0, 584.0));
    }

    #[test]
    fn 拉伸时偏移过大不会产生负尺寸() {
        let 矩形 = 计算像素矩形(盒(界面锚点::拉伸, 500.0, 500.0, 0.0, 0.0), 800.0, 600.0);
        assert!(矩形.宽 >= 0.0 && 矩形.高 >= 0.0);
    }

    #[test]
    fn 锚点往返与未知兜底() {
        for 锚点 in 界面锚点::全部 {
            assert_eq!(
                界面锚点::由值(锚点.变体名(), 锚点.序号()),
                锚点,
                "{} 往返失败",
                锚点.变体名()
            );
        }
        assert_eq!(界面锚点::由值("没见过的名字", 0), 界面锚点::左上);
        assert_eq!(界面锚点::由值("没见过的名字", 3), 界面锚点::右下);
    }
}
