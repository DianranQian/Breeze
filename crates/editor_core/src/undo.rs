    /// 造一个"把元数据场景名从 `名称` 改成 `改过`"的差量，代表一次真实编辑。
    fn 差量(名称: &str) -> 文档差量 {
        let 前 = 场景文档::新建(名称);
        let 后 = 场景文档::新建("改过");
        文档差量::比较(&前, &后)
    }

    fn 命令(名称: &str) -> 编辑器命令 {
        编辑器命令::重命名实体 {
            标识: 实体标识::新建(),
            新名称: 名称.to_string(),
        }
    }

    #[test]
    fn 提交后可以撤销重做() {
        let mut 栈 = 撤销栈::新建();
        assert!(!栈.有未保存修改());

        栈.提交(命令("甲"), 差量("基线"), None);
        assert_eq!(栈.可撤销步数(), 1);
        assert_eq!(栈.可重做步数(), 0);
        assert_eq!(栈.下一次撤销名(语言::中文), Some("重命名实体"));
        // 保存点仍是 None，当前位置有标记，因此算"已修改"
        assert!(栈.有未保存修改());

        let 条目 = 栈.弹出撤销().unwrap();
        let mut 文档 = 场景文档::新建("改过");
        条目.差量.逆向应用(&mut 文档);
        assert_eq!(文档.元数据.场景名, "基线", "撤销必须把元数据还原");
        栈.推入重做(条目);
        assert_eq!(栈.可撤销步数(), 0);
        assert_eq!(栈.可重做步数(), 1);
        assert_eq!(栈.下一次重做名(语言::中文), Some("重命名实体"));

        let 条目 = 栈.弹出重做().unwrap();
        栈.推入已应用(条目);
        assert_eq!(栈.可撤销步数(), 1);
        assert_eq!(栈.可重做步数(), 0);
    }

    #[test]
    fn 保存点能让文档恢复干净状态() {
        let mut 栈 = 撤销栈::新建();
        栈.标记已保存();
        assert!(!栈.有未保存修改());

        栈.提交(命令("甲"), 差量("基线"), None);
        assert!(栈.有未保存修改(), "提交之后应当算已修改");

        栈.标记已保存();
        assert!(!栈.有未保存修改(), "在当前位置标记保存后应当算干净");

        栈.提交(命令("乙"), 差量("基线"), None);
        assert!(栈.有未保存修改());

        // 撤销回到保存点，必须重新变干净
        栈.弹出撤销().unwrap();
        assert!(
            !栈.有未保存修改(),
            "撤销回到保存点后应当算干净，实际保存点={:?} 当前位置={:?}",
            栈.保存点,
            栈.当前位置标记()
        );

        // 再撤销一步（越过保存点）应当又算已修改
        栈.弹出撤销().unwrap();
        assert!(栈.有未保存修改(), "越过保存点之后应当算已修改");
    }

