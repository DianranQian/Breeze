//! 撤销与重做。
//!
//! # 为什么用"全量快照 + 命令"而不是"反向操作"
//!
//! 主流做法是给每个操作写一个 `undo()`，把变更反过来做一遍。它省内存，
//! 但代价是**每条命令都必须有人正确写出反向语义**，而下面这些操作的反向
//! 语义都不显然：
//!
//! * 删除实体连同其整棵子树 —— 反向要按原次序、原父实体精确复原；
//! * 调整层级 —— 反向要复原新旧两侧的次序编号；
//! * 拆除组件 —— 反向要复原组件的完整属性表。
//!
//! 任何一处写错，表现就是"撤销之后场景悄悄坏掉"，而且很难定位。
//!
//! 本实现改为：每次提交前，把**变更前的整份文档**存进撤销条目。
//! 撤销 = 把当前文档换回那份快照；重做 = 把命令重新应用一遍。
//! 这样"正确性"只依赖两个已经很可靠的部分：
//! 文档的 `Clone`，以及命令的 `应用`（两者都有独立测试覆盖）。
//!
//! 代价是内存，因此引入**字节预算**：超过预算就从最旧的一端丢弃条目。
//! 丢弃只影响"能撤销多少步"，不会让撤销结果出错。
//!
//! # 保存点为什么用标记而不是下标
//!
//! "文档是否已保存"需要记录保存时的栈位置。用下标的话，一旦因为内存
//! 预算丢弃了最旧的条目，所有下标都会位移，保存点就会指向错误的条目，
//! 表现为"存过盘的文件仍显示未保存"或更糟的"没存盘却显示已保存"。
//! 每个条目携带一个只增不减的标记，比较标记即可，丢弃条目不影响它。

use std::sync::Arc;

use scene_doc::document::{场景文档, 实体标识};

use crate::command::编辑器命令;
use crate::i18n::语言;

/// 撤销栈的默认内存预算：64 MiB。
pub const 默认内存预算字节: usize = 64 * 1024 * 1024;

/// 撤销栈的默认最大步数。
pub const 默认最大步数: usize = 256;

/// 一个撤销条目。
#[derive(Debug, Clone)]
pub struct 撤销条目 {
    /// 该条目的唯一标记，用于保存点比较。
    pub 标记: u64,
    /// 用户可见的操作名。
    pub 显示名: String,
    /// 执行该命令**之前**的文档快照。
    pub 执行前: Arc<场景文档>,
    /// 被执行的命令本身。重做时重新应用它。
    pub 命令: 编辑器命令,
    /// 首次执行该命令时新生成的实体标识（若有）。
    ///
    /// # 为什么必须记录它
    ///
    /// `新建实体` 命令里的 `指定标识` 首次执行时是 `None`，实体的 UUID
    /// 由执行过程生成。如果重做时再执行一次原始命令，就会**又生成一个
    /// 不同的 UUID**，结果是"撤销再重做之后，实体还在但标识变了"。
    ///
    /// 这会静默破坏所有记录了标识的外部状态：选择集、剪贴板、资源引用、
    /// 以及用户脚本里按标识查找实体的代码。因为文档看起来"有那个实体"，
    /// 问题极难被发现。记录首次生成的标识，重做时才可能幂等。
    pub 新实体: Option<实体标识>,
}

impl 撤销条目 {
    /// 返回一条用于**重做**的命令。
    ///
    /// 与原始命令的唯一区别是把首次生成的实体标识填回去，
    /// 保证重做产生与首次执行完全相同的文档。
    pub fn 重做用命令(&self) -> 编辑器命令 {
        match (&self.命令, self.新实体) {
            (
                编辑器命令::新建实体 {
                    名称,
                    父实体,
                    指定标识: None,
                },
                Some(标识),
            ) => 编辑器命令::新建实体 {
                名称: 名称.clone(),
                父实体: *父实体,
                指定标识: Some(标识),
            },
            _ => self.命令.clone(),
        }
    }
}

/// 撤销栈。
#[derive(Debug)]
pub struct 撤销栈 {
    /// 已应用的条目，最后一个是最近一次操作。
    已应用: Vec<撤销条目>,
    /// 被撤销掉的条目，用于重做。最后一个是最近一次撤销。
    可重做: Vec<撤销条目>,
    /// 内存预算（字节）。
    内存预算: usize,
    /// 最大步数。
    最大步数: usize,
    /// 标记计数器，只增不减。
    下一标记: u64,
    /// 保存点标记。`None` 表示"从未保存过"，此时只有栈为空才算干净。
    保存点: Option<u64>,
}

impl Default for 撤销栈 {
    fn default() -> Self {
        Self::新建()
    }
}

impl 撤销栈 {
    /// 用默认预算创建。
    pub fn 新建() -> Self {
        Self::带预算(默认内存预算字节, 默认最大步数)
    }

    /// 用指定预算创建。
    pub fn 带预算(内存预算: usize, 最大步数: usize) -> Self {
        Self {
            已应用: Vec::new(),
            可重做: Vec::new(),
            内存预算,
            最大步数,
            下一标记: 1,
            保存点: None,
        }
    }

    /// 可撤销的步数。
    pub fn 可撤销步数(&self) -> usize {
        self.已应用.len()
    }

    /// 可重做的步数。
    pub fn 可重做步数(&self) -> usize {
        self.可重做.len()
    }

    /// 下一次撤销会做什么（用于菜单项文字），按给定语言取命令名。
    ///
    /// 名字由条目里保存的命令现算，而不是用提交时定下的那份文案 ——
    /// 否则用户在切换界面语言之后，历史里已有的条目仍是旧语言。
    pub fn 下一次撤销名(&self, 语言: 语言) -> Option<&'static str> {
        self.已应用.last().map(|条目| 条目.命令.显示名(语言))
    }

    /// 下一次重做会做什么，按给定语言取命令名。
    pub fn 下一次重做名(&self, 语言: 语言) -> Option<&'static str> {
        self.可重做.last().map(|条目| 条目.命令.显示名(语言))
    }

    /// 当前所处的条目标记。栈为空时为 `None`。
    pub fn 当前位置标记(&self) -> Option<u64> {
        self.已应用.last().map(|条目| 条目.标记)
    }

    /// 当前估算占用的字节数。
    pub fn 估算字节(&self) -> usize {
        self.已应用.iter().map(条目大小).sum::<usize>()
            + self.可重做.iter().map(条目大小).sum::<usize>()
    }

    /// 最近 `数量` 条已应用条目的显示名（最新的在最后）。
    ///
    /// 只服务诊断与自动验收：当撤销栈异常增长时，名称能直接指出
    /// "是哪一类命令在被反复记录"，比只看步数快得多。
    pub fn 最近条目名(&self, 数量: usize) -> Vec<String> {
        let 起点 = self.已应用.len().saturating_sub(数量);
        self.已应用[起点..]
            .iter()
            .map(|条目| 条目.显示名.clone())
            .collect()
    }

    /// 记录一次提交。
    ///
    /// `执行前` 必须是命令应用**之前**的文档快照，
    /// `新实体` 是命令执行结果里新生成的实体标识（若有）。
    pub fn 提交(
        &mut self, 命令: 编辑器命令, 执行前: Arc<场景文档>, 新实体: Option<实体标识>
    ) {
        let 标记 = self.下一标记;
        self.下一标记 += 1;

        // 新操作会让原有的重做分支失效 —— 这是编辑器的标准语义：
        // 撤销几步后又做了新的事，原来的"未来"就不存在了。
        self.可重做.clear();

        self.已应用.push(撤销条目 {
            标记,
            // 条目里留一份默认语言的文案，供调试与日志；
            // 界面显示走 `下一次撤销名(语言)`，那里按当前语言现算。
            显示名: 命令.显示名(语言::中文).to_string(),
            执行前,
            命令,
            新实体,
        });

        self.收缩到预算内();
    }

    /// 弹出可撤销的条目。
    ///
    /// 返回条目；调用方负责把 `执行前` 快照恢复进文档，
    /// 并把条目交还给 [`撤销栈::推入重做`]。
    pub fn 弹出撤销(&mut self) -> Option<撤销条目> {
        self.已应用.pop()
    }

    /// 把刚撤销的条目登记到重做栈。
    pub fn 推入重做(&mut self, 条目: 撤销条目) {
        self.可重做.push(条目);
    }

    /// 弹出可重做的条目。
    pub fn 弹出重做(&mut self) -> Option<撤销条目> {
        self.可重做.pop()
    }

    /// 把刚重做的条目放回已应用栈。
    pub fn 推入已应用(&mut self, 条目: 撤销条目) {
        self.已应用.push(条目);
    }

    /// 清空全部历史。打开新场景或新建场景时调用。
    pub fn 清空(&mut self) {
        self.已应用.clear();
        self.可重做.clear();
        self.保存点 = None;
    }

    /// 把当前位置标记为保存点。
    pub fn 标记已保存(&mut self) {
        self.保存点 = self.当前位置标记();
    }

    /// 文档相对保存点是否已被修改。
    pub fn 有未保存修改(&self) -> bool {
        self.保存点 != self.当前位置标记()
    }

    /// 丢弃最旧的条目，直到估算占用回到预算内。
    ///
    /// 至少保留一个条目：否则"刚做的操作立刻不可撤销"，
    /// 在超大场景下会变成很突兀的体验。
    fn 收缩到预算内(&mut self) {
        while self.已应用.len() > self.最大步数 && self.已应用.len() > 1 {
            self.已应用.remove(0);
        }
        while self.估算字节() > self.内存预算 && self.已应用.len() > 1 {
            self.已应用.remove(0);
        }
    }
}

/// 估算一个条目占用的字节数。
///
/// 刻意不调用序列化来"精确测量"：那会让每次提交都付出一次全量序列化的
/// 代价，正是需求里禁止的"每次修改都重新序列化整个项目"。
/// 这里的估算与真实占用同阶，对"该丢弃多少"这个决策已经足够。
fn 条目大小(条目: &撤销条目) -> usize {
    估算文档字节(&条目.执行前) + 命令大小(&条目.命令)
}

/// 粗估一份文档的内存占用。
fn 估算文档字节(文档: &场景文档) -> usize {
    let 实体数量 = 文档.实体数量();
    let 组件字段数: usize = 文档
        .实体表
        .values()
        .map(|实体| 实体.组件.iter().map(|组件| 组件.属性.len()).sum::<usize>())
        .sum();
    // 每个实体按约 256 字节（名称、标识、变换、组件头部）估算，
    // 每个组件字段按约 64 字节估算。
    实体数量 * 256 + 组件字段数 * 64
}

/// 粗估一条命令的字节数。
fn 命令大小(命令: &编辑器命令) -> usize {
    match 命令 {
        编辑器命令::新建实体 { 名称, .. } => 名称.len() + 64,
        编辑器命令::重命名实体 { 新名称, .. } => 新名称.len() + 32,
        编辑器命令::添加组件 { 组件, .. } => 组件.属性.len() * 64 + 64,
        编辑器命令::设组件属性 { 属性名, .. } => 属性名.len() + 64,
        编辑器命令::批量设变换 { 项 } => 项.len() * 48,
        编辑器命令::批量设属性 { 项 } => 项.len() * 96,
        编辑器命令::替换实体 { .. } => 512,
        编辑器命令::设为快照 { 文档 } => 估算文档字节(文档),
        _ => 64,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    fn 快照(名称: &str) -> Arc<场景文档> {
        Arc::new(场景文档::新建(名称))
    }

    fn 命令(名称: &str) -> 编辑器命令 {
        编辑器命令::重命名实体 {
            标识: 实体标识::新建(),
            新名称: 名称.to_string(),
        }
    }

    #[test]
    fn 提交后可以撤销重做() {
        let mut 栈 = 撤销栈::新建();
        assert!(!栈.有未保存修改());

        栈.提交(命令("甲"), 快照("基线"), None);
        assert_eq!(栈.可撤销步数(), 1);
        assert_eq!(栈.可重做步数(), 0);
        assert_eq!(栈.下一次撤销名(语言::中文), Some("重命名实体"));
        // 保存点仍是 None，当前位置有标记，因此算"已修改"
        assert!(栈.有未保存修改());

        let 条目 = 栈.弹出撤销().unwrap();
        assert_eq!(条目.执行前.元数据.场景名, "基线");
        栈.推入重做(条目);
        assert_eq!(栈.可撤销步数(), 0);
        assert_eq!(栈.可重做步数(), 1);
        assert_eq!(栈.下一次重做名(语言::中文), Some("重命名实体"));

        let 条目 = 栈.弹出重做().unwrap();
        栈.推入已应用(条目);
        assert_eq!(栈.可撤销步数(), 1);
        assert_eq!(栈.可重做步数(), 0);
    }

    #[test]
    fn 保存点能让文档恢复干净状态() {
        let mut 栈 = 撤销栈::新建();
        栈.标记已保存();
        assert!(!栈.有未保存修改());

        栈.提交(命令("甲"), 快照("基线"), None);
        assert!(栈.有未保存修改(), "提交之后应当算已修改");

        栈.标记已保存();
        assert!(!栈.有未保存修改(), "在当前位置标记保存后应当算干净");

        栈.提交(命令("乙"), 快照("基线"), None);
        assert!(栈.有未保存修改());

        // 撤销回到保存点，必须重新变干净
        栈.弹出撤销().unwrap();
        assert!(
            !栈.有未保存修改(),
            "撤销回到保存点后应当算干净，实际保存点={:?} 当前位置={:?}",
            栈.保存点,
            栈.当前位置标记()
        );

        // 再撤销一步（越过保存点）应当又算已修改
        栈.弹出撤销().unwrap();
        assert!(栈.有未保存修改(), "越过保存点之后应当算已修改");
    }

    #[test]
    fn 新操作会清空重做分支() {
        let mut 栈 = 撤销栈::新建();
        栈.提交(命令("甲"), 快照("基线"), None);
        let 条目 = 栈.弹出撤销().unwrap();
        栈.推入重做(条目);
        assert_eq!(栈.可重做步数(), 1);

        // 撤销之后又做了新操作，原重做分支应当失效
        栈.提交(命令("乙"), 快照("基线"), None);
        assert_eq!(
            栈.可重做步数(),
            0,
            "提交新操作后重做分支必须被丢弃，否则重做会覆盖新操作"
        );
    }

    #[test]
    fn 超出步数上限会丢弃最旧条目() {
        let mut 栈 = 撤销栈::带预算(usize::MAX, 3);
        for 序号 in 0..5 {
            栈.提交(命令(&format!("第{序号}次")), 快照("基线"), None);
        }
        assert_eq!(栈.可撤销步数(), 3, "应当只保留最近 3 步");
        assert_eq!(栈.下一次撤销名(语言::中文), Some("重命名实体"));
    }

    #[test]
    fn 超出内存预算会丢弃最旧条目但至少保留一步() {
        // 预算刻意压得很低，逼出收缩逻辑
        let mut 栈 = 撤销栈::带预算(1, 1000);
        for 序号 in 0..10 {
            栈.提交(命令(&format!("第{序号}次")), 快照("基线"), None);
        }
        assert_eq!(栈.可撤销步数(), 1, "内存预算不足时应至少保留一步");
    }

    #[test]
    fn 清空会重置保存点() {
        let mut 栈 = 撤销栈::新建();
        栈.提交(命令("甲"), 快照("基线"), None);
        栈.标记已保存();
        栈.清空();
        assert_eq!(栈.可撤销步数(), 0);
        assert_eq!(栈.可重做步数(), 0);
        assert!(!栈.有未保存修改(), "清空之后新文档应当是干净的");
    }

    #[test]
    fn 丢弃最旧条目不会破坏保存点的正确性() {
        // 这是"用标记而不是下标"的直接验证：
        // 先在栈空时标记保存，再压入超过上限的条目把最旧的冲掉，
        // 此时应当仍然报告"已修改"。
        let mut 栈 = 撤销栈::带预算(usize::MAX, 2);
        栈.标记已保存();
        for 序号 in 0..5 {
            栈.提交(命令(&format!("第{序号}次")), 快照("基线"), None);
        }
        assert!(栈.有未保存修改(), "内容与保存点不同时必须报告已修改");
        assert_eq!(栈.保存点, None);
    }

    #[test]
    fn 重做命令会把首次生成的实体标识填回去() {
        // 这是"重做必须幂等"的单元级验证。
        // 若不填回标识，重做会生成新 UUID，外部记录的标识全部失效。
        let 指定 = 实体标识::新建();
        let 条目 = 撤销条目 {
            标记: 1,
            显示名: "新建实体".to_string(),
            执行前: 快照("基线"),
            命令: 编辑器命令::新建实体 {
                名称: "甲".to_string(),
                父实体: None,
                指定标识: None,
            },
            新实体: Some(指定),
        };

        match 条目.重做用命令() {
            编辑器命令::新建实体 { 指定标识, .. } => {
                assert_eq!(
                    指定标识,
                    Some(指定),
                    "重做时必须复用首次生成的实体标识，否则重做后标识会漂移"
                );
            }
            其他 => panic!("重做命令的类型不应改变，实际：{其他:?}"),
        }
    }

    #[test]
    fn 重做命令对其他命令保持原样() {
        let 原命令 = 编辑器命令::删除实体 {
            标识: 实体标识::新建(),
        };
        let 条目 = 撤销条目 {
            标记: 1,
            显示名: "删除实体".to_string(),
            执行前: 快照("基线"),
            命令: 原命令.clone(),
            新实体: None,
        };
        assert_eq!(条目.重做用命令(), 原命令);
    }
}
