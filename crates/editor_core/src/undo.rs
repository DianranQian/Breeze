//! 撤销与重做。
//!
//! # 为什么是"差量 + 命令"而不是"反向操作"
//!
//! 主流做法是给每个操作写一个 `undo()`，把变更反过来做一遍。它省内存，
//! 但代价是**每条命令都必须有人正确写出反向语义**，而下面这些操作的反向
//! 语义都不显然：
//!
//! * 删除实体连同其整棵子树 —— 反向要按原次序、原父实体精确复原；
//! * 调整层级 —— 反向要复原新旧两侧的次序编号；
//! * 拆除组件 —— 反向要复原组件的完整属性表。
//!
//! 任何一处写错，表现就是"撤销之后场景悄悄坏掉"，而且很难定位。
//!
//! # 为什么记录的是"差量"而不是"整份文档快照"
//!
//! 早期实现每次提交都存一份完整 `场景文档`，实测（1000 实体）单次命令
//! 7.6ms、撤销栈 256 步占 63.8MB（每步 249KB），且都随场景规模线性增长。
//! 现在改为只记录**真的变了的部分**（见 [`crate::delta`]）：撤销 = 把差量
//! 逆向应用回文档；重做 = 把命令重新应用一遍。
//!
//! 这样仍然只依赖两个可靠的部分：文档字段的 `Clone`，以及命令的 `应用`，
//! 而"漏还原某个字段"由 `delta` 里的机械比较 + 逐命令往返测试兜住。
//!
//! 代价是"记录什么"的判断集中在 `文档差量::比较` 一处，因此那里有一条
//! 强不变式的测试：对每种命令验证"执行 → 逆向应用差量 → 与执行前相同"。
//!
//! # 连续编辑为什么要合并
//!
//! 拖一次 Inspector 里的数值框会逐帧发出命令。若每帧一条记录，用户要按
//! 几十次 Ctrl+Z 才能退回拖拽前 —— 这正是 Godot `UndoRedo` 用
//! `MERGE_ENDS`/`MERGE_ALL` 解决的问题
//! （<https://github.com/godotengine/godot/blob/master/core/object/undo_redo.cpp>）。
//! 这里同样合并：命令自己给出**合并键**（动作名 + 目标），栈顶键相同且距离
//! 上次提交不超过 [`默认合并窗口`] 时并入上一条，保留**较早**的执行前状态。
//!
//! # 保存点为什么用标记而不是下标
//!
//! "文档是否已保存"需要记录保存时的栈位置。用下标的话，一旦因为内存
//! 预算丢弃了最旧的条目，所有下标都会位移，保存点就会指向错误的条目，
//! 表现为"存过盘的文件仍显示未保存"或更糟的"没存盘却显示已保存"。
//! 每个条目携带一个只增不减的标记，比较标记即可，丢弃条目不影响它。

use std::time::{Duration, Instant};

use scene_doc::document::{场景文档, 实体标识};

use crate::command::编辑器命令;
use crate::delta::文档差量;
use crate::i18n::语言;

/// 撤销栈的默认内存预算：64 MiB。
pub const 默认内存预算字节: usize = 64 * 1024 * 1024;

/// 撤销栈的默认最大步数。
pub const 默认最大步数: usize = 256;

/// 连续编辑的默认合并窗口。
///
/// 500ms 的依据：人手拖动一个数值框时，相邻两帧的间隔在 16~50ms 量级；
/// 而"松开鼠标、想一想、再拖一次"通常超过 1 秒。窗口取两者之间，
/// 既能合并一次连续拖动，又不会把两次独立的拖拽并成一条。
pub const 默认合并窗口: Duration = Duration::from_millis(500);

/// 连续编辑的合并键：动作名 + 目标。
///
/// 只有**同一个动作**作用在**同一个目标**上才允许合并：
/// 拖动甲的位置和拖动乙的位置必须是两步，否则撤销会连带改掉另一个实体。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 合并键 {
    /// 动作名（英文标识，不随界面语言变化）。
    pub 动作: &'static str,
    /// 目标描述：实体标识，或"实体/组件/属性"这样的复合键。
    pub 目标: String,
}

impl 合并键 {
    /// 构造一个合并键。
    pub fn 新建(动作: &'static str, 目标: impl Into<String>) -> Self {
        Self {
            动作,
            目标: 目标.into(),
        }
    }
}

/// 一个撤销条目。
#[derive(Debug, Clone)]
pub struct 撤销条目 {
    /// 该条目的唯一标记，用于保存点比较。
    pub 标记: u64,
    /// 用户可见的操作名。
    pub 显示名: String,
    /// 执行该命令**之前**的文档快照。
    pub 差量: 文档差量,
    /// 被执行的命令本身。重做时重新应用它。
    pub 命令: 编辑器命令,
    /// 首次执行该命令时新生成的实体标识（若有）。
    ///
    /// # 为什么必须记录它
    ///
    /// `新建实体` 命令里的 `指定标识` 首次执行时是 `None`，实体的 UUID
    /// 由执行过程生成。如果重做时再执行一次原始命令，就会**又生成一个
    /// 不同的 UUID**，结果是"撤销再重做之后，实体还在但标识变了"。
    ///
    /// 这会静默破坏所有记录了标识的外部状态：选择集、剪贴板、资源引用、
    /// 以及用户脚本里按标识查找实体的代码。因为文档看起来"有那个实体"，
    /// 问题极难被发现。记录首次生成的标识，重做时才可能幂等。
    pub 新实体: Option<实体标识>,
    /// 连续编辑的合并键。`None` 表示这条命令永不与其他命令合并。
    pub 合并键: Option<合并键>,
}

impl 撤销条目 {
    /// 返回一条用于**重做**的命令。
    ///
    /// 与原始命令的唯一区别是把首次生成的实体标识填回去，
    /// 保证重做产生与首次执行完全相同的文档。
    pub fn 重做用命令(&self) -> 编辑器命令 {
        match (&self.命令, self.新实体) {
            (
                编辑器命令::新建实体 {
                    名称,
                    父实体,
                    指定标识: None,
                },
                Some(标识),
            ) => 编辑器命令::新建实体 {
                名称: 名称.clone(),
                父实体: *父实体,
                指定标识: Some(标识),
            },
            _ => self.命令.clone(),
        }
    }
}

/// 撤销栈。
#[derive(Debug)]
pub struct 撤销栈 {
    /// 已应用的条目，最后一个是最近一次操作。
    已应用: Vec<撤销条目>,
    /// 被撤销掉的条目，用于重做。最后一个是最近一次撤销。
    可重做: Vec<撤销条目>,
    /// 内存预算（字节）。
    内存预算: usize,
    /// 最大步数。
    最大步数: usize,
    /// 标记计数器，只增不减。
    下一标记: u64,
    /// 保存点标记。`None` 表示"从未保存过"，此时只有栈为空才算干净。
    保存点: Option<u64>,
    /// 两个栈当前估算占用的总字节数。
    ///
    /// 增量维护而不是每次提交重算：重算是 O(条目数 × 实体数)，
    /// 实测在 256 步 × 1000 实体时要 4.4ms —— 正好是"每帧一次编辑"卡顿的根源。
    已用字节: usize,
    /// 连续编辑的合并窗口。
    合并窗口: Duration,
    /// 最近一次提交的时刻（用于判断是否落在合并窗口内）。
    最近提交: Option<Instant>,
    /// 撤销栈之外的隐式修改（例如打开场景时按 UID 修复引用）。
    ///
    /// 与 `保存点` 分开存：隐式修改不占历史条目，撤销不会"撤掉"它，
    /// 但它确实让内存与磁盘不一致，必须让保存按钮亮起来。
    强制未保存: bool,
}

impl Default for 撤销栈 {
    fn default() -> Self {
        Self::新建()
    }
}

impl 撤销栈 {
    /// 用默认预算创建。
    pub fn 新建() -> Self {
        Self::带预算(默认内存预算字节, 默认最大步数)
    }

    /// 用指定预算创建。
    pub fn 带预算(内存预算: usize, 最大步数: usize) -> Self {
        Self {
            已应用: Vec::new(),
            可重做: Vec::new(),
            内存预算,
            最大步数,
            下一标记: 1,
            保存点: None,
            已用字节: 0,
            合并窗口: 默认合并窗口,
            最近提交: None,
            强制未保存: false,
        }
    }

    /// 设置连续编辑的合并窗口。
    ///
    /// 测试需要确定性，因此可以把它设成 0（等价于"永不合并"）；
    /// 界面里用默认值即可。
    pub fn 设置合并窗口(&mut self, 窗口: Duration) {
        self.合并窗口 = 窗口;
    }

    /// 可撤销的步数。
    pub fn 可撤销步数(&self) -> usize {
        self.已应用.len()
    }

    /// 可重做的步数。
    pub fn 可重做步数(&self) -> usize {
        self.可重做.len()
    }

    /// 下一次撤销会做什么（用于菜单项文字），按给定语言取命令名。
    ///
    /// 名字由条目里保存的命令现算，而不是用提交时定下的那份文案 ——
    /// 否则用户在切换界面语言之后，历史里已有的条目仍是旧语言。
    pub fn 下一次撤销名(&self, 语言: 语言) -> Option<&'static str> {
        self.已应用.last().map(|条目| 条目.命令.显示名(语言))
    }

    /// 下一次重做会做什么，按给定语言取命令名。
    pub fn 下一次重做名(&self, 语言: 语言) -> Option<&'static str> {
        self.可重做.last().map(|条目| 条目.命令.显示名(语言))
    }

    /// 当前所处的条目标记。栈为空时为 `None`。
    pub fn 当前位置标记(&self) -> Option<u64> {
        self.已应用.last().map(|条目| 条目.标记)
    }

    /// 当前估算占用的字节数（增量维护，O(1)）。
    pub fn 估算字节(&self) -> usize {
        self.已用字节
    }

    /// 最近 `数量` 条已应用条目的显示名（最新的在最后）。
    ///
    /// 只服务诊断与自动验收：当撤销栈异常增长时，名称能直接指出
    /// "是哪一类命令在被反复记录"，比只看步数快得多。
    pub fn 最近条目名(&self, 数量: usize) -> Vec<String> {
        let 起点 = self.已应用.len().saturating_sub(数量);
        self.已应用[起点..]
            .iter()
            .map(|条目| 条目.显示名.clone())
            .collect()
    }

    /// 记录一次提交。
    ///
    /// `差量` 是命令造成的文档变化（撤销时按它还原），
    /// `新实体` 是命令执行结果里新生成的实体标识（若有）。
    pub fn 提交(
        &mut self, 命令: 编辑器命令, 差量: 文档差量, 新实体: Option<实体标识>
    ) {
        self.提交内部(命令, 差量, 新实体, Instant::now(), false);
    }

    /// 记录一次**连续编辑**（数值框/滑块的逐帧命令），允许与上一条合并。
    ///
    /// # 为什么"合并"必须由调用方声明
    ///
    /// 时间窗本身分不清"同一次拖拽的两帧"和"用户连按两次快捷键" ——
    /// 后者在毫秒级内连续发生，若自动合并，用户就再也回不到中间状态。
    /// Godot 的 `UndoRedo::create_action(name, merge_mode)` 同样是**调用方**
    /// 声明合并模式，而不是由历史自己猜。这里照此办理：
    /// 界面明确知道"这是拖拽中的一帧"，就调这个入口；其余一律不合并。
    pub fn 提交连续(
        &mut self, 命令: 编辑器命令, 差量: 文档差量, 新实体: Option<实体标识>
    ) {
        self.提交内部(命令, 差量, 新实体, Instant::now(), true);
    }

    /// 与 [`撤销栈::提交连续`] 相同，但用调用方给定的时刻判断合并窗口。
    ///
    /// 单独开这个入口是为了让测试能确定性地验证合并行为，
    /// 而不必真的 sleep。
    pub fn 提交在(
        &mut self,
        命令: 编辑器命令,
        差量: 文档差量,
        新实体: Option<实体标识>,
        时刻: Instant,
    ) {
        self.提交内部(命令, 差量, 新实体, 时刻, true);
    }

    /// 提交的统一实现。
    ///
    /// `允许合并` 由调用方决定（见 [`撤销栈::提交连续`]），
    /// `时刻` 只用来判断"是否还在同一次连续编辑的时间窗内"。
    fn 提交内部(
        &mut self,
        命令: 编辑器命令,
        差量: 文档差量,
        新实体: Option<实体标识>,
        时刻: Instant,
        允许合并: bool,
    ) {
        let 本次合并键 = if 允许合并 {
            命令.合并键()
        } else {
            None
        };
        let 可以合并 = self.可以并入栈顶(&本次合并键, 时刻);

        if 可以合并 {
            // MERGE_ENDS：保留较早的执行前状态，命令换成较晚的那条。
            let Some(顶) = self.已应用.last_mut() else {
                return;
            };
            let 旧字节 = 条目字节(顶);
            顶.差量.并入(差量);
            顶.命令 = 命令;
            // 新实体取"最早的那次"：重做时必须复用首次生成的标识。
            顶.新实体 = 顶.新实体.or(新实体);
            顶.显示名 = 顶.命令.显示名(语言::中文).to_string();
            let 新字节 = 条目字节(顶);
            self.已用字节 = self.已用字节 + 新字节 - 旧字节;
            self.最近提交 = Some(时刻);
            return;
        }

        let 标记 = self.下一标记;
        self.下一标记 += 1;

        // 新操作会让原有的重做分支失效 —— 这是编辑器的标准语义：
        // 撤销几步后又做了新的事，原来的"未来"就不存在了。
        self.可重做.clear();

        let 条目 = 撤销条目 {
            标记,
            // 条目里留一份默认语言的文案，供调试与日志；
            // 界面显示走 `下一次撤销名(语言)`，那里按当前语言现算。
            显示名: 命令.显示名(语言::中文).to_string(),
            差量,
            命令,
            新实体,
            合并键: 本次合并键,
        };
        self.已用字节 += 条目字节(&条目);
        self.已应用.push(条目);
        self.最近提交 = Some(时刻);

        self.收缩到预算内();
    }

    /// 这次提交能否并入栈顶。
    fn 可以并入栈顶(&self, 本次合并键: &Option<合并键>, 时刻: Instant) -> bool {
        // 有重做分支时不能合并：用户撤销过，栈顶已经不是"刚才那条"了。
        if !self.可重做.is_empty() {
            return false;
        }
        let (Some(键), Some(顶)) = (本次合并键, self.已应用.last()) else {
            return false;
        };
        if 顶.合并键.as_ref() != Some(键) {
            return false;
        }
        match self.最近提交 {
            Some(上次) => 时刻.saturating_duration_since(上次) <= self.合并窗口,
            None => false,
        }
    }

    /// 弹出可撤销的条目。
    ///
    /// 返回条目；调用方负责把 `执行前` 快照恢复进文档，
    /// 并把条目交还给 [`撤销栈::推入重做`]。
    pub fn 弹出撤销(&mut self) -> Option<撤销条目> {
        let 条目 = self.已应用.pop()?;
        self.已用字节 = self.已用字节.saturating_sub(条目字节(&条目));
        Some(条目)
    }

    /// 把刚撤销的条目登记到重做栈。
    pub fn 推入重做(&mut self, 条目: 撤销条目) {
        self.已用字节 += 条目字节(&条目);
        self.可重做.push(条目);
    }

    /// 弹出可重做的条目。
    pub fn 弹出重做(&mut self) -> Option<撤销条目> {
        let 条目 = self.可重做.pop()?;
        self.已用字节 = self.已用字节.saturating_sub(条目字节(&条目));
        Some(条目)
    }

    /// 把刚重做的条目放回已应用栈。
    pub fn 推入已应用(&mut self, 条目: 撤销条目) {
        self.已用字节 += 条目字节(&条目);
        self.已应用.push(条目);
    }

    /// 清空全部历史。打开新场景或新建场景时调用。
    pub fn 清空(&mut self) {
        self.已应用.clear();
        self.可重做.clear();
        self.保存点 = None;
        self.已用字节 = 0;
        self.最近提交 = None;
        self.强制未保存 = false;
    }

    /// 把当前位置标记为保存点。
    pub fn 标记已保存(&mut self) {
        self.保存点 = self.当前位置标记();
        self.强制未保存 = false;
    }

    /// 强制把文档标记为"相比磁盘有修改"。
    ///
    /// # 什么时候需要它
    ///
    /// 有些修改发生在**撤销栈之外**：例如打开场景时按 UID 把失效引用
    /// 重连到新路径。这种修改必须让用户保存，否则下次打开又会退回旧路径。
    /// 但撤销栈只认识"命令"，无法表达一次隐式修复，所以需要一个显式的脏标记。
    ///
    /// 下一次 [`撤销栈::标记已保存`] 会清掉它。
    pub fn 强制标记未保存(&mut self) {
        self.强制未保存 = true;
    }

    /// 文档相对保存点是否已被修改。
    pub fn 有未保存修改(&self) -> bool {
        self.强制未保存 || self.保存点 != self.当前位置标记()
    }

    /// 丢弃最旧的条目，直到估算占用回到预算内。
    ///
    /// 至少保留一个条目：否则"刚做的操作立刻不可撤销"，
    /// 在超大场景下会变成很突兀的体验。
    ///
    /// 判定用增量维护的 `已用字节`，因此逐条丢弃是线性的，
    /// 不再是"每丢一条就重算整个栈"。
    fn 收缩到预算内(&mut self) {
        while self.已应用.len() > self.最大步数 && self.已应用.len() > 1 {
            self.弹出并计账最旧();
        }
        while self.已用字节 > self.内存预算 && self.已应用.len() > 1 {
            self.弹出并计账最旧();
        }
    }

    /// 从最旧一端丢掉一条，并把它占的字节从总数里扣掉。
    fn 弹出并计账最旧(&mut self) {
        if self.已应用.is_empty() {
            return;
        }
        let 条目 = self.已应用.remove(0);
        self.已用字节 = self.已用字节.saturating_sub(条目字节(&条目));
    }
}

/// 估算一个条目占用的字节数。
///
/// 刻意不调用序列化来"精确测量"：那会让每次提交都付出一次全量序列化的
/// 代价，正是需求里禁止的"每次修改都重新序列化整个项目"。
/// 这里的估算与真实占用同阶，对"该丢弃多少"这个决策已经足够。
fn 条目字节(条目: &撤销条目) -> usize {
    条目.差量.估算字节() + 命令大小(&条目.命令)
}

/// 粗估一份文档的内存占用（仅用于 `设为快照` 这种整份替换的命令）。
fn 估算文档字节(文档: &场景文档) -> usize {
    let 实体数量 = 文档.实体数量();
    let 组件字段数: usize = 文档
        .实体表
        .values()
        .map(|实体| 实体.组件.iter().map(|组件| 组件.属性.len()).sum::<usize>())
        .sum();
    // 每个实体按约 256 字节（名称、标识、变换、组件头部）估算，
    // 每个组件字段按约 64 字节估算。
    实体数量 * 256 + 组件字段数 * 64
}

/// 粗估一条命令的字节数。
fn 命令大小(命令: &编辑器命令) -> usize {
    match 命令 {
        编辑器命令::新建实体 { 名称, .. } => 名称.len() + 64,
        编辑器命令::重命名实体 { 新名称, .. } => 新名称.len() + 32,
        编辑器命令::添加组件 { 组件, .. } => 组件.属性.len() * 64 + 64,
        编辑器命令::设组件属性 { 属性名, .. } => 属性名.len() + 64,
        编辑器命令::批量设变换 { 项 } => 项.len() * 48,
        编辑器命令::批量设属性 { 项 } => 项.len() * 96,
        编辑器命令::替换实体 { .. } => 512,
        编辑器命令::设为快照 { 文档 } => 估算文档字节(文档),
        _ => 64,
    }
}

