    /// 一千实体场景里，256 步历史的总占用必须与"改了几个实体"同阶。
    ///
    /// 旧实现每步存一份完整文档：实测 1000 实体时每步 249KB、256 步 63.8MB。
    /// 差量 + 顺序拼接之后，同样的 256 步应当只有几十 KB。
    #[test]
    fn 一千实体场景下历史占用与场景规模无关() {
        let mut 文档 = 场景文档::新建("大场景");
        for i in 0..1000 {
            let 实体 = scene_doc::document::场景实体::新建(format!("实体{i}"));
            文档.实体表.insert(实体.标识, 实体.clone());
            文档.顶层顺序.push(实体.标识);
        }
        let 目标 = *文档.顶层顺序.first().unwrap();

        let mut 栈 = 撤销栈::带预算(默认内存预算字节, 256);
        // 模拟"建一千个实体"这种会把顶层顺序一路改下去的编辑：
        // 每步只增加一个实体，但顺序向量在增长。若整份存顺序，这里会爆。
        for i in 0..256 {
            let mut 前 = 文档.clone();
            let 新实体 = scene_doc::document::场景实体::新建(format!("新增{i}"));
            前.实体表.insert(新实体.标识, 新实体.clone());
            前.顶层顺序.push(新实体.标识);
            let 后 = 前.clone();
            前.实体表.get_mut(&目标).unwrap().名称 = format!("改{i}");
            栈.提交(命令("新建"), 文档差量::比较(&文档, &前), None);
            let _ = 后;
        }
        let 占用 = 栈.估算字节();
        println!("MEASURE 256 步（新建类）共 {占用} 字节");
        assert!(
            占用 < 512 * 1024,
            "256 步占用 {占用} 字节过大（旧实现约 63.8MB）"
        );
    }

