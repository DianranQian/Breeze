//! 示例项目模板：把「打开示例」从仓库路径里解耦出来。
//!
//! # 要解决的问题
//!
//! 早期「打开示例项目」直接用编译期 `CARGO_MANIFEST_DIR` 上溯两级拼出
//! `examples/<名称>`。那串路径被**烙进二进制**，后果是三重的：
//!
//! * 绿色版/安装版里根本没有 `crates/editor_app`，示例永远打不开；
//! * 用户想换一套自己的模板，只能改代码重编译；
//! * 测试想覆盖「一个模板都找不到」的分支，必须真的把仓库里的示例删掉 ——
//!   这既危险又不可能并行。
//!
//! 本模块把这件事拆成四件**互不依赖的纯逻辑**（只用 `std`，不碰 egui/bevy，
//! 因此可以在没有窗口、没有 GPU 的环境里被完整测试）：
//!
//! | 关注点 | 入口 |
//! | --- | --- |
//! | 有哪些模板可用 | [`发现模板`] / [`从根集合发现`] |
//! | 把模板装到用户选的位置 | [`复制模板到`] |
//! | 打开一个已有项目（含最小校验） | [`打开已有项目目录`] |
//! | 资源路径必须落在项目内 | [`解析资源路径`] |
//!
//! # 发现模板的优先级
//!
//! 1. 环境变量 [`模板目录环境变量`]：用户显式配置的模板目录；
//!    该变量**也可以直接指向某一个模板目录**（用户把示例解压在任意位置的情况）；
//! 2. 可执行文件同级的 `examples/`：绿色版把示例放在 exe 旁边；
//! 3. 编译期 `CARGO_MANIFEST_DIR` 上溯到仓库根的 `examples/`：**仅开发期兜底**。
//!
//! 关键约定：**只要环境变量有值，就不再使用 2、3 两级**。这不是偷懒，而是让
//! "用户配置"与"仓库兜底"不会混在一起 —— 配置错了必须报错，而不是悄悄拿仓库里
//! 的旧示例把问题盖住；测试也因此可以完全绕开真实仓库路径。
//!
//! # 为什么复制要「默认拒绝覆盖」
//!
//! 模板安装的目标目录是用户**用文件对话框自己挑的**。如果那个目录里已经有
//! 一个项目（或用户忘了换目录），静默覆盖等于毁掉他的工程。所以默认行为是：
//! 目标非空 → 直接报错并**一个字节都不写**；只有调用方显式给出
//! [`复制选项::允许覆盖`] 才清空目标后复制。
//!
//! # 复制出的项目必须与模板彻底断奶
//!
//! 复制只产出**普通文件**：不走符号链接、不走硬链接，二进制资源按字节复制。
//! 复制完成后立刻校验 `目标/project.ron` 存在 —— 一个没有清单的目录不是项目，
//! 与其让用户在编辑器里点开一个空壳，不如当场报错。

use std::path::{Component, Path, PathBuf};

use crate::project::{目录名, 项目描述, 项目清单文件名, 项目错误};

/// 模板目录的配置环境变量名。
///
/// 值可以是**包含各模板子目录的目录**，也可以是**某一个模板目录本身**。
pub const 模板目录环境变量: &str = "BEVY_STUDIO_EXAMPLES_DIR";

/// 一个可用的示例项目模板。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 模板 {
    /// 模板的稳定标识：目录名（例如 `2d_demo`）。
    ///
    /// 界面上"二维 / 三维"之类的枚举与它靠这个名字对应，
    /// 因此**不要**把它换成清单里的项目名（项目名会随文案变）。
    pub 名称: String,
    /// 展示给用户的名字：优先取 `project.ron` 里的项目名，取不到才退回目录名。
    pub 显示名: String,
    /// 模板根目录（绝对路径）。
    pub 根目录: PathBuf,
    /// 这个模板是从哪一级候选里发现的，用于诊断与界面提示。
    pub 来源: 模板来源,
}

impl 模板 {
    /// 模板清单文件的路径。
    pub fn 清单路径(&self) -> PathBuf {
        self.根目录.join(项目清单文件名)
    }
}

/// 模板的发现来源。
///
/// 区分它的直接用途：出错时能说清"是用户配置的问题，还是发布包里缺文件"，
/// 而不是只回一句"找不到示例"。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 模板来源 {
    /// 环境变量指向的模板根（其下有多个模板子目录）。
    环境变量,
    /// 环境变量直接指向的单个模板目录。
    环境变量单模板,
    /// 可执行文件同级的 `examples/`。
    可执行文件同级,
    /// 编译期仓库根的 `examples/`，仅开发期兜底。
    开发期兜底,
    /// 调用方注入的候选目录（测试、自定义入口）。
    注入,
}

impl 模板来源 {
    /// 一句可读的中文说明，可直接进日志或界面。
    pub fn 说明(self) -> &'static str {
        match self {
            Self::环境变量 => "环境变量 BEVY_STUDIO_EXAMPLES_DIR 指定的模板目录",
            Self::环境变量单模板 => "环境变量 BEVY_STUDIO_EXAMPLES_DIR 直接指向的模板",
            Self::可执行文件同级 => "可执行文件同级的 examples 目录",
            Self::开发期兜底 => "开发期兜底：仓库内 examples 目录（发布版不应命中）",
            Self::注入 => "调用方注入的候选目录",
        }
    }
}

/// 模板操作的错误。
///
/// 每一类的文案都写清"哪个路径、为什么、下一步怎么办"：
/// 这些错误会直接出现在界面上，用户看不懂就等于没处理。
#[derive(Debug, thiserror::Error)]
pub enum 模板错误 {
    /// 环境变量指向的路径不存在。
    #[error("模板目录不存在：{}（来自环境变量 BEVY_STUDIO_EXAMPLES_DIR）", 路径.display())]
    环境变量目录不存在 {
        /// 环境变量里的值。
        路径: PathBuf,
    },

    /// 环境变量指向的路径不是目录。
    #[error("环境变量 BEVY_STUDIO_EXAMPLES_DIR 指向的不是目录：{}", 路径.display())]
    环境变量不是目录 {
        /// 环境变量里的值。
        路径: PathBuf,
    },

    /// 环境变量指向的目录里没有任何模板，它自己也不是模板。
    #[error(
        "环境变量 BEVY_STUDIO_EXAMPLES_DIR 指向 `{}`，但它本身不是模板（缺少 project.ron），\
         其子目录里也没有任何模板",
        路径.display()
    )]
    环境变量无模板 {
        /// 环境变量里的值。
        路径: PathBuf,
    },

    /// 作为模板使用的目录不存在。
    #[error("模板目录不存在：{}", .0.display())]
    模板目录不存在(PathBuf),

    /// 目录里没有 `project.ron`，因此不是模板。
    #[error("`{}` 不是示例模板：缺少 project.ron", .0.display())]
    缺少清单(PathBuf),

    /// 目标目录已存在且非空。
    #[error(
        "目标目录 `{}` 已存在且非空（{} 项）；为避免覆盖已有文件已拒绝，\
         需要覆盖请显式允许",
        路径.display(),
        数量
    )]
    目标已存在 {
        /// 目标目录。
        路径: PathBuf,
        /// 目录内的条目数。
        数量: usize,
    },

    /// 目标路径被一个文件占住。
    #[error("目标路径 `{}` 已存在但不是目录，无法作为项目目录", .0.display())]
    目标不是目录(PathBuf),

    /// 目标就是模板目录本身。
    #[error("目标目录 `{}` 就是模板目录本身，拒绝复制", .0.display())]
    目标即模板(PathBuf),

    /// 目标位于模板内部。
    #[error(
        "目标目录 `{}` 位于模板目录 `{}` 内部，复制会无限递归，已拒绝",
        目标.display(),
        模板.display()
    )]
    目标在模板内 {
        /// 模板目录。
        模板: PathBuf,
        /// 目标目录。
        目标: PathBuf,
    },

    /// 模板位于目标内部。
    #[error(
        "目标目录 `{}` 包含了模板目录 `{}`，覆盖会先把模板本身删掉，已拒绝",
        目标.display(),
        模板.display()
    )]
    目标包含模板 {
        /// 模板目录。
        模板: PathBuf,
        /// 目标目录。
        目标: PathBuf,
    },

    /// 复制过程中的文件操作失败。
    #[error("复制失败：`{}` → `{}` —— {}", 源.display(), 目标.display(), 来源)]
    复制失败 {
        /// 源路径。
        源: PathBuf,
        /// 目标路径。
        目标: PathBuf,
        /// 底层错误。
        来源: std::io::Error,
    },

    /// 复制完成但目标里没有项目清单。
    #[error("复制完成但校验失败：目标 `{}` 中缺少 project.ron", .0.display())]
    复制后缺少清单(PathBuf),

    /// 一个模板都没找到。
    #[error("未找到任何示例模板：{原因}")]
    无模板 {
        /// 已经检查过的位置说明。
        原因: String,
    },

    /// 项目目录不存在。
    #[error("项目目录不存在：{}", .0.display())]
    项目目录不存在(PathBuf),

    /// 项目目录里没有清单。
    #[error("`{}` 不是微风项目：未找到 project.ron", .0.display())]
    项目清单缺失(PathBuf),

    /// 项目清单无效。
    #[error("项目清单无效：{} —— {}", 路径.display(), 来源)]
    项目清单无效 {
        /// 清单路径。
        路径: PathBuf,
        /// 失败原因。
        来源: String,
    },

    /// 资源路径是绝对路径。
    #[error("资源路径必须是项目相对路径，但收到了绝对路径：{0}")]
    绝对路径(String),

    /// 资源路径为空。
    #[error("资源路径不能为空")]
    相对路径为空,

    /// 资源路径逃逸出了项目根目录。
    #[error("资源路径 `{相对}` 解析后越出了项目根 `{}`", 根.display())]
    路径逃逸 {
        /// 项目根。
        根: PathBuf,
        /// 用户给的相对路径。
        相对: String,
    },

    /// 资源文件不存在。
    #[error("资源不存在：`{相对}`（解析为 {}）", 绝对.display())]
    资源不存在 {
        /// 用户给的相对路径。
        相对: String,
        /// 解析出的绝对路径。
        绝对: PathBuf,
    },
}

/// 复制模板时的选项。
///
/// 默认值是**最安全**的那个：不覆盖、隐藏项也照抄（`.gitignore` 这类文件
/// 往往是模板的一部分）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 复制选项 {
    /// 是否允许覆盖已存在且非空的目标目录。
    ///
    /// 置为 `true` 时，目标目录的内容会**先被全部删除**再复制：
    /// 覆盖后的目标必须与模板逐文件一致，不留旧文件混在里面。
    pub 允许覆盖: bool,
    /// 是否复制点开头的隐藏项（文件与目录）。
    pub 复制隐藏项: bool,
}

impl Default for 复制选项 {
    fn default() -> Self {
        Self {
            允许覆盖: false,
            复制隐藏项: true,
        }
    }
}

impl 复制选项 {
    /// 允许覆盖的选项：目标非空时先清空再复制。
    pub fn 覆盖() -> Self {
        Self {
            允许覆盖: true,
            ..Self::default()
        }
    }
}

/// 复制模板的结果。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 复制结果 {
    /// 复制来源（模板根，绝对路径）。
    pub 源: PathBuf,
    /// 项目落地位置（绝对路径）。
    pub 目标: PathBuf,
    /// 复制的文件数（不含目录）。
    pub 文件数: usize,
    /// 创建的目录数（不含目标根本身）。
    pub 目录数: usize,
    /// 复制的总字节数（按源文件大小累计）。
    pub 总字节数: u64,
}

