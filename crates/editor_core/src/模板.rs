/// 把项目内的相对资源路径解析成真实存在的绝对路径。
///
/// # 三道闸
///
/// 1. **拒绝绝对路径**：`C:/…`、`/…`、`\\server\share`、`\\?\…` 一律不收 ——
///    绝对路径一旦写进场景，换台机器就断；
/// 2. **拒绝逃逸**：`..` 只能在同一层里回退，`../../etc/passwd` 这种直接报
///    [`模板错误::路径逃逸`]，而且是在**判断文件是否存在之前**就拒绝；
/// 3. **拒绝符号链接逃逸**：规范化之后仍要求前缀是项目根，
///    防止"项目内一个软链指向项目外"把外部文件带进来。
///
/// 通过后返回规范化（真实）路径；文件不存在则是 [`模板错误::资源不存在`]。
pub fn 解析资源路径(项目根: &Path, 相对: &str) -> Result<PathBuf, 模板错误> {
    let 原文 = 相对.trim();
    if 原文.is_empty() {
        return Err(模板错误::相对路径为空);
    }

    // 反斜杠统一成斜杠：Windows 上两种写法都可能出现在场景文件里。
    let 统一 = 原文.replace('\\', "/");

    // 绝对/带根/带盘符：这些形态一旦交给 `Path::join` 会**替换掉**项目根，
    // 所以必须在拼接之前拦下来。
    let 带盘符 = {
        let 字节 = 统一.as_bytes();
        字节.len() >= 2 && 字节[0].is_ascii_alphabetic() && 字节[1] == b':'
    };
    if 统一.starts_with('/') || 带盘符 {
        return Err(模板错误::绝对路径(原文.to_string()));
    }
    match Path::new(&统一).components().next() {
        Some(Component::Prefix(_)) | Some(Component::RootDir) => {
            return Err(模板错误::绝对路径(原文.to_string()));
        }
        _ => {}
    }

    let 规范根 = 去扩展前缀(
        std::fs::canonicalize(项目根)
            .map_err(|_| 模板错误::项目目录不存在(项目根.to_path_buf()))?,
    );

    // 逐段消解 `.` / `..`；`..` 把栈顶弹空就说明要跳出项目根。
    let mut 段列表: Vec<&str> = Vec::new();
    for 段 in 统一.split('/') {
        match 段 {
            "" | "." => {}
            ".." => {
                if 段列表.pop().is_none() {
                    return Err(模板错误::路径逃逸 {
                        根: 规范根,
                        相对: 原文.to_string(),
                    });
                }
            }
            _ => 段列表.push(段),
        }
    }
    if 段列表.is_empty() {
        // 只给了 `.` / `./`：那是项目根本身，不是资源。
        return Err(模板错误::相对路径为空);
    }

    let 拼接 = 段列表.iter().fold(规范根.clone(), |累计, 段| 累计.join(段));
    // 词法层的兜底：消解完 `..` 之后必须仍在项目根之下。
    if !拼接.starts_with(&规范根) {
        return Err(模板错误::路径逃逸 {
            根: 规范根,
            相对: 原文.to_string(),
        });
    }

    let 真实 =
        去扩展前缀(
            std::fs::canonicalize(&拼接).map_err(|_| 模板错误::资源不存在 {
                相对: 原文.to_string(),
                绝对: 拼接.clone(),
            })?,
        );
    if !真实.starts_with(&规范根) {
        return Err(模板错误::路径逃逸 {
            根: 规范根,
            相对: 原文.to_string(),
        });
    }
    Ok(真实)
}

