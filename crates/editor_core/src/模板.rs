/// 打开一个**已有项目目录**，做最小但真实的校验。
///
/// 校验链：目录存在 → `project.ron` 存在 → 清单能解析出项目名。
/// 校验成功后返回项目名与场景数，足够界面把"打开项目"的列表先画出来。
///
/// 兼容性：如果清单里有本版本解析不了的内容（某个字段换了类型、新版本用了
/// 不认识的枚举分支等），RON 完整解析会失败；此时退一步从文本里取「名称」
/// 并按目录数场景，而不是让用户对着一个明明存在的项目收到"打不开"。
/// 版本号比本编辑器新的情况仍然**拒绝**（那是真的不能安全处理，
/// 交给 [`项目描述::打开`] 把关）。
pub fn 打开已有项目目录(目录: &Path) -> Result<项目摘要, 模板错误> {
    if !目录.is_dir() {
        return Err(模板错误::项目目录不存在(目录.to_path_buf()));
    }
    let 根 = 绝对化(目录);
    let 清单路径 = 根.join(项目清单文件名);
    if !清单路径.is_file() {
        return Err(模板错误::项目清单缺失(根));
    }
    let 文本 =
        std::fs::read_to_string(&清单路径).map_err(|错误| 模板错误::项目清单无效 {
            路径: 清单路径.clone(),
            来源: format!("读取失败：{错误}"),
        })?;

    match 项目描述::打开(&根) {
        Ok(项目) => Ok(项目摘要 {
            根目录: 根,
            名称: 项目.名称().to_string(),
            场景数: 项目.场景列表().len(),
        }),
        // 只有"字段不认识"这一类才降级兼容；版本过新等错误必须照原样报出去。
        Err(项目错误::清单解析 { .. }) => {
            let 名称 = 从清单文本取名称(&文本).ok_or_else(|| 模板错误::项目清单无效 {
                路径: 清单路径.clone(),
                来源: "无法从清单文本中解析出项目名".to_string(),
            })?;
            Ok(项目摘要 {
                场景数: 统计场景数(&根),
                根目录: 根,
                名称,
            })
        }
        Err(错误) => Err(模板错误::项目清单无效 {
            路径: 清单路径,
            来源: 错误.to_string(),
        }),
    }
}

/// 统计 `scenes/` 下的场景文件数，与 [`项目描述::场景列表`] 的口径一致。
fn 统计场景数(根: &Path) -> usize {
    let mut 数量 = 0usize;
    let mut 栈 = vec![根.join(目录名::场景)];
    while let Some(当前) = 栈.pop() {
        let Ok(读取) = std::fs::read_dir(&当前) else {
            continue;
        };
        for 项 in 读取.flatten() {
            let 路径 = 项.path();
            let Ok(元数据) = 项.metadata() else {
                continue;
            };
            if 元数据.is_dir() {
                栈.push(路径);
                continue;
            }
            if !元数据.is_file() {
                continue;
            }
            let 扩展 = 路径
                .extension()
                .and_then(|值| 值.to_str())
                .unwrap_or_default();
            if 扩展 == "ron" || 扩展 == "scene" {
                数量 += 1;
            }
        }
    }
    数量
}

