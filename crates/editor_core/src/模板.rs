/// 发现全部可用的示例模板。
///
/// 优先级见模块文档：环境变量 → 可执行文件同级 `examples/` → 开发期仓库兜底。
/// 环境变量一旦有值就只有它能决定结果（成败都在它身上，不会回退到兜底路径）。
///
/// 找不到时返回 [`模板错误::无模板`]，文案里列出检查过的位置 ——
/// 绝不 panic，也绝不静默返回空列表让界面一片空白。
pub fn 发现模板() -> Result<Vec<模板>, 模板错误> {
    if let Some(值) = std::env::var_os(模板目录环境变量) {
        return 从环境值发现(Some(Path::new(&值)));
    }

    let 候选 = 模板根候选带来源();
    let 模板 = 从带来源的根发现(&候选);
    if 模板.is_empty() {
        return Err(模板错误::无模板 {
            原因: 候选说明(&候选),
        });
    }
    Ok(模板)
}

/// 解析一个环境变量值（或任意注入值）对应的模板集合。
///
/// 这是 [`发现模板`] 里"环境变量那一级"的**可注入版本**：
/// `值` 为 `None` 表示没配置环境变量，返回 `Ok(空列表)`；
/// `值` 指向单个模板 → 返回该模板（[`模板来源::环境变量单模板`]）；
/// `值` 指向模板根 → 返回其下全部模板（[`模板来源::环境变量`]）。
///
/// 拆出来公开，是为了让测试能在**不改进程环境变量**的前提下覆盖三种失败分支
/// （路径不存在 / 不是目录 / 里面没有模板），也方便将来做"设置里改模板目录，
/// 不重启就生效"。
pub fn 从环境值发现(值: Option<&Path>) -> Result<Vec<模板>, 模板错误> {
    let Some(路径) = 值 else {
        return Ok(Vec::new());
    };
    if !路径.exists() {
        return Err(模板错误::环境变量目录不存在 {
            路径: 路径.to_path_buf(),
        });
    }
    if !路径.is_dir() {
        return Err(模板错误::环境变量不是目录 {
            路径: 路径.to_path_buf(),
        });
    }

    // 情况一：变量直接指向一个模板；情况二：变量指向"装模板的目录"。
    let mut 模板 = if 是模板目录(路径) {
        vec![造模板(路径, 模板来源::环境变量单模板)]
    } else {
        从一个根发现(路径, 模板来源::环境变量)
    };
    if 模板.is_empty() {
        return Err(模板错误::环境变量无模板 {
            路径: 路径.to_path_buf(),
        });
    }
    规范化模板(&mut 模板);
    Ok(模板)
}

/// 模板根候选目录（按优先级）。
///
/// 环境变量有值时**只返回它**：用户显式配置的目录是唯一真理，
/// 这样测试与排查都不会被仓库里的兜底路径干扰。
pub fn 模板根候选() -> Vec<PathBuf> {
    模板根候选带来源()
        .into_iter()
        .map(|(路径, _)| 路径)
        .collect()
}

/// 从一组**注入的**候选根目录里发现模板。
///
/// 这个版本不读环境变量、不读可执行文件位置、不碰编译期仓库路径，
/// 因此测试可以完全不依赖真实仓库；返回结果按 [`模板::名称`] 排序，
/// 保证界面顺序稳定。识别规则只有一条：目录里有 `project.ron`。
pub fn 从根集合发现(根: &[PathBuf]) -> Vec<模板> {
    let 候选: Vec<(PathBuf, 模板来源)> = 根
        .iter()
        .map(|路径| (路径.clone(), 模板来源::注入))
        .collect();
    从带来源的根发现(&候选)
}

/// 带来源的候选列表（环境变量那一级由 [`发现模板`] 单独处理）。
fn 模板根候选带来源() -> Vec<(PathBuf, 模板来源)> {
    // 环境变量有值时完全接管候选列表。
    if let Some(值) = std::env::var_os(模板目录环境变量) {
        return vec![(PathBuf::from(值), 模板来源::环境变量)];
    }

    let mut 候选 = Vec::new();
    // 绿色版：示例放在可执行文件旁边。
    if let Ok(可执行文件) = std::env::current_exe()
        && let Some(目录) = 可执行文件.parent()
    {
        候选.push((目录.join("examples"), 模板来源::可执行文件同级));
    }
    // 开发期兜底：仓库根的 examples/。
    候选.push((开发期示例目录(), 模板来源::开发期兜底));
    候选
}

/// 编译期算出的仓库 `examples/` 路径。
///
/// `CARGO_MANIFEST_DIR` 是 `crates/editor_core`，上溯两级即仓库根。
/// 发布版里这个路径显然不存在，[`从一个根发现`] 会安静地返回空 ——
/// 它只是兜底，不是主路径。
fn 开发期示例目录() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("examples")
}

/// 从一个候选根发现模板：根本身是模板 → 单个；否则扫它的直接子目录。
fn 从一个根发现(根: &Path, 来源: 模板来源) -> Vec<模板> {
    if 是模板目录(根) {
        return vec![造模板(根, 来源)];
    }
    if !根.is_dir() {
        return Vec::new();
    }
    直接子目录(根)
        .into_iter()
        .filter(|子目录| 是模板目录(子目录))
        .map(|子目录| 造模板(&子目录, 来源))
        .collect()
}

/// 按来源列表发现模板，并按规范化路径去重、按名称排序。
fn 从带来源的根发现(候选: &[(PathBuf, 模板来源)]) -> Vec<模板> {
    let mut 结果: Vec<模板> = 候选
        .iter()
        .flat_map(|(根, 来源)| 从一个根发现(根, *来源))
        .collect();
    规范化模板(&mut 结果);

    // 同一个模板可能同时出现在"可执行文件同级"和"仓库兜底"里（开发期很常见），
    // 按规范化路径去重，界面上就只该出现一次。
    let mut 已见: Vec<PathBuf> = Vec::new();
    结果.retain(|模板| {
        let 键 = 去扩展前缀(
            std::fs::canonicalize(&模板.根目录).unwrap_or_else(|_| 模板.根目录.clone()),
        );
        if 已见.contains(&键) {
            false
        } else {
            已见.push(键);
            true
        }
    });
    结果
}

/// 把模板根目录绝对化，并按名称排序。
///
/// 界面上的模板顺序必须稳定：文件系统枚举顺序在不同磁盘、不同次运行里并不一致，
/// 不排序的话下拉框会自己跳。
fn 规范化模板(列表: &mut [模板]) {
    for 模板 in 列表.iter_mut() {
        模板.根目录 = 绝对化(&模板.根目录);
    }
    列表.sort_by(|左, 右| {
        左.名称
            .cmp(&右.名称)
            .then_with(|| 左.根目录.cmp(&右.根目录))
    });
}

/// 组装一个模板条目。
fn 造模板(目录: &Path, 来源: 模板来源) -> 模板 {
    let 名称 = 目录
        .file_name()
        .map(|名| 名.to_string_lossy().into_owned())
        .filter(|名| !名.is_empty())
        .unwrap_or_else(|| "未命名模板".to_string());
    let 显示名 = std::fs::read_to_string(目录.join(项目清单文件名))
        .ok()
        .and_then(|文本| 从清单文本取名称(&文本))
        .unwrap_or_else(|| 名称.clone());
    模板 {
        名称,
        显示名,
        根目录: 目录.to_path_buf(),
        来源,
    }
}

/// 一个目录是不是模板：目录里有 `project.ron` 就是。
fn 是模板目录(目录: &Path) -> bool {
    目录.is_dir() && 目录.join(项目清单文件名).is_file()
}

/// 目录下的直接子目录，按名称排序（读不到时返回空，不报错）。
fn 直接子目录(目录: &Path) -> Vec<PathBuf> {
    let Ok(读取) = std::fs::read_dir(目录) else {
        return Vec::new();
    };
    let mut 结果: Vec<PathBuf> = 读取
        .flatten()
        .filter(|项| 项.file_type().map(|类型| 类型.is_dir()).unwrap_or(false))
        .map(|项| 项.path())
        .collect();
    结果.sort();
    结果
}

/// 「未找到任何模板」时给出检查过的位置，别让用户猜。
fn 候选说明(候选: &[(PathBuf, 模板来源)]) -> String {
    if 候选.is_empty() {
        return "没有任何候选目录（也没有配置环境变量 BEVY_STUDIO_EXAMPLES_DIR）".to_string();
    }
    let 列表 = 候选
        .iter()
        .map(|(路径, 来源)| format!("{}（{}）", 路径.display(), 来源.说明()))
        .collect::<Vec<_>>()
        .join("；");
    format!("已检查这些位置：{列表}")
}

/// 从清单文本里宽松地取「名称」字段。
///
/// 用途有两个：模板的显示名（清单解析失败也不该让列表变空），
/// 以及 [`打开已有项目目录`] 对"本版本不认识的字段"的兼容读取。
/// 刻意用文本扫描而不是 RON 反序列化：目标恰恰是"RON 解析失败时还能读到名字"。
fn 从清单文本取名称(文本: &str) -> Option<String> {
    let 位置 = 文本.find("名称")?;
    let 后半 = &文本[位置..];
    let 冒号 = 后半.find(':')?;
    let 剩余 = 后半[冒号 + 1..].trim_start();
    let 剩余 = 剩余.strip_prefix('"')?;
    let 结束 = 剩余.find('"')?;
    let 名称 = 剩余[..结束].trim();
    (!名称.is_empty()).then(|| 名称.to_string())
}

