/// 把模板复制到目标位置，装成一个独立项目。
///
/// # 安全约定
///
/// * 目标已存在且**非空** → 默认拒绝（[`模板错误::目标已存在`]），
///   此时目标目录一个字节都不会被改动；
/// * 目标已存在但**为空** → 允许写入；
/// * [`复制选项::允许覆盖`] 为真 → 先清空目标内容再复制，结果与模板逐文件一致；
/// * 目标是模板自身或位于模板内部 → 直接拒绝（会无限递归或自杀式覆盖）；
/// * 目标**包含**模板目录 → 同样拒绝（覆盖要先清空目标，那会把模板删掉）。
///
/// # 复制语义
///
/// 递归复制全部文件与子目录（含二进制资源、含空目录），空文件也算；
/// 符号链接按它指向的真实内容复制成普通文件，复制出的项目不依赖模板那边
/// 的链接结构。复制完成后校验 `目标/project.ron` 存在，否则报错。
pub fn 复制模板到(
    模板根: &Path,
    目标: &Path,
    选项: 复制选项,
) -> Result<复制结果, 模板错误> {
    // ---- 1. 源必须是模板 ----
    if !模板根.exists() {
        return Err(模板错误::模板目录不存在(模板根.to_path_buf()));
    }
    if !模板根.is_dir() || !模板根.join(项目清单文件名).is_file() {
        return Err(模板错误::缺少清单(模板根.to_path_buf()));
    }
    let 源 = 绝对化(模板根);

    // ---- 2. 目标的位置检查（在任何写入之前）----
    if 目标.as_os_str().is_empty() {
        return Err(模板错误::复制失败 {
            源: 源.clone(),
            目标: 目标.to_path_buf(),
            来源: std::io::Error::new(std::io::ErrorKind::InvalidInput, "目标路径为空"),
        });
    }
    let mut 目标绝对 = 绝对化(目标);
    if 目标绝对 == 源 {
        return Err(模板错误::目标即模板(目标绝对));
    }
    if 目标绝对.starts_with(&源) {
        return Err(模板错误::目标在模板内 {
            模板: 源.clone(),
            目标: 目标绝对,
        });
    }
    // 反向也不行：覆盖会先清空目标，而模板就在目标里面，等于先把模板删了。
    if 源.starts_with(&目标绝对) {
        return Err(模板错误::目标包含模板 {
            模板: 源,
            目标: 目标绝对,
        });
    }

    // ---- 3. 目标现状：非空默认拒绝，空目录放行 ----
    if 目标.exists() {
        if !目标.is_dir() {
            return Err(模板错误::目标不是目录(目标绝对));
        }
        let 已有条目 = std::fs::read_dir(目标)
            .map_err(|错误| 复制出错(&源, 目标, 错误))?
            .count();
        if 已有条目 > 0 {
            if !选项.允许覆盖 {
                return Err(模板错误::目标已存在 {
                    路径: 目标绝对,
                    数量: 已有条目,
                });
            }
            清空目录(目标)?;
        }
    } else {
        std::fs::create_dir_all(目标).map_err(|错误| 复制出错(&源, 目标, 错误))?;
    }
    // 目标此刻一定存在，重新绝对化以拿到消解过 `..` 的真实路径。
    目标绝对 = 绝对化(目标);

    // ---- 4. 递归复制：显式栈 + 已访问集合 ----
    let mut 文件数 = 0usize;
    let mut 目录数 = 0usize;
    let mut 总字节数 = 0u64;
    let mut 栈 = vec![(源.clone(), 目标绝对.clone())];
    let mut 已访问: Vec<PathBuf> = Vec::new();

    while let Some((当前源, 当前目标)) = 栈.pop() {
        // 符号链接可能指回祖先目录，按真实路径去重就不会无限走。
        let 键 = std::fs::canonicalize(&当前源).unwrap_or_else(|_| 当前源.clone());
        if 已访问.contains(&键) {
            continue;
        }
        已访问.push(键);

        let 读取 =
            std::fs::read_dir(&当前源).map_err(|错误| 复制出错(&当前源, &当前目标, 错误))?;
        for 项 in 读取 {
            let 项 = 项.map_err(|错误| 复制出错(&当前源, &当前目标, 错误))?;
            let 名 = 项.file_name();
            if !选项.复制隐藏项 && 名.to_string_lossy().starts_with('.') {
                continue;
            }
            let 源子 = 项.path();
            let 目标子 = 当前目标.join(&名);
            // 用 metadata（跟随链接）判断类型：模板里的符号链接按真实内容复制。
            let 元数据 =
                std::fs::metadata(&源子).map_err(|错误| 复制出错(&源子, &目标子, 错误))?;
            if 元数据.is_dir() {
                std::fs::create_dir_all(&目标子)
                    .map_err(|错误| 复制出错(&源子, &目标子, 错误))?;
                目录数 += 1;
                栈.push((源子, 目标子));
            } else if 元数据.is_file() {
                std::fs::copy(&源子, &目标子).map_err(|错误| 复制出错(&源子, &目标子, 错误))?;
                文件数 += 1;
                总字节数 = 总字节数.saturating_add(元数据.len());
            }
            // 其它类型（设备、管道……）不是"项目文件"，也没有可移植的复制方式，跳过。
        }
    }

    // ---- 5. 落地校验：没有 project.ron 的目标不是项目 ----
    if !目标绝对.join(项目清单文件名).is_file() {
        return Err(模板错误::复制后缺少清单(目标绝对));
    }

    Ok(复制结果 {
        源,
        目标: 目标绝对,
        文件数,
        目录数,
        总字节数,
    })
}

/// 清空一个目录的内容，但保留目录本身。
fn 清空目录(目录: &Path) -> Result<(), 模板错误> {
    let 读取 = std::fs::read_dir(目录).map_err(|错误| 复制出错(目录, 目录, 错误))?;
    for 项 in 读取 {
        let 项 = 项.map_err(|错误| 复制出错(目录, 目录, 错误))?;
        let 路径 = 项.path();
        let 元数据 =
            std::fs::symlink_metadata(&路径).map_err(|错误| 复制出错(&路径, 目录, 错误))?;
        let 结果 = if 元数据.is_dir() {
            std::fs::remove_dir_all(&路径)
        } else {
            std::fs::remove_file(&路径)
        };
        结果.map_err(|错误| 复制出错(&路径, 目录, 错误))?;
    }
    Ok(())
}

/// 统一构造"复制失败"错误，省掉每处重复的路径样板。
fn 复制出错(源: &Path, 目标: &Path, 来源: std::io::Error) -> 模板错误 {
    模板错误::复制失败 {
        源: 源.to_path_buf(),
        目标: 目标.to_path_buf(),
        来源,
    }
}

