/// 绝对化一个路径，并去掉 Windows 的 `\\?\` 扩展前缀。
///
/// `canonicalize` 能保证 `..` 与符号链接都被消解，"目标是否在项目内"这类
/// 前缀比较必须基于它；但它在 Windows 上会返回 `\\?\C:\…`，直接显示给用户
/// 很难看，也会让外部代码的 `starts_with` 比较莫名失败，所以只保留盘符形态。
/// 路径还不存在时退回"当前目录 + 词法规范化"。
fn 绝对化(路径: &Path) -> PathBuf {
    if let Ok(规范) = std::fs::canonicalize(路径) {
        return 去扩展前缀(规范);
    }
    let 绝对 = if 路径.is_absolute() {
        路径.to_path_buf()
    } else {
        std::env::current_dir()
            .map(|当前| 当前.join(路径))
            .unwrap_or_else(|_| 路径.to_path_buf())
    };
    词法规范化(&绝对)
}

/// 纯词法规范化：消掉 `.` 与 `..`，不访问文件系统。
fn 词法规范化(路径: &Path) -> PathBuf {
    let mut 结果 = PathBuf::new();
    for 组件 in 路径.components() {
        match 组件 {
            Component::CurDir => {}
            Component::ParentDir => {
                结果.pop();
            }
            _ => 结果.push(组件),
        }
    }
    结果
}

/// 去掉 `\\?\C:\…` 这样的扩展前缀；UNC 路径（`\\?\UNC\…`）原样保留。
fn 去扩展前缀(路径: PathBuf) -> PathBuf {
    let Some(文本) = 路径.to_str() else {
        return 路径;
    };
    let Some(剩余) = 文本.strip_prefix(r"\\?\") else {
        return 路径;
    };
    let 字节 = 剩余.as_bytes();
    let 是本地盘符 = 字节.len() >= 2 && 字节[0].is_ascii_alphabetic() && 字节[1] == b':';
    if 是本地盘符 {
        PathBuf::from(剩余)
    } else {
        路径
    }
}
