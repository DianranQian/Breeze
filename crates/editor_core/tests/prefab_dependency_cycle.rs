//! 中文名：预制件依赖与环检测（P4-A）
//!
//! 验证「保存模板」在写盘前把嵌套引用转换成项目级依赖边，并拒绝任何
//! 会让项目成环的保存：
//!
//! ```text
//! 扫描内层实例记录 → 写入 头.直接依赖 → 装进项目依赖图
//!   → DFS 三色检测 → 有环：拒绝保存，版本/依赖/磁盘全部原样
//!   → 无环：版本 +1 → 写盘
//! ```
//!
//! # 为什么失败必须零副作用
//!
//! 环检测不通过时，用户看到的应该是一次「什么都没发生」的保存：版本号
//! 没变、依赖字段没变、磁盘文件字节级相同。只要其中任何一项偷偷推进，
//! 引用该模板的实例就会按一个不存在的版本进入待同步，错误会从一次
//! 保存扩散到整个工程的版本视图。
//!
//! # 为什么覆盖「磁盘上已有环」的情况
//!
//! 模板文件可能被外部工具写入过互相引用。此时保存其中一份、且把它的
//! 依赖清空，应当能修复这条环 —— 检测用的是「这份新内容」而不是
//! 「磁盘上的旧内容」，否则用户永远无法从编辑器里自救。

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use editor_core::prefab_graph::预制件依赖图;
use editor_core::state::{日志内容, 编辑器状态};
use scene_doc::document::场景文档;
use scene_doc::path::项目相对路径;
use scene_doc::prefab::{实体来源, 预制件实例记录, 预制件文档};

/// 造一份只有根节点的小模板。
fn 造模板(名称: &str) -> 预制件文档 {
    let mut 场景 = 场景文档::新建(名称);
    let 根 = 场景.生成实体(名称, None);
    预制件文档::新建(名称, 根, 场景)
}

/**
 * 在模板里挂一个内层实例站点。
 *
 * 同时写入两处：站点实体的来源标成 `预制件实例根`（真实嵌套模板的形态），
 * 以及模板场景自己的实例表记录（依赖扫描认的是记录）。两者缺一，
 * 展开语义与依赖扫描就会对不上。
 */
fn 加内层站点(
    外层: &mut 预制件文档,
    内层: &预制件文档,
    站点名: &str,
    内层路径: &项目相对路径,
) {
    let 根 = 外层.头.根;
    let 站点 = 外层.场景.生成实体(站点名, Some(根));
    外层.场景.取可变(站点).expect("站点实体必须存在").来源 =
        实体来源::预制件实例根 { 实例根: 站点 };
    let mut 记录 = 预制件实例记录::新建(内层.引用(内层路径.clone()));
    记录.展开版本 = 内层.头.版本;
    外层.场景.预制件实例表.insert(站点, 记录);
}

/// 建一个临时项目，并把给定的模板按初始内容写进 `prefabs/`。
fn 建工程(
    模板: &[(项目相对路径, 预制件文档)]
) -> (tempfile::TempDir, 编辑器状态, PathBuf) {
    let 目录 = tempfile::tempdir().expect("应当能创建临时目录");
    let 根 = 目录.path().join("依赖测试");
    let mut 编辑器 = 编辑器状态::新建();
    编辑器.创建项目(&根, "依赖测试").expect("创建项目应当成功");
    std::fs::create_dir_all(根.join("prefabs")).expect("应当能创建 prefabs 目录");
    {
        let 项目 = 编辑器.项目.as_ref().expect("项目已打开");
        for (路径, 模板) in 模板 {
            项目.保存预制件(路径, 模板).expect("初始写入模板应当成功");
        }
    }
    编辑器.刷新预制件目录();
    (目录, 编辑器, 根)
}

/// 读取磁盘上的模板。
fn 读盘(编辑器: &编辑器状态, 路径: &项目相对路径) -> 预制件文档 {
    编辑器
        .项目
        .as_ref()
        .expect("项目已打开")
        .读取预制件(路径)
        .expect("应当能读回模板")
}

/// 模板文件的绝对路径（用于比对失败时文件字节是否原样）。
fn 绝对(根: &Path, 路径: &项目相对路径) -> PathBuf {
    根.join(路径.文本())
}

#[test]
fn 保存模板会把内层引用写成直接依赖() {
    let 内层路径 = 项目相对路径::解析("prefabs/武器.prefab.ron").expect("模板路径应当合法");
    let 外层路径 = 项目相对路径::解析("prefabs/敌兵.prefab.ron").expect("模板路径应当合法");
    let 内层 = 造模板("武器");
    let mut 外层 = 造模板("敌兵");
    加内层站点(&mut 外层, &内层, "右手", &内层路径);

    let (_临时, mut 编辑器, _根) = 建工程(&[
        (内层路径.clone(), 内层.clone()),
        (外层路径.clone(), 外层.clone()),
    ]);

    let 报告 = 编辑器
        .保存预制件模板(&mut 外层)
        .expect("无环时保存应当成功");
    assert_eq!(报告.新版本, 2);

    let 磁盘 = 读盘(&编辑器, &外层路径);
    assert_eq!(
        磁盘.头.直接依赖,
        BTreeSet::from([内层.头.标识]),
        "保存必须把内层实例引用写进文件头的直接依赖"
    );
    assert_eq!(
        磁盘.场景.预制件实例表.len(),
        1,
        "依赖落盘不能丢掉模板里的内层实例记录"
    );
    assert_eq!(磁盘.头.版本, 2);
    let 图 = 预制件依赖图::从目录(&编辑器.预制件目录);
    assert_eq!(
        图.依赖(&外层.头.标识),
        Some(&BTreeSet::from([内层.头.标识])),
        "目录刷新后，图中该节点的边必须与磁盘一致"
    );

    match &编辑器.日志列表().last().expect("保存必须写日志").内容 {
        日志内容::自由文本(文本) => {
            assert!(文本.contains("直接依赖 1 个模板"), "{文本}");
        }
        其他 => panic!("保存日志应当是可读的自由文本，实际是 {其他:?}"),
    }
}

#[test]
fn 成环时拒绝保存且版本依赖与磁盘原样() {
    let 武器路径 = 项目相对路径::解析("prefabs/武器.prefab.ron").expect("模板路径应当合法");
    let 敌兵路径 = 项目相对路径::解析("prefabs/敌兵.prefab.ron").expect("模板路径应当合法");
    let 武器 = 造模板("武器");
    let mut 敌兵 = 造模板("敌兵");
    加内层站点(&mut 敌兵, &武器, "右手", &武器路径);

    let (_临时, mut 编辑器, 根) = 建工程(&[
        (武器路径.clone(), 武器.clone()),
        (敌兵路径.clone(), 敌兵.clone()),
    ]);
    编辑器
        .保存预制件模板(&mut 敌兵)
        .expect("敌兵引用武器不构成环，应当保存成功");
    assert_eq!(读盘(&编辑器, &敌兵路径).头.版本, 2);

    let mut 武器反引用 = 武器.clone();
    加内层站点(&mut 武器反引用, &敌兵, "背上的敌兵", &敌兵路径);
    let 保存前字节 = std::fs::read_to_string(绝对(&根, &武器路径)).expect("应当能读模板文件");

    let 错误 = 编辑器
        .保存预制件模板(&mut 武器反引用)
        .expect_err("武器再引用敌兵会形成 A → B → A，保存必须被拒绝");
    let 错误文本 = format!("{错误}");
    assert!(错误文本.contains("成环"), "{错误文本}");
    assert!(错误文本.contains("「武器」"), "{错误文本}");
    assert!(错误文本.contains("「敌兵」"), "{错误文本}");
    assert!(错误文本.contains("保存已取消"), "{错误文本}");

    assert_eq!(武器反引用.头.版本, 1, "被拒绝的保存不得推进版本号");
    assert!(
        武器反引用.头.直接依赖.is_empty(),
        "被拒绝的保存必须把依赖字段恢复原样"
    );
    assert_eq!(
        std::fs::read_to_string(绝对(&根, &武器路径)).expect("应当能读模板文件"),
        保存前字节,
        "被拒绝的保存不能改动磁盘上的任何字节"
    );
    assert_eq!(
        编辑器
            .预制件目录
            .取(&武器.头.标识)
            .expect("目录仍应收录武器模板")
            .头
            .版本,
        1,
        "目录缓存也不该被一次失败的保存推进"
    );
}

#[test]
fn 自引用模板被拒绝保存() {
    let 自引用路径 = 项目相对路径::解析("prefabs/自引用.prefab.ron").expect("模板路径应当合法");
    let mut 自引用 = 造模板("自引用");
    let 自引用内容 = 自引用.clone();
    加内层站点(&mut 自引用, &自引用内容, "自己", &自引用路径);

    let (_临时, mut 编辑器, 根) = 建工程(&[(自引用路径.clone(), 自引用.clone())]);

    let 错误 = 编辑器
        .保存预制件模板(&mut 自引用)
        .expect_err("模板引用自己必须被拒绝");
    let 错误文本 = format!("{错误}");
    assert!(错误文本.contains("成环"), "{错误文本}");
    assert_eq!(
        错误文本.matches("「自引用」").count(),
        2,
        "环首尾都要显示：{错误文本}"
    );
    assert_eq!(自引用.头.版本, 1);
    assert!(自引用.头.直接依赖.is_empty());
    assert_eq!(读盘(&编辑器, &自引用路径).头.版本, 1);
    assert!(读盘(&编辑器, &自引用路径).头.直接依赖.is_empty());
    let 磁盘路径 = 绝对(&根, &自引用路径);
    assert!(磁盘路径.exists(), "拒绝保存不能删除模板文件");
}

/**
 * 验证「保存能把磁盘上已有的环修好」。
 *
 * 初始两份文件互相引用（模拟外部工具写入），此时项目本身已带环。
 * 清空乙的内层记录后保存乙：检测按乙的**新内容**构图，环消失，
 * 保存放行且乙的依赖落盘为空集。
 */
#[test]
fn 清空内层引用后可以保存并解除磁盘上的环() {
    let 甲路径 = 项目相对路径::解析("prefabs/甲.prefab.ron").expect("模板路径应当合法");
    let 乙路径 = 项目相对路径::解析("prefabs/乙.prefab.ron").expect("模板路径应当合法");
    let 甲 = 造模板("甲");
    let 乙 = 造模板("乙");

    let mut 甲含乙 = 甲.clone();
    let mut 乙含甲 = 乙.clone();
    加内层站点(&mut 甲含乙, &乙, "乙站点", &乙路径);
    加内层站点(&mut 乙含甲, &甲, "甲站点", &甲路径);

    let (_临时, mut 编辑器, _根) = 建工程(&[
        (甲路径.clone(), 甲含乙.clone()),
        (乙路径.clone(), 乙含甲.clone()),
    ]);

    乙含甲.场景.预制件实例表.clear();
    let 报告 = 编辑器
        .保存预制件模板(&mut 乙含甲)
        .expect("清空内层记录后保存应当解除环并成功");
    assert_eq!(报告.新版本, 2);
    let 磁盘 = 读盘(&编辑器, &乙路径);
    assert!(磁盘.头.直接依赖.is_empty());
    assert!(磁盘.场景.预制件实例表.is_empty());
    let 图 = 预制件依赖图::从目录(&编辑器.预制件目录);
    assert_eq!(
        图.依赖(&乙.头.标识).expect("目录必须收录乙模板"),
        &BTreeSet::new(),
        "保存后依赖图里乙不应再指向甲"
    );
}

/// 无环时依赖字段为空集，旧模板保存一次也不会凭空产生依赖。
#[test]
fn 没有内层记录时依赖保持为空() {
    let 路径 = 项目相对路径::解析("prefabs/普通.prefab.ron").expect("模板路径应当合法");
    let mut 普通 = 造模板("普通");
    let (_临时, mut 编辑器, _根) = 建工程(&[(路径.clone(), 普通.clone())]);

    编辑器
        .保存预制件模板(&mut 普通)
        .expect("普通模板应当能保存");
    let 磁盘 = 读盘(&编辑器, &路径);
    assert!(磁盘.头.直接依赖.is_empty());
}

/**
 * 与本次保存无关的历史环不能阻止保存。
 *
 * 丙 ↔ 丁 由外部工具写成，保存完全不参与这个环的戊必须成功；而保存
 * 丙自己仍然要被拒绝 —— 拒绝的判据是「这份模板是否落在环上」，
 * 不是「项目里是否存在环」。
 */
#[test]
fn 与本次保存无关的环不会阻止保存() {
    let 丙路径 = 项目相对路径::解析("prefabs/丙.prefab.ron").expect("模板路径应当合法");
    let 丁路径 = 项目相对路径::解析("prefabs/丁.prefab.ron").expect("模板路径应当合法");
    let 戊路径 = 项目相对路径::解析("prefabs/戊.prefab.ron").expect("模板路径应当合法");
    let 丙 = 造模板("丙");
    let 丁 = 造模板("丁");
    let mut 戊 = 造模板("戊");
    let mut 丙含丁 = 丙.clone();
    let mut 丁含丙 = 丁.clone();
    加内层站点(&mut 丙含丁, &丁, "丁站点", &丁路径);
    加内层站点(&mut 丁含丙, &丙, "丙站点", &丙路径);

    let (_临时, mut 编辑器, _根) = 建工程(&[
        (丙路径.clone(), 丙含丁.clone()),
        (丁路径.clone(), 丁含丙),
        (戊路径.clone(), 戊.clone()),
    ]);

    编辑器
        .保存预制件模板(&mut 戊)
        .expect("戊不在环上，保存必须成功");
    let 错误 = 编辑器
        .保存预制件模板(&mut 丙含丁)
        .expect_err("丙在环上，保存必须被拒绝");
    assert!(format!("{错误}").contains("成环"), "{错误}");
}
