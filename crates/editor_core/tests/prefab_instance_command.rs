//! 中文名：预制件实例命令闭环
//!
//! 验证「执行创建命令 → 撤销 → 重做」之后，文档**逐字段**回到正确状态：
//! 实体表、顶层顺序、资源表、预制件实例表以及确定性派生标识都必须一致。
//!
//! # 为什么用整份文档相等而不是逐项抽查
//!
//! 创建实例会同时改动四处：实例根实体、派生实体、实例记录与资源表。
//! 抽查容易漏掉"记录里的展开版本没回滚"或"次序没复原"这类隐蔽问题；
//! `场景文档` 实现了 `PartialEq`，整份比较能把所有字段一次性覆盖。
//!
//! # 重做为什么必须复用同一个实例根
//!
//! 派生节点的标识由 `UUIDv5(实例根, 节点地址)` 算出。若重做换了实例根，
//! 整棵子树的 UUID 都会漂移，覆盖表里的节点地址、选择集与脚本引用随之失效。
//! 下面的整份比较会直接抓住这种漂移。

use std::collections::BTreeMap;

use editor_core::command::编辑器命令;
use editor_core::state::编辑器状态;
use scene_doc::document::{变换数据, 场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::prefab::{实体来源, 派生实体标识, 节点地址, 预制件文档};
use scene_doc::property::属性值;

/**
 * 造一个「根 + 一个子节点」的模板。
 *
 * 根节点带 `移动` 组件，子节点带 `武器` 组件：这样物化结果既有实例根，
 * 也有一个确定性派生节点，可以同时验证两种来源标记。
 */
fn 造模板() -> 预制件文档 {
    let mut 场景 = 场景文档::新建("敌人模板");
    let 根 = 场景.生成实体("敌人", None);
    let 子 = 场景.生成实体("武器", Some(根));

    let mut 移动属性 = BTreeMap::new();
    移动属性.insert("速度".to_string(), 属性值::浮点(2.0));
    场景
        .取可变(根)
        .expect("模板根存在")
        .加组件(组件数据::新建("移动", 移动属性));
    场景
        .取可变(子)
        .expect("模板子节点存在")
        .加组件(组件数据::标记("武器"));

    预制件文档::新建("敌人", 根, 场景)
}

/**
 * 取模板根的唯一直接子节点。
 *
 * 测试模板固定为一个子节点，直接下标访问失败时会 panic，正好提醒
 * "模板结构改了，断言也要同步"。
 */
fn 模板子节点(模板: &预制件文档) -> 实体标识 {
    模板
        .场景
        .子实体列表(Some(模板.头.根))
        .first()
        .copied()
        .expect("模板应当有一个直接子节点")
}

#[test]
fn 创建撤销重做闭环() {
    let 模板 = 造模板();
    let 模板路径 = 项目相对路径::解析("prefabs/敌人.prefab.ron").expect("模板路径应当合法");
    let 放置 = 变换数据 {
        平移: (3.0, 4.0, 0.0),
        ..变换数据::单位()
    };

    let mut 编辑器 = 编辑器状态::新建();
    let 容器 = 编辑器.会话.文档.生成实体("容器", None);
    let 创建前 = 编辑器.会话.文档.clone();

    let 结果 = 编辑器
        .执行(编辑器命令::创建预制件实例 {
            模板: Box::new(模板.clone()),
            模板路径: 模板路径.clone(),
            放置,
            父实体: Some(容器),
            指定实例根: None,
        })
        .expect("创建实例应当成功");

    let 实例根 = 结果.新实体.expect("命令结果必须带回新实例根");
    let 创建后 = 编辑器.会话.文档.clone();

    assert_eq!(
        结果.影响实体.len(),
        2,
        "实例根与一个派生节点都应当出现在影响实体里"
    );
    let 根实体 = 创建后.取(实例根).expect("实例根必须存在");
    assert_eq!(根实体.父实体, Some(容器), "实例根必须挂到指定父实体下");
    assert_eq!(
        根实体.来源,
        实体来源::预制件实例根 { 实例根 },
        "实例根必须标记为预制件实例根"
    );
    assert_eq!(根实体.变换, Some(放置), "放置必须写到实例根的变换字段");
    assert!(根实体.有组件("移动"), "模板根组件必须被物化到实例根");

    let 记录 = &创建后.预制件实例表[&实例根];
    assert_eq!(记录.模板.路径, 模板路径);
    assert_eq!(记录.模板.版本, 模板.头.版本);
    assert_eq!(记录.放置, 放置);
    assert!(
        记录.模板根组件.contains("移动"),
        "首次物化必须把模板根组件记进所有权清单"
    );
    assert_eq!(记录.展开版本, 模板.头.版本);

    let 子地址 = 节点地址::根().追加(模板子节点(&模板));
    let 子 = 派生实体标识(实例根, &子地址);
    assert_eq!(
        创建后.取(子).expect("派生节点必须存在").来源,
        实体来源::预制件派生 {
            实例根,
            地址: 子地址,
        },
        "派生节点必须使用由实例根与节点地址算出的确定性标识"
    );

    assert!(编辑器.撤销一步(), "创建实例必须是一条可撤销记录");
    assert_eq!(
        编辑器.会话.文档, 创建前,
        "撤销必须把实体、顺序、资源表与实例记录全部还原"
    );
    assert!(
        编辑器.会话.文档.预制件实例表.is_empty(),
        "撤销后不能留下指向已删除实例根的记录"
    );

    assert!(编辑器.重做一步(), "撤销之后必须能重做");
    assert_eq!(
        编辑器.会话.文档, 创建后,
        "重做必须逐字段复现首次执行的结果，包括实例根与派生节点标识"
    );
}

#[test]
fn 创建失败时文档一个字都不改() {
    let 模板 = 造模板();
    let mut 编辑器 = 编辑器状态::新建();
    let 创建前 = 编辑器.会话.文档.clone();

    let 结果 = 编辑器.执行(编辑器命令::创建预制件实例 {
        模板: Box::new(模板),
        模板路径: 项目相对路径::解析("prefabs/敌人.prefab.ron").expect("路径"),
        放置: 变换数据::单位(),
        父实体: Some(实体标识::新建()),
        指定实例根: None,
    });

    assert!(结果.is_err(), "父实体不存在时命令必须失败");
    assert_eq!(编辑器.会话.文档, 创建前, "失败的命令不能留下半成品");
    assert_eq!(编辑器.可撤销步数(), 0, "失败的命令不能进历史");
}
