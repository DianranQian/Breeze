//! 中文名：旧版场景升级后的重展开
//!
//! 守的是格式版本 1 → 2 这条**语义**迁移的用户体验：
//! v1 编辑器把「模板里挂一份模板」展平成普通派生节点，站点上没有内层实例记录，
//! 内层模板的子节点整批缺失。字段层面那份文件完全合法，版本比较也挑不出毛病，
//! 所以迁移只能做一件事——把实例记录标成待展开，让**用户点一次同步**补齐内容。
//!
//! ```text
//! v1 场景（读入后）          迁移 + 一次同步之后
//!   枪实例                     枪实例
//!     └── 弹夹（普通派生）        └── 弹夹（嵌套实例根 + 内层记录）
//!         （弹头整批缺失）              └── 弹头（补齐）
//! ```
//!
//! # 为什么用整条链路来验
//!
//! 单测 [`scene_doc::storage::迁移场景`] 只能证明「版本涨了、`展开版本` 归零」；
//! 归零之后场景真的能被补展开、来源真的从派生改成嵌套实例根、内层记录真的建出来，
//! 是**规划 + 提交**那一整条链的事。这条文件从解码后的文档状态一路跑到同步结果，
//! 中间不手工构造任何 P4 形态——那是要被验证的结论，不是前提。
//!
//! # 为什么现场要「先建再拆」
//!
//! 编辑器状态没有「加载一个 v1 场景文件」这条不依赖磁盘的路。因此现场用正式命令
//! 创建实例（唯一可信的摆法），再把站点**改回** v1 的表示：普通派生来源、删掉内层
//! 记录、删掉内层模板的子节点。改回去的正是 v1 落盘时文件里的样子，
//! 而实例根、确定性标识、记录版本这些外围事实全部由生产路径给出，不掺假。

use std::collections::BTreeMap;

use editor_core::command::编辑器命令;
use editor_core::prefab_catalog::预制件目录;
use editor_core::state::编辑器状态;
use scene_doc::document::{变换数据, 场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::prefab::{
    实体来源, 派生实体标识, 节点地址, 预制件实例记录, 预制件文档
};
use scene_doc::property::属性值;
use scene_doc::storage::迁移场景;

const 子弹路径文本: &str = "prefabs/子弹.prefab.ron";
const 枪路径文本: &str = "prefabs/枪.prefab.ron";

/// 解析预制件文件路径，测试里省掉逐个 `unwrap`。
fn 路径(文本: &str) -> 项目相对路径 {
    项目相对路径::解析(文本).expect("测试里的路径始终合法")
}

/// 只带类型名、不带属性的标记组件。
fn 标记组件(类型名: &str) -> 组件数据 {
    组件数据::新建(类型名, BTreeMap::new())
}

/// 带一组整数属性的组件。
fn 数值组件(类型名: &str, 字段名: &str, 值: i64) -> 组件数据 {
    let mut 属性 = BTreeMap::new();
    属性.insert(字段名.to_string(), 属性值::整数(值));
    组件数据::新建(类型名, 属性)
}

/**
 * 内层模板 `子弹`：根节点带 `精灵`，子节点 `弹头` 带 `碰撞体{半径:3}`。
 *
 * 返回 `(文档, 弹头)`；后者是模板场景里的实体标识，
 * 同时也是 B 命名空间里那条层内相对地址的段。
 */
fn 子弹模板() -> (预制件文档, 实体标识) {
    let mut 场景 = 场景文档::新建("子弹模板");
    let 根 = 场景.生成实体("子弹", None);
    场景
        .取可变(根)
        .expect("根必须存在")
        .加组件(标记组件("精灵"));
    let 弹头 = 场景.生成实体("弹头", Some(根));
    场景
        .取可变(弹头)
        .expect("弹头必须存在")
        .加组件(数值组件("碰撞体", "半径", 3));
    (预制件文档::新建("子弹", 根, 场景), 弹头)
}

/// 外层模板 `枪`：根下挂一个 `弹夹` 站点，站点带一份子弹内层实例记录。
fn 枪模板(内层: &预制件文档) -> (预制件文档, 实体标识) {
    let mut 场景 = 场景文档::新建("枪模板");
    let 枪根 = 场景.生成实体("枪", None);
    let 站点 = 场景.生成实体("弹夹", Some(枪根));
    场景
        .取可变(站点)
        .expect("站点必须存在")
        .加组件(标记组件("弹夹脚本"));
    let 站点记录 = 预制件实例记录::新建(内层.引用(路径(子弹路径文本)));
    场景.预制件实例表.insert(站点, 站点记录);
    (预制件文档::新建("枪", 枪根, 场景), 站点)
}

/**
 * 停在「迁移之前」的旧版现场。
 *
 * 字段字典：
 * * `编辑器` —— 目录里有两份模板、文档里有一份 v1 形态实例的完整编辑状态；
 * * `实例根` —— 最外层实例根，也就是外层记录的键；
 * * `站点地址` / `嵌套根` —— 站点的链式地址与该位置上那个实体的标识；
 * * `弹头标识` —— v1 场景里**不存在**、同步后必须被补出来的那个内层子节点；
 * * `弹头模板标识` —— `弹头` 在子弹模板里自己的标识，也就是那条层内相对地址
 *   的唯一一段。断言最外层命名空间里的地址时用它，而不是让测试记住一个数。
 */
struct 现场 {
    编辑器: 编辑器状态,
    实例根: 实体标识,
    站点地址: 节点地址,
    嵌套根: 实体标识,
    弹头标识: 实体标识,
    弹头模板标识: 实体标识,
}

/**
 * 建一份 v1 扁平现场：先按生产路径创建实例，再把站点改回 v1 的表示。
 *
 * 步骤：
 * 1. 造两份模板并塞进目录（目录是闭包快照的来源，同步与创建同路）；
 * 2. 正式命令创建实例，拿到 P4 形态；
 * 3. 站点来源改成 `预制件派生`、移除内层记录、删除内层子节点 ——
 *    `展开版本` 保持创建时写入的模板版本，正是 v1 文件里的值；
 * 4. 断言现场确实回到了 v1 形态，否则后面的测试只是在验证夹具。
 */
fn 建旧版现场() -> 现场 {
    let (内层, 弹头模板) = 子弹模板();
    let (外层, 站点) = 枪模板(&内层);

    let mut 编辑器 = 编辑器状态::新建();
    编辑器.预制件目录 = 预制件目录::从模板列表([内层.clone(), 外层.clone()]);

    let 实例根 = 编辑器
        .执行(编辑器命令::创建预制件实例 {
            模板: Box::new(外层.clone()),
            模板路径: 路径(枪路径文本),
            内层模板: 编辑器.预制件目录.嵌套模板集(&外层.头.标识),
            放置: 变换数据::单位(),
            父实体: None,
            指定实例根: None,
        })
        .expect("创建含嵌套内容的实例应当成功")
        .新实体
        .expect("创建命令必须带回实例根");

    let 站点地址 = 节点地址::根().追加(站点);
    let 嵌套根 = 派生实体标识(实例根, &站点地址);
    let 弹头标识 = 派生实体标识(实例根, &站点地址.追加(弹头模板));

    {
        let 文档 = &mut 编辑器.会话.文档;
        文档.取可变(嵌套根).expect("站点必须存在").来源 = 实体来源::预制件派生 {
            实例根,
            地址: 站点地址.clone(),
        };
        文档.预制件实例表.remove(&嵌套根);
        文档.删除实体(弹头标识);
    }

    let 文档 = &编辑器.会话.文档;
    assert!(
        matches!(
            文档.取(嵌套根).expect("站点必须存在").来源,
            实体来源::预制件派生 { .. }
        ),
        "站点必须已经改回 v1 的普通派生表示"
    );
    assert!(
        !文档.预制件实例表.contains_key(&嵌套根),
        "v1 现场不该有内层记录"
    );
    assert!(!文档.存在(弹头标识), "v1 现场的内层子节点整批缺失");

    现场 {
        编辑器,
        实例根,
        站点地址,
        嵌套根,
        弹头标识,
        弹头模板标识: 弹头模板,
    }
}

/**
 * v1 实例记录迁移后被标成待重展，且已是当前版本的文件不会被二次迁移重标。
 */
#[test]
fn 旧版实例记录迁移后被标成待重展() {
    let mut 台 = 建旧版现场();
    assert_eq!(
        台.编辑器.会话.文档.预制件实例表[&台.实例根].展开版本, 1,
        "夹具摆的是 v1 落盘时的『已展开』状态"
    );

    let 改动 = 迁移场景(&mut 台.编辑器.会话.文档, 1);
    assert_eq!(改动, 1, "一份实例记录被重标");
    assert_eq!(
        台.编辑器.会话.文档.格式版本,
        scene_doc::document::当前格式版本,
        "升级后的文档下一次保存直接落成新版文件"
    );
    let 记录 = &台.编辑器.会话.文档.预制件实例表[&台.实例根];
    assert_eq!(记录.展开版本, 0, "v1 的『已展开』在嵌套引擎下不成立");
    assert!(记录.待同步(), "只有标成待同步，用户才知道要按一次同步");

    let 再改动 = 迁移场景(&mut 台.编辑器.会话.文档, 2);
    assert_eq!(再改动, 0, "已是当前版本的文件不该被二次迁移重标");
    assert_eq!(
        台.编辑器.会话.文档.预制件实例表[&台.实例根].展开版本, 0,
        "第二次迁移必须一字不改"
    );
}

/**
 * 用户点一次同步：扁平站点升成嵌套实例根，内层记录建出来，缺失的子节点补齐。
 *
 * 这是迁移承诺的另一半 —— 「标成待同步」只是提示，真正让旧场景重新完整的是
 * 现有的递归展开。这里刻意不新增任何「升级专用」的写入代码：同步走的就是
 * 创建时那条 `规划 + 提交`，旧场景因此不需要第二套迁移逻辑。
 */
#[test]
fn 迁移后同步补齐嵌套结构与内层记录() {
    let mut 台 = 建旧版现场();
    迁移场景(&mut 台.编辑器.会话.文档, 1);

    let 结果 = 台
        .编辑器
        .同步预制件实例(台.实例根)
        .expect("迁移后的实例应当能同步");
    let 汇总 = 结果.预制件同步.expect("同步命令必须带回聚合统计");
    assert_eq!(汇总.同步实例, 1);
    assert_eq!(汇总.内层实例, 1, "站点这次真的被当成一份内层实例展开");
    assert!(
        汇总.新建节点 >= 1,
        "v1 缺失的内层子节点必须被补出来，实际新建 {}",
        汇总.新建节点
    );
    assert_eq!(汇总.忽略覆盖, 0);
    assert!(
        汇总.降级.is_empty(),
        "闭包里有子弹模板，不该出现降级告警：{:?}",
        汇总.降级
    );

    let 文档 = &台.编辑器.会话.文档;
    assert_eq!(
        文档.取(台.嵌套根).expect("站点必须存在").来源,
        实体来源::预制件嵌套实例根 {
            实例根: 台.实例根,
            站点: 台.站点地址.clone(),
        },
        "站点必须从普通派生节点升成嵌套实例根"
    );
    let 内层记录 = 文档
        .预制件实例表
        .get(&台.嵌套根)
        .expect("内层记录必须在同步后存在");
    assert_eq!(
        内层记录.展开版本, 内层记录.模板.版本,
        "内层记录推进到当前模板版本"
    );
    let 弹头实体 = 文档.取(台.弹头标识).expect("内层子节点必须被补齐");
    assert_eq!(弹头实体.父实体, Some(台.嵌套根), "补齐的弹头挂在嵌套根下面");
    assert_eq!(
        弹头实体.来源,
        实体来源::预制件派生 {
            实例根: 台.实例根,
            地址: 台.站点地址.追加(台.弹头模板标识),
        },
        "内层子节点的地址仍然写在最外层命名空间里"
    );
    assert_eq!(
        文档.预制件实例表[&台.实例根].展开版本, 1,
        "外层记录同样推进到已展开"
    );
}
