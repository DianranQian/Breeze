/**
 * 拖动**没有 `Transform` 组件**的派生节点：位置照样要写成层内覆盖，同步后必须存活。
 *
 * 这条守的是真实编辑器的形态：Inspector 与拖动操纵器写的都是
 * `场景实体.变换` 一等字段，而本仓库自己模板化出来的节点通常不带 `Transform`
 * 组件。若登记覆盖时要求组件存在，拖动派生节点就「什么都没写」——
 * 下一次同步按模板原值把位置还原，`恢复该项默认值` 也永远不出现，
 * 用户看到的症状是"改好了，一同步就弹回去"。函数级单测拿带组件的夹具跑，
 * 恰好照不到这一面，所以这里从命令一路验到同步之后。
 *
 * 三段断言各管一件事：写入（内层记录 + 层内相对地址）、落点（一等字段，
 * 不顺手造组件）、存活（重铺模板内容后新位置仍在，未覆盖字段跟随新模板）。
 */
#[test]
fn 拖动无变换组件的派生节点位置写层内覆盖且同步后存活() {
    let mut 台 = 建夹具();
    let 弹头 = 派生实体标识(台.实例根, &台.弹头链地址);
    assert!(
        台.编辑器
            .会话
            .文档
            .取(弹头)
            .expect("弹头必须已物化")
            .取组件("Transform")
            .is_none(),
        "夹具必须保持真实形态：弹头只有一等字段 `变换`，没有 `Transform` 组件"
    );

    let 新位置 = 变换数据 {
        平移: (4.0, 5.0, 6.0),
        ..变换数据::单位()
    };
    台.编辑器
        .执行(编辑器命令::设变换 {
            标识: 弹头,
            变换: Some(新位置),
        })
        .expect("改派生节点变换应当成功");

    let 文档 = &台.编辑器.会话.文档;
    assert_eq!(
        文档.预制件实例表[&台.嵌套根].覆盖.取动作(&字段键(
            台.弹头层内地址.clone(),
            "Transform",
            "translation"
        )),
        Some(&覆盖动作::设值(属性值::三维(4.0, 5.0, 6.0))),
        "位置必须按层内相对地址写进内层记录"
    );
    assert!(
        文档.预制件实例表[&台.实例根].覆盖.是空(),
        "外层记录不该收到这份属于内层的改动"
    );
    let 弹头实体 = 文档.取(弹头).expect("弹头必须存在");
    assert_eq!(
        弹头实体.变换,
        Some(新位置),
        "覆盖登记的同一帧，实体上必须真的能看到新位置"
    );
    assert!(
        弹头实体.取组件("Transform").is_none(),
        "登记覆盖不该顺手给节点造一个模板里没有的组件"
    );

    let 二版 = 升级到二版(&台.内层);
    换内层版本(&mut 台, 二版.clone());
    let 结果 = 台
        .编辑器
        .同步预制件实例(台.实例根)
        .expect("同步最外层实例应当成功");
    let 汇总 = 结果.预制件同步.expect("同步命令必须带回聚合统计");
    assert_eq!(
        汇总.忽略覆盖, 0,
        "变换覆盖必须真的被应用，而不是因为组件不存在被忽略掉"
    );

    let 同步后 = &台.编辑器.会话.文档;
    let 弹头实体 = 同步后.取(弹头).expect("弹头必须存在");
    assert_eq!(
        弹头实体.变换,
        Some(新位置),
        "同步整棵重铺了模板内容，用户拖出来的位置必须由覆盖挡住"
    );
    assert_eq!(
        取属性(弹头实体, "碰撞体", "硬度"),
        Some(属性值::整数(9)),
        "位置被覆盖挡住不代表别的字段也不同步：未覆盖字段必须跟随 v2"
    );
    assert!(
        同步后.预制件实例表[&台.实例根].覆盖.是空(),
        "同步同样不该往外层记录补写覆盖"
    );
}

