    台.编辑器
        .恢复预制件字段默认值(弹头, "碰撞体", "硬度")
        .expect("恢复已覆盖的字段应当成功");

    let 文档 = &台.编辑器.会话.文档;
    let 内层记录 = &文档.预制件实例表[&台.嵌套根];
