//! 中文名：预制件脱钩处理闭环
//!
//! 验证 P3 引入的脱钩冲突处理路径：
//!
//! ```text
//! 同步到 v2（模板删掉两枝）→ 两枝脱钩（本地保留）
//!   → 重新纳入某一枝：清可比条目 → 物化 → 来源改回「预制件派生」
//!   → 兄弟枝条的脱钩状态与来源原样保留
//!   → 撤销/重做逐字段复现
//!
//! 模板当前版本里没有该节点 → 重新纳入被拒绝 → 文档与撤销栈零变化
//!
//! 彻底删除本地副本（删除实体命令）
//!   → 尚未脱钩的派生节点：记入 `已删节点` → 后续同步不复活
//!   → 已脱钩的本地节点：它的脱钩条目被清理 → 不再出现在脱钩表里
//! ```
//!
//! # 为什么用「两枝 + 一棵子树」的结构
//!
//! 「重新纳入」的语义是「清除与目标地址可比的条目」：目标自身、祖先链、
//! 整棵子树。单枝条的模板无法同时验证「祖先被清」与「兄弟被保留」，
//! 因此模板固定为：根 → 挂点 → 炮塔（子树），以及根 → 装饰（兄弟枝条）。
//!
//! # 为什么撤销/重做用整份文档相等
//!
//! 一次重新纳入同时改动实体来源、实例记录的版本/指纹/脱钩集合与内部
//! 次序。`场景文档` 实现了 `PartialEq`，整份比较能一次覆盖所有字段，
//! 不会出现「版本回退了但脱钩集合没回退」这类隐蔽残留。

use std::collections::{BTreeMap, BTreeSet};

use editor_core::command::编辑器命令;
use editor_core::state::编辑器状态;
use scene_doc::document::{变换数据, 场景实体, 场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::prefab::{
    实体来源, 派生实体标识, 节点地址, 预制件文档, 预制件标识
};
use scene_doc::property::属性值;

/**
 * 造出与模板配套的嵌套闭包快照。
 *
 * 生产路径由 `预制件目录::嵌套模板集` 生成，至少要含外层模板自身；
 * 本文件的模板都不挂内层实例，所以闭包只有外层这一条。
 */
fn 闭包(模板: &预制件文档) -> BTreeMap<预制件标识, 预制件文档> {
    [(模板.头.标识, 模板.clone())].into_iter().collect()
}

/**
 * 测试用的装配体模板：根 → 挂点 → 炮塔，以及根 → 装饰。
 *
 * 记录各节点实体标识是为了让测试能随时算出节点地址与派生实体标识；
 * 模板标识与根 UUID 在升级版本时必须原样保留，否则派生地址整体漂移，
 * 实例记录里的脱钩集合会指向不存在的节点。
 */
struct 装配体模板 {
    文档: 预制件文档,
    挂点: 实体标识,
    炮塔: 实体标识,
    装饰: 实体标识,
}

/// 把实体标识链拼成节点地址。
fn 地址路径(段: &[实体标识]) -> 节点地址 {
    let mut 地址 = 节点地址::根();
    for 标识 in 段 {
        地址 = 地址.追加(*标识);
    }
    地址
}

/// 造一份版本 1 的装配体模板。
fn 造装配体模板() -> 装配体模板 {
    let mut 场景 = 场景文档::新建("装配体模板");
    let 根 = 场景.生成实体("装配体", None);
    let 挂点 = 场景.生成实体("挂点", Some(根));
    let 炮塔 = 场景.生成实体("炮塔", Some(挂点));
    let 装饰 = 场景.生成实体("装饰", Some(根));

    let mut 装甲属性 = BTreeMap::new();
    装甲属性.insert("护甲".to_string(), 属性值::整数(10));
    场景
        .取可变(根)
        .expect("模板根必须存在")
        .加组件(组件数据::新建("装甲", 装甲属性));

    let mut 武器属性 = BTreeMap::new();
    武器属性.insert("伤害".to_string(), 属性值::整数(5));
    场景
        .取可变(炮塔)
        .expect("炮塔必须存在")
        .加组件(组件数据::新建("武器", 武器属性));

    let 文档 = 预制件文档::新建("装配体", 根, 场景);
    装配体模板 {
        文档,
        挂点,
        炮塔,
        装饰,
    }
}

impl 装配体模板 {
    /// 挂点节点的地址（根的直接子节点）。
    fn 挂点地址(&self) -> 节点地址 {
        地址路径(&[self.挂点])
    }

    /// 炮塔节点的地址（挂在挂点之下）。
    fn 炮塔地址(&self) -> 节点地址 {
        地址路径(&[self.挂点, self.炮塔])
    }

    /// 装饰节点的地址（挂点的兄弟）。
    fn 装饰地址(&self) -> 节点地址 {
        地址路径(&[self.装饰])
    }
}

/**
 * 把一版模板升级成二版：删掉挂点（含炮塔）与装饰两枝。
 *
 * 两枝同时删除是为了让同步后的脱钩集合同时包含「子树根」「子树内部」
 * 「兄弟枝条」三类条目，后续重新纳入才能验证「可比条目被清、不可比
 * 条目保留」。
 */
fn 删除两枝(一版: &装配体模板) -> 预制件文档 {
    let mut 二版 = 一版.文档.clone();
    二版.头.版本 = 2;
    二版.场景.删除实体(一版.挂点);
    二版.场景.删除实体(一版.装饰);
    二版
}

/**
 * 把模板升级成三版：恢复 v1 的完整结构，仅推进版本号。
 *
 * 恢复的节点沿用 v1 的 UUID，因此派生地址与脱钩集合里的记录完全吻合 ——
 * 这正是「模板重新加回了这个节点」在数据层的样子。
 */
fn 恢复全枝(一版: &装配体模板) -> 预制件文档 {
    let mut 三版 = 一版.文档.clone();
    三版.头.版本 = 3;
    三版
}

/**
 * 通过正式命令创建一个实例，返回实例根标识。
 *
 * 不手工往实例表里塞记录：创建命令负责建立所有权清单、放置与首次物化，
 * 后续同步与重新纳入必须能在真实创建出来的实例上工作。
 */
fn 创建实例(编辑器: &mut 编辑器状态, 模板: &预制件文档) -> 实体标识 {
    编辑器
        .执行(编辑器命令::创建预制件实例 {
            模板: Box::new(模板.clone()),
            模板路径: 装配体路径(),
            放置: 变换数据 {
                平移: (1.0, 2.0, 0.0),
                ..变换数据::单位()
            },
            父实体: None,
            指定实例根: None,
            内层模板: 闭包(模板),
        })
        .expect("创建实例应当成功")
        .新实体
        .expect("命令结果必须带回新实例根")
}

/// 读取组件属性的副本，避免在断言里反复展开 `Option` 链。
fn 取属性(实体: &场景实体, 组件名: &str, 属性名: &str) -> Option<属性值> {
    实体.取组件(组件名)?.属性.get(属性名).cloned()
}

/// 装配体模板文件的项目相对路径。
fn 装配体路径() -> 项目相对路径 {
    项目相对路径::解析("prefabs/装配体.prefab.ron").expect("模板路径应当合法")
}

#[test]
fn 重新纳入祖先链上的脱钩节点会连同整枝回到模板管理() {
    let 一版 = 造装配体模板();
    let 二版 = 删除两枝(&一版);
    let 三版 = 恢复全枝(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版.文档);

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: vec![实例根],
            内层模板: 闭包(&二版),
        })
        .expect("同步到 v2 应当成功");

    let 挂点地址 = 一版.挂点地址();
    let 炮塔地址 = 一版.炮塔地址();
    let 装饰地址 = 一版.装饰地址();
    let 挂点实体 = 派生实体标识(实例根, &挂点地址);
    let 炮塔实体 = 派生实体标识(实例根, &炮塔地址);
    let 装饰实体 = 派生实体标识(实例根, &装饰地址);

    let 记录 = 编辑器
        .会话
        .文档
        .预制件实例表
        .get(&实例根)
        .expect("实例记录必须存在");
    assert_eq!(
        记录.脱钩节点,
        BTreeSet::from([挂点地址.clone(), 炮塔地址.clone(), 装饰地址.clone()]),
        "v2 删掉的两枝及其子树都应进入脱钩集合"
    );
    for 实体 in [挂点实体, 炮塔实体, 装饰实体] {
        assert_eq!(
            编辑器
                .会话
                .文档
                .取(实体)
                .expect("脱钩节点不能从场景消失")
                .来源,
            实体来源::本地,
            "脱钩节点归用户所有，来源必须改成本地"
        );
    }

    let 纳入前 = 编辑器.会话.文档.clone();
    let 结果 = 编辑器
        .执行(编辑器命令::重新纳入预制件节点 {
            模板: Box::new(三版.clone()),
            实例根,
            记录键: 实例根,
            地址: 炮塔地址.clone(),
            内层模板: 闭包(&三版),
        })
        .expect("模板已恢复该节点，重新纳入应当成功");

    let 汇总 = 结果.预制件同步.expect("重新纳入必须带回聚合统计");
    assert_eq!(汇总.同步实例, 1);
    assert_eq!(
        汇总.更新节点, 3,
        "根、挂点、炮塔各刷新一次；装饰不在被纳入的枝条里"
    );
    assert_eq!(汇总.新建节点, 0, "实体都还在场景里，只是改回派生来源");
    assert_eq!(汇总.脱钩节点, 0, "被纳入的枝条不再计入脱钩");
    assert_eq!(汇总.忽略覆盖, 0);

    let 影响: BTreeSet<实体标识> = 结果.影响实体.iter().copied().collect();
    assert_eq!(
        影响,
        BTreeSet::from([挂点实体, 炮塔实体]),
        "影响实体是整条被清除的链条（挂点 + 其子树）"
    );

    let 文档 = &编辑器.会话.文档;
    assert_eq!(
        文档.取(挂点实体).expect("挂点必须存在").来源,
        实体来源::预制件派生 {
            实例根,
            地址: 挂点地址.clone(),
        },
        "祖先链条上的脱钩条目被清除后，挂点必须回到模板管理"
    );
    assert_eq!(
        文档.取(炮塔实体).expect("炮塔必须存在").来源,
        实体来源::预制件派生 {
            实例根,
            地址: 炮塔地址.clone(),
        },
        "目标节点自身的来源必须改回预制件派生"
    );
    assert_eq!(
        文档.取(装饰实体).expect("装饰必须存在").来源,
        实体来源::本地,
        "兄弟枝条的脱钩状态必须原样保留"
    );
    assert_eq!(
        取属性(文档.取(炮塔实体).expect("炮塔必须存在"), "武器", "伤害"),
        Some(属性值::整数(5)),
        "重新纳入后组件内容来自模板"
    );

    let 记录 = &文档.预制件实例表[&实例根];
    assert_eq!(
        记录.脱钩节点,
        BTreeSet::from([装饰地址]),
        "只保留与目标地址不可比的兄弟条目"
    );
    assert_eq!(记录.模板.版本, 3, "记录的目标版本必须推进");
    assert_eq!(记录.展开版本, 3, "实体树已按 v3 展开");
    assert_eq!(
        记录.模板.内容指纹,
        三版.内容指纹(),
        "指纹必须随版本一起推进，否则下次加载会误报外部手改"
    );

    let 纳入后 = 编辑器.会话.文档.clone();
    assert!(编辑器.撤销一步(), "重新纳入必须是一条可撤销记录");
    assert_eq!(
        编辑器.会话.文档, 纳入前,
        "撤销必须把来源、脱钩集合与版本一起还原"
    );
    assert!(编辑器.重做一步());
    assert_eq!(编辑器.会话.文档, 纳入后, "重做必须逐字段复现纳入结果");
}

#[test]
fn 模板里没有该节点时拒绝重新纳入且不留痕迹() {
    let 一版 = 造装配体模板();
    let 二版 = 删除两枝(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版.文档);

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: vec![实例根],
            内层模板: 闭包(&二版),
        })
        .expect("同步到 v2 应当成功");

    let 失败前 = 编辑器.会话.文档.clone();
    let 错误 = 编辑器
        .执行(编辑器命令::重新纳入预制件节点 {
            模板: Box::new(二版.clone()),
            实例根,
            记录键: 实例根,
            地址: 一版.炮塔地址(),
            内层模板: 闭包(&二版),
        })
        .expect_err("模板仍没有该节点，重新纳入必须被拒绝");
    assert!(
        format!("{错误}").contains("无法重新纳入"),
        "错误信息必须说明这是重新纳入失败：{错误}"
    );

    assert_eq!(
        编辑器.会话.文档, 失败前,
        "失败不留痕迹：脱钩集合与文档必须逐字段不变"
    );
    assert!(编辑器.撤销一步(), "先撤销同步");
    assert!(编辑器.撤销一步(), "再撤销实例创建");
    assert!(
        !编辑器.撤销一步(),
        "失败的命令不得进入撤销栈：撤回两条之后栈必须已空"
    );
}

#[test]
fn 彻底删除派生节点会记入已删集合并阻止同步复活() {
    let 一版 = 造装配体模板();
    let 三版 = 恢复全枝(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版.文档);

    let 炮塔地址 = 一版.炮塔地址();
    let 炮塔实体 = 派生实体标识(实例根, &炮塔地址);

    编辑器
        .执行(编辑器命令::删除实体 {
            标识: 炮塔实体
        })
        .expect("删除派生节点应当成功");

    assert!(
        !编辑器.会话.文档.存在(炮塔实体),
        "彻底删除必须真的移除实体，而不是脱钩"
    );
    let 记录 = &编辑器.会话.文档.预制件实例表[&实例根];
    assert!(
        记录.已删节点.contains(&炮塔地址),
        "派生节点被删除后必须记入已删集合，否则下一次同步会把它复活"
    );

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(三版.clone()),
            实例根: vec![实例根],
            内层模板: 闭包(&三版),
        })
        .expect("同步应当成功");

    assert!(
        !编辑器.会话.文档.存在(炮塔实体),
        "已删集合优先于模板结构：同步不得复活被彻底删除的节点"
    );
    let 记录 = &编辑器.会话.文档.预制件实例表[&实例根];
    assert_eq!(记录.展开版本, 3, "其余节点的同步照常推进");
}

#[test]
fn 彻底删除脱钩节点会清理它的脱钩条目() {
    let 一版 = 造装配体模板();
    let 二版 = 删除两枝(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版.文档);

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: vec![实例根],
            内层模板: 闭包(&二版),
        })
        .expect("同步到 v2 应当成功");

    let 挂点地址 = 一版.挂点地址();
    let 炮塔地址 = 一版.炮塔地址();
    let 装饰地址 = 一版.装饰地址();
    let 炮塔实体 = 派生实体标识(实例根, &炮塔地址);

    编辑器
        .执行(编辑器命令::删除实体 {
            标识: 炮塔实体
        })
        .expect("删除脱钩节点应当成功");

    let 记录 = &编辑器.会话.文档.预制件实例表[&实例根];
    assert_eq!(
        记录.脱钩节点,
        BTreeSet::from([挂点地址, 装饰地址]),
        "被删除实体自身的脱钩条目必须清理；祖先与兄弟的条目保留"
    );
    assert!(
        !记录.已删节点.contains(&炮塔地址),
        "本地节点没有被模板解释，不需要记入已删集合"
    );

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: vec![实例根],
            内层模板: 闭包(&二版),
        })
        .expect("再次同步应当成功");
    assert!(
        !编辑器.会话.文档.存在(炮塔实体),
        "脱钩枝条内的节点被删除后，同步不得复活它"
    );
}
