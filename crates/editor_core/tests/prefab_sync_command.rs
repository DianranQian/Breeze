//! 中文名：预制件同步命令闭环
//!
//! 验证用户最关心的那条链路：
//!
//! ```text
//! 模板 v1 创建实例
//!   → 模板改成 v2（改字段 + 删子节点）
//!   → 执行 `同步预制件实例`
//!   → 未覆盖字段跟随 v2、覆盖字段保持实例值、被删节点脱钩而非销毁
//!   → 撤销：整份文档回到 v1 的实例状态
//!   → 重做：整份文档逐字段复现同步结果
//! ```
//!
//! # 为什么用整份文档相等来验证撤销/重做
//!
//! 一次同步会同时改动实例根组件、派生节点来源、实例记录的版本/指纹/
//! 脱钩集合，以及内部次序。逐项抽查很容易漏掉"版本回退了但指纹没回退"
//! 这类隐蔽残留；`场景文档` 实现了 `PartialEq`，整份比较能一次性覆盖
//! 所有字段。
//!
//! # 批量语义
//!
//! `同步预制件实例` 的 `实例根` 为空表示"引用该模板的全部实例"。模板文件
//! 更新后用户通常想一次同步整个关卡，而不是逐个点；空列表就是这条常用
//! 路径，因此单独测一遍。
//!
//! # 事务边界
//!
//! 命令逐实例调用 `物化实例`，跨实例的预检失败必须整批回滚，不能留下
//! "第一个实例已经改了、第二个才报错"的半成品。撤销栈的步数也不能增加。

use std::collections::BTreeMap;

use editor_core::command::编辑器命令;
use editor_core::prefab_catalog::{预制件告警, 预制件目录};
use editor_core::state::编辑器状态;
use scene_doc::document::{变换数据, 场景实体, 场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::prefab::{
    实体来源, 派生实体标识, 节点地址, 覆盖键, 路径段, 预制件文档
};
use scene_doc::property::属性值;

/**
 * 造一份版本 1 的模板：根节点带 `移动`，子节点带 `武器`。
 *
 * 根组件里放两个标量字段（`速度` / `生命`），是为了让"覆盖一个字段、
 * 另一个字段跟随模板"能在同一组件内被明确验证。子节点则用于验证
 * v2 删除节点后的脱钩行为。
 */
fn 造模板一版() -> 预制件文档 {
    let mut 场景 = 场景文档::新建("敌人模板");
    let 根 = 场景.生成实体("敌人", None);
    let 子 = 场景.生成实体("武器", Some(根));

    let mut 移动属性 = BTreeMap::new();
    移动属性.insert("速度".to_string(), 属性值::整数(1));
    移动属性.insert("生命".to_string(), 属性值::整数(10));
    场景
        .取可变(根)
        .expect("模板根必须存在")
        .加组件(组件数据::新建("移动", 移动属性));

    let mut 武器属性 = BTreeMap::new();
    武器属性.insert("伤害".to_string(), 属性值::整数(5));
    场景
        .取可变(子)
        .expect("模板子节点必须存在")
        .加组件(组件数据::新建("武器", 武器属性));

    预制件文档::新建("敌人", 根, 场景)
}

/**
 * 取模板根的唯一直接子节点。
 *
 * 模板固定只有一个子节点；下标越界时 panic 正好提醒"模板结构变了，
 * 测试断言也要同步"。
 */
fn 子节点(模板: &预制件文档) -> 实体标识 {
    模板
        .场景
        .子实体列表(Some(模板.头.根))
        .first()
        .copied()
        .expect("模板应当有一个直接子节点")
}

/**
 * 把一版模板升级成二版：改两个字段，并删掉子节点。
 *
 * `速度` 与 `生命` 都改值，配合实例上的 `速度` 覆盖，可以同时验证
 * "覆盖字段保留、未覆盖字段更新"。删除子节点则触发无损脱钩。
 *
 * 模板标识与根节点 UUID 必须原样保留，否则物化算出的派生地址会整体
 * 漂移，实例记录里的覆盖与脱钩集合将指向不存在的节点。
 */
fn 升级到二版(一版: &预制件文档) -> 预制件文档 {
    let mut 二版 = 一版.clone();
    二版.头.版本 = 2;
    let 根 = 二版.头.根;
    let 移动 = 二版
        .场景
        .取可变(根)
        .expect("模板根必须存在")
        .取组件可变("移动")
        .expect("模板根应当带移动组件");
    移动.属性.insert("速度".to_string(), 属性值::整数(2));
    移动.属性.insert("生命".to_string(), 属性值::整数(20));

    let 子 = 子节点(&二版);
    二版.场景.删除实体(子);
    二版
}

/// 造一份与敌人模板无关的模板，用于验证批量同步不会误伤其它实例。
fn 造无关模板() -> 预制件文档 {
    let mut 场景 = 场景文档::新建("道具模板");
    let 根 = 场景.生成实体("道具", None);
    预制件文档::新建("道具", 根, 场景)
}

/**
 * 通过正式命令创建一个实例，返回实例根标识。
 *
 * 测试刻意不手工往实例表里塞记录：创建命令负责建立所有权清单、放置与
 * 首次物化，后续同步必须能在"真实创建出来的实例"上工作。
 */
fn 创建实例(
    编辑器: &mut 编辑器状态,
    模板: &预制件文档,
    模板路径: &项目相对路径,
) -> 实体标识 {
    编辑器
        .执行(编辑器命令::创建预制件实例 {
            模板: Box::new(模板.clone()),
            模板路径: 模板路径.clone(),
            放置: 变换数据 {
                平移: (3.0, 4.0, 0.0),
                ..变换数据::单位()
            },
            父实体: None,
            指定实例根: None,
        })
        .expect("创建实例应当成功")
        .新实体
        .expect("命令结果必须带回新实例根")
}

/// 读取组件属性的副本，避免在断言里反复展开 `Option` 链。
fn 取属性(实体: &场景实体, 组件名: &str, 属性名: &str) -> Option<属性值> {
    实体.取组件(组件名)?.属性.get(属性名).cloned()
}

/// 敌人模板文件的项目相对路径。
fn 敌人路径() -> 项目相对路径 {
    项目相对路径::解析("prefabs/敌人.prefab.ron").expect("模板路径应当合法")
}

/// 道具模板文件的项目相对路径。
fn 道具路径() -> 项目相对路径 {
    项目相对路径::解析("prefabs/道具.prefab.ron").expect("模板路径应当合法")
}

#[test]
fn 同步保留覆盖并脱钩被删节点且可撤销重做() {
    let 一版 = 造模板一版();
    let 二版 = 升级到二版(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版, &敌人路径());

    let 子地址 = 节点地址::根().追加(子节点(&一版));
    let 子 = 派生实体标识(实例根, &子地址);

    编辑器
        .会话
        .文档
        .预制件实例表
        .get_mut(&实例根)
        .expect("创建命令必须写入实例记录")
        .覆盖
        .设值(
            覆盖键::含字段(
                节点地址::根(),
                "移动",
                vec![路径段::字段("速度".to_string())],
            ),
            属性值::整数(99),
        );

    let 同步前 = 编辑器.会话.文档.clone();

    let 结果 = 编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: vec![实例根],
        })
        .expect("同步应当成功");

    let 汇总 = 结果.预制件同步.expect("同步命令必须带回聚合统计");
    assert_eq!(汇总.同步实例, 1);
    assert_eq!(
        汇总.更新节点, 1,
        "根节点被刷新一次；子节点已从模板删除，因此不算更新"
    );
    assert_eq!(汇总.脱钩节点, 1, "模板删除的子节点必须脱钩而不是销毁");
    assert_eq!(汇总.应用覆盖, 1);
    assert_eq!(汇总.忽略覆盖, 0, "覆盖目标仍然存在，不应被忽略");
    assert_eq!(汇总.冲突数(), 1, "脱钩节点属于需要用户确认的冲突");

    let 同步后 = 编辑器.会话.文档.clone();
    let 根实体 = 同步后.取(实例根).expect("实例根必须存在");
    assert_eq!(
        取属性(根实体, "移动", "速度"),
        Some(属性值::整数(99)),
        "被覆盖的字段必须保留实例值，不能被模板新值冲掉"
    );
    assert_eq!(
        取属性(根实体, "移动", "生命"),
        Some(属性值::整数(20)),
        "未覆盖字段必须接收模板 v2 的新值"
    );

    let 子实体 = 同步后.取(子).expect("模板删除的节点不能在场景里消失");
    assert_eq!(
        子实体.来源,
        实体来源::本地,
        "脱钩后节点归用户所有，来源必须改成本地"
    );
    assert_eq!(
        子实体.父实体,
        Some(实例根),
        "脱钩不得改变节点在场景里的位置"
    );
    assert_eq!(
        取属性(子实体, "武器", "伤害"),
        Some(属性值::整数(5)),
        "脱钩节点的内容必须原样保留"
    );

    let 记录 = &同步后.预制件实例表[&实例根];
    assert_eq!(记录.模板.版本, 2, "记录的目标版本必须推进");
    assert_eq!(记录.展开版本, 2, "实体树已展开到 v2");
    assert_eq!(
        记录.模板.内容指纹,
        二版.内容指纹(),
        "指纹必须随版本一起推进，否则下次加载会误报外部手改"
    );
    assert!(记录.脱钩节点.contains(&子地址));

    let 目录 = 预制件目录::从模板列表([二版.clone()]);
    let 状态 = 目录.实例状态(记录);
    assert!(!状态.待同步, "同步之后不应再显示待同步");
    assert!(状态.有覆盖, "覆盖并不会因为同步而消失");
    assert!(!状态.指纹不一致);

    assert!(编辑器.撤销一步(), "同步必须是一条可撤销记录");
    assert_eq!(
        编辑器.会话.文档, 同步前,
        "撤销必须把版本、组件、来源与脱钩集合一起还原到 v1 状态"
    );

    assert!(编辑器.重做一步(), "撤销之后必须能重做");
    assert_eq!(编辑器.会话.文档, 同步后, "重做必须逐字段复现同步结果");
}

#[test]
fn 空目标列表同步该模板的全部实例且不误伤其它模板() {
    let 一版 = 造模板一版();
    let 二版 = 升级到二版(&一版);
    let 无关模板 = 造无关模板();
    let mut 编辑器 = 编辑器状态::新建();
    let 甲 = 创建实例(&mut 编辑器, &一版, &敌人路径());
    let 乙 = 创建实例(&mut 编辑器, &一版, &敌人路径());
    let 丙 = 创建实例(&mut 编辑器, &无关模板, &道具路径());

    编辑器
        .会话
        .文档
        .预制件实例表
        .get_mut(&甲)
        .expect("甲实例记录存在")
        .覆盖
        .设值(
            覆盖键::含字段(
                节点地址::根(),
                "移动",
                vec![路径段::字段("生命".to_string())],
            ),
            属性值::整数(777),
        );

    let 结果 = 编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: Vec::new(),
        })
        .expect("空目标列表表示批量同步，应当成功");

    let 汇总 = 结果.预制件同步.expect("同步命令必须带回聚合统计");
    assert_eq!(汇总.同步实例, 2, "只同步引用该模板的实例");
    assert_eq!(汇总.更新节点, 2, "两个实例的根节点各刷新一次");
    assert_eq!(汇总.脱钩节点, 2, "两个实例的子节点都被模板删除");
    assert_eq!(汇总.应用覆盖, 1, "只有甲实例带覆盖");
    assert_eq!(汇总.冲突数(), 2);

    let 文档 = &编辑器.会话.文档;
    assert_eq!(文档.预制件实例表[&甲].展开版本, 2);
    assert_eq!(文档.预制件实例表[&乙].展开版本, 2);
    assert_eq!(
        文档.预制件实例表[&丙].展开版本, 无关模板.头.版本,
        "其它模板的实例不能被批量同步牵连"
    );
    assert_eq!(
        取属性(文档.取(甲).expect("甲实例根"), "移动", "生命"),
        Some(属性值::整数(777))
    );
    assert_eq!(
        取属性(文档.取(乙).expect("乙实例根"), "移动", "生命"),
        Some(属性值::整数(20)),
        "没有覆盖的实例必须完整接收模板 v2"
    );
    assert_eq!(
        文档.取(丙).expect("丙实例根").来源,
        实体来源::预制件实例根 { 实例根: 丙 },
        "未同步的实例仍属于它自己的模板"
    );
}

#[test]
fn 跨实例预检失败时整批回滚() {
    let 一版 = 造模板一版();
    let 二版 = 升级到二版(&一版);
    let 无关模板 = 造无关模板();
    let mut 编辑器 = 编辑器状态::新建();
    let 甲 = 创建实例(&mut 编辑器, &一版, &敌人路径());
    let 乙 = 创建实例(&mut 编辑器, &无关模板, &道具路径());

    let 失败前 = 编辑器.会话.文档.clone();
    let 步数 = 编辑器.可撤销步数();

    let 结果 = 编辑器.执行(编辑器命令::同步预制件实例 {
        模板: Box::new(二版),
        实例根: vec![甲, 乙],
    });

    assert!(
        结果.is_err(),
        "目标列表混入其它模板的实例时，必须在写入前整批拒绝"
    );
    assert_eq!(
        编辑器.会话.文档, 失败前,
        "失败的命令不能留下'第一个实例已同步'的半成品"
    );
    assert_eq!(编辑器.可撤销步数(), 步数, "失败的同步不能进历史");
}

#[test]
fn 同步后指纹一致而同版本手改会被识别() {
    let 一版 = 造模板一版();
    let 二版 = 升级到二版(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版, &敌人路径());

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版.clone()),
            实例根: vec![实例根],
        })
        .expect("同步应当成功");

    let 目录 = 预制件目录::从模板列表([二版.clone()]);
    let 记录 = &编辑器.会话.文档.预制件实例表[&实例根];
    let 状态 = 目录.实例状态(记录);
    assert!(
        !状态.待同步 && !状态.指纹不一致,
        "刚同步完的记录必须与模板版本、指纹都一致"
    );
    assert!(
        目录.检查(&编辑器.会话.文档).is_empty(),
        "一致状态下不应产生任何告警"
    );

    let mut 手改 = 二版;
    手改
        .场景
        .取可变(手改.头.根)
        .expect("模板根存在")
        .取组件可变("移动")
        .expect("移动组件存在")
        .属性
        .insert("生命".to_string(), 属性值::整数(999));
    let 手改目录 = 预制件目录::从模板列表([手改]);

    let 状态 = 手改目录.实例状态(&编辑器.会话.文档.预制件实例表[&实例根]);
    assert!(
        状态.指纹不一致,
        "版本没变但内容变了，必须提示可能被外部修改"
    );
    assert!(!状态.待同步, "版本号没变就不能报成待同步");

    let 告警 = 手改目录.检查(&编辑器.会话.文档);
    assert!(
        matches!(告警.as_slice(), [预制件告警::指纹不一致 { .. }]),
        "场景一致性检查应当把同版本手改报成指纹告警，实际为 {告警:?}"
    );
}

/**
 * 验证「用户摆放的位置在同步后保留」这条语义。
 *
 * 实例根的位置权威在记录的 `放置` 字段（物化时用它覆盖实体变换），
 * 因此设变换必须把新值写回记录；否则同步会把位置还原成创建时的旧值。
 * 这里同时看两处：命令执行后记录立刻更新，同步后实体字段不被还原。
 */
#[test]
fn 设变换会写回实例放置并在同步后保留用户摆放() {
    let 一版 = 造模板一版();
    let 二版 = 升级到二版(&一版);
    let mut 编辑器 = 编辑器状态::新建();
    let 实例根 = 创建实例(&mut 编辑器, &一版, &敌人路径());

    let 新放置 = 变换数据 {
        平移: (7.0, 8.0, 0.0),
        ..变换数据::单位()
    };
    编辑器
        .执行并记录(编辑器命令::设变换 {
            标识: 实例根,
            变换: Some(新放置),
        })
        .expect("设变换应当成功");

    assert_eq!(
        编辑器.会话.文档.预制件实例表[&实例根].放置, 新放置,
        "实例根的变换必须写回记录的放置字段"
    );

    编辑器
        .执行(编辑器命令::同步预制件实例 {
            模板: Box::new(二版),
            实例根: vec![实例根],
        })
        .expect("同步应当成功");

    let 根实体 = 编辑器.会话.文档.取(实例根).expect("实例根必须存在");
    assert_eq!(
        根实体.变换,
        Some(新放置),
        "同步不得把用户摆放的位置还原成创建时的放置"
    );
}
