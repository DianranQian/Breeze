//! 中文名：预制件模板保存闭环
//!
//! 验证「保存模板」这条入口的全部承诺：
//!
//! ```text
//! 版本 +1 → 重算内容指纹 → 写入 RON 到磁盘
//!   → 刷新模板目录（缓存与磁盘一致）
//!   → 统计当前场景里因此变成「待同步」的实例数
//!   → 控制台输出「模板「X」已更新至 v2，当前场景有 N 个实例待同步」
//! ```
//!
//! # 为什么必须落盘后再统计
//!
//! 待同步判定比较「实例记录里的目标版本/指纹」与「目录里的当前版本/指纹」。
//! 若先统计后刷新目录，目录里还是旧内容，统计结果会与用户随后看到的
//! 蓝色箭头数量不一致。本测试同时断言磁盘、目录缓存与状态标记三者一致，
//! 把这条顺序约束钉在数据上。
//!
//! # 失败路径
//!
//! 没有打开项目、模板不在目录里，都必须拒绝且**不推进版本号** ——
//! 版本号是用户看得见的承诺，失败时不能留下「名义上升级了、实际没写盘」
//! 的错位。

use std::collections::BTreeMap;

use editor_core::command::编辑器命令;
use editor_core::state::{日志内容, 编辑器状态};
use scene_doc::document::{变换数据, 场景文档, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::prefab::预制件文档;
use scene_doc::property::属性值;

/// 造一份版本 1 的小模板：单根节点 + 移动组件（速度 1）。
fn 造模板() -> 预制件文档 {
    let mut 场景 = 场景文档::新建("敌人模板");
    let 根 = 场景.生成实体("敌人", None);
    let mut 移动属性 = BTreeMap::new();
    移动属性.insert("速度".to_string(), 属性值::整数(1));
    场景
        .取可变(根)
        .expect("模板根必须存在")
        .加组件(组件数据::新建("移动", 移动属性));
    预制件文档::新建("敌人", 根, 场景)
}

/// 敌人模板文件的项目相对路径。
fn 敌人路径() -> 项目相对路径 {
    项目相对路径::解析("prefabs/敌人.prefab.ron").expect("模板路径应当合法")
}

/// 读取根实体上某个组件的属性副本。
fn 根属性(模板: &预制件文档, 组件名: &str, 属性名: &str) -> Option<属性值> {
    模板
        .场景
        .取(模板.头.根)?
        .取组件(组件名)?
        .属性
        .get(属性名)
        .cloned()
}

#[test]
fn 保存模板推进版本重算指纹并统计待同步实例() {
    let 目录 = tempfile::tempdir().expect("应当能创建临时目录");
    let 根 = 目录.path().join("保存测试");
    let mut 编辑器 = 编辑器状态::新建();
    编辑器.创建项目(&根, "保存测试").expect("创建项目应当成功");
    std::fs::create_dir_all(根.join("prefabs")).expect("应当能创建 prefabs 目录");

    let 模板 = 造模板();
    let 标识 = 模板.头.标识;
    编辑器
        .项目
        .as_ref()
        .expect("项目已打开")
        .保存预制件(&敌人路径(), &模板)
        .expect("写入模板应当成功");
    编辑器.刷新预制件目录();
    assert!(
        编辑器.预制件目录.取(&标识).is_some(),
        "刷新后目录必须收录刚写入的模板"
    );

    let 实例根 = 编辑器
        .执行(编辑器命令::创建预制件实例 {
            模板: Box::new(模板.clone()),
            模板路径: 敌人路径(),
            放置: 变换数据::单位(),
            父实体: None,
            指定实例根: None,
            内层模板: BTreeMap::new(),
        })
        .expect("创建实例应当成功")
        .新实体
        .expect("命令结果必须带回新实例根");
    assert!(
        !编辑器.预制件状态(&实例根).expect("实例状态必须存在").待同步,
        "刚创建的实例展开的就是 v1，不该显示待同步"
    );

    let 旧指纹 = 模板.内容指纹();
    let mut 修改后 = 模板.clone();
    修改后
        .场景
        .取可变(修改后.头.根)
        .expect("模板根必须存在")
        .取组件可变("移动")
        .expect("模板根应当带移动组件")
        .属性
        .insert("速度".to_string(), 属性值::整数(2));

    let 报告 = 编辑器
        .保存预制件模板(&mut 修改后)
        .expect("保存模板应当成功");
    assert_eq!(报告.路径, 敌人路径());
    assert_eq!(报告.新版本, 2, "保存必须把版本推进一版");
    assert_eq!(报告.内容指纹, 修改后.内容指纹());
    assert_ne!(报告.内容指纹, 旧指纹, "内容变了，指纹必须跟着变");
    assert_eq!(
        报告.待同步实例, 1,
        "唯一实例的目标版本落后于 v2，应当计入待同步"
    );

    let 状态 = 编辑器.预制件状态(&实例根).expect("实例状态必须存在");
    assert!(状态.待同步, "保存后实例必须立刻显示待同步");
    assert!(!状态.模板缺失);
    assert!(!状态.指纹不一致, "目录与磁盘是同一份内容，不该报外部手改");

    let 磁盘版 = 编辑器
        .项目
        .as_ref()
        .expect("项目已打开")
        .读取预制件(&敌人路径())
        .expect("应当能读回模板");
    assert_eq!(磁盘版.头.版本, 2, "磁盘上的版本必须已推进");
    assert_eq!(
        根属性(&磁盘版, "移动", "速度"),
        Some(属性值::整数(2)),
        "磁盘内容必须是修改后的"
    );
    assert_eq!(
        编辑器.预制件目录.指纹(&标识),
        Some(报告.内容指纹),
        "目录缓存必须与磁盘指纹一致"
    );

    let 末条 = 编辑器.日志列表().last().expect("保存必须写日志");
    match &末条.内容 {
        日志内容::自由文本(文本) => {
            assert!(文本.contains("已更新至 v2"), "日志必须报告新版本：{文本}");
            assert!(
                文本.contains("1 个实例待同步"),
                "日志必须报告待同步实例数：{文本}"
            );
        }
        其他 => panic!("保存日志应当是可读的自由文本，实际是 {其他:?}"),
    }

    let mut 重开 = 编辑器状态::新建();
    重开.打开项目(&根).expect("重新打开项目应当成功");
    assert_eq!(
        重开
            .预制件目录
            .取(&标识)
            .expect("重开后目录必须收录该模板")
            .头
            .版本,
        2,
        "版本必须已经真正落盘，重开项目后仍然可见"
    );
}

#[test]
fn 未打开项目或模板不在目录里时保存被拒绝() {
    let mut 编辑器 = 编辑器状态::新建();
    let mut 模板 = 造模板();
    let 错误 = 编辑器
        .保存预制件模板(&mut 模板)
        .expect_err("没有打开项目时保存必须被拒绝");
    assert!(format!("{错误}").contains("尚未打开项目"), "{错误}");
    assert_eq!(模板.头.版本, 1, "失败不得推进版本号");

    let 目录 = tempfile::tempdir().expect("应当能创建临时目录");
    let 根 = 目录.path().join("空项目");
    let mut 编辑器 = 编辑器状态::新建();
    编辑器.创建项目(&根, "空项目").expect("创建项目应当成功");
    let mut 陌生 = 造模板();
    let 错误 = 编辑器
        .保存预制件模板(&mut 陌生)
        .expect_err("目录里没有这份模板时必须拒绝");
    assert!(
        format!("{错误}").contains("不在当前项目的模板目录里"),
        "{错误}"
    );
    assert_eq!(陌生.头.版本, 1, "失败不得推进版本号");
}
