//! 中文名：撤销差量往返
//! 差量撤销的强不变式：**任何**命令执行之后，把差量逆向应用回去，
//! 文档必须与执行前逐字段相同。
//!
//! # 这条测试为什么必须存在
//!
//! 差量撤销的正确性完全依赖 `文档差量::比较` 把"所有会变的东西"都记下来。
//! 一旦漏记某个字段，表现是"撤销之后场景悄悄不对劲"，而且极难定位 ——
//! 这正是当初选择"整份快照"而不是"反向操作"的原因。
//!
//! 这里对 14 种命令逐个做往返验证，把"漏字段"从"靠人记得"变成"编译期之后
//! 一定跑得到"。新增命令时必须在这里加一行，否则 `全部命令都覆盖到了` 会失败。

use std::collections::BTreeMap;

use editor_core::command::编辑器命令;
use editor_core::delta::文档差量;
use scene_doc::document::{变换数据, 场景实体, 场景文档, 实体标识, 组件数据};
use scene_doc::path::项目相对路径;
use scene_doc::property::属性值;

/// 造一个有两层结构、带组件与资源的小场景。
fn 造文档() -> (场景文档, 实体标识, 实体标识) {
    let mut 文档 = 场景文档::新建("往返测试");
    let mut 根 = 场景实体::新建("根");
    根.变换 = Some(变换数据::单位());
    let 根标识 = 根.标识;
    文档.实体表.insert(根标识, 根.clone());
    文档.顶层顺序.push(根标识);

    let mut 子 = 场景实体::新建("子");
    子.父实体 = Some(根标识);
    子.次序 = 0;
    let mut 属性 = BTreeMap::new();
    属性.insert("颜色".to_string(), 属性值::文本("红".to_string()));
    子.组件.push(组件数据::新建("Sprite", 属性));
    let 子标识 = 子.标识;
    文档.实体表.insert(子标识, 子.clone());

    文档.资源表.insert(
        项目相对路径::解析("textures/a.png").expect("路径"),
        scene_doc::document::资源引用 {
            路径: 项目相对路径::解析("textures/a.png").expect("路径"),
            唯一标识: None,
        },
    );

    (文档, 根标识, 子标识)
}

/// 14 种命令各造一条。
fn 命令清单(根: 实体标识, 子: 实体标识) -> Vec<(&'static str, 编辑器命令)> {
    let mut 属性 = BTreeMap::new();
    属性.insert("颜色".to_string(), 属性值::文本("蓝".to_string()));

    let mut 整份替换 = 场景文档::新建("替换后的场景");
    let mut 新实体 = 场景实体::新建("替换实体");
    新实体.变换 = Some(变换数据::单位());
    整份替换.实体表.insert(新实体.标识, 新实体.clone());
    整份替换.顶层顺序.push(新实体.标识);

    vec![
        (
            "新建实体",
            编辑器命令::新建实体 {
                名称: "新".to_string(),
                父实体: Some(根),
                指定标识: None,
            },
        ),
        ("删除实体", 编辑器命令::删除实体 { 标识: 根 }),
        (
            "重命名实体",
            编辑器命令::重命名实体 {
                标识: 子,
                新名称: "改名了".to_string(),
            },
        ),
        (
            "重设父子",
            编辑器命令::重设父子 {
                标识: 子,
                新父实体: None,
                新次序: 3,
            },
        ),
        ("上移实体", 编辑器命令::上移实体 { 标识: 子 }),
        ("下移实体", 编辑器命令::下移实体 { 标识: 子 }),
        (
            "设变换",
            编辑器命令::设变换 {
                标识: 子,
                变换: Some(变换数据 {
                    平移: (1.0, 2.0, 3.0),
                    ..变换数据::单位()
                }),
            },
        ),
        (
            "批量设变换",
            编辑器命令::批量设变换 {
                项: vec![(根, Some(变换数据::单位())), (子, None)],
            },
        ),
        (
            "添加组件",
            编辑器命令::添加组件 {
                标识: 根,
                组件: 组件数据::新建("Camera2d", 属性.clone()),
            },
        ),
        (
            "删除组件",
            编辑器命令::删除组件 {
                标识: 子,
                类型名: "Sprite".to_string(),
            },
        ),
        (
            "设组件属性",
            编辑器命令::设组件属性 {
                标识: 子,
                类型名: "Sprite".to_string(),
                属性名: "颜色".to_string(),
                新值: 属性值::文本("绿".to_string()),
            },
        ),
        (
            "批量设属性",
            编辑器命令::批量设属性 {
                项: vec![
                    (
                        子,
                        "Sprite".to_string(),
                        "颜色".to_string(),
                        属性值::文本("黄".to_string()),
                    ),
                    (
                        根,
                        "Sprite".to_string(),
                        "可见".to_string(),
                        属性值::布尔(true),
                    ),
                ],
            },
        ),
        (
            "替换实体",
            编辑器命令::替换实体 {
                实体: Box::new({
                    let mut 实体 = 场景实体::新建("被替换");
                    实体.标识 = 子;
                    实体
                }),
            },
        ),
        (
            "设为快照",
            编辑器命令::设为快照 {
                文档: Box::new(整份替换),
            },
        ),
    ]
}

#[test]
fn 每种命令的差量都能精确回滚() {
    let (文档, 根, 子) = 造文档();
    let 清单 = 命令清单(根, 子);
    assert_eq!(清单.len(), 14, "命令种类变了，这个测试必须同步更新");

    for (名称, 命令) in 清单 {
        let mut 当前 = 文档.clone();
        let 执行前 = 当前.clone();

        match 命令.应用(&mut 当前) {
            Ok(_) => {
                let 差量 = 文档差量::比较(&执行前, &当前);
                if 差量.为空() {
                    assert_eq!(
                        当前, 执行前,
                        "{名称}：差量为空，但文档确实变了 —— 说明比较漏了字段"
                    );
                    continue;
                }
                差量.逆向应用(&mut 当前);
                assert_eq!(
                    当前.实体表, 执行前.实体表,
                    "{名称}：撤销后实体表与执行前不一致"
                );
                assert_eq!(
                    当前.顶层顺序, 执行前.顶层顺序,
                    "{名称}：撤销后顶层顺序与执行前不一致"
                );
                assert_eq!(
                    当前.元数据, 执行前.元数据,
                    "{名称}：撤销后元数据与执行前不一致"
                );
                assert_eq!(
                    当前.资源表, 执行前.资源表,
                    "{名称}：撤销后资源表与执行前不一致"
                );
                assert_eq!(当前.格式版本, 执行前.格式版本, "{名称}：格式版本未还原");
            }
            Err(_) => {
                // 校验失败的命令不允许留下任何改动。
                assert_eq!(当前, 执行前, "{名称}：命令失败，但文档被改动了");
            }
        }
    }
}
