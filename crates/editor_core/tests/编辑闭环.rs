//! 编辑器核心的端到端测试。
//!
//! 这些测试**不用打开窗口、不需要 GPU**，因为 `editor_core` 刻意不依赖 Bevy。
//! 它们验证的是需求文档里程碑 A/B 里那条最关键的闭环：
//!
//! ```text
//! 创建项目 → 新建实体 → 修改属性 → 保存场景 → 重新打开 → 数据一致
//! ```
//!
//! 以及围绕它的一圈保证：撤销重做、保存失败不破坏数据、
//! 项目关闭重开、运行时数据隔离的前提条件。

// 测试名刻意采用「里程碑A_xxx」的形式：需求文档是按里程碑组织的，
// 测试名直接带上里程碑编号，跑测试时一眼就能看出哪条验收条件被覆盖。
// `non_snake_case` 检查的是标识符风格，这里是经过考虑的例外。
#![allow(non_snake_case)]

