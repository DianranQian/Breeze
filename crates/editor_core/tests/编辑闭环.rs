#[test]
fn 里程碑A_保存并重新打开场景后数据完全一致() {
    let (_守卫, 根) = 建临时项目("闭环项目");
    let mut 状态 = 建状态();
    状态.创建项目(&根, "闭环项目").unwrap();

    // 搭一个有层级的场景
    let 根实体 = 状态.新建实体("关卡", None).unwrap();
    let 玩家 = 状态.新建实体("玩家", Some(根实体)).unwrap();
    let _子弹 = 状态.新建实体("子弹", Some(玩家)).unwrap();

    // 改变换
    状态
        .执行(编辑器命令::设变换 {
            标识: 玩家,
            变换: Some(变换数据 {
                平移: (12.0, 34.0, 0.0),
                旋转: (0.0, 0.0, 0.0, 1.0),
                缩放: (1.5, 1.5, 1.0),
            }),
        })
        .unwrap();

    // 加组件并改属性
    let mut 属性 = BTreeMap::new();
    属性.insert("颜色".to_string(), 属性值::颜色(颜色值::srgb(1.0, 0.0, 0.0, 1.0)));
    属性.insert("可见".to_string(), 属性值::布尔(true));
    状态.添加组件(玩家, 组件数据::新建("Sprite", 属性));
    状态.设属性(玩家, "Sprite", "可见", 属性值::布尔(false));

    // 保存
    let 场景路径 = 项目相对路径::解析("scenes/主关卡.scene.ron").unwrap();
    状态.保存场景到(&场景路径).expect("保存应当成功");
    assert!(!状态.有未保存修改(), "保存后应当没有未保存修改");
    assert!(状态.场景已保存到磁盘());

    // 确认文件真的写出来了
    let 绝对 = 根.join("scenes").join("主关卡.scene.ron");
    assert!(绝对.is_file(), "场景文件应当存在于 {}", 绝对.display());

    // 记下全部关键数据
    let 保存前实体数 = 状态.会话.文档.实体数量();
    let 保存前玩家 = 状态.会话.文档.取(玩家).unwrap().clone();
    let 保存前顶层顺序 = 状态.会话.文档.顶层顺序.clone();

    // 模拟"关掉编辑器再打开"：全新状态 + 打开项目 + 打开场景
    let mut 新状态 = 建状态();
    新状态.打开项目(&根).unwrap();
    新状态.打开场景(&场景路径).expect("重新打开场景应当成功");

    assert_eq!(新状态.会话.文档.实体数量(), 保存前实体数);
    assert_eq!(新状态.会话.文档.顶层顺序, 保存前顶层顺序);

    let 重开玩家 = 新状态
        .会话
        .文档
        .取(玩家)
        .expect("重新打开后实体标识必须保持不变");
    assert_eq!(重开玩家, &保存前玩家, "实体数据必须逐字段一致");

    // 关键：属性修改必须被保存（而不是只改了内存）
    let 可见 = 重开玩家
        .取组件("Sprite")
        .unwrap()
        .属性
        .get("可见")
        .unwrap();
    assert_eq!(
        可见.取布尔(),
        Some(false),
        "保存前把「可见」改成了 false，重新打开必须还是 false"
    );

    // 层级必须保持
    assert_eq!(重开玩家.父实体, Some(根实体));
    assert_eq!(新状态.会话.文档.取(根实体).unwrap().名称, "关卡");

    // 重新打开的场景应当是干净的（没有未保存修改）
    assert!(!新状态.有未保存修改());
}

