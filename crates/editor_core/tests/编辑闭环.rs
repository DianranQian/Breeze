#[test]
fn 里程碑B_撤销重做能精确还原属性修改() {
    let (_守卫, 根) = 建临时项目("撤销项目");
    let mut 状态 = 建状态();
    状态.创建项目(&根, "撤销项目").unwrap();

    let 实体 = 状态.新建实体("目标", None).unwrap();
    let 原始变换 = 状态.会话.文档.取(实体).unwrap().变换.unwrap();

    // 改三次
    for x in [1.0f32, 2.0, 3.0] {
        状态
            .执行(编辑器命令::设变换 {
                标识: 实体,
                变换: Some(变换数据 {
                    平移: (x, 0.0, 0.0),
                    ..原始变换
                }),
            })
            .unwrap();
    }
    assert_eq!(
        状态.会话.文档.取(实体).unwrap().变换.unwrap().平移.0,
        3.0
    );
    // 新建实体本身也占一步，所以总共是 1 + 3 = 4 步。
    let 新建占用步数 = 状态.撤销.可撤销步数() - 3;
    assert_eq!(新建占用步数, 1, "新建实体应当只占一步撤销");

    // 撤销三次，回到刚创建、还没改变换的状态
    assert!(状态.撤销一步());
    assert!(状态.撤销一步());
    assert!(状态.撤销一步());
    assert_eq!(
        状态.会话.文档.取(实体).unwrap().变换.unwrap(),
        原始变换,
        "撤销三次之后应当回到初始变换"
    );
    assert_eq!(状态.撤销.可撤销步数(), 1, "此时应当只剩新建实体这一步");

    // 再撤销一步，把新建实体也撤销掉 —— 文档应当回到空的初始状态
    assert!(状态.撤销一步(), "应当能撤销掉新建实体这一步");
    assert!(
        !状态.会话.文档.存在(实体),
        "撤销掉新建实体之后该实体必须从文档消失"
    );
    assert!(!状态.撤销一步(), "没有更多可撤销的步骤");

    // 重做必须能把实体和它的变换一起恢复，且**标识不变**
    assert!(状态.重做一步(), "应当能重做新建实体");
    assert!(
        状态.会话.文档.存在(实体),
        "重做后实体必须回来，且标识必须与原来完全相同"
    );
    assert_eq!(
        状态.会话.文档.取(实体).unwrap().变换.unwrap(),
        原始变换,
        "重做出来的实体应当带有正确的初始变换"
    );
}

#[test]
fn 里程碑B_撤销删除实体能恢复整棵子树与层级() {
    let (_守卫, 根) = 建临时项目("撤销删除");
    let mut 状态 = 建状态();
    状态.创建项目(&根, "撤销删除").unwrap();

    let 甲 = 状态.新建实体("甲", None).unwrap();
    let 乙 = 状态.新建实体("乙", Some(甲)).unwrap();
    let 丙 = 状态.新建实体("丙", Some(乙)).unwrap();
    let 丁 = 状态.新建实体("丁", None).unwrap();

    let 删除前实体数 = 状态.会话.文档.实体数量();
    let 删除前次序丁 = 状态.会话.文档.取(丁).unwrap().次序;

    // 删除甲，会带走乙和丙
    状态.删除实体(甲);
    assert_eq!(状态.会话.文档.实体数量(), 删除前实体数 - 3);
    assert!(!状态.会话.文档.存在(乙));
    assert_eq!(状态.会话.文档.取(丁).unwrap().次序, 0, "丁的次序应当被整理");

    // 撤销：整棵子树、父关系、次序都要回来
    状态.撤销一步();
    assert_eq!(状态.会话.文档.实体数量(), 删除前实体数);
    assert!(状态.会话.文档.存在(甲));
    assert!(状态.会话.文档.存在(乙));
    assert!(状态.会话.文档.存在(丙));
    assert_eq!(状态.会话.文档.取(乙).unwrap().父实体, Some(甲));
    assert_eq!(状态.会话.文档.取(丙).unwrap().父实体, Some(乙));
    assert_eq!(
        状态.会话.文档.取(丁).unwrap().次序,
        删除前次序丁,
        "撤销后丁的次序必须复原"
    );
    assert!(
        状态.会话.文档.校验().无问题(),
        "撤销后文档必须自洽：{}",
        状态.会话.文档.校验().摘要()
    );
}

