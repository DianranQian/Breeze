use scene_doc::property::{属性值, 颜色值};

/// 在临时目录里建一个可用项目，返回 (临时目录守卫, 项目根路径)。
///
/// 守卫必须被持有到测试结束，否则临时目录会被提前删除。
fn 建临时项目(名称: &str) -> (tempfile::TempDir, PathBuf) {
    let 目录 = tempfile::tempdir().expect("应当能创建临时目录");
    let 根 = 目录.path().join(名称);
    (目录, 根)
}

/// 构造一个只含核心组件的编辑器状态。
fn 建状态() -> 编辑器状态 {
    编辑器状态::新建()
}

