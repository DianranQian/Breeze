#[test]
fn 里程碑B_组件属性修改会立刻反映到文档并且可保存() {
    let (_守卫, 根) = 建临时项目("属性持久化");
    let mut 状态 = 建状态();
    状态.创建项目(&根, "属性持久化").unwrap();

    let 实体 = 状态.新建实体("精灵", None).unwrap();
    let mut 属性 = BTreeMap::new();
    属性.insert("颜色".to_string(), 属性值::颜色(颜色值::白()));
    属性.insert("层级".to_string(), 属性值::整数(0));
    状态.添加组件(实体, 组件数据::新建("Sprite", 属性));

    // 改属性
    assert!(状态.设属性(
        实体,
        "Sprite",
        "颜色",
        属性值::颜色(颜色值::srgb(0.25, 0.5, 0.75, 1.0))
    ));
    assert!(状态.设属性(实体, "Sprite", "层级", 属性值::整数(7)));

    // 立刻反映到文档（而不是等某个刷新周期）
    let 组件 = 状态.会话.文档.取(实体).unwrap().取组件("Sprite").unwrap();
    assert_eq!(
        组件.属性.get("颜色").unwrap().取颜色().unwrap().红,
        0.25
    );
    assert_eq!(组件.属性.get("层级").unwrap().取整数(), Some(7));

    // 非法值应当被收拢而不是写进文档
    状态.设属性(
        实体,
        "Sprite",
        "颜色",
        属性值::颜色(颜色值::srgb(5.0, -3.0, 0.5, 1.0)),
    );
    let 收拢后 = 状态
        .会话
        .文档
        .取(实体)
        .unwrap()
        .取组件("Sprite")
        .unwrap()
        .属性
        .get("颜色")
        .unwrap()
        .取颜色()
        .unwrap();
    assert_eq!((收拢后.红, 收拢后.绿), (1.0, 0.0), "越界颜色必须被收拢");

    // 保存并重新打开
    let 路径 = 项目相对路径::解析("scenes/属性场景.scene.ron").unwrap();
    状态.保存场景到(&路径).unwrap();

    let mut 新状态 = 建状态();
    新状态.打开项目(&根).unwrap();
    新状态.打开场景(&路径).unwrap();
    let 重开组件 = 新状态
        .会话
        .文档
        .取(实体)
        .unwrap()
        .取组件("Sprite")
        .unwrap();
    assert_eq!(重开组件.属性.get("层级").unwrap().取整数(), Some(7));
    assert_eq!(重开组件.属性.get("颜色").unwrap().取颜色().unwrap().蓝, 0.5);
}

#[test]
