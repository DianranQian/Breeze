//! 顶部编辑模式导航（2D / 3D / 代码）与模式专用工具栏。
//!
//! # 顶部四行的职责划分（每行只有一个职责）
//!
//! ```text
//! ┌───────────────────────────────────────────────────────────────┐
//! │ 文件 编辑 场景 …                                    菜单栏    │ 全局命令
//! ├───────────────────────────────────────────────────────────────┤
//! │ 模式: [2D] [3D] [代码]                            编辑模式   │  ← 本模块
//! ├───────────────────────────────────────────────────────────────┤
//! │ 工作区: [通用] [场景] [资源] [调试] + ⧉ ✎ ✖ ⟲ ⋯   布局      │  面板怎么摆
//! ├───────────────────────────────────────────────────────────────┤
//! │ [模式专用工具] [预览控制] [项目运行] [编辑] [实体] [面板]     │  操作
//! └───────────────────────────────────────────────────────────────┘
//! ```
//!
//! ## 这张表是怎么定下来的（"两行功能重复"的根因）
//!
//! 整改前第二行是 `2D / 3D / 代码 / 运行 / 资源`，第三行是
//! `通用 / 场景 / 资源 / 调试`，并且第三行还会按模式生成一条
//! "运行默认布局"。于是：
//!
//! * **资源** 同时出现在两行，做的也是同一件事（把资源浏览器摆到中央）；
//! * **运行**（模式）与 **调试**（工作区）职责重叠（把控制台/运行时/性能摆到显眼处）；
//! * 第三行那条以模式命名的副本让"切模式"与"切工作区"看起来是同一类操作。
//!
//! 现在的划分依据是**"答案会不会随任务变化"**：
//!
//! | 行 | 回答 | 是否随任务变化 |
//! | --- | --- | --- |
//! | 模式 | 我在编辑什么（视口类型 + 专用工具） | 是 |
//! | 工作区 | 面板怎么摆 | 是，但与"编辑什么"正交 |
//! | 工具栏 | 现在能做什么操作 | 是，且**运行控制在所有模式都可用** |
//!
//! 因此「运行」不再是模式（它在任何模式下都该可用），
//! 「资源」不再是模式（那是一种布局）。两者分别回到**工具栏**与**工作区**，
//! 各自只有一个入口。
//!
//! # 模式切换必须"有实感"
//!
//! 只改高亮是不够的。每个模式都实际改变：
//!
//! * **视口类型**：3D 用透视轨道相机，2D 用正交网格视口；
//! * **专用工具栏**：本模块 [`绘制模式工具栏`] 按模式给不同工具；
//! * **默认布局**：每个模式一套（成为该模式里「通用」工作区的出厂布局，
//!   见 [`crate::workspaces::工作区集::以通用布局`]）；
//! * **活动编辑内容**：进入代码模式时会强调代码面板。
//!
//! 文档、选择、撤销栈、主题、语言在模式之间**共享**，切模式不会丢任何数据。

use egui::{Color32, CornerRadius, RichText, Ui};

use crate::dev_modes::开发模式;
use crate::icons::图标;
use crate::state::{UiAction, 绘制上下文};

/// 模式栏高度（逻辑像素）。
pub const 模式栏高度: f32 = 30.0;

/// 绘制编辑模式导航。
///
/// 左半是模式标签，右半是当前模式的说明。**不含**任何运行控制：
/// 运行是"操作"，属于工具栏；把它放进模式栏正是整改前的重复来源之一。
pub fn 绘制(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>) {
    let 语言 = 上下文.语言;
    let 配色 = 上下文.配色;
    let 当前 = 上下文.界面.模式;
    let 图标尺寸 = (上下文.外观.图标尺寸 * 1.05).max(14.0);

    ui.horizontal_centered(|ui| {
        ui.spacing_mut().item_spacing = egui::vec2(4.0, 0.0);
        ui.add_space(6.0);

        // 行首的身份标识：让用户一眼知道这一行是在切换"编辑模式"，
        // 与下一行的工作区切换区分开。整改前两行都没有身份标识，
        // 视觉上就是两排长得一样的文字按钮 —— 这正是"看起来重复"的成因。
        ui.label(
            RichText::new(语言.取("mode_label"))
                .small()
                .color(配色.次要文字),
        );
        ui.add_space(4.0);

        for 模式 in 开发模式::全部() {
            let 激活 = *模式 == 当前;
            let 名称 = 语言.取(模式.名称键());
            let 色 = if 激活 {
                配色.文字
            } else {
                配色.次要文字
            };
            let 文字 = RichText::new(名称)
                .size((上下文.外观.基础字号 + 1.0).max(12.0))
                .color(色);
            let 文字 = if 激活 { 文字.strong() } else { 文字 };

            // 先画图标再画文字：`Button::image_and_text` 会接管悬停/按下状态。
            let 图标项 = 模式.图标();
            let 有纹理 = 上下文.图标.纹理(ui.ctx(), 图标项).is_some();
            let mut 响应 = if 有纹理 {
                let 纹理 = 上下文
                    .图标
                    .纹理(ui.ctx(), 图标项)
                    .expect("上一行已确认纹理存在")
                    .id();
                let 图片 = egui::Image::new(egui::load::SizedTexture::new(
                    纹理,
                    egui::vec2(图标尺寸, 图标尺寸),
                ))
                .tint(if 激活 { 配色.强调 } else { 色 });
                ui.add(
                    egui::Button::image_and_text(图片, 文字)
                        .frame(false)
                        .fill(if 激活 {
                            配色.强调淡
                        } else {
                            Color32::TRANSPARENT
                        })
                        .stroke(if 激活 {
                            egui::Stroke::new(1.0, 配色.强调)
                        } else {
                            egui::Stroke::NONE
                        })
                        .corner_radius(CornerRadius::same(4))
                        .min_size(egui::vec2(0.0, 22.0)),
                )
            } else {
                ui.add(
                    egui::Button::new(文字)
                        .frame(false)
                        .fill(if 激活 {
                            配色.强调淡
                        } else {
                            Color32::TRANSPARENT
                        })
                        .corner_radius(CornerRadius::same(4)),
                )
            };
            响应 = 响应.on_hover_text(语言.取(模式.说明键()));
            // 记录模式按钮的真实矩形：自动验收要按矩形中心点击，
            // 而不是靠"大概在这个位置"。标识用稳定 id（`mode_2d` 等），
            // 与界面语言无关。
            上下文.界面.布局快照.push(crate::state::区域快照 {
                标识: 模式快照标识(*模式),
                矩形: 响应.rect,
            });
            if 响应.clicked() && !激活 {
                上下文.动作.推(UiAction::切换模式(*模式));
            }
        }

        // 右侧：当前模式的身份提示（小字，不抢视觉重心）。
        ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
            ui.add_space(8.0);
            ui.label(
                RichText::new(语言.取(当前.说明键()))
                    .small()
                    .color(配色.次要文字),
            );
        });
    });
}

/// 绘制模式专用工具栏。返回是否画了任何控件。
///
/// 只放**真实可用**的操作：每个按钮要么改界面状态、要么排一个动作、
/// 要么切换一个真实存在的显示选项。没有实现的工具不会出现在这里。
///
/// # 这里为什么不画运行控制
///
/// 运行/暂停/单步/停止在**任何**编辑模式下都应当可用，因此它们属于
/// 工具栏的通用部分（见 [`crate::menu_bar::绘制工具栏`]），
/// 由所有模式共享、且只有一份。整改前它们既在本函数（运行模式分支）、
/// 又在通用工具栏里各画了一遍，同一行里出现两个一模一样的「▶ 运行」。
pub fn 绘制模式工具栏(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>) -> bool {
    let 语言 = 上下文.语言;
    let 配色 = 上下文.配色;
    let 图标尺寸 = 上下文.外观.图标尺寸;
    let 模式 = 上下文.界面.模式;

    match 模式 {
        开发模式::二维 => {
            // 变换工具组：选择 / 移动 / 旋转 / 缩放。
            //
            // 只有 2D/3D 模式才画它 —— 代码/运行/资源模式没有可变换的视口，
            // 把工具放在那里只会让用户点了没反应。
            if let Some(工具) = crate::gizmo::绘制工具组(ui, 上下文) {
                // 切工具会顺手取消正在进行的拖拽（见 `gizmo::切换工具`）。
                crate::gizmo::切换工具(上下文, 工具);
            }
            ui.separator();
            let 适配响应 = 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::最大化,
                    Some(语言.取("fit_window")),
                    图标尺寸,
                    配色.文字,
                    true,
                )
                .on_hover_text(语言.取("fit_window_hint"));
            // 记录按钮矩形：验收要靠"点真实按钮"来把视角变成确定状态，
            // 而不是假设启动时的相机已经稳定。
            上下文.界面.布局快照.push(crate::state::区域快照 {
                标识: "btn_fit_2d",
                矩形: 适配响应.rect,
            });
            if 适配响应.clicked() {
                上下文.动作.推(UiAction::视口适应窗口);
            }
            let 重置响应 = 上下文
                .图标
                .图标按钮(ui, 图标::刷新, None, 图标尺寸, 配色.文字, true)
                .on_hover_text(语言.取("reset_view_hint"));
            上下文.界面.布局快照.push(crate::state::区域快照 {
                标识: "btn_reset_view_2d",
                矩形: 重置响应.rect,
            });
            if 重置响应.clicked() {
                上下文.动作.推(UiAction::视口重置视图);
            }
            // 显示开关是**界面状态**，直接改，不需要绕动作队列。
            let mut 相机 = 上下文.界面.相机;
            if ui
                .selectable_label(相机.显示网格, 语言.取("grid"))
                .on_hover_text(语言.取("tooltip_toggle_grid"))
                .clicked()
            {
                相机.显示网格 = !相机.显示网格;
            }
            if ui
                .selectable_label(相机.显示坐标轴, 语言.取("axes"))
                .clicked()
            {
                相机.显示坐标轴 = !相机.显示坐标轴;
            }
            if ui
                .selectable_label(相机.显示包围框, 语言.取("bounds"))
                .clicked()
            {
                相机.显示包围框 = !相机.显示包围框;
            }
            上下文.界面.相机 = 相机;
            true
        }
        开发模式::三维 => {
            // 与 2D 同一套工具组：工具模式是**视口无关**的界面状态，
            // 切到 3D 时不该换一套工具概念。
            if let Some(工具) = crate::gizmo::绘制工具组(ui, 上下文) {
                // 切工具会顺手取消正在进行的拖拽（见 `gizmo::切换工具`）。
                crate::gizmo::切换工具(上下文, 工具);
            }
            ui.separator();
            if 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::刷新,
                    Some(语言.取("orbit_reset")),
                    图标尺寸,
                    配色.文字,
                    true,
                )
                .on_hover_text(语言.取("orbit_reset_hint"))
                .clicked()
            {
                上下文.动作.推(UiAction::三维重置轨道);
            }
            if 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::最大化,
                    Some(语言.取("fit_window")),
                    图标尺寸,
                    配色.文字,
                    true,
                )
                .clicked()
            {
                上下文.动作.推(UiAction::视口适应窗口);
            }
            if ui
                .add_enabled(
                    !上下文.编辑器.选择.为空(),
                    egui::Button::new(语言.取("focus_selection")).small(),
                )
                .on_hover_text(语言.取("focus_selection_hint"))
                .clicked()
            {
                上下文.动作.推(UiAction::聚焦选中实体);
            }
            // 三维相机的实时读数：让用户确认自己在什么视角。
            let 相机 = &上下文.界面.三维相机;
            ui.label(
                RichText::new(format!(
                    "{} {:.0}° {:.0}° {:.0}",
                    语言.取("camera"),
                    相机.偏航.to_degrees(),
                    相机.俯仰.to_degrees(),
                    相机.距离
                ))
                .small()
                .color(配色.次要文字),
            );
            true
        }
        开发模式::脚本 => {
            let 有文档 = 上下文.界面.脚本.文档.is_some();
            if 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::保存,
                    Some(语言.取("script_save")),
                    图标尺寸,
                    配色.文字,
                    有文档,
                )
                .on_hover_text(语言.取("script_save_hint"))
                .clicked()
            {
                上下文.动作.推(UiAction::保存脚本);
            }
            if 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::放大,
                    Some(语言.取("script_find")),
                    图标尺寸,
                    配色.文字,
                    有文档,
                )
                .clicked()
            {
                上下文.界面.脚本.显示查找 = true;
            }
            match 上下文.界面.脚本.文档.as_ref() {
                Some(文档) => {
                    ui.label(
                        RichText::new(format!(
                            "{} {}",
                            文档.显示名(语言),
                            if 文档.有未保存修改() {
                                language_unsaved(语言)
                            } else {
                                ""
                            }
                        ))
                        .small()
                        .color(if 文档.有未保存修改() {
                            配色.警告
                        } else {
                            配色.次要文字
                        }),
                    );
                }
                None => {
                    ui.label(
                        RichText::new(语言.取("script_no_file"))
                            .small()
                            .color(配色.次要文字),
                    );
                }
            }
            true
        }
    }
}

fn language_unsaved(语言: crate::i18n::语言) -> &'static str {
    语言.取("script_unsaved")
}

/// 模式按钮在证据文件里的稳定标识。
///
/// 用 `&'static str` 而不是拼出来的字符串：`区域快照.标识` 是 `'static`，
/// 而且证据里的 id 必须跨帧、跨语言稳定，自动验收才能可靠地取到矩形。
fn 模式快照标识(模式: 开发模式) -> &'static str {
    match 模式 {
        开发模式::二维 => "mode_2d",
        开发模式::三维 => "mode_3d",
        开发模式::脚本 => "mode_script",
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 模式导航顺序稳定() {
        let ids: Vec<&str> = 开发模式::全部().iter().map(|模式| 模式.id()).collect();
        assert_eq!(ids, vec!["2d", "3d", "script"]);
    }

    #[test]
    fn 每个模式都有名称与说明键() {
        for 模式 in 开发模式::全部() {
            assert!(!模式.名称键().is_empty());
            assert!(!模式.说明键().is_empty());
            assert_ne!(模式.名称键(), 模式.说明键());
        }
    }
}
