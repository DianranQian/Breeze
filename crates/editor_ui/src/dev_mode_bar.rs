//! 顶部编辑模式导航（2D / 3D / 代码）与模式专用工具栏。
//!
//! # 顶部四行的职责划分（每行只有一个职责）
//!
//! ```text
//! ┌───────────────────────────────────────────────────────────────┐
//! │ 文件 编辑 场景 …                                    菜单栏    │ 全局命令
//! ├───────────────────────────────────────────────────────────────┤
//! │ 模式: [2D] [3D] [代码]                            编辑模式   │  ← 本模块
//! ├───────────────────────────────────────────────────────────────┤
//! │ 工作区: [通用] [场景] [资源] [调试] + ⧉ ✎ ✖ ⟲ ⋯   布局      │  面板怎么摆
//! ├───────────────────────────────────────────────────────────────┤
//! │ [模式专用工具] [预览控制] [项目运行] [编辑] [实体] [面板]     │  操作
//! └───────────────────────────────────────────────────────────────┘
//! ```
//!
//! ## 这张表是怎么定下来的（"两行功能重复"的根因）
//!
//! 整改前第二行是 `2D / 3D / 代码 / 运行 / 资源`，第三行是
//! `通用 / 场景 / 资源 / 调试`，并且第三行还会按模式生成一条
//! "运行默认布局"。于是：
//!
//! * **资源** 同时出现在两行，做的也是同一件事（把资源浏览器摆到中央）；
//! * **运行**（模式）与 **调试**（工作区）职责重叠（把控制台/运行时/性能摆到显眼处）；
//! * 第三行那条以模式命名的副本让"切模式"与"切工作区"看起来是同一类操作。
//!
//! 现在的划分依据是**"答案会不会随任务变化"**：
//!
//! | 行 | 回答 | 是否随任务变化 |
//! | --- | --- | --- |
//! | 模式 | 我在编辑什么（视口类型 + 专用工具） | 是 |
//! | 工作区 | 面板怎么摆 | 是，但与"编辑什么"正交 |
//! | 工具栏 | 现在能做什么操作 | 是，且**运行控制在所有模式都可用** |
//!
//! 因此「运行」不再是模式（它在任何模式下都该可用），
//! 「资源」不再是模式（那是一种布局）。两者分别回到**工具栏**与**工作区**，
//! 各自只有一个入口。
//!
//! # 模式切换必须"有实感"
//!
//! 只改高亮是不够的。每个模式都实际改变：
//!
//! * **视口类型**：3D 用透视轨道相机，2D 用正交网格视口；
//! * **专用工具栏**：本模块 [`绘制模式工具栏`] 按模式给不同工具；
//! * **默认布局**：每个模式一套（成为该模式里「通用」工作区的出厂布局，
//!   见 [`crate::workspaces::工作区集::以通用布局`]）；
//! * **活动编辑内容**：进入代码模式时会强调代码面板。
//!
//! 文档、选择、撤销栈、主题、语言在模式之间**共享**，切模式不会丢任何数据。

use egui::{RichText, Ui};

use crate::dev_modes::开发模式;
use crate::icons::图标;
use crate::state::{UiAction, 光源类型, 基础图元类型, 绘制上下文};

/// 模式栏高度（逻辑像素）。
pub const 模式栏高度: f32 = 30.0;

/// 绘制编辑模式导航。
///
/// 左半是模式标签，右半是当前模式的说明。**不含**任何运行控制：
/// 运行是"操作"，属于工具栏；把它放进模式栏正是整改前的重复来源之一。
pub fn 绘制(
    ui: &mut Ui,
    上下文: &mut 绘制上下文<'_>,
    右侧: impl FnOnce(&mut Ui, &mut 绘制上下文<'_>),
) {
    let 语言 = 上下文.语言;
    let 配色 = 上下文.配色;
    let 当前 = 上下文.界面.模式;
    let 图标尺寸 = (上下文.外观.图标尺寸 * 0.95).max(14.0);

    ui.horizontal_centered(|ui| {
        ui.spacing_mut().item_spacing = egui::vec2(2.0, 0.0);
        ui.add_space(10.0);

        // ---- 分段控件 ----
        //
        // 四个模式是**同一维度上的互斥选择**，因此画成一个分段控件，
        // 而不是四个各自带边框的按钮：分段控件一眼就能看出"只能选一个"，
        // 按钮列表则永远像四个各管各的命令。
        //
        // 选中态由 `visual_spec::分段标签` 统一给出（强调色淡底 + 强调描边 +
        // 强调色图标），这样它和视图开关、工作区标签的选中态是同一套语法。
        // 分段控件：不加外框，只让"选中项"自己有强调底色。
        //
        // 试过给四个模式套一个圆角容器（像网页原型那样），但 `egui::Frame`
        // 在横向布局里会按可用宽度撑开，整条模式栏被一个空框包住。
        // 去掉容器之后，四个标签靠"选中项有底色、未选中项透明"就能读出
        // 互斥关系，而且和下面工作区标签的语法完全一致。
        ui.horizontal(|ui| {
            ui.spacing_mut().item_spacing = egui::vec2(2.0, 0.0);
            for 模式 in 开发模式::全部() {
                let 激活 = *模式 == 当前;
                let 名称 = 语言.取(模式.名称键());
                let 图标项 = 模式.图标();
                let 纹理 = 上下文.图标.纹理(ui.ctx(), 图标项).map(|纹理| {
                    egui::load::SizedTexture::new(纹理.id(), egui::vec2(图标尺寸, 图标尺寸))
                });
                let 响应 = crate::visual_spec::分段标签(
                    ui,
                    配色,
                    上下文.外观.基础字号,
                    名称,
                    纹理.as_ref(),
                    激活,
                    true,
                )
                .on_hover_text(语言.取(模式.说明键()));
                // 记录模式按钮的真实矩形：自动验收要按矩形中心点击，
                // 而不是靠"大概在这个位置"。标识用稳定 id（`mode_2d` 等），
                // 与界面语言无关。
                上下文.界面.布局快照.push(crate::state::区域快照 {
                    标识: 模式快照标识(*模式),
                    矩形: 响应.rect,
                });
                if 响应.clicked() && !激活 {
                    上下文.动作.推(UiAction::切换模式(*模式));
                }
            }
        });

        // 右半行：由调用方决定画什么（当前是工作区切换）。
        //
        // 必须在**同一行**的布局里继续画：先关闭这一行再新开一行，
        // 得到的矩形会落到下面一条工具栏上（实测工作区标签被工具栏盖住）。
        ui.with_layout(egui::Layout::right_to_left(egui::Align::Center), |ui| {
            右侧(ui, 上下文);
        });
    });
}

/// 绘制模式专用工具栏。返回是否画了任何控件。
///
/// 只放**真实可用**的操作：每个按钮要么改界面状态、要么排一个动作、
/// 要么切换一个真实存在的显示选项。没有实现的工具不会出现在这里。
///
/// # 二维 / 三维：快速创建
///
/// 基础图元按钮放在模式工具栏而不在视口工具条：它产生的是**文档内容**
/// （新实体、新组件、新的撤销记录），和"怎么看待口"是两件事。
/// 按钮只负责发出 [`UiAction::创建基础图元`]，尺寸、颜色、放置点
/// 全部由动作层决定 —— 界面与文档格式因此互不耦合。
///
/// # 这里为什么不画运行控制
///
/// 运行/暂停/单步/停止在**任何**编辑模式下都应当可用，因此它们属于
/// 工具栏的通用部分（见 [`crate::menu_bar::绘制工具栏`]），
/// 由所有模式共享、且只有一份。整改前它们既在本函数（运行模式分支）、
/// 又在通用工具栏里各画了一遍，同一行里出现两个一模一样的「▶ 运行」。
pub fn 绘制模式工具栏(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>) -> bool {
    let 语言 = 上下文.语言;
    let 配色 = 上下文.配色;
    let 图标尺寸 = 上下文.外观.图标尺寸;
    let 模式 = 上下文.界面.模式;

    match 模式 {
        // AI Agent 模式：工具栏只放真实动作，不摆视口工具（这里没有视口）。
        开发模式::智能体 => {
            if ui.button(语言.取("agent_new_session")).clicked() {
                上下文.动作.推(crate::state::UiAction::智能体新建会话);
            }
            if ui
                .add_enabled(
                    上下文.界面.智能体.当前().is_some(),
                    egui::Button::new(语言.取("agent_refresh_changes")),
                )
                .clicked()
            {
                上下文.动作.推(crate::state::UiAction::智能体刷新变更);
            }
            if ui.button(语言.取("agent_attach_scene")).clicked() {
                上下文.动作.推(crate::state::UiAction::智能体附加场景上下文);
            }
            // 这个 match 每个分支返回 bool（"工具栏是否消费了输入"）。
            // AI Agent 的按钮都在工具区里，不消费全局输入。
            false
        }
        开发模式::二维 | 开发模式::三维 => {
            // 视口专用的工具（选择/移动/旋转/缩放、适应窗口、显示开关）
            // 已经搬到**视口自己的顶部工具条**里（见 `viewport_panel::绘制叠加层`），
            // 那里才是它们的语义位置：这些操作作用于画面，不作用于整个编辑器。
            //
            // 全局工具栏因此保持"与视口无关"：运行、编辑、实体、面板。
            ui.label(
                RichText::new(语言.取("quick_create"))
                    .small()
                    .color(配色.次要文字),
            );
            for 类型 in 基础图元类型::全部 {
                if ui
                    .button(语言.取(类型.词条键()))
                    .on_hover_text(语言.取(类型.提示词条键()))
                    .clicked()
                {
                    上下文.动作.推(UiAction::创建基础图元 { 类型 });
                }
            }
            // 光源只对三维场景有意义：二维模式不画这一组，
            // 免得用户点了以后发现画面没有任何变化。
            if 模式 == 开发模式::三维 {
                ui.separator();
                ui.label(
                    RichText::new(语言.取("light_create"))
                        .small()
                        .color(配色.次要文字),
                );
                for 类型 in 光源类型::全部 {
                    if ui
                        .button(语言.取(类型.词条键()))
                        .on_hover_text(语言.取(类型.提示词条键()))
                        .clicked()
                    {
                        上下文.动作.推(UiAction::创建光源 { 类型 });
                    }
                }
            }
            true
        }
        开发模式::脚本 => {
            let 有文档 = 上下文.界面.脚本.当前文档().is_some();
            if 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::保存,
                    Some(语言.取("script_save")),
                    图标尺寸,
                    配色.文字,
                    有文档,
                )
                .on_hover_text(语言.取("script_save_hint"))
                .clicked()
            {
                上下文.动作.推(UiAction::保存脚本);
            }
            if 上下文
                .图标
                .图标按钮(
                    ui,
                    图标::放大,
                    Some(语言.取("script_find")),
                    图标尺寸,
                    配色.文字,
                    有文档,
                )
                .clicked()
            {
                上下文.界面.脚本.显示查找 = true;
            }
            match 上下文.界面.脚本.当前文档() {
                Some(文档) => {
                    ui.label(
                        RichText::new(format!(
                            "{} {}",
                            文档.显示名(语言),
                            if 文档.有未保存修改() {
                                language_unsaved(语言)
                            } else {
                                ""
                            }
                        ))
                        .small()
                        .color(if 文档.有未保存修改() {
                            配色.警告
                        } else {
                            配色.次要文字
                        }),
                    );
                }
                None => {
                    ui.label(
                        RichText::new(语言.取("script_no_file"))
                            .small()
                            .color(配色.次要文字),
                    );
                }
            }
            true
        }
    }
}

fn language_unsaved(语言: crate::i18n::语言) -> &'static str {
    语言.取("script_unsaved")
}

/// 模式按钮在证据文件里的稳定标识。
///
/// 用 `&'static str` 而不是拼出来的字符串：`区域快照.标识` 是 `'static`，
/// 而且证据里的 id 必须跨帧、跨语言稳定，自动验收才能可靠地取到矩形。
fn 模式快照标识(模式: 开发模式) -> &'static str {
    match 模式 {
        开发模式::二维 => "mode_2d",
        开发模式::三维 => "mode_3d",
        开发模式::脚本 => "mode_script",
        开发模式::智能体 => "mode_agent",
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 模式导航顺序稳定() {
        let ids: Vec<&str> = 开发模式::全部().iter().map(|模式| 模式.id()).collect();
        assert_eq!(ids, vec!["2d", "3d", "script", "agent"]);
    }

    #[test]
    fn 每个模式都有名称与说明键() {
        for 模式 in 开发模式::全部() {
            assert!(!模式.名称键().is_empty());
            assert!(!模式.说明键().is_empty());
            assert_ne!(模式.名称键(), 模式.说明键());
        }
    }
}
