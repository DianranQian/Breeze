    #[test]
    fn 每个模式默认布局都可用且彼此不同() {
        let mut 文本: Vec<String> = Vec::new();
        for 模式 in 开发模式::全部() {
            let 布局 = 模式.默认布局();
            // 视口是编辑器主体，除脚本模式外都应当有。
            if *模式 != 开发模式::脚本 {
                assert!(
                    布局.find_tab(&Tab::视口).is_some(),
                    "模式 {} 的默认布局缺少视口",
                    模式.id()
                );
            }
            assert!(
                布局.find_tab(&模式.默认面板()).is_some(),
                "模式 {} 的默认布局缺少自己的主面板",
                模式.id()
            );
            文本.push(ron::ser::to_string(&布局).unwrap_or_default());
        }
        let 原数量 = 文本.len();
        文本.sort();
        文本.dedup();
        assert_eq!(文本.len(), 原数量, "各模式的默认布局必须彼此不同");
    }

