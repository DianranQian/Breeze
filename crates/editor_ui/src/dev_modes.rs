//! 主开发模式：2D / 3D / 代码。
//!
//! # 与"布局预设（工作区）"的区别（这是本模块存在的理由）
//!
//! 编辑器的顶部有两行导航，它们回答的是**两个不同的问题**：
//!
//! | | 主开发模式（本模块） | 工作区（[`crate::workspaces`]） |
//! | --- | --- | --- |
//! | 回答的问题 | 我现在在**编辑什么** | 面板**怎么摆** |
//! | 数量 | 固定三个（2D / 3D / 代码） | 内置四个 + 用户任意个 |
//! | 影响 | 视口类型、专用工具栏、活动编辑内容 | 只影响停靠布局 |
//! | 名称 | 2D / 3D / 代码 | 通用 / 场景 / 资源 / 调试 |
//! | 用户可否删除 | 否 | 用户预设可以 |
//!
//! # 为什么模式只有三个
//!
//! 早期版本还有「运行」与「资源」两个模式。它们与下面的工作区栏
//! （`通用 / 场景 / 资源 / 调试`）在职责上**重复**：
//!
//! * 「资源」模式与「资源」工作区做的是同一件事 —— 把资源浏览器摆到中央；
//! * 「运行」模式与「调试」工作区做的是同一件事 —— 把控制台/运行时/性能摆到显眼处；
//! * 并且工作区栏里还会额外生成一条以模式命名的副本（"运行默认布局"），
//!   使同样的功能在两行各出现一次、名字还不一样。
//!
//! 现在「运行控制」上移到工具栏（每个模式都有、且只有一套），
//! 「资源浏览」与「运行观察」由工作区承担。模式只剩三个**编辑面**
//! ——它们对应三种真正不同的视口与编辑行为，不再与布局维度重叠。
//!
//! # 模式之间共享什么
//!
//! 场景文档、选择、撤销栈、主题、语言全部**共享**：
//! 切模式不会丢实体、不会清选择、不会改主题。模式只切换
//! "看这份数据的角度"与"可用的工具"。

use serde::{Deserialize, Serialize};

use crate::docks::Tab;
use crate::icons::图标;

/// 布局存档的格式版本（模式 + 每模式工作区集）。
pub const 模式存档版本: u32 = 3;

/// 主开发模式。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum 开发模式 {
    /// 2D 场景编辑：二维视口、网格、精灵。
    二维,
    /// 3D 场景编辑：透视视口、轨道相机、空间坐标。
    三维,
    /// 脚本编辑：代码文件、查找、诊断。
    脚本,
}

impl 开发模式 {
    /// 全部模式（顺序即顶部导航顺序）。
    pub fn 全部() -> &'static [开发模式] {
        &[开发模式::二维, 开发模式::三维, 开发模式::脚本]
    }

    /// 稳定 id。**进配置文件，永不随语言变化。**
    pub fn id(self) -> &'static str {
        match self {
            Self::二维 => "2d",
            Self::三维 => "3d",
            Self::脚本 => "script",
        }
    }

    /// 名称键。
    pub fn 名称键(self) -> &'static str {
        match self {
            Self::二维 => "mode_2d",
            Self::三维 => "mode_3d",
            Self::脚本 => "mode_script",
        }
    }

    /// 该模式的说明键（顶部导航的工具提示）。
    pub fn 说明键(self) -> &'static str {
        match self {
            Self::二维 => "mode_2d_hint",
            Self::三维 => "mode_3d_hint",
            Self::脚本 => "mode_script_hint",
        }
    }

    /// 顶部导航图标。
    pub fn 图标(self) -> 图标 {
        match self {
            Self::二维 => 图标::网格,
            Self::三维 => 图标::世界,
            Self::脚本 => 图标::代码,
        }
    }

    /// 从 id 反查。
    pub fn 从id(id: &str) -> Option<Self> {
        Self::全部().iter().copied().find(|模式| 模式.id() == id)
    }

    /// 从**历史 id** 反查（用于读取旧存档）。
    ///
    /// 已移除的两个模式（`run` / `assets`）不再存在。这里显式返回
    /// [`旧模式迁移::已移除`]，让读取存档的代码能给出**具体**的迁移说明，
    /// 而不是把它们当成"未知模式"糊成一条含糊的警告。
    pub fn 兼容旧id(id: &str) -> 旧模式迁移 {
        match id {
            // 用字面量而不是回填参数：`已移除.id` 是 `&'static str`
            // （它会被写进日志与用户可见的迁移说明），参数本身不保证 'static。
            "run" => 旧模式迁移::已移除 {
                id: "run",
                代替: "运行控制已上移到工具栏（每个模式都可用）；观察布局请用「调试」工作区",
            },
            "assets" => 旧模式迁移::已移除 {
                id: "assets",
                代替: "资源浏览请用「资源」工作区",
            },
            _ => match Self::从id(id) {
                Some(模式) => 旧模式迁移::当前(模式),
                None => 旧模式迁移::未知,
            },
        }
    }

    /// 该模式默认激活的面板（新建该模式布局时用）。
    pub fn 默认面板(self) -> Tab {
        match self {
            Self::二维 | Self::三维 => Tab::视口,
            Self::脚本 => Tab::脚本,
        }
    }

    /// 是否使用三维视口。
    pub fn 是三维(self) -> bool {
        self == Self::三维
    }

    /// 该模式的默认布局。
    ///
    /// # 为什么每个模式给一份独立布局，而不是共用一份再"按模式隐藏面板"
    ///
    /// 隐藏面板会让布局里存在大量"看不见的标签"，用户拖动分隔条时
    /// 会发现明明只有两块却分出来五块。独立布局则让每个模式都是一份
    /// 干净、可解释的停靠树。
    ///
    /// 这份布局会成为该模式下「通用」工作区的**出厂布局**
    /// （见 [`crate::workspaces::工作区集::以通用布局`]），
    /// 因此模式切换仍然会改变面板摆放 —— 但并不需要在工作区栏里
    /// 额外造一个和模式同名的假工作区。
    pub fn 默认布局(self) -> egui_dock::DockState<Tab> {
        match self {
            Self::二维 => crate::docks::默认布局(),
            Self::三维 => 三维预设(),
            Self::脚本 => 脚本预设(),
        }
    }
}

/// 读取旧存档时，一个模式 id 的迁移结论。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 旧模式迁移 {
    /// 当前仍然存在的模式。
    当前(开发模式),
    /// 该模式已从产品中移除（附代替它的入口说明）。
    已移除 {
        /// 旧的 id。
        id: &'static str,
        /// 用户应当改用什么入口。
        代替: &'static str,
    },
    /// 完全无法识别的 id。
    未知,
}

/// 3D 模式预设：视口优先，右列检查器/历史，底部控制台/运行时。
///
/// ```text
/// Horizontal(主区 78% | 右列 22%)          ← 检查器/历史/性能
///   └ Vertical(上方 76% | 底部 24%)        ← 控制台/运行时 ECS/资源
///       └ Horizontal(视口 82% | 场景树 18%)
/// ```
fn 三维预设() -> egui_dock::DockState<Tab> {
    let mut 布局 = egui_dock::DockState::new(vec![Tab::视口]);
    let 主 = 布局.main_surface_mut();
    let [主区, _右列] = 主.split_right(
        egui_dock::NodeIndex::root(),
        0.78,
        vec![Tab::检查器, Tab::历史, Tab::时间轴, Tab::性能],
    );
    let [上方, _底部] = 主.split_below(
        主区,
        0.76,
        vec![
            Tab::控制台,
            Tab::构建,
            Tab::运行时ecs,
            Tab::资源浏览器,
            Tab::脚本,
        ],
    );
    let [_视口, _场景树] = 主.split_left(上方, 0.18, vec![Tab::场景树]);
    布局
}

/// 脚本模式预设：编辑区最大，左侧场景/资源，右侧检查器，底部控制台。
///
/// ```text
/// Horizontal(左列 20% | 主区 80%)
///   主区 └ Horizontal(脚本 76% | 右列 24%)
///            右列 = 检查器/历史
///            底部 = 控制台/性能
/// ```
fn 脚本预设() -> egui_dock::DockState<Tab> {
    let mut 布局 = egui_dock::DockState::new(vec![Tab::脚本]);
    let 主 = 布局.main_surface_mut();
    let [主区, _右列] = 主.split_right(
        egui_dock::NodeIndex::root(),
        0.76,
        vec![Tab::检查器, Tab::历史, Tab::时间轴],
    );
    let [上方, _底部] = 主.split_below(
        主区,
        0.72,
        vec![Tab::控制台, Tab::构建, Tab::运行时ecs, Tab::性能],
    );
    let [_脚本, _左列] = 主.split_left(上方, 0.20, vec![Tab::资源浏览器, Tab::场景树, Tab::视口]);
    布局
}

