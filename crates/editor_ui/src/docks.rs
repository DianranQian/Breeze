    ///
    /// 这是**独立于注册表**的第二只眼睛：清单来自枚举声明本身，所以
    /// "只在枚举里加了变体、没在注册表里登记一行"会被下面的测试抓到 ——
    /// 这一条正是 [`面板描述表`] 的 const 自检看不见的情况（排在枚举最后的
    /// 新变体没有代码引用它，编译器不知道它存在）。
    /// 手法与 `crates/editor_app/tests/action_reachability.rs` 一致。
    fn 枚举声明里的变体() -> Vec<String> {
        let 源码 = include_str!("docks.rs");
        let mut 变体 = Vec::new();
        let mut 在块内 = false;
        for 原始行 in 源码.lines() {
            let 行 = 原始行.trim();
            if !在块内 {
                在块内 = 行.starts_with("pub enum Tab {");
                continue;
            }
            if 行 == "}" {
                break;
            }
            if 行.is_empty() || 行.starts_with("//") {
                continue;
            }
            变体.push(行.trim_end_matches(',').to_string());
        }
        assert!(
            变体.len() > 10,
            "变体解析失败了？只解析到 {} 个（Tab 应当有十几个变体）",
            变体.len()
        );
        变体
    }

