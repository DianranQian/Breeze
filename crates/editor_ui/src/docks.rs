/// `通用` 分组的面板数量，编译期按分组数出来，不靠手数。
const 通用面板数量: usize = 计数通用();

/// 全部面板的身份，顺序与注册表一致。
static 全部面板清单: [Tab; 面板注册表.len()] = 取全部面板();

/// `通用` 面板的身份，顺序与注册表一致 —— 也就是拆分前手写的 `Tab::全部()`。
static 通用面板清单: [Tab; 通用面板数量] = 取通用面板();

/// 数注册表里 `通用` 分组有几行。
///
/// 三个派生 `const fn` 用 `matches!` 而不是 `==`：`PartialEq` 不是 `const fn`，
/// 在编译期求值只能走模式匹配。
const fn 计数通用() -> usize {
    let mut 数量 = 0;
    let mut 序号 = 0;
    while 序号 < 面板注册表.len() {
        if matches!(面板注册表[序号].分组, 面板分组::通用) {
            数量 += 1;
        }
        序号 += 1;
    }
    数量
}

/// 按注册表顺序取出每个面板的 `tab`。
const fn 取全部面板() -> [Tab; 面板注册表.len()] {
    // 初值随后会被逐位覆盖；这里只是满足"数组必须全元素初始化"。
    let mut 清单 = [Tab::场景树; 面板注册表.len()];
    let mut 序号 = 0;
    while 序号 < 面板注册表.len() {
        清单[序号] = 面板注册表[序号].tab;
        序号 += 1;
    }
    清单
}

/// 按注册表顺序取出 `通用` 分组的面板。
const fn 取通用面板() -> [Tab; 通用面板数量] {
    let mut 清单 = [Tab::场景树; 通用面板数量];
    let mut 写 = 0;
    let mut 读 = 0;
    while 读 < 面板注册表.len() {
        if matches!(面板注册表[读].分组, 面板分组::通用) {
            清单[写] = 面板注册表[读].tab;
            写 += 1;
        }
        读 += 1;
    }
    清单
}

/// `Tab` 的判别值 → 注册表行，**编译期**构建。
///
/// 建表时校验判别值恰好构成 `0..注册表行数` 的一个排列，于是两类手滑让
/// `cargo check` 直接失败（const 求值错误就是编译错误，不是运行时崩溃）：
///
/// * 注册表少一行（某个变体的判别值 ≥ 行数）→ `a Tab variant has no row in the panel registry`；
/// * 同一个变体登记了两行（重复判别值留下一个填不上的槽）→ `a panel variant is registered twice…`。
///
/// # 看不见的情况，由谁兜住
///
/// Rust 无法在编译期"枚举"一个枚举：只有当新变体被代码**引用**时编译器才知道它存在。
/// 所以「给 `pub enum Tab` 加一个排在最后的变体、注册表一行都没补」这一条 const 手段
/// 看不见 —— 表里根本没有它的槽。兜住它的是两张已有的网：
///
/// 1. 测试 `注册表恰好覆盖每个面板变体`：从 `include_str!("docks.rs")` 解析枚举声明本身，
///    把"枚举清单 == 注册表清单（含顺序）"逐字比较；
/// 2. `lib.rs` 里按 `Tab` 穷尽的 `match tab` 分发：加变体不补臂就编译不过，
///    因此新增面板必然要动那处显式清单，顺手就会补注册表。
///
/// 换言之：这一步消除的是**运行期 panic 分支**（原来那条 `expect`），
/// 而不是宣称编译期能看见枚举的全部变体。
static 面板描述表: [&面板描述; 面板注册表.len()] = 构建面板描述表();

/// 按判别值把 [`面板注册表`] 铺成一张直取表，并在编译期自检。
///
/// 【API 字典】
/// * `const fn`：可在编译期求值的函数。这里的返回值用来初始化 `static`，
///   所以函数体是**编译期**跑的 —— 里面的 `panic!` 表现为 `error[E0080]`，不是崩溃。
/// * `[&面板注册表[0]; N]`：数组 repeat 初始化。引用是 `Copy`，因此合法；
///   初值只是占位，后面逐格覆盖（const 求值不允许"未初始化数组"）。
/// * `行.tab as usize`：枚举判别值。用它而不是注册表下标做键，
///   所以"在表中间插一行"不会让别的面板拿到错的元数据。
///
/// 【逻辑步骤】
/// 1. 逐行取判别值，先判 `>= 面板注册表.len()`（注册表少了行）再写入表并标记已登记；
/// 2. 扫描 `已登记`：留下 `false` 的槽说明判别值不是 0..行数 的一个排列，即重复登记；
/// 3. 返回按判别值直取的表，`Tab::描述` 因此不再需要 `expect`。
const fn 构建面板描述表() -> [&'static 面板描述; 面板注册表.len()] {
    let mut 表 = [&面板注册表[0]; 面板注册表.len()];
    let mut 已登记 = [false; 面板注册表.len()];
    let mut 序号 = 0;
    while 序号 < 面板注册表.len() {
        let 行 = &面板注册表[序号];
        let 判别值 = 行.tab as usize;
        if 判别值 >= 面板注册表.len() {
            panic!("a Tab variant has no row in the panel registry");
        }
        表[判别值] = 行;
        已登记[判别值] = true;
        序号 += 1;
    }
    let mut 检查 = 0;
    while 检查 < 面板注册表.len() {
        if !已登记[检查] {
            panic!("a panel variant is registered twice in the panel registry");
        }
        检查 += 1;
    }
    表
}

impl Tab {
    /// 面板标题（按当前语言）。
    ///
    /// 语言作为参数传入而不是读全局状态：标题是纯展示数据，
    /// 保持成纯函数才好写单元测试。
    pub fn 标题(&self, 语言: crate::i18n::语言) -> &'static str {
        语言.取(self.标题键())
    }

    /// 该面板在 [`面板注册表`] 里的那一行。
    ///
    /// 按判别值直取 [`面板描述表`]：表在编译期建好并自检，所以这条读取**没有**
    /// panic 分支（拆分注册表之初这里是 `find(...).expect(...)`，整张表唯一的
    /// 运行期崩溃点）。缺行与重复登记的护栏见 [`面板描述表`] 的文档。
    fn 描述(&self) -> &'static 面板描述 {
        面板描述表[*self as usize]
    }

    /// 面板标签的词条键。
    ///
    /// 与 [`Tab::菜单键`] 分开：菜单里写的是"资源浏览器"，
    /// 而面板标签为了省宽度只写"资源"，两者的键不同。
    /// 两个键都登记在 [`面板注册表`] 的同一行里。
    pub fn 标题键(&self) -> &'static str {
        self.描述().标题键
    }

    /// 标题的中文原文。
    ///
    /// 只用于人可读的地方（动作摘要、自动验收报告里的面板名），
    /// 不参与翻译查找，因此可以带"▶ 运行"这样的显示符号。
    pub fn 中文标题(&self) -> &'static str {
        self.描述().中文标题
    }

    /// 该面板在「窗口」菜单里的词条键。
    ///
    /// 菜单定义与"文本 → 面板"的反映射都以它为准，
    /// 避免菜单文案一改就两边对不上。
    pub fn 菜单键(&self) -> &'static str {
        self.描述().菜单键
    }

    /// 是否可以关闭。
    ///
    /// 视口是编辑器的主体，关掉它用户就没有任何办法编辑场景了，
    /// 因此不允许关闭；其余面板都可以自由关闭再通过"窗口"菜单打开。
    /// 这个事实登记在 [`面板注册表`] 的 `可关闭` 列。
    pub fn 可关闭(&self) -> bool {
        self.描述().可关闭
    }

    /// 所有**通用**面板，顺序即"窗口"菜单里的显示顺序。
    ///
    /// 由 [`面板注册表`] 的 `通用` 分组在编译期派生，不再是手写的第二份清单。
    ///
    /// # 为什么 AI Agent 的三个面板不在这里
    ///
    /// `Tab::全部()` 是"窗口菜单 / 默认布局 / 内置工作区"的输入，这三处都属于
    /// **通用编辑环境**。AI Agent 有自己的一级模式与专属布局（对话 + 会话 +
    /// 审查），把它混进通用面板会让"恢复默认布局"凭空多出三个与当前工作无关
    /// 的面板，也会让窗口菜单出现"点了却没反应"的项（它们不在当前模式布局里）。
    /// 需要包含 AI 面板的地方用 [`Tab::全部含智能体`]。
    pub fn 全部() -> &'static [Tab] {
        &通用面板清单
    }

    /// 全部面板，**包含** AI Agent 的三个面板（模式布局与测试用）。
    ///
    /// 就是 [`面板注册表`] 的行序本身。
    pub fn 全部含智能体() -> &'static [Tab] {
        &全部面板清单
    }
}

/// 注册表里**尚未被任何预设标签组认领**的通用面板，顺序 = 注册表行序。
///
/// 只取 `分组 == 通用` 的部分（这正是 [`Tab::全部`] 的定义），所以智能体面板
/// 不会因为"没人为它安排位置"而凭空出现在通用工作区里。
pub(crate) fn 待布置面板(已布置: &[Tab]) -> Vec<Tab> {
    Tab::全部()
        .iter()
        .copied()
        .filter(|面板| !已布置.contains(面板))
        .collect()
}

/// 补全出厂布局的一个标签组：`显式` 成员在前，注册表里没被任何一栏认领的面板在后。
///
/// # 为什么出厂布局需要"派生"而不是全靠手写
///
/// 四个内置工作区各自是一份**完整**的工作环境：布局代码要覆盖全部通用面板，
/// 用户不需要先自己去"窗口"菜单里找面板。拆分注册表之前，这件事靠四份硬编码
/// 清单逐条维护，于是新增一个面板就必须同时改默认布局 + 3 个预设，
/// 漏掉一处不会报编译错，只表现为"新面板在某个工作区里打不开"。
///
/// 现在每个预设只声明**设计师显式安排过位置**的面板（这是真正的设计意图，
/// 派生不出来），其余通用面板由 [`待布置面板`] 追加到该预设指定的兜底栏。
/// 于是注册表登记一行，四个工作区自动都有它；而兜底栏的选择仍然是人为决定，
/// 不会把新面板随机丢进视口旁边。
///
/// 目前四份预设的显式清单已经覆盖全部通用面板，派生部分是空的 ——
/// 这条不变量由 `workspaces::测试::每个内置预设的标签组成员与派生前逐字一致` 守住。
pub(crate) fn 补全标签组(显式: &[Tab], 其余各栏: &[&[Tab]]) -> Vec<Tab> {
    let 已布置: Vec<Tab> = 显式
        .iter()
        .chain(其余各栏.iter().flat_map(|栏| 栏.iter()))
        .copied()
        .collect();
    let mut 标签组 = 显式.to_vec();
    标签组.extend(待布置面板(&已布置));
    标签组
}

/// 默认布局。
///
/// 刻意模仿 Godot 的经典四象限：左侧场景树、右侧检查器、
/// 中央视口、底部资源与控制台。这是绝大多数用户已经形成的肌肉记忆，
/// 第一次打开就能找到东西在哪，不需要先学一套新布局。
pub fn 默认布局() -> DockState<Tab> {
    let mut 布局 = DockState::new(vec![Tab::视口]);
    let 主表面 = 布局.main_surface_mut();

    // 布局结构（自外向内）：
    //
    //   Horizontal(主区 74% | 右列 26%)          ← 检查器/历史/运行时ecs/性能
    //     └ Vertical(上方 72% | 底部 28%)        ← 资源浏览器/控制台
    //         └ Horizontal(视口 78% | 场景树 22%)
    //
    // # egui_dock 0.21 的 `fraction` 语义（**已按源码与实测双重确认**）
    //
    // `fraction` 是**第一个子节点**所占的比例（`Node::Split` 的文档原话：
    // "The fraction taken by the top child of this node"）。而 `split_*`
    // 把新节点插到哪一侧决定了"谁是第一个子节点"：
    //
    // | 调用 | 第一个子节点 | 比例>0.5 的效果 |
    // | --- | --- | --- |
    // | `split_right` | **旧**节点（左） | 左侧变宽，右列变窄 |
    // | `split_below` | **旧**节点（上） | 上方变高，底部变矮 |
    // | `split_left`  | **新**节点（左） | 左侧（新）变宽 |
    // | `split_above` | **新**节点（上） | 上方（新）变高 |
    //
    // # 这里踩过两次真实的坑，别再改回去
    //
    // 1. 早期注释写成"fraction 是新节点的比例"，于是 `split_right(0.26)`
    //    被理解成"右列占 26%"，实际得到的是**右列 74%**，检查器撑满窗口；
    // 2. 后来把 `split_right` 改成 `0.74` 修好了右列，但同一条注释还留着，
    //    于是同一份布局里的 `split_below(0.28)` 被当成"底部 28%"，
    //    实际是**底部 72%** —— 视口被压成一条窄带。
    //
    // 第 2 个缺陷在改用"进程内渲染目标回读"截图后**一眼就看到了**，
    // 而在此之前靠 `PrintWindow` 的图根本判断不了。默认布局的几何测试
    // 现在会按真实矩形断言各栏占比，方向写反必然失败。
    //
    // 另一条必须记住的语义：`split_*` 返回 `[旧节点, 新节点]`，
    // 且旧节点可能被换到别的索引，因此后续 split 必须用返回的索引，
    // 不能反复写 `NodeIndex::root()`（它恒等于 `NodeIndex(0)`）。
    //
    // 顺序也必须是这样：先切出整条右列，再在"主区"里切出底部，
    // 最后在"上方"里切出左侧场景树。这样底部区域横跨左+中两列，
    // 与 Godot 一致。
    let 右列: &[Tab] = &[
        Tab::检查器,
        Tab::历史,
        // 时间轴放在右列：它与检查器看同一批实体，左右相邻最顺手。
        Tab::时间轴,
        Tab::运行时ecs,
        Tab::性能,
    ];
    let 左列: &[Tab] = &[Tab::场景树, Tab::项目文件树];
    let 底部 = 补全标签组(
        &[
            Tab::资源浏览器,
            // 预制件面板紧挨资源浏览器：两者都是"从项目资产拖进场景"的入口。
            Tab::预制件,
            Tab::控制台,
            // 构建与诊断紧挨控制台：两者都是"输出的地方"。
            Tab::构建,
            // 运行与诊断同一个区域：看完构建错误接着就要跑一次。
            Tab::运行,
            Tab::脚本,
            // 瓦片地图是"边画边看视口"的工作，放在底部标签组里。
            Tab::瓦片地图,
        ],
        &[&[Tab::视口], 右列, 左列],
    );
    let [主区, _右列] = 主表面.split_right(NodeIndex::root(), 0.74, 右列.to_vec());
    // 0.72 = 上方（旧节点）占 72%，底部 28%。
    let [上方, _底部] = 主表面.split_below(主区, 0.72, 底部);
    // 0.22 = 左侧（新节点）占 22%。
    let [_视口, _场景树] = 主表面.split_left(上方, 0.22, 左列.to_vec());

    布局
}

/// 在给定的逻辑尺寸下跑**一帧真实 Dock 布局**，返回每个激活标签的内容矩形。
///
/// 仅用于测试（`cfg(test)`），供 `docks` 与 `workspaces` 两个测试模块共用。
///
/// # 为什么这是唯一可靠的几何验证手段
///
/// 直接读 `DockState` 的内部字段既脆弱，也拿不到真实像素尺寸 ——
/// `fraction` 写反这类缺陷只会在"真正布局一次"之后才暴露成矩形比例异常。
/// 这里用一个离屏 `egui::Context` 跑真实的一帧，从
/// `TabViewer::ui` 的 `ui.max_rect()` 取真实内容矩形，走的全是公开 API。
#[cfg(test)]
pub(crate) fn 测量布局矩形(
    停靠: &mut DockState<Tab>,
    尺寸: egui::Vec2,
) -> Vec<(Tab, egui::Rect)> {
    /// 记录每个标签实际拿到的矩形。
    struct 记录查看器 {
        矩形: Vec<(Tab, egui::Rect)>,
    }

    impl egui_dock::TabViewer for 记录查看器 {
        type Tab = Tab;

        fn id(&mut self, tab: &mut Self::Tab) -> egui::Id {
            egui::Id::new(("布局几何测试", format!("{:?}", tab)))
        }

        fn title(&mut self, tab: &mut Self::Tab) -> egui::WidgetText {
            (*tab).标题(crate::i18n::语言::中文).into()
        }

        fn ui(&mut self, ui: &mut egui::Ui, tab: &mut Self::Tab) {
            self.矩形.push((*tab, ui.max_rect()));
            ui.label("内容");
        }
    }

    let 上下文 = egui::Context::default();
    let 输入 = egui::RawInput {
        screen_rect: Some(egui::Rect::from_min_size(egui::Pos2::ZERO, 尺寸)),
        ..Default::default()
    };
    let mut 查看器 = 记录查看器 { 矩形: Vec::new() };
    上下文.begin_pass(输入);
    {
        let ctx = &上下文;
        let mut 根界面 = egui::Ui::new(
            ctx.clone(),
            egui::Id::new("布局几何测试根界面"),
            egui::UiBuilder::new().max_rect(egui::Rect::from_min_size(egui::Pos2::ZERO, 尺寸)),
        );
        egui_dock::DockArea::new(停靠).show_inside(&mut 根界面, &mut 查看器);
    }
    let mut 输出 = 上下文.end_pass();
    // egui 要求纹理增量必须被处理；测试里不渲染，显式清空，
    // 否则 epaint 会在 drop 时 panic（"Dropped TexturesDelta"）。
    输出.textures_delta.clear();
    查看器.矩形
}

