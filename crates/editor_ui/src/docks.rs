//! 停靠布局与面板定义。

use egui_dock::{DockState, NodeIndex};

/// 编辑器里的一个可停靠面板。
///
/// 用枚举而不是字符串标识：这样"新增面板"是一个编译器会强制处理的变更，
/// 不会出现"面板加进布局了但绘制分发忘了加分支"这种只在运行时暴露的问题。
///
/// 派生 `Serialize` / `Deserialize` 是为了把用户的布局持久化到磁盘。
/// 用枚举还有一个额外好处：布局文件里存的是 `场景树` 这样的**变体名**，
/// 而不是依赖声明顺序的索引 —— 将来在枚举中间插入一个新面板，
/// 也不会让旧布局文件里的面板错位成别的面板。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub enum Tab {
    /// 场景树。
    场景树,
    /// 项目文件树（`src/` 与根目录核心文件的浏览入口）。
    项目文件树,
    /// 属性检查器。
    检查器,
    /// 中央视口。
    视口,
    /// 资源浏览器。
    资源浏览器,
    /// 预制件面板。
    预制件,
    /// 控制台。
    控制台,
    /// 撤销历史。
    历史,
    /// 运行时 ECS 浏览。
    运行时ecs,
    /// 性能统计。
    性能,
    /// 脚本编辑器。
    脚本,
    /// 构建与诊断。
    构建,
    /// 运行与诊断（开发工作台）：入口选择、构建/运行/停止、日志与诊断。
    运行,
    /// 动画时间轴。
    时间轴,
    /// 瓦片地图（`.terrain.ron` 的地表/覆盖编辑）。
    瓦片地图,
    /// AI Agent 对话与任务执行（一级模式的主工作区）。
    智能体对话,
    /// AI Agent 会话列表与 DSH 连接状态。
    智能体会话,
    /// AI Agent 上下文与文件变更审查。
    智能体审查,
}

/// 面板所属的工作区域分组。
///
/// 它回答的是"这个面板属于通用编辑环境，还是属于 AI Agent 的一级模式"，
/// 也就是 [`Tab::全部`] 与 [`Tab::全部含智能体`] 的分界线。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 面板分组 {
    /// 通用编辑环境：出现在「窗口」菜单、「恢复默认布局」与内置工作区里。
    通用,
    /// AI Agent 一级模式的专属面板，不进「窗口」菜单。
    智能体,
}

/// 一个面板的全部静态元数据。
///
/// 面板身份**只在这里登记一次**。以下四处过去各自维护一份清单，现在全部
/// 由 [`面板注册表`] 派生：
///
/// * 标签标题的词条键、菜单文案的词条键、标题的中文原文；
/// * 能否关闭 / 能否拖成浮动窗口；
/// * `Tab::全部()` 与 `Tab::全部含智能体()` 两份面板清单；
/// * 「窗口」菜单的菜单项，以及"菜单文本 → 面板"的反映射
///   （`menu_bar::窗口菜单对应面板`）。
///
/// 唯一不能由查表代替的是 `lib.rs` 里按 `Tab` 穷尽的 `match tab` 分发：
/// 它把"面板登记了、但绘制忘了接"挡在编译期。新增面板仍然要在那里补一行。
#[derive(Debug, Clone, Copy)]
pub(crate) struct 面板描述 {
    /// 面板身份。布局存档里存的是它的**变体名**，与这张表的下标无关，
    /// 因此在表中间插入一行不会让旧存档的面板错位成别的面板。
    pub tab: Tab,
    /// 面板标签的词条键。
    ///
    /// 与 [`面板描述::菜单键`] 分开：菜单里写"资源浏览器"，
    /// 而面板标签为了省宽度只写"资源"，两者的键不同。
    pub 标题键: &'static str,
    /// 该面板在「窗口」菜单里的词条键。
    ///
    /// 它同时是自动验收工具给区域快照起的名字（`lib.rs` 的 `记录区域`），
    /// 所以必须与 `Tab::全部()` 一起稳定。
    pub 菜单键: &'static str,
    /// 标题的中文原文。
    ///
    /// 用于动作摘要与验收报告里的人可读名字，不参与翻译查找，
    /// 因此允许写成"▶ 运行"这种带符号的显示名。
    pub 中文标题: &'static str,
    /// 是否可以被关闭、是否允许浮动成独立窗口。
    ///
    /// 视口是编辑器的主体，关掉它用户就没有任何办法编辑场景了，因此它是
    /// 整张表里唯一 `可关闭: false` 的一行。
    pub 可关闭: bool,
    /// 属于哪个工作区域。
    pub 分组: 面板分组,
}

