//! 场景变换工具（2D 与 3D 共用的那一半）。
//!
//! # 统一哪些、分开哪些
//!
//! 这个模块只放**与视口维度无关**的东西：
//!
//! * 工具模式（选择 / 移动 / 旋转 / 缩放）与它的快捷键、文案键；
//! * 操纵器部件（被悬停、被按下、被拖拽的那个东西）的枚举与代号；
//! * 一次拖拽的**生命周期数据**（[`拖拽会话`]）与它的求解基准；
//! * 四元数、线段距离、箭头/方块/圆环的绘制原语；
//! * 主题到轴颜色的映射。
//!
//! 而**几何求解**必须分开写，见 [`crate::gizmo2d`] 与 [`crate::gizmo3d`]：
//! 2D 是"屏幕像素 ↔ 世界平面"的仿射映射，3D 是"屏幕射线 ↔ 世界直线/平面"的
//! 求交，两者的退化情况、容差与尺度策略完全不同。把它们硬塞进一个函数，
//! 只会得到一个谁都不敢改的巨型 `match`。
//!
//! # 坐标系约定（与既有视口一致）
//!
//! * 2D：世界 y 向上、屏幕 y 向下，映射由 [`crate::state::视口相机`] 负责；
//! * 3D：`变换.平移` 被视口当作**世界位置**使用（与 `viewport3d::画实体`
//!   和 `viewport_panel::计算实体框` 完全一致），本模块不引入第二套解释。

