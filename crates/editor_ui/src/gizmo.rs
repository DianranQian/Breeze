/// 四元数 `(x, y, z, w)` 乘法（Hamilton 积）。
///
/// 约定：`四元数乘(a, b)` 表示"先施加 b、再施加 a"（与 Bevy/glam 的
/// `a * b` 一致）。局部轴旋转因此写成 `起始 * 增量`。
pub fn 四元数乘(左: (f32, f32, f32, f32), 右: (f32, f32, f32, f32)) -> (f32, f32, f32, f32) {
    let (lx, ly, lz, lw) = 左;
    let (rx, ry, rz, rw) = 右;
    (
        lw * rx + lx * rw + ly * rz - lz * ry,
        lw * ry - lx * rz + ly * rw + lz * rx,
        lw * rz + lx * ry - ly * rx + lz * rw,
        lw * rw - lx * rx - ly * ry - lz * rz,
    )
}

/// 绕单位轴旋转 `角` 弧度的四元数。
pub fn 绕轴四元数(轴: (f32, f32, f32), 角: f32) -> (f32, f32, f32, f32) {
    let 半 = 角 * 0.5;
    let 正弦 = 半.sin();
    (轴.0 * 正弦, 轴.1 * 正弦, 轴.2 * 正弦, 半.cos())
}

/// 规范化四元数；长度过小时退回单位四元数。
///
/// 退化输入（长度 0、NaN）必须被兜住：四元数一旦变成 NaN，写到文档里
/// 之后整个实体会消失，而场景文件仍然是"合法"的 —— 这种损坏最难排查。
pub fn 规范化四元数(四元数: (f32, f32, f32, f32)) -> (f32, f32, f32, f32) {
    let (x, y, z, w) = 四元数;
    let 长度 = (x * x + y * y + z * z + w * w).sqrt();
    if !长度.is_finite() || 长度 < 1e-6 {
        return (0.0, 0.0, 0.0, 1.0);
    }
    (x / 长度, y / 长度, z / 长度, w / 长度)
}

/// 绕轴施加一个增量角，返回新的旋转四元数。
pub fn 施加旋转(
    起始: (f32, f32, f32, f32),
    轴: (f32, f32, f32),
    角: f32,
) -> (f32, f32, f32, f32) {
    规范化四元数(四元数乘(起始, 绕轴四元数(轴, 角)))
}

// ---------------------------------------------------------------------------
// 缩放分量保护（2D 与 3D 共用）
// ---------------------------------------------------------------------------

/// 缩放分量的合法下限（绝对值）。
pub const 缩放下限: f32 = 1e-3;
/// 缩放分量的合法上限（绝对值）。
pub const 缩放上限: f32 = 1.0e4;

/// 把缩放分量收拢到合法范围。
///
/// * 非有限值（NaN / ±∞）→ 退回 `备用`（通常是原值），
///   绝不让 NaN 进入文档：写到场景文件里之后整个实体会消失，
///   而文件本身仍然是"合法"的，这种损坏最难排查；
/// * 绝对值过小 → 收到下限，且**保留符号**：因此把指针拖过中心时
///   缩放只会停在极小值，不会突然翻面（"意外翻转"）；
/// * 绝对值过大 → 收到上限，避免一次误拖把物体放大到相机都装不下。
pub fn 收拢缩放(值: f32, 备用: f32) -> f32 {
    if !值.is_finite() {
        return 备用;
    }
    let 符号 = if 值 < 0.0 { -1.0 } else { 1.0 };
    符号 * 值.abs().clamp(缩放下限, 缩放上限)
}

// ---------------------------------------------------------------------------
// 几何原语（绘制与命中测试共用）
// ---------------------------------------------------------------------------

/// 点到线段的距离（屏幕空间）。
///
/// 命中容差是按**屏幕像素**定的，因此这里一律用屏幕坐标，不做世界单位换算：
/// 世界单位在缩放变化时会改变视觉粗细，用世界容差会让"放大后点不中"。
pub fn 点到线段距离(点: Pos2, 起: Pos2, 终: Pos2) -> f32 {
    let 段 = 终 - 起;
    let 长平方 = 段.length_sq();
    if 长平方 < 1e-9 {
        return (点 - 起).length();
    }
    let 投影 = ((点 - 起).dot(段) / 长平方).clamp(0.0, 1.0);
    let 最近 = 起 + 段 * 投影;
    (点 - 最近).length()
}

/// 点到折线（圆环等）的最短距离。
pub fn 点到折线距离(点: Pos2, 折线: &[Pos2]) -> f32 {
    if 折线.len() < 2 {
        return f32::MAX;
    }
    折线
        .windows(2)
        .map(|段| 点到线段距离(点, 段[0], 段[1]))
        .fold(f32::MAX, f32::min)
}

/// 点是否在多边形内（射线法）。
pub fn 点在多边形内(点: Pos2, 多边形: &[Pos2]) -> bool {
    if 多边形.len() < 3 {
        return false;
    }
    let mut 内 = false;
    let mut j = 多边形.len() - 1;
    for i in 0..多边形.len() {
        let (a, b) = (多边形[i], 多边形[j]);
        if (a.y > 点.y) != (b.y > 点.y) {
            let 交点x = a.x + (点.y - a.y) / (b.y - a.y) * (b.x - a.x);
            if 点.x < 交点x {
                内 = !内;
            }
        }
        j = i;
    }
    内
}

/// 指针到图元的最短屏幕距离。
pub fn 图元距离(图元: &图元, 指针: Pos2) -> f32 {
    match 图元 {
        图元::线段 { 起, 终 } | 图元::箭头 { 起, 终 } => {
            点到线段距离(指针, *起, *终)
        }
        图元::方块轴 { 起, 终, 半边 } => {
            // 端帽也算命中区域：否则贴着方块点会"漏"。
            点到线段距离(指针, *起, *终).min((指针 - *终).length() - *半边)
        }
        图元::实心方块 { 中心, 半边 } | 图元::空心方块 { 中心, 半边 } => {
            ((指针 - *中心).length() - *半边).max(0.0)
        }
        图元::折线(点) => 点到折线距离(指针, 点),
        图元::四边形(点) => {
            if 点在多边形内(指针, 点) {
                0.0
            } else {
                let mut 闭合 = 点.clone();
                if let Some(首) = 点.first() {
                    闭合.push(*首);
                }
                点到折线距离(指针, &闭合)
            }
        }
    }
}

/// 绘制一个图元。
pub fn 绘制图元(
    画布: &egui::Painter, 图元: &图元, 色: Color32, 线宽: f32, 配色: &编辑器配色
) {
    match 图元 {
        图元::线段 { 起, 终 } => {
            画布.line_segment([*起, *终], Stroke::new(线宽, 色));
        }
        图元::箭头 { 起, 终 } => 画箭头(画布, *起, *终, 色, 线宽),
        图元::方块轴 { 起, 终, 半边 } => {
            画方块手柄(画布, *起, *终, 色, 线宽, *半边);
        }
        图元::实心方块 { 中心, 半边 } => {
            let 方块 = Rect::from_center_size(*中心, Vec2::splat(*半边 * 2.0));
            画布.rect_filled(方块, 1.0, 色);
            画布.rect_stroke(
                方块,
                1.0,
                Stroke::new(1.0, 配色.视口背景),
                egui::StrokeKind::Inside,
            );
        }
        图元::空心方块 { 中心, 半边 } => {
            let 方块 = Rect::from_center_size(*中心, Vec2::splat(*半边 * 2.0));
            画布.rect_stroke(
                方块,
                1.0,
                Stroke::new(线宽.max(1.5), 色),
                egui::StrokeKind::Inside,
            );
        }
        图元::折线(点) => {
            if 点.len() >= 2 {
                画布.add(egui::Shape::line(点.clone(), Stroke::new(线宽, 色)));
            }
        }
        图元::四边形(点) => {
            if 点.len() >= 3 {
                // 半透明填充 + 实线边框：填充让"这是一个面"一眼可读，
                // 边框保证在深色场景上仍然看得见。
                画布.add(egui::Shape::convex_polygon(
                    点.clone(),
                    填充淡化(色),
                    Stroke::new(线宽, 色),
                ));
            }
        }
    }
}

/// 把颜色变淡，用作平面手柄的填充。
fn 填充淡化(色: Color32) -> Color32 {
    Color32::from_rgba_unmultiplied(色.r(), 色.g(), 色.b(), 64)
}

/// 绘制一个部件的全部图元。
pub fn 绘制部件(
    画布: &egui::Painter,
    几何: &部件几何,
    色: Color32,
    线宽: f32,
    配色: &编辑器配色,
) {
    for 图元 in &几何.图元 {
        绘制图元(画布, 图元, 色, 线宽, 配色);
    }
}

/// 命中测试：返回指针下方**最贴合**的部件。
///
/// 用"距离 / 该部件容差"作为得分并取最小，而不是"先命中先返回"：
/// 中心手柄与轴起点都在中心附近，用归一化得分才能让"离中心 3px"
/// 稳定地落到中心手柄、而"离轴 3px 但离中心 40px"落到轴上。
pub fn 命中(部件列表: &[部件几何], 指针: Pos2) -> Option<操纵器部件> {
    let mut 最佳: Option<(f32, 操纵器部件)> = None;
    for 项 in 部件列表 {
        let 距离 = 项.距离(指针);
        if 距离 > 项.容差 {
            continue;
        }
        let 得分 = 距离 / 项.容差;
        if 最佳.map(|(分, _)| 得分 < 分).unwrap_or(true) {
            最佳 = Some((得分, 项.部件));
        }
    }
    最佳.map(|(_, 部件)| 部件)
}

/// 从中心指向指针的屏幕单位向量；退化时返回右方向。
pub fn 屏幕径向方向(中心: Pos2, 指针: Pos2) -> Vec2 {
    let 差 = 指针 - 中心;
    if 差.length() < 1e-4 {
        return Vec2::X;
    }
    差 / 差.length()
}

/// 屏幕切线方向（逆时针 90°）。
pub fn 切线方向(径向: Vec2) -> Vec2 {
    Vec2::new(-径向.y, 径向.x)
}

/// 画一条带箭头的手柄（轴线 + 箭头）。
pub fn 画箭头(画布: &egui::Painter, 起: Pos2, 终: Pos2, 色: Color32, 线宽: f32) {
    let 方向 = 终 - 起;
    if 方向.length() < 1.0 {
        return;
    }
    画布.line_segment([起, 终], Stroke::new(线宽, 色));
    let 单位 = 方向 / 方向.length();
    let 法线 = 切线方向(单位);
    let 尖长 = 11.0;
    let 半宽 = 5.0;
    let 底 = 终 - 单位 * 尖长;
    画布.add(egui::Shape::convex_polygon(
        vec![终, 底 + 法线 * 半宽, 底 - 法线 * 半宽],
        色,
        Stroke::NONE,
    ));
}

/// 画一条带方块手柄的轴线（缩放用）。
pub fn 画方块手柄(
    画布: &egui::Painter,
    起: Pos2,
    终: Pos2,
    色: Color32,
    线宽: f32,
    半边长: f32,
) {
    画布.line_segment([起, 终], Stroke::new(线宽, 色));
    let 方块 = Rect::from_center_size(终, Vec2::splat(半边长 * 2.0));
    画布.rect_filled(方块, 1.0, 色);
}

/// 画一个圆环（折线近似）。
pub fn 画圆环(
    画布: &egui::Painter, 中心: Pos2, 半径: f32, 色: Color32, 线宽: f32, 段数: usize
) {
    let 段数 = 段数.max(12);
    let 点: Vec<Pos2> = (0..=段数)
        .map(|下标| {
            let 角 = std::f32::consts::TAU * 下标 as f32 / 段数 as f32;
            中心 + Vec2::new(角.cos(), 角.sin()) * 半径
        })
        .collect();
    画布.add(egui::Shape::line(点, Stroke::new(线宽, 色)));
}

/// 生成屏幕空间圆环的折线点（3D 投影圆环与 2D 圆环共用）。
pub fn 圆环折线(中心: Pos2, 半径: f32, 段数: usize) -> Vec<Pos2> {
    let 段数 = 段数.max(12);
    (0..=段数)
        .map(|下标| {
            let 角 = std::f32::consts::TAU * 下标 as f32 / 段数 as f32;
            中心 + Vec2::new(角.cos(), 角.sin()) * 半径
        })
        .collect()
}

/// 部件当前应该用的线宽与强调程度。
pub fn 部件强调(
    悬停: Option<操纵器部件>, 拖拽: Option<操纵器部件>, 部件: 操纵器部件
) -> f32 {
    if 拖拽 == Some(部件) {
        3.0
    } else if 悬停 == Some(部件) {
        2.5
    } else {
        1.6
    }
}

/// 按悬停/拖拽状态挑选部件颜色：正在操作的那个用强调色，其余用轴色。
pub fn 部件颜色(
    配色: &编辑器配色,
    轴: Option<轴>,
    悬停: Option<操纵器部件>,
    拖拽: Option<操纵器部件>,
    部件: 操纵器部件,
) -> Color32 {
    let 激活 = 拖拽 == Some(部件) || (拖拽.is_none() && 悬停 == Some(部件));
    if 激活 {
        return 配色.强调;
    }
    match 轴 {
        Some(轴) => 轴颜色(配色, 轴),
        // 平面手柄与等比缩放不属于任何单轴：用次要文字色 + 淡填充表示，
        // 避免让用户误以为它是某条轴。
        None => 配色.次要文字,
    }
}

