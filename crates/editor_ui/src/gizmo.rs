/// 收集当前选中实体在**按下那一刻**的变换，作为拖拽的绝对基准。
///
/// 只收集有变换的实体：纯逻辑实体没有变换，把它们塞进会话只会让
/// "未选中实体不发生变化"这条契约变模糊。
pub fn 收集选中变换(编辑器: &编辑器状态) -> Vec<(实体标识, 变换数据)> {
    编辑器
        .选择
        .全部()
        .into_iter()
        .filter_map(|标识| {
            编辑器
                .会话
                .文档
                .取(标识)
                .and_then(|实体| 实体.变换)
                .map(|变换| (标识, 变换))
        })
        .collect()
}

/// 开始一次拖拽会话。返回是否真的开始了。
pub fn 开始会话(
    上下文: &mut 绘制上下文<'_>,
    工具: 变换工具,
    部件: 操纵器部件,
    基准: 拖拽基准,
) -> bool {
    let 起始 = 收集选中变换(上下文.编辑器);
    if 起始.is_empty() {
        return false;
    }
    上下文.界面.操纵器拖拽 = Some(拖拽会话::新建(工具, 部件, 起始, 基准));
    true
}

/// 把一帧的求解结果写成预览动作。
///
/// **只推进动作队列，不改文档**：界面层拿不到可变文档，而且"谁在什么时候
/// 改了文档"必须只有一个入口（`editor_app::actions`）。
pub fn 推送预览(上下文: &mut 绘制上下文<'_>, 项: Vec<(实体标识, 变换数据)>) {
    上下文.动作.推(UiAction::预览变换 { 项 });
}

/// 结束会话：`提交` 为真则提交一次（无实际变化时不产生撤销记录），
/// 否则取消并恢复起始变换。
pub fn 收尾(上下文: &mut 绘制上下文<'_>, 会话: 拖拽会话, 提交: bool) {
    if !提交 {
        上下文.动作.推(UiAction::取消变换 {
            起始: 会话.起始.clone(),
        });
        return;
    }
    if 会话.无变化() {
        // 零位移：文档在预览里也没被改过，不该留下撤销记录。
        return;
    }
    上下文.动作.推(UiAction::提交变换 {
        起始: 会话.起始.clone(),
        最终: 会话.最新.clone(),
    });
}

/// 主选中实体在视口里的世界位置（2D 取 xy，3D 取 xyz）。
///
/// 取**世界变换**：操纵器必须落在实体实际绘制的位置上，而子实体的本地
/// 变换只是相对父级的。预览尚未就绪时，顶层实体的本地变换就是世界变换。
///
/// 锁定或隐藏的实体不参与变换：`编辑器锁定` 的语义就是"不可在视口中被
/// 拖动"，给锁定实体画一个能拖的操纵器会与这条契约直接冲突。
pub fn 操纵器原点(
    编辑器: &编辑器状态,
    世界变换: &世界变换表,
) -> Option<(实体标识, 变换数据)> {
    let 标识 = 编辑器.选择.主选中()?;
    let 实体 = 编辑器.会话.文档.取(标识)?;
    if 实体.编辑器锁定 {
        return None;
    }
    let 变换 = match 世界变换.get(&标识).copied() {
        Some(变换) => 变换,
        None if 实体.父实体.is_none() => 实体.变换?,
        None => return None,
    };
    Some((标识, 变换))
}

/// 等比缩放：每拖动多少像素对应 1.0 的比例变化。
///
/// 120px 让"从中心拖出一整条轴长（64px）"大约变成 1.5 倍，手感接近
/// 主流编辑器；太大的话轻轻一动就翻倍，太小则拖到手酸。
pub const 等比缩放每格像素: f32 = 120.0;

/// 由"到中心的屏幕距离变化"换算等比缩放比例。
///
/// 见 [`拖拽基准::屏幕距离`] 的说明：比例取 `1 + Δ距离 / 每格像素`，
/// 起点距离为 0 也成立，且结果恒为正。
pub fn 距离换算比例(当前距离: f32, 起点距离: f32) -> f32 {
    if !当前距离.is_finite() || !起点距离.is_finite() {
        return 1.0;
    }
    let 比例 = 1.0 + (当前距离 - 起点距离) / 等比缩放每格像素;
    // 下界取一个很小的正数：用户把指针拖回中心甚至越过中心时，
    // 物体只会缩到极小，不会翻面（翻面会让用户以为"模型坏了"）。
    比例.clamp(0.02, 50.0)
}

/// 把一组 `(x, y)` 的屏幕点写成证据用的矩形记录。
pub fn 包围盒到证据(矩形: Rect) -> [f32; 4] {
    [矩形.min.x, 矩形.min.y, 矩形.width(), 矩形.height()]
}

/// 处理工具快捷键（Q/W/E/R）。
///
/// 返回是否切换了工具，调用方据此决定是否跳过后面的快捷键处理。
/// 文本编辑中一律不响应：用户重命名实体时按 R 不应该把工具切走。
pub fn 处理工具快捷键(ui: &egui::Ui, 上下文: &mut 绘制上下文<'_>) -> bool {
    if 上下文.界面.文本编辑.is_some() {
        return false;
    }
    let 按下: Vec<egui::Key> = ui.input(|输入| {
        变换工具::全部()
            .into_iter()
            .filter(|工具| 输入.key_pressed(工具.快捷键()))
            .map(|工具| 工具.快捷键())
            .collect()
    });
    for 键 in 按下 {
        if let Some(工具) = 变换工具::全部()
            .into_iter()
            .find(|工具| 工具.快捷键() == 键)
        {
            切换工具(上下文, 工具);
            return true;
        }
    }
    false
}

