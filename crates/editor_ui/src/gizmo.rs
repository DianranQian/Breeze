/// 绘制"选择 / 移动 / 旋转 / 缩放"工具组，返回被点中的工具。
///
/// 只在 2D/3D 视口模式里出现：代码/运行/资源模式没有可变换的视口，
/// 把工具放在那里只会让用户点了没反应。
pub fn 绘制工具组(
    ui: &mut egui::Ui, 上下文: &mut 绘制上下文<'_>
) -> Option<变换工具> {
    let 语言 = 上下文.语言;
    let 当前 = 上下文.界面.变换工具;
    let mut 结果 = None;

    // 纯图标：四个工具在视口里是**一组互斥模式**，不是四个命令。
    // 文字版（"选择/移动/旋转/缩放"）会占掉视口上方一整段宽度，
    // 而且和 Godot 那类视口工具条的语言不同；名称与快捷键放进悬停提示。
    let 边长 = (上下文.外观.基础字号 + 15.0).max(29.0);
    let 图标尺寸 = 上下文.外观.图标尺寸;
    ui.spacing_mut().item_spacing.x = 1.0;
    for 工具 in 变换工具::全部() {
        let 激活 = 工具 == 当前;
        let 图标项 = match 工具 {
            变换工具::选择 => crate::icons::图标::指针,
            变换工具::移动 => crate::icons::图标::移动,
            变换工具::旋转 => crate::icons::图标::旋转,
            变换工具::缩放 => crate::icons::图标::缩放,
        };
        let Some(纹理) = 上下文.图标.纹理(ui.ctx(), 图标项) else {
            // 图标资源缺失时退回文字按钮，保证工具仍然可切换。
            let 响应 = ui.selectable_label(激活, 语言.取(工具.名称键()));
            上下文.界面.布局快照.push(crate::state::区域快照 {
                标识: 工具.区域标识(),
                矩形: 响应.rect,
            });
            if 响应.clicked() && !激活 {
                结果 = Some(工具);
            }
            continue;
        };
        let 纹理 = egui::load::SizedTexture::new(纹理.id(), egui::vec2(图标尺寸, 图标尺寸));
        let 响应 = crate::visual_spec::图标分段按钮(ui, 上下文.配色, 边长, &纹理, 激活, true)
            .on_hover_text(format!(
                "{}（{}）",
                语言.取(工具.名称键()),
                快捷键名(工具.快捷键())
            ));
        // 记录工具按钮的真实矩形：自动验收按矩形中心点击来切换工具，
        // 而不是靠"猜工具栏第几个按钮"。
        上下文.界面.布局快照.push(crate::state::区域快照 {
            标识: 工具.区域标识(),
            矩形: 响应.rect,
        });
        if 响应.clicked() && !激活 {
            结果 = Some(工具);
        }
    }
    结果
}

/// 快捷键的显示名（`Q` / `W` / `E` / `R`）。
fn 快捷键名(键: egui::Key) -> &'static str {
    match 键 {
        egui::Key::Q => "Q",
        egui::Key::W => "W",
        egui::Key::E => "E",
        egui::Key::R => "R",
        _ => "?",
    }
}

/// 切换工具时要排的动作。
///
/// 工具是**界面状态**，但切换会牵动两件事：正在进行的拖拽必须取消，
/// 悬停高亮必须清掉。把它们收在一个函数里，避免每个调用点各写一遍
/// （漏掉一处就会出现"换了工具但操纵器还在跟着鼠标动"）。
pub fn 切换工具(上下文: &mut 绘制上下文<'_>, 工具: 变换工具) {
    if 上下文.界面.变换工具 == 工具 {
        return;
    }
    取消当前拖拽(上下文);
    // 切到"选择"时保留悬停为空；其余工具下一帧会重新计算悬停。
    上下文.界面.操纵器悬停 = None;
    上下文.界面.变换工具 = 工具;
}

/// 取消当前拖拽（如果有），把文档恢复成拖拽开始前的变换。
pub fn 取消当前拖拽(上下文: &mut 绘制上下文<'_>) {
    let Some(会话) = 上下文.界面.操纵器拖拽.take() else {
        return;
    };
    上下文.动作.推(UiAction::取消变换 {
        起始: 会话.起始.clone(),
    });
}

