#[cfg(test)]
mod 测试 {
    use super::*;

    /// 角度 → 四元数 → 再转回绕轴角度，用于验证旋转组合。
    fn 绕_z角(角: f32) -> (f32, f32, f32, f32) {
        绕轴四元数(轴::Z.单位(), 角)
    }

    #[test]
    fn 绕_z旋转九十度得到半角正弦余弦() {
        let q = 绕_z角(std::f32::consts::FRAC_PI_2);
        let 半角 = std::f32::consts::FRAC_PI_4;
        assert!((q.0).abs() < 1e-6);
        assert!((q.1).abs() < 1e-6);
        assert!(
            (q.2 - 半角.sin()).abs() < 1e-6,
            "z 分量应为 sin(45°)：{q:?}"
        );
        assert!(
            (q.3 - 半角.cos()).abs() < 1e-6,
            "w 分量应为 cos(45°)：{q:?}"
        );
    }

    #[test]
    fn 两次九十度等于一次一百八十度() {
        let 九十 = 绕_z角(std::f32::consts::FRAC_PI_2);
        let 两次 = 四元数乘(九十, 九十);
        let 一次 = 绕_z角(std::f32::consts::PI);
        assert!((两次.2 - 一次.2).abs() < 1e-6, "({} vs {})", 两次.2, 一次.2);
        assert!((两次.3 - 一次.3).abs() < 1e-6, "({} vs {})", 两次.3, 一次.3);
    }

    #[test]
    fn 施加旋转保持四元数规范化() {
        let mut q = (0.0, 0.0, 0.0, 1.0);
        for _ in 0..37 {
            q = 施加旋转(q, 轴::X.单位(), 0.21);
        }
        let 长度 = (q.0 * q.0 + q.1 * q.1 + q.2 * q.2 + q.3 * q.3).sqrt();
        assert!((长度 - 1.0).abs() < 1e-5, "长度应保持 1，实际 {长度}");
    }

    #[test]
    fn 退化四元数退回单位值而不是_nan() {
        let q = 规范化四元数((0.0, 0.0, 0.0, 0.0));
        assert_eq!(q, (0.0, 0.0, 0.0, 1.0));
        let q = 规范化四元数((f32::NAN, 0.0, 0.0, 1.0));
        assert_eq!(q, (0.0, 0.0, 0.0, 1.0));
    }

    #[test]
    fn 收拢缩放保留符号且不产生零或非有限值() {
        // 正常值原样通过。
        assert!((收拢缩放(2.5, 1.0) - 2.5).abs() < 1e-6);
        // 为零 → 收到下限，保留正号。
        assert!((收拢缩放(0.0, 1.0) - 缩放下限).abs() < 1e-9);
        // 负零在 IEEE 754 里不小于 0，因此被当作正零处理（收到 +下限）。
        assert!((收拢缩放(-0.0, 1.0) - 缩放下限).abs() < 1e-9);
        // 真正的负值 → 保留负号，不翻面。
        assert!((收拢缩放(-1e-9, 1.0) + 缩放下限).abs() < 1e-9);
        assert!((收拢缩放(-5.0, 1.0) + 5.0).abs() < 1e-6);
        // 非有限值 → 退回备用值。
        assert_eq!(收拢缩放(f32::NAN, 3.0), 3.0);
        assert_eq!(收拢缩放(f32::INFINITY, 3.0), 3.0);
        assert_eq!(收拢缩放(f32::NEG_INFINITY, 3.0), 3.0);
        // 过大 → 收到上限。
        assert!((收拢缩放(1e9, 1.0) - 缩放上限).abs() < 1e-3);
    }

    #[test]
    fn 点到线段距离在端点处退化为点距() {
        let 距离 = 点到线段距离(Pos2::new(0.0, 3.0), Pos2::ZERO, Pos2::new(10.0, 0.0));
        assert!((距离 - 3.0).abs() < 1e-5, "实际 {距离}");
        // 线段之外的投影要被夹在端点，而不是无限延长。
        let 距离 = 点到线段距离(Pos2::new(20.0, 0.0), Pos2::ZERO, Pos2::new(10.0, 0.0));
        assert!((距离 - 10.0).abs() < 1e-5, "实际 {距离}");
    }

    #[test]
    fn 零长度线段不会除零() {
        let 距离 = 点到线段距离(Pos2::new(3.0, 4.0), Pos2::ZERO, Pos2::ZERO);
        assert!((距离 - 5.0).abs() < 1e-5, "实际 {距离}");
    }

    #[test]
    fn 圆环折线是闭合的() {
        let 点 = 圆环折线(Pos2::ZERO, 10.0, 32);
        assert_eq!(点.len(), 33);
        assert!((点[0] - 点[32]).length() < 1e-4, "首尾必须重合");
    }

    #[test]
    fn 工具代号可往返解析() {
        for 工具 in 变换工具::全部() {
            assert_eq!(变换工具::从代号(工具.代号()), Some(工具));
        }
        assert_eq!(变换工具::从代号("不存在"), None);
    }

    #[test]
    fn 部件归类与轴归属正确() {
        assert!(操纵器部件::移动X.是移动() && !操纵器部件::移动X.是旋转());
        assert!(操纵器部件::旋转平面.是旋转());
        assert_eq!(操纵器部件::旋转平面.轴(), Some(轴::Z));
        assert!(操纵器部件::缩放等比.是缩放());
        assert_eq!(操纵器部件::缩放等比.轴(), None);
        assert_eq!(操纵器部件::移动平面Yz.轴(), None);
    }

    #[test]
    fn 无变化会话可被识别() {
        let 标识 = 实体标识::新建();
        let 起始 = vec![(标识, 变换数据::单位())];
        let 会话 = 拖拽会话::新建(
            变换工具::移动,
            操纵器部件::移动X,
            起始.clone(),
            拖拽基准::平面二维((0.0, 0.0)),
        );
        assert!(会话.无变化(), "刚建立的会话必须等于起始状态");
        let mut 会话 = 会话;
        会话.最新 = vec![(
            标识,
            变换数据 {
                平移: (1.0, 0.0, 0.0),
                ..变换数据::单位()
            },
        )];
        assert!(!会话.无变化());
    }
}
