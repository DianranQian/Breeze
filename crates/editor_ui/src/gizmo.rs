/// 颜色语义用的坐标轴。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 轴 {
    /// 世界 X 轴。
    X,
    /// 世界 Y 轴。
    Y,
    /// 世界 Z 轴。
    Z,
}

impl 轴 {
    /// 世界空间单位向量。
    pub fn 单位(self) -> (f32, f32, f32) {
        match self {
            // 2D 视口里"屏幕右"就是 +X。
            轴::X => (1.0, 0.0, 0.0),
            // 屏幕上方是 +Y（世界 y 向上）。
            轴::Y => (0.0, 1.0, 0.0),
            轴::Z => (0.0, 0.0, 1.0),
        }
    }

    /// 稳定代号（进证据文件，与语言无关）。
    pub fn 代号(self) -> &'static str {
        match self {
            轴::X => "x",
            轴::Y => "y",
            轴::Z => "z",
        }
    }
}

/// 主题里该轴的颜色。
///
/// # 为什么 Z 复用「信息」色
///
/// 主题的配色契约是 2D 时代定下的，只有 [`编辑器配色::轴_x`] 与
/// [`编辑器配色::轴_y`]，没有 Z。而 [`编辑器配色`] **没有** `serde(default)`：
/// 给它加字段会让所有已保存的用户主题在反序列化时整体失败 —— 那是
/// "为了让 Z 有个专属颜色，把用户主题全废掉"。
///
/// 因此 Z 复用主题里同为语义槽位的「信息」色：它跟随主题切换、在深浅两套
/// 主题下都与 X/Y 有足够区分度，且不动序列化契约。后续若要给 Z 独立颜色，
/// 应同时给 `编辑器配色` 加 `#[serde(default)]` 并做旧主题迁移。
pub fn 轴颜色(配色: &编辑器配色, 轴: 轴) -> Color32 {
    match 轴 {
        轴::X => 配色.轴_x,
        轴::Y => 配色.轴_y,
        轴::Z => 配色.信息,
    }
}

/// 视口里的变换工具。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum 变换工具 {
    /// 只选择，不显示操纵器。
    #[default]
    选择,
    /// 移动。
    移动,
    /// 旋转。
    旋转,
    /// 缩放。
    缩放,
}

impl 变换工具 {
    /// 工具条上的顺序。
    pub fn 全部() -> [Self; 4] {
        [Self::选择, Self::移动, Self::旋转, Self::缩放]
    }

    /// 稳定代号（与 `BEVY_STUDIO_TOOL` 环境变量、证据文件共用）。
    pub fn 代号(self) -> &'static str {
        match self {
            Self::选择 => "select",
            Self::移动 => "move",
            Self::旋转 => "rotate",
            Self::缩放 => "scale",
        }
    }

    /// 从代号解析（环境变量与证据回读用）。
    pub fn 从代号(代号: &str) -> Option<Self> {
        Self::全部().into_iter().find(|工具| 工具.代号() == 代号)
    }

    /// 工具名文案键。
    pub fn 名称键(self) -> &'static str {
        match self {
            Self::选择 => "tool_select",
            Self::移动 => "tool_move",
            Self::旋转 => "tool_rotate",
            Self::缩放 => "tool_scale",
        }
    }

    /// 快捷键。
    ///
    /// 选 Q/W/E/R 而不是 F1–F4：功能键已经被运行/单步占用（F5/F6/F7），
    /// 而 Q/W/E/R 是建模软件里最常见的"选择/移动/旋转/缩放"四连，
    /// 且不与文本输入冲突（文本编辑态由调用方整体屏蔽快捷键）。
    pub fn 快捷键(self) -> egui::Key {
        match self {
            Self::选择 => egui::Key::Q,
            Self::移动 => egui::Key::W,
            Self::旋转 => egui::Key::E,
            Self::缩放 => egui::Key::R,
        }
    }

    /// 工具栏区域标识（自动验收按它点击切换工具）。
    pub fn 区域标识(self) -> &'static str {
        match self {
            Self::选择 => "tool_select",
            Self::移动 => "tool_move",
            Self::旋转 => "tool_rotate",
            Self::缩放 => "tool_scale",
        }
    }
}

/// 操纵器上可命中的部件。
///
/// 一个枚举覆盖两种视口：2D 不会产生 `移动Z` / `旋转X` 这类部件，
/// 3D 不会产生 `旋转平面`（2D 的绕 Z 圆环）。这样"悬停/按下/拖拽的是哪一个
/// 部件"在证据里是同一种表达，探针与断言不必分两套。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 操纵器部件 {
    /// 沿世界 X 移动。
    移动X,
    /// 沿世界 Y 移动。
    移动Y,
    /// 沿世界 Z 移动（仅 3D）。
    移动Z,
    /// 在 XY 平面内移动（2D 的自由移动）。
    移动平面Xy,
    /// 在 YZ 平面内移动（仅 3D）。
    移动平面Yz,
    /// 在 XZ 平面内移动（仅 3D）。
    移动平面Xz,
    /// 绕世界 X 旋转（仅 3D）。
    旋转X,
    /// 绕世界 Y 旋转（仅 3D）。
    旋转Y,
    /// 绕世界 Z 旋转。
    旋转Z,
    /// 2D 的绕平面法线旋转圆环（等价于绕 Z）。
    旋转平面,
    /// 沿世界 X 缩放。
    缩放X,
    /// 沿世界 Y 缩放。
    缩放Y,
    /// 沿世界 Z 缩放（仅 3D）。
    缩放Z,
    /// 三轴等比缩放。
    缩放等比,
}

impl 操纵器部件 {
    /// 稳定代号（进证据文件；探针用 `gizmo-drag:<代号>:<像素>` 指定部件）。
    pub fn 代号(self) -> &'static str {
        match self {
            Self::移动X => "move_x",
            Self::移动Y => "move_y",
            Self::移动Z => "move_z",
            Self::移动平面Xy => "move_xy",
            Self::移动平面Yz => "move_yz",
            Self::移动平面Xz => "move_xz",
            Self::旋转X => "rotate_x",
            Self::旋转Y => "rotate_y",
            Self::旋转Z => "rotate_z",
            Self::旋转平面 => "rotate_plane",
            Self::缩放X => "scale_x",
            Self::缩放Y => "scale_y",
            Self::缩放Z => "scale_z",
            Self::缩放等比 => "scale_uniform",
        }
    }

    /// 该部件主要作用于哪条轴（等比缩放与 2D 自由移动没有单轴）。
    pub fn 轴(self) -> Option<轴> {
        match self {
            Self::移动X | Self::旋转X | Self::缩放X => Some(轴::X),
            Self::移动Y | Self::旋转Y | Self::缩放Y => Some(轴::Y),
            Self::移动Z | Self::旋转Z | Self::缩放Z => Some(轴::Z),
            // 2D 的旋转圆环绕的就是平面法线（Z）。
            Self::旋转平面 => Some(轴::Z),
            Self::移动平面Xy | Self::移动平面Yz | Self::移动平面Xz | Self::缩放等比 => {
                None
            }
        }
    }

    /// 是否属于"移动"工具。
    pub fn 是移动(self) -> bool {
        matches!(
            self,
            Self::移动X
                | Self::移动Y
                | Self::移动Z
                | Self::移动平面Xy
                | Self::移动平面Yz
                | Self::移动平面Xz
        )
    }

    /// 是否属于"旋转"工具。
    pub fn 是旋转(self) -> bool {
        matches!(
            self,
            Self::旋转X | Self::旋转Y | Self::旋转Z | Self::旋转平面
        )
    }

    /// 是否属于"缩放"工具。
    pub fn 是缩放(self) -> bool {
        matches!(
            self,
            Self::缩放X | Self::缩放Y | Self::缩放Z | Self::缩放等比
        )
    }
}

/// 屏幕上可绘制、可命中的图元。
///
/// # 为什么绘制几何与命中几何是**同一个值**
///
/// 工程要求"绘制与命中测试必须共享同一套几何参数或具有可验证的一致性"。
/// 做到这一点的最省事办法不是"两边都小心地写对"，而是让两边都从
/// 同一个 `图元` 取数：画的时候按它画，命中时按它算距离。
/// 于是"画在这里、点在那里"这类缺陷在结构上不可能发生。
#[derive(Debug, Clone)]
pub enum 图元 {
    /// 一条直线段。
    线段 {
        /// 起点。
        起: Pos2,
        /// 终点。
        终: Pos2,
    },
    /// 带箭头的手柄（移动轴）。
    箭头 {
        /// 起点。
        起: Pos2,
        /// 终点（箭头尖）。
        终: Pos2,
    },
    /// 带方块端帽的手柄（缩放轴）。
    方块轴 {
        /// 起点。
        起: Pos2,
        /// 终点（方块中心）。
        终: Pos2,
        /// 端帽半边长（像素）。
        半边: f32,
    },
    /// 实心方块（等比缩放中心、圆环起点标记）。
    实心方块 {
        /// 中心。
        中心: Pos2,
        /// 半边长（像素）。
        半边: f32,
    },
    /// 空心方块（2D 自由移动）。
    空心方块 {
        /// 中心。
        中心: Pos2,
        /// 半边长（像素）。
        半边: f32,
    },
    /// 折线（旋转圆环）。
    折线(Vec<Pos2>),
    /// 四边形（3D 的平面约束手柄）。
    四边形(Vec<Pos2>),
}

/// 一个部件的**屏幕几何**。
///
/// 绘制、命中测试与自动验收共用同一份：绘制按 `图元` 画，命中按 `图元`
/// 算距离，探针按 `命中点` 与 `拖拽方向` 落点并拖拽。
#[derive(Debug, Clone)]
pub struct 部件几何 {
    /// 部件身份。
    pub 部件: 操纵器部件,
    /// 该部件的代表点（屏幕绝对坐标）。自动验收按它落点。
    pub 命中点: Pos2,
    /// 沿"增大方向"的屏幕单位向量。
    ///
    /// 自动验收用它推导拖拽终点：沿这个方向拖 N 像素就是"把该部件往正方向推"。
    /// 轴向部件取该轴在屏幕上的投影方向；圆环取命中点处的切线方向。
    pub 拖拽方向: Vec2,
    /// 屏幕包围盒（证据与粗判）。
    pub 包围盒: Rect,
    /// 命中容差（屏幕像素）。不同部件可以有不同容差。
    pub 容差: f32,
    /// 组成该部件的图元（绘制与命中共用）。
    pub 图元: Vec<图元>,
}

impl 部件几何 {
    /// 指针到该部件的屏幕距离（用最贴近的那个图元）。
    pub fn 距离(&self, 指针: Pos2) -> f32 {
        self.图元
            .iter()
            .map(|图元| 图元距离(图元, 指针))
            .fold(f32::MAX, f32::min)
    }
}

/// 拖拽会话的求解基准。
///
/// 每一种都记录"按下那一刻"的几何基准：后续每一帧都从基准重新求值，
/// 而不是把增量累加到当前值上。后者会因丢帧与浮点误差漂移，
/// 表现为"快速拖动时对象慢慢偏离鼠标"。
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum 拖拽基准 {
    /// 平面内移动：按下时的世界坐标（2D 为 xy，3D 为所在操作平面上的交点）。
    平面移动 {
        /// 2D：按下时的世界 xy。
        起点二维: (f32, f32),
        /// 3D：按下时与操作平面的交点。
        起点三维: (f32, f32, f32),
    },
    /// 沿轴移动/缩放：按下时指针在轴上的参数（世界单位）。
    轴向 {
        /// 轴参数。
        起点参数: f32,
    },
    /// 绕轴旋转：按下时的角度，以及**累计**角度。
    ///
    /// 累计角是解决"跨过 ±π 突然翻转"的关键：每一帧只把**最短角差**
    /// 累加进来，角度因此可以连续增长到任意多圈，而不会在边界跳变。
    旋转 {
        /// 上一帧的角度（用于求最短角差）。
        上次角: f32,
        /// 从按下到现在的累计角。
        累计角: f32,
    },
    /// 等比缩放：按下时指针到操纵器中心的屏幕距离。
    ///
    /// # 为什么用"距离差"而不是"距离比"
    ///
    /// 2D 的等比缩放手柄就画在操纵器**中心**，按下时到中心的距离约为 0。
    /// 用比值（`当前距离 / 起点距离`）会除以零，或者必须拒绝开始拖拽 ——
    /// 那等于"这个手柄点不动"。改成按像素差换算比例：
    ///
    /// ```text
    /// 比例 = 1 + (当前距离 - 起点距离) / 每格像素
    /// ```
    ///
    /// 从中心往外拖就放大、往里拖就缩小，起点距离为 0 也完全正常，
    /// 而且比例永远为正（不会把物体翻面）。
    屏幕距离 {
        /// 起点屏幕距离（像素）。
        起点距离: f32,
    },
}

impl 拖拽基准 {
    /// 2D 移动用的基准构造。
    pub fn 平面二维(起点: (f32, f32)) -> Self {
        Self::平面移动 {
            起点二维: 起点,
            起点三维: (0.0, 0.0, 0.0),
        }
    }

    /// 3D 平面移动用的基准构造。
    pub fn 平面三维(起点: (f32, f32, f32)) -> Self {
        Self::平面移动 {
            起点二维: (0.0, 0.0),
            起点三维: 起点,
        }
    }
}

/// 一次操纵器拖拽的完整会话。
///
/// # 生命周期
///
/// ```text
/// 空闲 → 悬停 → 按下并命中 → 建立会话（记录起始变换 + 基准）
///      → 每帧预览（预览变换，不进撤销栈）
///      → 释放（提交一次）/ Escape 或失焦或目标失效（取消并恢复）
/// ```
///
/// 会话**只保存起始值**。连续拖拽因此不会继承上一次的起点、角度或累计偏移：
/// 每次按下都新建一个会话。
#[derive(Debug, Clone)]
pub struct 拖拽会话 {
    /// 拖拽开始时的工具（会话期间工具被换掉就取消，见调用方）。
    pub 工具: 变换工具,
    /// 正在拖拽的部件。
    pub 部件: 操纵器部件,
    /// 拖拽开始时各实体的变换。
    pub 起始: Vec<(实体标识, 变换数据)>,
    /// 求解基准（求解过程中会被更新，例如累计角度）。
    pub 基准: 拖拽基准,
    /// 最近一次求解出的变换；提交时用它，取消时丢弃。
    pub 最新: Vec<(实体标识, 变换数据)>,
}

impl 拖拽会话 {
    /// 用起始变换与基准新建会话。
    pub fn 新建(
        工具: 变换工具,
        部件: 操纵器部件,
        起始: Vec<(实体标识, 变换数据)>,
        基准: 拖拽基准,
    ) -> Self {
        Self {
            工具,
            部件,
            最新: 起始.clone(),
            起始,
            基准,
        }
    }

    /// 起始变换是否与最新结果完全一致（用于"零位移不产生撤销记录"）。
    pub fn 无变化(&self) -> bool {
        self.起始 == self.最新
    }
}

