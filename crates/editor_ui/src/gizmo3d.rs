/// 部件对应的世界轴（旋转环的法线 / 移动轴 / 缩放轴）。
fn 部件轴(部件: 操纵器部件) -> Option<轴> {
    部件.轴()
}

/// 按下时建立求解基准。
///
/// 返回 `None` 表示这一帧的几何退化（射线与轴/平面近乎平行），
/// 此时**不应该**开始拖拽：否则第一帧就会产生一个极大位移。
pub fn 建立基准(
    部件: 操纵器部件,
    中心世界: 向量,
    指针局部: Vec2,
    相机: &三维相机,
    尺寸: Vec2,
) -> Option<拖拽基准> {
    let (射线起点, 射线方向) = 相机.屏幕射线(指针局部, 尺寸);
    match 部件 {
        // 平面移动：射线与平面求交。
        操纵器部件::移动平面Xy | 操纵器部件::移动平面Yz | 操纵器部件::移动平面Xz =>
        {
            let 法线 = match 部件 {
                操纵器部件::移动平面Xy => 平面::Xy.法线(),
                操纵器部件::移动平面Yz => 平面::Yz.法线(),
                _ => 平面::Xz.法线(),
            };
            let 交点 = 射线平面交点(射线起点, 射线方向, 中心世界, 法线)?;
            Some(拖拽基准::平面三维(交点))
        }
        // 轴向移动 / 缩放：射线与直线的最近点参数。
        操纵器部件::移动X
        | 操纵器部件::移动Y
        | 操纵器部件::移动Z
        | 操纵器部件::缩放X
        | 操纵器部件::缩放Y
        | 操纵器部件::缩放Z => {
            let 轴 = 部件轴(部件)?;
            let 参数 = 射线直线参数(射线起点, 射线方向, 中心世界, 轴.单位())?;
            if 部件.是缩放() && 参数.abs() < 1e-3 {
                // 缩放比例的分母是"按下时在轴上的参数"，为 0 就没有定义。
                return None;
            }
            Some(拖拽基准::轴向 {
                起点参数: 参数
            })
        }
        // 三个旋转环。
        操纵器部件::旋转X | 操纵器部件::旋转Y | 操纵器部件::旋转Z => {
            let 轴 = 部件轴(部件)?;
            let 法线 = 轴.单位();
            let 交点 = 射线平面交点(射线起点, 射线方向, 中心世界, 法线)?;
            let 角 = 平面角(中心世界, 交点, 法线)?;
            Some(拖拽基准::旋转 {
                上次角: 角,
                累计角: 0.0,
            })
        }
        // 等比缩放：屏幕距离比。
        操纵器部件::缩放等比 => {
            // 手柄在中心，按下距离接近 0 也不能拒绝（见 `距离换算比例`）。
            let 中心局部 = 相机.投影(中心世界, 尺寸)?;
            Some(拖拽基准::屏幕距离 {
                起点距离: (指针局部 - 中心局部).length(),
            })
        }
        _ => None,
    }
}

/// 求解当前拖拽下的新变换。
///
/// # 世界位移 → 父级局部位移
///
/// 射线求交得到的平移增量在世界空间，返回值却是文档里的局部变换。
/// 移动分支统一经 [`拖拽局部位移`] 乘父级世界逆矩阵；父子同时选中时
/// 子级返回零位移（由父级带动），避免移动两倍。
#[allow(clippy::too_many_arguments)]
pub fn 求解(
    部件: 操纵器部件,
    基准: &mut 拖拽基准,
    中心世界: 向量,
    指针局部: Vec2,
    相机: &三维相机,
    尺寸: Vec2,
    起始: &[(实体标识, 变换数据)],
    世界: 世界空间<'_>,
) -> Option<Vec<(实体标识, 变换数据)>> {
    let (射线起点, 射线方向) = 相机.屏幕射线(指针局部, 尺寸);
    match (部件, 基准) {
        // ---- 平面移动：位移 = 当前交点 - 按下交点 ----
        (
            操纵器部件::移动平面Xy | 操纵器部件::移动平面Yz | 操纵器部件::移动平面Xz,
            拖拽基准::平面移动 { 起点三维, .. },
        ) => {
            let 法线 = match 部件 {
                操纵器部件::移动平面Xy => 平面::Xy.法线(),
                操纵器部件::移动平面Yz => 平面::Yz.法线(),
                _ => 平面::Xz.法线(),
            };
            let 交点 = 射线平面交点(射线起点, 射线方向, 中心世界, 法线)?;
            let 位移 = 减(交点, *起点三维);
            if !有限(位移) {
                return None;
            }
            Some(整体平移(起始, 位移, 世界))
        }
        // ---- 轴向移动：参数差 → 沿该轴的世界位移 ----
        (
            操纵器部件::移动X | 操纵器部件::移动Y | 操纵器部件::移动Z,
            拖拽基准::轴向 { 起点参数 },
        ) => {
            let 轴 = 部件轴(部件)?.单位();
            let 参数 = 射线直线参数(射线起点, 射线方向, 中心世界, 轴)?;
            let 位移 = 乘(轴, 参数 - *起点参数);
            if !有限(位移) {
                return None;
            }
            Some(整体平移(起始, 位移, 世界))
        }
        // ---- 轴向缩放：参数比 ----
        (
            操纵器部件::缩放X | 操纵器部件::缩放Y | 操纵器部件::缩放Z,
            拖拽基准::轴向 { 起点参数 },
        ) => {
            if 起点参数.abs() < 1e-3 {
                return None;
            }
            let 轴 = 部件轴(部件)?;
            let 参数 = 射线直线参数(射线起点, 射线方向, 中心世界, 轴.单位())?;
            Some(沿世界轴缩放(起始, 轴.单位(), 参数 / *起点参数, 世界))
        }
        // ---- 旋转：平面交点角度的最短差累加 ----
        (
            操纵器部件::旋转X | 操纵器部件::旋转Y | 操纵器部件::旋转Z,
            拖拽基准::旋转 {
                上次角, 累计角
            },
        ) => {
            let 轴 = 部件轴(部件)?.单位();
            let 交点 = 射线平面交点(射线起点, 射线方向, 中心世界, 轴)?;
            let 当前角 = 平面角(中心世界, 交点, 轴)?;
            let 增量 = 最短角差(当前角, *上次角);
            *累计角 += 增量;
            *上次角 = 当前角;
            Some(整体旋转(起始, 轴, *累计角, 世界))
        }
        // ---- 等比缩放：屏幕距离差 ----
        (操纵器部件::缩放等比, 拖拽基准::屏幕距离 { 起点距离 }) => {
            let 中心局部 = 相机.投影(中心世界, 尺寸)?;
            let 距离 = (指针局部 - 中心局部).length();
            Some(等比缩放选中(
                起始,
                3,
                crate::gizmo::距离换算比例(距离, *起点距离),
                世界,
            ))
        }
        _ => None,
    }
}

/// 射线与平面（过 `平面上一点`、法线 `法线`）的交点。
///
/// 射线与平面近乎平行时返回 `None`：那种情况下交点会跑到极远处，
/// 用它算出来的位移是一个天文数字。
fn 射线平面交点(
    射线起点: 向量,
    射线方向: 向量,
    平面上一点: 向量,
    法线: 向量,
) -> Option<向量> {
    let 法线 = 规范化(法线)?;
    let 分母 = 点积(射线方向, 法线);
    if 分母.abs() < 1e-4 {
        return None;
    }
    let t = 点积(减(平面上一点, 射线起点), 法线) / 分母;
    if !t.is_finite() {
        return None;
    }
    Some(加(射线起点, 乘(射线方向, t)))
}

/// 射线与直线的最近点在直线上的参数 `t`（直线为 `原点 + t * 方向`）。
///
/// 标准的两直线最近点解。射线与直线近乎平行时返回 `None`：
/// 此时 `1 - b²` 趋近 0，参数会爆炸。
fn 射线直线参数(
    射线起点: 向量,
    射线方向: 向量,
    直线原点: 向量,
    直线方向: 向量,
) -> Option<f32> {
    let u = 规范化(直线方向)?;
    let v = 规范化(射线方向)?;
    let w0 = 减(直线原点, 射线起点);
    let b = 点积(u, v);
    let 分母 = 1.0 - b * b;
    if 分母 < 1e-4 {
        return None;
    }
    let d = 点积(u, w0);
    let e = 点积(v, w0);
    let t = (b * e - d) / 分母;
    if t.is_finite() { Some(t) } else { None }
}

/// 点相对操纵器中心的绕轴角度。
fn 平面角(中心: 向量, 点: 向量, 法线: 向量) -> Option<f32> {
    let (u, v) = 平面基(法线)?;
    let 差 = 减(点, 中心);
    // 投影到平面内再取角度：交点本来就在平面上，这里只是防御性处理。
    let 横向 = 点积(差, u);
    let 纵向 = 点积(差, v);
    if !横向.is_finite() || !纵向.is_finite() {
        return None;
    }
    Some(纵向.atan2(横向))
}

/// 从 `上次` 到 `当前` 的最短角差，落在 `(-π, π]`（与 2D 同一规则）。
pub fn 最短角差(当前: f32, 上次: f32) -> f32 {
    let mut 差 = 当前 - 上次;
    while 差 > std::f32::consts::PI {
        差 -= std::f32::consts::TAU;
    }
    while 差 <= -std::f32::consts::PI {
        差 += std::f32::consts::TAU;
    }
    差
}

fn 有限(a: 向量) -> bool {
    a.0.is_finite() && a.1.is_finite() && a.2.is_finite()
}

/// 平移所有实体（只改平移分量）。
///
/// 输入是世界位移，写回的是文档里的局部平移；换算规则见
/// [`crate::world_space::拖拽局部位移`]。父级也在本次拖拽集合里时，
/// 子级位移为零 —— 它的世界移动由父级带动。
fn 整体平移(
    起始: &[(实体标识, 变换数据)],
    位移: 向量,
    世界: 世界空间<'_>,
) -> Vec<(实体标识, 变换数据)> {
    let 选中: Vec<实体标识> = 起始.iter().map(|(标识, _)| *标识).collect();
    起始
        .iter()
        .map(|(标识, 变换)| {
            let 局部 = 拖拽局部位移(*标识, 位移, &选中, 世界);
            (
                *标识,
                变换数据 {
                    平移: (
                        变换.平移.0 + 局部.0,
                        变换.平移.1 + 局部.1,
                        变换.平移.2 + 局部.2,
                    ),
                    ..*变换
                },
            )
        })
        .collect()
}

