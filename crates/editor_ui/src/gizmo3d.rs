type 向量 = (f32, f32, f32);

fn 减(a: 向量, b: 向量) -> 向量 {
    (a.0 - b.0, a.1 - b.1, a.2 - b.2)
}
fn 加(a: 向量, b: 向量) -> 向量 {
    (a.0 + b.0, a.1 + b.1, a.2 + b.2)
}
fn 乘(a: 向量, k: f32) -> 向量 {
    (a.0 * k, a.1 * k, a.2 * k)
}
fn 点积(a: 向量, b: 向量) -> f32 {
    a.0 * b.0 + a.1 * b.1 + a.2 * b.2
}
fn 叉积(a: 向量, b: 向量) -> 向量 {
    (
        a.1 * b.2 - a.2 * b.1,
        a.2 * b.0 - a.0 * b.2,
        a.0 * b.1 - a.1 * b.0,
    )
}
fn 长度(a: 向量) -> f32 {
    点积(a, a).sqrt()
}
fn 规范化(a: 向量) -> Option<向量> {
    let 长 = 长度(a);
    if !长.is_finite() || 长 < 1e-6 {
        return None;
    }
    Some(乘(a, 1.0 / 长))
}

/// 垂直于 `n` 的一组正交基 `(u, v)`，满足 `u × v = n`。
///
/// 基只由法线决定，因此同一次拖拽里它**不会变**：角度基准因此稳定，
/// 不会因为指针移动导致基重建而跳变。
fn 平面基(n: 向量) -> Option<(向量, 向量)> {
    let n = 规范化(n)?;
    let 参考 = if n.0.abs() < 0.9 {
        (1.0, 0.0, 0.0)
    } else {
        (0.0, 1.0, 0.0)
    };
    let u = 规范化(叉积(n, 参考))?;
    let v = 叉积(n, u);
    Some((u, v))
}

