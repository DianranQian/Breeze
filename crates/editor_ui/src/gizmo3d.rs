//! 3D 视口的变换操纵器：布局、命中测试、世界空间求解。
//!
//! # 与 2D 的根本差异
//!
//! 3D 的几何**不是仿射**的：一条世界轴的屏幕表现取决于相机朝向、相机距离
//! 与透视投影。因此这里必须做三件 2D 不需要做的事：
//!
//! 1. **轴长按相机距离换算**，让操纵器在屏幕上保持恒定大小
//!    （见 [`布局`] 里的 `轴长`）。若用固定世界长度，相机拉远后操纵器
//!    会缩成一个点、推近后会占满屏幕；
//! 2. **移动/缩放靠射线与直线的最近点**求解，而不是坐标差；
//! 3. **平面约束与旋转靠射线与平面求交**，并且必须处理"射线与平面
//!    近乎平行"的退化 —— 那种情况下交点会飞到无穷远，必须拒绝该帧
//!    而不是把一个天文数字写进文档。
//!
//! # 退化处理策略
//!
//! * 轴几乎正对相机（屏幕上投影长度 < 6px）→ **不生成该轴部件**。
//!   这类轴在屏幕上就是一个点，既看不清也点不中；隐藏它比画一条
//!   无法操作的手柄诚实。
//! * 拖拽中射线与轴/平面近乎平行 → **本帧不更新**（保持上一帧结果），
//!   下一帧指针偏移后自然恢复。这样不会出现"突然跳到极远处"。
//!
//! # 坐标约定
//!
//! 操纵器中心来自 `GlobalTransform` 快照，求解出的位移在世界空间；
//! 写回文档前经 [`crate::world_space::拖拽局部位移`] 换算到父级局部空间，
//! 因此父级带旋转或缩放时，子实体的 `平移` 增量不等于世界增量。

use egui::{Pos2, Rect, Vec2};
use scene_doc::document::{变换数据, 实体标识};

use crate::gizmo::{
    变换工具, 命中, 图元, 拖拽基准, 操纵器部件, 整体旋转, 沿世界轴缩放, 等比缩放选中, 轴, 部件几何,
};
use crate::state::三维相机;
use crate::world_space::{世界空间, 拖拽局部位移};

/// 操纵器在屏幕上的目标轴长（逻辑像素）。
pub const 屏幕轴长像素: f32 = 88.0;
/// 轴向手柄与圆环的命中容差（屏幕像素）。
pub const 命中容差: f32 = 10.0;
/// 中心手柄的命中容差。
pub const 中心容差: f32 = 12.0;
/// 圆环半径相对轴长的比例。
pub const 圆环半径系数: f32 = 0.92;
/// 平面手柄的起始偏移（相对轴长）。
pub const 平面起点系数: f32 = 0.30;
/// 平面手柄的边长（相对轴长）。
pub const 平面边长系数: f32 = 0.30;
/// 圆环折线段数。
const 圆环段数: usize = 64;
/// 屏幕上投影长度小于该值的轴不生成部件（正对相机，无法操作）。
const 最小投影长度: f32 = 6.0;

/// 一帧的 3D 操纵器布局（屏幕绝对坐标）。
#[derive(Debug, Clone)]
pub struct 布局 {
    /// 操纵器中心（选中实体世界位置在屏幕上的投影）。
    pub 中心: Pos2,
    /// 轴长（世界单位）。
    pub 轴长: f32,
    /// 本帧所有可命中部件。
    pub 部件: Vec<部件几何>,
}

impl 布局 {
    /// 取某个部件的几何。
    pub fn 取(&self, 部件: 操纵器部件) -> Option<&部件几何> {
        self.部件.iter().find(|项| 项.部件 == 部件)
    }

    /// 命中测试（与绘制共用同一份图元）。
    pub fn 命中(&self, 指针: Pos2) -> Option<操纵器部件> {
        命中(&self.部件, 指针)
    }
}

