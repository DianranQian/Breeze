    #[test]
    fn 空白区落在名称与开关之间且不重叠() {
        let 整行 = egui::Rect::from_min_max(egui::pos2(10.0, 100.0), egui::pos2(370.0, 122.0));
        let 名称右 = 150.0;
        let 开关左 = 330.0;
        let 空白 = 计算行空白矩形(整行, 名称右, 开关左).expect("这段宽度足够，应当有空白区");

        assert!(
            空白.min.x > 名称右,
            "空白区左边缘 {} 必须严格在名称右边缘 {名称右} 之后，\
             否则它会压在名称标签上、把点击抢走",
            空白.min.x
        );
        assert!(
            空白.max.x < 开关左,
            "空白区右边缘 {} 必须严格在开关左边缘 {开关左} 之前，\
             否则它会压在隐藏/锁定开关上",
            空白.max.x
        );
        assert!(
            空白.min.y >= 整行.min.y && 空白.max.y <= 整行.max.y,
            "空白区不得超出整行纵向范围"
        );
    }

