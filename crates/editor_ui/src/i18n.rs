//! 界面多语言（简体中文 / English）。
//!
//! # 为什么用"中文字面量"当键
//!
//! 常见的做法是给每条文案起一个符号名（`MENU_FILE_SAVE`）再查表。
//! 这里改成**直接用中文字面量当键**：
//!
//! ```ignore
//! ui.label(语言.取("保存场景"));   // 中文环境原样返回，英文环境返回 "Save Scene"
//! ```
//!
//! 这样做的三个实际好处：
//!
//! 1. **调用点可读**：读代码时看到的就是用户看到的字，不需要来回跳表；
//! 2. **漏翻译不会静默**：忘了翻译就退回中文原文，不会出现空白或
//!    `MENU_FILE_SAVE` 这种泄露到界面上的符号名；
//! 3. **可自动查漏**：源码里的中文字面量是**可以直接扫描**的，
//!    因此能写一条测试"界面上出现的每一句中文都必须有英文翻译"
//!    （见本模块的 `界面文案全部有英文翻译`）。
//!    如果键是符号名，就只能靠人工核对。
//!
//! 这套思路和 gettext 用源字符串当 msgid 是同一个道理。
//!
//! # 查找方式
//!
//! [`英文表`] 按中文字符串的 UTF-8 字节序排好序，用二分查找。
//! 顺序由生成脚本保证，`文案表有序且无重复` 这条测试守着它 ——
//! 顺序错了二分就会静默查不到，属于必须用测试钉住的一类问题。

use std::borrow::Cow;

/// 界面语言。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Default)]
pub enum 语言 {
    /// 简体中文（界面文案的原文）。
    #[default]
    中文,
    /// English。
    英文,
}

impl 语言 {
    /// 全部可选语言，用于在设置菜单里列出。
    pub const 全部: [语言; 2] = [语言::中文, 语言::英文];

    /// 稳定代号，用于写进配置文件。**不要**改这些字符串，
    /// 否则用户已保存的语言偏好会失效。
    pub fn 代号(self) -> &'static str {
        match self {
            语言::中文 => "zh-CN",
            语言::英文 => "en",
        }
    }

    /// 由代号解析。无法识别时回退到中文。
    pub fn 从代号(代号: &str) -> Self {
        match 代号 {
            "en" => 语言::英文,
            _ => 语言::中文,
        }
    }

    /// 在设置菜单里显示的名字。
    ///
    /// 刻意用各语言自己的写法（"简体中文" / "English"）而不是翻译成
    /// 当前语言：用户在只看得懂一种语言时，也要能找到自己那一项。
    pub fn 自称(self) -> &'static str {
        match self {
            语言::中文 => "简体中文",
            语言::英文 => "English",
        }
    }

    /// 把一句中文界面文案翻译成当前语言。
    ///
    /// 中文环境直接返回原文；英文环境查 [`英文表`]，
    /// 查不到就退回原文 —— 宁可显示中文，也不要显示空白。
    pub fn 取(self, 中文原文: &'static str) -> &'static str {
        match self {
            语言::中文 => 中文原文,
            语言::英文 => 查英文(中文原文).unwrap_or(中文原文),
        }
    }

    /// 同 [`语言::取`]，但接受运行时拼出来的字符串。
    ///
    /// 用于文案本身就带动态部分、无法用 `&'static str` 表示的情况。
    /// 代价是英文环境可能分配一次字符串，因此**优先用 [`语言::取`]**。
    pub fn 取动态<'a>(self, 中文原文: &'a str) -> Cow<'a, str> {
        match self {
            语言::中文 => Cow::Borrowed(中文原文),
            // 动态字符串当键查不到（表里只有静态字面量），
            // 因此这里如实退回原文，而不是伪装成已翻译。
            语言::英文 => match 查英文静态化(中文原文) {
                Some(英文) => Cow::Borrowed(英文),
                None => Cow::Borrowed(中文原文),
            },
        }
    }

    /// 在两种语言间切换（给"下一个语言"这类入口用）。
    pub fn 下一个(self) -> Self {
        match self {
            语言::中文 => 语言::英文,
            语言::英文 => 语言::中文,
        }
    }

    /// 由语言的自称反查语言。
    ///
    /// 菜单里两种语言各列一项、各用**自己的写法**显示，
    /// 因此需要从显示文本反查它代表哪种语言。
    pub fn 从自称(自称: &str) -> Option<Self> {
        Self::全部.into_iter().find(|语言| 语言.自称() == 自称)
    }

    /// 取出译文并依次填充其中的 `{}` 占位符。
    ///
    /// # 为什么需要这个函数
    ///
    /// `format!` 要求格式串是**字面量** —— 它在编译期解析那个字符串。
    /// 而译文是运行时查表得到的 `&str`，因此
    /// `format!(语言.取("2D 视口 · {} 个实体"), 数)` **根本编译不过**。
    ///
    /// 所以这里在运行时做替换。占位符统一只用 `{}`：
    /// 需要控制小数位数时由调用方先把值格式化成字符串再传进来，例如
    /// `语言.填充("缩放 {}%", &[&format!("{:.0}", 缩放 * 100.0)])`。
    /// 这样这个函数只需要处理"顺序替换"，不必实现一个格式化器。
    ///
    /// 占位符数量多于参数时，多出来的原样保留；少于参数时多余参数被忽略 ——
    /// 两种情况都不会 panic，译文出错顶多显示难看，不会把编辑器搞崩。
    pub fn 填充(self, 中文模板: &'static str, 参数: &[&dyn std::fmt::Display]) -> String {
        let 模板 = self.取(中文模板);
        let mut 结果 = String::with_capacity(模板.len() + 32);
        let mut 参数迭代 = 参数.iter();
        let mut 剩余 = 模板;

        while let Some(左) = 剩余.find("{}") {
            结果.push_str(&剩余[..左]);
            match 参数迭代.next() {
                Some(值) => 结果.push_str(&值.to_string()),
                None => {
                    // 参数不够：把占位符原样留着，便于一眼看出漏传了什么。
                    结果.push_str("{}");
                }
            }
            剩余 = &剩余[左 + 2..];
        }
        结果.push_str(剩余);
        结果
    }
}

/// 在英文表里二分查找。表必须按 UTF-8 字节序有序。
fn 查英文(中文: &str) -> Option<&'static str> {
    // `binary_search_by` 用的是 `str` 的 `Ord`，即 UTF-8 字节序，
    // 与生成表的排序方式一致。
    table::英文表
        .binary_search_by(|(键, _)| (*键).cmp(中文))
        .ok()
        .map(|下标| table::英文表[下标].1)
}

/// 与 [`查英文`] 相同，只是明确要求键是 `'static`。
fn 查英文静态化(中文: &str) -> Option<&'static str> {
    查英文(中文)
}

/// 文案表单独成文件：它有二百多条、且由脚本生成，
/// 与这里的逻辑放在一起会把逻辑本身淹掉。
///
/// 文件名用 `table.rs` 而不是中文名：**Rust 的模块文件名必须是 ASCII**，
/// 用中文会直接编译不过（`trying to load file for module ... with
/// non-ascii identifier name`）。这也正好符合本项目"文件名用英文、
/// 标识符用中文"的约定。
mod table;
pub use table::英文表;

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 中文环境下必须原样返回原文（不查表、不改写）。
    #[test]
    fn 中文环境原样返回原文() {
        for 原文 in ["保存场景", "撤销", "场景树", "包含中文的任意串"] {
            assert_eq!(语言::中文.取(原文), 原文);
        }
    }

    /// 表必须有序且无重复 —— 二分查找的前提。
    ///
    /// 顺序错了不会报错，只会**静默查不到**，因此必须由测试钉住。
    #[test]
    fn 文案表有序且无重复() {
        let 键列表: Vec<&str> = 英文表.iter().map(|(键, _)| *键).collect();

        for 窗口 in 键列表.windows(2) {
            assert!(
                窗口[0] < 窗口[1],
                "文案表必须按 UTF-8 字节序严格升序，但出现了 `{}` 在 `{}` 之前/相等。\
                 请重新运行生成脚本排序。",
                窗口[0],
                窗口[1]
            );
        }
    }

    /// 表里不能出现空翻译（空串会在界面上留下空白）。
    #[test]
    fn 没有空翻译() {
        for (中文, 英文) in 英文表 {
            assert!(!中文.is_empty(), "键不能为空");
            assert!(
                !英文.trim().is_empty(),
                "`{中文}` 的英文翻译是空的 —— 界面上会显示成空白"
            );
        }
    }

    /// 翻译里不得混入汉字（那说明只是复制了原文，没有真正翻译）。
    ///
    /// 例外：允许中英混排里刻意保留的中文，例如语言自称。
    /// 这里允许少量，但整体不允许"整条都是中文"。
    #[test]
    fn 英文翻译不应整条都是中文() {
        let mut 未翻译 = Vec::new();
        for (中文, 英文) in 英文表 {
            if 中文 == 英文 {
                continue; // 纯符号串，允许原样
            }
            let 汉字数 = 英文.chars().filter(|c| is_汉字(*c)).count();
            let 总字数 = 英文.chars().count();
            if 总字数 > 0 && 汉字数 * 2 > 总字数 {
                未翻译.push((*中文, *英文));
            }
        }
        assert!(
            未翻译.is_empty(),
            "以下条目看起来没有被真正翻译（英文里汉字占多数）：{未翻译:?}"
        );
    }

    /// 英文环境下，对表里每个键都必须能查到翻译。
    #[test]
    fn 英文环境能查到表里每一项() {
        let mut 查不到 = Vec::new();
        for (中文, 英文) in 英文表 {
            let 结果 = 语言::英文.取(中文);
            if 结果 != *英文 {
                查不到.push((*中文, *英文, 结果));
            }
        }
        assert!(查不到.is_empty(), "以下条目查不到或查错：{查不到:?}");
    }

    /// 表里查不到的串必须**退回原文**，而不是变成空白或 panic。
    #[test]
    fn 未收录的串退回原文() {
        let 生僻 = "这句话故意不在翻译表里";
        assert_eq!(语言::英文.取(生僻), 生僻);
        assert_eq!(语言::英文.取动态(生僻).as_ref(), 生僻);
    }

    /// 语言代号必须能往返转换，且未知代号回退到中文。
    #[test]
    fn 语言代号往返一致() {
        for 语言 in 语言::全部 {
            assert_eq!(语言::从代号(语言.代号()), 语言);
        }
        assert_eq!(语言::从代号("zh-CN"), 语言::中文);
        assert_eq!(语言::从代号("klingon"), 语言::中文);
        assert_eq!(语言::从代号(""), 语言::中文);
    }

    /// 默认语言是中文（界面文案的原文语言）。
    #[test]
    fn 默认语言是中文() {
        assert_eq!(语言::default(), 语言::中文);
    }

    /// 每种语言的自称必须是它自己的写法，方便用户找到母语选项。
    #[test]
    fn 语言自称用各自的写法() {
        assert_eq!(语言::中文.自称(), "简体中文");
        assert_eq!(语言::英文.自称(), "English");
    }

    /// 切换一次再切回来应当回到原语言。
    #[test]
    fn 切换语言可往返() {
        for 语言 in 语言::全部 {
            assert_eq!(语言.下一个().下一个(), 语言);
        }
    }

    /// 判断是否为汉字。
    fn is_汉字(c: char) -> bool {
        matches!(u32::from(c), 0x3000..=0x303F | 0x4E00..=0x9FFF | 0xFF00..=0xFFEF)
    }

    /// 中文环境下 `填充` 必须还原成与 `format!` 完全相同的结果。
    #[test]
    fn 填充在中文环境等价于_format() {
        assert_eq!(
            语言::中文.填充("2D 视口 · {} 个实体", &[&3]),
            format!("2D 视口 · {} 个实体", 3)
        );
        assert_eq!(语言::中文.填充("{} / {} 项", &[&"甲", &"乙"]), "甲 / 乙 项");
        // 没有占位符时原样返回
        assert_eq!(语言::中文.填充("保存场景", &[]), "保存场景");
    }

    /// 英文环境下 `填充` 用译文替换中文，但保留参数位置。
    #[test]
    fn 填充在英文环境用译文() {
        // `2D 视口 · {} 个实体` 在表里译成 `2D Viewport · {} entities`
        let 结果 = 语言::英文.填充("2D 视口 · {} 个实体", &[&7]);
        assert!(结果.contains('7'), "参数必须被填进去，实际：{结果}");
        assert!(!结果.contains("视口"), "英文环境不应残留中文，实际：{结果}");
    }

    /// 参数少于占位符时不能 panic，且要留下可辨认的痕迹。
    ///
    /// 注：测试名里不能出现空格 —— 那会让 `panic` 被当成另一个标识符，
    /// 直接编译不过（本项目踩过两次）。
    #[test]
    fn 填充参数不足时不会崩溃() {
        let 结果 = 语言::中文.填充("{} 与 {}", &[&1]);
        assert!(结果.contains('1'));
        assert!(
            结果.contains("{}"),
            "缺少参数时应把占位符留着，方便看出漏传，实际：{结果}"
        );
    }

    /// 参数多于占位符时多余参数被忽略，不能 panic。
    #[test]
    fn 填充参数过多时忽略多余() {
        let 结果 = 语言::中文.填充("只有 {} 个", &[&1, &2, &3]);
        assert_eq!(结果, "只有 1 个");
    }

    /// 小数位数这类格式由调用方预先格式化，`填充` 只做顺序替换。
    #[test]
    fn 填充支持调用方预格式化的小数() {
        let 结果 = 语言::中文.填充("缩放 {}%", &[&format!("{:.0}", 1.234_f32 * 100.0)]);
        assert_eq!(结果, "缩放 123%");
    }
}
