//! 场景树节点类型 → 图标 的集中映射。
//!
//! # 为什么必须集中（而不是在场景树绘制里散一堆 if）
//!
//! 场景树一行要画三个东西：折叠指示器、类型图标、名称。类型判定一旦散落在
//! 绘制代码里，就会出现三种典型问题：
//!
//! * 同一个组件在两个地方判出不同结果（图标自相矛盾）；
//! * 新增组件类型时只改了绘制、忘了改"添加组件"菜单的图标；
//! * 无法单独测试"这个实体应当显示哪个图标"。
//!
//! 因此这里只做两件事：**判定节点类型**（纯函数，可单测）与
//! **类型 → 图标/文案**（纯查表）。绘制代码只负责排版。
//!
//! # 判定依据是真实组件数据，不是节点名称
//!
//! 判据只有一条：实体 `组件` 里是否存在某个**已注册的组件类型名**。
//! 组件类型名来自 `editor_app::scene_bridge::默认组件注册表()`，也就是
//! 运行时会真正实例化的那一套：
//!
//! | 组件名 | 含义 | 节点类型 |
//! | --- | --- | --- |
//! | `Sprite` | 2D 精灵/贴图 | [`节点类型::精灵`] |
//! | `Camera2d` | 2D 摄像机 | [`节点类型::摄像机`] |
//! | `Camera3d` | 3D 摄像机 | [`节点类型::摄像机`] |
//! | `TileTerrain` | 瓦片地形 | [`节点类型::地形`] |
//! | `Primitive3d` | 三维网格/几何体/模型 | [`节点类型::三维网格`] |
//!
//! `Transform` / `Visibility` 不参与判定：它们是几乎所有实体都有的
//! 基础组件，用它判类型等于没有判定。
//!
//! **绝不按名称猜类型**。"长货柜·西北"看起来像容器、"摄像机"看起来像摄像机，
//! 但只有真挂了 `Camera2d` 才是摄像机 —— 名称是用户可随意改的字符串，
//! 拿它当类型依据会让图标随重命名而变，属于伪造类型信息。
//!
//! # 当前不支持的类型（如实说明，不伪造图标）
//!
//! 本工程的组件注册表里**没有**音频、灯光、UI 布局这几类组件，
//! 因此没有为它们准备图标，也不会靠名称去猜。它们会落到
//! [`节点类型::容器`] 或 [`节点类型::普通实体`]，即通用图标。
//! 将来新增组件时，只需在 [`节点类型::判定`] 里加一条判据 +
//! 在 [`节点类型::图标`] 里加一条映射，绘制代码不用动。
//!
//! # 多个组件同时存在时的优先级
//!
//! 一个实体可能同时挂 `Sprite` 与 `Camera2d`（例如"带背景的相机"）。
//! 这里用**固定顺序**取第一个命中的类型（见 [`节点类型::判定`]），
//! 顺序写在代码里、有测试锁住，因此图标不会随哈希顺序或帧序变化。
//! 顺序的取舍原则是"越具体的渲染能力越优先"：
//! 摄像机 > 地形 > 三维网格 > 精灵 > 容器 > 普通实体。

use crate::icons::图标;
use scene_doc::document::场景实体;

/// 场景树一行的节点类型。
///
/// 只有枚举里的这几类会在场景树里出现；未知/未挂载可识别组件的实体
/// 一律归入 [`节点类型::普通实体`] 或 [`节点类型::容器`]，**不会**有第五种结果。
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum 节点类型 {
    /// 挂了 `Camera2d` 或 `Camera3d`。
    摄像机,
    /// 挂了 `TileTerrain`。
    地形,
    /// 挂了 `Primitive3d`。
    三维网格,
    /// 挂了 `Sprite`。
    精灵,
    /// 没有可识别的渲染组件，但有子实体 → 容器/分组。
    容器,
    /// 没有可识别的渲染组件，也没有子实体 → 普通实体。
    普通实体,
}

impl 节点类型 {
    /// 判定一个实体属于哪种节点类型。
    ///
    /// `有子实体` 由调用方从**真实的父子关系**里算出来（场景树本来就要算它
    /// 来决定显示不显示折叠箭头），因此这里不需要再读一次文档。
    ///
    /// 判定顺序即优先级，见模块文档。
    pub fn 判定(实体: &场景实体, 有子实体: bool) -> Self {
        if 实体.有组件("Camera2d") || 实体.有组件("Camera3d") {
            return Self::摄像机;
        }
        if 实体.有组件("TileTerrain") {
            return Self::地形;
        }
        if 实体.有组件("Primitive3d") {
            return Self::三维网格;
        }
        if 实体.有组件("Sprite") {
            // `Sprite` 带 `模型` 资源时**实际渲染成三维模型**
            // （见 `editor_app::scene_bridge` 的 Sprite 组件：
            //   `模型` 属性 → `模型路径` → 预览层加载 glTF/GLB）。
            // 因此它属于"三维内容"，图标应当与二维精灵区分开。
            // 判据是真实组件属性，不是节点名称。
            return if 精灵是三维模型(实体) {
                Self::三维网格
            } else {
                Self::精灵
            };
        }
        if 有子实体 {
            Self::容器
        } else {
            Self::普通实体
        }
    }

    /// 该类型在场景树里显示的图标。
    pub fn 图标(self) -> 图标 {
        match self {
            Self::摄像机 => 图标::摄像机,
            Self::地形 => 图标::地形,
            Self::三维网格 => 图标::立方体,
            Self::精灵 => 图标::图片,
            Self::容器 => 图标::层级容器,
            Self::普通实体 => 图标::实体点,
        }
    }

    /// 该类型的词条键（悬停提示用）。
    pub fn 名称键(self) -> &'static str {
        match self {
            Self::摄像机 => "node_kind_camera",
            Self::地形 => "node_kind_terrain",
            Self::三维网格 => "node_kind_mesh3d",
            Self::精灵 => "node_kind_sprite",
            Self::容器 => "node_kind_container",
            Self::普通实体 => "node_kind_entity",
        }
    }

    /// 该类型的稳定代号（进证据 JSON，与界面语言无关）。
    pub fn 代号(self) -> &'static str {
        match self {
            Self::摄像机 => "camera",
            Self::地形 => "terrain",
            Self::三维网格 => "mesh3d",
            Self::精灵 => "sprite",
            Self::容器 => "container",
            Self::普通实体 => "entity",
        }
    }

    /// 全部类型（测试与覆盖性断言用）。
    pub fn 全部() -> &'static [节点类型] {
        &[
            节点类型::摄像机,
            节点类型::地形,
            节点类型::三维网格,
            节点类型::精灵,
            节点类型::容器,
            节点类型::普通实体,
        ]
    }
}

/// `Sprite` 组件是否被配置成三维模型。
///
/// 判据只有一条：`Sprite` 的 `模型` 属性是一个**非空资源引用**。
/// 属性名取自 `editor_app::scene_bridge` 的 Sprite 组件描述
/// （`结果.insert("模型", …)`），不是这里凭空约定的字符串。
fn 精灵是三维模型(实体: &场景实体) -> bool {
    let Some(精灵) = 实体.取组件("Sprite") else {
        return false;
    };
    match 精灵.属性.get("模型") {
        Some(scene_doc::property::属性值::资源(引用)) => !引用.路径.文本().is_empty(),
        _ => false,
    }
}

/// 折叠指示器的状态。///
/// 与节点类型图标**完全独立**：折叠指示器在左、类型图标在右，
/// 各自有独立的绘制矩形与点击区域（折叠指示器可点，类型图标不可点）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 折叠指示 {
    /// 有子实体且已折叠 → 右向箭头。
    收起,
    /// 有子实体且已展开 → 下向箭头。
    展开,
    /// 没有子实体 → 固定宽度的空白占位（**不画**可点击的箭头）。
    无,
}

impl 折叠指示 {
    /// 由"是否有子实体"与"是否展开"决定。
    pub fn 判定(有子实体: bool, 展开: bool) -> Self {
        match (有子实体, 展开) {
            (false, _) => Self::无,
            (true, true) => Self::展开,
            (true, false) => Self::收起,
        }
    }

    /// 指示器图标（`无` 时为 `None`，调用方画等宽占位）。
    pub fn 图标(self) -> Option<图标> {
        match self {
            Self::收起 => Some(图标::折叠收起),
            Self::展开 => Some(图标::折叠展开),
            Self::无 => None,
        }
    }

    /// 该指示器是否可点击（只有真正的折叠箭头可点）。
    pub fn 可点击(self) -> bool {
        matches!(self, Self::收起 | Self::展开)
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use scene_doc::document::{场景实体, 组件数据};

    /// 造一个挂了指定组件的实体。
    fn 带组件(名称: &str, 类型名: &str) -> 场景实体 {
        let mut 实体 = 场景实体::新建(名称);
        let 组件 = 组件数据 {
            类型名: 类型名.to_string(),
            属性: Default::default(),
        };
        assert!(实体.加组件(组件), "组件应当被加上");
        实体
    }

    #[test]
    fn 已注册组件各自映射到专用图标() {
        assert_eq!(
            节点类型::判定(&带组件("相机", "Camera2d"), false),
            节点类型::摄像机
        );
        assert_eq!(
            节点类型::判定(&带组件("主相机", "Camera3d"), false),
            节点类型::摄像机
        );
        assert_eq!(
            节点类型::判定(&带组件("地形", "TileTerrain"), false),
            节点类型::地形
        );
        assert_eq!(
            节点类型::判定(&带组件("地板", "Primitive3d"), false),
            节点类型::三维网格
        );
        assert_eq!(
            节点类型::判定(&带组件("树", "Sprite"), false),
            节点类型::精灵
        );
    }

    /// 每种类型的图标必须互不相同 —— 否则"不同类型显示不同图标"就是空话。
    #[test]
    fn 每种节点类型的图标互不相同() {
        let 图标列表: Vec<图标> = 节点类型::全部().iter().map(|类型| 类型.图标()).collect();
        let 原数量 = 图标列表.len();
        let mut 去重 = 图标列表.clone();
        去重.sort_unstable();
        去重.dedup();
        assert_eq!(去重.len(), 原数量, "节点类型图标必须互不相同：{图标列表:?}");
    }

    /// 基础组件不参与判定（否则所有实体都会被判成同一种）。
    #[test]
    fn 只有变换与可见性的实体不算任何专用类型() {
        for 类型名 in ["Transform", "Visibility"] {
            let 实体 = 带组件("随便", 类型名);
            assert_eq!(
                节点类型::判定(&实体, false),
                节点类型::普通实体,
                "`{类型名}` 不应被判成专用节点类型"
            );
        }
    }

    /// 有子实体、无可识别组件 → 容器；没有子实体 → 普通实体。
    #[test]
    fn 容器与普通实体按真实子实体关系区分() {
        let 空 = 场景实体::新建("空");
        assert_eq!(节点类型::判定(&空, false), 节点类型::普通实体);
        assert_eq!(节点类型::判定(&空, true), 节点类型::容器);
    }

    /// 多组件同时存在时优先级固定，不随组件顺序变化。
    #[test]
    fn 多组件优先级固定且与添加顺序无关() {
        let 先精灵后相机 = {
            let mut 实体 = 带组件("甲", "Sprite");
            实体.加组件(组件数据 {
                类型名: "Camera2d".to_string(),
                属性: Default::default(),
            });
            实体
        };
        let 先相机后精灵 = {
            let mut 实体 = 带组件("乙", "Camera2d");
            实体.加组件(组件数据 {
                类型名: "Sprite".to_string(),
                属性: Default::default(),
            });
            实体
        };
        assert_eq!(节点类型::判定(&先精灵后相机, false), 节点类型::摄像机);
        assert_eq!(节点类型::判定(&先相机后精灵, false), 节点类型::摄像机);
    }

    /// 未知组件名不能让判定崩，也不能被当成已知类型。
    #[test]
    fn 未知组件回退到通用类型() {
        let 实体 = 带组件("音频?", "AudioSource");
        assert_eq!(节点类型::判定(&实体, false), 节点类型::普通实体);
        let 实体 = 带组件("灯?", "PointLight");
        assert_eq!(节点类型::判定(&实体, true), 节点类型::容器);
    }

    /// `Sprite` 带 `模型` 资源时实际渲染成三维模型，图标必须与二维精灵不同。
    ///
    /// 判据是**真实组件属性**（`模型` → 资源引用），不是节点名称：
    /// 3D 示例里的「长货柜·中央」挂的是 `Sprite` + `模型`，它渲染出来是
    /// 一个 glTF 模型，给它贴"二维图片"图标会误导用户。
    #[test]
    fn 带模型资源的精灵被判成三维网格() {
        use scene_doc::property::{属性值, 资源引用值};

        // 纯二维精灵：只有贴图，没有模型。
        let 二维精灵 = 带组件("青溪村·东屋", "Sprite");
        assert_eq!(节点类型::判定(&二维精灵, false), 节点类型::精灵);

        // 带模型的精灵：`模型` 属性是非空资源引用。
        let 路径 = scene_doc::path::项目相对路径::解析("assets/models/box.gltf")
            .expect("测试路径应当合法");
        let mut 三维模型 = 场景实体::新建("长货柜·中央");
        let 属性 = [("模型".to_string(), 属性值::资源(资源引用值::按路径(路径)))]
            .into_iter()
            .collect();
        assert!(三维模型.加组件(组件数据 {
            类型名: "Sprite".to_string(),
            属性,
        }));
        assert_eq!(
            节点类型::判定(&三维模型, false),
            节点类型::三维网格,
            "带模型资源的 Sprite 应当按三维内容显示"
        );
    }

    /// `模型` 属性存在但为空（属性值 `空`）时不算三维模型。
    #[test]
    fn 空的模型属性仍算二维精灵() {
        use scene_doc::property::属性值;

        let mut 实体 = 场景实体::新建("尚未指定模型");
        let 属性 = [("模型".to_string(), 属性值::空)].into_iter().collect();
        assert!(实体.加组件(组件数据 {
            类型名: "Sprite".to_string(),
            属性,
        }));
        assert_eq!(节点类型::判定(&实体, false), 节点类型::精灵);
    }

    #[test]
    fn 折叠指示由子实体与展开状态共同决定() {
        assert_eq!(折叠指示::判定(false, false), 折叠指示::无);
        assert_eq!(折叠指示::判定(false, true), 折叠指示::无);
        assert_eq!(折叠指示::判定(true, true), 折叠指示::展开);
        assert_eq!(折叠指示::判定(true, false), 折叠指示::收起);

        // 叶子节点不得有可点击的箭头。
        assert_eq!(折叠指示::无.图标(), None);
        assert!(!折叠指示::无.可点击());
        assert!(折叠指示::收起.可点击());
        assert!(折叠指示::展开.可点击());
        // 折叠指示器的图标不能与任何节点类型图标相同（视觉上必须能区分）。
        for 指示 in [折叠指示::收起, 折叠指示::展开] {
            let 指示图标 = 指示.图标().expect("有子实体时必须有图标");
            for 类型 in 节点类型::全部() {
                assert_ne!(
                    指示图标,
                    类型.图标(),
                    "折叠指示器与节点类型 `{}` 用了同一个图标",
                    类型.代号()
                );
            }
        }
    }

    #[test]
    fn 类型都有代号与词条键且唯一() {
        let mut 代号: Vec<&str> = 节点类型::全部().iter().map(|类型| 类型.代号()).collect();
        let 原数量 = 代号.len();
        代号.sort_unstable();
        代号.dedup();
        assert_eq!(代号.len(), 原数量, "类型代号必须唯一");
        for 类型 in 节点类型::全部() {
            assert!(!类型.名称键().is_empty());
            assert_ne!(类型.名称键(), 类型.代号());
        }
    }
}
