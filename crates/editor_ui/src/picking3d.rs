    #[test]
    fn 包围盒可以合并与膨胀() {
        let 甲 = 世界包围盒::由角点((0.0, 0.0, 0.0), (1.0, 1.0, 1.0));
        let 乙 = 世界包围盒::由角点((1.0, 1.0, 1.0), (2.0, 3.0, 2.0));
        let mut 并 = 甲;
        并.并(乙);
        assert_eq!(并.最小, (0.0, 0.0, 0.0));
        assert_eq!(并.最大, (2.0, 3.0, 2.0));
        assert!(并.有效());
        let 空 = 世界包围盒 {
            最小: (f32::MAX, f32::MAX, f32::MAX),
            最大: (f32::MIN, f32::MIN, f32::MIN),
        };
        let mut 初 = 空;
        初.并(甲);
        assert_eq!(初, 甲, "无效盒并入有效盒时应直接取后者");
        assert_eq!(并.膨胀(0.5).最大, (2.5, 3.5, 2.5));
    }

