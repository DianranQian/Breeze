//! 预制件面板：列出项目里的模板，点击创建实例。
//!
//! 这是三层预制件架构在界面层的入口。模板目录（`prefab_catalog`）只读，
//! 创建实例统一走 `编辑器命令::创建预制件实例`：撤销、存档与后续同步
//! 因此自动生效，面板自身不直接修改场景文档。

use editor_core::command::编辑器命令;
use editor_core::prefab_catalog::预制件目录;
use egui::{RichText, Ui};
use scene_doc::document::变换数据;
use scene_doc::path::项目相对路径;
use scene_doc::prefab::预制件标识;

use crate::state::{UiAction, 绘制上下文};

/**
 * 面板一行所需的全部数据，从模板目录按帧拷贝一份。
 *
 * 字段字典：
 * * `标识` —— 模板身份，点击时用它回目录取完整模板；
 * * `名称 / 版本` —— 行首显示的文字；
 * * `路径` —— 模板文件的项目相对路径，也是创建命令的必填参数。
 *
 * 【为什么不直接在循环里借用模板条目】
 * 每行点击后要往 `上下文.动作` 里推动作，而 `上下文` 是可变借用：
 * 一边持有目录里的模板引用、一边可变借用同一个结构，借用检查器不允许。
 * 拷贝名称与路径（都是短字符串）比「先收集再绘制」结构下反复取模板更直接。
 */
struct 模板行数据 {
    标识: 预制件标识,
    名称: String,
    版本: u64,
    路径: Option<项目相对路径>,
}

/// 把模板目录摊平成面板行。
fn 收集模板行(目录: &预制件目录) -> Vec<模板行数据> {
    目录
        .条目列表()
        .map(|条目| 模板行数据 {
            标识: 条目.标识,
            名称: 条目.模板.头.名称.clone(),
            版本: 条目.模板.头.版本,
            路径: 条目.路径.cloned(),
        })
        .collect()
}

/**
 * 绘制预制件面板。
 *
 * 【数据来源】模板清单取自 `编辑器状态.预制件目录`：目录在打开项目与保存
 * 模板时刷新，面板每帧只读内存，不扫描磁盘。
 *
 * 【交互】
 * 1. 点击一条模板 → 在视口相机中心创建实例，并被自动选中；
 * 2. 顶部「刷新」重扫 `prefabs/`，用于在编辑器外修改过模板文件之后；
 * 3. 未打开项目或目录为空时给一句提示，不留一片空白。
 *
 * 【放置为什么取相机中心】
 * 用户把视图滚远之后原点常常落在屏幕外，新建的实例「看不见」；
 * 相机中心一定在当前视野内，符合拖入即现身的编辑习惯。
 */
pub fn 绘制(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>) {
    ui.horizontal(|ui| {
        ui.label(RichText::new(上下文.语言.取("prefab_browser")).strong());
        ui.label(
            RichText::new(上下文.编辑器.预制件目录.数量().to_string()).color(上下文.配色.次要文字),
        );
        if ui
            .small_button(上下文.语言.取("refresh"))
            .on_hover_text(上下文.语言.取("prefab_refresh_hint"))
            .clicked()
        {
            上下文.动作.推(UiAction::刷新预制件目录);
        }
    });
    ui.separator();

    if 上下文.编辑器.项目.is_none() {
        ui.add_space(12.0);
        ui.label(
            RichText::new(上下文.语言.取("assets_no_project_hint")).color(上下文.配色.次要文字),
        );
        return;
    }

    if 上下文.编辑器.预制件目录.数量() == 0 {
        ui.add_space(12.0);
        ui.label(RichText::new(上下文.语言.取("prefab_empty_hint")).color(上下文.配色.次要文字));
        return;
    }

    let 中心 = 上下文.界面.相机.中心;
    let 放置 = 变换数据 {
        平移: (中心.0, 中心.1, 0.0),
        ..变换数据::单位()
    };
    let 行列表 = 收集模板行(&上下文.编辑器.预制件目录);
    let 行高 = (上下文.外观.基础字号 + 10.0).max(24.0);

    egui::ScrollArea::vertical()
        .auto_shrink([false, false])
        .show(ui, |ui| {
            for 行 in &行列表 {
                绘制模板行(ui, 上下文, 行, &放置, 行高);
            }
        });
}

/**
 * 画一条模板行，并在点击时把创建实例命令推进动作队列。
 *
 * 【参数字典】
 * * `行` —— 本行展示的数据（名称 / 版本 / 路径 / 标识）；
 * * `放置` —— 新实例相对父节点的变换，取进入绘制时的相机中心；
 * * `行高` —— 与字号联动的整行高度。
 *
 * 【为什么整行都是按钮】
 * 面板常被拖窄，只有文字可点会让点击目标和视觉行对不上；
 * `add_sized` 把按钮撑满可用宽度，行与行的点击区域不会重叠。
 *
 * 【没有文件路径的模板为什么禁用】
 * 创建命令要求写入模板路径，实例记录靠它找回模板；内存构造的目录
 * （测试或未落盘的模板）没有路径，此时禁用按钮并说明原因，
 * 比让命令报错更像是「这里本来就不可用」。
 *
 * 【为什么要把行矩形写进界面状态】
 * 自动验收需要按真实矩形中心点击这一行。行高随字号、行宽随停靠宽度变化，
 * 猜坐标一旦点偏就会落到相邻模板上，于是「点击没创建实例」与
 * 「点错了模板」在证据上无法区分。
 */
fn 绘制模板行(
    ui: &mut Ui,
    上下文: &mut 绘制上下文<'_>,
    行: &模板行数据,
    放置: &变换数据,
    行高: f32,
) {
    let 标题 = format!("{}  v{}", 行.名称, 行.版本);
    let Some(路径) = &行.路径 else {
        let 响应 = ui.add_enabled(
            false,
            egui::Button::new(标题).min_size(egui::vec2(ui.available_width(), 行高)),
        );
        上下文.界面.预制件行几何.push(crate::state::预制件行几何 {
            标识: format!("{:?}", 行.标识),
            名称: 行.名称.clone(),
            版本: 行.版本,
            行矩形: 响应.rect,
            可创建: false,
        });
        响应.on_disabled_hover_text(上下文.语言.取("prefab_path_missing_hint"));
        return;
    };

    let 提示 = format!("{}\n{}", 上下文.语言.取("prefab_create_hint"), 路径.文本());
    let 响应 = ui
        .add_sized([ui.available_width(), 行高], egui::Button::new(标题))
        .on_hover_text(提示);
    上下文.界面.预制件行几何.push(crate::state::预制件行几何 {
        标识: format!("{:?}", 行.标识),
        名称: 行.名称.clone(),
        版本: 行.版本,
        行矩形: 响应.rect,
        可创建: true,
    });
    if !响应.clicked() {
        return;
    }

    let Some(模板) = 上下文.编辑器.预制件目录.取(&行.标识) else {
        return;
    };
    let 命令 = 编辑器命令::创建预制件实例 {
        模板: Box::new(模板.clone()),
        模板路径: 路径.clone(),
        内层模板: 上下文.编辑器.预制件目录.嵌套模板集(&行.标识),
        放置: *放置,
        父实体: None,
        指定实例根: None,
    };
    上下文.动作.推(UiAction::执行命令(命令));
}
