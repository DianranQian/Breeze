    #[test]
    fn 清空资源预览会丢弃旧目标() {
        let mut 界面 = 界面状态::新建();
        界面.选中资源(路径("assets/hero.png"));
        界面.资源预览.阶段 = 预览阶段::就绪;
        let 旧代次 = 界面.预览请求.代次;

        界面.清空资源预览();
        assert!(界面.资源选中.is_none());
        assert_eq!(界面.资源预览.阶段, 预览阶段::空闲);
        assert!(界面.资源预览.路径.is_none());
        assert!(
            界面.预览请求.代次 > 旧代次,
            "清空也必须递增代次：迟到的旧结果不能把预览填回来"
        );
    }

    #[test]
    fn 只有代次匹配的结果才算最新() {
        let mut 界面 = 界面状态::新建();
        界面.选中资源(路径("assets/hero.png"));
        let 请求 = 界面.预览请求.clone();

        let 旧结果 = 资源预览快照 {
            代次: 请求.代次.saturating_sub(1),
            阶段: 预览阶段::就绪,
            ..Default::default()
        };
        assert!(!旧结果.是最新(&请求), "旧代次的结果不能覆盖新选择");

        let 新结果 = 资源预览快照 {
            代次: 请求.代次,
            阶段: 预览阶段::就绪,
            ..Default::default()
        };
        assert!(新结果.是最新(&请求));
    }

