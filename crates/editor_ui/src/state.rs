/// 视口的 Bevy 渲染结果。
///
/// 由 `editor_app` 的预览模块每帧填入：它把场景实体渲染到一张纹理，
/// 再把该纹理的 egui 句柄交给界面显示。界面**不知道**纹理是怎么来的，
/// 只知道"有这么一张图，画在视口矩形里"。
///
/// 这种解耦让 `editor_ui` 继续不依赖 Bevy —— 它只需要一个
/// `egui::TextureId` 与尺寸。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 视口渲染结果 {
    /// egui 纹理句柄。
    pub 纹理: egui::TextureId,
    /// 纹理的像素尺寸。用于按视口区域等比显示。
    pub 像素尺寸: (u32, u32),
}

/// 一次绘制所需的全部输入。
///
/// 把"编辑器数据"与"界面状态"分开持有：面板只允许**读**编辑器数据，
/// 所有对它的修改必须变成 [`UiAction`] 排进队列。
pub struct 绘制上下文<'平台> {
    /// 编辑器权威状态（只读）。
    pub 编辑器: &'平台 编辑器状态,
    /// 界面自有状态（可变）。
    pub 界面: &'平台 mut 界面状态,
    /// 动作队列（可变）。
    pub 动作: &'平台 mut 动作队列,
    /// 本帧生效的主题。
    ///
    /// 为什么是**克隆**而不是引用：主题库住在 [`界面状态`] 里，
    /// 而面板需要 `&mut 界面状态`（搜索框、展开状态等）。同时持有
    /// "可变的状态"与"其中的不可变引用"在 Rust 里是不允许的。
    /// 一个主题只有几百字节，每帧克隆一份的代价远低于把状态拆成两半。
    ///
    /// 当主题编辑器打开时，这里放的是**草稿**（实时预览）。
    pub 主题: crate::theme::主题,
    /// 配色（从主题里取出的拷贝，面板绘制高频使用）。
    pub 配色: 编辑器配色,
    /// 外观参数（字号、圆角、间距、图标尺寸）。
    pub 外观: crate::theme::外观,
    /// 图标纹理缓存。
    ///
    /// 由调用方（`editor_app`）持有并传进来：纹理是 GPU 资源，
    /// 不属于"界面状态"，也不该跟着界面状态一起被克隆。
    pub 图标: &'平台 mut crate::icons::图标库,
    /// 资源缩略图纹理缓存：项目相对路径文本 → 纹理句柄。
    ///
    /// 由 `editor_app` 负责按需加载并塞进来。纹理只属于界面，
    /// 不能进场景文档，因此单独放在这里而不是编辑器状态里。
    pub 缩略图: &'平台 BTreeMap<String, egui::TextureHandle>,
    /// 瓦片集图集纹理：图片路径文本 → egui 纹理。
    ///
    /// 瓦片地图面板用 UV 从整张图集里取瓦片，因此这里只按图片缓存，
    /// 不为每张瓦片单独建纹理。
    pub 瓦片图集: &'平台 BTreeMap<String, egui::TextureHandle>,
    /// 视口的 Bevy 渲染结果。`None` 表示预览尚未就绪（例如首帧），
    /// 此时视口退化为只画叠加层。
    pub 视口纹理: Option<视口渲染结果>,
    /// 运行时是否正在播放。
    pub 正在运行: bool,
    /// 运行时是否已暂停。
    pub 已暂停: bool,
    /// 运行时诊断信息。
    pub 运行时信息: &'平台 运行时诊断,
    /// 构建配置与最近一次构建报告（只读；改配置走动作队列）。
    pub 构建: &'平台 editor_core::build::构建快照,
    /// 运行状态、本次运行日志与最近运行记录（只读；操作走动作队列）。
    pub 运行: &'平台 editor_core::run_entry::运行快照,
    /// 远程调试会话的只读快照（真实协议数据；断开后仍保留但不可标成实时）。
    pub 调试: &'平台 editor_core::runtime_debug::运行时调试快照,
    /// 运行时快照与属性修改历史（只读）。
    pub 调试历史: &'平台 editor_core::runtime_debug::运行时调试历史,
    /// 统一诊断的当前结果视图（只读；筛选状态在 [`界面状态`] 里）。
    pub 统一诊断: &'平台 editor_core::diagnostics::诊断快照,
    /// 资源导入状态表：项目相对路径文本 → 状态。
    ///
    /// 用表而不是报告：资源面板每帧要为每个文件查状态，
    /// 线性扫几百条会让面板变成 O(n²)。
    pub 导入状态: &'平台 BTreeMap<String, editor_core::project::导入状态>,
    /// 编辑器配置目录（帮助窗口显示路径、并提供"打开配置目录"入口）。
    pub 配置目录: &'平台 std::path::Path,
    /// 当前界面语言。
    ///
    /// 放在绘制上下文里而不是全局静态：语言是**用户可切换的状态**，
    /// 用全局可变静态会让"谁在什么时候改了语言"变得无法追踪，
    /// 也会让测试之间互相干扰。
    pub 语言: crate::i18n::语言,
}

impl 绘制上下文<'_> {
    /// 查询某实体的缩略图。
    pub fn 缩略图(&self, 路径: &项目相对路径) -> Option<&egui::TextureHandle> {
        self.缩略图.get(路径.文本())
    }

    /// 查询一张图集图片的 egui 纹理。
    pub fn 图集纹理(&self, 图片: &str) -> Option<&egui::TextureHandle> {
        self.瓦片图集.get(图片)
    }

    /// 视口纹理是否可用。
    pub fn 有视口纹理(&self) -> bool {
        self.视口纹理.is_some()
    }

    /// 当前选中的主实体。
    pub fn 主选中(&self) -> Option<实体标识> {
        self.编辑器.选择.主选中()
    }

    /// 当前是否有打开的项目。
    pub fn 有项目(&self) -> bool {
        self.编辑器.项目.is_some()
    }
}

