    /// 当前项目的 Rust 源文件列表（项目变化时重扫，其余时候走缓存）。
    ///
    /// 返回**克隆**而不是引用：调用方随后要拿 `&mut` 的动作队列/界面状态，
    /// 持有这里的借用会与之冲突。列表通常只有几十项，克隆成本可以忽略。
    pub fn 源文件(
        &mut self,
        项目: Option<&editor_core::project::项目描述>,
    ) -> Vec<项目相对路径> {
        let 根 = 项目.map(|项目| 项目.根目录().to_path_buf());
        if self.源文件缓存.0 != 根 {
            self.源文件缓存.1 = 项目.map(|项目| 项目.源文件列表()).unwrap_or_default();
            self.源文件缓存.0 = 根;
        }
        self.源文件缓存.1.clone()
    }

