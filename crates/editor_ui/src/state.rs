#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 视口渲染结果 {
    /// egui 纹理句柄。
    pub 纹理: egui::TextureId,
    /// 纹理的像素尺寸。用于按视口区域等比显示。
    pub 像素尺寸: (u32, u32),
}

/// 一次绘制所需的全部输入。
///
/// 把"编辑器数据"与"界面状态"分开持有：面板只允许**读**编辑器数据，
/// 所有对它的修改必须变成 [`UiAction`] 排进队列。
pub struct 绘制上下文<'平台> {
    /// 编辑器权威状态（只读）。
    pub 编辑器: &'平台 编辑器状态,
    /// 界面自有状态（可变）。
    pub 界面: &'平台 mut 界面状态,
    /// 动作队列（可变）。
    pub 动作: &'平台 mut 动作队列,
    /// 本帧生效的主题。
    ///
    /// 为什么是**克隆**而不是引用：主题库住在 [`界面状态`] 里，
    /// 而面板需要 `&mut 界面状态`（搜索框、展开状态等）。同时持有
    /// "可变的状态"与"其中的不可变引用"在 Rust 里是不允许的。
    /// 一个主题只有几百字节，每帧克隆一份的代价远低于把状态拆成两半。
    ///
    /// 当主题编辑器打开时，这里放的是**草稿**（实时预览）。
    pub 主题: crate::theme::主题,
    /// 配色（从主题里取出的拷贝，面板绘制高频使用）。
    pub 配色: 编辑器配色,
    /// 外观参数（字号、圆角、间距、图标尺寸）。
    pub 外观: crate::theme::外观,
    /// 图标纹理缓存。
    ///
    /// 由调用方（`editor_app`）持有并传进来：纹理是 GPU 资源，
    /// 不属于"界面状态"，也不该跟着界面状态一起被克隆。
    pub 图标: &'平台 mut crate::icons::图标库,
    /// 资源缩略图纹理缓存：项目相对路径文本 → 纹理句柄。
    ///
    /// 由 `editor_app` 负责按需加载并塞进来。纹理只属于界面，
    /// 不能进场景文档，因此单独放在这里而不是编辑器状态里。
    pub 缩略图: &'平台 BTreeMap<String, egui::TextureHandle>,
    /// 视口的 Bevy 渲染结果。`None` 表示预览尚未就绪（例如首帧），
    /// 此时视口退化为只画叠加层。
    pub 视口纹理: Option<视口渲染结果>,
    /// 运行时是否正在播放。
    pub 正在运行: bool,
    /// 运行时是否已暂停。
    pub 已暂停: bool,
    /// 运行时诊断信息。
    pub 运行时信息: &'平台 运行时诊断,
    /// 当前界面语言。
    ///
    /// 放在绘制上下文里而不是全局静态：语言是**用户可切换的状态**，
    /// 用全局可变静态会让"谁在什么时候改了语言"变得无法追踪，
    /// 也会让测试之间互相干扰。
    pub 语言: crate::i18n::语言,
}

impl 绘制上下文<'_> {
    /// 查询某实体的缩略图。
    pub fn 缩略图(&self, 路径: &项目相对路径) -> Option<&egui::TextureHandle> {
        self.缩略图.get(路径.文本())
    }

    /// 视口纹理是否可用。
    pub fn 有视口纹理(&self) -> bool {
        self.视口纹理.is_some()
    }

    /// 当前选中的主实体。
    pub fn 主选中(&self) -> Option<实体标识> {
        self.编辑器.选择.主选中()
    }

    /// 当前是否有打开的项目。
    pub fn 有项目(&self) -> bool {
        self.编辑器.项目.is_some()
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 视口矩形的四角必须精确映射到视口的四角。
    ///
    /// 这是"可见世界矩形"作为坐标映射唯一真源的核心性质：
    /// Bevy 正交投影被设成这个矩形，因此纹理边缘就是矩形边缘；
    /// egui 用 `世界转屏幕` 画叠加层，也必须把矩形边缘落在视口边缘。
    /// 两者一致，叠加层才可能与渲染结果对齐。
    #[test]
    fn 可见世界矩形与屏幕映射自洽() {
        let 相机 = 视口相机 {
            中心: (100.0, -50.0),
            缩放: 37.0,
            ..视口相机::default()
        };
        let 视口尺寸 = egui::vec2(800.0, 600.0);
        let (最小, 最大) = 相机.可见世界矩形(视口尺寸);

        // 左上角：世界 (最小.0, 最大.1) → 屏幕 (0, 0)
        let 左上 = 相机.世界转屏幕((最小.0, 最大.1), 视口尺寸);
        assert!(
            左上.x.abs() < 1e-3 && 左上.y.abs() < 1e-3,
            "世界矩形左上角应映射到屏幕 (0,0)，实际 {左上:?}"
        );

        // 右下角：世界 (最大.0, 最小.1) → 屏幕 (宽, 高)
        let 右下 = 相机.世界转屏幕((最大.0, 最小.1), 视口尺寸);
        assert!(
            (右下.x - 视口尺寸.x).abs() < 1e-3 && (右下.y - 视口尺寸.y).abs() < 1e-3,
            "世界矩形右下角应映射到屏幕 ({}, {})，实际 {右下:?}",
            视口尺寸.x,
            视口尺寸.y
        );
    }

    /// 世界矩形的中心必须等于相机中心，宽高必须等于视口尺寸除以缩放。
    ///
    /// Bevy 相机的正交投影直接吃这三个量，因此这条性质保证了
    /// "相机看到的世界范围"就是编辑器认为的可见范围。
    #[test]
    fn 可见世界矩形尺寸与缩放一致() {
        for (缩放, 尺寸) in [
            (4.0f32, egui::vec2(400.0, 300.0)),
            (48.0, egui::vec2(800.0, 600.0)),
            (200.0, egui::vec2(1600.0, 900.0)),
        ] {
            let 相机 = 视口相机 {
                中心: (10.0, 20.0),
                缩放,
                ..视口相机::default()
            };
            let (最小, 最大) = 相机.可见世界矩形(尺寸);

            assert!(
                ((最小.0 + 最大.0) * 0.5 - 10.0).abs() < 1e-3,
                "矩形中心 x 应等于相机中心"
            );
            assert!(
                ((最小.1 + 最大.1) * 0.5 - 20.0).abs() < 1e-3,
                "矩形中心 y 应等于相机中心"
            );
            // 像素/世界单位 = 缩放 → 世界宽度 = 像素宽度 / 缩放
            assert!(
                ((最大.0 - 最小.0) - 尺寸.x / 缩放).abs() < 1e-3,
                "世界宽度应为 {}，实际 {}",
                尺寸.x / 缩放,
                最大.0 - 最小.0
            );
            assert!(
                ((最大.1 - 最小.1) - 尺寸.y / 缩放).abs() < 1e-3,
                "世界高度应为 {}，实际 {}",
                尺寸.y / 缩放,
                最大.1 - 最小.1
            );
        }
    }

    /// 屏幕与世界之间的往返转换必须无漂移。
    #[test]
    fn 屏幕与世界往返一致() {
        let 相机 = 视口相机 {
            中心: (-12.5, 7.25),
            缩放: 63.5,
            ..视口相机::default()
        };
        let 视口尺寸 = egui::vec2(1024.0, 768.0);

        for 屏幕 in [
            egui::vec2(0.0, 0.0),
            egui::vec2(1024.0, 768.0),
            egui::vec2(512.0, 384.0),
            egui::vec2(123.0, 456.0),
        ] {
            let 世界 = 相机.屏幕转世界(屏幕, 视口尺寸);
            let 回到屏幕 = 相机.世界转屏幕(世界, 视口尺寸);
            assert!(
                (回到屏幕.x - 屏幕.x).abs() < 1e-2 && (回到屏幕.y - 屏幕.y).abs() < 1e-2,
                "往返转换漂移过大：{屏幕:?} → {世界:?} → {回到屏幕:?}"
            );
        }
    }

    /// 以锚点缩放后，锚点下的世界坐标必须保持不动。
    ///
    /// 这条性质决定了滚轮缩放的手感：锚点漂移会让用户觉得
    /// "想放大看的东西跑出屏幕"。
    #[test]
    fn 以锚点缩放保持锚点世界坐标不变() {
        let 视口尺寸 = egui::vec2(800.0, 600.0);
        let 锚点 = egui::vec2(150.0, 500.0); // 左下角附近
        let mut 相机 = 视口相机::default();

        let 锚点世界_前 = 相机.屏幕转世界(锚点, 视口尺寸);
        for _ in 0..8 {
            相机.以锚点缩放(1.25, 锚点, 视口尺寸);
        }
        let 锚点世界_后 = 相机.屏幕转世界(锚点, 视口尺寸);

        assert!(
            (锚点世界_前.0 - 锚点世界_后.0).abs() < 1e-2
                && (锚点世界_前.1 - 锚点世界_后.1).abs() < 1e-2,
            "缩放后锚点世界坐标漂移了：{锚点世界_前:?} → {锚点世界_后:?}"
        );
    }

    /// 缩放始终被夹在允许范围内。
    #[test]
    fn 缩放被限制在合法区间() {
        let 视口尺寸 = egui::vec2(800.0, 600.0);
        let 锚点 = egui::vec2(400.0, 300.0);
        let mut 相机 = 视口相机::default();

        for _ in 0..100 {
            相机.以锚点缩放(0.5, 锚点, 视口尺寸);
        }
        assert!(
            (相机.缩放 - 视口相机::最小缩放).abs() < 0.01,
            "持续缩小应停在最小缩放 {}，实际 {}",
            视口相机::最小缩放,
            相机.缩放
        );

        for _ in 0..200 {
            相机.以锚点缩放(2.0, 锚点, 视口尺寸);
        }
        assert!(
            (相机.缩放 - 视口相机::最大缩放).abs() < 0.01,
            "持续放大应停在最大缩放 {}，实际 {}",
            视口相机::最大缩放,
            相机.缩放
        );
    }

    /// 适应包围盒后，整个包围盒必须落在可见矩形内。
    ///
    /// 这条测试曾经抓出一个真实缺陷：缩放下限取得太大（4.0），
    /// 导致跨度超过 200 世界单位的场景**无法**被适应到窗口里 ——
    /// 按钮看起来"没反应"，其实是缩放被夹住了。
    #[test]
    fn 适应包围盒后对象可见() {
        let 视口尺寸 = egui::vec2(800.0, 600.0);

        // 覆盖小、中、大三种跨度，其中"大"这一档正是原先会失败的场景。
        for (最小, 最大) in [
            ((-10.0, -10.0), (10.0, 10.0)),         // 小：20 单位
            ((-500.0, -300.0), (700.0, 900.0)),     // 大：1200 单位
            ((-8000.0, -5000.0), (8000.0, 5000.0)), // 很大：16000 单位
        ] {
            let mut 相机 = 视口相机::default();
            相机.适应包围盒(最小, 最大, 视口尺寸);

            let (可见最小, 可见最大) = 相机.可见世界矩形(视口尺寸);
            assert!(
                可见最小.0 <= 最小.0 + 1e-2 && 可见最小.1 <= 最小.1 + 1e-2,
                "适应后可见矩形应包含包围盒左下角：\
                 可见 {可见最小:?} 应 ≤ 包围盒 {最小:?}（视口 {视口尺寸:?}）"
            );
            assert!(
                可见最大.0 >= 最大.0 - 1e-2 && 可见最大.1 >= 最大.1 - 1e-2,
                "适应后可见矩形应包含包围盒右上角：\
                 可见 {可见最大:?} 应 ≥ 包围盒 {最大:?}（视口 {视口尺寸:?}）"
            );
        }
    }

    /// 极小的包围盒不能把缩放推到上限之外。
    #[test]
    fn 适应极小包围盒时缩放松紧有度() {
        let 视口尺寸 = egui::vec2(800.0, 600.0);
        let mut 相机 = 视口相机::default();
        相机.适应包围盒((0.0, 0.0), (0.001, 0.001), 视口尺寸);
        assert!(
            相机.缩放 <= 视口相机::最大缩放,
            "缩放不应超过上限 {}，实际 {}",
            视口相机::最大缩放,
            相机.缩放
        );
        assert!(相机.缩放.is_finite(), "缩放必须是有限值");
    }
}
