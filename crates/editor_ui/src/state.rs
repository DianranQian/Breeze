impl 界面状态 {
    /// 选中一个资源并请求预览。
    ///
    /// # 为什么换目标一定要递增代次
    ///
    /// 应用层的加载可能是异步的。若两次选择共用同一个代次，慢的旧请求
    /// 完成后会把自己当成"当前答案"写回来，用户看到的就是上一个资源。
    /// 代次是这条链路上唯一的顺序依据，不能省。
    ///
    /// 重复选中同一个资源**不**重置预览，也不重新读盘：反复单击同一个文件
    /// 是常见操作（用户只是想选中它），每次都重新解码会让面板闪一下。
    pub fn 选中资源(&mut self, 路径: 项目相对路径) {
        if self.资源选中.as_ref() == Some(&路径) {
            return;
        }
        self.资源选中 = Some(路径.clone());
        self.模型旋转 = (0.0, 0.0);
        self.模型缩放 = 1.0;
        self.预览请求 = 预览请求 {
            目标: Some(路径),
            代次: self.预览请求.代次.wrapping_add(1),
            强制重载: false,
        };
        // 旧结果立刻失效：面板在等待新结果的这一帧里显示"加载中"，
        // 而不是继续画上一个资源的图。
        self.资源预览 = 资源预览快照 {
            代次: self.预览请求.代次,
            阶段: 预览阶段::加载中,
            ..Default::default()
        };
    }

    /// 清空资源选择与预览（关闭项目/切换项目时调用）。
    pub fn 清空资源预览(&mut self) {
        self.资源选中 = None;
        self.资源行几何.clear();
        self.预览请求 = 预览请求 {
            目标: None,
            代次: self.预览请求.代次.wrapping_add(1),
            强制重载: false,
        };
        self.资源预览 = 资源预览快照 {
            代次: self.预览请求.代次,
            ..Default::default()
        };
    }

    /// 请求重新加载当前选中的资源（文件可能已在编辑器外被修改）。
    pub fn 重新加载预览(&mut self) {
        let Some(路径) = self.资源选中.clone() else {
            return;
        };
        self.预览请求 = 预览请求 {
            目标: Some(路径),
            代次: self.预览请求.代次.wrapping_add(1),
            强制重载: true,
        };
        self.资源预览 = 资源预览快照 {
            代次: self.预览请求.代次,
            阶段: 预览阶段::加载中,
            ..Default::default()
        };
    }
}

/// 音频试听请求。
///
/// # 为什么用"请求 + 清空"而不是让动作层直接播放
///
/// 播放需要 `AssetServer` 与 `Commands`，而动作层（`执行动作队列`）刻意
/// 不持有这些重资源：它要能在没有渲染/资产环境的测试里跑。把"想听什么"
/// 留成一个数据请求，由拥有 `AssetServer` 的系统去执行，
/// 动作层就仍然可以纯数据地测试。
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct 试听请求 {
    /// 要播放的音频（`None` 表示不播放）。
    pub 要播放: Option<scene_doc::path::项目相对路径>,
    /// 是否要求停止当前播放。
    pub 要停止: bool,
}

/// 一次试听请求应当产生的动作。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 试听动作 {
    /// 什么都不做。
    无,
    /// 停止当前播放。
    停止,
    /// 播放指定音频。
    播放(scene_doc::path::项目相对路径),
}

/// 决策函数：把"请求 + 当前正在播什么"变成具体动作。
///
/// 抽成纯函数是为了让状态机可以被单测覆盖：
/// 反复点同一个文件的「试听」应该**从头重播**（先停再播），
/// 而不是静默什么都不发生 —— 后者是"按钮坏了"的典型症状。
pub fn 决定试听动作(请求: &试听请求, 当前: Option<&str>) -> 试听动作 {
    if 请求.要停止 {
        return match 当前 {
            Some(_) => 试听动作::停止,
            None => 试听动作::无,
        };
    }
    match &请求.要播放 {
        Some(路径) => 试听动作::播放(路径.clone()),
        None => 试听动作::无,
    }
}

