//! 界面状态与"界面意图"。
//!
//! # 单向数据流
//!
//! 界面**不直接**改编辑器的数据。每次绘制都把用户操作翻译成
//! [`UiAction`] 推进一个队列，由 `editor_app` 在绘制结束后统一执行。
//!
//! 这样做的三个直接好处：
//!
//! 1. **可测试**：面板绘制函数可以只检查"点了按钮是否产生了正确的意图"，
//!    不需要跑起整个 Bevy 应用；
//! 2. **不会在遍历中改容器**：egui 的闭包里拿着文档的不可变借用，
//!    若在那里直接修改文档，借用检查器必然拒绝，队列天然避开这一问题；
//! 3. **可以合并与拦截**：将来做"关闭前询问是否保存"，只需在
//!    执行队列的地方插入判断，不必改任何面板代码。

