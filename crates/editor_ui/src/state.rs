    /// 切换主开发模式。
    ///
    /// # 这里交换的是"布局集"，不是文档
    ///
    /// 场景文档、选择、撤销栈、主题、语言**全部共享**：切模式不会丢实体、
    /// 不会清选择、不会改主题。只有每个模式的布局集会被换出来。
    /// 第一次进入某个模式时用它自己的出厂布局。
    pub fn 切换模式(&mut self, 新: 开发模式) -> Result<(), String> {
        if 新 == self.模式 {
            return Ok(());
        }
        let 旧模式 = self.模式;
        if matches!(新, 开发模式::脚本) && self.脚本.文档.is_none() {
            // 进入脚本模式但还没有打开任何文件：让脚本面板成为活动标签，
            // 这样用户第一眼看到的是"空编辑器的引导"，而不是视口。
            // （面板本身已经在脚本模式的默认布局里。）
        }
        let 新集 = self
            .模式布局
            .remove(&新)
            .unwrap_or_else(|| crate::dev_modes::出厂工作区集(新, self.语言));
        // 把当前集搬进"其他模式"，再把新集放进来。
        let 旧集 = std::mem::replace(&mut self.工作区, 新集);
        self.模式布局.insert(旧模式, 旧集);
        self.模式 = 新;
        // 修复必须按**新模式**的主面板判断。
        //
        // 这里曾经是不带参数的 `修复()`，它硬性要求"布局必须含视口"，
        // 于是在切到 AI Agent 时把刚装进去的智能体预设判成损坏，
        // 整份换成 2D 通用布局 —— 模式切了、布局没切。
        self.工作区.修复(&新.主面板候选());
        Ok(())
    }

