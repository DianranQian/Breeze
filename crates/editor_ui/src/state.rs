/// 一块具名区域在本帧拿到的矩形（egui 逻辑像素）。
///
/// # 为什么界面层要输出这个
///
/// 自动验收需要把"截图里的像素"与"界面自认为的布局"对上号：
/// 只看截图无法知道某个面板**应该**在哪，只能靠肉眼猜；
/// 只读布局代码又无法证明它真的被画到了窗口上。
///
/// 因此每帧把菜单栏、工具栏、状态栏与每个停靠面板的真实矩形记下来，
/// 截图工具把它写成 JSON 证据文件，再由 `gui_probe` 交叉核对。
/// 这是**测量**，不是渲染逻辑：记录本身不影响任何像素。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 区域快照 {
    /// 稳定标识：`menubar` / `toolbar` / `statusbar`，或面板的菜单键。
    pub 标识: &'static str,
    /// 该区域在界面坐标里的矩形。
    pub 矩形: egui::Rect,
}

/// 场景树一行的真实几何（自动验收用，不影响渲染）。
///
/// # 为什么必须记录"箭头的矩形"而不只是"行的矩形"
///
/// 折叠箭头只有 18px 宽，且靠左缩进 `深度 × indent`。没有真实矩形时，
/// 自动化点击只能**猜**坐标 —— 一旦猜偏，点到的是名称标签（那会改变选择），
/// 而不是折叠按钮，于是"折叠功能坏了"与"点击落点错了"无法区分。
///
/// 上一轮正是这样：折叠算法与单元测试都通过，GUI 点击却没有生效，
/// 因为没有任何证据能说明点击到底落在哪里。现在把行的矩形与箭头的矩形
/// 都写进证据文件，验收按**箭头矩形的中心**点击，并用点击前后的
/// `collapsed` 与可见行列表判断结果。
#[derive(Debug, Clone, PartialEq)]
pub struct 场景行几何 {
    /// 稳定标识（实体标识的调试文本），用于跨帧匹配同一行。
    pub 标识: String,
    /// 显示名。
    pub 名称: String,
    /// 缩进层级。
    pub 深度: usize,
    /// 是否有子实体。
    pub 有子实体: bool,
    /// 当前是否展开（仅对有子实体的行有意义）。
    pub 展开: bool,
    /// 整行矩形。
    pub 行矩形: egui::Rect,
    /// 折叠箭头矩形（没有子实体时为 `None`）。
    pub 箭头矩形: Option<egui::Rect>,
    /// 节点类型代号（`camera` / `terrain` / `mesh3d` / `sprite` / `container` / `entity`）。
    ///
    /// 进证据文件后，"不同类型的节点显示了不同图标"这件事就可以被
    /// **结构化断言**，而不只是靠人眼看截图。
    pub 节点类型: &'static str,
    /// 该行实际使用的图标资源名（来自 [`crate::图标::名称`]）。
    pub 图标: &'static str,
    /// 类型图标矩形（永远存在；类型图标不参与折叠）。
    pub 类型图标矩形: Option<egui::Rect>,
    /// 行内**空白区**矩形（名称文字右边缘 → 右侧状态开关左边缘）。
    ///
    /// 这一块在改造前既不能右键、也不能点选：它上面没有任何控件。
    /// 现在它挂了一个只覆盖空白的点击感应区（右键 = 该行菜单，
    /// 左键 = 选中该行），因此必须把它的真实矩形交给验收，
    /// 否则右键用例只能"猜一个 x 坐标"，猜偏就落到状态开关上，
    /// 于是"菜单没弹出来"与"点错了地方"无法区分。
    ///
    /// 名称过长（空白区宽度不足 [`crate::hierarchy_panel::最小空白区宽度`]）
    /// 时为 `None`：那种情况下确实没有空白区可点。
    pub 行空白矩形: Option<egui::Rect>,
}

/// 场景树右键菜单的**种类**。
///
/// 分成两种而不是一种，是因为它们对用户表达的是两件事：
/// 行菜单作用于"这一个实体"，空白菜单作用于"这张列表本身"
/// （新建顶层实体）。验收也必须能分辨这两者 —— 否则"菜单弹出来了"
/// 无法说明弹的是**哪一个**。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 右键菜单种类 {
    /// 挂在某一行上的菜单（重命名 / 复制 / 新建子实体 / 上移下移 / 删除）。
    场景行,
    /// 挂在场景树**空白区域**上的菜单（新建顶层实体）。
    场景空白,
}

impl 右键菜单种类 {
    /// 稳定代号（进证据文件，与界面语言无关）。
    pub fn 代号(self) -> &'static str {
        match self {
            右键菜单种类::场景行 => "scene_row",
            右键菜单种类::场景空白 => "scene_blank",
        }
    }
}

/// 本帧真实弹出的场景树右键菜单（采集证据用，不影响渲染）。
///
/// # 为什么必须把它记进证据
///
/// 右键菜单是**浮层**：它不改变任何已记录的矩形，不改文档、不改选择。
