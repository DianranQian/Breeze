    ///
    /// Bevy 相机的正交投影直接吃这三个量，因此这条性质保证了
    /// "相机看到的世界范围"就是编辑器认为的可见范围。
    #[test]
    fn 可见世界矩形尺寸与缩放一致() {
        for (缩放, 尺寸) in [
            (4.0f32, egui::vec2(400.0, 300.0)),
            (48.0, egui::vec2(800.0, 600.0)),
            (200.0, egui::vec2(1600.0, 900.0)),
        ] {
            let 相机 = 视口相机 {
                中心: (10.0, 20.0),
                缩放,
                ..视口相机::default()
            };
            let (最小, 最大) = 相机.可见世界矩形(尺寸);

            assert!(
                ((最小.0 + 最大.0) * 0.5 - 10.0).abs() < 1e-3,
                "矩形中心 x 应等于相机中心"
            );
            assert!(
                ((最小.1 + 最大.1) * 0.5 - 20.0).abs() < 1e-3,
                "矩形中心 y 应等于相机中心"
            );
            // 像素/世界单位 = 缩放 → 世界宽度 = 像素宽度 / 缩放
            assert!(
                ((最大.0 - 最小.0) - 尺寸.x / 缩放).abs() < 1e-3,
                "世界宽度应为 {}，实际 {}",
                尺寸.x / 缩放,
                最大.0 - 最小.0
            );
            assert!(
                ((最大.1 - 最小.1) - 尺寸.y / 缩放).abs() < 1e-3,
                "世界高度应为 {}，实际 {}",
                尺寸.y / 缩放,
                最大.1 - 最小.1
            );
        }
    }

    /// 屏幕与世界之间的往返转换必须无漂移。
    #[test]
