#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 右键菜单记录 {
    /// 菜单种类。
    pub 种类: 右键菜单种类,
    /// 行菜单的目标实体显示名；空白菜单为 `None`。
    pub 目标: Option<String>,
    /// 菜单项的语言键（按绘制顺序，与界面语言无关）。
    pub 项: Vec<&'static str>,
}

