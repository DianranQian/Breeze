/// 视口相机。
///
/// 刻意自己算这个变换，而不是复用 Bevy 的 `Camera2d`：编辑器视口的
/// 平移/缩放是**编辑器状态**，它与游戏运行时的相机是两回事。
/// 混用会导致"编辑时拖动视图把游戏相机也带跑了"。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 视口相机 {
    /// 视口中心对应的世界坐标。
    pub 中心: (f32, f32),
    /// 缩放：1 个世界单位等于多少逻辑像素。
    pub 缩放: f32,
    /// 是否显示网格。
    pub 显示网格: bool,
    /// 网格间距（世界单位）。
    pub 网格间距: f32,
    /// 是否显示坐标轴。
    pub 显示坐标轴: bool,
    /// 是否显示实体包围框。
    pub 显示包围框: bool,
    /// 是否显示碰撞体轮廓。
    ///
    /// 与包围框分开：包围框回答"实体在哪"，碰撞轮廓回答"它挡住哪里"，
    /// 排错时经常只需要看其中一个。
    pub 显示碰撞: bool,
    /// 设计分辨率（来自项目设置）。
    ///
    /// # 它为什么属于相机
    ///
    /// 预览画布按**设计分辨率的比例**渲染（见 `editor_app::preview`），而叠加层
    /// （网格/包围框/操纵器）仍在整个面板上绘制。要让两者对齐，世界↔屏幕换算
    /// 必须知道"设计帧"有多大、以及它被 letterbox 到面板的哪个矩形里。
    /// 这个信息放在相机上，所有既有调用点（几十处）**一行不改**就自动正确。
    ///
    /// `None` 表示不启用设计帧（等价于旧行为：面板像素即世界像素）。
    pub 设计尺寸: Option<(f32, f32)>,
}

impl Default for 视口相机 {
    fn default() -> Self {
        Self {
            中心: (0.0, 0.0),
            // 默认缩放 = 1.0，即 **1 世界单位 = 1 像素**，界面显示为 100%。
            //
            // # 为什么不是更大的值
            //
            // 这里原先取 48.0，含义是"1 世界单位 = 48 像素"。
            // 但 `默认精灵尺寸` 是 **64 世界单位**，于是一个默认大小的精灵
            // 在屏幕上是 64 × 48 = 3072 像素宽 —— 比视口本身宽三倍多。
            //
            // 实测中的表现是：打开一个正常场景，视口被某个精灵的纯色铺满，
            // 看起来就像"渲染坏了"。这正是当时被报上来的现象。
            //
            // 取 1.0 之后，约 900 像素宽的视口能看到约 900 个世界单位，
            // 一个 64 单位的精灵占 64 像素 —— 大小正常，一眼能看清场景全貌。
            //
            // 顺带让"100%"有了直观含义（与图像软件的 100% 一致）：
            // 1 世界单位正好对应 1 个物理像素。
            缩放: 1.0,
            显示网格: true,
            网格间距: 1.0,
            显示坐标轴: true,
            显示包围框: true,
            // 默认关闭：碰撞轮廓是排错用的，常态显示会让画面变吵。
            显示碰撞: false,
            设计尺寸: None,
        }
    }
}

impl 视口相机 {
    /// 缩放下限：每个世界单位最少对应多少像素。
    ///
    /// # 为什么这个下限定得这么小
    ///
    /// 它必须小到"适应窗口"能真正装下一个大场景。
    /// 在 800 像素宽的视口里，下限 `z` 意味着最多能看到 `800 / z`
    /// 个世界单位：
    ///
    /// | 下限 | 800px 视口可见世界宽度 |
    /// | --- | --- |
    /// | 4.0（原先的值） | 200 单位 |
    /// | 0.05（当前值） | 16000 单位 |
    ///
    /// 原先取 4.0 时，只要场景跨度超过 200 世界单位，
    /// 「适应窗口」就会被夹在 4.0 而**装不下整个场景** ——
    /// 用户按了按钮却发现远处的对象仍在屏幕外，而且再怎么缩也缩不动。
    /// 这是实测中由 `适应包围盒后对象可见` 这条测试抓出来的真实缺陷。
    ///
    /// 网格绘制在很小的缩放下不会失控：网格间距会自适应放大，
    /// 并且有最大线数上限兜底。
    pub const 最小缩放: f32 = 0.05;
    /// 缩放上限：每个世界单位最多对应多少像素（用于精细对齐）。
    pub const 最大缩放: f32 = 800.0;

    /// 画布（设计帧）的像素尺寸；未设置设计分辨率时就是面板尺寸。
    ///
    /// 世界坐标先映射到这个"画布空间"，再整体等比缩放并居中到面板里。
    pub fn 画布尺寸(&self, 视口尺寸: egui::Vec2) -> egui::Vec2 {
        match self.设计尺寸 {
            Some((宽, 高)) if 宽 > 0.0 && 高 > 0.0 => egui::vec2(宽, 高),
            _ => 视口尺寸,
        }
    }

    /// 画布到面板的等比缩放与留边。
    pub fn 画布适配(&self, 视口尺寸: egui::Vec2) -> editor_core::ui_layout::适配缩放 {
        let 画布 = self.画布尺寸(视口尺寸);
        editor_core::ui_layout::适配缩放(画布.x, 画布.y, 视口尺寸.x, 视口尺寸.y)
    }

    /// 画布在面板里占据的矩形（letterbox 后的**可见画面**区域）。
    ///
    /// 预览纹理必须画在这个矩形里，叠加层则由 [`视口相机::世界转屏幕`] 映射到
    /// 同一个矩形 —— 两者共用这一份几何，不会出现"纹理与叠加层错位"。
    pub fn 显示矩形(&self, 视口尺寸: egui::Vec2) -> egui::Rect {
        let 画布 = self.画布尺寸(视口尺寸);
        let 适配 = self.画布适配(视口尺寸);
        egui::Rect::from_min_size(
            egui::pos2(适配.偏移x, 适配.偏移y),
            egui::vec2(画布.x * 适配.缩放, 画布.y * 适配.缩放),
        )
    }

    /// 世界坐标 → 视口局部坐标（相对视口矩形左上角，y 轴向下）。
    ///
    /// 先按"画布空间"线性映射（世界 y 向上、屏幕 y 向下，因此取反），
    /// 再等比缩放并加 letterbox 偏移。设计帧未启用时 `适配` 是恒等变换，
    /// 行为与旧实现完全一致。
    pub fn 世界转屏幕(&self, 世界: (f32, f32), 视口尺寸: egui::Vec2) -> egui::Vec2 {
        let 画布 = self.画布尺寸(视口尺寸);
        let 适配 = self.画布适配(视口尺寸);
        egui::vec2(
            适配.偏移x + (画布.x * 0.5 + (世界.0 - self.中心.0) * self.缩放) * 适配.缩放,
            适配.偏移y + (画布.y * 0.5 - (世界.1 - self.中心.1) * self.缩放) * 适配.缩放,
        )
    }

    /// 视口局部坐标 → 世界坐标（[`视口相机::世界转屏幕`] 的逆）。
    pub fn 屏幕转世界(&self, 屏幕: egui::Vec2, 视口尺寸: egui::Vec2) -> (f32, f32) {
        let 画布 = self.画布尺寸(视口尺寸);
        let 适配 = self.画布适配(视口尺寸);
        // 适配缩放恒为正（见 `适配缩放` 的保证），这里再兜一层防止除零。
        let 缩放 = if 适配.缩放 > 0.0 {
            适配.缩放
        } else {
            1.0
        };
        let 局部 = egui::vec2((屏幕.x - 适配.偏移x) / 缩放, (屏幕.y - 适配.偏移y) / 缩放);
        (
            self.中心.0 + (局部.x - 画布.x * 0.5) / self.缩放,
            self.中心.1 - (局部.y - 画布.y * 0.5) / self.缩放,
        )
    }

    /// 按屏幕位移平移视图。
    pub fn 平移(&mut self, 屏幕位移: egui::Vec2) {
        self.中心.0 -= 屏幕位移.x / self.缩放;
        self.中心.1 += 屏幕位移.y / self.缩放;
    }

    /// 以某个屏幕位置为锚点缩放，保证锚点下的世界坐标不动。
    ///
    /// 不这样做的话，滚轮缩放会以视口中心为锚点，用户想放大看角落里的
    /// 对象时会发现对象跑出屏幕，需要反复平移，非常难用。
    pub fn 以锚点缩放(
        &mut self, 缩放系数: f32, 锚点屏幕: egui::Vec2, 视口尺寸: egui::Vec2
    ) {
        let 锚点世界 = self.屏幕转世界(锚点屏幕, 视口尺寸);
        self.缩放 = (self.缩放 * 缩放系数).clamp(Self::最小缩放, Self::最大缩放);
        // 锚点必须先换算回画布空间：面板上有 letterbox 留边，
        // 直接用面板坐标会算偏（留边越大偏得越多）。
        let 画布 = self.画布尺寸(视口尺寸);
        let 适配 = self.画布适配(视口尺寸);
        let 缩放 = if 适配.缩放 > 0.0 {
            适配.缩放
        } else {
            1.0
        };
        let 局部 = egui::vec2(
            (锚点屏幕.x - 适配.偏移x) / 缩放,
            (锚点屏幕.y - 适配.偏移y) / 缩放,
        );
        self.中心.0 = 锚点世界.0 - (局部.x - 画布.x * 0.5) / self.缩放;
        self.中心.1 = 锚点世界.1 + (局部.y - 画布.y * 0.5) / self.缩放;
    }

    /// 适应到给定的世界包围盒。
    pub fn 适应包围盒(
        &mut self, 最小: (f32, f32), 最大: (f32, f32), 视口尺寸: egui::Vec2
    ) {
        let 宽 = (最大.0 - 最小.0).abs().max(0.001);
        let 高 = (最大.1 - 最小.1).abs().max(0.001);
        self.中心 = ((最小.0 + 最大.0) * 0.5, (最小.1 + 最大.1) * 0.5);
        // 按**画布**尺寸拟合：可见世界矩形由画布尺寸决定，用面板尺寸算会让
        // 场景在 letterbox 之后仍然出界。
        let 画布 = self.画布尺寸(视口尺寸);
        let 缩放_x = (画布.x * 0.85) / 宽;
        let 缩放_y = (画布.y * 0.85) / 高;
        self.缩放 = 缩放_x.min(缩放_y).clamp(Self::最小缩放, Self::最大缩放);
    }

    /// 当前可见的世界矩形 `(最小, 最大)`。
    ///
    /// # 这是坐标映射的**唯一真源**
    ///
    /// 视口有两套绘制者：
    ///
    /// 1. **Bevy 预览相机**把场景实体渲染到纹理；
    /// 2. **egui 叠加层**在同一块区域上画网格、坐标轴、选中框。
    ///
    /// 两者只要有一处算错，用户就会看到"选中框和精灵错位"。
    /// 消除这个风险的办法不是"两边都小心地写对"，而是让它们
    /// **从同一个矩形推导**：
    ///
    /// * egui 侧用 [`视口相机::世界转屏幕`]，它就是把这个矩形线性映射到
    ///   `(0,0)..(视口尺寸)`；
    /// * Bevy 侧把这个矩形的宽高直接设成正交投影的
    ///   `ScalingMode::Fixed { width, height }`，把矩形中心设成相机位置。
    ///
    /// 于是"纹理里的像素"与"egui 画在纹理上的像素"按构造对齐，
    /// 不依赖两边各自算对。测试 `可见世界矩形与屏幕映射自洽`
    /// 把这个性质固定下来。
    pub fn 可见世界矩形(&self, 视口尺寸: egui::Vec2) -> ((f32, f32), (f32, f32)) {
        // 可见范围由**画布**（设计帧）决定，而不是面板像素。
        // 这与预览相机的正交投影 `ScalingMode::Fixed { width, height }` 一致。
        let 画布 = self.画布尺寸(视口尺寸);
        let 半宽 = 画布.x * 0.5 / self.缩放;
        let 半高 = 画布.y * 0.5 / self.缩放;
        (
            (self.中心.0 - 半宽, self.中心.1 - 半高),
            (self.中心.0 + 半宽, self.中心.1 + 半高),
        )
    }
}

/// 三维轨道相机。
///
/// # 为什么自己做投影而不是读 Bevy 相机
///
/// 视口叠加层（网格、坐标轴、选中框）由 egui 绘制，渲染由 Bevy 相机完成。
/// 两者必须**按构造**对齐（与 2D 视口同一条原则）。如果叠加层去反查
/// Bevy 相机的矩阵，就需要跨层传矩阵，且一旦渲染延迟一帧就会错位。
///
/// 因此这里用同一组参数（目标/距离/偏航/俯仰/视场角）同时驱动：
/// Bevy 的透视相机位置与朝向、egui 的投影。数学是标准透视投影，
/// 有测试守着"中心点总在视口中心""相机背后的点被剔除"。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 三维相机 {
    /// 轨道中心（世界坐标）。
    pub 目标: (f32, f32, f32),
    /// 相机到目标的距离。
    pub 距离: f32,
    /// 水平角（弧度）。
    pub 偏航: f32,
    /// 俯仰角（弧度），被夹在 ±±80° 内避免万向节翻转。
    pub 俯仰: f32,
    /// 垂直视场角（弧度）。
    pub 视场角: f32,
}

impl Default for 三维相机 {
    fn default() -> Self {
        Self {
            目标: (0.0, 0.0, 0.0),
            距离: 12.0,
            偏航: std::f32::consts::FRAC_PI_4,
            俯仰: 0.5,
            视场角: 45f32.to_radians(),
        }
    }
}

impl 三维相机 {
    /// 距离下限。
    pub const 最小距离: f32 = 0.5;
    /// 距离上限。
    pub const 最大距离: f32 = 500.0;
    /// 俯仰绝对值上限（约 80°）。
    pub const 最大俯仰: f32 = 1.396;

    /// 相机在世界里的位置。
    pub fn 位置(&self) -> (f32, f32, f32) {
        let (仰角余弦, 仰角正弦) = (self.俯仰.cos(), self.俯仰.sin());
        (
            self.目标.0 + self.距离 * 仰角余弦 * self.偏航.sin(),
            self.目标.1 + self.距离 * 仰角正弦,
            self.目标.2 + self.距离 * 仰角余弦 * self.偏航.cos(),
        )
    }

    /// 重置到默认视角。
    pub fn 重置(&mut self) {
        *self = Self::default();
    }

    /// 轨道旋转（像素位移 → 角度）。
    pub fn 旋转(&mut self, 位移: egui::Vec2) {
        self.偏航 -= 位移.x * 0.01;
        self.俯仰 = (self.俯仰 + 位移.y * 0.01).clamp(-Self::最大俯仰, Self::最大俯仰);
    }

    /// 缩放（滚轮）。
    pub fn 缩放(&mut self, 系数: f32) {
        self.距离 = (self.距离 * 系数).clamp(Self::最小距离, Self::最大距离);
    }

    /// 平移（沿相机的右方向与世界上方向近似）。
    pub fn 平移(&mut self, 位移: egui::Vec2) {
        let 比例 = self.距离 * 0.002;
        let (右, 前) = (self.偏航.cos(), self.偏航.sin());
        self.目标.0 += (-位移.x * 右) * 比例;
        self.目标.2 += (位移.x * 前) * 比例;
        self.目标.1 += 位移.y * 比例;
    }

    /// 世界点 → 视口局部像素坐标（左上角原点）。
    ///
    /// 返回 `None` 表示点在相机背后或在视锥之外（调用方应剔除）。
    pub fn 投影(&self, 世界: (f32, f32, f32), 视口尺寸: egui::Vec2) -> Option<egui::Vec2> {
        let 相机 = self.位置();
        // 视线方向 = 目标 - 相机
        let 视 = (
            self.目标.0 - 相机.0,
            self.目标.1 - 相机.1,
            self.目标.2 - 相机.2,
        );
        let 视长 = (视.0 * 视.0 + 视.1 * 视.1 + 视.2 * 视.2).sqrt();
        if 视长 < 1e-5 {
            return None;
        }
        let 前 = (视.0 / 视长, 视.1 / 视长, 视.2 / 视长);
        // 右 = 前 × 世界上方 = (-fz, 0, fx)。
        //
        // 曾写成 (fz, 0, -fx)：整块 egui 叠加层会左右镜像，
        // 由它叉乘出的「上」也反号，于是网格与坐标轴上下也反 ——
        // 而 Bevy 渲染的实体是正的，两者对不上、拾取也落到镜像位置。
        // 这是本轮 3D 方向异常的根因，修复有 GUI 截图对照。
        let 右 = (-前.2, 0.0, 前.0);
        let 右长 = (右.0 * 右.0 + 右.2 * 右.2).sqrt();
        if 右长 < 1e-5 {
            return None;
        }
        let 右 = (右.0 / 右长, 0.0, 右.2 / 右长);
        // 上 = 右 × 前
        let 上 = (
            右.1 * 前.2 - 右.2 * 前.1,
            右.2 * 前.0 - 右.0 * 前.2,
            右.0 * 前.1 - 右.1 * 前.0,
        );

        let 相对 = (世界.0 - 相机.0, 世界.1 - 相机.1, 世界.2 - 相机.2);
        let 深度 = 相对.0 * 前.0 + 相对.1 * 前.1 + 相对.2 * 前.2;
        if 深度 <= 0.01 {
            return None;
        }
        let 横向 = 相对.0 * 右.0 + 相对.2 * 右.2;
        let 纵向 = 相对.0 * 上.0 + 相对.1 * 上.1 + 相对.2 * 上.2;
        let 焦距 = (视口尺寸.y * 0.5) / (self.视场角 * 0.5).tan();
        Some(egui::vec2(
            视口尺寸.x * 0.5 + 横向 / 深度 * 焦距,
            视口尺寸.y * 0.5 - 纵向 / 深度 * 焦距,
        ))
    }

    /// 屏幕像素坐标 → 世界射线（用于拾取）。返回 `(起点, 方向)`。
    pub fn 屏幕射线(
        &self,
        屏幕: egui::Vec2,
        视口尺寸: egui::Vec2,
    ) -> ((f32, f32, f32), (f32, f32, f32)) {
        let 相机 = self.位置();
        let 视 = (
            self.目标.0 - 相机.0,
            self.目标.1 - 相机.1,
            self.目标.2 - 相机.2,
        );
        let 视长 = (视.0 * 视.0 + 视.1 * 视.1 + 视.2 * 视.2).sqrt();
        let 前 = (视.0 / 视长, 视.1 / 视长, 视.2 / 视长);
        // 右 = 前 × 世界上方 = (-fz, 0, fx)。
        //
        // 曾写成 (fz, 0, -fx)：整块 egui 叠加层会左右镜像，
        // 由它叉乘出的「上」也反号，于是网格与坐标轴上下也反 ——
        // 而 Bevy 渲染的实体是正的，两者对不上、拾取也落到镜像位置。
        // 这是本轮 3D 方向异常的根因，修复有 GUI 截图对照。
        let 右 = (-前.2, 0.0, 前.0);
        let 右长 = (右.0 * 右.0 + 右.2 * 右.2).sqrt();
        let 右 = (右.0 / 右长, 0.0, 右.2 / 右长);
        let 上 = (
            右.1 * 前.2 - 右.2 * 前.1,
            右.2 * 前.0 - 右.0 * 前.2,
            右.0 * 前.1 - 右.1 * 前.0,
        );
        let 焦距 = (视口尺寸.y * 0.5) / (self.视场角 * 0.5).tan();
        let 横向 = (屏幕.x - 视口尺寸.x * 0.5) / 焦距;
        let 纵向 = -(屏幕.y - 视口尺寸.y * 0.5) / 焦距;
        let 方向 = (
            前.0 + 右.0 * 横向 + 上.0 * 纵向,
            前.1 + 右.1 * 横向 + 上.1 * 纵向,
            前.2 + 右.2 * 横向 + 上.2 * 纵向,
        );
        let 长 = (方向.0 * 方向.0 + 方向.1 * 方向.1 + 方向.2 * 方向.2).sqrt();
        (相机, (方向.0 / 长, 方向.1 / 长, 方向.2 / 长))
    }
}

