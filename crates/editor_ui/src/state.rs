/// 界面绘制期间累积的动作队列。
#[derive(Debug, Default)]
pub struct 动作队列 {
    动作: Vec<UiAction>,
}

impl 动作队列 {
    /// 新建空队列。
    pub fn 新建() -> Self {
        Self::default()
    }

    /// 推入一个动作。
    pub fn 推(&mut self, 动作: UiAction) {
        self.动作.push(动作);
    }

    /// 是否为空。
    pub fn 为空(&self) -> bool {
        self.动作.is_empty()
    }

    /// 数量。
    pub fn 数量(&self) -> usize {
        self.动作.len()
    }

    /// 取出全部动作并清空队列。
    pub fn 取出(&mut self) -> Vec<UiAction> {
        std::mem::take(&mut self.动作)
    }

    /// 只读查看（供测试断言与调试）。
    pub fn 列表(&self) -> &[UiAction] {
        &self.动作
    }
}

