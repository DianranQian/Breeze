/// 变换数据与视口框的便捷转换（供测试）。
pub fn 由变换构造框(
    标识: 实体标识, 变换: 变换数据, 半尺寸: (f32, f32)
) -> 视口实体框 {
    视口实体框 {
        标识,
        半宽: 半尺寸.0 * 变换.缩放.0.abs(),
        半高: 半尺寸.1 * 变换.缩放.1.abs(),
        中心: (变换.平移.0, 变换.平移.1),
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use std::collections::BTreeMap;

    fn 造带精灵的场景() -> (场景文档, 实体标识, 实体标识) {
        let mut 文档 = 场景文档::新建("视口测试");
        let 甲 = 文档.生成实体("甲", None);
        let 乙 = 文档.生成实体("乙", None);

        // 甲是 64x64 的精灵，放在原点
        let mut 属性 = BTreeMap::new();
        属性.insert(
            "自定义尺寸".to_string(),
            scene_doc::property::属性值::二维(64.0, 64.0),
        );
        属性.insert(
            "颜色".to_string(),
            scene_doc::property::属性值::颜色(scene_doc::property::颜色值::白()),
        );
        if let Some(实体) = 文档.取可变(甲) {
            实体.加组件(scene_doc::document::组件数据::新建("Sprite", 属性));
        }

        // 乙是普通节点，放在 (200, 0)
        if let Some(实体) = 文档.取可变(乙) {
            实体.变换 = Some(变换数据 {
                平移: (200.0, 0.0, 0.0),
                ..变换数据::单位()
            });
        }

        (文档, 甲, 乙)
    }

    #[test]
    fn 命中测试选中覆盖点位的实体() {
        let (文档, 甲, 乙) = 造带精灵的场景();
        assert_eq!(命中测试(&文档, (0.0, 0.0)), Some(甲), "原点应命中甲");
        assert_eq!(命中测试(&文档, (200.0, 0.0)), Some(乙), "(200,0) 应命中乙");
        assert_eq!(
            命中测试(&文档, (1000.0, 1000.0)),
            None,
            "空白处不应命中任何实体"
        );
    }

    #[test]
    fn 命中测试会跳过锁定与隐藏的实体() {
        let (mut 文档, 甲, _) = 造带精灵的场景();

        if let Some(实体) = 文档.取可变(甲) {
            实体.编辑器锁定 = true;
        }
        assert_eq!(命中测试(&文档, (0.0, 0.0)), None, "锁定实体不应被命中");

        if let Some(实体) = 文档.取可变(甲) {
            实体.编辑器锁定 = false;
            实体.编辑器隐藏 = true;
        }
        assert_eq!(命中测试(&文档, (0.0, 0.0)), None, "隐藏实体不应被命中");
    }

    #[test]
    fn 精灵尺寸取自自定义尺寸属性() {
        let (文档, 甲, _) = 造带精灵的场景();
        let 框 = 计算实体框(&文档, 甲).unwrap();
        assert_eq!((框.半宽, 框.半高), (32.0, 32.0), "64x64 的半尺寸应是 32");
    }

    #[test]
    fn 缩放会影响实体框大小() {
        let (mut 文档, 甲, _) = 造带精灵的场景();
        if let Some(实体) = 文档.取可变(甲) {
            实体.变换 = Some(变换数据 {
                平移: (0.0, 0.0, 0.0),
                旋转: (0.0, 0.0, 0.0, 1.0),
                缩放: (2.0, 3.0, 1.0),
            });
        }
        let 框 = 计算实体框(&文档, 甲).unwrap();
        assert_eq!((框.半宽, 框.半高), (64.0, 96.0));
    }

    #[test]
    fn 负缩放按绝对值处理() {
        // 负缩放是合法的（镜像翻转），包围框不应变成负数。
        let (mut 文档, 甲, _) = 造带精灵的场景();
        if let Some(实体) = 文档.取可变(甲) {
            实体.变换 = Some(变换数据 {
                平移: (0.0, 0.0, 0.0),
                旋转: (0.0, 0.0, 0.0, 1.0),
                缩放: (-2.0, -2.0, 1.0),
            });
        }
        let 框 = 计算实体框(&文档, 甲).unwrap();
        assert!(框.半宽 > 0.0 && 框.半高 > 0.0);
    }

    #[test]
    fn 无变换的实体不出现在视口里() {
        let mut 文档 = 场景文档::新建("无变换");
        let 标识 = 文档.生成实体("纯逻辑节点", None);
        if let Some(实体) = 文档.取可变(标识) {
            实体.变换 = None;
        }
        assert!(计算实体框(&文档, 标识).is_none());
        assert!(收集可见框(&文档).is_empty(), "没有变换的实体不应有视口框");
    }

    #[test]
    fn 隐藏实体不出现在可见框里() {
        let (mut 文档, 甲, _) = 造带精灵的场景();
        assert_eq!(收集可见框(&文档).len(), 2);
        if let Some(实体) = 文档.取可变(甲) {
            实体.编辑器隐藏 = true;
        }
        assert_eq!(收集可见框(&文档).len(), 1);
    }

    #[test]
    fn 世界包围盒覆盖所有可见实体() {
        let (文档, _, _) = 造带精灵的场景();
        let (最小, 最大) = 世界包围盒(&文档).unwrap();
        // 甲在原点、半径 32；乙在 (200,0)、半径 8
        assert!(
            (最小.0 - (-32.0)).abs() < 1e-4,
            "最小 x 应为 -32，实际 {}",
            最小.0
        );
        assert!(
            (最大.0 - 208.0).abs() < 1e-4,
            "最大 x 应为 208，实际 {}",
            最大.0
        );
    }

    #[test]
    fn 空场景没有世界包围盒() {
        let 文档 = 场景文档::新建("空");
        assert!(世界包围盒(&文档).is_none());
    }

    #[test]
    fn 框的包含判定() {
        let 框 = 视口实体框 {
            标识: 实体标识::新建(),
            半宽: 10.0,
            半高: 5.0,
            中心: (100.0, 50.0),
        };
        assert!(框.包含((100.0, 50.0)), "中心应被包含");
        assert!(框.包含((110.0, 55.0)), "边界应被包含");
        assert!(!框.包含((110.1, 50.0)), "右外侧不应被包含");
        assert!(!框.包含((100.0, 44.9)), "下外侧不应被包含");
    }
}
