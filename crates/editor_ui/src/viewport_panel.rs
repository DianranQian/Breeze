//! 2D 视口面板。
//!
//! # 本期视口的实现边界（必须说清楚）
//!
//! 视口内容由 egui 直接绘制，渲染的是**编辑器对场景的表示**：
//! 网格、坐标轴、实体包围框、选中高亮、变换控件。它不是把游戏画面
//! 渲染到纹理再贴上来。
//!
//! 这样做的理由与代价：
//!
//! * **好处**：编辑器不依赖游戏相机与渲染管线就能工作，场景数据的
//!   每一个改动都能立刻、确定地看到效果，也不存在"编辑器和游戏
//!   抢同一台相机"的问题。这一期的目标是**编辑闭环可验证**。
//! * **代价**：看不到材质的真实外观、看不到光照与动画。
//! * **演进路线**：`editor_app` 里预留了 `视口渲染目标`，
//!   后续把游戏场景渲染到 `Image` 纹理并作为视口底板贴上来，
//!   编辑叠加层（网格/包围框/Gizmo）继续由本模块绘制。
//!   这条路线不需要改本模块的交互逻辑。
//!
//! 详细评估记录在 `功能路线图.md` 与 `工作日志.md` 中。

use editor_core::state::编辑器状态;
use egui::{Painter, Pos2, Rect, RichText, Sense, Stroke, Ui};
use scene_doc::document::{变换数据, 场景文档, 实体标识};

use crate::state::{UiAction, 绘制上下文, 视口拖拽, 选择意图};

/// 一个实体在视口里的屏幕矩形。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 视口实体框 {
    /// 实体标识。
    pub 标识: 实体标识,
    /// 世界坐标下的半宽。
    pub 半宽: f32,
    /// 世界坐标下的半高。
    pub 半高: f32,
    /// 世界坐标下的中心。
    pub 中心: (f32, f32),
}

impl 视口实体框 {
    /// 世界包围盒。
    pub fn 世界包围盒(&self) -> ((f32, f32), (f32, f32)) {
        (
            (self.中心.0 - self.半宽, self.中心.1 - self.半高),
            (self.中心.0 + self.半宽, self.中心.1 + self.半高),
        )
    }

    /// 是否包含一个世界坐标点。
    pub fn 包含(&self, 点: (f32, f32)) -> bool {
        (点.0 - self.中心.0).abs() <= self.半宽 && (点.1 - self.中心.1).abs() <= self.半高
    }
}

/// 一个实体的默认视觉尺寸（世界单位），当它没有声明尺寸时使用。
///
/// 用"组件是否存在"来推断尺寸，而不是硬编码"所有实体都是 64x64"：
/// 这样带 `Sprite` 的实体看起来像精灵，不带的大多只是逻辑节点，
/// 用一个小方块表示更容易分辨。
const 默认精灵半尺寸: f32 = 32.0;
const 默认节点半尺寸: f32 = 8.0;

/// 计算一个实体在视口里的框。
///
/// 尺寸的优先级：
/// 1. `Sprite` 组件里用户可编辑的 `custom_size`（若设置了）；
/// 2. 有 `Sprite` 组件 → 默认 64×64；
/// 3. 其余 → 8×8 的小节点框。
///
/// 没有直接从 Bevy 的 `Sprite` 类型读，是因为组件在文档里是弱类型的；
/// 这也意味着"视口显示尺寸"与"运行时真实尺寸"在用户没设置
/// `custom_size` 时可能不一致 —— 这一点在路线图里记为已知限制。
pub fn 计算实体框(文档: &场景文档, 标识: 实体标识) -> Option<视口实体框> {
    let 实体 = 文档.取(标识)?;
    let 变换 = 实体.变换?;

    let 半尺寸 = 实体
        .取组件("Sprite")
        .and_then(|组件| 组件.属性.get("自定义尺寸"))
        .and_then(属性取二维)
        .map(|(宽, 高)| (宽.abs() * 0.5, 高.abs() * 0.5))
        .unwrap_or_else(|| {
            if 实体.有组件("Sprite") {
                (默认精灵半尺寸, 默认精灵半尺寸)
            } else {
                (默认节点半尺寸, 默认节点半尺寸)
            }
        });

    Some(视口实体框 {
        标识,
        半宽: 半尺寸.0 * 变换.缩放.0.abs(),
        半高: 半尺寸.1 * 变换.缩放.1.abs(),
        中心: (变换.平移.0, 变换.平移.1),
    })
}

/// 从属性值里取二维尺寸。
fn 属性取二维(值: &scene_doc::property::属性值) -> Option<(f32, f32)> {
    use scene_doc::property::属性值;
    match 值 {
        属性值::二维(x, y) => Some((*x, *y)),
        属性值::三维(x, y, _) => Some((*x, *y)),
        _ => None,
    }
}

/// 命中测试：返回世界坐标点下最靠上的实体。
///
/// "最靠上"按视口绘制顺序**倒序**查找，也就是后画的（在场景树里靠后的）
/// 优先命中，与用户在画面上的直觉一致。
pub fn 命中测试(文档: &场景文档, 世界点: (f32, f32)) -> Option<实体标识> {
    let 顺序 = 文档.深度优先遍历();
    for (标识, _) in 顺序.iter().rev() {
        let Some(实体) = 文档.取(*标识) else {
            continue;
        };
        if 实体.编辑器锁定 || 实体.编辑器隐藏 {
            continue;
        }
        if let Some(框) = 计算实体框(文档, *标识)
            && 框.包含(世界点)
        {
            return Some(*标识);
        }
    }
    None
}

/// 收集所有可见实体的视口框。
pub fn 收集可见框(文档: &场景文档) -> Vec<视口实体框> {
    文档
        .深度优先遍历()
        .into_iter()
        .filter_map(|(标识, _)| {
            let 实体 = 文档.取(标识)?;
            if 实体.编辑器隐藏 {
                return None;
            }
            计算实体框(文档, 标识)
        })
        .collect()
}

/// 文档中所有实体框的合并包围盒。空场景返回 `None`。
pub fn 世界包围盒(文档: &场景文档) -> Option<((f32, f32), (f32, f32))> {
    let 所有框 = 收集可见框(文档);
    if 所有框.is_empty() {
        return None;
    }
    let mut 最小 = (f32::INFINITY, f32::INFINITY);
    let mut 最大 = (f32::NEG_INFINITY, f32::NEG_INFINITY);
    for 框 in &所有框 {
        let (框最小, 框最大) = 框.世界包围盒();
        最小.0 = 最小.0.min(框最小.0);
        最小.1 = 最小.1.min(框最小.1);
        最大.0 = 最大.0.max(框最大.0);
        最大.1 = 最大.1.max(框最大.1);
    }
    if !最小.0.is_finite() || !最大.0.is_finite() {
        return None;
    }
    Some((最小, 最大))
}

/// 绘制视口内容。所有几何绘制都相对 `内容矩形`（视口面板内实际可画区域）。
pub fn 绘制内容(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>, 内容矩形: Rect) {
    // 三维模式：渲染由 Bevy 的 Camera3d 完成，叠加层由 `viewport3d` 绘制。
    // 两条路径共用同一个相机参数，因此网格与实体的位置按构造一致。
    if crate::viewport3d::活动(上下文) {
        上下文.界面.视口尺寸 = 内容矩形.size();
        crate::viewport3d::绘制(ui, 上下文, 内容矩形);
        return;
    }
    let 尺寸 = 内容矩形.size();
    上下文.界面.视口尺寸 = 尺寸;

    // 一次性视口命令（模式工具栏的"适应窗口 / 重置视图 / 聚焦选中"）。
    //
    // 2D 面板以前没有消费这个命令，导致 2D 模式工具栏的"适应窗口"按钮
    // 点了没反应 —— 只有视口底部状态栏里的同名按钮有效。现在两条入口
    // 走同一条路径，3D 面板也继续用自己的消费点。
    let 命令 = 上下文.界面.视口命令.取出();
    if 命令.适应窗口 {
        适应场景(上下文, 尺寸);
    }
    if 命令.重置视图 {
        上下文.界面.相机 = crate::state::视口相机::default();
    }
    if 命令.聚焦选中 {
        聚焦选中(上下文, 尺寸);
    }

    let 文档 = &上下文.编辑器.会话.文档;

    // 把"视口局部坐标"换算成屏幕坐标的辅助闭包。
    let 到屏幕 = |局部: egui::Vec2| -> Pos2 {
        Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y)
    };

    // ---------- 1. 输入处理 ----------
    let 响应 = ui.allocate_rect(内容矩形, Sense::click_and_drag());
    let 指针 = ui.input(|输入| 输入.pointer.clone());
    let 修饰 = ui.input(|输入| 输入.modifiers);
    // 空格不是 Modifiers 的字段，它是一个按键，因此单独查询按键状态。
    let 空格按下 = ui.input(|输入| 输入.key_down(egui::Key::Space));
    // egui 0.36 用 `smooth_scroll_delta`（已按滚动平滑处理）。
    let 滚轮 = ui.input(|输入| 输入.smooth_scroll_delta.y);

    let 局部指针 = 指针
        .hover_pos()
        .map(|位置| egui::vec2(位置.x - 内容矩形.min.x, 位置.y - 内容矩形.min.y));

    // 滚轮缩放（以指针为锚点）
    if 响应.hovered()
        && 滚轮.abs() > 0.0
        && let Some(锚点) = 局部指针
    {
        let 系数 = (滚轮 * 0.0015).exp();
        上下文.界面.相机.以锚点缩放(系数, 锚点, 尺寸);
    }

    // ---------- 1.5 变换操纵器（2D） ----------
    //
    // 操纵器必须**先于**选择与框选处理：命中手柄时按下鼠标要做的是"变换"，
    // 不是"重新选择实体"、也不是"Dock 拖动"。
    //
    // 生命周期（2D 与 3D 完全一致，只有几何求解不同）：
    //   悬停 → 按下并命中 → 建立会话 → 每帧预览 → 释放提交 / Escape 取消
    let 主键刚按下 = ui.input(|输入| 输入.pointer.button_pressed(egui::PointerButton::Primary));
    let 主键按下中 = ui.input(|输入| 输入.pointer.button_down(egui::PointerButton::Primary));
    let 取消键 = ui.input(|输入| 输入.key_pressed(egui::Key::Escape));

    let 操纵器 = 驱动操纵器(
        ui,
        上下文,
        内容矩形,
        尺寸,
        局部指针,
        主键刚按下,
        主键按下中,
        取消键,
        空格按下,
    );

    // 中键或空格拖动 = 平移视图
    if 上下文.界面.操纵器拖拽.is_none()
        && (响应.dragged_by(egui::PointerButton::Middle)
            || (响应.dragged_by(egui::PointerButton::Primary) && 空格按下))
    {
        let 增量 = ui.input(|输入| 输入.pointer.delta());
        上下文.界面.相机.平移(egui::vec2(增量.x, 增量.y));
        上下文.界面.拖拽 = 视口拖拽::平移;
    } else if 响应.drag_stopped() && 上下文.界面.操纵器拖拽.is_none() {
        上下文.界面.拖拽 = 视口拖拽::无;
    }

    // 左键按下：命中测试 → 选择 + 开始拖动
    //
    // `操纵器.占用了按下` 为真时整段跳过：否则"抓住 X 轴手柄"会顺带把
    // 手柄后面的实体重新选择一遍，多选会被打散成单选。
    let 主键按下 = 响应.drag_started_by(egui::PointerButton::Primary) && !空格按下;
    if 主键按下
        && !操纵器.占用了按下
        && 操纵器.悬停.is_none()
        && let Some(局部) = 局部指针
    {
        let 世界 = 上下文.界面.相机.屏幕转世界(局部, 尺寸);
        match 命中测试(文档, 世界) {
            Some(命中) => {
                let 已选中 = 上下文.编辑器.选择.包含(命中);
                if !已选中 {
                    let 意图 = if 修饰.command {
                        选择意图::切换(命中)
                    } else {
                        选择意图::单选(命中)
                    };
                    上下文.动作.推(UiAction::选择(意图));
                }
                上下文.动作.推(UiAction::开始拖动实体 {
                    实体: 命中,
                    追加选择: 修饰.shift,
                    按下世界: 世界,
                });
            }
            None => {
                // 点空白处：清空选择并开始框选
                if !修饰.command {
                    上下文.动作.推(UiAction::选择(选择意图::清空));
                }
                上下文.界面.拖拽 = 视口拖拽::框选 { 起点: 局部 };
            }
        }
    }

    // 拖动中
    if 响应.dragged_by(egui::PointerButton::Primary)
        && !空格按下
        && 上下文.界面.操纵器拖拽.is_none()
    {
        match 上下文.界面.拖拽.clone() {
            视口拖拽::移动实体 { 按下世界, .. } => {
                if let Some(局部) = 局部指针 {
                    let 世界 = 上下文.界面.相机.屏幕转世界(局部, 尺寸);
                    上下文.动作.推(UiAction::拖动实体到 {
                        世界偏移: (世界.0 - 按下世界.0, 世界.1 - 按下世界.1),
                    });
                }
            }
            视口拖拽::框选 { .. } | 视口拖拽::无 => {}
            视口拖拽::平移 => {}
        }
    }

    // 松手：结束拖动 / 完成框选
    if 响应.drag_stopped_by(egui::PointerButton::Primary) {
        if let 视口拖拽::框选 { 起点 } = 上下文.界面.拖拽.clone() {
            if let Some(终点) = 局部指针 {
                完成框选(上下文, 起点, 终点, 尺寸);
            }
        } else if matches!(上下文.界面.拖拽, 视口拖拽::移动实体 { .. }) {
            上下文.动作.推(UiAction::结束拖动);
        }
        上下文.界面.拖拽 = 视口拖拽::无;
    }

    // 点击（未拖动）时若命中了已选中实体，保持选择不变。
    // 这里不额外处理：上面的 drag_started 分支已经覆盖。

    // ---------- 2. 绘制 ----------
    //
    // 绘制顺序是这个视口的关键，三层由下到上：
    //
    //   ① 视口背景色
    //   ② 网格与坐标轴          ← 必须在游戏画面**下面**
    //   ③ Bevy 渲染纹理         ← 场景实体的真实渲染结果
    //   ④ 选中高亮、包围框、中心锚点
    //
    // ② 在 ③ 下面，靠的是 Bevy 预览相机把背景清成**透明**
    // （见 `editor_app::preview` 里的 `ClearColorConfig::Custom(Color::NONE)`）。
    // 这样网格透过来，而精灵是不透明的，视觉层次与真实游戏一致。
    //
    // 反过来说：如果预览相机清成不透明色，网格就只能画在精灵上面，
    // 看起来像"隔着纱窗看场景"，是明显错误的观感。
    let 画布 = ui.painter_at(内容矩形);
    画布.rect_filled(内容矩形, 0.0, 上下文.配色.视口背景);

    if 上下文.界面.相机.显示网格 {
        绘制网格(&画布, 内容矩形, &上下文.界面.相机, 上下文.配色);
    }
    if 上下文.界面.相机.显示坐标轴 {
        绘制坐标轴(&画布, 内容矩形, &上下文.界面.相机, 上下文.配色);
    }

    // ③ Bevy 渲染的纹理。按视口区域拉伸铺满 —— 因为预览相机的
    //    正交投影已经按同一个"可见世界矩形"设置过（见
    //    `视口相机::可见世界矩形`），所以拉伸到这里恰好是 1:1 对应，
    //    叠加层与渲染结果不会错位。
    绘制预览纹理(ui, 上下文, 内容矩形);

    let 选中列表 = 上下文.编辑器.选择.全部();
    let 主选中 = 上下文.编辑器.选择.主选中();

    let 所有框 = 收集可见框(文档);
    for 框 in &所有框 {
        let 屏幕中心 = 到屏幕(上下文.界面.相机.世界转屏幕(框.中心, 尺寸));
        let 屏幕半宽 = 框.半宽 * 上下文.界面.相机.缩放;
        let 屏幕半高 = 框.半高 * 上下文.界面.相机.缩放;
        let 矩形 = Rect::from_center_size(屏幕中心, egui::vec2(屏幕半宽 * 2.0, 屏幕半高 * 2.0));

        let 被选中 = 选中列表.contains(&框.标识);
        if 被选中 {
            画布.rect_filled(矩形, 1.0, 上下文.配色.选中填充(主选中 == Some(框.标识)));
        }
        if 上下文.界面.相机.显示包围框 || 被选中 {
            let 线色 = if 被选中 {
                上下文.配色.强调
            } else {
                上下文.配色.实体框
            };
            let 线宽 = if 被选中 { 2.0 } else { 1.0 };
            画布.rect_stroke(矩形, 1.0, Stroke::new(线宽, 线色), egui::StrokeKind::Inside);
        }
    }

    // 碰撞体轮廓：画在实体框之上、操纵器之下。
    //
    // 顺序有讲究：碰撞体可能比精灵大也可能小，压在实体框下面会被挡住；
    // 而操纵器必须始终能点，所以它必须在最上面。
    if 上下文.界面.相机.显示碰撞 {
        crate::collision_overlay::绘制碰撞轮廓(
            &画布,
            内容矩形.min,
            尺寸,
            &上下文.界面.相机,
            文档,
            主选中,
            &上下文.配色,
        );
    }
    // 选中标记：中心锚点 + 标识首段，便于在重叠对象中确认选的是谁。
    if let Some(标识) = 主选中
        && let Some(框) = 计算实体框(文档, 标识)
    {
        let 屏幕中心 = 到屏幕(上下文.界面.相机.世界转屏幕(框.中心, 尺寸));
        画布.circle_filled(屏幕中心, 3.0, 上下文.配色.强调);
    }

    // 变换操纵器画在实体与选中框**之上**：它是最需要被看清、被点中的东西。
    绘制操纵器(&画布, 上下文);

    // 框选矩形
    if let (视口拖拽::框选 { 起点 }, Some(终点)) = (&上下文.界面.拖拽, 局部指针)
    {
        let 矩形 = Rect::from_two_pos(到屏幕(*起点), 到屏幕(终点));
        画布.rect_filled(矩形, 0.0, 上下文.配色.强调淡);
        画布.rect_stroke(
            矩形,
            0.0,
            Stroke::new(1.0, 上下文.配色.强调),
            egui::StrokeKind::Inside,
        );
    }

    // ---------- 3. 键盘快捷键 ----------
    //
    // `取消键` 若已经被操纵器用来取消拖拽，就不能再顺手清空选择：
    // 用户按 Escape 的意图是"放弃这次变换"，不是"取消选中"。
    处理快捷键(ui, 上下文, 尺寸);

    // ---------- 4. 状态栏 ----------
    绘制状态栏(ui, 上下文, 内容矩形, &所有框);
}

/// 绘制 Bevy 预览渲染的纹理。
///
/// 预览尚未就绪时（例如启动首帧、或渲染后端尚未产出纹理）静默跳过：
/// 视口会退化成只有网格与包围框，用户仍能编辑，不会看到报错或黑块。
///
/// 这里刻意用一个"占位提示"而不是直接什么都不画 ——
/// 用户需要能分辨"场景是空的"与"预览没起来"，
/// 否则会把预览故障误当成场景里没有对象。
fn 绘制预览纹理(ui: &mut Ui, 上下文: &绘制上下文<'_>, 内容矩形: Rect) {
    let Some(结果) = 上下文.视口纹理 else {
        // 预览未就绪：在视口中央给一句说明。
        ui.painter_at(内容矩形).text(
            内容矩形.center(),
            egui::Align2::CENTER_CENTER,
            上下文.语言.取("preview_render_is_not_ready_yet"),
            egui::FontId::proportional(13.0),
            上下文.配色.次要文字,
        );
        return;
    };

    let 尺寸 = egui::vec2(结果.像素尺寸.0 as f32, 结果.像素尺寸.1 as f32);
    if 尺寸.x <= 0.0 || 尺寸.y <= 0.0 {
        return;
    }

    let 网格 = egui::load::SizedTexture::new(结果.纹理, 尺寸);
    // 用 `Image` 而不是 `painter.image`：前者会正确处理 UV 与染色，
    // 并且能与 egui 的布局/裁剪正确配合。
    egui::Image::new(网格)
        .fit_to_exact_size(内容矩形.size())
        .paint_at(ui, 内容矩形);
}

/// 绘制网格。
fn 绘制网格(
    画布: &Painter,
    内容矩形: Rect,
    相机: &crate::state::视口相机,
    配色: crate::theme::编辑器配色,
) {
    let 尺寸 = 内容矩形.size();

    // 网格间距随缩放自适应，避免缩小时画出成千上万条线。
    let mut 间距 = 相机.网格间距;
    while 间距 * 相机.缩放 < 12.0 {
        间距 *= 2.0;
    }
    // 间距过大时也没必要继续画
    if 间距 * 相机.缩放 > 400.0 {
        return;
    }

    let 左上世界 = 相机.屏幕转世界(egui::vec2(0.0, 0.0), 尺寸);
    let 右下世界 = 相机.屏幕转世界(egui::vec2(尺寸.x, 尺寸.y), 尺寸);

    let 起_x = (左上世界.0 / 间距).floor() as i32;
    let 止_x = (右下世界.0 / 间距).ceil() as i32;
    let 起_y = (右下世界.1 / 间距).floor() as i32;
    let 止_y = (左上世界.1 / 间距).ceil() as i32;

    // 安全上限：即使上面的自适应失效，也不允许画出爆炸数量的线。
    const 最大线数: i32 = 400;
    if (止_x - 起_x) > 最大线数 || (止_y - 起_y) > 最大线数 {
        return;
    }

    let 到屏幕 = |世界: (f32, f32)| -> Pos2 {
        let 局部 = 相机.世界转屏幕(世界, 尺寸);
        Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y)
    };

    for 序号 in 起_x..=止_x {
        let 世界_x = 序号 as f32 * 间距;
        let 颜色 = if 序号 % 10 == 0 {
            配色.网格主
        } else {
            配色.网格次
        };
        画布.line_segment(
            [到屏幕((世界_x, 左上世界.1)), 到屏幕((世界_x, 右下世界.1))],
            Stroke::new(1.0, 颜色),
        );
    }
    for 序号 in 起_y..=止_y {
        let 世界_y = 序号 as f32 * 间距;
        let 颜色 = if 序号 % 10 == 0 {
            配色.网格主
        } else {
            配色.网格次
        };
        画布.line_segment(
            [到屏幕((左上世界.0, 世界_y)), 到屏幕((右下世界.0, 世界_y))],
            Stroke::new(1.0, 颜色),
        );
    }
}

/// 绘制坐标轴。
fn 绘制坐标轴(
    画布: &Painter,
    内容矩形: Rect,
    相机: &crate::state::视口相机,
    配色: crate::theme::编辑器配色,
) {
    let 尺寸 = 内容矩形.size();
    let 到屏幕 = |世界: (f32, f32)| -> Pos2 {
        let 局部 = 相机.世界转屏幕(世界, 尺寸);
        Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y)
    };

    let 左上 = 相机.屏幕转世界(egui::vec2(0.0, 0.0), 尺寸);
    let 右下 = 相机.屏幕转世界(egui::vec2(尺寸.x, 尺寸.y), 尺寸);

    // Y 轴（世界 x = 0）
    if 左上.0 <= 0.0 && 右下.0 >= 0.0 {
        画布.line_segment(
            [到屏幕((0.0, 左上.1)), 到屏幕((0.0, 右下.1))],
            Stroke::new(1.5, 配色.轴_y),
        );
    }
    // X 轴（世界 y = 0）
    if 右下.1 <= 0.0 && 左上.1 >= 0.0 {
        画布.line_segment(
            [到屏幕((左上.0, 0.0)), 到屏幕((右下.0, 0.0))],
            Stroke::new(1.5, 配色.轴_x),
        );
    }
}

/// 完成框选：选中所有与矩形相交的实体。
fn 完成框选(
    上下文: &mut 绘制上下文<'_>, 起点: egui::Vec2, 终点: egui::Vec2, 尺寸: egui::Vec2
) {
    let 世界起 = 上下文.界面.相机.屏幕转世界(起点, 尺寸);
    let 世界止 = 上下文.界面.相机.屏幕转世界(终点, 尺寸);
    let 选择最小 = (世界起.0.min(世界止.0), 世界起.1.min(世界止.1));
    let 选择最大 = (世界起.0.max(世界止.0), 世界起.1.max(世界止.1));

    let 文档 = &上下文.编辑器.会话.文档;
    let mut 命中 = Vec::new();
    for 框 in 收集可见框(文档) {
        let (框最小, 框最大) = 框.世界包围盒();
        // 相交判定：完全在外面才排除。
        let 相交 = 框最大.0 >= 选择最小.0
            && 框最小.0 <= 选择最大.0
            && 框最大.1 >= 选择最小.1
            && 框最小.1 <= 选择最大.1;
        if 相交 {
            命中.push(框.标识);
        }
    }
    上下文.动作.推(UiAction::选择(选择意图::设为(命中)));
}

/// 把视口适应到整个场景。
fn 适应场景(上下文: &mut 绘制上下文<'_>, 尺寸: egui::Vec2) {
    if let Some((最小, 最大)) = 世界包围盒(&上下文.编辑器.会话.文档) {
        上下文.界面.相机.适应包围盒(最小, 最大, 尺寸);
    }
}

/// 聚焦到主选中实体；没有选中时退化为适应整个场景。
fn 聚焦选中(上下文: &mut 绘制上下文<'_>, 尺寸: egui::Vec2) {
    let Some(标识) = 上下文.主选中() else {
        适应场景(上下文, 尺寸);
        return;
    };
    let Some(框) = 计算实体框(&上下文.编辑器.会话.文档, 标识) else {
        适应场景(上下文, 尺寸);
        return;
    };
    // 留出边距，避免实体正好贴着视口边缘。
    let 半宽 = 框.半宽.max(0.5) * 1.6;
    let 半高 = 框.半高.max(0.5) * 1.6;
    上下文.界面.相机.适应包围盒(
        (框.中心.0 - 半宽, 框.中心.1 - 半高),
        (框.中心.0 + 半宽, 框.中心.1 + 半高),
        尺寸,
    );
}

/// 处理视口快捷键。
fn 处理快捷键(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>, 尺寸: egui::Vec2) {
    // 只在视口获得焦点、且没有文本输入框在编辑时响应，
    // 否则用户重命名实体时按 Delete 会连带删掉实体。
    if 上下文.界面.文本编辑.is_some() {
        return;
    }

    // 工具快捷键（Q/W/E/R）。它是"模式切换"，与下面的动作快捷键
    // （F/Delete/Escape）不是一类东西，因此单独先行处理。
    if crate::gizmo::处理工具快捷键(ui, 上下文) {
        return;
    }

    let (聚焦键, 删除键) = ui.input(|输入| {
        (
            输入.key_pressed(egui::Key::F),
            输入.key_pressed(egui::Key::Delete),
        )
    });

    if 聚焦键 {
        // F：聚焦到选中实体；没有选中则适应整个场景。
        聚焦选中(上下文, 尺寸);
    }

    if 删除键 {
        let 目标: Vec<实体标识> = 上下文.编辑器.选择.全部();
        for 标识 in 目标 {
            上下文.动作.推(UiAction::删除实体(标识));
        }
    }
}

/// 操纵器这一帧的结论（供调用方决定是否让出这次按下）。
struct 操纵器结论 {
    /// 当前悬停的部件（拖拽期间就是正在拖的那个）。
    悬停: Option<crate::gizmo::操纵器部件>,
    /// 这次按下是否已经被操纵器接管。
    占用了按下: bool,
    /// Escape 是否被用来取消了拖拽（此时调用方不应再清空选择）。
    取消了拖拽: bool,
}

/// 驱动 2D 操纵器：悬停 → 按下 → 拖拽（预览）→ 释放提交 / Escape 取消。
///
/// 生命周期与 3D 完全一致（见 [`crate::gizmo3d`] 的同名驱动），
/// 只有"怎么把指针换算成世界量"这一步不同 —— 这里用
/// [`视口相机::屏幕转世界`]，3D 那里用射线。
#[allow(clippy::too_many_arguments)]
fn 驱动操纵器(
    _ui: &mut Ui,
    上下文: &mut 绘制上下文<'_>,
    内容矩形: Rect,
    尺寸: egui::Vec2,
    局部指针: Option<egui::Vec2>,
    主键刚按下: bool,
    主键按下中: bool,
    取消键: bool,
    空格按下: bool,
) -> 操纵器结论 {
    use crate::gizmo::变换工具;
    use crate::gizmo2d;

    let 工具 = 上下文.界面.变换工具;
    let 相机 = 上下文.界面.相机;
    let mut 结论 = 操纵器结论 {
        悬停: None,
        占用了按下: false,
        取消了拖拽: false,
    };
    // 指针是否落在视口内容区里。
    //
    // # 为什么必须做这个裁剪
    //
    // 操纵器的命中测试是纯坐标计算，**不会**被 `painter_at` 的裁剪自动限制。
    // 不做这个检查时，落点在视口之外（例如压在检查器上）的操纵器依然可以
    // 被"命中"并开始拖拽 —— 实测就是：手柄在视口右侧外面，鼠标拖过去
    // 结果拖动的是检查器里的数值输入框，逐帧产生撤销记录。
    // 绘制被裁掉了、命中却还在，这是输入路由最容易出的错。
    let 指针在视口内 = 局部指针
        .map(|局部| 局部.x >= 0.0 && 局部.y >= 0.0 && 局部.x <= 尺寸.x && 局部.y <= 尺寸.y)
        .unwrap_or(false);

    // ---- 1. 先处理已有会话：它跨帧存活，直到释放/取消/目标失效 ----
    if let Some(mut 会话) = 上下文.界面.操纵器拖拽.take() {
        // 目标实体被删掉（或变换被移除）→ 目标失效，安全取消。
        let 目标有效 = 会话
            .起始
            .iter()
            .all(|(标识, _)| 上下文.编辑器.会话.文档.存在(*标识));
        let 主选中 = crate::gizmo::操纵器原点(上下文.编辑器);
        let 中心世界 = 主选中.map(|(_, 变换)| (变换.平移.0, 变换.平移.1));

        if 取消键 || !目标有效 || 空格按下 {
            结论.取消了拖拽 = true;
            crate::gizmo::收尾(上下文, 会话, false);
        } else if let (Some(局部), Some(中心)) = (局部指针, 中心世界) {
            if 主键按下中 {
                // 指针离开手柄也继续算：拖拽不能被"滑出手柄"中断。
                if let Some(新) = gizmo2d::求解(
                    会话.部件,
                    &mut 会话.基准,
                    中心,
                    局部,
                    &相机,
                    尺寸,
                    &会话.起始,
                ) {
                    会话.最新 = 新.clone();
                    crate::gizmo::推送预览(上下文, 新);
                }
                结论.悬停 = Some(会话.部件);
                上下文.界面.操纵器拖拽 = Some(会话);
            } else {
                // 松手：提交一次（无实际变化时不产生撤销记录）。
                crate::gizmo::收尾(上下文, 会话, true);
            }
        } else if 主键按下中 {
            // 指针在视口外：保持会话与上一帧预览，等指针回来。
            结论.悬停 = Some(会话.部件);
            上下文.界面.操纵器拖拽 = Some(会话);
        } else {
            crate::gizmo::收尾(上下文, 会话, true);
        }
    }

    // ---- 2. 重建本帧布局（悬停、绘制与证据都靠它） ----
    //
    // 会话进行中也重建：操纵器跟着实体走（移动时中心会一起移动），
    // 视觉上必须连续，否则会看到"手柄留在原地、实体跑掉"。
    let 原点 = crate::gizmo::操纵器原点(上下文.编辑器);
    if 工具 != 变换工具::选择
        && let Some((_, 变换)) = 原点
    {
        let 中心屏幕 = Pos2::new(
            内容矩形.min.x + 相机.世界转屏幕((变换.平移.0, 变换.平移.1), 尺寸).x,
            内容矩形.min.y + 相机.世界转屏幕((变换.平移.0, 变换.平移.1), 尺寸).y,
        );
        let 布 = gizmo2d::布局(工具, 中心屏幕);
        // 证据：本帧各部件的真实几何（探针据此取落点与拖拽方向）。
        上下文.界面.操纵器部件几何 = 布.部件.clone();

        if 上下文.界面.操纵器拖拽.is_none()
            && 指针在视口内
            && let Some(局部) = 局部指针
        {
            let 指针屏幕 = Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y);
            结论.悬停 = 布.命中(指针屏幕);
        }
    }

    // ---- 3. 按下：命中手柄则建立会话 ----
    if 主键刚按下
        && !空格按下
        && 指针在视口内
        && 上下文.界面.操纵器拖拽.is_none()
        && let (Some(部件), Some(局部), Some((_, 变换))) = (结论.悬停, 局部指针, 原点)
    {
        if let Some(基准) =
            gizmo2d::建立基准(部件, (变换.平移.0, 变换.平移.1), 局部, &相机, 尺寸)
        {
            上下文.界面.操纵器拖拽 = Some(crate::gizmo::拖拽会话::新建(
                工具,
                部件,
                crate::gizmo::收集选中变换(上下文.编辑器),
                基准,
            ));
            结论.占用了按下 = true;
            结论.悬停 = Some(部件);
        } else {
            // 几何退化（例如缩放轴的分母为 0）：这一下什么也不做，
            // 但**仍然吞掉按下** —— 否则会顺带重新选择实体。
            结论.占用了按下 = true;
        }
    }

    上下文.界面.操纵器悬停 = 结论.悬停;
    结论
}

/// 绘制 2D 操纵器（图元与命中几何是同一份）。
fn 绘制操纵器(画布: &egui::Painter, 上下文: &绘制上下文<'_>) {
    if 上下文.界面.变换工具 == crate::gizmo::变换工具::选择 {
        return;
    }
    let 拖拽部件 = 上下文.界面.操纵器拖拽.as_ref().map(|会话| 会话.部件);
    for 项 in &上下文.界面.操纵器部件几何 {
        let 色 = crate::gizmo::部件颜色(
            &上下文.配色,
            项.部件.轴(),
            上下文.界面.操纵器悬停,
            拖拽部件,
            项.部件,
        );
        let 线宽 = crate::gizmo::部件强调(上下文.界面.操纵器悬停, 拖拽部件, 项.部件);
        crate::gizmo::绘制部件(画布, 项, 色, 线宽, &上下文.配色);
    }
}

/// 绘制视口底部状态栏与工具栏。
fn 绘制状态栏(
    ui: &mut Ui,
    上下文: &mut 绘制上下文<'_>,
    内容矩形: Rect,
    所有框: &[视口实体框],
) {
    let 相机 = 上下文.界面.相机;
    let 指针世界 = ui.input(|输入| 输入.pointer.hover_pos()).map(|位置| {
        相机.屏幕转世界(
            egui::vec2(位置.x - 内容矩形.min.x, 位置.y - 内容矩形.min.y),
            内容矩形.size(),
        )
    });

    // 把工具栏放在视口左下角内部。
    let 工具栏位置 = Pos2::new(内容矩形.min.x + 8.0, 内容矩形.min.y + 8.0);
    let mut 子界面 = ui.new_child(
        egui::UiBuilder::new()
            .max_rect(Rect::from_min_size(
                工具栏位置,
                egui::vec2(内容矩形.width() - 16.0, 22.0),
            ))
            .layout(egui::Layout::left_to_right(egui::Align::Center)),
    );

    egui::Frame::NONE
        // 叠加条的颜色来自主题：浅色主题下必须换成浅底深字，
        // 否则深色半透明底 + 深色次要文字几乎看不清（上一轮遗留缺陷）。
        .fill(上下文.配色.叠加背景)
        .stroke(egui::Stroke::new(1.0, 上下文.配色.叠加边框))
        .inner_margin(egui::Margin::symmetric(6, 2))
        .corner_radius(3)
        .show(&mut 子界面, |ui| {
            // 预览渲染状态。必须让用户能分辨"场景是空的"与"预览没起来"，
            // 否则会以为自己的场景丢了。
            let (预览文本, 预览色) = match &上下文.视口纹理 {
                Some(结果) => (
                    上下文
                        .语言
                        .填充("preview", &[&结果.像素尺寸.0, &结果.像素尺寸.1]),
                    上下文.配色.强调,
                ),
                None => (
                    上下文.语言.取("preview_not_ready").to_string(),
                    上下文.配色.警告,
                ),
            };
            ui.label(RichText::new(预览文本).small().color(预览色))
                .on_hover_text(if 上下文.视口纹理.is_some() {
                    上下文.语言.取("viewport_render_pipeline_hint")
                } else {
                    上下文.语言.取("viewport_preview_not_ready_hint")
                });

            ui.separator();
            ui.label(
                RichText::new(
                    上下文
                        .语言
                        .填充("viewport_2d_entity_count", &[&所有框.len()]),
                )
                .small()
                .color(上下文.配色.次要文字),
            );
            ui.separator();
            ui.label(
                RichText::new(上下文.语言.填充(
                    "viewport_zoom",
                    &[&format!("{:.0}", 上下文.界面.相机.缩放 * 100.0)],
                ))
                .small()
                .color(上下文.配色.次要文字),
            );
            if let Some(世界) = 指针世界 {
                ui.separator();
                ui.label(
                    RichText::new(format!("{:.2}, {:.2}", 世界.0, 世界.1))
                        .small()
                        .monospace()
                        .color(上下文.配色.次要文字),
                );
            }
            ui.separator();
            if ui.small_button(上下文.语言.取("fit_to_window_f")).clicked()
                && let Some((最小, 最大)) = 世界包围盒(&上下文.编辑器.会话.文档)
            {
                上下文.界面.相机.适应包围盒(最小, 最大, 内容矩形.size());
            }
            if ui.small_button(上下文.语言.取("reset_view")).clicked() {
                // 复用一个来源：默认值只写在 `视口相机::default()` 里，
                // 避免"默认缩放"在两处各写一个数字、改一处漏一处。
                上下文.界面.相机 = crate::state::视口相机::default();
            }
            let mut 网格 = 上下文.界面.相机.显示网格;
            if ui.checkbox(&mut 网格, 上下文.语言.取("grid")).changed() {
                上下文.界面.相机.显示网格 = 网格;
            }
            let mut 包围框 = 上下文.界面.相机.显示包围框;
            if ui.checkbox(&mut 包围框, 上下文.语言.取("bounds")).changed() {
                上下文.界面.相机.显示包围框 = 包围框;
            }
            let mut 碰撞 = 上下文.界面.相机.显示碰撞;
            if ui
                .checkbox(&mut 碰撞, 上下文.语言.取("collision_shapes"))
                .on_hover_text(上下文.语言.取("collision_shapes_hint"))
                .changed()
            {
                上下文.界面.相机.显示碰撞 = 碰撞;
            }
        });
}

