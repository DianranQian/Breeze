//! 2D 视口面板。
//!
//! # 本期视口的实现边界（必须说清楚）
//!
//! 视口内容由 egui 直接绘制，渲染的是**编辑器对场景的表示**：
//! 网格、坐标轴、实体包围框、选中高亮、变换控件。它不是把游戏画面
//! 渲染到纹理再贴上来。
//!
//! 这样做的理由与代价：
//!
//! * **好处**：编辑器不依赖游戏相机与渲染管线就能工作，场景数据的
//!   每一个改动都能立刻、确定地看到效果，也不存在"编辑器和游戏
//!   抢同一台相机"的问题。这一期的目标是**编辑闭环可验证**。
//! * **代价**：看不到材质的真实外观、看不到光照与动画。
//! * **演进路线**：`editor_app` 里预留了 `视口渲染目标`，
//!   后续把游戏场景渲染到 `Image` 纹理并作为视口底板贴上来，
//!   编辑叠加层（网格/包围框/Gizmo）继续由本模块绘制。
//!   这条路线不需要改本模块的交互逻辑。
//!
//! 详细评估记录在 `功能路线图.md` 与 `工作日志.md` 中。

use editor_core::state::编辑器状态;
use egui::{Color32, Painter, Pos2, Rect, RichText, Sense, Stroke, Ui};
use scene_doc::document::{变换数据, 实体标识, 场景文档};

use crate::state::{绘制上下文, 视口拖拽, 选择意图, UiAction};

/// 一个实体在视口里的屏幕矩形。
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct 视口实体框 {
    /// 实体标识。
    pub 标识: 实体标识,
    /// 世界坐标下的半宽。
    pub 半宽: f32,
    /// 世界坐标下的半高。
    pub 半高: f32,
    /// 世界坐标下的中心。
    pub 中心: (f32, f32),
}

impl 视口实体框 {
    /// 世界包围盒。
    pub fn 世界包围盒(&self) -> ((f32, f32), (f32, f32)) {
        (
            (self.中心.0 - self.半宽, self.中心.1 - self.半高),
            (self.中心.0 + self.半宽, self.中心.1 + self.半高),
        )
    }

    /// 是否包含一个世界坐标点。
    pub fn 包含(&self, 点: (f32, f32)) -> bool {
        (点.0 - self.中心.0).abs() <= self.半宽 && (点.1 - self.中心.1).abs() <= self.半高
    }
}

/// 一个实体的默认视觉尺寸（世界单位），当它没有声明尺寸时使用。
///
/// 用"组件是否存在"来推断尺寸，而不是硬编码"所有实体都是 64x64"：
/// 这样带 `Sprite` 的实体看起来像精灵，不带的大多只是逻辑节点，
/// 用一个小方块表示更容易分辨。
const 默认精灵半尺寸: f32 = 32.0;
const 默认节点半尺寸: f32 = 8.0;

/// 计算一个实体在视口里的框。
///
/// 尺寸的优先级：
/// 1. `Sprite` 组件里用户可编辑的 `custom_size`（若设置了）；
/// 2. 有 `Sprite` 组件 → 默认 64×64；
/// 3. 其余 → 8×8 的小节点框。
///
/// 没有直接从 Bevy 的 `Sprite` 类型读，是因为组件在文档里是弱类型的；
/// 这也意味着"视口显示尺寸"与"运行时真实尺寸"在用户没设置
/// `custom_size` 时可能不一致 —— 这一点在路线图里记为已知限制。
pub fn 计算实体框(文档: &场景文档, 标识: 实体标识) -> Option<视口实体框> {
    let 实体 = 文档.取(标识)?;
    let 变换 = 实体.变换?;

    let 半尺寸 = 实体
        .取组件("Sprite")
        .and_then(|组件| 组件.属性.get("自定义尺寸"))
        .and_then(属性取二维)
        .map(|(宽, 高)| (宽.abs() * 0.5, 高.abs() * 0.5))
        .unwrap_or_else(|| {
            if 实体.有组件("Sprite") {
                (默认精灵半尺寸, 默认精灵半尺寸)
            } else {
                (默认节点半尺寸, 默认节点半尺寸)
            }
        });

    Some(视口实体框 {
        标识,
        半宽: 半尺寸.0 * 变换.缩放.0.abs(),
        半高: 半尺寸.1 * 变换.缩放.1.abs(),
        中心: (变换.平移.0, 变换.平移.1),
    })
}

/// 从属性值里取二维尺寸。
fn 属性取二维(值: &scene_doc::property::属性值) -> Option<(f32, f32)> {
    use scene_doc::property::属性值;
    match 值 {
        属性值::二维(x, y) => Some((*x, *y)),
        属性值::三维(x, y, _) => Some((*x, *y)),
        _ => None,
    }
}

/// 命中测试：返回世界坐标点下最靠上的实体。
///
/// "最靠上"按视口绘制顺序**倒序**查找，也就是后画的（在场景树里靠后的）
/// 优先命中，与用户在画面上的直觉一致。
pub fn 命中测试(文档: &场景文档, 世界点: (f32, f32)) -> Option<实体标识> {
    let 顺序 = 文档.深度优先遍历();
    for (标识, _) in 顺序.iter().rev() {
        let Some(实体) = 文档.取(*标识) else {
            continue;
        };
        if 实体.编辑器锁定 || 实体.编辑器隐藏 {
            continue;
        }
        if let Some(框) = 计算实体框(文档, *标识)
            && 框.包含(世界点) {
                return Some(*标识);
            }
    }
    None
}

/// 收集所有可见实体的视口框。
pub fn 收集可见框(文档: &场景文档) -> Vec<视口实体框> {
    文档
        .深度优先遍历()
        .into_iter()
        .filter_map(|(标识, _)| {
            let 实体 = 文档.取(标识)?;
            if 实体.编辑器隐藏 {
                return None;
            }
            计算实体框(文档, 标识)
        })
        .collect()
}

/// 文档中所有实体框的合并包围盒。空场景返回 `None`。
pub fn 世界包围盒(文档: &场景文档) -> Option<((f32, f32), (f32, f32))> {
    let 所有框 = 收集可见框(文档);
    if 所有框.is_empty() {
        return None;
    }
    let mut 最小 = (f32::INFINITY, f32::INFINITY);
    let mut 最大 = (f32::NEG_INFINITY, f32::NEG_INFINITY);
    for 框 in &所有框 {
        let (框最小, 框最大) = 框.世界包围盒();
        最小.0 = 最小.0.min(框最小.0);
        最小.1 = 最小.1.min(框最小.1);
        最大.0 = 最大.0.max(框最大.0);
        最大.1 = 最大.1.max(框最大.1);
    }
    if !最小.0.is_finite() || !最大.0.is_finite() {
        return None;
    }
    Some((最小, 最大))
}

/// 绘制视口内容。所有几何绘制都相对 `内容矩形`（视口面板内实际可画区域）。
pub fn 绘制内容(
    ui: &mut Ui,
    上下文: &mut 绘制上下文<'_>,
    内容矩形: Rect,
) {
    let 尺寸 = 内容矩形.size();
    上下文.界面.视口尺寸 = 尺寸;

    let 文档 = &上下文.编辑器.会话.文档;

    // 把"视口局部坐标"换算成屏幕坐标的辅助闭包。
    let 到屏幕 = |局部: egui::Vec2| -> Pos2 {
        Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y)
    };

    // ---------- 1. 输入处理 ----------
    let 响应 = ui.allocate_rect(内容矩形, Sense::click_and_drag());
    let 指针 = ui.input(|输入| 输入.pointer.clone());
    let 修饰 = ui.input(|输入| 输入.modifiers);
    // 空格不是 Modifiers 的字段，它是一个按键，因此单独查询按键状态。
    let 空格按下 = ui.input(|输入| 输入.key_down(egui::Key::Space));
    // egui 0.36 用 `smooth_scroll_delta`（已按滚动平滑处理）。
    let 滚轮 = ui.input(|输入| 输入.smooth_scroll_delta.y);

    let 局部指针 = 指针
        .hover_pos()
        .map(|位置| egui::vec2(位置.x - 内容矩形.min.x, 位置.y - 内容矩形.min.y));

    // 滚轮缩放（以指针为锚点）
    if 响应.hovered() && 滚轮.abs() > 0.0
        && let Some(锚点) = 局部指针 {
            let 系数 = (滚轮 * 0.0015).exp();
            上下文.界面.相机.以锚点缩放(系数, 锚点, 尺寸);
        }

    // 中键或空格拖动 = 平移视图
    if 响应.dragged_by(egui::PointerButton::Middle)
        || (响应.dragged_by(egui::PointerButton::Primary) && 空格按下)
    {
        let 增量 = ui.input(|输入| 输入.pointer.delta());
        上下文.界面.相机.平移(egui::vec2(增量.x, 增量.y));
        上下文.界面.拖拽 = 视口拖拽::平移;
    } else if 响应.drag_stopped() {
        上下文.界面.拖拽 = 视口拖拽::无;
    }

    // 左键按下：命中测试 → 选择 + 开始拖动
    let 主键按下 = 响应.drag_started_by(egui::PointerButton::Primary) && !空格按下;
    if 主键按下
        && let Some(局部) = 局部指针 {
            let 世界 = 上下文.界面.相机.屏幕转世界(局部, 尺寸);
            match 命中测试(文档, 世界) {
                Some(命中) => {
                    let 已选中 = 上下文.编辑器.选择.包含(命中);
                    if !已选中 {
                        let 意图 = if 修饰.command {
                            选择意图::切换(命中)
                        } else {
                            选择意图::单选(命中)
                        };
                        上下文.动作.推(UiAction::选择(意图));
                    }
                    上下文.动作.推(UiAction::开始拖动实体 {
                        实体: 命中,
                        追加选择: 修饰.shift,
                        按下世界: 世界,
                    });
                }
                None => {
                    // 点空白处：清空选择并开始框选
                    if !修饰.command {
                        上下文.动作.推(UiAction::选择(选择意图::清空));
                    }
                    上下文.界面.拖拽 = 视口拖拽::框选 { 起点: 局部 };
                }
            }
        }

    // 拖动中
    if 响应.dragged_by(egui::PointerButton::Primary) && !空格按下 {
        match 上下文.界面.拖拽.clone() {
            视口拖拽::移动实体 { 按下世界, .. } => {
                if let Some(局部) = 局部指针 {
                    let 世界 = 上下文.界面.相机.屏幕转世界(局部, 尺寸);
                    上下文.动作.推(UiAction::拖动实体到 {
                        世界偏移: (世界.0 - 按下世界.0, 世界.1 - 按下世界.1),
                    });
                }
            }
            视口拖拽::框选 { .. } | 视口拖拽::无 => {}
            视口拖拽::平移 => {}
        }
    }

    // 松手：结束拖动 / 完成框选
    if 响应.drag_stopped_by(egui::PointerButton::Primary) {
        if let 视口拖拽::框选 { 起点 } = 上下文.界面.拖拽.clone() {
            if let Some(终点) = 局部指针 {
                完成框选(上下文, 起点, 终点, 尺寸);
            }
        } else if matches!(上下文.界面.拖拽, 视口拖拽::移动实体 { .. }) {
            上下文.动作.推(UiAction::结束拖动);
        }
        上下文.界面.拖拽 = 视口拖拽::无;
    }

    // 点击（未拖动）时若命中了已选中实体，保持选择不变。
    // 这里不额外处理：上面的 drag_started 分支已经覆盖。

    // ---------- 2. 绘制 ----------
    let 画布 = ui.painter_at(内容矩形);
    画布.rect_filled(内容矩形, 0.0, 上下文.配色.视口背景);

    if 上下文.界面.相机.显示网格 {
        绘制网格(&画布, 内容矩形, &上下文.界面.相机, 上下文.配色);
    }
    if 上下文.界面.相机.显示坐标轴 {
        绘制坐标轴(&画布, 内容矩形, &上下文.界面.相机, 上下文.配色);
    }

    let 选中列表 = 上下文.编辑器.选择.全部();
    let 主选中 = 上下文.编辑器.选择.主选中();

    let 所有框 = 收集可见框(文档);
    for 框 in &所有框 {
        let 屏幕中心 = 到屏幕(上下文.界面.相机.世界转屏幕(框.中心, 尺寸));
        let 屏幕半宽 = 框.半宽 * 上下文.界面.相机.缩放;
        let 屏幕半高 = 框.半高 * 上下文.界面.相机.缩放;
        let 矩形 = Rect::from_center_size(屏幕中心, egui::vec2(屏幕半宽 * 2.0, 屏幕半高 * 2.0));

        let 被选中 = 选中列表.contains(&框.标识);
        if 被选中 {
            画布.rect_filled(矩形, 1.0, 上下文.配色.选中填充(主选中 == Some(框.标识)));
        }
        if 上下文.界面.相机.显示包围框 || 被选中 {
            let 线色 = if 被选中 {
                上下文.配色.强调
            } else {
                上下文.配色.实体框
            };
            let 线宽 = if 被选中 { 2.0 } else { 1.0 };
            画布.rect_stroke(
                矩形,
                1.0,
                Stroke::new(线宽, 线色),
                egui::StrokeKind::Inside,
            );
        }
    }

    // 选中标记：中心锚点 + 标识首段，便于在重叠对象中确认选的是谁。
    if let Some(标识) = 主选中
        && let Some(框) = 计算实体框(文档, 标识) {
            let 屏幕中心 = 到屏幕(上下文.界面.相机.世界转屏幕(框.中心, 尺寸));
            画布.circle_filled(屏幕中心, 3.0, 上下文.配色.强调);
        }

    // 框选矩形
    if let (视口拖拽::框选 { 起点 }, Some(终点)) = (&上下文.界面.拖拽, 局部指针) {
        let 矩形 = Rect::from_two_pos(到屏幕(*起点), 到屏幕(终点));
        画布.rect_filled(矩形, 0.0, 上下文.配色.强调淡);
        画布.rect_stroke(
            矩形,
            0.0,
            Stroke::new(1.0, 上下文.配色.强调),
            egui::StrokeKind::Inside,
        );
    }

    // ---------- 3. 键盘快捷键 ----------
    处理快捷键(ui, 上下文, 尺寸);

    // ---------- 4. 状态栏 ----------
    绘制状态栏(ui, 上下文, 内容矩形, &所有框);
}

/// 绘制网格。
fn 绘制网格(
    画布: &Painter,
    内容矩形: Rect,
    相机: &crate::state::视口相机,
    配色: crate::theme::编辑器配色,
) {
    let 尺寸 = 内容矩形.size();

    // 网格间距随缩放自适应，避免缩小时画出成千上万条线。
    let mut 间距 = 相机.网格间距;
    while 间距 * 相机.缩放 < 12.0 {
        间距 *= 2.0;
    }
    // 间距过大时也没必要继续画
    if 间距 * 相机.缩放 > 400.0 {
        return;
    }

    let 左上世界 = 相机.屏幕转世界(egui::vec2(0.0, 0.0), 尺寸);
    let 右下世界 = 相机.屏幕转世界(egui::vec2(尺寸.x, 尺寸.y), 尺寸);

    let 起_x = (左上世界.0 / 间距).floor() as i32;
    let 止_x = (右下世界.0 / 间距).ceil() as i32;
    let 起_y = (右下世界.1 / 间距).floor() as i32;
    let 止_y = (左上世界.1 / 间距).ceil() as i32;

    // 安全上限：即使上面的自适应失效，也不允许画出爆炸数量的线。
    const 最大线数: i32 = 400;
    if (止_x - 起_x) > 最大线数 || (止_y - 起_y) > 最大线数 {
        return;
    }

    let 到屏幕 = |世界: (f32, f32)| -> Pos2 {
        let 局部 = 相机.世界转屏幕(世界, 尺寸);
        Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y)
    };

    for 序号 in 起_x..=止_x {
        let 世界_x = 序号 as f32 * 间距;
        let 颜色 = if 序号 % 10 == 0 {
            配色.网格主
        } else {
            配色.网格次
        };
        画布.line_segment(
            [
                到屏幕((世界_x, 左上世界.1)),
                到屏幕((世界_x, 右下世界.1)),
            ],
            Stroke::new(1.0, 颜色),
        );
    }
    for 序号 in 起_y..=止_y {
        let 世界_y = 序号 as f32 * 间距;
        let 颜色 = if 序号 % 10 == 0 {
            配色.网格主
        } else {
            配色.网格次
        };
        画布.line_segment(
            [
                到屏幕((左上世界.0, 世界_y)),
                到屏幕((右下世界.0, 世界_y)),
            ],
            Stroke::new(1.0, 颜色),
        );
    }
}

/// 绘制坐标轴。
fn 绘制坐标轴(
    画布: &Painter,
    内容矩形: Rect,
    相机: &crate::state::视口相机,
    配色: crate::theme::编辑器配色,
) {
    let 尺寸 = 内容矩形.size();
    let 到屏幕 = |世界: (f32, f32)| -> Pos2 {
        let 局部 = 相机.世界转屏幕(世界, 尺寸);
        Pos2::new(内容矩形.min.x + 局部.x, 内容矩形.min.y + 局部.y)
    };

    let 左上 = 相机.屏幕转世界(egui::vec2(0.0, 0.0), 尺寸);
    let 右下 = 相机.屏幕转世界(egui::vec2(尺寸.x, 尺寸.y), 尺寸);

    // Y 轴（世界 x = 0）
    if 左上.0 <= 0.0 && 右下.0 >= 0.0 {
        画布.line_segment(
            [到屏幕((0.0, 左上.1)), 到屏幕((0.0, 右下.1))],
            Stroke::new(1.5, 配色.轴_y),
        );
    }
    // X 轴（世界 y = 0）
    if 右下.1 <= 0.0 && 左上.1 >= 0.0 {
        画布.line_segment(
            [到屏幕((左上.0, 0.0)), 到屏幕((右下.0, 0.0))],
            Stroke::new(1.5, 配色.轴_x),
        );
    }
}

/// 完成框选：选中所有与矩形相交的实体。
fn 完成框选(
    上下文: &mut 绘制上下文<'_>,
    起点: egui::Vec2,
    终点: egui::Vec2,
    尺寸: egui::Vec2,
) {
    let 世界起 = 上下文.界面.相机.屏幕转世界(起点, 尺寸);
    let 世界止 = 上下文.界面.相机.屏幕转世界(终点, 尺寸);
    let 选择最小 = (世界起.0.min(世界止.0), 世界起.1.min(世界止.1));
    let 选择最大 = (世界起.0.max(世界止.0), 世界起.1.max(世界止.1));

    let 文档 = &上下文.编辑器.会话.文档;
    let mut 命中 = Vec::new();
    for 框 in 收集可见框(文档) {
        let (框最小, 框最大) = 框.世界包围盒();
        // 相交判定：完全在外面才排除。
        let 相交 = 框最大.0 >= 选择最小.0
            && 框最小.0 <= 选择最大.0
            && 框最大.1 >= 选择最小.1
            && 框最小.1 <= 选择最大.1;
        if 相交 {
            命中.push(框.标识);
        }
    }
    上下文
        .动作
        .推(UiAction::选择(选择意图::设为(命中)));
}

/// 处理视口快捷键。
fn 处理快捷键(ui: &mut Ui, 上下文: &mut 绘制上下文<'_>, 尺寸: egui::Vec2) {
    // 只在视口获得焦点、且没有文本输入框在编辑时响应，
    // 否则用户重命名实体时按 Delete 会连带删掉实体。
    if 上下文.界面.文本编辑.is_some() {
        return;
    }

    let (聚焦键, 删除键, 取消键) = ui.input(|输入| {
        (
            输入.key_pressed(egui::Key::F),
            输入.key_pressed(egui::Key::Delete),
            输入.key_pressed(egui::Key::Escape),
        )
    });

    if 聚焦键 {
        // F：聚焦到选中实体；没有选中则适应整个场景。
        match 上下文.主选中() {
            Some(标识) => {
                if let Some(框) = 计算实体框(&上下文.编辑器.会话.文档, 标识) {
                    // 留出边距，避免实体正好贴着视口边缘。
                    let 半宽 = 框.半宽.max(0.5) * 1.6;
                    let 半高 = 框.半高.max(0.5) * 1.6;
                    上下文.界面.相机.适应包围盒(
                        (框.中心.0 - 半宽, 框.中心.1 - 半高),
                        (框.中心.0 + 半宽, 框.中心.1 + 半高),
                        尺寸,
                    );
                }
            }
            None => {
                if let Some((最小, 最大)) = 世界包围盒(&上下文.编辑器.会话.文档) {
                    上下文.界面.相机.适应包围盒(最小, 最大, 尺寸);
                }
            }
        }
    }

    if 删除键 {
        let 目标: Vec<实体标识> = 上下文.编辑器.选择.全部();
        for 标识 in 目标 {
            上下文.动作.推(UiAction::删除实体(标识));
        }
    }

    if 取消键 {
        上下文.动作.推(UiAction::选择(选择意图::清空));
    }
}

/// 绘制视口底部状态栏与工具栏。
fn 绘制状态栏(
    ui: &mut Ui,
    上下文: &mut 绘制上下文<'_>,
    内容矩形: Rect,
    所有框: &[视口实体框],
) {
    let 相机 = 上下文.界面.相机;
    let 指针世界 = ui
        .input(|输入| 输入.pointer.hover_pos())
        .map(|位置| {
            相机.屏幕转世界(
                egui::vec2(位置.x - 内容矩形.min.x, 位置.y - 内容矩形.min.y),
                内容矩形.size(),
            )
        });

    // 把工具栏放在视口左下角内部。
    let 工具栏位置 = Pos2::new(内容矩形.min.x + 8.0, 内容矩形.min.y + 8.0);
    let mut 子界面 = ui.new_child(
        egui::UiBuilder::new()
            .max_rect(Rect::from_min_size(工具栏位置, egui::vec2(内容矩形.width() - 16.0, 22.0)))
            .layout(egui::Layout::left_to_right(egui::Align::Center)),
    );

    egui::Frame::NONE
        .fill(Color32::from_rgba_premultiplied(20, 21, 24, 200))
        .inner_margin(egui::Margin::symmetric(6, 2))
        .corner_radius(3)
        .show(&mut 子界面, |ui| {
            ui.label(
                RichText::new(format!("2D 视口 · {} 个实体", 所有框.len()))
                    .small()
                    .color(上下文.配色.次要文字),
            );
            ui.separator();
            ui.label(
                RichText::new(format!("缩放 {:.0}%", 上下文.界面.相机.缩放 / 48.0 * 100.0))
                    .small()
                    .color(上下文.配色.次要文字),
            );
            if let Some(世界) = 指针世界 {
                ui.separator();
                ui.label(
                    RichText::new(format!("{:.2}, {:.2}", 世界.0, 世界.1))
                        .small()
                        .monospace()
                        .color(上下文.配色.次要文字),
                );
            }
            ui.separator();
            if ui.small_button("适应窗口 (F)").clicked()
                && let Some((最小, 最大)) = 世界包围盒(&上下文.编辑器.会话.文档) {
                    上下文
                         .界面
                         .相机
                        .适应包围盒(最小, 最大, 内容矩形.size());
                }
            if ui.small_button("重置视图").clicked() {
                上下文.界面.相机.中心 = (0.0, 0.0);
                上下文.界面.相机.缩放 = 48.0;
            }
            let mut 网格 = 上下文.界面.相机.显示网格;
            if ui.checkbox(&mut 网格, "网格").changed() {
                上下文.界面.相机.显示网格 = 网格;
            }
            let mut 包围框 = 上下文.界面.相机.显示包围框;
            if ui.checkbox(&mut 包围框, "包围框").changed() {
                上下文.界面.相机.显示包围框 = 包围框;
            }
        });
}

