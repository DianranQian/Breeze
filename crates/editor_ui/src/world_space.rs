//! 世界坐标位移与父级局部空间的换算。
//!
//! # 为什么需要这一层
//!
//! 预览把父子关系交给 Bevy 的 `GlobalTransform` 传播之后，文档里的 `平移`
//! 只表示**相对父级**的位置。拖动、对齐与分布算出来的增量都在世界空间，
//! 若直接加到 `平移` 上，父级带旋转或缩放时子实体会偏离指针：
//! 父级旋转 45°、放大 2 倍时，世界 +X 的 100 单位在父级空间里是
//! `(35.36, -35.36)`，而不是 `(100, 0)`。
//!
//! # 逆矩阵从哪里来
//!
//! `editor_app::preview::同步预览世界变换` 在 `TransformSystems::Propagate`
//! 之后，把每个预览节点的 `GlobalTransform::affine().inverse().matrix3`
//! 抄成 [`世界逆矩阵`]。界面层与动作层只做"逆矩阵 × 位移向量"，
//! 不重新组合父子变换，也不手写矩阵累加。
//!
//! # 布局约定
//!
//! [`世界逆矩阵`] 是**行主序**的 `[[行][列]; 3]`；表中的键是实体自身的标识，
//! 值是该实体**世界变换**的逆线性部分。

use std::collections::BTreeMap;

use scene_doc::document::{场景文档, 实体标识};

/// 一个世界变换的逆线性部分（行主序 3×3）。
///
/// 来自 `GlobalTransform::affine().inverse().matrix3`，因此已经包含
/// 父链上的旋转与缩放；非均匀缩放产生的剪切也原样保留。
pub type 世界逆矩阵 = [[f32; 3]; 3];

/// 文档实体 → 其世界变换的逆线性部分。
pub type 世界逆矩阵表 = BTreeMap<实体标识, 世界逆矩阵>;

/// 一次换算所需的世界空间数据。
///
/// 字段是 `Option` 是为了让纯几何单元测试可以只关心坐标：
/// 缺省（`None`）时按"根实体、世界增量即局部增量"处理，
/// 与 P5-2 之前的拓扑一致；生产路径必须用 [`世界空间::新建`] 提供真实数据。
#[derive(Clone, Copy, Default, Debug)]
pub struct 世界空间<'a> {
    /// 文档，用于判断实体是否有父级以及祖先链。
    pub 文档: Option<&'a 场景文档>,
    /// 世界逆矩阵表，键是实体自身。
    pub 逆矩阵: Option<&'a 世界逆矩阵表>,
}

impl<'a> 世界空间<'a> {
    /// 用真实文档与逆矩阵表构造。
    pub fn 新建(文档: &'a 场景文档, 逆矩阵: &'a 世界逆矩阵表) -> Self {
        Self {
            文档: Some(文档),
            逆矩阵: Some(逆矩阵),
        }
    }
}

/// 把世界位移换算成实体父级空间里的局部位移。
///
/// # 规则
///
/// * 根实体：局部位移就是世界位移；
/// * 有父级且逆矩阵可用：`父级逆矩阵 × 世界位移`；
/// * 快照尚未就绪（缺文档或逆矩阵）：退回世界位移。
///   这只对根实体严格正确，但比"原地不动"更接近用户预期，
///   与 P5-2 之前的退化行为一致。
pub fn 世界位移转局部位移(
    标识: 实体标识,
    世界位移: (f32, f32, f32),
    世界: 世界空间<'_>,
) -> (f32, f32, f32) {
    let (Some(文档), Some(逆矩阵)) = (世界.文档, 世界.逆矩阵) else {
        return 世界位移;
    };
    let Some(父) = 文档.取(标识).and_then(|实体| 实体.父实体) else {
        return 世界位移;
    };
    let Some(逆) = 逆矩阵.get(&父) else {
        return 世界位移;
    };
    let (x, y, z) = 世界位移;
    (
        逆[0][0] * x + 逆[0][1] * y + 逆[0][2] * z,
        逆[1][0] * x + 逆[1][1] * y + 逆[1][2] * z,
        逆[2][0] * x + 逆[2][1] * y + 逆[2][2] * z,
    )
}

/// 实体是否存在一个也在 `选中` 集合里的祖先。
///
/// 多选拖动时父子同时被选中：父级会带着子级一起移动，
/// 子级若再按世界位移换算一次就会移动两倍，因此必须跳过。
pub fn 有选中祖先(
    文档: &场景文档, 标识: 实体标识, 选中: &[实体标识]
) -> bool {
    let mut 当前 = 文档.取(标识).and_then(|实体| 实体.父实体);
    while let Some(父) = 当前 {
        if 选中.contains(&父) {
            return true;
        }
        当前 = 文档.取(父).and_then(|实体| 实体.父实体);
    }
    false
}

/// 拖拽使用的局部位移：祖先也在选中集合里时返回零。
///
/// 与 [`世界位移转局部位移`] 的区别只有这一条：多个实体被同一个世界增量
/// 拖动时，后代的世界位移由祖先带动，不能再落到自己的局部平移上。
pub fn 拖拽局部位移(
    标识: 实体标识,
    世界位移: (f32, f32, f32),
    选中: &[实体标识],
    世界: 世界空间<'_>,
) -> (f32, f32, f32) {
    if let Some(文档) = 世界.文档
        && 有选中祖先(文档, 标识, 选中)
    {
        return (0.0, 0.0, 0.0);
    }
    世界位移转局部位移(标识, 世界位移, 世界)
}

#[cfg(test)]
mod 测试 {
    use super::*;
    use scene_doc::document::变换数据;

    const 半根号二: f32 = std::f32::consts::FRAC_1_SQRT_2;

    /// 父级绕 Z 旋转 45°、放大 2 倍时的世界逆线性部分（行主序）。
    fn 旋转四十五度两倍逆矩阵() -> 世界逆矩阵 {
        [
            [半根号二 * 0.5, 半根号二 * 0.5, 0.0],
            [-半根号二 * 0.5, 半根号二 * 0.5, 0.0],
            [0.0, 0.0, 0.5],
        ]
    }

    fn 父子文档() -> (场景文档, 实体标识, 实体标识) {
        let mut 文档 = 场景文档::新建("换算");
        let 父 = 文档.生成实体("父", None);
        let 子 = 文档.生成实体("子", Some(父));
        if let Some(实体) = 文档.取可变(父) {
            实体.变换 = Some(变换数据::单位());
        }
        if let Some(实体) = 文档.取可变(子) {
            实体.变换 = Some(变换数据::单位());
        }
        (文档, 父, 子)
    }

    #[test]
    fn 根实体的局部位移就是世界位移() {
        let (文档, 父, _) = 父子文档();
        let 逆 = 世界逆矩阵表::new();
        let 结果 = 世界位移转局部位移(父, (100.0, 0.0, 0.0), 世界空间::新建(&文档, &逆));
        assert_eq!(结果, (100.0, 0.0, 0.0));
    }

    #[test]
    fn 旋转缩放的父级把世界位移换到局部空间() {
        let (文档, 父, 子) = 父子文档();
        let mut 逆 = 世界逆矩阵表::new();
        逆.insert(父, 旋转四十五度两倍逆矩阵());
        let 结果 = 世界位移转局部位移(子, (100.0, 0.0, 0.0), 世界空间::新建(&文档, &逆));
        assert!(
            (结果.0 - 35.355_34).abs() < 1e-3 && (结果.1 + 35.355_34).abs() < 1e-3,
            "世界 +X 100 在旋转 45°、放大 2 倍的父级里应是 (35.36, -35.36)，实际 {结果:?}"
        );
        assert!((结果.2).abs() < 1e-6);
    }

    #[test]
    fn 缺少逆矩阵时退回世界增量() {
        let (文档, _, 子) = 父子文档();
        let 逆 = 世界逆矩阵表::new();
        let 结果 = 世界位移转局部位移(子, (100.0, 0.0, 0.0), 世界空间::新建(&文档, &逆));
        assert_eq!(结果, (100.0, 0.0, 0.0));
        assert_eq!(
            世界位移转局部位移(子, (100.0, 0.0, 0.0), 世界空间::default()),
            (100.0, 0.0, 0.0)
        );
    }

    #[test]
    fn 父级也在选中集合时子级不再重复位移() {
        let (文档, 父, 子) = 父子文档();
        let mut 逆 = 世界逆矩阵表::new();
        逆.insert(父, 旋转四十五度两倍逆矩阵());
        let 选中 = [父, 子];
        assert_eq!(
            拖拽局部位移(子, (100.0, 0.0, 0.0), &选中, 世界空间::新建(&文档, &逆)),
            (0.0, 0.0, 0.0)
        );
        assert_eq!(
            拖拽局部位移(父, (100.0, 0.0, 0.0), &选中, 世界空间::新建(&文档, &逆)),
            (100.0, 0.0, 0.0),
            "父级没有选中祖先，仍应获得完整世界位移"
        );
    }
}
