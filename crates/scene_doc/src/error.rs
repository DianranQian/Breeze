//! 场景文档层的错误类型。
//!
//! 设计原则：**错误必须携带足够的信息让上层给出可操作的提示**。
//! 例如 `版本过新` 必须带上文件里的版本号，编辑器才能告诉用户
//! "这个场景是 Bevy Studio 0.9 写的，请升级编辑器"，而不是一句 "解析失败"。

use std::path::PathBuf;

use crate::path::路径错误;

/// 场景文档层的统一错误类型。
#[derive(Debug, thiserror::Error)]
pub enum 场景错误 {
    /// 文件系统读写失败。
    #[error("文件读写失败：{} —— {来源}", 路径.display())]
    文件读写 {
        /// 出错的文件路径。
        路径: PathBuf,
        /// 底层 IO 错误。
        #[source]
        来源: std::io::Error,
    },

    /// RON 文本语法错误。
    #[error("场景格式解析失败：{} —— {来源}", 路径.display())]
    格式解析 {
        /// 出错的文件路径。
        路径: PathBuf,
        /// 底层 RON 反序列化错误。
        #[source]
        来源: Box<ron::error::SpannedError>,
    },

    /// 场景被反序列化出来，但结构非法（例如父实体不存在）。
    #[error("场景结构非法：{0}")]
    结构非法(String),

    /// 文件里的格式版本高于本编辑器支持的版本。
    ///
    /// 这是**必须拒绝**而不是尽力解析的情况：高版本可能引入了
    /// 本版本不认识的语义变更，强行解析会静默丢数据。
    #[error("场景格式版本 {文件版本} 高于本编辑器支持的最高版本 {支持版本}，请升级 Bevy Studio")]
    版本过新 {
        /// 文件里记录的版本号。
        文件版本: u32,
        /// 本编辑器支持的最高版本号。
        支持版本: u32,
    },

    /// 路径不是合法的项目相对路径。
    #[error(transparent)]
    路径非法(#[from] 路径错误),

    /// 保存前的编码阶段失败（一般不会发生，出现即代表数据损坏）。
    #[error("场景编码失败：{0}")]
    编码失败(String),

    /// 写入临时文件后替换原文件失败。
    #[error("保存场景失败：{} —— {来源}", 原文件.display())]
    保存失败 {
        /// 目标文件路径。
        原文件: PathBuf,
        /// 底层 IO 错误。
        #[source]
        来源: std::io::Error,
    },

    /// 组件注册表相关错误。
    #[error(transparent)]
    注册表(#[from] crate::registry::注册表错误),
}

impl 场景错误 {
    /// 构造一个文件读写错误。
    pub fn 文件(路径: impl Into<PathBuf>, 来源: std::io::Error) -> Self {
        Self::文件读写 {
            路径: 路径.into(),
            来源,
        }
    }

    /// 构造一个结构非法错误。
    pub fn 非法(说明: impl Into<String>) -> Self {
        Self::结构非法(说明.into())
    }
}

/// 场景文档层的 `Result` 别名。
pub type 场景结果<T> = Result<T, 场景错误>;
