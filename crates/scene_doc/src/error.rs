//! 场景文档层的错误类型。
//!
//! 设计原则：**错误必须携带足够的信息让上层给出可操作的提示**。
//! 例如 `版本过新` 必须带上文件里的版本号，编辑器才能告诉用户
//! "这个场景是 Bevy Studio 0.9 写的，请升级编辑器"，而不是一句 "解析失败"。

use std::path::PathBuf;

use crate::path::路径错误;

/// 场景文档层的统一错误类型。
#[derive(Debug, thiserror::Error)]
pub enum 场景错误 {
    /// 文件系统读写失败。
    #[error("文件读写失败：{} —— {来源}", 路径.display())]
    文件读写 {
        /// 出错的文件路径。
        路径: PathBuf,
        /// 底层 IO 错误。
        #[source]
        来源: std::io::Error,
    },

    /// RON 文本语法错误。
    #[error("场景格式解析失败：{} —— {来源}", 路径.display())]
    格式解析 {
        /// 出错的文件路径。
        路径: PathBuf,
        /// 底层 RON 反序列化错误。
        #[source]
        来源: Box<ron::error::SpannedError>,
    },

    /// 场景被反序列化出来，但结构非法（例如父实体不存在）。
    #[error("场景结构非法：{0}")]
    结构非法(String),

    /// 文件里的格式版本高于本编辑器支持的版本。
    ///
    /// 这是**必须拒绝**而不是尽力解析的情况：高版本可能引入了
    /// 本版本不认识的语义变更，强行解析会静默丢数据。
    #[error("场景格式版本 {文件版本} 高于本编辑器支持的最高版本 {支持版本}，请升级 Bevy Studio")]
    版本过新 {
        /// 文件里记录的版本号。
        文件版本: u32,
        /// 本编辑器支持的最高版本号。
        支持版本: u32,
    },

    /// 路径不是合法的项目相对路径。
    #[error(transparent)]
    路径非法(#[from] 路径错误),

    /// 保存前的编码阶段失败（一般不会发生，出现即代表数据损坏）。
    #[error("场景编码失败：{0}")]
    编码失败(String),

    /// 写入临时文件后替换原文件失败。
    #[error("保存场景失败：{} —— {来源}", 原文件.display())]
    保存失败 {
        /// 目标文件路径。
        原文件: PathBuf,
        /// 底层 IO 错误。
        #[source]
        来源: std::io::Error,
    },

    /// 组件注册表相关错误。
    #[error(transparent)]
    注册表(#[from] crate::registry::注册表错误),
}

impl 场景错误 {
    /// 构造一个文件读写错误。
    pub fn 文件(路径: impl Into<PathBuf>, 来源: std::io::Error) -> Self {
        Self::文件读写 {
            路径: 路径.into(),
            来源,
        }
    }

    /// 构造一个结构非法错误。
    pub fn 非法(说明: impl Into<String>) -> Self {
        Self::结构非法(说明.into())
    }
}

/// 错误的**稳定类别**。
///
/// # 为什么需要它
///
/// 错误在 `Display` 里是一句自然语言（中文）。上层若靠比较那句话来判断
/// "到底是哪种失败"，就等于把**自然语言当成了错误身份** ——
/// 改一句文案就会悄无声息地改掉行为，而且没法按语言渲染。
///
/// 类别是纯语义标签：与语言无关，可安全用于匹配、测试与日志检索。
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum 场景错误类别 {
    /// 文件系统读写失败。
    文件读写,
    /// RON 文本语法错误。
    格式解析,
    /// 场景结构非法。
    结构非法,
    /// 文件格式版本高于本编辑器支持。
    版本过新,
    /// 路径不是合法的项目相对路径。
    路径非法,
    /// 保存前的编码阶段失败。
    编码失败,
    /// 替换原文件失败。
    保存失败,
    /// 组件注册表相关错误。
    注册表,
}

impl 场景错误类别 {
    /// 该类别在词表里的键。
    ///
    /// `scene_doc` **只输出键**，不查表、不决定语言：
    /// 本 crate 不依赖界面层，也没有全局语言状态。
    /// 渲染由上层（`editor_core` / `editor_ui`）用现有词表完成。
    pub fn 消息键(self) -> &'static str {
        match self {
            场景错误类别::文件读写 => "error_scene_read_failed",
            场景错误类别::格式解析 => "error_scene_parse_failed",
            场景错误类别::结构非法 => "error_scene_struct_invalid",
            场景错误类别::版本过新 => "error_scene_version_too_new",
            场景错误类别::路径非法 => "error_scene_path_invalid",
            场景错误类别::编码失败 => "error_scene_encode_failed",
            场景错误类别::保存失败 => "error_scene_save_failed",
            场景错误类别::注册表 => "error_scene_registry_failed",
        }
    }

    /// 全部类别。供测试核对"每个类别都有中英词条"。
    pub const 全部: [场景错误类别; 8] = [
        场景错误类别::文件读写,
        场景错误类别::格式解析,
        场景错误类别::结构非法,
        场景错误类别::版本过新,
        场景错误类别::路径非法,
        场景错误类别::编码失败,
        场景错误类别::保存失败,
        场景错误类别::注册表,
    ];
}

/// 结构化错误参数：按顺序填入消息模板的 `{}`。
///
/// 参数**不翻译**。区分种类是为了把"这是用户数据"写进类型，
/// 而不是先拼成一句中文再交给上层猜。
#[derive(Debug, Clone, PartialEq)]
pub enum 错误参数 {
    /// 文件/资源路径。用户数据，任何语言下都原样保留。
    路径(PathBuf),
    /// 版本号一类数值。
    数值(u32),
    /// 开发者诊断文本：底层库的原始原因、或尚未结构化的说明。
    ///
    /// 它**不参与翻译** —— 第三方错误文本不是我们能翻译的东西，
    /// 强行塞进翻译占位符只会把诊断信息毁掉。
    诊断(String),
}

impl std::fmt::Display for 错误参数 {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            错误参数::路径(路径) => write!(f, "{}", 路径.display()),
            错误参数::数值(数值) => write!(f, "{数值}"),
            错误参数::诊断(文本) => write!(f, "{文本}"),
        }
    }
}

impl 场景错误 {
    /// 稳定类别。
    pub fn 类别(&self) -> 场景错误类别 {
        match self {
            Self::文件读写 { .. } => 场景错误类别::文件读写,
            Self::格式解析 { .. } => 场景错误类别::格式解析,
            Self::结构非法(_) => 场景错误类别::结构非法,
            Self::版本过新 { .. } => 场景错误类别::版本过新,
            Self::路径非法(_) => 场景错误类别::路径非法,
            Self::编码失败(_) => 场景错误类别::编码失败,
            Self::保存失败 { .. } => 场景错误类别::保存失败,
            Self::注册表(_) => 场景错误类别::注册表,
        }
    }

    /// 该错误的消息键（等于其类别的键）。
    pub fn 消息键(&self) -> &'static str {
        self.类别().消息键()
    }

    /// 结构化参数。
    ///
    /// 注意底层原因以 [`错误参数::诊断`] 传入：第三方错误文本不可翻译，
    /// 但它必须**保留下来**，否则排查问题时会丢掉最有价值的信息。
    pub fn 参数(&self) -> Vec<错误参数> {
        match self {
            Self::文件读写 { 路径, 来源 } => {
                vec![
                    错误参数::路径(路径.clone()),
                    错误参数::诊断(来源.to_string()),
                ]
            }
            Self::格式解析 { 路径, 来源 } => {
                vec![
                    错误参数::路径(路径.clone()),
                    错误参数::诊断(来源.to_string()),
                ]
            }
            Self::结构非法(说明) => vec![错误参数::诊断(说明.clone())],
            Self::版本过新 {
                文件版本, 支持版本
            } => vec![错误参数::数值(*文件版本), 错误参数::数值(*支持版本)],
            // 路径错误与注册表错误是嵌套的底层错误：
            // 它们各自的诊断文本在这里原样带上，不做二次翻译。
            Self::路径非法(内部) => vec![错误参数::诊断(内部.to_string())],
            Self::编码失败(说明) => vec![错误参数::诊断(说明.clone())],
            Self::保存失败 { 原文件, 来源 } => vec![
                错误参数::路径(原文件.clone()),
                错误参数::诊断(来源.to_string()),
            ],
            Self::注册表(内部) => vec![错误参数::诊断(内部.to_string())],
        }
    }

    /// 面向用户的**本地化渲染**：把消息模板按参数填好。
    ///
    /// 语言由调用方传入，本函数不读任何全局状态 ——
    /// 这样测试可以确定地指定语言，也不会出现测试之间互相污染。
    pub fn 本地化(&self, 键: &str, 语言: &dyn Fn(&str) -> &'static str) -> String {
        let 模板 = 语言(键);
        let 参数 = self.参数();
        let mut 结果 = String::with_capacity(模板.len() + 32);
        let mut 迭代 = 参数.iter();
        let mut 剩余 = 模板;
        while let Some(左) = 剩余.find("{}") {
            结果.push_str(&剩余[..左]);
            match 迭代.next() {
                Some(值) => 结果.push_str(&值.to_string()),
                None => 结果.push_str("{}"),
            }
            剩余 = &剩余[左 + 2..];
        }
        结果.push_str(剩余);
        结果
    }
}

/// 场景文档层的 `Result` 别名。
pub type 场景结果<T> = Result<T, 场景错误>;

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 错误身份必须来自**类别**，而不是自然语言句子。
    ///
    /// 这条同时否掉了两种错误做法：
    /// 用 `Display` 文本比较来区分错误；以及中文句子变了就改变行为。
    #[test]
    fn 错误身份是稳定类别而不是文案() {
        let 读写 = 场景错误::文件(
            "C:/x/a.ron",
            std::io::Error::new(std::io::ErrorKind::NotFound, "缺失"),
        );
        let 版本 = 场景错误::版本过新 {
            文件版本: 9,
            支持版本: 1,
        };

        assert_eq!(读写.类别(), 场景错误类别::文件读写);
        assert_eq!(版本.类别(), 场景错误类别::版本过新);
        assert_ne!(读写.类别(), 版本.类别());

        // 类别是纯语义标签：不含自然语言
        let 键 = 读写.消息键();
        assert!(键.is_ascii(), "消息键 `{键}` 不能是自然语言");
        assert_eq!(键, 场景错误类别::文件读写.消息键());
    }

    /// 每个类别都有唯一的消息键，且全部列在 `全部` 里。
    #[test]
    fn 每个类别都有唯一消息键() {
        let mut 键集 = std::collections::HashSet::new();
        for 类别 in 场景错误类别::全部 {
            let 键 = 类别.消息键();
            assert!(键.starts_with("error_scene_"), "键 `{键}` 命名不符合约定");
            assert!(键集.insert(键), "键 `{键}` 重复");
        }
        assert_eq!(键集.len(), 场景错误类别::全部.len());
    }

    /// 动态参数必须完整保留：路径、版本号、底层原因。
    #[test]
    fn 参数保留路径版本与底层原因() {
        let 读写 = 场景错误::文件(
            "关卡/主场景.scene.ron",
            std::io::Error::new(std::io::ErrorKind::PermissionDenied, "拒绝访问"),
        );
        let 参数 = 读写.参数();
        assert_eq!(参数.len(), 2, "路径与原因都要保留");
        match (&参数[0], &参数[1]) {
            (错误参数::路径(路径), 错误参数::诊断(原因)) => {
                assert_eq!(路径.display().to_string(), "关卡/主场景.scene.ron");
                assert!(原因.contains("拒绝访问"), "底层原因不能被丢掉：{原因}");
            }
            其他 => panic!("参数种类不符：{其他:?}"),
        }

        let 版本 = 场景错误::版本过新 {
            文件版本: 9,
            支持版本: 1,
        };
        assert_eq!(
            版本.参数(),
            vec![错误参数::数值(9), 错误参数::数值(1)],
            "版本号必须以数值形式保留，而不是先拼进句子里"
        );
    }

    /// 底层 `std::error::Error` 来源必须可访问（错误链没有被截断）。
    #[test]
    fn 底层原因可访问() {
        use std::error::Error;
        let 读写 = 场景错误::文件("a.ron", std::io::Error::other("底层原因"));
        let 来源 = 读写.source().expect("应当保留底层来源");
        assert!(来源.to_string().contains("底层原因"));
    }

    /// 本地化渲染：同一个错误在两种语言下得到不同文案，参数保持原样。
    ///
    /// 这里用两个简单的模板闭包代替真实词表 —— `scene_doc` 不依赖翻译系统，
    /// 语言由调用方传入，因此测试不需要任何全局状态。
    #[test]
    fn 本地化按传入语言渲染且参数不翻译() {
        let 错误 = 场景错误::文件(
            "关卡/主场景.scene.ron",
            std::io::Error::new(std::io::ErrorKind::NotFound, "缺失"),
        );
        let 中文 = |_: &str| "文件读写失败：{} —— {}";
        let 英文 = |_: &str| "File read/write failed: {} — {}";

        let 中 = 错误.本地化(错误.消息键(), &中文);
        let 英 = 错误.本地化(错误.消息键(), &英文);

        assert!(中.starts_with("文件读写失败："), "{中}");
        assert!(英.starts_with("File read/write failed:"), "{英}");
        for 文本 in [&中, &英] {
            assert!(
                文本.contains("关卡/主场景.scene.ron"),
                "路径属于用户数据，任何语言下都要原样保留：{文本}"
            );
            assert!(文本.contains("缺失"), "底层原因要保留：{文本}");
        }
    }

    /// 模板占位符多于参数时不 panic（译文写错不会把编辑器搞崩）。
    #[test]
    fn 本地化占位符过多时不崩溃() {
        let 错误 = 场景错误::非法("结构有问题");
        let 模板 = |_: &str| "非法：{} 还有 {}";
        let 文本 = 错误.本地化(错误.消息键(), &模板);
        assert!(文本.contains("结构有问题"));
        assert!(文本.contains("{}"), "缺参数处应保留占位符以便定位：{文本}");
    }
}
