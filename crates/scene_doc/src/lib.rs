//! Bevy Studio 场景文档数据模型。
//!
//! # 为什么需要这一层
//!
//! Bevy 自带 `bevy_scene` 的 BSN 序列化，但它是**运行时导向**的：它序列化的是
//! `World` 里的实体与组件，服从引擎的类型路径与反射注册表。编辑器需要的却是
//! 另一种东西：
//!
//! * 文件格式必须**长期稳定**，不能因为引擎换代就整体失效；
//! * 必须携带**编辑器专有元数据**（展开状态、锁定、折叠），这些在游戏运行时毫无意义；
//! * 必须保存**未知组件**，否则用新版编辑器打开旧场景再保存会静默丢数据；
//! * 必须能**在没有 GPU、没有窗口**的环境（CI、单元测试）里读写。
//!
//! 因此本 crate 是刻意设计成 **不依赖 Bevy** 的纯逻辑层。它只做一件事：
//! 把"场景"表示为可序列化、可校验、可迁移的文档数据，并保证读写是原子且可恢复的。
//!
//! 与 Bevy 世界之间的映射由 `editor_app` 的 `scene_bridge` 模块负责。

