    #[test]
    fn 模板删除根组件时移除该组件并保留本地组件() {
        let 模板 = 造敌人模板();
        let (mut 文档, 根) = 造实例(&模板);
        物化实例(&mut 文档, 根, &模板).expect("首次物化");
        assert!(文档.取(根).expect("实例根").有组件("移动"));
        assert_eq!(
            文档.预制件实例表[&根].模板根组件,
            BTreeSet::from(["Transform".to_string(), "移动".to_string()]),
            "首次物化必须记下模板根提供的组件清单"
        );

        文档
            .取可变(根)
            .expect("实例根")
            .加组件(组件数据::标记("关卡触发器"));

        let mut 新模板 = 模板.clone();
        新模板.头.版本 = 4;
        新模板
            .场景
            .取可变(新模板.头.根)
            .expect("模板根")
            .删组件("移动");

        let 统计 = 物化实例(&mut 文档, 根, &新模板).expect("模板更新物化");

        assert!(统计.更新节点 >= 1);
        let 根实体 = 文档.取(根).expect("实例根");
        assert!(
            !根实体.有组件("移动"),
            "模板已删除的根组件必须从实例根上移除"
        );
        assert!(
            根实体.有组件("关卡触发器"),
            "实例本地后加的组件从未由模板提供，绝不能被同步流程误删"
        );
        assert!(
            !文档.预制件实例表[&根].模板根组件.contains("移动"),
            "清单必须跟随模板更新，否则下一轮会被反复误判为模板组件"
        );
    }

