/*!
嵌套预制件的递归展开：只读规划 + 一次性提交。

# 为什么拆成"规划"与"提交"两步

`物化实例` 走的是一条已经跑通的路径：拿一份模板、一条记录，把模板树写进
文档。嵌套之后这件事变复杂，因为一次展开要跨**多份**模板（A 里挂 B、B 里
又挂 C），并且要同时决定四件事：

* 每个实体的确定性标识（链式地址 → UUIDv5）；
* 每个实体的父级（可能是内层模板的节点，也可能是外层站点）；
* 每层记录自己的覆盖，以及层与层之间的优先级；
* 内层实例的实例记录（版本、指纹、根组件清单）。

如果边遍历边写文档，任何一步失败都会留下"半棵树"，撤销与回滚都得写反向
逻辑。这里先做**纯只读**的 [`规划嵌套展开`]，把所有要生成的实体标识、父级、
内容与覆盖一次算完；再由 [`提交嵌套展开`] 单遍写入文档。于是：

* 校验（标识冲突、实例根缺失、模板层级损坏）全部发生在第一次写入之前，
  失败时文档一个字都不改；
* 递归过程中需要读的模板、记录、覆盖都在只读借用上完成，避免"遍历文档
  的同时又改文档"的借用冲突；
* 规划结果本身可测试：断言"生成了哪些标识、父级是谁、哪条覆盖胜出"不需要
  先构造文档。

# 地址是"链式"的

外层实例根 `R` 下，A 模板里的站点地址 `[S]`，B 模板里的子节点地址 `[T]`，
展开到场景后的地址是 `[S, T]`（见 [`节点地址::拼接`]）。这个链式地址同时用于：

* [`派生实体标识`] 生成确定性标识；
* 外层记录里用户对该子节点的覆盖键；
* 内层记录**不能**用它 —— 每层记录的覆盖键始终相对于该层模板根，
  由 [`覆盖表::取节点`] 在规划时搬到链式地址上。

这样内层记录保持"一份 B 实例"的完整语义，将来单独同步某个内层实例时
不必先反推它在外层的站位。

# 组件与覆盖的优先级

站点根（内层模板的根实体）内容来自四层，低到高：

```text
B 模板根组件 < A 模板站点组件 < 外层实例覆盖 < 内层记录根覆盖
```

其余节点低到高是：内层记录覆盖 < 外层实例覆盖 —— 场景里用户对整份 A 实例
的修改必须赢过模板作者在内层预置的默认值。两套次序由 [`收集层覆盖`] 的
`内层优先` 开关统一实现，规则见该函数文档。

# 深度上限与降级

[`最大嵌套深度`] 是硬上限。规划时超出上限的站点**不报错**，而是记一条
[`嵌套告警::深度超限`]，并把该站点当作普通派生节点处理：树照样能展开，
用户照样能编辑，只是那层往下不再跟随模板。模板缺失与循环引用走同一套降级
策略 —— 展开引擎不能因为一份坏模板把整个实例拒之门外，那会让用户连场景
都打不开。项目级的静态超限由 `editor_core::prefab_catalog` 作为目录问题上报。
*/

