    /**
     * 确定性标识撞上别人的实体时整批拒绝，文档一字不改。
     *
     * 这条守住"规划/提交分离"的承诺：校验全部发生在第一次写入之前。
     */
    #[test]
    fn 提交在标识冲突时零副作用() {
        let 台 = 夹具();
        let (mut 文档, 实例根) = 场景宿主(&台.外层);
        let 另一个实例 = 实体标识::新建();
        let 嵌套根 = 派生实体标识(实例根, &台.站点地址);
        let 冒名 = 台.外层.场景.取(台.站点).expect("站点").clone();
        let mut 冒名实体 = 冒名;
        冒名实体.标识 = 嵌套根;
        冒名实体.父实体 = Some(实例根);
        冒名实体.来源 = 实体来源::预制件实例根 {
            实例根: 另一个实例
        };
        文档.插入实体(冒名实体);
        文档
            .预制件实例表
            .insert(嵌套根, 预制件实例记录::新建(台.内层.引用(路径(子弹路径))));

        let 快照 = 文档.clone();
        let 计划 = 规划嵌套展开(
            实例根,
            &台.外层,
            &文档.预制件实例表[&实例根].clone(),
            &文档.预制件实例表,
            &台.解析器,
            最大嵌套深度,
        )
        .expect("规划不看文档，冲突要到提交才发现");

        let 错误 =
            提交嵌套展开(&mut 文档, 实例根, &台.外层, &计划).expect_err("别人的实体不该被接管");
        assert_eq!(
            错误.类别(),
            场景错误类别::结构非法,
            "冲突是结构校验失败，不是文件读写问题"
        );
        assert_eq!(文档, 快照, "校验失败时文档必须一字不改");
    }
