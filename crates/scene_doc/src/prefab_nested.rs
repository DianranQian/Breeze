        提交嵌套展开(&mut 文档, 实例根, &台.外层, &新计划).expect("第二次提交");

        assert!(文档.取(嵌套根).is_none(), "站点实体应被删除");
        assert!(文档.取(弹头标识).is_none(), "内层子树应随站点消失");
        assert!(
            文档.预制件实例表.get(&嵌套根).is_none(),
            "站点没了就不该留内层记录"
        );
        assert_eq!(文档.实体数量(), 1);
