#[test]
fn 性能_保存一千个实体不会退化为平方复杂度() {
    // 需求里明确要求"不要每次修改一个属性就重新序列化整个项目"。
    // 这里验证序列化本身是线性可扩展的：1000 个实体的耗时
    // 不应显著超过 100 个实体的 10 倍量级。
    use std::time::Instant;

    let 构造 = |数量: usize| {
        let mut 文档 = 场景文档::新建("压力测试");
        for 序号 in 0..数量 {
            let 标识 = 文档.生成实体(format!("实体{序号}"), None);
            let mut 属性 = std::collections::BTreeMap::new();
            属性.insert("序号".to_string(), 属性值::整数(序号 as i64));
            属性.insert("位置".to_string(), 属性值::三维(序号 as f32, 0.0, 0.0));
            if let Some(实体) = 文档.取可变(标识) {
                实体.加组件(组件数据::新建("测试", 属性));
            }
        }
        文档
    };

    let 小 = 构造(100);
    let 大 = 构造(1000);

    let 计时 = |文档: &场景文档| {
        let 开始 = Instant::now();
        let 文本 = 编码场景(文档).unwrap();
        let 耗时 = 开始.elapsed();
        (耗时, 文本.len())
    };

    let (小耗时, _) = 计时(&小);
    let (大耗时, _) = 计时(&大);

    // 数据量是 10 倍，允许 40 倍的耗时余量以吸收测量噪声，
    // 但平方复杂度会给出约 100 倍，能被这条断言拦住。
    let 倍数 = 大耗时.as_secs_f64() / 小耗时.as_secs_f64().max(1e-9);
    assert!(
        倍数 < 40.0,
        "10 倍数据导致 {倍数:.1} 倍耗时，疑似非线性：小={小耗时:?} 大={大耗时:?}"
    );
}

