    assert_ne!(原, 副本1);
    assert_ne!(副本1, 副本2);

    let 名称: Vec<&str> = [原, 副本1, 副本2]
        .iter()
        .map(|标识| 文档.取(*标识).unwrap().名称.as_str())
        .collect();
    // 三个名字必须互不相同，否则场景树里无法区分
