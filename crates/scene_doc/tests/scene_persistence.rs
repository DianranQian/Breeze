//! 中文名：场景持久化
//! 场景文档层的集成测试。
//!
//! 这里测试的是**跨模块的端到端保证**，而不是单个函数的边界：
//! 保存后重新打开数据是否一致、层级操作后文档是否仍然自洽、
//! 保存失败时原文件是否真的没被动过。
//!
//! 每个测试名对应需求文档里的一条验收条件，便于逐条核对。

