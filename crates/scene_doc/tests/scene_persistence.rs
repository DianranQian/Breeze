/// 构造一个内容足够丰富的场景，覆盖层级、变换、组件与资源引用。
fn 构造样例场景() -> 场景文档 {
    let mut 文档 = 场景文档::新建("样例关卡");

    let 根 = 文档.生成实体("关卡根", None);
    let 玩家 = 文档.生成实体("玩家", Some(根));
    let 敌人 = 文档.生成实体("敌人", Some(根));
    let 子弹 = 文档.生成实体("子弹", Some(玩家));

    // 变换
    if let Some(实体) = 文档.取可变(玩家) {
        实体.变换 = Some(变换数据 {
            平移: (10.0, 20.0, 0.0),
            旋转: (0.0, 0.0, 0.0, 1.0),
            缩放: (2.0, 2.0, 1.0),
        });
    }

    // Sprite 组件，带资源引用与颜色
    let 贴图路径 = 项目相对路径::解析("textures/hero.png").unwrap();
    let 贴图标识 = 资源唯一标识::新建();
    let mut 属性 = std::collections::BTreeMap::new();
    属性.insert(
        "贴图".to_string(),
        属性值::资源(资源引用值::完整(贴图路径.clone(), 贴图标识.内部())),
    );
    属性.insert(
        "颜色".to_string(),
        属性值::颜色(颜色值::srgb(1.0, 0.5, 0.25, 1.0)),
    );
    属性.insert("是否翻转".to_string(), 属性值::布尔(false));
    if let Some(实体) = 文档.取可变(玩家) {
        实体.加组件(组件数据::新建("Sprite", 属性));
    }

    // 带枚举的组件
    let mut 敌人属性 = std::collections::BTreeMap::new();
    敌人属性.insert(
        "行为模式".to_string(),
        属性值::枚举(枚举值::新建("巡逻", 1)),
    );
    敌人属性.insert("视野半径".to_string(), 属性值::浮点(120.0));
    if let Some(实体) = 文档.取可变(敌人) {
        实体.加组件(组件数据::新建("敌人行为", 敌人属性));
    }

    // 嵌套结构的组件
    let mut 子弹属性 = std::collections::BTreeMap::new();
    子弹属性.insert(
        "速度".to_string(),
        属性值::结构(vec![
            ("线性".to_string(), 属性值::二维(0.0, 400.0)),
            ("角速度".to_string(), 属性值::浮点(0.0)),
        ]),
    );
    子弹属性.insert(
        "轨迹点".to_string(),
        属性值::列表(vec![
            属性值::二维(0.0, 0.0),
            属性值::二维(1.0, 2.0),
            属性值::二维(3.0, 4.0),
        ]),
    );
    if let Some(实体) = 文档.取可变(子弹) {
        实体.加组件(组件数据::新建("投射物", 子弹属性));
    }

    // 编辑器元数据
    if let Some(实体) = 文档.取可变(根) {
        实体.编辑器展开 = true;
        实体.编辑器锁定 = false;
    }

    文档.同步资源表();
    文档
}

#[test]
fn 场景保存后重新打开数据保持一致() {
    let 存储 = 临时存储::新建();
    let 路径 = PathBuf::from("C:/project/scenes/关卡.scene.ron");

    let 原始 = 构造样例场景();
    let 保存结果 = 存储.写入(&路径, &原始).unwrap();
    assert_eq!(保存结果, 保存结果::新建);

    let 读取 = 存储.读取(&路径).unwrap();
    assert!(!读取.从备份恢复);

    // 逐项核对，而不是只比整体 —— 只比整体的话，一旦失败无法定位是哪一层出了问题。
    assert_eq!(读取.文档.实体数量(), 原始.实体数量());
    assert_eq!(读取.文档.顶层顺序, 原始.顶层顺序);
    assert_eq!(读取.文档.元数据.场景名, "样例关卡");
    assert_eq!(读取.文档.格式版本, scene_doc::document::当前格式版本);

    // 层级关系
    let 玩家标识 = 原始
        .实体表
        .values()
        .find(|实体| 实体.名称 == "玩家")
        .unwrap()
        .标识;
    let 玩家原 = 原始.取(玩家标识).unwrap();
    let 玩家读 = 读取.文档.取(玩家标识).unwrap();
    assert_eq!(玩家原.父实体, 玩家读.父实体);
    assert_eq!(玩家原.变换, 玩家读.变换);
    assert_eq!(玩家原.组件, 玩家读.组件);

    // 资源表与 UUID 必须原样保留 —— 丢了 UUID 就失去了改名重连的能力
    assert_eq!(读取.文档.资源表, 原始.资源表);
    let 记录 = 读取
        .文档
        .资源表
        .get(&项目相对路径::解析("textures/hero.png").unwrap())
        .expect("资源表应保留贴图条目");
    assert!(记录.唯一标识.is_some());
}

