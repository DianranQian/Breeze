def 反转义(s):
    """把 TSV 里的转义序列还原成真实字符。

    为什么需要这一步：TSV 是纯文本、一行一条，因此换行只能用 `\\n`
    这两个字符来表示。若直接把这两个字符交给 [`转义`]，
    反斜杠会被再转义一次，Rust 源码里就变成 `\\\\n`，
    运行时渲染出的是**可见的 `\\n` 两个字符**而不是换行。

    这个 bug 真的发生过：7 条文案（含空状态提示）在界面上显示成
    `没有资源。\\n把图片拖进来`。因此这里先还原成真实换行，
    再由 [`转义`] 统一按 Rust 字面量规则重新转义。
    """
    return s.replace("\\n", "\n").replace("\\t", "\t").replace('\\"', '"')


def 读取词条():
    """读 messages.tsv，返回 [(键, 中文, 英文)]。"""
    行列表 = []
    with io.open(数据文件, encoding="utf-8") as f:
        for 序号, 原始 in enumerate(f, 1):
            行 = 原始.rstrip("\n").rstrip("\r")
            if not 行.strip() or 行.lstrip().startswith("#"):
                continue
            列 = 行.split("\t")
            if len(列) != 3:
                raise SystemExit(
                    f"{数据文件}:{序号} 应当有 3 列（键/中文/英文，制表符分隔），"
                    f"实际 {len(列)} 列：{行!r}"
                )
            # 只对**键**做 strip。
            #
            # 文案列的首尾空白是**有意义**的：界面里有些文案靠前导空格做对齐
            # （例如菜单项未选中时用 "   " 占住勾选标记的位置）。
            # 早先这里对三列一律 strip，结果是"源码里的文案与词表里的对不上"，
            # 覆盖核对会误报成漏翻译 —— 这个 bug 也真的发生过。
            键 = 列[0].strip()
            中 = 反转义(列[1])
            英 = 反转义(列[2])
            行列表.append((键, 中, 英))
    return 行列表


def _占位符数量(文本: str) -> int:
    """统计 `{}` / `{:.1}` 这类格式化占位符的个数。"""
    return len(re.findall(r"\{[^{}]*\}", 文本))


def _含中文(文本: str) -> bool:
    return re.search(r"[\u4e00-\u9fff]", 文本) is not None

def 校验词条(行列表):
    错 = []
    已见 = set()
    for 键, 中, 英 in 行列表:
        if not 键:
            错.append("存在空键")
        elif not re.fullmatch(r"[a-z][a-z0-9_]*", 键):
            错.append(f"键 `{键}` 不是规范的小写 ASCII 标识符")
        elif 键.endswith("_"):
            错.append(f"键 `{键}` 不应以下划线结尾")
        if 键 in 已见:
            错.append(f"键 `{键}` 重复")
        已见.add(键)
        if not 中:
            错.append(f"`{键}` 中文为空")
        if not 英:
            错.append(f"`{键}` 英文为空")
        # 占位符数量必须与中文一致：不一致时英文界面会格式化出错，
        # 而且这类错误只在切到英文时才会暴露。
        if 中 and 英 and _占位符数量(中) != _占位符数量(英):
            错.append(
                f"`{键}` 占位符数量不一致（中 {_占位符数量(中)} / 英 {_占位符数量(英)}）"
                "，切到英文会格式化出错"
            )
        # 英文列混入中文 = 漏翻译的复制粘贴，英文界面会出现中文。
        #
        # 例外：`language_self_*` 是**语言名**，按惯例用自己的文字显示
        # （Godot 的语言下拉也是这么做的：简体中文 / English / 日本語）。
        if 英 and _含中文(英) and not 键.startswith("language_self_"):
            错.append(f"`{键}` 英文列含中文（疑似漏翻译）")
    return 错


def _跳过注释与字面量(正文, i):
    """若 `正文[i:]` 以注释/字符串/字符字面量开头，返回它**结束后**的下标，否则返回 None。

    花括号配对必须先过这一关：测试模块里到处都是 `"{通用布局:?}"`、
    `"里有 } 的字符串"`，把它们的花括号算进配对就会提前结束剔除，
    把后面的测试代码当成生产代码扫，或者反过来一口吞掉真正的生产代码。
    Rust 的块注释可以嵌套（`/* … /* … */ … */`），所以这里用深度计数而不是找 `*/`。
    """
    c = 正文[i : i + 1]
    if c == "/" and 正文[i + 1 : i + 2] == "/":
        j = 正文.find("\n", i)
        return len(正文) if j < 0 else j
    if c == "/" and 正文[i + 1 : i + 2] == "*":
        深度 = 1
        j = i + 2
        while j < len(正文) and 深度:
            if 正文[j : j + 2] == "/*":
                深度 += 1
                j += 2
            elif 正文[j : j + 2] == "*/":
                深度 -= 1
                j += 2
            else:
                j += 1
        return j
    if c == '"':
        # `r"…"#"…"`：raw 字符串里的反斜杠不转义，结束标记是 `"` 加同样多的 `#`。
        井 = 0
        k = i - 1
        while k >= 0 and 正文[k] == "#":
            井 += 1
            k -= 1
        if k >= 0 and 正文[k] == "r":
            结束标记 = '"' + "#" * 井
            j = i + 1
            while j < len(正文):
                if 正文[j] == '"' and 正文.startswith(结束标记, j):
                    return j + len(结束标记)
                j += 1
            return j
        j = i + 1
        while j < len(正文):
            if 正文[j] == "\\":
                j += 2
                continue
            if 正文[j] == '"':
                return j + 1
            j += 1
        return j
    if c == "'":
        # 字符字面量与生命周期标注共用 `'`：只有 `'x'` / `'\x'` 这种成对形式才算字面量，
        # 否则当成普通字符前移一位（生命周期里不会出现花括号，忽略它不影响配对）。
        if 正文[i + 1 : i + 2] == "\\":
            j = i + 2
            while j < len(正文) and 正文[j] != "'":
                j += 1
            return j + 1 if j < len(正文) else j
        if 正文[i + 1 : i + 2] and 正文[i + 2 : i + 3] == "'":
            return i + 3
        return None
    return None


def _配对花括号(正文, 起点):
    """返回与 `正文[起点] == "{"` 配对的那个 `}` 的下一个下标。"""
    深度 = 0
    i = 起点
    while i < len(正文):
        跳过 = _跳过注释与字面量(正文, i)
        if 跳过 is not None:
            i = 跳过
            continue
        if 正文[i] == "{":
            深度 += 1
        elif 正文[i] == "}":
            深度 -= 1
            if 深度 == 0:
                return i + 1
        i += 1
    return len(正文)


